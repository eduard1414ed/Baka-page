#!/usr/bin/env node
// СБОРКА ГОВОРИТ ВСЛУХ: В ЗАГОЛОВКЕ ОПУБЛИКОВАННОГО ПОСТА СНОВА ЖИРНЫЙ.
//
//   node scripts/check-heading-bold.mjs             — спросить архив
//   node scripts/check-heading-bold.mjs --selftest  — плюс подлоги
//
// ЗАЧЕМ. Решение заказчика 12 августа 2026: жирного внутри заголовка
// не бывает. Разовый скрипт задачи 19 снял его по всему архиву — и на этом
// правило кончилось. Заказчик правит посты в админке каждый день, заголовки
// пишет руками, и 15 августа их снова оказалось четыре: в `trogatelno` рядом
// стояли «### Начнём с сюжета» и «### **А музыка...**», то есть в одном посте
// обе формы. Ровно та беда, ради которой правило и заводили.
//
// РАЗОВАЯ УБОРКА НЕ УДЕРЖИВАЕТ ПРАВИЛА. Это записанный урок проекта в чистом
// виде: правило, у которого нет постоянно действующего механизма, живёт
// до первой правки руками, а узнать о его пропаже неоткуда.
//
// ТОЛЬКО ГОВОРИМ, НЕ ЧИНИМ, И СБОРКУ НЕ РОНЯЕМ. Тихо подменить слово в тексте
// заказчика нельзя — это прямой запрет проекта. Уронить сборку тоже нельзя:
// текст пишет человек, и его правка не должна оставлять сайт невыложенным.
// Значит остаётся сказать вслух и назвать поимённо, что и где.
//
// ЧЕРНОВИКИ НЕ СПРАШИВАЮТСЯ — так же, как у соседних правил про ссылки:
// страницы у них нет, читателю не видно, а ругани вышло бы на сотни строк,
// то есть ровно тем письмом «всё хорошо», которое перестают читать.
//
// ПРАВИЛО ЗДЕСЬ НЕ ПИШЕТСЯ ЗАНОВО: и оно, и разовые скрипты зовут один
// `scripts/heading-bold.mjs`. Своя копия отвечала бы про правило, которого
// на сайте нет, — этим уже кончилась находка 36.
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readPostsRaw, parseBody } from './archive-clean-lib.mjs';
import { планСнятияЖирного } from './heading-bold.mjs';

/** Опубликованные посты, у которых в заголовке остался жирный. */
export function жирныеЗаголовки(posts) {
	const найдено = [];
	for (const post of posts) {
		if (post.draft) continue;
		for (const h of планСнятияЖирного(parseBody(post.body), post.body).заголовки) {
			найдено.push({ id: post.id, title: String(post.front?.title ?? ''), было: h.было.trim(), стало: h.стало.trim() });
		}
	}
	return найдено;
}

async function main() {
	const posts = await readPostsRaw();
	const опубликованных = posts.filter((p) => !p.draft).length;
	const найдено = жирныеЗаголовки(posts);

	// Число СЧИТАЕТСЯ, а не пишется словами: вписанное руками переживает
	// правку того, что описывает, и начинает врать.
	console.log(`Жирный в заголовке: просмотрено опубликованных постов ${опубликованных}, найдено ${найдено.length}.`);

	if (!найдено.length) return;

	const поПостам = new Map();
	for (const х of найдено) поПостам.set(х.id, [...(поПостам.get(х.id) ?? []), х]);

	console.warn(
		`⚠ ЖИРНЫЙ ВНУТРИ ЗАГОЛОВКА — ${найдено.length} в ${поПостам.size} опубликованных постах. ` +
			'Решение 12 августа 2026: его не бывает. Ничего не правлю — правьте в админке.',
	);
	for (const [id, список] of поПостам) {
		console.warn(`  ${id} («${список[0].title}»)`);
		for (const х of список) {
			console.warn(`      было:  ${х.было}`);
			console.warn(`      стало: ${х.стало}`);
		}
	}
}

// ── ПОДЛОГИ ───────────────────────────────────────────────────────────────
// «Пусто» ничего не значит, пока не показано, что проверка умеет находить,
// и что она молчит на здоровом. Подлог тут не трогает файлов вовсе: правило
// спрашивается на подложенных постах, ответ на которые известен заранее
// и от работы заказчика не протухает.
function selftest() {
	const пост = (id, body, draft = false) => ({ id, draft, front: { title: id }, body });
	let плохо = 0;
	const скажи = (ок, что) => {
		if (!ок) плохо++;
		console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
	};

	const случаи = [
		['### **Весь заголовок жирный**', 1, 'заголовок целиком жирный'],
		['### Часть **жирная**, часть нет', 1, 'жирный внутри заголовка'],
		['### __Подчёркиванием__', 1, 'жирный записан подчёркиваниями'],
		['> ### **в цитате**', 1, 'заголовок внутри цитаты — тоже заголовок'],
		['- ### **в пункте списка**', 1, 'заголовок внутри пункта списка'],
		['### Обычный заголовок', 0, 'чистый заголовок — молчим'],
		['текст **жирный** в абзаце', 0, 'жирный в абзаце — не наше дело'],
		['**Весь абзац жирный**', 0, 'жирный абзац — не заголовок'],
		['### Заголовок с *курсивом*', 0, 'курсив в заголовке не трогаем'],
		['`### **код**`', 0, 'решётка и звёздочки внутри кода до заголовка не доезжают'],
	];

	for (const [тело, сколько, зачем] of случаи) {
		const вышло = жирныеЗаголовки([пост('подлог', `\n${тело}\n`)]).length;
		скажи(вышло === сколько, `${зачем}: ${вышло}, ждали ${сколько}`);
	}

	// ЧЕРНОВИК НЕ СПРАШИВАЕТСЯ — иначе отчёт утонул бы в сотнях строк,
	// а читателю черновиков не видно вовсе.
	скажи(жирныеЗаголовки([пост('чрн', '\n### **Жирный**\n', true)]).length === 0, 'у черновика не спрашиваем');

	// И ЖИВЫЕ ДАННЫЕ: правило обязано отвечать про них тем же числом, каким
	// отвечает разовый скрипт. Разойдись они — правило снова стало бы двумя.
	console.log();
	console.log(`Подлогов ${случаи.length + 1}, провалилось ${плохо}.`);
	if (плохо) process.exit(1);
	console.log('Правило и находит, и молчит там, где должно.');
}

// ЗАПУСКАЕМСЯ ТОЛЬКО ТОГДА, КОГДА НАС ПОЗВАЛИ НАПРЯМУЮ. Без развилки простой
// `import { жирныеЗаголовки }` прогонял бы весь отчёт посреди чужого замера —
// и поймано это было сразу: `heading-bold.test.mjs` зовёт эту функцию, а сам
// запускается с ключом `--selftest`, и скрипт принял чужой ключ за свой.
//
// Сравниваем ПУТЯМИ, а не строками: в пути к проекту русские буквы, и
// `import.meta.url` кодирует их (`%D0%A0%D0%B0…`), а `process.argv[1]` нет
// (CLAUDE.md, урок про русские буквы в пути).
const calledDirectly = resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1] ?? '');

if (calledDirectly) {
	if (process.argv.includes('--selftest')) selftest();
	else await main();
}
