// НЕУДАЧНЫЙ ПОХОД К ФИДУ ЗАПОМИНАЕТСЯ, А НЕ ПОВТОРЯЕТСЯ 142 РАЗА.
//
//   node scripts/feed-failure.test.mjs             — спросить
//   node scripts/feed-failure.test.mjs --selftest  — плюс подлог: прежнее правило
//
// ЗАЧЕМ. Аудио выпусков живёт в RSS чужого хостинга и берётся ВО ВРЕМЯ СБОРКИ.
// Запоминался только удачный поход; при недоступном хостинге сборка ходила
// к фиду заново на КАЖДОЙ странице выпуска (ревизия задачи 15, находка 15).
//
// ЦЕНА ЭТОГО ВЫРОСЛА 15 АВГУСТА, и это главное, что тут проверяется. Сначала
// походу добавили три повтора с паузами 2, 6 и 18 секунд (находка 1), потом —
// срок 30 секунд на попытку (находка 5). Каждая починка по отдельности верная,
// а вместе они превратили «медленно» в «никогда»: худший случай на одну
// страницу — четыре попытки по 30 секунд плюс 26 секунд пауз, и это при 142
// страницах выпусков.
//
// ЧТО СПРАШИВАЕТСЯ. Не «работает ли кэш» вообще, а ровно то, ради чего он
// заведён: СКОЛЬКО РАЗ мы сходим в сеть, если сеть не отвечает. Ответ должен
// быть «один», а не «по разу на страницу».
import { fetchFeedItems, забытьОтказФида, ПАУЗЫ } from '../src/lib/podcastFeed.mjs';
import { ТАЙМАУТ } from './retry.mjs';

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

/** Сколько страниц выпусков спрашивают фид за сборку. Замер, а не догадка. */
const СТРАНИЦ_ВЫПУСКОВ = 142;

const настоящийFetch = globalThis.fetch;
const тихо = console.warn;

/**
 * Прогнать N обращений к фиду на подделке сети и посчитать походы.
 *
 * Паузы повтора подменяются короткими: проверяется ЧИСЛО походов, а не длина
 * ожидания, и ждать настоящие 26 секунд на каждый случай незачем.
 */
async function сколькоПоходов(обращений, ответ) {
	забытьОтказФида();
	let походов = 0;
	globalThis.fetch = async () => {
		походов++;
		if (ответ === 'молчит') throw Object.assign(new Error('fetch failed'), { cause: new Error('ECONNREFUSED') });
		return { ok: true, status: 200, text: async () => ответ };
	};
	console.warn = () => {};
	try {
		for (let i = 0; i < обращений; i++) await fetchFeedItems();
		return походов;
	} finally {
		console.warn = тихо;
		globalThis.fetch = настоящийFetch;
		забытьОтказФида();
	}
}

console.log('ОТКАЗ ФИДА ЗАПОМИНАЕТСЯ: в сеть ходим один раз, а не на каждую страницу.');
console.log();

// ── 1. Отказ ──────────────────────────────────────────────────────────────
const заходовПовтора = ПАУЗЫ.length + 1;
const приОтказе = await сколькоПоходов(СТРАНИЦ_ВЫПУСКОВ, 'молчит');
скажи(
	приОтказе === заходовПовтора,
	`фид молчит, ${СТРАНИЦ_ВЫПУСКОВ} страниц спросили его → походов в сеть ${приОтказе} (это один поход с ${ПАУЗЫ.length} повторами)`,
);

// ── 2. Успех ──────────────────────────────────────────────────────────────
const фид = '<rss><channel><item><guid>g1</guid><title>Выпуск</title></item></channel></rss>';
const приУспехе = await сколькоПоходов(СТРАНИЦ_ВЫПУСКОВ, фид);
скажи(приУспехе === 1, `фид отвечает, ${СТРАНИЦ_ВЫПУСКОВ} страниц спросили его → походов в сеть ${приУспехе}`);

// ── 3. Чего это стоит ─────────────────────────────────────────────────────
// Числа СЧИТАЮТСЯ из настоящих настроек, а не вписаны словами: вписанное
// переживает правку того, что описывает, и начинает врать.
const худшийПоход = заходовПовтора * ТАЙМАУТ + ПАУЗЫ.reduce((с, п) => с + п, 0);
const былоБы = (худшийПоход * СТРАНИЦ_ВЫПУСКОВ) / 1000 / 60;
const стало = худшийПоход / 1000;
console.log();
console.log(`  Худший поход при молчащем хостинге: ${(худшийПоход / 1000).toFixed(0)} с`);
console.log(`  Прежнее правило (спрашивать заново на каждой странице): ${былоБы.toFixed(0)} мин`);
console.log(`  Нынешнее (спросить один раз):                          ${стало.toFixed(0)} с`);

// ── ПОДЛОГ ────────────────────────────────────────────────────────────────
// «Пусто» ничего не значит, пока не показано, что проверка умеет находить.
// Подлог возвращает ПРЕЖНЕЕ правило — «запоминаем только успех» — и обязан
// дать ровно то число походов, которое находка и называла.
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── ПОДЛОГ: прежнее правило, запоминаем только успех ──');

	let походов = 0;
	let память = null;
	const прежнееПравило = async () => {
		if (память) return память;
		try {
			походов++;
			throw new Error('fetch failed');
		} catch {
			return []; // прежний код возвращал пустоту и НИЧЕГО не запоминал
		}
	};
	for (let i = 0; i < СТРАНИЦ_ВЫПУСКОВ; i++) await прежнееПравило();
	скажи(походов === СТРАНИЦ_ВЫПУСКОВ, `прежнее правило сходило бы в сеть ${походов} раз — по разу на страницу`);
	скажи(приОтказе < походов, `нынешнее правило ходит ${приОтказе} раз против ${походов} — разница в ${Math.round(походов / приОтказе)} раз`);

	// И ВТОРАЯ ПОЛОВИНА: на отвечающем фиде прежнее и нынешнее правило дают
	// одно и то же — один поход. Иначе «поймал» значило бы «ругается на всё».
	скажи(приУспехе === 1, 'на отвечающем фиде оба правила ходят по разу — проверка ругается не на всё');
}

console.log();
if (плохо) {
	console.log(`ПРОВАЛОВ: ${плохо}`);
	process.exit(1);
}
console.log('Отказ фида запоминается: в сеть ходим один раз за сборку.');
