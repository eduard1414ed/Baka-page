//   node scripts/mentions-sort.test.mjs
//   node scripts/mentions-sort.test.mjs --selftest
//
// ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА. Порядок карточек видом не является: на живой
// странице «по количеству» и «по дате» глазами не отличить — надо знать, сколько
// раз тайтл назван в каждом материале, а этого на карточке не написано. Значит
// заказчик такое принять не может в принципе, и проверять должен код.
//
// А ГЛАВНОЕ — ТУТ ЧЕТЫРЕ КРАЯ, КОТОРЫХ В ЖИВОМ АРХИВЕ НЕ ВЫЗВАТЬ ПО ЗАКАЗУ:
// материал, попавший на страницу полем «Тайтлы поста» и не назвавший тайтл
// в тексте; выпуск, где тайтл и в описании, и в разговоре; внешняя статья
// рядом с материалом, у которого упоминаний больше десяти; ничья.
//
// ДАННЫЕ ПОДЛОЖЕННЫЕ, А КОД НАСТОЯЩИЙ: `buildMentionIndex` и `postsForAnime`
// берутся из src/lib как есть. Переписать правило рядом своими словами нельзя —
// копия проверяла бы саму себя.
//
// ЧЕГО ЭТА ПРОВЕРКА НЕ ЗНАЕТ. Ничего про вид карточек и ничего про то, попал ли
// порядок в собранную страницу: она смотрит на функцию, а не на `dist/`.

import { readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Путь достаём через fileURLToPath, а не `.pathname`: в пути к проекту русские
// буквы, и `.pathname` отдаёт их закодированными — «файла нет» про файл, который есть.
const МОДУЛЬ = fileURLToPath(new URL('../src/lib/animeMentionIndex.mjs', import.meta.url));
const ПОДЛОГ = fileURLToPath(new URL('../src/lib/animeMentionIndex.selftest-tmp.mjs', import.meta.url));

const cases = [];
const проверка = (name, ok, подробности = '') => cases.push({ name, ok, подробности });

// ── Подложенные данные ──────────────────────────────────────────────────────

const animeList = [{ id: 'naruto', data: { titleRu: 'Наруто', titleOriginal: 'Naruto' } }];

function пост(id, { дата, тело = '', внешний = false, тайтлы = [], guid = null }) {
	return {
		id,
		body: тело,
		data: {
			title: id,
			date: new Date(дата),
			category: guid ? 'podcast' : 'note',
			draft: false,
			anime: тайтлы.map((ref) => ({ id: ref })),
			...(внешний ? { externalUrl: 'https://t-j.ru/example/' } : {}),
			...(guid ? { audioGuid: guid } : {}),
		},
	};
}

// Расшифровка, где «Наруто» звучит в двух РАЗНЫХ кусках разговора. Реплики
// разнесены по времени больше чем на порог блока (90 секунд), иначе они
// склеились бы в один блок и упоминание засчиталось бы один раз.
function расшифровка(id) {
	return {
		id,
		data: {
			speakers: { speaker_0: 'Ведущий' },
			replicas: [
				{ start: 10, end: 20, speaker: 'speaker_0', text: 'Сегодня говорим про Наруто.' },
				{ start: 400, end: 410, speaker: 'speaker_0', text: 'И снова Наруто, куда без него.' },
			],
		},
	};
}

const пусто = [];

/** Порядок карточек на странице тайтла: id постов сверху вниз. */
function порядок(lib, posts, transcripts = пусто) {
	const index = lib.buildMentionIndex({ posts, transcripts, animeList });
	return lib.postsForAnime('naruto', posts, index).map((item) => item.post.id);
}

// ── Сами проверки ───────────────────────────────────────────────────────────

// Сколько раз уже звали main. Хвост к адресу считается отсюда: подлоги ложатся
// в ОДИН и тот же файл, и без счётчика Node отдал бы второму подлогу модуль,
// разобранный для первого, — проверка молча спрашивала бы не тот код.
let прогонов = 0;
const prog = () => ++прогонов;

async function main(файл = МОДУЛЬ) {
	cases.length = 0;
	const lib = await import(`${pathToFileURL(файл).href}?v=${prog()}`);

	// 1. БОЛЬШЕ УПОМИНАНИЙ — ВЫШЕ, ДАЖЕ ЕСЛИ МАТЕРИАЛ СТАРЫЙ.
	{
		const частый = пост('часто-2020', {
			дата: '2020-01-01',
			тело: 'Наруто, ещё раз Наруто и снова Наруто.',
		});
		const редкий = пост('редко-2026', { дата: '2026-01-01', тело: 'Мельком про Наруто.' });
		const got = порядок(lib, [редкий, частый]);
		проверка('больше упоминаний — выше, дата не спасает', got[0] === 'часто-2020', got.join(' → '));
	}

	// 2. НИЧЬЯ РЕШАЕТСЯ ДАТОЙ, СВЕЖЕЕ СВЕРХУ. Самый частый случай на сайте:
	//    замер по архиву — 1906 карточек из 2761 с равным счётом.
	{
		const старый = пост('старый', { дата: '2020-01-01', тело: 'Про Наруто.' });
		const свежий = пост('свежий', { дата: '2026-01-01', тело: 'Тоже про Наруто.' });
		const got = порядок(lib, [старый, свежий]);
		проверка('при равном счёте сверху свежее', got.join(' → ') === 'свежий → старый', got.join(' → '));
	}

	// 3. ВНЕШНЯЯ СТАТЬЯ ВЕСИТ РОВНО 10 — не больше и не меньше.
	{
		const внешняя = пост('внешняя-2020', { дата: '2020-01-01', тайтлы: ['naruto'], внешний: true });
		const девять = пост('девять-2026', { дата: '2026-01-01', тело: 'Наруто '.repeat(9) });
		const одиннадцать = пост('одиннадцать-2019', { дата: '2019-01-01', тело: 'Наруто '.repeat(11) });
		const got = порядок(lib, [девять, внешняя, одиннадцать]);
		проверка(
			'внешняя статья обгоняет девять упоминаний и уступает одиннадцати',
			got.join(' → ') === 'одиннадцать-2019 → внешняя-2020 → девять-2026',
			got.join(' → '),
		);
	}

	// 4. МАТЕРИАЛ, ПОПАВШИЙ ПОЛЕМ «ТАЙТЛЫ ПОСТА», ВЕСИТ ЕДИНИЦУ, А НЕ НОЛЬ.
	//    В архиве таких 124: подборки сезона называют тайтлы вставками
	//    `::anime-ref`, словами в тексте их нет. С нулём они утонули бы ниже
	//    материалов, где тайтл помянут вскользь один раз.
	{
		const полем = пост('полем-2026', { дата: '2026-01-01', тайтлы: ['naruto'], тело: 'Подборка сезона.' });
		const словом = пост('словом-2020', { дата: '2020-01-01', тело: 'Один раз Наруто.' });
		const got = порядок(lib, [словом, полем]);
		проверка('материал без найденных упоминаний весит 1, а не 0', got[0] === 'полем-2026', got.join(' → '));
	}

	// 5. МИНУТЫ РАЗГОВОРА И СЛОВА В ТЕКСТЕ СКЛАДЫВАЮТСЯ. У выпуска бывает и то,
	//    и другое, и раньше текстовый счёт затирался минутами.
	{
		const выпуск = пост('выпуск-2020', {
			дата: '2020-01-01',
			guid: 'g1',
			тело: 'В этом выпуске обсуждаем Наруто.', // 1 в тексте + 2 куска разговора = 3
		});
		const текст = пост('текст-2026', { дата: '2026-01-01', тело: 'Наруто и ещё раз Наруто.' }); // 2
		const got = порядок(lib, [текст, выпуск], [расшифровка('g1')]);
		проверка('у выпуска текст и минуты складываются', got[0] === 'выпуск-2020', got.join(' → '));

		const index = lib.buildMentionIndex({ posts: [выпуск], transcripts: [расшифровка('g1')], animeList });
		const [карточка] = lib.postsForAnime('naruto', [выпуск], index);
		проверка('и счёт у него ровно 3', карточка?.weight === 3, `вышло ${карточка?.weight}`);
		проверка('минуты при этом целы', карточка?.times.length === 2, `минут ${карточка?.times.length}`);
	}

	// 6. КРАЯ, КОТОРЫХ В ЖИВОМ АРХИВЕ НЕ ВЫЗВАТЬ.
	{
		const один = пост('один', { дата: '2026-01-01', тело: 'Наруто.' });
		проверка('одна карточка — не падаем', порядок(lib, [один]).join('') === 'один');
		проверка('ни одной карточки — пустой список', порядок(lib, []).length === 0);
		const чужой = пост('чужой', { дата: '2026-01-01', тело: 'Тут про что-то другое.' });
		проверка('материал без тайтла на страницу не попадает', порядок(lib, [чужой]).length === 0);
	}

	for (const item of cases) {
		console.log(`  ${item.ok ? 'ок  ' : 'СБОЙ'}  ${item.name}${item.подробности ? `  [${item.подробности}]` : ''}`);
	}
	return cases.filter((item) => !item.ok).length;
}

// ── Самопроверка: умеет ли она вообще краснеть ──────────────────────────────
//
// Правило отменяем ровно так, как его отменил бы человек. Настоящий файл при
// этом НЕ ТРОГАЕМ: подлог кладётся копией рядом, иначе он уехал бы в `git stash`
// вместе с работой.
//
// ПОДЛОГА ДВА, И ЭТО НЕ ИЗЛИШЕСТВО. Первый отменяет сортировку целиком, второй
// — только правило «минимум единица». Отмени мы одну сортировку — проверка
// про 124 подборки осталась бы зелёной (дата в этом примере тянет в ту же
// сторону), и доказательства, что она умеет падать, у нас бы не было.
const ПОДЛОГИ = [
	{
		имя: 'сортировка по количеству отменена, снова по дате',
		было: '.sort((a, b) => b.weight - a.weight || b.post.data.date.valueOf() - a.post.data.date.valueOf());',
		стало: '.sort((a, b) => b.post.data.date.valueOf() - a.post.data.date.valueOf());',
	},
	{
		имя: 'снят минимум в одно упоминание',
		было: 'return Math.max(1, text + times.length);',
		стало: 'return text + times.length;',
	},
];

async function selftest() {
	const текст = readFileSync(МОДУЛЬ, 'utf8');
	let провалов = 0;

	for (const подлог of ПОДЛОГИ) {
		const сломанный = текст.replace(подлог.было, подлог.стало);
		if (сломанный === текст) {
			throw new Error(`в animeMentionIndex.mjs нет строки «${подлог.было}» — подлог не встал, проверка смотрит не туда`);
		}

		console.log(`\n── подлог: ${подлог.имя}`);
		writeFileSync(ПОДЛОГ, сломанный);
		try {
			const плохо = await main(ПОДЛОГ);
			const покраснели = cases.filter((item) => !item.ok).map((item) => item.name);
			console.log(
				плохо > 0
					? `  ок    КРАСНЕЕТ: ${покраснели.join('; ')}`
					: '  СБОЙ  проверка НИЧЕГО НЕ ЗАМЕТИЛА. На этом правиле она бесполезна.',
			);
			if (плохо === 0) провалов++;
		} finally {
			unlinkSync(ПОДЛОГ);
		}
	}

	return провалов;
}

// Сравнение путями, а не строками: `import.meta.url` кодирует русские буквы
// в пути к проекту, а `process.argv[1]` — нет, и строчное сравнение
// не совпало бы никогда.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
	const плохо = process.argv.includes('--selftest') ? await selftest() : await main();
	process.exit(плохо === 0 ? 0 : 1);
}
