// КАВЫЧКА В АТРИБУТЕ ДИРЕКТИВЫ — ОДНО ПРАВИЛО, И ОБЕ СТОРОНЫ СХОДЯТСЯ.
//
//   node scripts/directive-attr.test.mjs             — спросить
//   node scripts/directive-attr.test.mjs --selftest  — плюс подлоги
//
// ЗАЧЕМ. Правило двустороннее: кто пишет — подменяет прямую кавычку
// на `&quot;`, кто читает — подменяет обратно. Копий было шесть, а восемь
// сборщиков переносов подпись не экранировали вовсе (доревизия задачи 15,
// находка 32). Разъедься стороны — блок показался бы на странице словами
// `::image{src=… caption=…}`, и увидеть это можно было бы только глазами
// и только на посте, где кавычка есть.
//
// ЧТО СПРАШИВАЕТСЯ, И ПОЧЕМУ ТРИ РАЗНЫХ ВОПРОСА:
//   1. ТУДА-ОБРАТНО ЧЕРЕЗ НАСТОЯЩИЙ РАЗБОР — не «строка стала другой»,
//      а «директива с такой подписью разбирается, и подпись вернулась целой».
//      Спрашиваем тот же разбор, каким её читает сборка.
//   2. АДМИНКА ЭКРАНИРУЕТ ТАК ЖЕ — её копия неизбежна (`public/admin/index.html`
//      живёт вне сборки), но сверяется, а не помечается: пометка «поправьте
//      и там» в этом проекте не удержала ни одной копии.
//   3. НИКТО НЕ СОБИРАЕТ ПОДПИСЬ В ОБХОД ПРАВИЛА — поиском по сборщикам.
import { readdir, readFile, writeFile, unlink } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { escapeAttr, unescapeAttr } from '../src/lib/directiveAttr.mjs';
import { parseBody } from './archive-clean-lib.mjs';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const КОРЕНЬ = join(ЗДЕСЬ, '..');

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

/** Подпись из первой директивы тела — так, как её достаёт сборка. */
function подписьИзТела(текст) {
	const дерево = parseBody(текст);
	let найдено;
	const обход = (узел) => {
		if (узел.name && узел.attributes && узел.attributes.caption !== undefined && найдено === undefined) {
			найдено = unescapeAttr(узел.attributes.caption);
		}
		for (const дитя of узел.children ?? []) обход(дитя);
	};
	обход(дерево);
	return найдено;
}

console.log('КАВЫЧКА В АТРИБУТЕ ДИРЕКТИВЫ: одно правило, обе стороны сходятся.');
console.log();

// ── 1. Туда-обратно через настоящий разбор ────────────────────────────────
console.log('── подпись переживает запись и чтение ──');

const ПОДПИСИ = [
	['The Brilliance of Naoki Urasawa\'s "Monster"', 'настоящая подпись из ep-83 — с прямыми кавычками'],
	['Interview with Hiromu Arakawa, author of "Fullmetal Alchemist"', 'настоящая подпись из ep-21'],
	['Кадр из «Синего периода»', 'ёлочки — их трогать не надо'],
	['студии Bones и MAPPA', 'обычная подпись без кавычек'],
	['Он сказал: "да" — и "нет"', 'две пары кавычек в одной подписи'],
	['', 'пустая подпись'],
];

for (const [подпись, зачем] of ПОДПИСИ) {
	const строка = `::image{src="/images/uploads/x.webp" alt="" caption="${escapeAttr(подпись)}" width="column"}`;
	const вернулось = подписьИзТела(`\n${строка}\n`);
	скажи(вернулось === подпись, `${зачем}: ${вернулось === подпись ? 'вернулась целой' : `вернулось ${JSON.stringify(вернулось)}`}`);
}

// ЭТО ПОЛОВИНА ПРАВИЛА, БЕЗ КОТОРОЙ «ВСЁ ХОРОШО» НИЧЕГО НЕ ЗНАЧИТ: без замены
// директива с кавычкой в подписи ЛОМАЕТСЯ, и подпись не возвращается.
const безЗамены = подписьИзТела('\n::image{src="/x.webp" alt="" caption="Naoki Urasawa\'s "Monster"" width="column"}\n');
скажи(безЗамены !== 'Naoki Urasawa\'s "Monster"', 'БЕЗ замены та же подпись НЕ возвращается — значит замена и правда нужна');

// ── 2. Копия в админке ────────────────────────────────────────────────────
console.log();
console.log('── копия в админке ──');

const админка = await readFile(join(КОРЕНЬ, 'public', 'admin', 'index.html'), 'utf8');
// Достаём саму строку правила, а не пересказываем её: пересказ разошёлся бы
// с админкой ровно так же, как разошлись бы копии.
// Строка берётся ЦЕЛИКОМ до конца строки, а не до первой точки с запятой:
// точка с запятой стоит ВНУТРИ самого значения (`'&quot;'`), и обрезка по ней
// давала обрывок, на котором проверка падала — то есть врала не в ту сторону,
// но всё же врала.
const строкаАдминки = админка.match(/^\s*const escapeAttr = .*$/m);
скажи(Boolean(строкаАдминки), 'строка escapeAttr в админке нашлась');
if (строкаАдминки) {
	// Правило админки собирается из её же текста и спрашивается на тех же
	// подписях. Сравнивать посимвольно нельзя: у неё своя запись (`?? ''`).
	const правилоАдминки = new Function(`${строкаАдминки[0]} return escapeAttr;`)();
	const расходятся = ПОДПИСИ.filter(([подпись]) => правилоАдминки(подпись) !== escapeAttr(подпись));
	скажи(расходятся.length === 0, `правило админки и общее совпадают на всех ${ПОДПИСИ.length} подписях`);
	for (const [подпись] of расходятся) console.log(`          «${подпись}» → админка ${JSON.stringify(правилоАдминки(подпись))}, общее ${JSON.stringify(escapeAttr(подпись))}`);
}

// ── 3. Никто не собирает подпись мимо правила ─────────────────────────────
console.log();
console.log('── кто собирает `caption="…"` ──');

async function файлыСборщиков() {
	const собрано = [];
	for (const папка of ['dtf', 'osen-2022']) {
		for (const имя of await readdir(join(ЗДЕСЬ, папка))) {
			// СВЕРКИ НЕ СПРАШИВАЕМ. `verify.mjs` строит ОЖИДАЕМУЮ строку, чтобы
			// сравнить её с тем, что лежит в посте, — то есть читает, а не пишет.
			// Прогони мы её через это правило, она сравнивала бы экранированное
			// с экранированным и перестала бы замечать как раз расхождение.
			if (имя.endsWith('verify.mjs')) continue;
			if (имя.endsWith('.mjs')) собрано.push(join(ЗДЕСЬ, папка, имя));
		}
	}
	собрано.push(join(ЗДЕСЬ, 'archive-source-insets.mjs'));
	return собрано;
}

/** Места, где значение атрибута подставляется в строку МИМО `escapeAttr`. */
async function мимоПравила() {
	const найдено = [];
	for (const путь of await файлыСборщиков()) {
		const текст = await readFile(путь, 'utf8');
		for (const строка of текст.split('\n')) {
			// Ищем подстановку в caption/label/text — те атрибуты, куда едет
			// написанное человеком. `src` собираем мы сами из имён файлов.
			for (const совпадение of строка.matchAll(/\b(caption|label|text)="\$\{([^}]*)\}"/g)) {
				const внутри = совпадение[2];
				if (!/escapeAttr|обрезатьИЭкранировать/.test(внутри)) {
					найдено.push({ файл: путь.slice(КОРЕНЬ.length + 1), атрибут: совпадение[1], внутри });
				}
			}
		}
	}
	return найдено;
}

const мимо = await мимоПравила();
скажи(мимо.length === 0, `подстановок мимо правила: ${мимо.length}`);
for (const место of мимо) console.log(`          ${место.файл}: ${место.атрибут}="\${${место.внутри}}"`);

// ── ПОДЛОГИ ───────────────────────────────────────────────────────────────
// Подлог СОЗДАЁТ расхождение, а не меняет значение во всех копиях сразу:
// общая подмена расхождения не создаёт и не ловится (CLAUDE.md).
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── ПОДЛОГИ ──');

	const подделка = join(ЗДЕСЬ, 'dtf', 'ПОДЛОГ-build.mjs');
	await writeFile(подделка, 'export const строка = `::image{src="/x.webp" caption="${подпись}" width="column"}`;\n', 'utf8');
	try {
		const сПодлогом = await мимоПравила();
		скажи(
			сПодлогом.some((м) => м.файл.endsWith('ПОДЛОГ-build.mjs')),
			`подложенный сборщик без экранирования найден (всего ${сПодлогом.length})`,
		);
	} finally {
		await unlink(подделка);
	}
	скажи((await мимоПравила()).length === 0, 'после уборки подлога проверка снова молчит');

	// Второй подлог — расхождение сторон: правило админки «как было бы, если бы
	// её копию поправили, а общую нет».
	const админкаИначе = (value) => String(value ?? '').replaceAll('"', '&#34;');
	const разошлись = ПОДПИСИ.some(([подпись]) => админкаИначе(подпись) !== escapeAttr(подпись));
	скажи(разошлись, 'разошедшаяся копия админки (числовая запись &#34;) поймана сверкой');
}

console.log();
if (плохо) {
	console.log(`ПРОВАЛОВ: ${плохо}`);
	process.exit(1);
}
console.log('Правило одно, копия админки совпадает, мимо него никто не пишет.');
