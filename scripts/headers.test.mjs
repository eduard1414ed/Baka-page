/**
 * ЗАЩИТНЫЕ ЗАГОЛОВКИ ДОЕЗЖАЮТ ДО ЖИВОГО САЙТА.
 *
 * Список лежит в `public/_headers`, но написать его мало: файл читает
 * Cloudflare при выкладке, и узнать, понял ли он написанное, можно только
 * спросив живой сайт. Поэтому проверка сверяет НЕ файл с собой, а файл
 * с тем, что сайт отдаёт на самом деле.
 *
 * Заодно смотрит, что сам файл наружу не отдаётся: на зеркале он лежал бы
 * обычной страницей, потому туда и не едет (scripts/mirror-sync.mjs).
 *
 * Ключ --подлог задаёт те же вопросы ЗЕРКАЛУ. Там заголовков нет и быть
 * не может — голое хранилище Яндекса их не умеет, — значит проверка обязана
 * покраснеть. Промолчала на заведомо голом хосте — она не смотрит никуда.
 */
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname, join } from 'node:path';

const КОРЕНЬ = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ФАЙЛ = join(КОРЕНЬ, 'public/_headers');
const САЙТ = 'https://bakapodcast.com';
const ЗЕРКАЛО = 'https://ru.bakapodcast.com';

/** Какой живой адрес представляет правило из файла. */
const ОБРАЗЕЦ = { '/*': '/', '/admin/*': '/admin/' };

/** Разобрать `_headers`: путь → список пар «имя, значение». */
function разобрать(текст) {
	const правила = [];
	let текущее = null;
	for (const строка of текст.split('\n')) {
		const без = строка.replace(/#.*$/, '').trimEnd();
		if (!без.trim()) continue;
		if (!/^\s/.test(без)) {
			текущее = { путь: без.trim(), заголовки: [] };
			правила.push(текущее);
			continue;
		}
		const пара = /^\s+([A-Za-z-]+):\s*(.+)$/.exec(без);
		if (пара && текущее) текущее.заголовки.push({ имя: пара[1], значение: пара[2].trim() });
	}
	return правила.filter((п) => п.заголовки.length);
}

/**
 * Сошёлся ли заголовок с тем, что записано в файле.
 *
 * ПОЧЕМУ НЕ ПРОСТОЕ РАВЕНСТВО. Правила в `_headers` складываются: к адресу
 * /admin/ подходят и «/*», и «/admin/*», и Cloudflare отдаёт ОДИН заголовок
 * Content-Security-Policy, склеив оба значения через запятую. Для браузера
 * это две отдельные политики, и выполнены должны быть ОБЕ — то есть склейка
 * не ослабляет ничего. Первая версия этой проверки знала только про точное
 * совпадение и объявила поломкой исправно доехавший заголовок.
 *
 * Поэтому у политики безопасности спрашиваем «есть ли наша среди отданных»,
 * а у остальных заголовков — обычное равенство: там склейки не бывает.
 */
function совпало(имя, ожидаем, пришло) {
	if (пришло == null) return false;
	if (имя.toLowerCase() !== 'content-security-policy') return пришло === ожидаем;
	const политики = пришло.split(',').map((п) => п.trim());
	return политики.includes(ожидаем.trim());
}

async function main() {
	const подлог = process.argv.includes('--подлог');
	const хост = подлог ? ЗЕРКАЛО : САЙТ;
	const правила = разобрать(await readFile(ФАЙЛ, 'utf8'));

	if (!правила.length) {
		console.log('✗ В public/_headers не нашлось ни одного правила — проверять нечего.');
		return 1;
	}

	console.log(`ЗАЩИТНЫЕ ЗАГОЛОВКИ НА ${хост}${подлог ? '  (ПОДЛОГ: у зеркала их быть не может)' : ''}\n`);

	const беды = [];
	for (const правило of правила) {
		const путь = ОБРАЗЕЦ[правило.путь];
		if (!путь) {
			беды.push(`правилу «${правило.путь}» не назначен образец живого адреса в ОБРАЗЕЦ`);
			continue;
		}
		// У зеркала админки нет вовсе — спрашивать её там бессмысленно.
		if (подлог && правило.путь !== '/*') continue;

		let ответ;
		try {
			ответ = await fetch(`${хост}${путь}`);
		} catch (е) {
			беды.push(`до ${хост}${путь} не достучались: ${е.message}`);
			continue;
		}
		console.log(`${правило.путь}  →  ${путь}  (код ${ответ.status})`);
		for (const { имя, значение } of правило.заголовки) {
			const пришло = ответ.headers.get(имя);
			const сошлось = совпало(имя, значение, пришло);
			const коротко = значение.length > 60 ? `${значение.slice(0, 57)}…` : значение;
			console.log(`  ${сошлось ? 'ок  ' : '✗   '} ${имя}: ${сошлось ? коротко : `НЕ НАШЛОСЬ среди отданного (${пришло == null ? 'заголовка нет вовсе' : `${пришло.length} знаков`})`}`);
			if (!сошлось) беды.push(`${путь}: заголовок ${имя} не совпал`);
		}
		console.log();
	}

	// Сам список наружу отдаваться не должен: Cloudflare его съедает.
	if (!подлог) {
		const свой = await fetch(`${САЙТ}/_headers`);
		const спрятан = свой.status === 404;
		console.log(`/_headers наружу  →  код ${свой.status} ${спрятан ? '(не отдаётся, так и надо)' : ''}`);
		if (!спрятан) беды.push('файл /_headers отдаётся наружу — Cloudflare его не съел');
		console.log();
	}

	if (подлог) {
		if (беды.length) {
			console.log(`✓ ПОДЛОГ ПОЙМАН: на заведомо голом хосте проверка нашла ${беды.length} расхождений.`);
			console.log('  Значит она смотрит на настоящие заголовки, а не отвечает «ок» всегда.');
			return 0;
		}
		console.log('✗ ПОДЛОГ НЕ ПОЙМАН: у зеркала защитных заголовков нет и быть не может,');
		console.log('  а проверка промолчала — её «всё хорошо» ничего не значит.');
		return 1;
	}

	if (беды.length) {
		console.log('✗✗ ЗАГОЛОВКИ НЕ ДОЕХАЛИ ДО САЙТА:');
		for (const б of беды) console.log(`   ${б}`);
		console.log('   Написать список мало — его читает Cloudflare при выкладке.');
		console.log('   Либо выкладки ещё не было, либо файл лежит не там, где надо.');
		return 1;
	}
	console.log('ок      Все заголовки из public/_headers живой сайт отдаёт, сам файл спрятан.');
	return 0;
}

const позвалиНапрямую = resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1] ?? '');
if (позвалиНапрямую) process.exit(await main());
