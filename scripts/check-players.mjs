#!/usr/bin/env node
// ЗАСЛОН ПРОТИВ СБОРКИ БЕЗ ПЛЕЕРОВ (ревизия 15 августа 2026, находка 1).
//
// ЧТО ЭТО ЛЕЧИТ. Аудио выпусков живёт не у нас, а в RSS хостинга подкаста,
// и берётся оно ВО ВРЕМЯ СБОРКИ. Не ответил фид — страницы выпусков соберутся
// без плееров, а лента без длительностей. Сборка при этом проходит успешно,
// ошибки нет ни одной, и Cloudflare выкладывает такой сайт на живой адрес.
// Случай не теоретический: фид не отвечал уже дважды.
//
// Хвосты обещали, что это «ловится до деплоя». Не ловилось: проверка была
// сделана глазами один раз, в одной сессии восьмого этапа, а механизма
// не существовало вовсе. Вот он.
//
// ПОЧЕМУ РОНЯЕМ ТОЛЬКО ПРИ ПОЛНОЙ ПРОПАЖЕ. У отдельного выпуска плеера может
// не быть законно: его guid не нашёлся в фиде, у него нет ссылки на аудио,
// он ещё черновик. Это единичные случаи, и ронять из-за них сборку значило бы
// научить всех обходить проверку. А вот «постов с привязкой к RSS полторы
// сотни, а плееров ноль» — это ровно один случай: фид не ответил. Порог
// поэтому не доля, а ноль: он не требует подбора и не устаревает от роста
// архива.
//
// ЧТО БУДЕТ, ЕСЛИ ЗАСЛОН СРАБОТАЕТ. `npm run build` кончится ошибкой, и сайт
// не выложится — на живом адресе останется прежняя версия, с плеерами. Это
// и есть цель: старый сайт целиком лучше нового и наполовину пустого.
// Лечится повторной сборкой, когда фид ответит; сам поход к фиду уже идёт
// с тремя повторами (src/lib/podcastFeed.mjs).
//
//   node scripts/check-players.mjs            после npm run build
//   node scripts/check-players.mjs --подлог   спросить, умеет ли она падать

import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const POSTS = join(ROOT, 'src/content/posts');
const DIST = join(ROOT, 'dist');

/** Признак плеера в собранной странице — ровно тот, что ставит EpisodePlayer.astro. */
const ПЛЕЕР = 'id="player-audio"';

/**
 * САМО ПРАВИЛО, ВЫНЕСЕННОЕ ОТДЕЛЬНО, ЧТОБЫ ЕГО МОЖНО БЫЛО УРОНИТЬ ПОДЛОГОМ.
 * На живых данных оно молчит и будет молчать — то есть ничем не отличалось бы
 * от сломанного, спроси мы его только по сборке.
 *
 * @param {number} сГуидом сколько опубликованных постов привязано к RSS
 * @param {number} сПлеером у скольких из них в собранной странице есть плеер
 * @returns {string|null} строка беды или null, если всё в порядке
 */
export function бедаСПлеерами(сГуидом, сПлеером) {
	if (сГуидом === 0) return null; // выпусков нет вовсе — проверять нечего
	if (сПлеером > 0) return null; // хоть один есть — значит фид ответил
	return (
		`Постов, привязанных к RSS: ${сГуидом}. Плееров в собранных страницах: 0.\n` +
		'Это значит, что RSS подкаста не ответил во время сборки — на страницах выпусков\n' +
		'нет ни плееров, ни длительностей. Такую сборку выкладывать нельзя.\n' +
		'Что делать: собрать заново (npm run build), когда хостинг подкаста ответит.'
	);
}

function главная() {
	if (!existsSync(DIST)) {
		console.error('Папки dist/ нет. Сначала npm run build.');
		process.exitCode = 1;
		return;
	}

	let сГуидом = 0;
	let сПлеером = 0;
	const безПлеера = [];

	for (const файл of readdirSync(POSTS).filter((имя) => имя.endsWith('.md'))) {
		const текст = readFileSync(join(POSTS, файл), 'utf8');
		const шапка = текст.split('\n---')[0];
		if (!/^audioGuid:\s*\S/m.test(шапка)) continue;
		// Черновик страницы не получает вовсе — спрашивать с него нечего.
		if (/^draft:\s*true\s*$/m.test(шапка)) continue;

		сГуидом += 1;
		const страница = join(DIST, 'posts', файл.replace(/\.md$/, ''), 'index.html');
		if (!existsSync(страница)) continue;
		if (readFileSync(страница, 'utf8').includes(ПЛЕЕР)) сПлеером += 1;
		else безПлеера.push(файл.replace(/\.md$/, ''));
	}

	if (process.argv.includes('--подлог')) {
		const поймано = бедаСПлеерами(сГуидом || 143, 0);
		const промолчала = бедаСПлеерами(сГуидом || 143, 1);
		console.log(поймано ? '✓ подлог пойман: правило видит сборку без плееров' : '✗ ПОДЛОГ НЕ ПОЙМАН — заслон сломан');
		console.log(промолчала === null ? '✓ на здоровом молчит' : '✗ РУГАЕТСЯ НА ЗДОРОВОЕ — заслон сломан');
		process.exitCode = поймано && промолчала === null ? 0 : 1;
		return;
	}

	const беда = бедаСПлеерами(сГуидом, сПлеером);
	if (беда) {
		// АВАРИЙНЫЙ ВЫХОД, И ОН НУЖЕН. Заслон останавливает выкладку целиком,
		// а значит, пока хостинг подкаста лежит, на сайт не попадёт вообще
		// ничего — в том числе правка, которая к выпускам отношения не имеет.
		// Переменная `ALLOW_NO_PLAYERS=1` (в панели Cloudflare или перед
		// командой) снимает заслон на одну сборку, оставляя предупреждение.
		if (process.env.ALLOW_NO_PLAYERS === '1') {
			console.warn(`ВНИМАНИЕ  ${беда}`);
			console.warn('ВНИМАНИЕ  Заслон снят переменной ALLOW_NO_PLAYERS=1 — сайт выложится БЕЗ плееров.');
			return;
		}
		console.error(`ПРОВАЛ  ${беда}`);
		console.error('        Если выложить надо срочно и без плееров — ALLOW_NO_PLAYERS=1 npm run build');
		process.exitCode = 1;
		return;
	}

	console.log(`ок      Плееры на месте: ${сПлеером} из ${сГуидом} выпусков (проверено по собранным страницам)`);
	// Единичная пропажа — не повод ронять сборку, но сказать о ней надо:
	// молчание тут значило бы, что о выпуске без аудио никто никогда не узнает.
	if (безПлеера.length > 0) {
		console.log(`        без плеера ${безПлеера.length}: ${безПлеера.slice(0, 5).join(', ')}${безПлеера.length > 5 ? ' и другие' : ''}`);
		console.log('        (обычно значит, что выпуска нет в RSS или у него нет ссылки на аудио)');
	}
}

// Русские буквы в пути к проекту: import.meta.url кодирует их, а process.argv[1]
// нет, и строчное сравнение не совпало бы никогда (CLAUDE.md, «Уроки проекта»).
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
	главная();
}
