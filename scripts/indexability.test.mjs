// ПРОВЕРКА ПРАВИЛА ИНДЕКСИРУЕМОСТИ (src/lib/animeIndexability.mjs).
//
//   node scripts/indexability.test.mjs           — проверить
//   node scripts/indexability.test.mjs --подлог  — развести по одной строке
//                                                  и убедиться, что краснеет
//
// ЗАЧЕМ ПОДЛОГ. Проверка, которая не может провалиться, — это ложь в сторону
// «всё хорошо». Каждый подлог здесь разводит РОВНО ОДНУ строку в НАСТОЯЩЕМ
// файле правила — так, как это и случится в жизни, когда строку сочтут лишней
// и вычистят. Текст берётся из самого файла, а не переписывается рядом:
// копия разошлась бы с первой же правкой.
//
// И обязательная вторая половина: на здоровом коде проверка обязана
// ПРОМОЛЧАТЬ. «Поймал» ничего не значит, пока не показано, что на исправном
// правиле тот же случай проходит.
//
// Данные подложные, код настоящий: правило чистое, ему не нужны ни Astro,
// ни указатель упоминаний, ни сеть.

import { readFile, writeFile, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

