/** Все страницы всех случаев разом — на них проверяется порядконезависимость. */
function вседанные() {
	return СЛУЧАИ.flatMap(([имя, страницы]) => страницы.map((с) => ({ ...с, id: `${имя}::${с.id}` })));
}

/** Устойчивый к порядку ключей слепок ответа. */
function слепок(решения) {
	return JSON.stringify([...решения.entries()].map(([id, р]) => [id, р.index, р.причина]).sort());
}

function перемешать(массив, зерно) {
	const a = [...массив];
	let s = зерно;
	for (let i = a.length - 1; i > 0; i--) {
		s = (s * 1103515245 + 12345) % 2147483648;
		const j = s % (i + 1);
		[a[i], a[j]] = [a[j], a[i]];
	}
	return a;
}

/** Прогнать все случаи против переданного правила. @returns {string[]} беды */
function проверить(решить) {
	const беды = [];

	for (const [имя, страницы, ждём] of СЛУЧАИ) {
		let решения;
		try {
			решения = решить(страницы);
		} catch (e) {
			беды.push(`«${имя}»: правило упало — ${e.message}`);
			continue;
		}
		for (const [id, ожидание] of Object.entries(ждём)) {
			const р = решения.get(id);
			if (!р) {
				беды.push(`«${имя}»: правило не сказало ничего про ${id}`);
			} else if (р.index !== ожидание) {
				беды.push(
					`«${имя}»: ${id} ожидался ${ожидание ? 'в индексе' : 'закрытым'}, ` +
						`а вышло ${р.index ? 'в индексе' : 'закрыто'} (причина «${р.причина}», счёт ${р.счёт})`,
				);
			}
		}
	}

	// ПОРЯДКОНЕЗАВИСИМОСТЬ. Мерим не глазами: тот же вход развёрнутый
	// и трижды перемешанный обязан дать ПОБАЙТНО тот же ответ.
	const данные = вседанные();
	let эталон;
	try {
		эталон = слепок(решить(данные));
		const входы = [['развёрнутый', [...данные].reverse()]];
		for (const зерно of [1, 7, 42]) входы.push([`перемешанный (зерно ${зерно})`, перемешать(данные, зерно)]);
		for (const [как, вход] of входы) {
			if (слепок(решить(вход)) !== эталон) беды.push(`порядок входа изменил ответ: вход ${как}`);
		}
	} catch (e) {
		беды.push(`порядконезависимость: правило упало — ${e.message}`);
	}

	return беды;
}

async function правилоИз(путь) {
	// Метка времени в адресе — чтобы Node не отдал модуль из своего кэша.
	const m = await import(`${путь}?${Date.now()}${Math.random()}`);
	return m.решить;
}

async function главная() {
	const подлог = process.argv.includes('--подлог') || process.argv.includes('--selftest');
	let код = 0;

	if (!подлог) {
		const беды = проверить(await правилоИз(ПРАВИЛО.href));
		if (беды.length > 0) {
			console.error(`✗ Правило индексируемости нарушено в ${беды.length} случаях:`);
			for (const б of беды) console.error('   ' + б);
			return 1;
		}
		console.log(`ок      Правило индексируемости: ${СЛУЧАИ.length} случаев, ответ не зависит от порядка входа.`);
		return 0;
	}

	const исходник = await readFile(ПРАВИЛО, 'utf8');
	for (const [имя, [было, стало]] of Object.entries(ПОДЛОГИ)) {
		if (!исходник.includes(было)) {
			console.error(`✗ ПОДЛОГ «${имя}» НЕ СОБРАН: строки нет в правиле дословно.`);
			console.error(`   Искал: ${было}`);
			console.error('   Значит правило переписали — чинить надо проверку вместе с ним.');
			код = 1;
			continue;
		}
		await writeFile(ПОДМЕНА, исходник.replace(было, стало), 'utf8');
		let беды;
		try {
			беды = проверить(await правилоИз(ПОДМЕНА.href));
		} finally {
			// Убираем ДО любого выхода: `process.exit` внутри try не выполняет
			// finally, поэтому кодом возврата тут не бросаемся вовсе.
			await unlink(ПОДМЕНА).catch(() => {});
		}
		if (беды.length === 0) {
			console.error(`✗ ПОДЛОГ «${имя}» НЕ ПОЙМАН: развели строку, а проверка промолчала. Чинить надо проверку.`);
			console.error(`   Развели: ${было}`);
			код = 1;
		} else {
			console.log(`✓ Подлог «${имя}» пойман, нарушений ${беды.length}. Первое: ${беды[0]}`);
		}
	}

	if (код === 0) {
		// Вторая половина: показать, что на здоровом правиле те же случаи проходят.
		const беды = проверить(await правилоИз(ПРАВИЛО.href));
		if (беды.length > 0) {
			console.error('✗ А на ЗДОРОВОМ правиле проверка красная — значит она ловит не подлог, а себя:');
			for (const б of беды) console.error('   ' + б);
			код = 1;
		} else {
			console.log('✓ На здоровом правиле те же случаи проходят молча. Проверка умеет краснеть по делу.');
		}
	}
	return код;
}

// Русские буквы в пути: import.meta.url их кодирует, process.argv[1] — нет.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
	process.exitCode = await главная();
}
