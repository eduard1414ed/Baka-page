// ПРОВЕРКА СЛУШАЮЩЕЙ ЧАСТИ БОТА (задача 28).
//
//   node scripts/analytics-bot.test.mjs
//   node scripts/analytics-bot.test.mjs --подлог
//
// ЧТО ИМЕННО ЗДЕСЬ ДЕРЖИТСЯ:
//   1. ЧУЖОМУ — МОЛЧАНИЕ, А НЕ ОТКАЗ. Ответ «вам нельзя» подтверждает, что бот
//      жив и что за ним что-то есть. Это главное правило задачи 28, пункт 4:
//      бот выкладывает статистику сайта, и знать о нём посторонним незачем.
//   2. Свой получает ответ.
//   3. Не понял — говорит, что умеет, а не молчит и не выдумывает.
//   4. НИ ОДНО СЛОВО ИЗ СООБЩЕНИЯ НЕ ПОПАДАЕТ В КОМАНДНУЮ СТРОКУ. Из всего
//      написанного человеком берётся только число дней, и берётся числом.
//
// ГОНЯЕТСЯ НАСТОЯЩИЙ hetzner/analytics-bot.mjs, а не копия его логики рядом:
// копия разошлась бы с оригиналом на первой правке и продолжала бы зеленеть.
// Подменяется ровно один адрес — телеграма (TELEGRAM_API_BASE) — и папка,
// где лежат скрипты аналитики (BAKA_REPO): поддельный digest.mjs печатает
// свои доводы, и по ним видно, что именно бот запустил.
//
// ПОДЛОГ ВОЗВРАЩАЕТ РОВНО ТУ ОШИБКУ, ОТ КОТОРОЙ ЗАЩИЩАЕМСЯ: снимает проверку
// «свой ли чат». Проверка обязана на нём покраснеть — иначе её «всё хорошо»
// не значит ничего. И обязана промолчать на здоровом: подлог, который
// «поймался», ничего не стоит, пока проверка не молчит на исправном коде.

import { createServer } from 'node:http';
import { spawn } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..');
const ФАЙЛ_БОТА = join(КОРЕНЬ, 'hetzner', 'analytics-bot.mjs');
const ПОДЛОГ = process.argv.includes('--подлог');

const СВОЙ = '200100300';
const ЧУЖОЙ = '999888777';

const пауза = (мс) => new Promise((r) => setTimeout(r, мс));

let провалов = 0;
function сверка(описание, вышло) {
	console.log(`${вышло ? '  ✓' : '  ✗'} ${описание}`);
	if (!вышло) провалов++;
}

// ── ПЕСОЧНИЦА ──────────────────────────────────────────────────────────────

const песок = mkdtempSync(join(tmpdir(), 'baka-bot-'));
mkdirSync(join(песок, 'scripts', 'analytics'), { recursive: true });

// Поддельный digest.mjs: в сеть не ходит, печатает свои доводы. По ним видно,
// что бот запустил и с чем, — то есть проверяется не обещание, а факт.
writeFileSync(
	join(песок, 'scripts', 'analytics', 'digest.mjs'),
	'process.stdout.write("СВОДКА|" + process.argv.slice(2).join("|") + "\\n");\n',
	'utf8',
);

// Настоящий файл бота или он же с вырезанным заслоном.
const исходник = readFileSync(ФАЙЛ_БОТА, 'utf8');
let код = исходник;
if (ПОДЛОГ) {
	const было = 'if (!СВОИ.has(чат)) {';
	if (!исходник.includes(было)) {
		console.error('ПОДЛОГ НЕ НАШЁЛ, ЧТО ПОДМЕНЯТЬ: строка проверки «свой ли чат» изменилась.');
		console.error('Это не «всё хорошо», это сломанный подлог — почините его вместе с ботом.');
		process.exit(1);
	}
	// ПОДМЕНЯЕМ УСЛОВИЕ, А НЕ ВЫБРАСЫВАЕМ ВЕТКУ: так возвращается ровно та
	// поломка, которая случается в жизни, — заслон на месте, но не срабатывает.
	код = исходник.replace(было, 'if (false) {');
}
const путьБота = join(песок, 'bot.mjs');
writeFileSync(путьБота, код, 'utf8');

// ── ПОДДЕЛЬНЫЙ ТЕЛЕГРАМ ────────────────────────────────────────────────────

const очередь = [];        // что бот ещё не забрал
const отправлено = [];     // что бот прислал: {метод, чат, текст}
const запусков = [];       // доводы, с которыми бот звал digest.mjs
let командыПоставлены = false;

const сервер = createServer((зпр, отв) => {
	let тело = '';
	зпр.on('data', (к) => (тело += к));
	зпр.on('end', () => {
		const метод = зпр.url.split('/').pop();
		const дано = тело ? JSON.parse(тело) : {};
		const ответить = (о) => {
			отв.writeHead(200, { 'Content-Type': 'application/json' });
			отв.end(JSON.stringify({ ok: true, result: о }));
		};
		if (метод === 'setMyCommands') {
			командыПоставлены = Array.isArray(дано.commands) && дано.commands.length > 0;
			return ответить(true);
		}
		if (метод === 'getUpdates') {
			const выдать = очередь.splice(0, очередь.length);
			// Не отдаём пустой ответ мгновенно: иначе бот крутил бы пустой
			// круг тысячи раз в секунду и съел бы всё время проверки.
			if (!выдать.length) return setTimeout(() => ответить([]), 120);
			return ответить(выдать);
		}
		if (метод === 'sendMessage') {
			отправлено.push({ метод, чат: String(дано.chat_id), текст: String(дано.text ?? '') });
			return ответить({ message_id: отправлено.length });
		}
		ответить(true);
	});
});
await new Promise((r) => сервер.listen(0, '127.0.0.1', r));
const порт = сервер.address().port;

let номер = 1;
const написать = (чат, текст) => очередь.push({ update_id: номер++, message: { message_id: номер, chat: { id: Number(чат) }, from: { username: 'кто-то' }, text: текст } });

// ── ЗАПУСК ─────────────────────────────────────────────────────────────────

const бот = spawn(process.execPath, [путьБота], {
	env: {
		...process.env,
		TELEGRAM_BOT_TOKEN: 'проверочный-токен',
		TELEGRAM_CHAT_ID: СВОЙ,
		TELEGRAM_API_BASE: `http://127.0.0.1:${порт}`,
		BAKA_REPO: песок,
	},
	stdio: ['ignore', 'pipe', 'pipe'],
});
let журнал = '';
бот.stdout.on('data', (к) => (журнал += к));
бот.stderr.on('data', (к) => (журнал += к));

// Бот запускает node по абсолютному пути /usr/bin/node — на macOS его нет.
// Ловим это заранее и говорим прямо, а не выдаём за поломку правил.
const естьUsrBinNode = (() => {
	try {
		readFileSync('/usr/bin/node');
		return true;
	} catch {
		return false;
	}
})();

function прибрать(код) {
	бот.kill('SIGKILL');
	сервер.close();
	rmSync(песок, { recursive: true, force: true });
	process.exit(код);
}

try {
	await пауза(700); // дать боту подняться и поставить список команд

	console.log(ПОДЛОГ ? 'ПОДЛОГ: заслон «свой ли чат» снят — проверка ОБЯЗАНА покраснеть\n' : 'Проверка слушающей части бота\n');

	сверка('список команд для меню телеграма поставлен', командыПоставлены);

	// ── 1. ЧУЖОЙ ───────────────────────────────────────────────────────────
	написать(ЧУЖОЙ, '/week');
	написать(ЧУЖОЙ, 'привет, ты кто');
	await пауза(900);
	const чужому = отправлено.filter((о) => о.чат === ЧУЖОЙ);
	сверка(`чужому не отправлено НИ ОДНОГО сообщения (отправлено ${чужому.length})`, чужому.length === 0);
	сверка('стук чужого при этом записан в журнал', /чужой 999888777/.test(журнал));

	// ── 2. СВОЙ ────────────────────────────────────────────────────────────
	написать(СВОЙ, '/help');
	await пауза(700);
	const помощь = отправлено.filter((о) => о.чат === СВОЙ).pop();
	сверка('свой на /help получил список команд', Boolean(помощь) && помощь.текст.includes('/week') && помощь.текст.includes('/report'));

	// ── 3. НЕ ПОНЯЛ — ГОВОРИТ, ЧТО УМЕЕТ ───────────────────────────────────
	написать(СВОЙ, 'сколько у нас денег');
	await пауза(700);
	const непонятно = отправлено.filter((о) => о.чат === СВОЙ).pop();
	сверка('на непонятное — ответ, а не молчание', Boolean(непонятно));
	сверка('и в ответе перечислено, что бот умеет', Boolean(непонятно) && непонятно.текст.includes('/week'));
	сверка('и сказано, что именно не понято', Boolean(непонятно) && непонятно.текст.includes('Не понял'));

	// ── 4. РАБОТА ЗАПУСКАЕТСЯ, И ТОЛЬКО СВОЯ ───────────────────────────────
	if (естьUsrBinNode) {
		написать(СВОЙ, 'неделя');
		await пауза(1500);
		const сводка = отправлено.filter((о) => о.чат === СВОЙ).pop();
		сверка('русское слово «неделя» тоже понято', Boolean(сводка) && сводка.текст.startsWith('СВОДКА|'));
		сверка('и запущено с недельным сроком', Boolean(сводка) && сводка.текст.includes('--дней|7'));

		// ЧИСЛО БЕРЁТСЯ, СЛОВА — НЕТ. Пишем срок вперемешку с посторонним
		// текстом: до командной строки обязано доехать только число.
		написать(СВОЙ, 'месяц 14');
		await пауза(1500);
		const свой14 = отправлено.filter((о) => о.чат === СВОЙ).pop();
		сверка('число дней из сообщения доехало', Boolean(свой14) && свой14.текст.includes('--дней|14'));
		сверка('а слов из сообщения в доводах нет', Boolean(свой14) && !/месяц/.test(свой14.текст));
	} else {
		console.log('  · запуск работы не проверен: бот зовёт /usr/bin/node, а здесь его нет (так на macOS)');
		console.log('    Это проверяется на сервере — там путь настоящий.');
	}

	console.log('');
	if (ПОДЛОГ) {
		if (провалов > 0) {
			console.log(`ПОДЛОГ ПОЙМАН: провалов ${провалов}. Проверка умеет краснеть.`);
			прибрать(0);
		}
		console.log('ПОДЛОГ НЕ ПОЙМАН — проверка ничего не стоит.');
		прибрать(1);
	}
	if (провалов > 0) {
		console.log(`ПРОВАЛОВ: ${провалов}`);
		прибрать(1);
	}
	console.log('Всё сошлось.');
	прибрать(0);
} catch (e) {
	console.error(`проверка сломалась: ${e.stack}`);
	console.error(`журнал бота:\n${журнал}`);
	прибрать(1);
}
