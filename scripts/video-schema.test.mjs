// РОЛИК НА СТРАНИЦЕ МАТЕРИАЛА ОБЯЗАН ИМЕТЬ СВОЙ ОБЪЕКТ РАЗМЕТКИ
// (TASK-markup, пункт 1.2).
//
// ЗАЧЕМ ЭТА ПРОВЕРКА ВООБЩЕ ЕСТЬ. «Как выглядит вставка ролика» знают ДВА
// куска кода, и разными путями:
//
//   src/plugins/remark-video.mjs — работает на разобранном дереве разметки
//                                  и рисует на странице <iframe>;
//   src/lib/youtube.mjs          — читает исходный markdown глазами строки
//                                  и отдаёт список адресов для разметки.
//
// Копии свести в одну нельзя: странице разобранное дерево недоступно, плагину
// исходный текст — уже не нужен. Значит они могут разъехаться, и разъедутся
// молча: на странице ролик будет, в разметке его не будет, и не заметит никто.
// Пометка «меняете тут — поправьте и там» в этом проекте не удержала ни одной
// копии, поэтому копии сверяет замер по СОБРАННЫМ страницам.
//
//   node scripts/video-schema.test.mjs             — проверить
//   node scripts/video-schema.test.mjs --selftest  — развести одну копию
//                                                    и убедиться, что красная
//
// ПОДЛОГ РАЗВОДИТ РОВНО ОДНУ СТРАНИЦУ, а не отменяет правило целиком: в жизни
// копии расходятся именно так — у одного ролика объект пропал, у другого
// появился лишний. Подлог, снимающий разметку со всех страниц сразу, проверял
// бы не то.
//
// ВТОРОЕ, ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ (с 13 сентября 2026): объект, который всё-таки
// вышел, обязан нести `name`, `uploadDate` и `thumbnailUrl` — у Schema.org они
// обязательные, а без них Google не показывает страницу в выдаче вовсе.
// Огрызок из одного адреса сайт печатал полгода, и узнали об этом письмом
// из Search Console, а не от сборки.
//
// У НАХОДОК ДВА РОДА, И РОНЯТЬ СБОРКУ ИМЕЕТ ПРАВО ТОЛЬКО ОДИН.
//
//   ПОЛОМКА КОДА — роняем. Ролик, про который кэш всё знает, а объекта у него
//   нет; объект без обязательного поля; объект без окошка на странице.
//   Такого в репозитории быть не должно.
//
//   ПРОБЕЛ В ДАННЫХ — печатаем строчку и идём дальше. Заказчик опубликовал
//   выпуск с новым роликом, а `node scripts/fetch-youtube-meta.mjs` никто
//   не позвал: ролик выпал из разметки законно. Урони мы на этом сборку —
//   выкладка сайта встала бы из-за поста, набранного в админке, и заслон
//   сняли бы вместе с пользой. Кэш при этом спрашивается НАСТОЯЩИЙ
//   (src/data/youtubeMeta.mjs), а не переписанный сюда списком.

import { readdir, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { youtubeMeta } from '../src/data/youtubeMeta.mjs';

const selftest = process.argv.includes('--selftest');

const DIST = fileURLToPath(new URL('../dist/posts/', import.meta.url));

if (!existsSync(DIST)) {
	console.error('✗ Нет собранной папки dist/posts — сначала `npm run build`.');
	process.exit(1);
}

const LD_RE = /<script type="application\/ld\+json">(.*?)<\/script>/gs;
const IFRAME_SRC_RE = /<iframe[^>]*\bsrc="(https:\/\/www\.youtube\.com\/embed\/[^"]*)"/g;

/** Что на странице: адреса роликов в разметке и адреса роликов в вёрстке. */
function разобрать(html) {
	const объекты = [];
	for (const [, json] of html.matchAll(LD_RE)) {
		let data;
		try {
			data = JSON.parse(json);
		} catch {
			continue;
		}
		if (data['@type'] === 'VideoObject' && data.embedUrl) объекты.push(data);
	}

	// Только те окошки, что стоят в тексте материала: закреплённый плеер
	// и прочая обвязка страницы роликов не содержит, но искать надо всё равно
	// по вёрстке, а не по нашему же списку — иначе проверка сверяла бы список
	// сам с собой.
	const вёрстка = [...html.matchAll(IFRAME_SRC_RE)].map(([, src]) => src.split('?')[0]);

	return { объекты, вёрстка: [...new Set(вёрстка)] };
}

const файлы = (await readdir(DIST, { withFileTypes: true })).filter((d) => d.isDirectory()).map((d) => d.name);

const беды = [];
const пробелы = [];
let страниц = 0;
let роликов = 0;
let подложено = false;
let подложеноПоле = false;

/** Имя ролика из адреса окошка. */
const имяРолика = (src) => String(src).split('/').pop();

/** Знает ли кэш про этот ролик всё, что разметке обязательно. */
const кэшЗнает = (id) => Boolean(youtubeMeta[id]?.name && youtubeMeta[id]?.uploadDate);

for (const slug of файлы) {
	const путь = `${DIST}${slug}/index.html`;
	if (!existsSync(путь)) continue;

	let html = await readFile(путь, 'utf8');

	// ПОДЛОГ ПЕРВЫЙ: у первой же страницы, где ролик есть, отнимаем его объект
	// разметки. Ровно то, что случится, если правило разбора текста перестанет
	// узнавать вставку, которую плагин узнаёт.
	if (selftest && !подложено && html.includes('"@type":"VideoObject"')) {
		html = html.replace(/<script type="application\/ld\+json">\{"@context":"https:\/\/schema\.org","@type":"VideoObject".*?<\/script>/s, '');
		подложено = true;
	} else if (selftest && подложено && !подложеноПоле && html.includes('"@type":"VideoObject"')) {
		// ПОДЛОГ ВТОРОЙ, И ОН ПРО ДРУГОЕ: объект на месте, а обязательного поля
		// в нём нет. Так выглядела разметка ep-154, из-за которой пришло письмо
		// из Search Console: адрес есть, имени нет, страница к показу
		// не допускается. Разводим РОВНО ОДНУ страницу, как и первый.
		const было = html;
		html = html.replace(/("@type":"VideoObject",.*?),"name":"(?:[^"\\]|\\.)*"/s, '$1');
		подложеноПоле = было !== html;
	}

	const { объекты, вёрстка } = разобрать(html);
	// Страницы без единого ролика не считаем: их сотни, и «ноль равен нулю»
	// в отчёте только прячет настоящее число.
	if (объекты.length === 0 && вёрстка.length === 0) continue;

	страниц += 1;
	роликов += вёрстка.length;

	const адресаОбъектов = объекты.map((o) => o.embedUrl);

	for (const src of вёрстка) {
		if (адресаОбъектов.includes(src)) continue;
		const id = имяРолика(src);
		if (кэшЗнает(id)) {
			беды.push(`${slug}: ролик ${src} есть на странице, кэш про него всё знает, а объекта разметки у него нет`);
		} else {
			пробелы.push(`${slug}: ролик ${id} — в кэше нет названия или даты выхода, объект разметки не выведен`);
		}
	}

	for (const объект of объекты) {
		const src = объект.embedUrl;
		if (!вёрстка.includes(src)) беды.push(`${slug}: объект разметки ${src} есть, а самого ролика на странице нет`);

		// Обязательные поля VideoObject. Проверяем У СОБРАННОЙ СТРАНИЦЫ,
		// а не у кэша: между кэшем и страницей лежит наш код, и разошлись бы
		// они именно в нём.
		for (const поле of ['name', 'uploadDate', 'thumbnailUrl']) {
			if (!объект[поле]) беды.push(`${slug}: у объекта ${src} нет обязательного поля «${поле}»`);
		}
	}
}

if (selftest) {
	if (!подложено || !подложеноПоле) {
		console.error('✗ ПОДЛОГ НЕ УДАЛСЯ: не нашлось двух страниц с роликами — проверять нечего.');
		process.exit(1);
	}
	const пойманоПропажу = беды.some((б) => б.includes('объекта разметки у него нет'));
	const пойманоПоле = беды.some((б) => б.includes('обязательного поля'));
	if (!пойманоПропажу) {
		console.error('✗ ПОДЛОГ НЕ ПОЙМАН: у ролика отняли объект разметки, а проверка промолчала. Чинить надо проверку.');
		process.exit(1);
	}
	if (!пойманоПоле) {
		console.error('✗ ПОДЛОГ НЕ ПОЙМАН: у объекта отняли обязательное поле, а проверка промолчала. Чинить надо проверку.');
		process.exit(1);
	}
	console.log(`✓ Подлог пойман дважды:`);
	console.log('   ' + беды.find((б) => б.includes('объекта разметки у него нет')));
	console.log('   ' + беды.find((б) => б.includes('обязательного поля')));
	console.log('  Проверка умеет краснеть на обоих родах поломки.');
	process.exit(0);
}

// Пробелы в данных печатаются ВСЕГДА, и красными они сборку не роняют.
// Молчать о них нельзя: ролик выпал из разметки, и узнать об этом иначе
// неоткуда — страница-то выглядит правильно.
if (пробелы.length > 0) {
	console.log(`!  Роликов без данных: ${пробелы.length} — они выпали из разметки (это не поломка, это пустой кэш):`);
	for (const п of пробелы) console.log('   ' + п);
	console.log('   Лечится одной командой: node scripts/fetch-youtube-meta.mjs');
}

if (беды.length > 0) {
	console.error(`✗ Разметка роликов разошлась с вёрсткой в ${беды.length} случаях:`);
	for (const б of беды) console.error('   ' + б);
	process.exit(1);
}

console.log(
	`ок      Разметка роликов: страниц с роликами ${страниц}, роликов на них ${роликов}, у каждого свой объект с name, uploadDate и thumbnailUrl.`,
);
