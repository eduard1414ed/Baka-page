// ВИД МАРКИ ТАЙТЛА ОДИН НА ВСЕ МЕСТА — сверка по СОБРАННОМУ CSS.
//
//   node scripts/stamp-look.test.mjs             — сверить
//   node scripts/stamp-look.test.mjs --selftest  — подлог: развести копии
//
// ЗАЧЕМ. Марка тайтла — «почтовая марка» с зубчиками по краям — рисуется
// в ЧЕТЫРЁХ местах: горизонтальная (главная и блоки «Упоминается»), каталожная,
// страница тайтла и выдача поиска. Карта кода утверждает, что форм две и живут
// они в двух компонентах; на деле описание вида лежало в четырёх файлах
// (доревизия задачи 15, находка 23). Пока копии совпадают, беды нет — а когда
// разойдутся, увидит это заказчик глазами, и не сразу: расхождение мелкой
// детали читается неряшливостью, а не ошибкой.
//
// ЧТО СПРАШИВАЕМ. Не «одинаково ли написано», а «одинаковы ли ЗНАЧЕНИЯ»:
// сборщик сжимает цвета и пробелы по-своему, и посимвольное сравнение
// объявляло бы нарушением здоровый код (записанный урок проекта).
//
// ЗУБЧИКИ БЫВАЮТ ДВУХ РАЗМЕРОВ, И ЭТО НЕ ОШИБКА: у мелких марок шаг 16×10,
// у крупных 18×12. Требуется не «все четыре одинаковы», а «внутри каждого
// размера — одно описание».

import fs from 'node:fs';
import { styleSourcesOf } from './measure-computed.mjs';

// СТРАНИЦЫ-ОБРАЗЦЫ — ПО ОДНОЙ НА КАЖДОЕ МЕСТО, ГДЕ РИСУЕТСЯ МАРКА.
// Спрашивать надо именно страницы, а не папку `_astro/`: Astro часть правил
// кладёт файлом, а часть вставляет ПРЯМО В `<head>` страницы. Первая редакция
// этой проверки читала только файлы — и не увидела ни горизонтальной марки,
// ни каталожной, зато бодро ответила «вид сходится». Записанный урок проекта,
// и я на него наступил здесь же.
const ОБРАЗЦЫ = [
	['горизонтальная марка (главная)', 'dist/index.html'],
	['каталожная марка', 'dist/anime/index.html'],
	['страница тайтла', null], // подставится первой попавшейся
	['выдача поиска', 'dist/search/index.html'],
];

/** Все куски CSS страниц-образцов: и файлы по ссылкам, и вставленное в разметку. */
function собранныйCss() {
	if (!fs.existsSync('dist')) {
		console.error('Нет собранной папки — сначала `npm run build`.');
		process.exit(1);
	}
	const тайтл = fs.existsSync('dist/anime')
		? fs.readdirSync('dist/anime').filter((n) => n !== 'index.html').map((n) => `dist/anime/${n}/index.html`).find((p) => fs.existsSync(p))
		: null;

	const out = [];
	const видели = new Set();
	for (const [имя, путь] of ОБРАЗЦЫ) {
		const файл = путь ?? тайтл;
		if (!файл || !fs.existsSync(файл)) {
			console.error(`✗ Страница-образец «${имя}» не нашлась в сборке — проверять нечем.`);
			process.exit(1);
		}
		for (const s of styleSourcesOf(файл)) {
			const ключ = `${s.from}::${s.css.length}`;
			if (видели.has(ключ)) continue;
			видели.add(ключ);
			out.push({ file: `${имя}: ${s.from}`, css: s.css });
		}
	}
	console.log(`кусков стилей прочитано: ${out.length} (страниц-образцов ${ОБРАЗЦЫ.length})`);
	return out;
}

/**
 * Объявления зубчиков у каждой марки: ищем правила псевдоэлементов
 * с радиальным градиентом — именно им нарисована перфорация.
 *
 * Сборщик пишет псевдоэлемент ОДНИМ двоеточием (`:after`, а не `::after`) —
 * записанный урок проекта, спрашивать надо на языке сборщика.
 */
export function зубчики(sources) {
	const out = new Map(); // имя марки → набор «свойство:значение»

	for (const { css } of sources) {
		for (const m of css.matchAll(/([^{}@]*radial-gradient[^{}]*)\}/g)) void m;
		for (const m of css.matchAll(/([^{}@]+)\{([^{}]*radial-gradient[^{}]*)\}/g)) {
			const selectors = m[1].split(',').map((s) => s.trim());
			const decls = m[2]
				.split(';')
				.map((d) => d.trim().replace(/\s+/g, ' '))
				.filter(Boolean)
				.sort()
				.join(' | ');
			for (const sel of selectors) {
				const марка = /\.([\w-]*stamp[\w-]*|perf-[\w-]+|inner)\b/.exec(sel);
				if (!марка) continue;
				const сторона = /:{1,2}(before|after)/.test(sel) ? 'край' : 'бок';
				const ключ = `${марка[1]} ${сторона}`;
				if (!out.has(ключ)) out.set(ключ, new Set());
				out.get(ключ).add(decls);
			}
		}
	}
	return out;
}

/**
 * Вид стрелки «→» в углу марки: кегль, высота строки, цвет.
 *
 * МЕСТО НЕ СЧИТАЕМ НАРОЧНО. `position`, `right` и `bottom` у каждой марки свои
 * и обязаны быть своими — у горизонтальной угол один, у каталожной другой.
 * Сверяем ровно то, что обязано совпадать.
 */
export function стрелкаМарки(sources) {
	const out = new Map();
	const ВИДОВЫЕ = ['font-size', 'line-height', 'color'];

	for (const { css } of sources) {
		for (const m of css.matchAll(/([^{}@]+)\{([^{}]*)\}/g)) {
			for (const sel of m[1].split(',').map((s) => s.trim())) {
				const хвост = sel.split(/\s+/).pop() ?? '';
				if (!/\.(arrow|result-arrow)\b/.test(хвост)) continue;
				if (/:{1,2}(hover|focus|before|after|focus-visible)/.test(хвост)) continue;
				const вид = m[2]
					.split(';')
					.map((d) => d.trim())
					.filter((d) => ВИДОВЫЕ.some((p) => d.startsWith(`${p}:`)))
					.map((d) => d.replace(/\s+/g, ''))
					.sort()
					.join(' | ');
				if (!вид) continue;
				// КЛЮЧ — САМ СЕЛЕКТОР ЦЕЛИКОМ, а не «имя класса плюс догадка о месте».
				// Первая редакция звала обе `.arrow` одним именем, и вторая молча
				// затирала первую: мест было три, проверка показывала два —
				// и расхождение между двумя затёршимися пропустила бы совсем.
				// Метку компонента (`[data-astro-cid-…]`) Astro даёт разную,
				// поэтому селектор сам по себе места и различает.
				out.set(sel.replace(/\s+/g, ' '), вид);
			}
		}
	}
	return out;
}

/** Шаг зубчиков — число, по которому марки делятся на мелкие и крупные. */
function шаг(decls) {
	const m = /\/ ?(\d+)px (\d+)px/.exec(decls);
	return m ? `${m[1]}×${m[2]}` : '?';
}

const FAILURES = [];
const check = (name, ok, detail = '') => {
	console.log((ok ? '  ок    ' : '  ПЛОХО ') + name + (detail && !ok ? `\n         ${detail}` : ''));
	if (!ok) FAILURES.push(name);
};

function main() {
	const selftest = process.argv.includes('--selftest');
	let sources = собранныйCss();

	if (selftest) {
		// ПОДЛОГ: РАЗВОДИМ ОДНУ КОПИЮ, А НЕ МЕНЯЕМ ЗНАЧЕНИЕ ВЕЗДЕ СРАЗУ.
		//
		// Первая редакция подлога делала именно второе — заменяла размер зубца
		// во всех файлах — и не ловилась, потому что расхождения не создавала:
		// описание оставалось одно, просто другое. Это записанный урок проекта
		// («подлог, ничего не разведший, обвиняет проверку в своей ошибке»).
		//
		// Сборщик СКЛЕИВАЕТ правила с одинаковыми объявлениями, поэтому четыре
		// копии из исходников лежат в сборке одним правилом с четырьмя
		// селекторами. Развести копию — значит дописать ОДНОМУ месту своё,
		// отличное описание: ровно так это и случится в жизни, когда кто-то
		// поправит вид в одном файле и не поправит в трёх.
		const беглец =
			'.anime-stamp:before,.anime-stamp:after{background:radial-gradient(circle at 5px 0, var(--paper) 3px, transparent 3.5px) 0 0 / 16px 10px repeat-x}';
		const где = sources.findIndex(({ css }) => css.includes('radial-gradient'));
		if (где === -1) {
			console.error('✗ ПОДЛОГ НЕ СРАБОТАЛ: в собранном CSS не нашлось описания зубчиков.');
			console.error('  Пока подлог ничего не подменил, проверка не доказывает ничего.');
			process.exit(1);
		}
		sources = sources.map((s, i) => (i === где ? { ...s, css: s.css + беглец } : s));
		console.log('ПОДЛОГ: одной марке дописано СВОЁ описание зубчиков — зубец 3px вместо 4px.\n');
	}

	const найдено = зубчики(sources);
	console.log(`мест с зубчиками найдено: ${найдено.size}`);
	for (const [ключ, набор] of [...найдено].sort()) {
		console.log(`   ${ключ.padEnd(22)} шаг ${[...набор].map(шаг).join(', ')}`);
	}
	console.log();

	// 1. У одного места — ровно одно описание. Два разных значения на одном
	//    и том же месте это уже разъехавшаяся копия внутри себя.
	for (const [ключ, набор] of найдено) {
		check(`«${ключ}» описано один раз`, набор.size === 1, `описаний ${набор.size}: ${[...набор].map(шаг).join(' и ')}`);
	}

	// 2. Внутри каждого размера описание ОДНО на всех. Это и есть главный вопрос.
	const поШагу = new Map();
	for (const [ключ, набор] of найдено) {
		for (const decls of набор) {
			const s = шаг(decls);
			if (!поШагу.has(s)) поШагу.set(s, new Map());
			поШагу.get(s).set(ключ, decls);
		}
	}
	for (const [s, места] of поШагу) {
		const разные = new Set(места.values());
		check(
			`шаг ${s}: одно описание на все места (${[...места.keys()].join(', ')})`,
			разные.size === 1,
			`разных описаний ${разные.size}`,
		);
	}

	// 3. Размеров ровно два — третьего у марок не бывает.
	check('размеров зубчиков ровно два', поШагу.size === 4, `нашлось ${поШагу.size}: ${[...поШагу.keys()].join(', ')}`);

	// 4. СТРЕЛКА «→» В УГЛУ МАРКИ — тоже часть её вида, и описана она в трёх
	//    местах: горизонтальная марка, каталожная и выдача поиска. Место у неё
	//    своё (у каждой марки свой угол), а ВИД обязан совпадать: кегль, высота
	//    строки, цвет. Ровно та беда, из-за которой в проекте уже разъехалась
	//    стрелка ↗ — пять мест, пять описаний, и никто не замечал, пока
	//    заказчик не посмотрел на почту.
	const стрелки = стрелкаМарки(sources);
	console.log();
	for (const [сел, вид] of стрелки) console.log(`   стрелка ${сел.padEnd(16)} ${вид}`);
	const видыСтрелок = new Set(стрелки.values());
	check(
		`стрелка марки описана одинаково во всех местах (${стрелки.size})`,
		стрелки.size > 0 && видыСтрелок.size === 1,
		стрелки.size === 0 ? 'стрелок не нашлось вовсе — проверка ослепла' : `разных описаний ${видыСтрелок.size}: ${[...видыСтрелок].join(' / ')}`,
	);

	console.log();
	if (FAILURES.length) {
		if (selftest) {
			console.log('✓ ПОДЛОГ ПОЙМАН: разведённые копии названы.');
			process.exit(0);
		}
		console.log(`ЕСТЬ РАСХОЖДЕНИЯ (${FAILURES.length}): ` + FAILURES.join('; '));
		process.exit(1);
	}
	if (selftest) {
		console.log('✗ ПОДЛОГ НЕ ПОЙМАН: копии развели, а проверка молчит — она смотрит не туда.');
		process.exit(1);
	}
	console.log('Вид марки сходится во всех местах.');
}

main();
