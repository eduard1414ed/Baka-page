#!/usr/bin/env node
// ПРОВЕРКА ЗАПУСКАТОРА: ЧТО ОН ДЕЛАЕТ, КОГДА ПРАВКИ СТОЛКНУЛИСЬ (задача 25).
//
// Запуск: node scripts/launcher-conflict.test.mjs
//
// ПОЧЕМУ ПЕСОЧНИЦА, А НЕ ЧТЕНИЕ КОДА. Столкновение — единственная ветка
// запускатора, где он обязан ОСТАНОВИТЬСЯ и никого не затереть. Проверить это
// на живом репозитории нельзя: пришлось бы нарочно ссорить рабочую копию
// с GitHub. Поэтому строим три настоящих репозитория во временной папке —
// «хранилище», «заказчик» и «робот» — и сталкиваем их по-настоящему.
//
// ЗАПУСКАТОР БЕРЁТСЯ ИЗ САМОГО ФАЙЛА, а не переписывается рядом: копия
// разошлась бы с оригиналом при первой же правке и проверяла бы вчерашний код.
//
// ВЫКЛАДКА ПОДМЕНЕНА ЗАГЛУШКОЙ, и это не поблажка, а требование безопасности:
// настоящий scripts/quick-deploy.mjs выложил бы НАСТОЯЩИЙ САЙТ из песочницы.
// Заглушка оставляет отметку — по ней и видно, дошло дело до выкладки или нет.
//
// ДВЕ ПОЛОВИНЫ, И ОБЕ ОБЯЗАТЕЛЬНЫ:
//   1. столкновение   — запускатор обязан остановиться, объяснить и не затереть;
//   2. чистый случай  — тот же запускатор на тех же данных, но правки в РАЗНЫХ
//                       файлах, обязан пройти до конца.
// Без второй половины «поймал» ничего не значит: проверка, которая краснеет
// всегда, ловит не столкновение, а сама себя.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync, cpSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ЗАПУСКАТОР = join(ROOT, 'scripts', 'launch-deploy.mjs');

let бед = 0;
const скажи = (текст = '') => console.log(текст);
const проверь = (условие, что) => {
	скажи(`   ${условие ? '✓' : '✗'} ${что}`);
	if (!условие) бед += 1;
};

const гит = (где, доводы) => execFileSync('git', доводы, { cwd: где, encoding: 'utf8' }).trim();

const ПОСТ = 'src/content/posts/test-post.md';
const постТекст = (строка) => `---\ntitle: Проверочный пост\ndate: 2026-08-25\ncategory: note\n---\n\n${строка}\n`;

// Заглушка выкладки: настоящую звать нельзя — она выложит живой сайт.
const ЗАГЛУШКА = `import { writeFileSync } from 'node:fs';
console.log('── собираю сайт');
console.log('   готово за 0 с');
console.log('── выкладываю на bakapodcast.com');
writeFileSync(new URL('../ВЫЛОЖЕНО', import.meta.url), 'да');
process.exit(0);
`;

// ── песочница ──────────────────────────────────────────────────────────────
function построить() {
	const корень = mkdtempSync(join(tmpdir(), 'baka-launcher-'));
	const хранилище = join(корень, 'github.git');
	const заказчик = join(корень, 'заказчик');
	const робот = join(корень, 'робот');

	execFileSync('git', ['init', '--bare', '-b', 'main', хранилище], { stdio: 'ignore' });
	execFileSync('git', ['clone', '--quiet', хранилище, заказчик], { stdio: 'ignore' });

	const представься = (где, имя) => {
		гит(где, ['config', 'user.name', имя]);
		гит(где, ['config', 'user.email', `${имя}@example.com`]);
	};
	представься(заказчик, 'eduard1414ed');

	mkdirSync(join(заказчик, 'src', 'content', 'posts'), { recursive: true });
	mkdirSync(join(заказчик, 'scripts'), { recursive: true });
	writeFileSync(join(заказчик, ПОСТ), постТекст('Исходная строка.'));
	writeFileSync(join(заказчик, 'README.md'), 'проверочный репозиторий\n');
	гит(заказчик, ['add', '-A']);
	гит(заказчик, ['commit', '-m', 'Начало']);
	гит(заказчик, ['push', '--quiet', 'origin', 'main']);

	// Запускатор — настоящий, копируется прямо перед прогоном.
	cpSync(ЗАПУСКАТОР, join(заказчик, 'scripts', 'launch-deploy.mjs'));
	writeFileSync(join(заказчик, 'scripts', 'quick-deploy.mjs'), ЗАГЛУШКА);
	гит(заказчик, ['add', '-A']);
	гит(заказчик, ['commit', '-m', 'Запускатор']);
	гит(заказчик, ['push', '--quiet', 'origin', 'main']);

	execFileSync('git', ['clone', '--quiet', хранилище, робот], { stdio: 'ignore' });
	представься(робот, 'baka-anime-bot');

	return { корень, заказчик, робот };
}

function прогнать(где) {
	try {
		const вывод = execFileSync(process.execPath, ['scripts/launch-deploy.mjs'], {
			cwd: где, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'],
		});
		return { код: 0, вывод };
	} catch (сбой) {
		return { код: сбой.status, вывод: `${сбой.stdout || ''}${сбой.stderr || ''}` };
	}
}

// ═══ 1. СТОЛКНОВЕНИЕ ═══════════════════════════════════════════════════════
скажи('\n=== 1. Правки столкнулись: один и тот же пост правили оба ===\n');
{
	const { корень, заказчик, робот } = построить();

	// Робот правит пост и кладёт правку в хранилище.
	writeFileSync(join(робот, ПОСТ), постТекст('Строка от робота.'));
	гит(робот, ['add', '-A']);
	гит(робот, ['commit', '-m', 'Робот поправил пост']);
	гит(робот, ['push', '--quiet', 'origin', 'main']);

	// Заказчик правит ТУ ЖЕ строку у себя и не коммитит.
	writeFileSync(join(заказчик, ПОСТ), постТекст('Строка от заказчика.'));

	const итог = прогнать(заказчик);

	проверь(итог.код === 1, 'запускатор остановился (код возврата 1, а не 0)');
	проверь(/СТОЛКНУЛИСЬ С ЧУЖИМИ/.test(итог.вывод), 'сказал прямым текстом, что правки столкнулись');
	проверь(/Проверочный пост/.test(итог.вывод), 'назвал пост по заголовку, а не по имени файла');
	проверь(/ВАШИ ПРАВКИ ЦЕЛЫ/.test(итог.вывод), 'сказал, что правки заказчика целы');
	проверь(/Claude Code/.test(итог.вывод), 'сказал, что делать дальше');

	проверь(!existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'до выкладки дело НЕ дошло');

	const незавершённое = ['.git/rebase-merge', '.git/rebase-apply', '.git/MERGE_HEAD']
		.some((п) => existsSync(join(заказчик, п)));
	проверь(!незавершённое, 'репозиторий не брошен в середине совмещения');

	проверь(гит(заказчик, ['status', '--porcelain']) === '', 'правки заказчика записаны, рабочая копия чистая');
	проверь(/Строка от заказчика/.test(readFileSync(join(заказчик, ПОСТ), 'utf8')),
		'НИЧЕГО НЕ ЗАТЁРТО: в файле по-прежнему вариант заказчика');
	проверь(/Проверочный пост/.test(гит(заказчик, ['log', '-1', '--format=%s%n%b'])),
		'работа заказчика сохранена отдельным шагом и подписана понятно');

	rmSync(корень, { recursive: true, force: true });
}

// ═══ 2. ЧИСТЫЙ СЛУЧАЙ ══════════════════════════════════════════════════════
скажи('\n=== 2. Правки в разных файлах: остановиться было бы ошибкой ===\n');
{
	const { корень, заказчик, робот } = построить();

	// Робот правит СВОЙ файл.
	writeFileSync(join(робот, 'README.md'), 'правка робота\n');
	гит(робот, ['add', '-A']);
	гит(робот, ['commit', '-m', 'Робот поправил другое']);
	гит(робот, ['push', '--quiet', 'origin', 'main']);

	// Заказчик правит пост.
	writeFileSync(join(заказчик, ПОСТ), постТекст('Строка от заказчика.'));

	const итог = прогнать(заказчик);

	проверь(итог.код === 0, 'запускатор дошёл до конца (код возврата 0)');
	проверь(!/СТОЛКНУЛИСЬ/.test(итог.вывод), 'о столкновении не заикнулся');
	проверь(existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'дело дошло до выкладки');
	проверь(/ГОТОВО/.test(итог.вывод), 'сказал «готово»');
	проверь(/правка робота/.test(readFileSync(join(заказчик, 'README.md'), 'utf8')),
		'чужая правка забрана');
	проверь(/Строка от заказчика/.test(readFileSync(join(заказчик, ПОСТ), 'utf8')),
		'своя правка на месте');

	// Порядок: своё ЛЕЖИТ ПОВЕРХ чужого, а не наоборот.
	const история = гит(заказчик, ['log', '-2', '--format=%s']).split('\n');
	проверь(/Проверочный пост|Правк/.test(история[0]) && /Робот поправил другое/.test(история[1]),
		'порядок верный: сначала чужое, своё сверху');

	// ═══ 3. ПОВТОРНЫЙ ЗАПУСК ═══════════════════════════════════════════════
	скажи('\n=== 3. Второй запуск подряд, ничего не меняя ===\n');
	rmSync(join(заказчик, 'ВЫЛОЖЕНО'));
	const второй = прогнать(заказчик);
	проверь(второй.код === 0, 'второй запуск прошёл спокойно');
	проверь(/ВСЁ УЖЕ НА САЙТЕ/.test(второй.вывод), 'сказал, что выкладывать нечего');
	проверь(!existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'сайт ВТОРОЙ РАЗ НЕ СОБИРАЛСЯ');

	rmSync(корень, { recursive: true, force: true });
}

скажи('');
if (бед > 0) {
	скажи(`✗ НЕ СОШЛОСЬ: ${бед}`);
	process.exit(1);
}
скажи('✓ ВСЁ СОШЛОСЬ: столкновение останавливает, чистый случай проходит,');
скажи('  повторный запуск ничего лишнего не делает.');
process.exit(0);
