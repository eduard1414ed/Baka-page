/**
 * ЗАПИСИ DNS, КОТОРЫЕ НЕЛЬЗЯ ЗАБЫТЬ: DMARC И CAA.
 *
 * DMARC говорит чужим почтовым серверам, что делать с письмом, которое
 * притворяется отправленным с нашего домена. Без записи ответ по умолчанию —
 * «доставить»: написать от имени bakapodcast.com может кто угодно.
 * Домен почтой не пользуется вовсе (проверено у заказчика 20 августа 2026),
 * поэтому стоит самый строгий ответ: отбрасывать. Сломать этим нечего —
 * своих писем с домена не уходит.
 *
 * CAA перечисляет, кому разрешено выдавать сертификаты на домен. Без записи
 * это может сделать любой из полусотни удостоверяющих центров мира.
 * Список взят у Cloudflare (developers.cloudflare.com/ssl/reference/
 * certificate-authorities), а не по памяти, и покрывает обе копии сайта:
 * основной сертификат выдаёт Google Trust Services, зеркальный — Let's Encrypt.
 * Cloudflare дописывает недостающие сам, как только в зоне появится хоть одна
 * запись CAA, — поэтому продление сертификата этим сломать нельзя.
 *
 * Записи живут в панели Cloudflare, в репозитории их нет. Значит проверить
 * можно только спросив DNS — что и делается. Ключ --подлог задаёт те же
 * вопросы домену, у которого таких записей заведомо нет.
 */
import { Resolver } from 'node:dns/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const ДОМЕН = 'bakapodcast.com';

// ИМЯ ДЛЯ ПОДЛОГА — НЕСУЩЕСТВУЮЩЕЕ ИМЯ ВНУТРИ НАШЕГО ЖЕ ДОМЕНА.
//
// Первым подлогом стоял example.com «у него таких записей заведомо нет» —
// и это оказалось неправдой: DMARC у него есть, и как раз p=reject. Подлог
// при этом «поймался» на второй половине (CAA), то есть выглядел удачным,
// а половина проверки молчала неизвестно почему. Опираться на чужой домен
// нельзя вовсе: его записи меняет чужой человек, ничего нам не сообщая.
//
// У несуществующего имени нет ни DMARC, ни CAA по определению, и зависит
// оно только от нас. Разбор имён вверх по дереву не поднимается, поэтому
// записи самого bakapodcast.com сюда не подмешаются.
const ГОЛЫЙ = 'нет-такого-имени-подлог.bakapodcast.com';

/** Чем должна начинаться запись DMARC и что в ней обязано стоять. */
const ЖДЁМ_DMARC = [
	{ что: 'v=DMARC1', зачем: 'признак записи DMARC' },
	{ что: 'p=reject', зачем: 'поддельное письмо отбрасывать, а не прятать в спам' },
];

/** Кому разрешено выдавать сертификаты. Обязателен каждый. */
const ЖДЁМ_CAA = [
	{ что: 'pki.goog', зачем: 'сертификат bakapodcast.com — Google Trust Services' },
	{ что: 'letsencrypt.org', зачем: 'сертификат ru.bakapodcast.com — Let’s Encrypt' },
];

/** Спросить DNS напрямую у публичных серверов, минуя кэш системы. */
function спрашивающий() {
	const р = new Resolver();
	р.setServers(['1.1.1.1', '8.8.8.8']);
	return р;
}

async function main() {
	const подлог = process.argv.includes('--подлог');
	const домен = подлог ? ГОЛЫЙ : ДОМЕН;
	const р = спрашивающий();
	const беды = [];

	console.log(`ЗАПИСИ DNS У ${домен}${подлог ? '  (ПОДЛОГ: имени не существует, записей быть не может)' : ''}\n`);

	// DMARC
	let dmarc = '';
	try {
		const куски = await р.resolveTxt(`_dmarc.${домен}`);
		dmarc = куски.map((к) => к.join('')).find((с) => с.toLowerCase().startsWith('v=dmarc1')) ?? '';
	} catch {
		// «записи нет» приходит ошибкой — это законный ответ, а не сбой связи
	}
	console.log(`DMARC (_dmarc.${домен})`);
	if (!dmarc) {
		console.log('  ✗    записи нет вовсе — письмо от имени домена подделает кто угодно');
		беды.push('нет записи DMARC');
	} else {
		console.log(`       ${dmarc}`);
		for (const { что, зачем } of ЖДЁМ_DMARC) {
			const есть = dmarc.replace(/\s/g, '').toLowerCase().includes(что.toLowerCase());
			console.log(`  ${есть ? 'ок  ' : '✗   '} ${что} — ${зачем}`);
			if (!есть) беды.push(`в DMARC нет «${что}»`);
		}
	}
	console.log();

	// CAA
	let caa = [];
	try {
		caa = await р.resolveCaa(домен);
	} catch {
		// та же история: отсутствие записи приходит ошибкой
	}
	// Теги РАЗНЫЕ, и мешать их в одну кучу нельзя: issue — про обычные
	// сертификаты, issuewild — про сертификаты со звёздочкой. Склеенные,
	// они выглядят повторами одного и того же, и первый вывод этой проверки
	// именно так и выглядел: одиннадцать строк, из которых пять «дубли».
	const записи = caa
		.map((з) => ({ тег: з.issue ? 'issue' : з.issuewild ? 'issuewild' : '', кто: з.issue ?? з.issuewild ?? '' }))
		.filter((з) => з.кто);
	// Сертификаты у нас на точные имена (bakapodcast.com, ru.bakapodcast.com),
	// поэтому обязателен именно issue; issuewild показываем для полноты.
	const выдают = записи.filter((з) => з.тег === 'issue').map((з) => з.кто);
	console.log(`CAA (${домен})`);
	if (!выдают.length) {
		console.log('  ✗    записей нет — сертификат на домен может выпустить любой центр мира');
		беды.push('нет записей CAA');
	} else {
		for (const тег of ['issue', 'issuewild']) {
			const свои = записи.filter((з) => з.тег === тег);
			if (!свои.length) continue;
			console.log(`       ${тег} (${тег === 'issue' ? 'обычные сертификаты' : 'со звёздочкой'}): ${свои.length}`);
			for (const з of свои) console.log(`         ${з.кто}`);
		}
		for (const { что, зачем } of ЖДЁМ_CAA) {
			const есть = выдают.some((с) => с.includes(что));
			console.log(`  ${есть ? 'ок  ' : '✗   '} ${что} — ${зачем}`);
			if (!есть) беды.push(`в CAA нет «${что}» — ${зачем}`);
		}
	}
	console.log();

	if (подлог) {
		if (беды.length) {
			console.log(`✓ ПОДЛОГ ПОЙМАН: у ${ГОЛЫЙ} проверка нашла ${беды.length} расхождений.`);
			console.log('  Значит она смотрит на настоящие записи, а не отвечает «ок» всегда.');
			return 0;
		}
		console.log(`✗ ПОДЛОГ НЕ ПОЙМАН: у ${ГОЛЫЙ} нужных записей нет, а проверка промолчала.`);
		return 1;
	}

	if (беды.length) {
		console.log('✗✗ ЗАПИСЕЙ НЕ ХВАТАЕТ:');
		for (const б of беды) console.log(`   ${б}`);
		console.log('   Заводятся в панели Cloudflare: сайт → DNS → Records → Add record.');
		return 1;
	}
	console.log('ок      DMARC отбрасывает подделки, CAA пускает только нужные центры.');
	return 0;
}

const позвалиНапрямую = resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1] ?? '');
if (позвалиНапрямую) process.exit(await main());
