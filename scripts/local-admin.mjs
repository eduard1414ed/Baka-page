function забратьЧужое() {
	if (!existsSync(join(ROOT, '.git'))) return; // не репозиторий — молча мимо

	const ветка = гит.можно(['rev-parse', '--abbrev-ref', 'HEAD']);
	if (!ветка.ок) {
		скажи('   ⚠ git не ответил, работаю с тем, что лежит на диске');
		return;
	}
	if (ветка.вывод !== 'main') {
		скажи(`   ⚠ вы на ветке «${ветка.вывод}», а не на главной — чужое не забираю`);
		return;
	}

	const спросил = гит.можно(['fetch', '--quiet', 'origin', 'main']);
	if (!спросил.ок) {
		скажи('   ⚠ не достучался до хранилища (нет интернета?) — открываю то, что лежит на диске');
		скажи('     Если робот что-то привёз, вы этого пока не увидите.');
		return;
	}

	const отстали = Number(гит.строка(['rev-list', '--count', 'HEAD..origin/main']) || 0);
	const впереди = Number(гит.строка(['rev-list', '--count', 'origin/main..HEAD']) || 0);

	if (отстали === 0) {
		скажи('   нового нет, ваша копия свежая');
		return;
	}

	const приехало = чтоПриехало(ROOT, 'HEAD', 'origin/main');

	// Есть свои невыложенные коммиты — перематывать нельзя, тут нужен разбор
	// со столкновениями. Это работа кнопки «Выложить», а не открытия админки.
	if (впереди > 0) {
		скажи(`   ⚠ в хранилище есть новое (${отстали}), но у вас ${впереди} невыложенных правок.`);
		скажи('     Не трогаю: свести их — работа кнопки «ВЫЛОЖИТЬ НА САЙТ», она это умеет.');
		рассказать(приехало, 'ЖДЁТ В ХРАНИЛИЩЕ', 'origin/main');
		return;
	}

	const перемотал = гит.можно(['merge', '--ff-only', 'origin/main']);
	if (!перемотал.ок) {
		// Обычная причина: на диске лежат несохранённые правки в тех же файлах.
		// git не тронул ничего — и это ровно то, что нам нужно.
		скажи(`   ⚠ в хранилище есть новое (${отстали}), но забрать не вышло — и НИЧЕГО не тронуто.`);
		скажи('     Чаще всего мешают ваши несохранённые правки в тех же файлах.');
		скажи('     Выложите их кнопкой «ВЫЛОЖИТЬ НА САЙТ» — она заберёт чужое сама.');
		рассказать(приехало, 'ЖДЁТ В ХРАНИЛИЩЕ', 'origin/main');
		return;
	}

	рассказать(приехало, 'ПОКА ВАС НЕ БЫЛО');
}

// Списком названий, а не числом: «привёз 11 файлов» не говорит ничего,
// «выпуск „…“» говорит.
//
// ГЛАВНОЕ ОТДЕЛЬНО ОТ СВИТЫ. Замер на настоящем приходе робота 27.08.2026:
// один новый выпуск приезжает ОДИННАДЦАТЬЮ файлами — две обложки, две
// вырезки персонажа, расшифровка, пословные данные, три служебных списка.
// Вывалить их в столбик значит утопить единственную строчку, ради которой
// список и читают. Поэтому посты и карточки аниме — списком, всё прочее —
// одной строкой числом.
//
// Служебная закладка робота телеграма не попадает даже в это число
// (см. МОЛЧА в repo-news-lib): она переписывается четырежды в сутки
// и не меняет на сайте ровно ничего.
// Довод «версия» задаётся там, где файла на диске ещё нет: заголовок поста
// живёт внутри файла, и без него в списке стояло бы «пост (src/content/…md)» —
// то есть ровно то, чего человек прочесть не может.
function рассказать(приехало, заголовок, версия) {
	if (!приехало) return;
	const новости = приехало.новости;
	if (новости.length === 0) {
		скажи('   роботы приходили, но нового для вас нет — только служебные отметки');
		return;
	}

	const главное = новости.filter((п) =>
		п.startsWith('src/content/posts/') || п.startsWith('src/content/anime/'));
	const свита = новости.length - главное.length;

	скажи('');
	скажи(`   ┌─ ${заголовок} ──────────────────────────────`);
	// «Приходили», а не «привезли»: робот телеграма заходит четырежды в сутки
	// и чаще всего с пустыми руками. Числа тут — сколько раз заходил, а что
	// привёз — видно списком ниже.
	скажи('   │  Приходили:');
	for (const [автор, сколько] of приехало.поАвторам) {
		скажи(`   │    ${БОТЫ[автор] || автор} — ${сколько} раз`);
	}
	скажи('   │');
	if (главное.length === 0) {
		скажи(`   │  Постов и карточек нет — только обложки, расшифровки`);
		скажи(`   │  и служебные данные: ${свита} файлов.`);
	} else {
		for (const путь of главное.slice(0, 12)) {
			const текст = версия ? версияИзКоммита(ROOT, версия, путь) : undefined;
			скажи(`   │  • ${поЧеловечески(путь, текст)}`);
		}
		if (главное.length > 12) скажи(`   │  … и ещё ${главное.length - 12}`);
		if (свита > 0) {
			скажи('   │');
			скажи(`   │  Плюс к ним обложки, расшифровки и служебные данные: ${свита} файлов.`);
		}
	}
	скажи('   └────────────────────────────────────────────');
	скажи('');
}

