скажи('\n── Поднимаю сервер админки');

// КОМАНДУ ЗАПУСКА НЕЛЬЗЯ ЖДАТЬ — ОНА МОЖЕТ НЕ КОНЧИТЬСЯ НИКОГДА.
//
// `astro dev` ведёт себя по-разному в зависимости от того, откуда его позвали.
// Из настоящего окна терминала (а именно так и запускает ярлык заказчика) он
// ДЕРЖИТ ОКНО: работает, пока его не остановят. А запущенный без окна — уходит
// в фон и возвращает управление сразу.
//
// Первая написанная здесь развилка ждала окончания команды. У меня она
// проходила: я проверял без настоящего окна, и Astro уходил в фон. У заказчика
// на первом же двойном щелчке ярлык напечатал «Поднимаю сервер админки»
// и повис навсегда. Проверять надо в тех условиях, в которых работает
// заказчик, а не в тех, что под рукой.
//
// Поэтому теперь: запускаем и НЕ ЖДЁМ, а адрес ловим двумя удочками сразу —
// из того, что сервер печатает (когда держит окно), и вопросом `dev status`
// (когда ушёл в фон). Что ответит первым, то и берём.
let подняли = false;
let серверАдминки = null;
let адресАдминки = адресИз(спроси(['dev', 'status']));

function поднятьАдминку() {
	return new Promise((готово) => {
		let ответил = false;
		let опрос = null;
		const дать = (адрес) => {
			if (ответил) return;
			ответил = true;
			clearInterval(опрос);
			готово(адрес);
		};

		серверАдминки = spawn(ASTRO, ['dev'], {
			cwd: ROOT, env: process.env, stdio: ['ignore', 'pipe', 'pipe'],
		});

		let хвост = '';
		const смотри = (кусок) => {
			хвост += безЦвета(кусок.toString('utf8'));
			const адрес = адресИз(хвост);
			if (адрес) дать(адрес);
		};
		серверАдминки.stdout.on('data', смотри);
		серверАдминки.stderr.on('data', смотри);
		// Закрылся, ничего не сказав, — значит ушёл в фон. Это не беда: адрес
		// принесёт вторая удочка. Ронять тут нечего.
		серверАдминки.on('error', () => дать(null));

		опрос = setInterval(() => {
			const адрес = адресИз(спроси(['dev', 'status']));
			if (адрес) дать(адрес);
		}, 900);

		setTimeout(() => дать(null), 45000);
	});
}

if (адресАдминки) {
	скажи(`   уже работала на ${адресАдминки} — беру её, вторую не поднимаю`);
} else {
	адресАдминки = await поднятьАдминку();
	подняли = true;
	if (!адресАдминки) {
		скажи('\n✗ Сервер админки не назвал адреса за 45 секунд.');
		скажи('\nЧТО ДЕЛАТЬ: позовите Claude Code и скажите «админка не поднимается».\n');
		process.exit(1);
	}
	скажи(`   поднялась на ${адресАдминки}`);
}

