#!/usr/bin/env node
// АДМИНКА НА МАШИНЕ ЗАКАЗЧИКА ПЛЮС КНОПКА «ВЫЛОЖИТЬ» (задача 26).
//
// Запускается двойным щелчком по «Открыть-админку.command» в корне проекта.
//
// ЧТО ДЕЛАЕТ: поднимает сервер админки, поднимает рядом свой маленький сервер
// со страничкой-кнопкой и открывает в браузере оба адреса. Дальше живёт: пока
// открыто окно — работают админка и кнопка. Закрыли окно — обе выключились.
//
// ── ПОЧЕМУ КНОПКА НЕ ВНУТРИ АДМИНКИ ────────────────────────────────────────
// Свои компоненты Sveltia в этом проекте дважды теряли данные и один раз
// ломали вставку текста из соцсетей. Решение заказчика: своих компонентов
// не делать. Поэтому кнопка живёт на ОТДЕЛЬНОЙ страничке рядом — ровно как
// `/admin/tools/` сделана рядом с админкой на сайте.
//
// ── ПОЧЕМУ СТРАНИЧКА НЕ В `public/` ────────────────────────────────────────
// Всё, что лежит в `public/`, уезжает в сборку и на сайт. Кнопка, которая
// собирает и выкладывает сайт, на самом сайте не нужна никому и никогда.
// Поэтому она лежит в `scripts/local-admin/` — оттуда в сборку не попадает
// ничто, физически: Astro эту папку не читает.
//
// ── АДРЕС АДМИНКИ БЕРЁТСЯ У СЕРВЕРА, А ПОТОМ ПРОВЕРЯЕТСЯ ЗАПРОСОМ ──────────
// Astro занимает 4321, а если тот занят — следующий свободный; кроме того,
// он умеет отвечать «сервер уже работает вон там» и молча выходить. Первая
// написанная здесь развилка приняла это сообщение за свой успех и объявила
// поднятой админку, которой не поднимала. Поэтому теперь два шага: сначала
// спрашиваем адрес, потом СТУЧИМСЯ ПО НЕМУ и убеждаемся, что отвечает наша
// админка. Сообщение — не факт.
//
// ── АДРЕС ИМЕННО `/admin/index.html` ───────────────────────────────────────
// Замер 25.08.2026: `/admin/` в режиме разработки отдаёт 404, а
// `/admin/index.html` — 200. Astro не достраивает имя файла к папке из
// `public/`. Открыв «красивый» адрес, мы показали бы человеку страницу
// «не найдено» вместо админки.
//
// ── ВТОРОЙ ЩЕЛЧОК НЕ ПОДНИМАЕТ ВТОРУЮ АДМИНКУ ──────────────────────────────
// Сначала обходим свои порты: не отвечает ли там уже наш сервер кнопки. Жив —
// просто открываем окна браузера и уходим. Иначе админок стало бы две,
// и заказчик правил бы в одной, а смотрел другую.
//
// ── СБОРКУ ЗАПУСКАЕМ, НЕ ОСТАНАВЛИВАЯ АДМИНКУ ──────────────────────────────
// Опасение было: `astro dev` и `astro build` лезут в одну служебную папку.
// Замер 25.08.2026: четыре полные сборки подряд при живом `astro dev` — все
// четыре прошли. Останавливать нечего.

import { createServer } from 'node:http';
import { spawn, execFile, execFileSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const СТРАНИЦА = join(ROOT, 'scripts', 'local-admin', 'page.html');
const ЗАПУСКАТОР = join(ROOT, 'scripts', 'launch-deploy.mjs');
const ASTRO = join(ROOT, 'node_modules', '.bin', 'astro');
const ПУТЬ_АДМИНКИ = '/admin/index.html';

// Порт кнопки не один, а диапазон: 4399 у этой машины уже занят чужим
// сервером, и заученное число посадило бы нас поверх него.
const ПОРТЫ_КНОПКИ = [4399, 4400, 4401, 4402, 4403, 4404, 4405];

const скажи = (текст = '') => console.log(текст);
const открыть = (адрес) => execFile('/usr/bin/open', [адрес], () => {});
const подожди = (мс) => new Promise((готово) => setTimeout(готово, мс));

// Знак «сбежать» пишется именной записью: литерал в исходнике невидим,
// и правящий эту строку сотрёт его, не заметив.
const безЦвета = (текст) => текст.replace(/\u001b\[[0-9;]*m/g, '');
const АДРЕС_В_ВЫВОДЕ = /https?:\/\/(?:localhost|127\.0\.0\.1):(\d+)/;

const адресИз = (текст) => {
	const найдено = безЦвета(текст).match(АДРЕС_В_ВЫВОДЕ);
	return найдено ? `http://localhost:${найдено[1]}` : null;
};

// ═══ 1. МЫ УЖЕ ЗАПУЩЕНЫ? ═══════════════════════════════════════════════════
async function ктоНаПорту(порт) {
	try {
		const ответ = await fetch(`http://127.0.0.1:${порт}/alive`, { signal: AbortSignal.timeout(700) });
		const данные = await ответ.json();
		return данные?.наш === true ? { чей: 'наш', данные } : { чей: 'чужой' };
	} catch (сбой) {
		// Отказ в соединении — порт свободен. Всё прочее (ответил, но не тем)
		// значит «там кто-то есть», и садиться туда нельзя.
		return { чей: сбой?.cause?.code === 'ECONNREFUSED' ? 'никого' : 'чужой' };
	}
}

for (const порт of ПОРТЫ_КНОПКИ) {
	const кто = await ктоНаПорту(порт);
	if (кто.чей !== 'наш') continue;
	скажи('\n=== АДМИНКА УЖЕ РАБОТАЕТ ===\n');
	скажи('Второй сервер поднимать не стал — открываю окна той, что уже запущена.');
	скажи(`   админка: ${кто.данные.admin}`);
	скажи(`   кнопка:  http://127.0.0.1:${порт}/`);
	открыть(кто.данные.admin);
	await подожди(700);
	открыть(`http://127.0.0.1:${порт}/`);
	скажи('\nЭто окно можно закрыть — админка живёт в другом.');
	await подожди(500);
	process.exit(0);
}

// ═══ 2. ПОДНИМАЕМ АДМИНКУ ══════════════════════════════════════════════════
скажи('');
скажи('═══════════════════════════════════════════════════════════════');
скажи('   ЛОКАЛЬНАЯ АДМИНКА');
скажи('═══════════════════════════════════════════════════════════════');

if (!existsSync(СТРАНИЦА)) {
	скажи(`\n✗ Пропала страничка с кнопкой: ${СТРАНИЦА}`);
	скажи('\nЧТО ДЕЛАТЬ: позовите Claude Code и скажите «пропала страничка с кнопкой».\n');
	process.exit(1);
}

const спроси = (доводы) => {
	try {
		return execFileSync(ASTRO, доводы, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
	} catch (сбой) {
		return `${сбой.stdout || ''}${сбой.stderr || ''}`;
	}
};

скажи('\n── Поднимаю сервер админки');

// Сервер админки у этой версии Astro живёт отдельно от нас и переживает выход:
// поэтому сначала спрашиваем, не запущен ли он, и только потом запускаем.
//
// АДРЕС СПРАШИВАЕТСЯ У ОДНОГО И ТОГО ЖЕ МЕСТА — у `astro dev status`. Команда
// запуска печатает его тоже, но по-разному: с ключом `--silent` она молчит
// вовсе (замерено), и разбор её вывода дал бы «адреса не назвал» на успешно
// поднятой админке. Один источник ответа надёжнее двух похожих.
let подняли = false;
let адресАдминки = адресИз(спроси(['dev', 'status']));

if (адресАдминки) {
	скажи(`   уже работала на ${адресАдминки} — беру её, вторую не поднимаю`);
} else {
	спроси(['dev']);
	подняли = true;
	// Команда возвращает управление сразу, а сервер поднимается ещё пару
	// секунд: спрашиваем адрес, пока не ответит.
	for (let попытка = 1; попытка <= 15 && !адресАдминки; попытка++) {
		await подожди(700);
		адресАдминки = адресИз(спроси(['dev', 'status']));
	}
	if (!адресАдминки) {
		скажи('\n✗ Сервер админки не поднялся за десять секунд.');
		скажи('\nЧТО ДЕЛАТЬ: позовите Claude Code и скажите «админка не поднимается».\n');
		process.exit(1);
	}
	скажи(`   поднялась на ${адресАдминки}`);
}

// ПРОВЕРКА ПО ФАКТУ. Сообщение сервера — ещё не работающая админка: первая
// версия этого файла объявила поднятым то, что упало. Стучимся и смотрим код
// ответа, а заодно — что отвечает именно наша админка, а не чужой сервер,
// случайно занявший тот же порт.
async function админкаОтвечает() {
	for (let попытка = 1; попытка <= 12; попытка++) {
		try {
			const ответ = await fetch(`${адресАдминки}${ПУТЬ_АДМИНКИ}`, { signal: AbortSignal.timeout(2000) });
			if (ответ.ok) {
				const текст = await ответ.text();
				if (текст.includes('Бака')) return true;
			}
		} catch { /* ещё не проснулась */ }
		await подожди(800);
	}
	return false;
}

if (!(await админкаОтвечает())) {
	скажи(`\n✗ Админка не отвечает по адресу ${адресАдминки}${ПУТЬ_АДМИНКИ}`);
	скажи('   Сервер сказал, что поднялся, но на запрос не ответил.');
	скажи('\nЧТО ДЕЛАТЬ: позовите Claude Code и скажите «админка не отвечает».\n');
	process.exit(1);
}
скажи('   проверил запросом: отвечает, это наша админка');

// ═══ 3. СЕРВЕР КНОПКИ ══════════════════════════════════════════════════════
const состояние = {
	идёт: false, шаг: '', строки: [],
	завершено: false, удача: false, заголовок: '', текст: '',
};

const очистить = (строки) => строки.map((с) => с.replace(/[═╭╮╰╯│─]/g, '').trim());

function разобратьИтог(код) {
	const строки = состояние.строки;
	const чистые = очистить(строки);
	состояние.удача = код === 0;

	if (код === 0) {
		const ничего = строки.findIndex((с) => с.includes('ВСЁ УЖЕ НА САЙТЕ'));
		if (ничего >= 0) {
			состояние.заголовок = 'Выкладывать было нечего';
			состояние.текст = чистые.slice(ничего + 1).filter(Boolean).join('\n');
			return;
		}
		const готово = строки.findIndex((с) => с.includes('САЙТ ОБНОВЛЁН НА ОБОИХ АДРЕСАХ'));
		состояние.заголовок = 'Готово. Сайт обновлён на обоих адресах';
		состояние.текст = (готово >= 0 ? чистые.slice(готово + 1) : чистые.slice(-8)).filter(Boolean).join('\n');
		return;
	}

	// Беда. Запускатор печатает её сам, человеческим языком, вместе с разделом
	// «ЧТО ДЕЛАТЬ»; наше дело — вынести это на страницу, а не пересказывать
	// своими словами. Второй копии объяснений быть не должно.
	const место = строки.findIndex((с) => с.trim().startsWith('✗'));
	if (место >= 0) {
		состояние.заголовок = чистые[место].replace(/^✗\s*/, '') || 'Не выложено';
		состояние.текст = чистые.slice(место + 1).filter(Boolean).join('\n');
	} else {
		состояние.заголовок = 'Не выложено';
		состояние.текст = чистые.filter(Boolean).slice(-12).join('\n');
	}
}

function выложить() {
	состояние.идёт = true;
	состояние.завершено = false;
	состояние.строки = [];
	состояние.шаг = 'Начинаю';

	const прогон = spawn(process.execPath, [ЗАПУСКАТОР], {
		cwd: ROOT, env: process.env, stdio: ['ignore', 'pipe', 'pipe'],
	});

	let хвост = '';
	const принять = (кусок) => {
		хвост += кусок.toString('utf8');
		const строки = хвост.split('\n');
		хвост = строки.pop();
		for (const строка of строки) {
			состояние.строки.push(строка);
			const шаг = строка.match(/^\s*──\s*(?:\d+\.\s*)?(.+?)\s*$/);
			if (шаг && шаг[1]) состояние.шаг = шаг[1];
		}
	};
	прогон.stdout.on('data', принять);
	прогон.stderr.on('data', принять);

	прогон.on('close', (код) => {
		if (хвост) состояние.строки.push(хвост);
		// КОД ВОЗВРАТА У ПРОЦЕССА, А НЕ ПО ВЫВОДУ. Оболочка отвечает «0» и там,
		// где node упал; здесь спрашивается сам процесс.
		разобратьИтог(код);
		состояние.идёт = false;
		состояние.завершено = true;
		состояние.шаг = '';
		скажи(`\n   кнопка: выкладка завершена, код возврата ${код}\n`);
	});
}

const кнопка = createServer((запрос, ответ) => {
	const путь = (запрос.url || '/').split('?')[0];
	const отдай = (код, тип, тело) => {
		ответ.writeHead(код, { 'Content-Type': тип, 'Cache-Control': 'no-store' });
		ответ.end(тело);
	};

	if (путь === '/alive') return отдай(200, 'application/json; charset=utf-8',
		JSON.stringify({ наш: true, admin: `${адресАдминки}${ПУТЬ_АДМИНКИ}` }));

	if (путь === '/state') return отдай(200, 'application/json; charset=utf-8', JSON.stringify({
		running: состояние.идёт, step: состояние.шаг, lines: состояние.строки,
		finished: состояние.завершено, ok: состояние.удача,
		title: состояние.заголовок, text: состояние.текст,
	}));

	if (путь === '/deploy') {
		if (запрос.method !== 'POST') return отдай(405, 'text/plain; charset=utf-8', 'только POST');
		// Второе нажатие, пока идёт первое, отклоняем. Два запускателя разом
		// подрались бы за репозиторий и за сборку.
		if (состояние.идёт) return отдай(409, 'text/plain; charset=utf-8', 'уже идёт');
		выложить();
		return отдай(202, 'text/plain; charset=utf-8', 'пошёл');
	}

	if (путь === '/' || путь === '/index.html') {
		// Читаем файл на каждый запрос: правку страницы видно обновлением
		// вкладки, без перезапуска сервера.
		return отдай(200, 'text/html; charset=utf-8', readFileSync(СТРАНИЦА));
	}

	отдай(404, 'text/plain; charset=utf-8', 'нет такой страницы');
});

// Только 127.0.0.1: наружу эта кнопка не смотрит ни одним боком.
async function поднятьКнопку() {
	for (const порт of ПОРТЫ_КНОПКИ) {
		if ((await ктоНаПорту(порт)).чей !== 'никого') continue;
		const вышло = await new Promise((готово) => {
			кнопка.once('error', () => готово(false));
			кнопка.listen(порт, '127.0.0.1', () => готово(true));
		});
		if (вышло) return порт;
	}
	return null;
}

const портКнопки = await поднятьКнопку();
if (!портКнопки) {
	скажи(`\n✗ Не нашёл свободного порта для странички с кнопкой (пробовал ${ПОРТЫ_КНОПКИ.join(', ')}).`);
	скажи('\nЧТО ДЕЛАТЬ: позовите Claude Code и скажите «нет свободного порта для кнопки».\n');
	убратьЗаСобой(1);
}

const АДРЕС_КНОПКИ = `http://127.0.0.1:${портКнопки}/`;
скажи('── Поднимаю страничку с кнопкой «Выложить»');
скажи(`   ${АДРЕС_КНОПКИ}`);

скажи('\n── Открываю окна браузера');
открыть(`${адресАдминки}${ПУТЬ_АДМИНКИ}`);
await подожди(900);
открыть(АДРЕС_КНОПКИ);

скажи('');
скажи('═══════════════════════════════════════════════════════════════');
скажи('   ВСЁ ГОТОВО. ПРАВЬТЕ В АДМИНКЕ.');
скажи('═══════════════════════════════════════════════════════════════');
скажи('');
скажи(`   Админка:  ${адресАдминки}${ПУТЬ_АДМИНКИ}`);
скажи(`   Кнопка:   ${АДРЕС_КНОПКИ}`);
скажи('');
скажи('   Поправили и сохранили — нажмите на второй вкладке');
скажи('   большую кнопку «ВЫЛОЖИТЬ НА САЙТ».');
скажи('');
скажи('   ЗАКРЫТЬ: просто закройте это окно (или нажмите Ctrl+C).');
скажи('   Вместе с ним выключится и админка, и кнопка. Это нормально:');
скажи('   сайт от этого не страдает, он живёт в интернете сам по себе.');
скажи('');

// ═══ 4. ЗАКРЫТИЕ ═══════════════════════════════════════════════════════════
// Сервер админки у этой версии Astro — отдельный житель: он переживает нас
// и нашим ребёнком не является, поэтому «убить процесс» его не берёт. Гасится
// он своей же командой. Не погасить — значит оставить занятым порт 4321:
// следующий запуск возьмёт 4322, и правки будут видны не там, где смотришь.
let уходим = false;
function убратьЗаСобой(код = 0) {
	if (уходим) return;
	уходим = true;
	if (подняли) {
		скажи('\n── Выключаю админку');
		спроси(['dev', 'stop']);
		скажи('   выключена');
	}
	setTimeout(() => process.exit(код), 200);
}
for (const знак of ['SIGINT', 'SIGTERM', 'SIGHUP']) process.on(знак, () => убратьЗаСобой(0));
