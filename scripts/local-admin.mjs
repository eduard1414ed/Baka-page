	открыть(кто.данные.admin);
	await подожди(700);
	открыть(`http://127.0.0.1:${порт}/`);
	// ЧУЖОЕ ЗДЕСЬ НЕ ЗАБИРАЕМ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ. Админка уже работает,
	// значит вкладка с постом может быть открыта — а она держит СВОЮ копию
