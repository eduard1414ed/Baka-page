// ДОБОР ОДНОГО ПОЛЯ В КАРТОЧКИ ТАЙТЛОВ — ОБЩАЯ МАШИНЕРИЯ.
//
// Выросло из scripts/anime-franchise.mjs, когда за тем же ответом Shikimori
// пришли второй раз — за типом произведения (`kind`, задача 32). Второй
// скрипт-близнец на 168 строк разошёлся бы с первым молча: пауза между
// запросами, разбор сетевого сбоя, отступ файла и порядок ключей — правила,
// которые нельзя чинить в одном месте и забыть в другом.
//
// Здесь живёт всё, что у обоих одинаково. Скрипту остаётся сказать три вещи:
// как называется поле, как прочитать его из ответа и после какого ключа
// поставить.

import { readdir, readFile, writeFile } from 'node:fs/promises';

export const ПАПКА = new URL('../src/content/anime/', import.meta.url);
export const USER_AGENT = 'BakaPodcastSite/1.0 (+https://github.com/eduard1414ed/Baka-page)';

/**
 * Пауза между запросами.
 *
 * У проекта записано 1500 мс (`SHIKIMORI_PAUSE_MS` в anime-lib.mjs), но замер
 * 30 августа 2026 показал, что этого мало: прогон по 15 тайтлам с паузой
 * 1200 мс дал 13 отказов из 15, и выглядело это как «поля franchise
 * не существует». Сломан был измеритель, а не измеряемое. Берём 2000.
 */
export const ПАУЗА = 2000;

export const спать = (мс) => new Promise((r) => setTimeout(r, мс));

/**
 * Сетевой ли сбой.
 *
 * ПОВТОРЯТЬ НАДО ТОЛЬКО СЕТЕВОЕ: «тайтла с таким номером нет» повтором
 * не лечится, а три захода с паузами превращают честный отказ в минуту
 * молчания. `fetch` заворачивает всё, что случилось под ним, в `cause`.
 */
export const сетевая = (e) =>
	Boolean(e?.cause) || /network|fetch failed|socket|ECONN|ETIMEDOUT|EAI_AGAIN/i.test(e?.message ?? '');

/**
 * Карточка тайтла у Shikimori. Один ответ — все поля, которые нам от него
 * бывают нужны; какое из них взять, решает вызывающий.
 */
export async function спроситьShikimori(sourceId) {
	for (let попытка = 1; ; попытка++) {
		try {
			const ответ = await fetch(`https://shikimori.io/api/animes/${sourceId}`, {
				headers: { 'User-Agent': USER_AGENT },
				signal: AbortSignal.timeout(20000),
			});
			if (ответ.status === 429 || ответ.status >= 500) {
				// Слишком часто спрашиваем или сервер прилёг — это сетевое,
				// повторяем с растущей паузой.
				throw Object.assign(new Error(`ответ ${ответ.status}`), { cause: 'частота' });
			}
			if (!ответ.ok) return { беда: `ответ ${ответ.status}` };
			return { данные: await ответ.json() };
		} catch (e) {
			if (попытка >= 3 || !сетевая(e)) return { беда: e.message };
			await спать(ПАУЗА * попытка * 2);
		}
	}
}

/**
 * Каким отступом набран файл.
 *
 * В репозитории живут ДВА формата, и это не беспорядок: робот
 * (`writeAnimeEntry`) пишет табом, а админка Sveltia — двумя пробелами.
 * То есть пробелами набраны ровно те карточки, которые заказчик правил
 * руками, — 37 штук на 30 августа 2026.
 *
 * Приводить их к своему виду нельзя: диффа получается на весь файл, тронуты
 * оказываются именно правленные человеком карточки, а первое же сохранение
 * в админке вернёт пробелы обратно. Дописывая одно поле, отступ надо взять
 * у самого файла.
 */
export function отступФайла(текст) {
	const m = текст.match(/\n(\t| +)"/);
	return m ? m[1] : '\t';
}

/** Вставить ключ после названного, сохранив порядок остальных. */
export function сПолем(карточка, имяПоля, значение, послеКлюча) {
	const готово = {};
	let вставлено = false;
	for (const [k, v] of Object.entries(карточка)) {
		if (k === имяПоля) continue; // старое значение выкидываем, поставим на своё место
		готово[k] = v;
		if (k === послеКлюча) {
			готово[имяПоля] = значение;
			вставлено = true;
		}
	}
	// У трёх карточек архива нет `url` — им поле уходит в конец, но уходит.
	if (!вставлено) готово[имяПоля] = значение;
	return готово;
}

/**
 * Прогон: обойти карточки, спросить источник, дописать поле.
 *
 * @param {object} что
 * @param {string} что.имяПоля       Как ключ называется в файле карточки.
 * @param {(данные: object) => any} что.прочитать  Что взять из ответа Shikimori.
 * @param {string} что.послеКлюча    После какого ключа поставить.
 * @param {(значение: any) => string} что.назвать  Как показать значение в логе.
 * @param {(значение: any) => string} [что.считать] Ключ для сводки «чего сколько».
 * @param {string[]} что.арг         process.argv.slice(2).
 * @returns {Promise<number>} Код возврата.
 */
export async function доборПоля({ имяПоля, прочитать, послеКлюча, назвать, считать, арг }) {
	const обновить = арг.includes('--обновить');
	const сколькоАрг = арг.find((a) => a.startsWith('--сколько='));
	const предел = сколькоАрг ? Number(сколькоАрг.split('=')[1]) : Infinity;

	const файлы = (await readdir(ПАПКА)).filter((f) => f.endsWith('.json')).sort();
	let взято = 0;
	let пропущено = 0;
	const сводка = {};
	const беды = [];

	for (const файл of файлы) {
		if (взято >= предел) break;
		const путь = new URL(файл, ПАПКА);
		const сырое = await readFile(путь, 'utf8');
		const карточка = JSON.parse(сырое);
		const отступ = отступФайла(сырое);

		if (карточка.source !== 'shikimori') {
			пропущено++;
			continue;
		}
		if (!обновить && имяПоля in карточка) {
			пропущено++;
			continue;
		}

		const { данные, беда } = await спроситьShikimori(карточка.sourceId);
		if (беда) {
			беды.push(`${карточка.id}: ${беда}`);
			console.log(`✗ ${карточка.id} — ${беда}`);
		} else {
			const значение = прочитать(данные);
			await writeFile(путь, JSON.stringify(сПолем(карточка, имяПоля, значение, послеКлюча), null, отступ) + '\n', 'utf8');
			взято++;
			const ключ = считать ? считать(значение) : назвать(значение);
			сводка[ключ] = (сводка[ключ] ?? 0) + 1;
			console.log(`  ${карточка.id} → ${назвать(значение)}`);
		}
		await спать(ПАУЗА);
	}

	console.log('');
	console.log(`Записано карточек: ${взято}.`);
	for (const [ключ, сколько] of Object.entries(сводка).sort((a, b) => b[1] - a[1])) {
		console.log(`   ${String(сколько).padStart(4)}  ${ключ}`);
	}
	console.log(`Пропущено (поле уже есть либо не Shikimori): ${пропущено}.`);
	if (беды.length > 0) {
		console.log(`Не ответили: ${беды.length}. Прогнать скрипт ещё раз — он возьмётся только за них.`);
		for (const б of беды.slice(0, 20)) console.log('   ' + б);
	}
	// ПРОГОН, У КОТОРОГО ОТВАЛИЛСЯ ИСТОЧНИК, ОБЯЗАН КРИЧАТЬ. Ноль записанных
	// при непустой очереди — это не «всё уже сделано», это «сеть молчит».
	if (взято === 0 && беды.length > 0) {
		console.error('✗ Не записано НИ ОДНОЙ карточки, а отказов ' + беды.length + ' — источник не отвечает.');
		return 1;
	}
	return 0;
}
