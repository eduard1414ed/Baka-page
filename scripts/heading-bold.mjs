// ЖИРНЫЙ ВНУТРИ ЗАГОЛОВКА — ОДНО ПРАВИЛО НА ПРОЕКТ.
//
// РЕШЕНИЕ ЗАКАЗЧИКА 12 АВГУСТА 2026: жирного внутри заголовка не бывает.
// Повод был живой: в «Пара слов о режиссёре Тацуюки Нагаи» первый заголовок
// чистый, а следующие три жирные — в ОДНОМ посте две формы разом.
//
// ГДЕ ДЕЙСТВУЕТ: ВЕЗДЕ, включая заголовок внутри цитаты, спойлера и пункта
// списка. Решение заказчика 15 августа 2026. До него ответов было два:
// `archive-headings.mjs` смотрел только верхний уровень дерева и заголовок
// в цитате не трогал (и у него на это стоял подлог), а `archive-subheads.mjs`
// обходил дерево целиком и трогал (доревизия задачи 15, находка 36). Одно
// правило — один ответ; какой скрипт запустили, значения иметь не должно.
//
// РАЗБОР ТОТ ЖЕ, ЧТО У СБОРКИ, И РЕЖЕМ ПО СМЕЩЕНИЯМ. Звёздочку по строкам
// не ищем: она живёт и в тексте абзаца, и внутри кода, и в адресе. Где
// заголовок и где внутри него жирный — знает дерево. Дерево отвечает только
// на вопрос «где», а режется исходная строка: пересборка дерева переписала бы
// каждый файл по-своему, и правку в этой разнице было бы не найти.
//
// СНИМАЕТСЯ ЛЮБАЯ ЗАПИСЬ ЖИРНОГО. У узла `strong` смещения охватывают ВЕСЬ
// узел вместе с разделителем, а у его детей — только содержимое. Значит
// вырезать надо ровно два зазора: от начала узла до начала первого ребёнка
// и от конца последнего ребёнка до конца узла. Так снимается и `**`, и `__`,
// и любая другая запись, какую поймёт разбор, — длину разделителя мы
// не назначаем, а спрашиваем.

/** Все узлы поддерева. Обход свой: нужны и вложенные `strong`. */
function всеУзлы(узел) {
	const из = [];
	const идти = (n) => {
		из.push(n);
		if (Array.isArray(n.children)) n.children.forEach(идти);
	};
	идти(узел);
	return из;
}

/** Все заголовки дерева, на какой бы глубине они ни лежали. */
function всеЗаголовки(дерево) {
	return всеУзлы(дерево).filter((узел) => узел.type === 'heading');
}

/**
 * Что вырезать из тела, чтобы у заголовков не осталось жирного.
 *
 * @param {object} дерево разбор тела (`parseBody` из archive-clean-lib.mjs)
 * @param {string} тело исходная строка — из неё берутся «было» и «стало»
 * @returns {{ куски: {start:number,end:number}[], заголовки: {было:string, стало:string, уровень:number, start:number, end:number}[] }}
 */
export function планСнятияЖирного(дерево, тело) {
	const куски = [];
	const заголовки = [];

	for (const заголовок of всеЗаголовки(дерево)) {
		const жирные = всеУзлы(заголовок).filter((n) => n.type === 'strong');
		if (!жирные.length) continue;

		const свои = [];
		for (const узел of жирные) {
			const дети = узел.children ?? [];
			if (!дети.length) continue; // `****` без содержимого — не наш случай, не трогаем
			const первый = дети[0].position?.start?.offset;
			const последний = дети[дети.length - 1].position?.end?.offset;
			const начало = узел.position?.start?.offset;
			const конец = узел.position?.end?.offset;
			if ([первый, последний, начало, конец].some((v) => typeof v !== 'number')) continue;
			if (начало < первый) свои.push({ start: начало, end: первый });
			if (последний < конец) свои.push({ start: последний, end: конец });
		}
		if (!свои.length) continue;

		const start = заголовок.position.start.offset;
		const end = заголовок.position.end.offset;
		const было = тело.slice(start, end);
		заголовки.push({
			было,
			стало: вырезать(было, свои.map((c) => ({ start: c.start - start, end: c.end - start }))),
			уровень: заголовок.depth,
			start,
			end,
		});
		куски.push(...свои);
	}

	// Куски идут в порядке обхода дерева; вложенные заголовки могут прийти
	// не по возрастанию смещений, а резать надо слева направо.
	куски.sort((a, b) => a.start - b.start);
	заголовки.sort((a, b) => a.start - b.start);
	return { куски, заголовки };
}

/**
 * Вырезать из строки куски по смещениям.
 *
 * Своя копия `cutRanges` из `archive-clean-lib.mjs` тут была бы лишней, но
 * зависеть от него этому файлу нельзя: его зовёт и проверка сборки, а тот
 * объявлен «разовой чисткой и в механизмы не встраивается». Восемь строк.
 *
 * @param {{ start: number, end: number }[]} куски — не пересекаются
 */
export function вырезать(текст, куски) {
	const по_порядку = [...куски].sort((a, b) => a.start - b.start);
	let из = '';
	let курсор = 0;
	for (const кусок of по_порядку) {
		if (кусок.start < курсор) throw new Error('вырезаемые куски пересекаются — это ошибка в правиле отбора');
		из += текст.slice(курсор, кусок.start);
		курсор = кусок.end;
	}
	return из + текст.slice(курсор);
}

/**
 * Тело без жирного в заголовках — или `null`, если снимать нечего.
 *
 * @returns {null | { тело: string, заголовки: {было:string, стало:string}[] }}
 */
export function телоБезЖирного(дерево, тело) {
	const { куски, заголовки } = планСнятияЖирного(дерево, тело);
	if (!куски.length) return null;
	return { тело: вырезать(тело, куски), заголовки };
}
