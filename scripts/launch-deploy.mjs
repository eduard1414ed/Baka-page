// Прерванный посреди работы git оставляет папку в промежуточном состоянии.
// Работать в нём нельзя: любая правка ляжет непонятно куда.
for (const [папка, беда] of [
	['.git/rebase-merge', 'прошлый заход не доделал совмещение правок'],
	['.git/rebase-apply', 'прошлый заход не доделал совмещение правок'],
	['.git/MERGE_HEAD', 'прошлый заход не доделал слияние'],
]) {
	if (existsSync(join(ROOT, папка))) {
		стоп(`Репозиторий в незавершённом состоянии: ${беда}.`,
			'Сам я это не разберу: там наполовину сведённые правки, и любое моё\nдействие может стереть чью-то работу.',
			'  Позовите Claude Code и скажите: «git застрял в середине совмещения правок».');
	}
}

// ── 1. что поправил заказчик ───────────────────────────────────────────────
шаг(1, 'Смотрю, что вы поправили у себя');
// Ключ -z: без него git экранирует русские пути восьмеричными кодами
// («статус/…» превращается в «\321\201…»), и человеку их не прочесть.
//
// Отдельной функцией, потому что спрашивается это ДВАЖДЫ: в начале — что
// поправил человек, и ещё раз после добора тайтлов — иначе заведённые роботом
// карточки и обложки остались бы незакоммиченными и не уехали бы вместе
// с постом, ради которого их завели.
function собратьСвоиПравки() {
	return гитСырой(['status', '--porcelain', '-z'])
		.split('\0')
		.filter(Boolean)
		.map((строка) => ({ знак: строка.slice(0, 2).trim(), путь: строка.slice(3) }));
}

let своё = собратьСвоиПравки();

if (своё.length === 0) {
	скажи('   правок нет — ни одного изменённого файла');
} else {
	скажи(`   правок: ${своё.length}`);
	for (const п of своё.slice(0, 12)) {
		const пометка = п.знак === 'D' ? ' (удалён)' : п.знак === '??' ? ' (новый)' : '';
		скажи(`     • ${поЧеловечески(п.путь)}${пометка}`);
	}
	if (своё.length > 12) скажи(`     … и ещё ${своё.length - 12}`);
}

// ── 2. что принесли роботы ─────────────────────────────────────────────────
шаг(2, 'Спрашиваю хранилище, что нового принесли роботы');
const забрал = гитМожно(['fetch', '--quiet', 'origin', 'main']);
if (!забрал.ок) {
	стоп('Не смог связаться с хранилищем GitHub.',
		`Интернета нет или GitHub недоступен. Вот что ответил git:\n\n${забрал.вывод.split('\n').slice(0, 6).map((с) => `    ${с}`).join('\n')}`,
		'  Проверьте интернет и запустите ещё раз. Ничего не сломалось:\n  ваши правки на месте, сайт не тронут.');
}

const отстали = Number(git(['rev-list', '--count', 'HEAD..origin/main']));
const впереди = Number(git(['rev-list', '--count', 'origin/main..HEAD']));

if (отстали === 0) {
	скажи('   нового нет, ваша копия свежая');
} else {
	// Считает общий дом (repo-news-lib): ровно тот же счёт нужен ярлыку
	// админки, когда он забирает чужое при запуске.
	const приехало = чтоПриехало(ROOT, 'HEAD', 'origin/main');
	// Требование 2.3: давно не запускали — сказать, сколько и чего, ДО работы.
	if (отстали >= 15) {
		скажи(`   вас долго не было: накопилось ${отстали} чужих изменений`);
	} else {
		скажи(`   новых изменений: ${отстали}`);
	}
	for (const [автор, сколько] of приехало?.поАвторам ?? []) {
		скажи(`     • ${БОТЫ[автор] || автор}: ${сколько}`);
	}
	const посты = (приехало?.файлы ?? []).filter((ф) => ф.startsWith('src/content/posts/'));
	if (посты.length) скажи(`     затронуто постов: ${посты.length}`);
}

// ── 3. тайтлы, помеченные в текстах, но ещё не заведённые ──────────────────
//
// ЗАЧЕМ ЭТО ЗДЕСЬ. Пометили в редакторе кнопкой «Аниме» тайтл, которого нет
// в справочнике, — сборка не упадёт (замерено), но название останется обычным
// текстом: ни ссылки, ни плашки под постом, ни страницы тайтла. Появится всё
// это только после прохода робота добора, а он опрашивает репозиторий раз
// в пять минут. То есть без этого шага заказчик выложил бы пост и увидел
// на сайте не то, что размечал.
//
// ПОЧЕМУ ЗОВЁМ РОБОТА ВСЕГДА, А НЕ «ЕСЛИ НАДО». Решение «надо ли» — это
// правило «какие метки в текстах против того, что есть в справочнике»,
// и живёт оно ВНУТРИ самого робота. Спросить его — 0,4 секунды, ни одного
// обращения в сеть и ни одной записи на диск, когда добирать нечего
// (замер 25.08.2026). Своя копия того же правила здесь разошлась бы
// с оригиналом при первой же его правке.
//
// ДО ЗАПИСИ ПРАВОК, А НЕ ПОСЛЕ: заведённые карточки и обложки должны уехать
// в хранилище тем же коммитом, что и пост, ради которого их завели.
шаг(3, 'Проверяю, всё ли заведено: тайтлы и данные о роликах');
const доборТайтлов = гитМожноЗапустить(process.execPath, [join(ROOT, 'scripts', 'sync-anime.mjs')]);
const заведено = (доборТайтлов.вывод.match(/^\s*сохранено: src\/content\/anime\/(.+)\.json$/gm) || [])
	.map((строка) => строка.replace(/^\s*сохранено: src\/content\/anime\//, '').replace(/\.json$/, ''));

if (!доборТайтлов.ок) {
	// НЕ РОНЯЕМ ВЫКЛАДКУ. Не добрался до справочника аниме — это досадно,
	// но пост всё равно надо выложить: без карточки он выйдет с названием
	// обычным текстом, а не сломанным. Молчать при этом нельзя.
	скажи('   ⚠ не смог сходить за карточками тайтлов (нет интернета или источник молчит)');
	скажи('     Выкладываю дальше. Если вы размечали новый тайтл — ссылки на него');
	скажи('     пока не будет; её доделает робот на сервере в течение пяти минут.');
} else if (заведено.length > 0) {
	скажи(`   завёл новых карточек: ${заведено.length}`);
	for (const id of заведено.slice(0, 10)) скажи(`     • ${поЧеловечески(`src/content/anime/${id}.json`)}`);
	// Карточки и обложки только что появились на диске — пересматриваем,
	// что теперь предстоит записать, иначе они остались бы незакоммиченными.
	своё = собратьСвоиПравки();
} else {
	скажи('   все размеченные тайтлы уже заведены');
}

// ── 3б. данные о роликах, встроенных в тексты ──────────────────────────────
//
// ЗАЧЕМ ЭТО ЗДЕСЬ, РЯДОМ С ТАЙТЛАМИ. Разметке ролика обязательны название
// и дата выхода, а в тексте поста их нет — только адрес. Без них Google
// не пускает страницу в выдачу вовсе («отсутствует поле name, отсутствует
// поле uploadDate», письмо Search Console от 13 сентября 2026), и объект
// разметки поэтому не выводится совсем. То есть выложить пост с новым роликом
// и не спросить про него у YouTube — значит выложить страницу, у которой
// ролика для поисковика нет.
