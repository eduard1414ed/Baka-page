// 11 августа 2026 появился третий пользователь из совсем другой области —
// заливка сайта на зеркало (`mirror-sync.mjs`), — и библиотека аниме перестала
// быть подходящим домом: тянуть ради двух функций `sharp` и словари морфологии
// незачем. `anime-lib.mjs` теперь берёт их отсюда и отдаёт дальше своим
// читателям, поэтому прежние импорты работают как работали.

export function sleep(ms) {
	return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * СРОК ОДНОГО ПОХОДА В ЧУЖОЙ СЕРВИС — ОДНО ЧИСЛО НА ПРОЕКТ.
 *
 * ЗАЧЕМ. Без срока Node ждёт молчащее соединение минутами, а робот в это время
 * держит очередь: у всех воркфлоу стоит `cancel-in-progress: false`, поэтому
 * следующий заход по расписанию встаёт и ждёт. Один зависший чужой сервер
 * останавливал робота на сутки, а выглядело это как «робот перестал ходить»
 * (ревизия задачи 15, находка 5). Предел GitHub по умолчанию — шесть часов.
 *
 * ПОЧЕМУ 30 СЕКУНД, А НЕ «НА ГЛАЗ». Замер 15 августа 2026, по три захода
 * к каждому сервису:
 *
 *   лента подкаста (Mave, 924 КБ)   0,56…0,61 с
 *   Shikimori, карточка тайтла       0,25…0,61 с
 *   api.dtf.ru, статья               0,55…0,71 с
 *
 * Худшее измеренное — 0,72 секунды. Тридцать это сорокакратный запас: срок
 * не сработает ни на медленной сети, ни на тяжёлом ответе, а сработает только
 * на настоящем зависании. Самый крупный файл, который проект качает и льёт,
 * меньше мегабайта (в собранном сайте файлов тяжелее 1 МБ нет вовсе), поэтому
 * второго числа «для загрузок» тут не нужно.
 *
 * СРОК И ПОВТОР ЖИВУТ РЯДОМ НАРОЧНО. Оборванный по сроку запрос кидает ошибку
 * со словом `timeout` — а оно есть в списке сетевого ниже, значит `сПовторами`
 * такой поход ПЕРЕЖИВЁТ и сходит заново. Разъедься эти два правила по разным
 * файлам — и однажды сроком начнут обрывать то, что повтор считает честным
 * отказом.
 */
export const ТАЙМАУТ = 30_000;

/**
 * Настройки `fetch` со сроком.
 *
 * Пишется у КАЖДОГО похода: `fetch(адрес, сроком({ headers }))`. Свой `signal`
 * вызывающего не перебиваем — у него может быть своя причина оборвать поход.
 *
 * @param {RequestInit} [опции]
 * @returns {RequestInit}
 */
export function сроком(опции = {}) {
	return { ...опции, signal: опции.signal ?? AbortSignal.timeout(ТАЙМАУТ) };
}

/**
 * ПОХОД В ЧУЖОЙ СЕРВИС ОБЯЗАН ПЕРЕЖИВАТЬ ОДИН СБОЙ.
 *
 * Наступили дважды за один день. 11 августа утром сбор кандидатов упал на 450-й
 * фразе из 1980 с «Connect Timeout Error». Тем же вечером `fetch failed` убил
 * заведение «Человека-бензопилы» — один тайтл из четырёх, и поход заказчика
 * закончился красной строчкой на экране из-за одной моргнувшей сети.
 *
 * ПОВТОРЯЕМ ТОЛЬКО СЕТЕВОЕ. «Тайтла с таким номером нет» повтором не лечится:
 * три захода с паузами превратили бы честный отказ в минуту молчания. Признак
 * сетевого сбоя — либо `cause` у ошибки (так `fetch` заворачивает всё, что
 * случилось под ним), либо знакомое слово в тексте.
 */
/**
 * 429 ЗДЕСЬ ПОТОМУ ЖЕ, ПОЧЕМУ 502–504: это не отказ по существу, а «сейчас
 * не могу, спроси позже». Своя копия этого правила жила в `dtf/collect-studios.mjs`
 * с отдельной веткой на 429 и своими паузами; когда копии сводили в одно место
 * (доревизия задачи 15, находка 27), ветку надо было либо потерять, либо
 * поднять сюда. Потерять нельзя: AniList отвечает 429 при обычном обходе
 * справочника. Пауза после 429 берётся длиннее — её называет вызывающий.
 */
const СЕТЕВОЕ = /fetch failed|timeout|timed out|ECONN|ENOTFOUND|EAI_AGAIN|socket|network|terminated|429|502|503|504/i;

export const похоженаСбойСети = (error) =>
	Boolean(error?.cause) || СЕТЕВОЕ.test(String(error?.message ?? error));

/**
 * @param {() => Promise<any>} что     — сам поход
 * @param {object} как
 * @param {number[]} как.паузы         — сколько ждать перед каждым следующим заходом
 * @param {string} как.назвать         — как назвать дело в строчке журнала
 * @param {(text: string) => void} [как.сказать] — куда писать; молчать нельзя
 */
export async function сПовторами(что, { паузы, назвать, сказать = console.log }) {
	for (let заход = 0; ; заход++) {
		try {
			return await что();
		} catch (error) {
			if (заход >= паузы.length || !похоженаСбойСети(error)) throw error;
			сказать(`  сеть подвела на «${назвать}» (${error.message}); жду ${паузы[заход] / 1000} с`);
			await sleep(паузы[заход]);
		}
	}
}
