export function sleep(ms) {
	return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * ПОХОД В ЧУЖОЙ СЕРВИС ОБЯЗАН ПЕРЕЖИВАТЬ ОДИН СБОЙ.
 *
 * Наступили дважды за один день. 11 августа утром сбор кандидатов упал на 450-й
 * фразе из 1980 с «Connect Timeout Error». Тем же вечером `fetch failed` убил
 * заведение «Человека-бензопилы» — один тайтл из четырёх, и поход заказчика
 * закончился красной строчкой на экране из-за одной моргнувшей сети.
 *
 * ПОВТОРЯЕМ ТОЛЬКО СЕТЕВОЕ. «Тайтла с таким номером нет» повтором не лечится:
 * три захода с паузами превратили бы честный отказ в минуту молчания. Признак
 * сетевого сбоя — либо `cause` у ошибки (так `fetch` заворачивает всё, что
 * случилось под ним), либо знакомое слово в тексте.
 */
const СЕТЕВОЕ = /fetch failed|timeout|timed out|ECONN|ENOTFOUND|EAI_AGAIN|socket|network|terminated|502|503|504/i;

export const похоженаСбойСети = (error) =>
	Boolean(error?.cause) || СЕТЕВОЕ.test(String(error?.message ?? error));

/**
 * @param {() => Promise<any>} что     — сам поход
 * @param {object} как
 * @param {number[]} как.паузы         — сколько ждать перед каждым следующим заходом
 * @param {string} как.назвать         — как назвать дело в строчке журнала
 * @param {(text: string) => void} [как.сказать] — куда писать; молчать нельзя
 */
export async function сПовторами(что, { паузы, назвать, сказать = console.log }) {
	for (let заход = 0; ; заход++) {
		try {
			return await что();
		} catch (error) {
			if (заход >= паузы.length || !похоженаСбойСети(error)) throw error;
			сказать(`  сеть подвела на «${назвать}» (${error.message}); жду ${паузы[заход] / 1000} с`);
			await sleep(паузы[заход]);
		}
	}
}
