// ОБЩИЙ ДОМ ДЛЯ ДВУХ ПРАВИЛ: «ЧТО ПРИЕХАЛО» И «НЕ ЗАТИРАЮ ЛИ Я ЧУЖОЕ» (задача 29).
//
// Зовут отсюда двое:
//   • scripts/local-admin.mjs — ярлык админки. Забирает чужое ПРИ ЗАПУСКЕ
//     и показывает списком, что привезли роботы, пока заказчика не было.
//   • scripts/launch-deploy.mjs — кнопка «Выложить». Перед записью правок
//     спрашивает, не стирает ли сохранение из админки свежую работу робота.
//
// ПОЧЕМУ ОБЩИЙ ФАЙЛ, А НЕ ДВЕ КОПИИ. Человеческие имена файлов («пост „…“»
// вместо «src/content/posts/ep-153.md») и список ботов нужны обоим. Две копии
// разъехались бы на первой же правке — и разъехались бы МОЛЧА: беда выглядела
// бы как «в одном месте пишет по-человечески, в другом почему-то нет».
//
// ЧЕГО ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО: ни одной команды, меняющей репозиторий.
// Здесь только чтение и счёт. Кто и что двигает — решают вызывающие.

import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

// ── кто из авторов коммитов робот ──────────────────────────────────────────
// Имена те же, что у роботов на сервере (hetzner/run-on-posts.sh). Список
// закрытый нарочно: незнакомый автор — это человек, а работу человека
// проверка «не затираю ли робота» трогать не должна.
export const БОТЫ = {
	'baka-episodes-bot': 'робот выпусков — новые выпуски подкаста и расшифровки',
	'baka-telegram-bot': 'робот телеграма — посты из канала',
	'baka-anime-bot': 'робот аниме — карточки тайтлов и упоминания',
	'baka-tg-photos-bot': 'робот картинок — картинки к постам из телеграма',
};
export const этоРобот = (автор) => Object.hasOwn(БОТЫ, автор);

// ── что из привезённого показывать человеку, а что молчком ─────────────────
// Закладка робота телеграма («докуда я дошёл») переписывается КАЖДЫЙ заход,
// четырежды в сутки, и не читается ни одной страницей сайта (замер 25.08.2026,
// задача 21). Показать её новостью — значит четырежды в день говорить
// «приехало новое» о пустоте, а через неделю заказчик перестанет читать
// и настоящие новости вместе с ней.
//
// СПИСОК ЗАКРЫТЫЙ И КОРОТКИЙ НАРОЧНО. Ошибка здесь стоит непоказанной новости,
// поэтому незнакомый файл считается новостью всегда.
const МОЛЧА = ['src/data/telegramFeed.mjs'];
export const этоНовость = (путь) => !МОЛЧА.includes(путь);

// ── материалы против всего прочего ─────────────────────────────────────────
// Защита от затирания смотрит только на материалы: посты, карточки, картинки,
// расшифровки. Код сайта и документы роботы не пишут, а вкладка админки
// не держит их копий — там затирать нечего.
export const этоМатериал = (путь) =>
	путь.startsWith('src/content/') ||
	путь.startsWith('public/images/') ||
	путь.startsWith('public/episodes/') ||
	путь.startsWith('public/cutout/');

// ── человеческие имена файлов ──────────────────────────────────────────────
// «src/content/posts/ep-153.md» человеку не говорит ничего, «пост „…“» —
// говорит. Заголовок берётся ИЗ САМОГО ФАЙЛА, а не из имени: у выпусков имена
// это сквозные номера, и по ним не узнать даже, о чём выпуск.
//
// Текст файла можно передать вторым доводом — так зовут для файлов, которых
// на диске нет (удалённых) или которые лежат только в другой версии.
export function создатьИменователь(ROOT) {
	const прочесть = (путь, текстСнаружи) => {
		if (typeof текстСнаружи === 'string') return текстСнаружи;
		try {
			return readFileSync(join(ROOT, путь), 'utf8').slice(0, 4000);
		} catch {
			return null;
		}
	};

	const заголовокПоста = (путь, текстСнаружи) => {
		const текст = прочесть(путь, текстСнаружи);
		const строка = текст?.match(/^title:\s*(.+)$/m);
		return строка ? строка[1].trim().replace(/^["']|["']$/g, '') : null;
	};

	const имяТайтла = (путь, текстСнаружи) => {
		const текст = прочесть(путь, текстСнаружи);
		if (!текст) return null;
		try {
			const данные = JSON.parse(текст);
			return данные.titleRu || данные.titleOriginal || null;
		} catch {
			return null;
		}
	};

	return function поЧеловечески(путь, текстСнаружи) {
		if (путь.startsWith('src/content/posts/')) {
			const имя = заголовокПоста(путь, текстСнаружи);
			return имя ? `пост «${имя}»` : `пост (${путь})`;
		}
		if (путь.startsWith('src/content/anime/')) {
			const имя = имяТайтла(путь, текстСнаружи);
			return имя ? `карточка аниме «${имя}»` : `карточка аниме (${путь})`;
		}
		if (путь.startsWith('src/content/transcripts/')) return `расшифровка выпуска (${путь})`;
		if (путь.startsWith('public/cutout/')) return `вырезанный персонаж с обложки (${путь})`;
		if (путь.startsWith('public/episodes/')) return `обложка выпуска (${путь})`;
		if (путь.startsWith('public/images/')) return `картинка (${путь})`;
		if (путь.startsWith('src/data/')) return `служебные данные (${путь})`;
		if (путь.startsWith('src/')) return `код сайта (${путь})`;
		if (путь.startsWith('статус/') || путь.endsWith('.md')) return `документ (${путь})`;
		return путь;
	};
}

// ── разговор с git ─────────────────────────────────────────────────────────
// Через execFileSync со списком доводов, а не строкой в оболочке: в пути
// к проекту русские буквы и пробелы, а в заголовках постов бывают кавычки.
export function создатьГит(ROOT) {
	const гит = (доводы) => execFileSync('git', доводы, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
	return {
		// Обрезанный вывод — для однострочных ответов.
		строка: (доводы) => гит(доводы).trim(),
		// СЫРОЙ, БЕЗ .trim(). У «git status --porcelain» первый знак строки —
		// пробел («изменён, но не записан»), и обрезка съедала его вместе
		// с двумя буквами пути: «src/content/…» превращалось в «rc/content/…».
		// Путь оставался похожим на настоящий, поэтому в глаза не бросалось.
		сырой: гит,
		// Ключ -z обязателен везде, где в ответе пути: без него git пишет
		// русские имена восьмеричными кодами, и человеку их не прочесть.
		можно: (доводы) => {
			try {
				return { ок: true, вывод: гит(доводы).trim() };
			} catch (сбой) {
				const части = [сбой.stdout, сбой.stderr, сбой.message]
					.map((что) => (Buffer.isBuffer(что) ? что.toString('utf8') : что || ''));
				return { ок: false, вывод: части.join('').trim() };
			}
		},
	};
}

// ── ЧТО ПРИЕХАЛО ───────────────────────────────────────────────────────────
// Сводка о чужих коммитах между двумя точками: кто привёз, сколько, и какие
// файлы тронул. Отсюда берут списки и ярлык админки, и кнопка «Выложить».
export function чтоПриехало(ROOT, откуда, куда) {
	const гит = создатьГит(ROOT);
	const записи = гит.можно(['log', '--format=%H%x09%an%x09%s', `${откуда}..${куда}`]);
	if (!записи.ок) return null;

	const коммиты = записи.вывод.split('\n').filter(Boolean).map((строка) => {
		const [сха, автор, ...остальное] = строка.split('\t');
		return { сха, автор, сообщение: остальное.join('\t') };
	});

	// ТРИ ТОЧКИ, А НЕ ДВЕ, И ЭТО НЕ ПРИДИРКА. Две точки сравнивают две вершины
	// напрямую — и в список «что приехало» попадают ФАЙЛЫ, КОТОРЫЕ ПРАВИЛИ МЫ
	// САМИ: у нас они есть, в хранилище их ещё нет, а diff разницы в стороне
	// не различает. Замер 27.08.2026: ярлык сказал «15 файлов» там, где робот
	// привёз 9, — шесть лишних были мои собственные, только что записанные.
	// Три точки считают от точки расхождения, то есть ровно чужую работу.
	const файлы = гит.можно(['diff', '--name-only', '-z', `${откуда}...${куда}`]);
	const списокФайлов = файлы.ок ? файлы.вывод.split('\0').filter(Boolean) : [];

	const поАвторам = new Map();
	for (const коммит of коммиты) поАвторам.set(коммит.автор, (поАвторам.get(коммит.автор) || 0) + 1);

	return {
		коммитов: коммиты.length,
		коммиты,
		поАвторам,
		файлы: списокФайлов,
		// Файлы, о которых стоит рассказывать вслух. Служебная закладка робота
		// телеграма сюда не попадает — см. МОЛЧА выше.
		новости: списокФайлов.filter(этоНовость),
	};
}

// ── НЕ ЗАТИРАЮ ЛИ Я ЧУЖОЕ ──────────────────────────────────────────────────
//
// ЧТО ИМЕННО ЛОВИМ. Открытая вкладка админки держит СВОЮ копию поста в памяти
// и при сохранении пишет её на диск целиком. Если за это время в папку приехала
// правка робота, сохранение возвращает файл к дороботовскому виду — и для git
// это не столкновение, а обычная правка: «человек удалил строчку». Он её
// послушно запишет, отправит и выложит. Ровно так откатился пост ep-102.
//
// Замер 27.08.2026 в песочнице из настоящих репозиториев: git не возражает,
// правка заказчика на месте, правка робота стёрта молча, никто не скажет.
//
// ПОЧЕМУ ПРИЗНАК ИМЕННО «ПРОПАЛИ ВСЕ СТРОКИ РОБОТА», А НЕ «ХОТЬ ОДНА».
// Основная работа заказчика — как раз править свежий черновик, привезённый
// роботом: дописать текст, убрать галочку «черновик», поправить заголовок.
// При этом строки робота меняются ЗАКОННО и постоянно. Проверка «пропала хоть
// одна» краснела бы на каждой нормальной правке — а проверку, которая красная
// всегда, через неделю снимают вместе с пользой. Пропали ВСЕ до единой —
// это уже не правка, это возврат файла к состоянию до прихода робота.
//
// ГРАНИЦА «СВЕЖЕГО» — С ПРОШЛОЙ УДАЧНОЙ ВЫКЛАДКИ. Всё, что приехало после неё,
// вкладка админки могла не видеть. Что было раньше — видела наверняка, и его
// правка законна. Нет отметки (первый запуск, стёрлась) — берём трое суток:
// молчание измерителя не повод не проверять вовсе.
export function затираемоеЧужое({ ROOT, свои, отметкаКоммит }) {
	const гит = создатьГит(ROOT);
	const поЧеловечески = создатьИменователь(ROOT);

	// Отметка годится только та, что и правда лежит в нашей истории: чужой
	// или стёртый коммит превратил бы диапазон в бессмыслицу.
	let откуда = null;
	if (отметкаКоммит) {
		const свой = гит.можно(['merge-base', '--is-ancestor', отметкаКоммит, 'HEAD']);
		if (свой.ок) откуда = отметкаКоммит;
	}

	const подозрительные = свои.filter((п) => (п.знак === 'M' || п.знак === 'D') && этоМатериал(п.путь));
	if (подозрительные.length === 0) return [];

	const находки = [];
	for (const { знак, путь } of подозрительные) {
		const доводы = ['log', '--format=%H%x09%an', '-n', '1'];
		if (откуда) доводы.push(`${откуда}..HEAD`);
		else доводы.push('--since=3.days');
		доводы.push('--', путь);

		const последний = гит.можно(доводы);
		if (!последний.ок || !последний.вывод) continue;
		const [сха, автор] = последний.вывод.split('\n')[0].split('\t');
		if (!этоРобот(автор)) continue;

		// Файл удалён целиком, а робот его на днях трогал — спрашивать надо
		// всегда: снос свежепривезённого материала это не мелкая правка.
		if (знак === 'D') {
			находки.push({
				путь, автор, сха, знак: 'снесён',
				имя: поЧеловечески(путь, версияИзКоммита(ROOT, сха, путь)),
				сколько: null,
				примеры: [],
			});
			continue;
		}

		const добавленные = строкиДобавленные(гит, сха, путь);
		if (добавленные.length === 0) continue; // картинка или перестановка — сравнивать нечего

		let рабочий;
		try {
			рабочий = readFileSync(join(ROOT, путь), 'utf8');
		} catch {
			continue;
		}
		const наМесте = new Set(рабочий.split('\n').map((с) => с.trim()));
		const пропали = добавленные.filter((с) => !наМесте.has(с));

		if (пропали.length === добавленные.length) {
			находки.push({
				путь, автор, сха, знак: 'затёрт',
				имя: поЧеловечески(путь),
				сколько: пропали.length,
				примеры: пропали.slice(0, 3),
			});
		}
	}
	return находки;
}

// Строки, которые этот коммит ДОБАВИЛ в этот файл. Пустые и разделители шапки
// не в счёт: они есть в любом посте и «пропасть» не могут.
function строкиДобавленные(гит, сха, путь) {
	const показ = гит.можно(['show', '--format=', '--unified=0', сха, '--', путь]);
	if (!показ.ок) return [];
	return показ.вывод.split('\n')
		.filter((с) => с.startsWith('+') && !с.startsWith('+++'))
		.map((с) => с.slice(1).trim())
		.filter((с) => с.length > 0 && с !== '---');
}

// Содержимое файла в другой версии. Нужно там, где рассказывают о файле,
// которого на диске ещё (или уже) нет: заголовок поста берётся из текста,
// а не из имени, и без этого «пост „Как жить во время конца света?“»
// превратился бы в «пост (src/content/posts/ep-153.md)».
export function версияИзКоммита(ROOT, сха, путь) {
	const показ = создатьГит(ROOT).можно(['show', `${сха}:${путь}`]);
	return показ.ок ? показ.вывод : undefined;
}
