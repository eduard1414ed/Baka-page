//
// Что сторожим. Падежные формы считаются от «головы» именной группы и того,
// что с ней согласовано. Ошибись в голове — и форма выйдет связной на вид,
// но неправильной: «Мёртвых-мёртвые демоны», «Плачущий убийцы», «Непостижимая
// Ахарэна». В поле она ляжет молча, искать по ней будет нечего, и узнать
// об этом можно только тем, что у тайтла ноль упоминаний, — а ноль упоминаний
// бывает и у честно неупомянутого тайтла. Ровно так и вышло с «Мёртвыми
// демонами»: беда пролежала до тех пор, пока заказчик не открыл видеоэссе.
//
// Три правила, каждое из-за своей поломки на живых данных:
//   1. ОМОНИМ. «Мёртвые» словарь читает и прилагательным, и существительным,
//      оба разбора весом 1.00. Кто победит — решал порядок в словаре.
//   2. ВЫБРОС. Существительное в именительном, не согласованное с набранными
//      определениями, забирало себе голову, а определения выбрасывались.
//   3. ОБЩИЙ РОД. «Убийца» помечен женским (Ms-f), и определение уезжало
//      в женский род вслед за ним.
//   4. ФРАЗА. «Танцуй, танцуй, танцор» — не именная группа, а склонялась
//      середина: «Танцуй, танцуй, танцора». Правило было, но жило только
//      в отчёте: формы помечались подозрительными и всё равно записывались.
//   5. НЕНАДЁЖНЫЙ РАЗБОР. Незнакомому слову словарь отрезает начало и склоняет
//      остаток, теряя отрезанное: «Торадора» → «Доры», «Стимбой» → «Боя».
//      Последнее стоило 66 ложных упоминаний обычного слова «бой».
//   6. ХВОСТ ФРАЗЫ. Причастный оборот справа («Клинок, рассекающий демонов»)
//      и приложение через дефис («Папаши-дружбаны») не склонялись вовсе.
//   7. СЛОВАРНОСТЬ ХВОСТА. Определение справа берётся только словарное: справа
//      почти всегда стоит имя, и догадка делала из «Фумико» — «Фумика».
//
//   node scripts/anime-cases-head.test.mjs
//   node scripts/anime-cases-head.test.mjs --подлог-омоним
//   node scripts/anime-cases-head.test.mjs --подлог-выброс
//   node scripts/anime-cases-head.test.mjs --подлог-род
//   node scripts/anime-cases-head.test.mjs --подлог-фраза
//   node scripts/anime-cases-head.test.mjs --подлог-разбор
//   node scripts/anime-cases-head.test.mjs --подлог-хвост
//   node scripts/anime-cases-head.test.mjs --подлог-словарность
//
// ПОДЛОГ РАЗВОДИТ РОВНО ОДНУ СТРОКУ, а не снимает блок целиком: снятый блок
// вернул бы состояние «правила не было вовсе», а в жизни строку правят или
// вычищают поодиночке. Строка берётся ИЗ САМОГО ФАЙЛА и подменяется в его
// копии — переписать её рядом значило бы завести вторую копию правила,
// которая разойдётся с первой при первой же правке.
//
// И ОБЯЗАТЕЛЬНЫЙ ЗДОРОВЫЙ СЛУЧАЙ. Названия, которые склонялись правильно
// и до починки, обязаны остаться прежними: правка головы легко ломает соседа,
// а «поймал» ничего не значит, пока проверка не промолчала на здоровом.

