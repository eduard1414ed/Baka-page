const ключ = process.argv.find((a) => a.startsWith('--подлог'));
if (ключ && !ПОДЛОГИ[ключ]) {
	console.error(`Не знаю такого подлога: ${ключ}. Есть: ${Object.keys(ПОДЛОГИ).join(', ')}`);
	process.exit(2);
}

let код = 0;
let убрать = false;

try {
	let модуль = ФАЙЛ;

	if (ключ) {
		const исходник = await readFile(ФАЙЛ, 'utf8');
		const [строка, подмена] = ПОДЛОГИ[ключ];
		if (!исходник.includes(строка)) {
			console.error(`✗ ПОДЛОГ НЕ СРАБОТАЛ: строки правила в файле нет.\n   искал: ${строка.trim()}`);
			console.error('   Правило переписали — либо поправьте подлог, либо снимите проверку. Молчать тут нельзя.');
			process.exit(2);
		}
		await writeFile(КОПИЯ, исходник.replace(строка, подмена));
		убрать = true;
		модуль = КОПИЯ;
		console.log(`ПОДЛОГ ${ключ}: одна строка разведена, проверка ОБЯЗАНА покраснеть.\n`);
	}

	const { initMorph, inflectTitle } = await import(модуль.href);
	await initMorph();

	const беды = [];
	for (const случай of ОЖИДАЕМ) {
		const формы = inflectTitle(случай.имя);
		const пропали = случай.обязаны.filter((ф) => !формы.includes(ф));
		const лишние = случай.запрещены.filter((ф) => формы.includes(ф));
		const знак = пропали.length || лишние.length ? '✗' : 'ок';
		console.log(`${знак}  [${случай.правило}] ${случай.имя}`);
		console.log(`      ${формы.join(' | ') || '— форм нет —'}`);
		for (const ф of пропали) console.log(`      ✗ нет обязательной формы: ${ф}`);
		for (const ф of лишние) console.log(`      ✗ есть запрещённая форма: ${ф}`);
		if (пропали.length || лишние.length) беды.push(случай.имя);
	}

	console.log();
	if (беды.length) {
		console.log(`✗ бед: ${беды.length} из ${ОЖИДАЕМ.length} — ${беды.join(', ')}`);
		код = 1;
	} else {
		console.log(`ок  все ${ОЖИДАЕМ.length} названий склоняются как условлено`);
	}

	if (ключ) {
		// На подлоге красное — это УСПЕХ проверки, а зелёное — её провал.
		if (код === 1) {
			console.log('ок  подлог пойман: правило действительно работает.');
			код = 0;
		} else {
			console.log('✗ ПОДЛОГ НЕ ПОЙМАН: правило сняли, а проверка молчит. Она ничего не сторожит.');
			код = 1;
		}
	}
} finally {
	// Выход ставим ПОСЛЕ уборки: process.exit внутри try не выполняет finally,
	// и временный файл остался бы лежать в scripts/ навсегда.
	if (убрать && existsSync(КОПИЯ)) await unlink(КОПИЯ);
}

process.exit(код);
