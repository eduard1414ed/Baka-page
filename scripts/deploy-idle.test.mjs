// ЗАКЛАДКА РОБОТА НЕ БУДИТ СБОРКУ: ВОСПРОИЗВЕДЕНИЕ 25 АВГУСТА.
//
//   node scripts/deploy-idle.test.mjs
//   node scripts/deploy-idle.test.mjs --подлог
//
// ЧТО СЛУЧИЛОСЬ 25 АВГУСТА 2026. В 14:02 UTC робот телеграма сходил в канал,
// новых постов не нашёл — и всё равно сделал коммит 6e8a6dee: он записывает
// себе закладку «докуда дошёл» (`src/data/telegramFeed.mjs`), а в ней стоит
// время захода, и оно новое всегда. Робот выкладки увидел новый коммит и в
// 14:11 честно собрал сайт 336 секунд, получив его байт в байт прежним:
// закладку не читает ни одна страница, её открывает только сам робот телеграма.
// В тишине так было бы четырежды в сутки.
//
// ЧТО ПРОВЕРЯЕТСЯ. Из hetzner/run-deploy.sh вынимается НАСТОЯЩИЙ текст блока
// «нечего выкладывать» — не его пересказ — и гоняется в песочнице из живого
// git-репозитория. Блок обязан пропустить закладку и НЕ пропустить ничего
// больше: пост, картинку, стиль, незнакомый файл. Самый важный случай —
// смешанный коммит: закладка вместе с настоящим постом обязана собираться,
// иначе экономия превращается в невыложенную правку.
//
// ПОЧЕМУ ЭТО НЕ «ВЕЧНОЗЕЛЁНАЯ» ПРОВЕРКА. Ключ `--подлог` возвращает ПРЕЖНЕЕ
// правило — то есть отсутствие блока, как было до 25 августа, — и проверка
// обязана покраснеть: робот пойдёт собирать сайт ради закладки. Не покраснела —
// значит песочница не воспроизводит поломку и её «ок» ничего не значит.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const SCRIPT = join(ROOT, 'hetzner/run-deploy.sh');
const НАЧАЛО = '# ─── начало блока «нечего выкладывать»';
const КОНЕЦ = '# ─── конец блока «нечего выкладывать»';

/**
 * Текст блока — из самого робота, а не переписанный рядом: копия разошлась бы
 * с первой же правкой, и проверка сторожила бы себя, а не робота.
 */
export function читатьБлок(текст) {
	const от = текст.indexOf(НАЧАЛО);
	const до = текст.indexOf(КОНЕЦ);
	if (от < 0 || до < 0) return null;
	return текст.slice(от + НАЧАЛО.length, до);
}

const git = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });

const положить = (repo, путь, текст) => {
	const файл = join(repo, путь);
	mkdirSync(dirname(файл), { recursive: true });
	writeFileSync(файл, текст, 'utf8');
};

/**
 * Песочница: репозиторий, где уже выложен один коммит, а следом приехал второй
 * с перечисленными файлами.
 *
 * @param {string[]} файлы — что поменялось во втором коммите.
 * @param {string} блок — текст блока (пустой = прежнее правило, подлога ради).
 * @param {{ласт?: string}} [как] — чем подменить отметку «докуда выложено».
 * @returns {{собрал: boolean, отметка: string, вывод: string, код: number}}
 */
function прогон(файлы, блок, как = {}) {
	const box = mkdtempSync(join(tmpdir(), 'baka-deploy-idle-'));
	try {
		const repo = join(box, 'repo');
		mkdirSync(repo, { recursive: true });
		git(repo, 'init', '--initial-branch=main');
		git(repo, 'config', 'user.name', 'заказчик');
		git(repo, 'config', 'user.email', 'owner@example.com');
		положить(repo, 'src/content/posts/первый.md', '---\ntitle: Первый\n---\n');
		положить(repo, 'src/data/telegramFeed.mjs', 'export const telegramFeed = {"lastRunAt": "вчера"};\n');
		git(repo, 'add', '-A');
		git(repo, 'commit', '-m', 'Первый пост');
		const LAST = git(repo, 'rev-parse', 'HEAD').trim();

		for (const путь of файлы) положить(repo, путь, `правка ${путь} ${файлы.length}\n`);
		git(repo, 'add', '-A');
		git(repo, 'commit', '-m', 'Что-то приехало');
		const NEW = git(repo, 'rev-parse', 'HEAD').trim();

		const STATE = join(box, 'last-deployed-commit');
		writeFileSync(STATE, `${как.ласт ?? LAST}\n`, 'utf8');

		// Дальше — собственный текст робота; «СОБИРАЮ» стоит ровно там, где
		// у него `npm run build`.
		const сценарий = `set -u\nLAST=${как.ласт ?? LAST}\nNEW=${NEW}\nSTATE=${STATE}\n${блок}\necho СОБИРАЮ\n`;
		let вывод = '';
		let код = 0;
		try {
			вывод = execFileSync('bash', ['-c', сценарий], { cwd: repo, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
		} catch (err) {
			код = err.status ?? 1;
			вывод = `${err.stdout ?? ''}${err.stderr ?? ''}`;
		}
		return {
			собрал: вывод.includes('СОБИРАЮ'),
			отметка: readFileSync(STATE, 'utf8').trim(),
			выложено: NEW,
			вывод: вывод.trim(),
			код,
		};
	} finally {
		rmSync(box, { recursive: true, force: true });
	}
}

// ─── Прогон ────────────────────────────────────────────────────────────────

const подлог = process.argv.includes('--подлог') || process.argv.includes('--selftest');
const беды = [];
const ок = (строка) => console.log(`  ✓ ${строка}`);
const плохо = (строка) => {
	беды.push(строка);
	console.log(`  ✗ ${строка}`);
};

const текст = readFileSync(SCRIPT, 'utf8');
const ЗАКЛАДКА = 'src/data/telegramFeed.mjs';

if (подлог) {
	console.log('=== ПОДЛОГ: роботу возвращено ПРЕЖНЕЕ правило — блока нет вовсе ===\n');
	const r = прогон([ЗАКЛАДКА], '');
	if (r.собрал) ок('робот пошёл собирать сайт ради закладки — ровно как 25 августа в 14:11');
	else плохо('робот НЕ пошёл собирать даже без блока — песочница не воспроизводит поломку, её «ок» ничего не значит');
} else {
	console.log('=== СБОРКА НЕ БУДИТСЯ ЗАКЛАДКОЙ РОБОТА ===\n');

	const блок = читатьБлок(текст);
	if (блок === null) {
		плохо('в hetzner/run-deploy.sh нет блока «нечего выкладывать» — проверять нечего');
	} else {
		const где = текст.indexOf(НАЧАЛО);
		const сборка = текст.indexOf('npm run build');
		if (сборка > где) ок('блок спрашивает ДО сборки — после шести минут работы спрашивать поздно');
		else плохо('блок стоит ПОСЛЕ сборки — экономить уже нечего');

		const пусто = прогон([ЗАКЛАДКА], блок);
		if (!пусто.собрал) ок('коммит с одной закладкой робота сборку не будит');
		else плохо('коммит с одной закладкой ПОШЁЛ собирать — вернулась лишняя сборка 25 августа');
		if (пусто.отметка === пусто.выложено) ок('отметка «докуда выложено» сдвинута — робот не вернётся с тем же вопросом через десять минут');
		else плохо('отметка не сдвинулась — робот будет спрашивать про этот коммит каждые десять минут вечно');

		// САМЫЙ ВАЖНЫЙ СЛУЧАЙ. Робот телеграма кладёт закладку В ОДИН КОММИТ
		// с постами: спутай их — и новый пост не уедет на сайт вовсе.
		const смешанный = прогон([ЗАКЛАДКА, 'src/content/posts/новый.md'], блок);
		if (смешанный.собрал) ок('закладка ВМЕСТЕ с новым постом собирается — пост не потерян');
		else плохо('коммит с закладкой И постом не собрался — новый пост не уехал бы на сайт');

		for (const [что, файлы] of [
			['новый пост', ['src/content/posts/новый.md']],
			['картинка из админки', ['public/images/uploads/снимок.jpg']],
			['правка стилей', ['src/styles/base.css']],
			['настройка сборки', ['astro.config.mjs']],
			['незнакомый файл в корне', ['странный.конфиг']],
		]) {
			const r = прогон(файлы, блок);
			if (r.собрал) ок(`${что} — собирается`);
			else плохо(`${что} НЕ собрался: правка не уехала бы на сайт вовсе`);
		}

		for (const [что, файлы] of [
			['документы в корне', ['СТАТУС.md', 'CLAUDE.md']],
			['журнал сессий', ['статус/задача-21-роботы-на-hetzner.md']],
			['скрипты сервера', ['hetzner/run-deploy.sh']],
		]) {
			const r = прогон(файлы, блок);
			if (!r.собрал) ок(`${что} — сборку не будят`);
			else плохо(`${что} разбудили сборку: шесть минут работы впустую`);
		}

		// Не смогли сравнить — собираем. Молчание измерителя не повод
		// не выкладывать: это та же семья, что «инструмент, который не умеет
		// проверяемого, отвечает „всё хорошо“».
		const слепой = прогон([ЗАКЛАДКА], блок, { ласт: '0'.repeat(40) });
		if (слепой.собрал) ок('не сравнилось с отметкой — собирает, как собирал');
		else плохо('не сравнилось — и робот решил не собирать: слепота выдана за «нечего делать»');
	}
}

console.log('');
if (беды.length) {
	console.log(`ПРОВЕРКА НЕ ПРОШЛА: ${беды.length}.`);
	process.exit(1);
}
console.log('Всё сошлось.');
