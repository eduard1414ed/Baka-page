// НА ПОДЛОЖЕННЫХ ДАННЫХ.
//
//   node scripts/post-anime-sort.test.mjs
//   node scripts/post-anime-sort.test.mjs --selftest
//
// ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА, А НЕ СТРОЧКА В mentions-sort.test.mjs. Правила два,
// и они РАЗНЫЕ: там «сколько весит материал на странице тайтла» (бонус и внешняя
// статья весят фиксированные 10), здесь «сколько раз тайтл назван внутри одного
// материала». Свести их в одну проверку значило бы намекнуть, что правило одно.
//
// А ГЛАВНОЕ — ПОРЯДОК МАРОК ВИДОМ НЕ ЯВЛЯЕТСЯ. На карточке не написано, сколько
// раз тайтл назван, поэтому «по количеству» и «как было» заказчик не отличит
// глазами в принципе. Значит проверять должен код.
//
// ЗДЕСЬ ЖЕ ТРИ КРАЯ, КОТОРЫХ В ЖИВОМ АРХИВЕ НЕ ВЫЗВАТЬ ПО ЗАКАЗУ: подборка
// сезона, где счёт у всех тайтлов ноль; бонус, где считать нечего вовсе;
// выпуск, где тайтл и в тексте, и в разговоре.
//
// ЧЕГО ЭТА ПРОВЕРКА НЕ ЗНАЕТ. Ничего про вид марок и ничего про то, доехал ли
// порядок до собранной страницы: она смотрит на функцию, а не на `dist/`.

import { readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Путь достаём через fileURLToPath, а не `.pathname`: в пути к проекту русские
// буквы, и `.pathname` отдаёт их закодированными — «файла нет» про файл, который есть.
const МОДУЛЬ = fileURLToPath(new URL('../src/lib/animeMentionIndex.mjs', import.meta.url));
const ПОДЛОГ = fileURLToPath(new URL('../src/lib/animeMentionIndex.selftest-sort-tmp.mjs', import.meta.url));

const cases = [];
const проверка = (name, ok, подробности = '') => cases.push({ name, ok, подробности });

const счёт = (пары) => new Map(пары);
const минуты = (пары) => new Map(пары.map(([id, n]) => [id, Array.from({ length: n }, (_, i) => i * 100)]));

let прогонов = 0;

async function main(файл = МОДУЛЬ) {
	cases.length = 0;
	const { sortAnimeByMentions } = await import(`${pathToFileURL(файл).href}?v=${++прогонов}`);
	const порядок = (ids, counts = new Map(), times = new Map()) => sortAnimeByMentions(ids, counts, times).join(' → ');

	// 1. ЧАЩЕ НАЗВАН — ВЫШЕ. Ради этого всё и затевалось.
	{
		const got = порядок(['редкий', 'частый'], счёт([['редкий', 1], ['частый', 5]]));
		проверка('чаще назван — выше', got === 'частый → редкий', got);
	}

	// 2. НИЧЬЯ ОСТАВЛЯЕТ ПРЕЖНИЙ ПОРЯДОК — тот, что расставлен в поле «Аниме».
	//    Замер по архиву: у 165 материалов из 415 счёт у всех тайтлов равный,
	//    то есть прежний порядок читатель видит чаще самой сортировки.
	{
		const got = порядок(['я-третий', 'а-первый', 'м-второй'], счёт([['я-третий', 2], ['а-первый', 2], ['м-второй', 2]]));
		проверка('при ничьей порядок не трогается, и алфавит тут ни при чём', got === 'я-третий → а-первый → м-второй', got);
	}

	// 3. ПОДБОРКА СЕЗОНА. Тайтлы названы вставками `::anime-ref`, счётчик видит
	//    у них НОЛЬ, а в тексте мимоходом помянут посторонний тайтл. Без минимума
	//    в единицу он встал бы ПЕРВЫМ, выше всех, ради которых статья написана.
	//    Замер: таких статей в архиве шесть.
	{
		const got = порядок(
			['подборка-1', 'подборка-2', 'подборка-3', 'мимоходом'],
			счёт([['мимоходом', 1]]),
		);
		проверка(
			'случайное упоминание не обгоняет подборку',
			got === 'подборка-1 → подборка-2 → подборка-3 → мимоходом',
			got,
		);
	}

	// 4. БОНУС: считать нечего вовсе — ни текста, ни расшифровки. Все тайтлы
	//    равны, и порядок обязан остаться тем, который расставили руками.
	{
		const got = порядок(['второй-по-полю', 'первый-по-полю']);
		проверка('у бонуса порядок поля цел', got === 'второй-по-полю → первый-по-полю', got);
	}

	// 5. ВЫПУСК: текст и разговор СКЛАДЫВАЮТСЯ. Тайтл, названный в описании
	//    один раз и в разговоре трижды, обгоняет названный в тексте трижды.
	{
		const got = порядок(['текстовый', 'звучавший'], счёт([['текстовый', 3], ['звучавший', 1]]), минуты([['звучавший', 3]]));
		проверка('текст и куски разговора складываются', got === 'звучавший → текстовый', got);
	}

	// 6. КРАЯ.
	{
		проверка('пустой список — не падаем', порядок([]) === '');
		проверка('один тайтл — не падаем', порядок(['один']) === 'один');
		const исходный = ['а', 'б'];
		sortAnimeByMentions(исходный, счёт([['б', 9]]), new Map());
		проверка('исходный список не портится на месте', исходный.join('') === 'аб', исходный.join(''));
	}

	for (const item of cases) {
		console.log(`  ${item.ok ? 'ок  ' : 'СБОЙ'}  ${item.name}${item.подробности ? `  [${item.подробности}]` : ''}`);
	}
	return cases.filter((item) => !item.ok).length;
}

// ── Самопроверка: умеет ли она вообще краснеть ──────────────────────────────
//
// Правило отменяем ровно так, как его отменил бы человек. Настоящий файл при
// этом НЕ ТРОГАЕМ: подлог кладётся копией рядом, иначе он уехал бы в `git stash`
// вместе с работой.
//
// ПОДЛОГОВ ТРИ, ПО ЧИСЛУ ПОЛОВИНОК ПРАВИЛА. Отмени мы одну сортировку — случаи
// про ничью и про подборку остались бы зелёными: там правильный ответ и есть
// «ничего не переставлять», и проверка похвалила бы код, который не работает.
const ПОДЛОГИ = [
	{
		имя: 'сортировка отменена, список отдаётся как пришёл',
		было: '\treturn [...ids].sort((a, b) => вес(b) - вес(a));',
		стало: '\treturn [...ids];',
	},
	{
		имя: 'снят минимум в одно упоминание',
		было: 'const вес = (id) => Math.max(1, (counts.get(id) ?? 0) + (times.get(id)?.length ?? 0));',
		стало: 'const вес = (id) => (counts.get(id) ?? 0) + (times.get(id)?.length ?? 0);',
	},
	{
		// Так выглядела бы «ничью разбивает алфавит» — один из отвергнутых
		// вариантов. Он тихо стирает порядок, расставленный руками в поле.
		имя: 'ничью разбивает алфавит, а не прежний порядок',
		было: '\treturn [...ids].sort((a, b) => вес(b) - вес(a));',
		стало: '\treturn [...ids].sort((a, b) => вес(b) - вес(a) || a.localeCompare(b));',
	},
];

async function selftest() {
	const текст = readFileSync(МОДУЛЬ, 'utf8');
	let провалов = 0;

	for (const подлог of ПОДЛОГИ) {
		const сломанный = текст.replace(подлог.было, подлог.стало);
		if (сломанный === текст) {
			throw new Error(`в animeMentionIndex.mjs нет строки «${подлог.было}» — подлог не встал, проверка смотрит не туда`);
		}

		console.log(`\n── подлог: ${подлог.имя}`);
		writeFileSync(ПОДЛОГ, сломанный);
		try {
			const плохо = await main(ПОДЛОГ);
			const покраснели = cases.filter((item) => !item.ok).map((item) => item.name);
			console.log(
				плохо > 0
					? `  ок    КРАСНЕЕТ: ${покраснели.join('; ')}`
					: '  СБОЙ  проверка НИЧЕГО НЕ ЗАМЕТИЛА. На этом правиле она бесполезна.',
			);
			if (плохо === 0) провалов++;
		} finally {
			unlinkSync(ПОДЛОГ);
		}
	}

	return провалов;
}

const selftestMode = process.argv.includes('--selftest');
console.log(selftestMode ? 'ПОРЯДОК МАРОК ПОД МАТЕРИАЛОМ — самопроверка' : 'ПОРЯДОК МАРОК ПОД МАТЕРИАЛОМ');
const провалов = selftestMode ? await selftest() : await main();
process.exit(провалов > 0 ? 1 : 0);
