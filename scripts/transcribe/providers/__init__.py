"""Реестр сервисов распознавания речи.

Провайдер — это модуль в этой папке. Пайплайн (pipeline.py) не знает про
конкретный сервис ничего: он умеет работать только с тем, что описано ниже.
Поэтому смена сервиса — это новый файл рядом плюс одна строка в PROVIDERS,
а не переписывание пайплайна.

Так же устроены источники данных об аниме (scripts/anime-sources/) — там
у каждого модуля тоже есть id, label и одна рабочая функция.

Что обязан иметь модуль провайдера
----------------------------------

  id       — короткое имя, его пишут в --provider
  label    — как называть сервис в сообщениях на экране
  env_key  — имя переменной в .env, где лежит ключ доступа

  estimate(duration_sec) -> dict
      Сколько будет стоить распознать аудио такой длины. Возвращает
      {"usd": float | None, "credits": int | None, "note": str}.
      Считается без обращения к сети — нужно для сметы и --dry-run.

  transcribe(audio_path, api_key, language="ru") -> dict
      Отправляет файл на распознавание. Возвращает:
      {
          "words": [
              {"start": float, "end": float, "text": str, "speaker": str},
              ...
          ],
          "audio_duration_sec": float | None,  # длительность по данным сервиса
          "raw": <ответ сервиса как есть, на случай разбирательств>,
      }

Главное в этой договорённости — поле "words". Оно всегда одинаковое,
независимо от того, в каком виде сервис отдал ответ. Всё остальное
в пайплайне (сборка реплик, измерение высоты голоса, сверка названий аниме,
сохранение JSON) работает уже с ним и от сервиса не зависит.
"""

from . import elevenlabs

PROVIDERS = {module.id: module for module in (elevenlabs,)}

DEFAULT = elevenlabs.id


def get(name):
	"""Вернуть модуль провайдера по имени, с понятной ошибкой если такого нет."""
	if name not in PROVIDERS:
		known = ", ".join(sorted(PROVIDERS))
		raise KeyError(f"Неизвестный провайдер «{name}». Доступны: {known}")
	return PROVIDERS[name]


def names():
	return sorted(PROVIDERS)
