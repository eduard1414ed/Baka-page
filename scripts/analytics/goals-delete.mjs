// СНОС ЦЕЛИ В МЕТРИКЕ. Отдельным скриптом и с заслонами — потому что
// снос необратим: Метрика привязывает достижения к номеру цели, и вместе
// с целью исчезает вся её история.
//
//   node scripts/analytics/goals-delete.mjs                 — показать, что есть
//   node scripts/analytics/goals-delete.mjs --снести 12345  — снести одну по номеру
//
// ═══════════════════════════════════════════════════════════════════════════
// ЗАСЛОН ПЕРВЫЙ: СНОСИТ ТОЛЬКО АВТОЦЕЛИ.
//
// Метрика помечает свои цели полем goal_source: 'auto'. У заведённых нами
// оно другое. Скрипт отказывается трогать что угодно, кроме 'auto', и это
// не перестраховка: наши двенадцать целей — это код на сайте, который шлёт
// в них события, и снос одной означал бы молчащую цель до конца проекта.
//
// ЗАСЛОН ВТОРОЙ: НОМЕР НАЗЫВАЮТ ЯВНО.
//
// Ни «снести все автоцели», ни «снести по имени». Имя человек правит
// в панели, а номер — нет. Одна команда сносит ровно одну цель.
//
// ЗАСЛОН ТРЕТИЙ: СНАЧАЛА ПОКАЗЫВАЕТ, ЧТО ПРОПАДЁТ.
//
// Перед сносом печатается, сколько эта цель насчитала за всё время. Это
// и есть цена: числа не переносятся никуда и не восстанавливаются.
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЧЕМ ЭТО ПОНАДОБИЛОСЬ. Автоцели Метрика заводит сама и угадывает неточно:
// замер за месяц показал, что её «поиск по сайту» поймал 5 запросов из 42,
// а «отправка формы» — это на самом деле нажатие Enter в строке поиска
// (единственная форма на сайте). Наши цели считают то же самое точнее.
//
// ⚠️ НО ДВЕ ИЗ ЧЕТЫРЁХ АВТОЦЕЛЕЙ БЫЛИ НЕ ДУБЛЯМИ. «Переход в соц.сеть»
// и «переход в мессенджер» до 26 августа 2026 были ЕДИНСТВЕННЫМ, что считало
// уходы в телеграм-канал и TikTok, — так и было записано в реестре наших
// целей. Поэтому сначала заведена своя цель go_social, и только потом
// сносятся автоцели. Снести их раньше значило бы ослепнуть на том месте,
// где стоит второе по частоте действие на сайте.

import { метрикаУправление, метрика, СЧЁТЧИК } from './lib.mjs';

const доводы = process.argv.slice(2);
const i = доводы.indexOf('--снести');
const номер = i > -1 ? доводы[i + 1] : undefined;

const { goals } = await метрикаУправление(`/counter/${СЧЁТЧИК}/goals`);
const авто = goals.filter((g) => g.goal_source === 'auto');
const наши = goals.filter((g) => g.goal_source !== 'auto');

/** Сколько цель насчитала за всё время работы счётчика. Это и есть цена сноса. */
async function накоплено(id) {
	try {
		const j = await метрика({ date1: '2020-01-01', date2: 'today', metrics: `ym:s:goal${id}reaches` });
		return Number(j.totals[0]);
	} catch (e) {
		return `не спросить (${e.message.slice(0, 60)})`;
	}
}

console.log(`Счётчик ${СЧЁТЧИК}. Целей всего ${goals.length}: наших ${наши.length}, автоцелей Метрики ${авто.length}.\n`);

console.log('НАШИ ЦЕЛИ — СНОСУ ЭТИМ СКРИПТОМ НЕ ПОДЛЕЖАТ:');
for (const g of наши) console.log(`   ${g.id}  ${g.name}`);
console.log();

console.log('АВТОЦЕЛИ МЕТРИКИ:');
for (const g of авто) console.log(`   ${g.id}  ${g.name}  —  насчитала за всё время: ${await накоплено(g.id)}`);
console.log();

if (!номер) {
	console.log('Ничего не сделано, это просмотр.');
	console.log('Снести одну: node scripts/analytics/goals-delete.mjs --снести <номер>');
	process.exit(0);
}

const цель = goals.find((g) => String(g.id) === String(номер));
if (!цель) {
	console.error(`✗ Цели с номером ${номер} в счётчике нет. Ничего не снесено.`);
	process.exit(1);
}
if (цель.goal_source !== 'auto') {
	// ЭТО НЕ ПРИДИРКА. В наши цели шлёт события код сайта; снесённая цель
	// не вернётся, а код продолжит слать в пустоту — и Метрика будет молча
	// выбрасывать событие, для которого цели нет.
	console.error(`✗ «${цель.name}» — НАША цель, а не автоцель Метрики (goal_source: ${цель.goal_source ?? 'не указан'}).`);
	console.error('  Этот скрипт сносит только автоцели. Ничего не снесено.');
	process.exit(1);
}

const было = await накоплено(цель.id);
console.log(`СНОШУ: ${цель.id} «${цель.name}»`);
console.log(`Вместе с ней исчезнут её достижения за всё время: ${было}. Назад их не вернуть.\n`);

await метрикаУправление(`/counter/${СЧЁТЧИК}/goal/${цель.id}`, { method: 'DELETE' });

// СПРАШИВАЕМ МЕТРИКУ ЗАНОВО, А НЕ ВЕРИМ ОТВЕТУ НА СНОС. «Запрос прошёл»
// и «цели больше нет» — разные утверждения, и проверять надо второе.
const { goals: стало } = await метрикаУправление(`/counter/${СЧЁТЧИК}/goals`);
const жива = стало.find((g) => String(g.id) === String(номер));
if (жива) {
	console.error(`✗ Метрика ответила на снос без ошибки, НО цель ${номер} по-прежнему в списке. Снос не удался.`);
	process.exit(1);
}
console.log(`✓ Снесено. Целей стало ${стало.length} (было ${goals.length}).`);
console.log(`   автоцелей осталось: ${стало.filter((g) => g.goal_source === 'auto').length}`);
console.log('\nМетрика заводит автоцели сама. Вернётся ли эта — покажет список через несколько дней;');
console.log('увидеть это можно в сводке бота командой /goals.');
