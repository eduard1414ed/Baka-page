// ЦЕЛИ ЯНДЕКС.МЕТРИКИ: план, заведение, реестр.
//
//   node scripts/analytics/goals-metrika.mjs            — показать план, НИЧЕГО не менять
//   node scripts/analytics/goals-metrika.mjs --завести   — завести недостающие
//
// ПОЧЕМУ ПО УМОЛЧАНИЮ НИЧЕГО НЕ ДЕЛАЕТ. Цель, заведённая по ошибке, стирается
// руками, но данные, которые она успела собрать, не переносятся никуда:
// переименовать идентификатор — значит начать копить заново. Дешевле
// посмотреть план дважды.
//
// ПОВТОРНЫЙ ЗАПУСК БЕЗОПАСЕН: сначала спрашиваем у Метрики, что там уже есть,
// и сверяем ПО ИДЕНТИФИКАТОРУ, а не по названию. Название человек может
// поправить в панели — и сверка по нему завела бы двойника, который молча
// делит достижения пополам.
//
// ПОРЯДОК ВАЖЕН И ОБРАТНОМУ НЕ ПОДЛЕЖИТ: в Метрике цель должна существовать
// ДО того, как код начнёт слать событие. Событие с неизвестным
// идентификатором она выбрасывает молча, и задним числом его не вернуть.

import { метрикаУправление, СЧЁТЧИК } from './lib.mjs';
import { ЦЕЛИ } from './goals-list.mjs';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

const хочуЗавести = process.argv.includes('--завести');

const { goals: было } = await метрикаУправление(`/counter/${СЧЁТЧИК}/goals`);

/** Идентификатор JS-цели лежит в conditions[].url. */
const ключЦели = (g) => (g.type === 'action' ? g.conditions?.[0]?.url : undefined);
const естьКлючи = new Set(было.map(ключЦели).filter(Boolean));

const нужно = ЦЕЛИ.filter((ц) => !естьКлючи.has(ц.ключ));
const уже = ЦЕЛИ.filter((ц) => естьКлючи.has(ц.ключ));

console.log(`В счётчике ${СЧЁТЧИК} сейчас целей: ${было.length}`);
for (const g of было) console.log(`   есть: ${g.id}  ${g.type.padEnd(9)} ${g.name}${ключЦели(g) ? `  [${ключЦели(g)}]` : ''}`);
console.log();
if (уже.length) console.log(`Уже заведены и пропускаются: ${уже.map((ц) => ц.ключ).join(', ')}\n`);

if (!нужно.length) {
	console.log('Заводить нечего — все цели на месте.');
} else if (!хочуЗавести) {
	console.log(`ПЛАН (ничего не сделано, это просмотр). Завести ${нужно.length} целей:\n`);
	for (const ц of нужно) {
		console.log(`  ${ц.имя}`);
		console.log(`     идентификатор: ${ц.ключ}`);
		console.log(`     считает:       ${ц.считает}`);
		console.log(`     НЕ считает:    ${ц.неСчитает}\n`);
	}
	console.log('Чтобы завести на самом деле: тот же вызов с ключом --завести');
	process.exit(0);
} else {
	console.log(`ЗАВОЖУ ${нужно.length} целей…\n`);
	let удачно = 0;
	const беды = [];
	for (const ц of нужно) {
		try {
			const { goal } = await метрикаУправление(`/counter/${СЧЁТЧИК}/goals`, {
				method: 'POST',
				тело: { goal: { name: ц.имя, type: 'action', is_retargeting: 0, conditions: [{ type: 'exact', url: ц.ключ }] } },
			});
			console.log(`  ✓ ${goal.id}  ${ц.ключ}  — ${ц.имя}`);
			удачно++;
		} catch (e) {
			console.log(`  ✗ ${ц.ключ}: ${e.message}`);
			беды.push(ц.ключ);
		}
	}
	console.log(`\nЗаведено: ${удачно} из ${нужно.length}.`);
	if (беды.length) console.log(`НЕ ЗАВЕДЕНЫ: ${беды.join(', ')}`);
}

// ── РЕЕСТР ─────────────────────────────────────────────────────────────────
//
// Пишется ПОСЛЕ работы и ИЗ ЖИВОГО ОТВЕТА Метрики, а не из плана выше.
// Отчёт, составленный до попытки сохранить, врёт про сохранённое — этот
// урок в проекте оплачен письмом «применено 2 ✓» про работу, не попавшую
// в репозиторий.
const { goals: стало } = await метрикаУправление(`/counter/${СЧЁТЧИК}/goals`);
const поКлючу = new Map(ЦЕЛИ.map((ц) => [ц.ключ, ц]));

const строки = [];
строки.push('# Цели веб-аналитики: что заведено, когда и зачем');
строки.push('');
строки.push('**Файл собирается сам** — `node scripts/analytics/goals-metrika.mjs`.');
строки.push('Правьте не его, а список `ЦЕЛИ` в том же скрипте: иначе следующий');
строки.push('запуск сотрёт правку и никто об этом не узнает.');
строки.push('');
строки.push('**ЦЕЛЬ СЧИТАЕТ С МОМЕНТА СОЗДАНИЯ. Задним числом данных нет и не будет.**');
строки.push('');
строки.push('## Наши цели');
строки.push('');
for (const g of стало.filter((g) => поКлючу.has(ключЦели(g)))) {
	const ц = поКлючу.get(ключЦели(g));
	строки.push(`### ${ц.имя}`);
	строки.push('');
	строки.push(`- **Номер в Метрике:** ${g.id}`);
	строки.push(`- **Идентификатор (шлёт код):** \`${ц.ключ}\``);
	строки.push(`- **Считает:** ${ц.считает}`);
	строки.push(`- **НЕ считает:** ${ц.неСчитает}`);
	строки.push('');
}
const автоцели = стало.filter((g) => !поКлючу.has(ключЦели(g)));
if (автоцели.length) {
	строки.push('## Автоцели Метрики');
	строки.push('');
	// «НЕ ТРОГАЕМ» СТОЯЛО ЗДЕСЬ ДО 26 АВГУСТА 2026 И СТАЛО НЕПРАВДОЙ В ТОТ ЖЕ
	// ДЕНЬ, когда автоцели начали сносить как неточные. Файл собирается сам,
	// и строчка про «не трогаем» пережила бы решение молча.
	строки.push('Их завела сама Метрика, без нашего участия. **Сносятся** — они угадывают неточно:');
	строки.push('замер за месяц дал у «поиска по сайту» 5 запросов из 42, а «отправка формы» —');
	строки.push('это на самом деле нажатие Enter в единственной форме сайта, строке поиска.');
	строки.push('Снос необратим: достижения исчезают вместе с целью.');
	строки.push('Чем сносить — `node scripts/analytics/goals-delete.mjs`.');
	строки.push('');
	строки.push('⚠️ **Метрика заводит автоцели сама**, поэтому снесённая может вернуться.');
	строки.push('Если в этом списке снова появилось то, что сносили, — так и есть.');
	строки.push('');
	for (const g of автоцели) строки.push(`- **${g.name}** (${g.id}, тип \`${g.type}\`)`);
	строки.push('');
}
const путь = join(КОРЕНЬ, 'статус', 'цели-аналитики.md');
writeFileSync(путь, строки.join('\n'), 'utf8');
console.log(`\nРеестр переписан из живого ответа Метрики: статус/цели-аналитики.md (наших целей ${стало.length - автоцели.length}, автоцелей ${автоцели.length})`);
