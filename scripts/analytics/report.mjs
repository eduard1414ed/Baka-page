// ── ЧИСЛА И РАЗНИЦА ────────────────────────────────────────────────────────

const N = (n, знаков = 0) => Number(n).toLocaleString('ru-RU', { maximumFractionDigits: знаков });

/** Склонение при числе: 1 человек, 2 человека, 5 человек. */
function склонение(n, один, два, много) {
	const a = Math.abs(Math.round(n)) % 100;
	if (a > 10 && a < 20) return много;
	const b = a % 10;
	if (b === 1) return один;
	if (b >= 2 && b <= 4) return два;
	return много;
}

/** Разница в процентах словами. Ноль в основании — «было пусто». */
function дельта(сейчас, было, знаков = 0) {
	const a = Number(сейчас), b = Number(было);
	if (!Number.isFinite(a) || !Number.isFinite(b)) return '—';
	if (b === 0) return a === 0 ? '—' : 'было пусто';
	const п = ((a - b) / b) * 100;
	if (Math.abs(п) < 0.5) return 'без изменений';
	return `${п > 0 ? '+' : '−'}${N(Math.abs(п), 0)} %`;
}

