/**
 * Что искали. ДВА РАЗНЫХ ВОПРОСА В ОДНОМ РАЗДЕЛЕ, и путать их нельзя:
 * Search Console знает, по каким словам нас ПОКАЗЫВАЛИ в Google (даже без
 * нажатия), а Метрика — только тех, кто дошёл до сайта. Сам Google Analytics
 * поисковых запросов не показывает вообще, никогда.
 */
async function искалиБлок(сколько = 5) {
	подпись('🔎 <b>Что искали</b>');
	const sc = await можно('Search Console', async () => {
		const t = await googleПропуск('https://www.googleapis.com/auth/webmasters.readonly');
		const site = encodeURIComponent('https://ru.bakapodcast.com/');
		const r = await fetch(`https://searchconsole.googleapis.com/webmasters/v3/sites/${site}/searchAnalytics/query`, {
			method: 'POST',
			headers: { Authorization: `Bearer ${t}`, 'Content-Type': 'application/json' },
			body: JSON.stringify({ startDate: с, endDate: по, dimensions: ['query'], rowLimit: 15 }),
		});
		const j = await r.json();
		if (!r.ok) throw new Error(String(j.error?.message ?? JSON.stringify(j)).slice(0, 160));
		return j;
	});
	if (sc?.rows?.length) {
		const показов = sc.rows.reduce((s, r) => s + r.impressions, 0);
		строка(`<i>В Google показали ${N(показов)} ${склонение(показов, 'раз', 'раза', 'раз')}:</i>`);
		for (const r of sc.rows.slice(0, сколько)) строка(`${Э(r.keys[0])} — ${N(r.impressions)} / нажали ${N(r.clicks)}`);
	} else {
		строка('<i>Google Search Console данных не дал.</i>');
	}
	const фразы = await можно('Метрика: поисковые фразы', () => ym('фразы', с, по, { dimensions: 'ym:s:searchPhrase', metrics: 'ym:s:visits', sort: '-ym:s:visits', limit: '10' }));
	const ряды = (фразы?.data ?? []).filter((r) => r.dimensions[0].name && r.dimensions[0].name !== 'Not set');
	if (ряды.length) {
		строка(`<i>Дошли до сайта по словам:</i>`);
		for (const r of ряды.slice(0, сколько)) строка(`${Э(r.dimensions[0].name)} — ${N(r.metrics[0])}`);
	}
}

/**
 * Цели. ПОКАЗЫВАЕМ ТОЛЬКО СРАБОТАВШИЕ. Двенадцать строк, из которых девять
 * нули, на телефоне читаются мусором и хоронят под собой три настоящие;
 * сколько целей промолчало — сказано числом отдельной строкой, чтобы
 * «нулей нет» не путалось с «целей нет».
 */
async function целиБлок(сколько = 8) {
	подпись('🎯 <b>Что делали на сайте</b>');
	const цели = await можно('Метрика: список целей', () => метрикаУправление(`/counter/${СЧЁТЧИК}/goals`));
	if (!цели?.goals?.length) return строка('Список целей получить не удалось.');
	const метрики = цели.goals.map((g) => `ym:s:goal${g.id}reaches`);
	const д = await можно('Метрика: достижения целей', () => ym(`цели-${метрики.length}`, с, по, { metrics: метрики.join(',') }));
	if (!д) return строка('Числа по целям получить не удалось.');
	const пары = цели.goals.map((g, i) => [g.name, Number(д.totals[i])]).filter(([, n]) => n > 0).sort((a, b) => b[1] - a[1]);
	if (!пары.length) return строка('Ни одна цель за период не сработала.');
	for (const [имя, n] of пары.slice(0, сколько)) строка(`${Э(имя)} — ${N(n)}`);
	const молча = цели.goals.length - пары.length;
	if (молча) строка(`<i>Ещё ${N(молча)} ${склонение(молча, 'цель', 'цели', 'целей')} за период не сработало ни разу.</i>`);
}

/**
 * ЧТО ИСКАЛИ ВНУТРИ САЙТА — и это НЕ ТО ЖЕ САМОЕ, что раздел «что искали».
 * Тот про поисковики: по каким словам нас находят снаружи. Этот — про людей,
 * которые уже пришли и не нашли глазами; он говорит, чего на сайте не хватает.
 *
 * ТЕКСТ ЗАПРОСА ЕСТЬ ТОЛЬКО У МЕТРИКИ. Наш код шлёт его обоим сервисам
 * параметром события, но Google отдаёт такие параметры лишь после того, как
 * их объявят своим измерением в его настройках, — сейчас они не объявлены,
 * и на «customEvent:query» он отвечает отказом 400. Замер 26 августа 2026.
 *
 * ЧИСЛО РЯДОМ — ЗАХОДЫ, А НЕ ПОИСКИ. Параметр Метрика хранит при ВИЗИТЕ:
 * искал человек за один заход трижды одно и то же — это один заход. Врать
 * про «столько раз искали» нельзя, поэтому так и подписано.
 */
async function внутриБлок(сколько = 8) {
	подпись('🔤 <b>Что искали ВНУТРИ сайта</b>');
	const пар = (что) => ym(`пар-${что}`, с, по, { dimensions: 'ym:s:paramsLevel2', metrics: 'ym:s:visits', filters: `ym:s:paramsLevel1=='${что}'`, sort: '-ym:s:visits', limit: '30' });
	const запросы = await можно('Метрика: слова из поиска по сайту', () => пар('query'));
	const ряды = ymСтроки(запросы ?? { data: [] }).filter(([имя]) => имя && имя !== 'Не задано');
	if (!ряды.length) {
		строка('За период внутри сайта не искали.');
	} else {
		for (const [имя, n] of ряды.slice(0, сколько)) строка(`${Э(имя)} — ${N(n)}`);
		строка('<i>Число — заходы, в которых это искали, а не сколько раз набрали.</i>');
	}
	// «НИЧЕГО НЕ НАЙДЕНО» — САМОЕ ЦЕННОЕ ЗДЕСЬ, и потому отдельной строкой.
	const нашлось = await можно('Метрика: сколько нашлось', () => пар('found'));
	const пусто = ymСтроки(нашлось ?? { data: [] }).find(([имя]) => имя === '0');
	if (пусто) строка(`<i>Из них без единой находки: ${N(пусто[1])}.</i>`);
	const где = await можно('Метрика: где искали', () => пар('place'));
	const ГДЕ = { site: 'поиск по сайту', catalog: 'каталог тайтлов', text: 'внутри расшифровки' };
	const местa = ymСтроки(где ?? { data: [] }).filter(([имя]) => ГДЕ[имя]);
	if (местa.length) строка(`<i>Где: ${местa.map(([имя, n]) => `${ГДЕ[имя]} ${N(n)}`).join(', ')}.</i>`);
}

/**
 * ЧТО СЛУШАЛИ. Название выпуска приходит параметром цели «включил выпуск»
 * и берётся из подписи в самой панели плеера, а не из адреса, — то есть это
 * ровно то, что человек видел на экране.
 *
 * ДОСЛУШИВАНИЕ СЧИТАЕТСЯ ПРОСЛУШАННЫМ ВРЕМЕНЕМ, А НЕ ПОЛОЖЕНИЕМ ПОЛЗУНКА:
 * увёл ползунок в конец — «дослушал» не засчитано (так устроен код целей).
 */
async function плеерБлок(сколько = 8) {
	подпись('🎧 <b>Что слушали</b>');
	const выпуски = await можно('Метрика: включённые выпуски', () =>
		ym('пар-episode', с, по, { dimensions: 'ym:s:paramsLevel2', metrics: 'ym:s:visits', filters: "ym:s:paramsLevel1=='episode'", sort: '-ym:s:visits', limit: '30' }),
	);
	const ряды = ymСтроки(выпуски ?? { data: [] }).filter(([имя]) => имя && имя !== 'Не задано');
	if (!ряды.length) строка('За период плеер не включали.');
	else for (const [имя, n] of ряды.slice(0, сколько)) строка(`${Э(имя)} — ${N(n)}`);

	// Докуда доходят. Числа берём у самих целей, а не считаем заново:
	// два счётчика рядом обязаны считать одно и то же.
	const цели = await можно('Метрика: список целей', () => метрикаУправление(`/counter/${СЧЁТЧИК}/goals`));
	const нужные = [
		['player_start', 'включили'],
		['player_25', 'четверть'],
		['player_50', 'половина'],
		['player_90', 'дослушали'],
	];
	if (цели?.goals?.length) {
		const поИмени = new Map(цели.goals.map((g) => [g.name, g.id]));
		const ИМЕНА = { player_start: 'Плеер: включил выпуск', player_25: 'Плеер: прослушал четверть', player_50: 'Плеер: прослушал половину', player_90: 'Плеер: дослушал (90 %)' };
		const ид = нужные.map(([к]) => поИмени.get(ИМЕНА[к])).filter(Boolean);
		if (ид.length === нужные.length) {
			const д = await можно('Метрика: ступени прослушивания', () =>
				ym('ступени', с, по, { metrics: ид.map((i) => `ym:s:goal${i}reaches`).join(',') }),
			);
			// Лесенка печатается, ТОЛЬКО если плеер вообще включали: строчка
			// «включили 0 → четверть 0 → половина 0 → дослушали 0» стоит сразу
			// под словами «плеер не включали» и повторяет их четырьмя нулями.
			if (д && Number(д.totals[0]) > 0) {
				строка('');
				строка(`<i>Докуда доходят: ${нужные.map(([, подпись], i) => `${подпись} ${N(д.totals[i])}`).join(' → ')}.</i>`);
			}
		}
	}
}

