const МЕТ = 'ym:s:visits,ym:s:users,ym:s:pageviews';

/**
 * Посещаемость. ЕДИНСТВЕННЫЙ РАЗДЕЛ, БЕЗ КОТОРОГО СВОДКА НЕ ИМЕЕТ СМЫСЛА:
 * не ответил он — вся сводка превращается в сообщение о беде (см. низ файла).
 */
async function людиБлок() {
	const т1 = await можно('Метрика: посещаемость', () => ym('итог', с, по, { metrics: МЕТ }));
	if (!т1) return false;
	const т0 = await можно('Метрика: посещаемость прошлого периода', () => ym('итог', пС, пПо, { metrics: МЕТ }));
	const б = (i) => (т0 ? дельта(т1.totals[i], т0.totals[i]) : '');
	строка(`👥 <b>Людей ${N(т1.totals[1])}</b>${б(1)}`);
	строка(`Заходов ${N(т1.totals[0])}${б(0)}, страниц открыто ${N(т1.totals[2])}${б(2)}`);

	const новые = await можно('Метрика: новые и вернувшиеся', () => ym('новые', с, по, { dimensions: 'ym:s:isNewUser', metrics: 'ym:s:users' }));
	if (новые?.data?.length) {
		const найти = (имя) => Number(новые.data.find((r) => r.dimensions[0].name === имя)?.metrics[0] ?? 0);
		строка(`Впервые ${N(найти('New users'))}, вернулись ${N(найти('Returning users'))}`);
	}
	return true;
}

