function аргумент(имя) {
	const i = process.argv.indexOf(имя);
	return i > -1 ? process.argv[i + 1] : undefined;
}

const день = 86400000;
const строкойД = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

let с = аргумент('--с');
let по = аргумент('--по');
const дней = Number(аргумент('--дней') ?? 7);
if (!с || !по) {
	// Кончаем ВЧЕРА, а не сегодня: сегодняшний день не прожит, и сравнение
	// неполного дня с полным прошлым периодом врало бы в меньшую сторону.
	const вчера = new Date(Date.now() - день);
	по = строкойД(вчера);
	с = строкойД(new Date(вчера.getTime() - (дней - 1) * день));
}
const длина = Math.round((new Date(по) - new Date(с)) / день) + 1;
const пПо = строкойД(new Date(new Date(с).getTime() - день));
const пС = строкойД(new Date(new Date(с).getTime() - длина * день));

const раздел = аргумент('--раздел') ?? 'всё';

// ── ЧИСЛА, СЛОВА, ЗНАКИ ────────────────────────────────────────────────────

const N = (n, знаков = 0) => Number(n).toLocaleString('ru-RU', { maximumFractionDigits: знаков });

function склонение(n, один, два, много) {
	const a = Math.abs(Math.round(n)) % 100;
	if (a > 10 && a < 20) return много;
	const b = a % 10;
	if (b === 1) return один;
	if (b >= 2 && b <= 4) return два;
	return много;
}

/**
 * Разница словами. Ноль в основании — «было пусто», а не «+100 %»: рост
 * от нуля процентами не считается, и такая строка читалась бы успехом там,
 * где на деле счётчик просто не работал.
 */
function дельта(сейчас, было) {
	const a = Number(сейчас), b = Number(было);
	if (!Number.isFinite(a) || !Number.isFinite(b)) return '';
	if (b === 0) return a === 0 ? '' : ' (было пусто)';
	const п = ((a - b) / b) * 100;
	if (Math.abs(п) < 0.5) return ' (столько же)';
	return ` (${п > 0 ? '+' : '−'}${N(Math.abs(п), 0)} %)`;
}

// ЗНАКИ & < > ТЕЛЕГРАМ ЧИТАЕТ РАЗМЕТКОЙ И НА КРИВУЮ ОТВЕЧАЕТ ОТКАЗОМ:
// сообщение не уходит ВОВСЕ. А сюда попадают заголовки постов и поисковые
// запросы людей — то есть чужой текст, в котором такой знак рано или поздно
// окажется. Тот же урок, что у писем робота телеграма.
const Э = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** Заголовок страницы без хвоста «— Бака!»: в сводке он повторялся бы в каждой строке. */
const заголовок = (t) => Э(String(t).replace(/\s*[—–-]\s*Бака!?\s*$/u, '').trim() || '(без заголовка)');

const МЕСЯЦЫ = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
function попросту(дата) {
	const d = new Date(дата);
	return `${d.getDate()} ${МЕСЯЦЫ[d.getMonth()]}`;
}

// ── ПОХОДЫ ЗА ДАННЫМИ ──────────────────────────────────────────────────────

// В ключ кэша входит сам запрос, а не только его подпись и даты: иначе
// поменянный вопрос получил бы с диска ответ на прежний (урок задачи 27).
const отпечаток = (o) => createHash('sha1').update(JSON.stringify(o)).digest('hex').slice(0, 10);
const ym = (ключ, date1, date2, params) =>
	изКэша(`ym-${ключ}-${date1}-${date2}-${отпечаток(params)}`, date2, () => метрика({ date1, date2, ...params })).then((r) => r.данные);

const ymСтроки = (j) => (j.data ?? []).map((r) => [r.dimensions.map((d) => d.name ?? d.id ?? '—').join(' / '), Number(r.metrics[0])]);

const беды = [];
async function можно(имя, дело, запасное = null) {
	try {
		return await дело();
	} catch (e) {
		беды.push(`${имя}: ${e.message}`);
		return запасное;
	}
}

const Т = [];
const строка = (s = '') => Т.push(s);

/**
 * Подпись раздела ВНУТРИ общей сводки. Спрошенный отдельной командой раздел
 * свою подпись не печатает: над ним уже стоит заголовок с датами, и вместе
 * они читались бы как «🔤 Искали внутри сайта / 🔤 Что искали внутри сайта» —
 * то есть одно и то же дважды подряд.
 */
function подпись(текст) {
	if (раздел !== 'всё') return;
	строка('');
	строка(текст);
}

