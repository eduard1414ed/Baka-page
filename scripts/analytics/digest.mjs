//
// ОТВАЛИВШИЙСЯ ИСТОЧНИК КРИЧИТ, А НЕ ПРИСЫЛАЕТ ПУСТУЮ СВОДКУ. Если не удалось
// забрать главное (посещаемость), печатается красное сообщение о беде вместо
// цифр: пустая сводка читается как «читателей ноль», и отличить одно от другого
// заказчик не может никак. Прямое требование, пункт 5.2 задания.
//
// СОВЕТОВ ЗДЕСЬ НЕТ И НЕ БУДЕТ. То же правило, что у report.mjs: «отчёт — это
// цифры и что изменилось, выводы буду делать я». Появится строчка «стоит
// написать больше про исекаи» — её надо убрать, а не развить.

