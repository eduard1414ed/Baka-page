// ДАННЫЕ О НОВОМ РОЛИКЕ ОБЯЗАНЫ ДОЕХАТЬ ДО РЕПОЗИТОРИЯ САМИ — И ТО, ЧТО
// УСПЕЛИ УЗНАТЬ, ОБЯЗАНО СОХРАНИТЬСЯ ДАЖЕ ПРИ СБОЕ СЕТИ.
//
// ЗАЧЕМ ЭТА ПРОВЕРКА ЕСТЬ. Разметке ролика обязательны `name` и `uploadDate`,
// а в тексте поста их нет — только адрес. Спрашивают их у YouTube отдельным
// скриптом, и пока это делали руками, дыра открывалась сама: ep-154 вышел
// 10 сентября 2026 с новым роликом, кэш последний раз писался 31 августа,
// и 13 сентября Google Search Console прислал «отсутствует поле name,
// отсутствует поле uploadDate» с пометкой «к показу не допускается».
// Теперь добор стоит шагом у робота постов — он просыпается на каждый
// человеческий коммит в посты.
//
// ГЛАВНОЕ УТВЕРЖДЕНИЕ ЗДЕСЬ НЕ «ШАГ ЕСТЬ», А «ЗАПИСЬ ИДЁТ ДО ПРОВЕРКИ
// ИСХОДА». Скрипт добора при сбое сети пишет всё, что успел узнать, и только
// потом отвечает единицей. Напиши шаг привычным `if node …; then commit;
// else fail; fi` — и добытое осталось бы лежать в рабочей копии
// незакоммиченным: следующий заход счёл бы эти ролики уже разобранными
// (они в файле) и в сеть за ними не пошёл бы никогда. Именно эту форму
// возвращает подлог.
//
// Текст шага берётся ИЗ САМОГО РОБОТА по границам блока, а не переписывается
// сюда: копия разошлась бы с первой же правкой.
//
//   node scripts/video-meta-robot.test.mjs             — проверить
//   node scripts/video-meta-robot.test.mjs --selftest  — вернуть привычную
//                                                        форму шага и убедиться,
//                                                        что проверка краснеет

import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, readFileSync, writeFileSync, mkdirSync, chmodSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const SCRIPT = join(ROOT, 'hetzner/run-on-posts.sh');
const НАЧАЛО = '# ─── начало блока «данные о роликах»';
const КОНЕЦ = '# ─── конец блока «данные о роликах»';

function читатьБлок(текст) {
	const от = текст.indexOf(НАЧАЛО);
	const до = текст.indexOf(КОНЕЦ);
	if (от < 0 || до < 0) return null;
	return текст.slice(от + НАЧАЛО.length, до);
}

/**
 * ПОДЛОГ: та форма шага, которую пишут не задумываясь, — и которая теряет
 * добытое при сбое сети. Ровно она стоит у трёх соседних шагов этого же
 * робота, и там она верна: те скрипты при сбое ничего не пишут.
 */
const ПРИВЫЧНАЯ_ФОРМА = `
echo "--- данные о роликах, встроенных в посты"
if node scripts/fetch-youtube-meta.mjs; then
	commit_and_push "Данные о новых роликах YouTube" src/data/youtubeMeta.mjs \\
		&& NEWS="\${NEWS}🎬 добраны данные о новых роликах\\n"
else
	fail "добор данных о роликах не отработал"
fi
`;

/**
 * Песочница: настоящий git-репозиторий, поддельный `node` вместо скрипта
 * добора и поддельные `commit_and_push` с `fail` — оба записывают, что их
 * звали, в порядке вызова.
 *
 * @param {object} что
 * @param {string} что.вывод   что печатает скрипт добора
 * @param {number} что.код     чем он отвечает
 * @param {boolean} что.пишет  переписывает ли он файл кэша
 * @param {string} блок        текст шага
 */
function прогон({ вывод, код, пишет }, блок) {
	const box = mkdtempSync(join(tmpdir(), 'baka-video-meta-'));
	try {
		const repo = join(box, 'repo');
		mkdirSync(join(repo, 'src/data'), { recursive: true });
		mkdirSync(join(repo, 'scripts'), { recursive: true });
		const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
		git('init', '--initial-branch=main');
		git('config', 'user.name', 'робот');
		git('config', 'user.email', 'bot@example.com');
		writeFileSync(join(repo, 'src/data/youtubeMeta.mjs'), 'export const youtubeMeta = {};\n', 'utf8');
		git('add', '-A');
		git('commit', '-m', 'начало');

		// Поддельный `node`: печатает заготовленное, при надобности правит файл
		// кэша (скрипт добора пишет его ДО того, как ответить единицей)
		// и отвечает заданным кодом.
		const bin = join(box, 'bin');
		mkdirSync(bin);
		const подделка = `#!/bin/bash\ncat <<'КОНЕЦВЫВОДА'\n${вывод}\nКОНЕЦВЫВОДА\n${
			пишет ? `printf 'export const youtubeMeta = { "новый": {} };\\n' > src/data/youtubeMeta.mjs\n` : ''
		}exit ${код}\n`;
		writeFileSync(join(bin, 'node'), подделка, 'utf8');
		chmodSync(join(bin, 'node'), 0o755);

		const обвязка = `
set -u
NEWS=""
ERRORS=""
CALLS=""
fail() { ERRORS="\${ERRORS}\${1};"; CALLS="\${CALLS}fail "; echo "!!! $1"; }
commit_and_push() {
	local msg="$1"; shift
	git add "$@" 2>/dev/null
	if git diff --cached --quiet; then CALLS="\${CALLS}пусто "; return 1; fi
	git commit -q -m "$msg" || return 1
	CALLS="\${CALLS}коммит "
	echo "запушено: $msg"
	return 0
}
${блок}
echo "---ИТОГ---"
echo "ПОРЯДОК: $CALLS"
printf 'НОВОСТИ: %b\\n' "$NEWS"
echo "ОШИБКИ: $ERRORS"
`;
		let текст = '';
		let кодВыхода = 0;
		try {
			текст = execFileSync('bash', ['-c', обвязка], {
				cwd: repo,
				encoding: 'utf8',
				stdio: ['ignore', 'pipe', 'pipe'],
				env: { ...process.env, PATH: `${bin}:${process.env.PATH}` },
			});
		} catch (err) {
			кодВыхода = err.status ?? 1;
			текст = `${err.stdout ?? ''}${err.stderr ?? ''}`;
		}
		const строка = (имя) => текст.split('\n').find((с) => с.startsWith(имя))?.slice(имя.length).trim() ?? '';
		return {
			порядок: строка('ПОРЯДОК:'),
			новости: текст.slice(текст.indexOf('НОВОСТИ:')).split('ОШИБКИ:')[0],
			ошибки: строка('ОШИБКИ:'),
			коммитов: Number(execFileSync('git', ['rev-list', '--count', 'HEAD'], { cwd: repo, encoding: 'utf8' }).trim()),
			вывод: текст,
			код: кодВыхода,
		};
	} finally {
		rmSync(box, { recursive: true, force: true });
	}
}

// ─── Прогон ────────────────────────────────────────────────────────────────

const selftest = process.argv.includes('--selftest') || process.argv.includes('--подлог');
const беды = [];
const ок = (с) => console.log(`  ✓ ${с}`);
const плохо = (с) => {
	беды.push(с);
	console.log(`  ✗ ${с}`);
};

const настоящий = читатьБлок(readFileSync(SCRIPT, 'utf8'));
if (!настоящий) {
	console.error('✗ Не нашёл блок «данные о роликах» в hetzner/run-on-posts.sh — границы переставили или снесли.');
	process.exit(1);
}
const блок = selftest ? ПРИВЫЧНАЯ_ФОРМА : настоящий;

console.log(selftest ? '── ПОДЛОГ: привычная форма шага ──' : '── шаг робота, как он написан ──');

// 1. Обычный заход: добирать нечего.
{
	const р = прогон({ вывод: 'Роликов в текстах: 136. Уже знаем: 136. Спросить: 0.\nок      Про все ролики всё известно — в сеть не ходил.', код: 0, пишет: false }, блок);
	if (р.коммитов === 1) ок('добирать нечего — коммита нет');
	else плохо(`добирать нечего, а коммитов стало ${р.коммитов}`);
	if (!р.ошибки) ок('добирать нечего — робот не жалуется');
	else плохо(`добирать нечего, а в ошибках: ${р.ошибки}`);
}

// 2. Добрали два ролика, один из них закрыт на YouTube.
{
	const вывод = [
		'Роликов в текстах: 138. Уже знаем: 136. Спросить: 2.',
		'  KObWhui56dA — Это — главный спор в аниме | Видеоэссе',
		'  29SndZlRFA4 — недоступен (404)',
		'Записано роликов: 138 → src/data/youtubeMeta.mjs',
	].join('\n');
	const р = прогон({ вывод, код: 0, пишет: true }, блок);
	if (р.коммитов === 2) ок('добрали — данные закоммичены');
	else плохо(`добрали, а коммитов ${р.коммитов} вместо 2`);
	if (/добраны данные о новых роликах/.test(р.новости)) ок('в новостях сказано про добор');
	else плохо('добрали, а в новостях про это ни слова');
	if (/закрыто или удалено/.test(р.новости)) ок('закрытый ролик назван отдельной новостью');
	else плохо('ролик закрыт на YouTube, а робот об этом промолчал');
	if (!р.ошибки) ок('удачный добор — не жалуется');
	else плохо(`удачный добор, а в ошибках: ${р.ошибки}`);
}

// 3. ГЛАВНОЕ: сеть отвалилась на полпути. Скрипт записал, что успел,
//    и ответил единицей.
{
	const вывод = [
		'Роликов в текстах: 140. Уже знаем: 136. Спросить: 4.',
		'  KObWhui56dA — Это — главный спор в аниме | Видеоэссе',
		'Записано роликов: 137 → src/data/youtubeMeta.mjs',
		'✗ Не смог спросить про 3 роликов (сеть). Они не записаны — запустите ещё раз:',
	].join('\n');
	const р = прогон({ вывод, код: 1, пишет: true }, блок);
	if (р.коммитов === 2) ок('сеть отвалилась — добытое всё равно закоммичено');
	else плохо(`сеть отвалилась, и добытое ПРОПАЛО: коммитов ${р.коммитов} вместо 2`);
	if (/^коммит fail/.test(р.порядок)) ок('порядок верный: сперва запись, потом жалоба');
	else плохо(`порядок неверный: «${р.порядок || 'ничего не звали'}»`);
	if (р.ошибки) ок('сеть отвалилась — робот жалуется');
	else плохо('сеть отвалилась, а робот смолчал');
}

console.log('');
if (selftest) {
	if (беды.length === 0) {
		console.error('✗ ПОДЛОГ НЕ ПОЙМАН: вернули привычную форму шага, теряющую добытое, а проверка промолчала.');
		process.exit(1);
	}
	console.log(`✓ Подлог пойман (${беды.length}): ${беды[0]}`);
	console.log('  Проверка умеет краснеть.');
	process.exit(0);
}

if (беды.length > 0) {
	console.error(`✗ Шаг «данные о роликах» ведёт себя не так, как обещано: бед ${беды.length}`);
	process.exit(1);
}
console.log('ок      Данные о роликах: добор стоит у робота постов, запись идёт до жалобы, закрытый ролик назван.');
