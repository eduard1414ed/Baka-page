// ЗАСЛОН ТЕСТОВ (викторина и личностный). Стоит в `npm run build` сразу
// после заслона врезок, ДО `astro build`.
//
//   node scripts/check-quizzes.mjs             — спросить
//   node scripts/check-quizzes.mjs --selftest  — плюс подлоги на каждое правило
//
// ПРАВИЛА — тз/ТЗ-тесты.md, §3, «Проверка при сборке». Здесь они живут
// в ОДНОМ месте: схема (src/content.config.ts) нарочно нестрогая и ничего
// не проверяет, потому что падение схемы роняет сборку ВСЕГО сайта, даже
// из-за черновика.
//
// ПОЧЕМУ ОТДЕЛЬНЫМ СКРИПТОМ, А НЕ ИЗ СТРАНИЦЫ ИЛИ ПЛАГИНА — та же причина,
// что у scripts/check-post-refs.mjs: ошибка, брошенная из разметки, сборку
// не останавливает, а стирает текст материала (урок CLAUDE.md).
//
// ОПУБЛИКОВАННЫЙ ТЕСТ С ОШИБКОЙ РОНЯЕТ СБОРКУ, ЧЕРНОВИК — ТОЛЬКО ПРЕДУПРЕЖДАЕТ.
// Неготовый тест в админке — обычная работа, и остановить из-за него выкладку
// всего сайта значило бы завести заслон, который снимут вместе с пользой.
//
// ФАЙЛ ЧИТАЕТСЯ СЫРЫМ, а не через схему: схема читает «abc» в числе как
// «пусто», а сказать человеку надо именно «тут буквы».
//
// АДРЕС РЕЗУЛЬТАТА — из заголовка, правилом адресов постов (src/lib/slug.mjs):
// поля id у результата нет, решение заказчика 8 октября 2026. Отсюда две
// проверки: заголовок, из которого адреса не собрать (одни эмодзи), и два
// заголовка, дающие один адрес («Маг» и «маг!»).
//
// «РЕЗУЛЬТАТ НЕВОЗМОЖНО ПОЛУЧИТЬ» УПРОЩЕНО до «ему не даёт балл ни один
// вариант» — решение заказчика: полный перебор сочетаний ответов слишком
// тяжёл для сборки. Результат, который получает баллы, но всегда проигрывает
// соседу, эта проверка не видит.

import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import { normalizeFrontmatter } from '../src/lib/frontmatter.mjs';
import { isPublished } from '../src/lib/publishing.mjs';
import { slugify } from '../src/lib/slug.mjs';

const POSTS_DIR = new URL('../src/content/posts/', import.meta.url);

/** Виды теста — те же имена, что у `types` в public/admin/config.yml. */
const ВИДЫ = { quiz: 'викторина', personality: 'личностный' };
const ВАРИАНТОВ_МИН = 2;
const ВАРИАНТОВ_МАКС = 6;
const КАРТИНОК_МАКС = 4;

function тесты() {
	const итог = [];
	for (const файл of readdirSync(fileURLToPath(POSTS_DIR))) {
		if (!файл.endsWith('.md')) continue;
		const сырое = readFileSync(fileURLToPath(new URL(файл, POSTS_DIR)), 'utf8');
		const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(сырое);
		if (!m) continue;
		const data = normalizeFrontmatter(yaml.load(m[1]) ?? {});
		if (data.category !== 'test') continue;
		итог.push({ файл: `src/content/posts/${файл}`, data });
	}
	return итог;
}

const текст = (значение) => (значение === undefined || значение === null ? '' : String(значение).trim());
const список = (значение) => (Array.isArray(значение) ? значение : []);

/** Целое число из поля админки; `null` — пусто, `NaN` — там не число. */
function целое(значение) {
	if (значение === undefined || значение === null || значение === '') return null;
	const число = Number(значение);
	return Number.isInteger(число) ? число : NaN;
}

/** «Баллы» варианта: админка пишет список, рука может написать строку. */
function баллы(значение) {
	if (Array.isArray(значение)) return значение.map(текст).filter(Boolean);
	return текст(значение)
		.split(',')
		.map((с) => с.trim())
		.filter(Boolean);
}

/**
 * Все беды одного теста. Каждая — `{ код, что }`: код нужен самопроверке,
 * чтобы подлог ловился ИМЕННО своим правилом, а не соседним.
 */
export function бедыТеста(data) {
	const беды = [];
	const скажи = (код, что) => беды.push({ код, что });

	const тест = data.test && typeof data.test === 'object' ? data.test : {};
	const вид = тест.kind && typeof тест.kind === 'object' ? тест.kind : {};
	const тип = текст(вид.type);
	const вопросы = список(вид.questions);
	const результаты = список(тест.results);

	if (!тип) скажи('вид', 'не выбран вид теста — в блоке «Вид и вопросы» выберите «Викторина» или «Личностный тест».');
	else if (!(тип in ВИДЫ)) скажи('вид', `неизвестный вид теста «${тип}» — бывают только ${Object.values(ВИДЫ).join(' и ')}.`);
	if (!вопросы.length) скажи('нет-вопросов', 'в тесте нет ни одного вопроса.');
	if (!результаты.length) скажи('нет-результатов', 'в тесте нет ни одного результата.');

	// ── Результаты: заголовок и адрес ───────────────────────────────────────
	const поАдресу = new Map();
	результаты.forEach((р, i) => {
		const где = `результат ${i + 1}`;
		const заголовок = текст(р?.title);
		if (!заголовок) {
			скажи('заголовок-результата', `${где}: нет заголовка.`);
			return;
		}
		const адрес = slugify(заголовок);
		if (!адрес) {
			скажи('адрес-результата', `${где} «${заголовок}»: из заголовка не собрать адрес — в нём нет ни одной буквы или цифры.`);
			return;
		}
		if (поАдресу.has(адрес)) {
			скажи(
				'адрес-результата',
				`${где} «${заголовок}» и «${поАдресу.get(адрес)}» дают один и тот же адрес «${адрес}» — переименуйте один из них.`,
			);
		} else поАдресу.set(адрес, заголовок);
	});

	// ── Вопросы: общее для обоих видов ──────────────────────────────────────
	вопросы.forEach((в, i) => {
		const где = `вопрос ${i + 1}`;
		if (!текст(в?.text)) скажи('текст-вопроса', `${где}: нет текста вопроса.`);

		const картинки = список(в?.images);
		if (картинки.length > КАРТИНОК_МАКС) скажи('картинки', `${где}: картинок ${картинки.length}, можно не больше ${КАРТИНОК_МАКС}.`);
		картинки.forEach((к, j) => {
			if (!текст(к?.src)) скажи('картинки', `${где}, картинка ${j + 1}: картинка не выбрана — выберите или уберите строку.`);
		});

		const варианты = список(в?.options);
		if (варианты.length < ВАРИАНТОВ_МИН || варианты.length > ВАРИАНТОВ_МАКС) {
			скажи('число-вариантов', `${где}: вариантов ответа ${варианты.length}, нужно от ${ВАРИАНТОВ_МИН} до ${ВАРИАНТОВ_МАКС}.`);
		}
		варианты.forEach((о, j) => {
			if (!текст(о?.text)) скажи('текст-варианта', `${где}, вариант ${j + 1}: нет текста варианта.`);
		});
	});

	// ── Викторина ───────────────────────────────────────────────────────────
	if (тип === 'quiz') {
		вопросы.forEach((в, i) => {
			const верных = список(в?.options).filter((о) => о?.correct === true || о?.correct === 'true').length;
			if (верных !== 1) {
				скажи('верный', `вопрос ${i + 1}: верных вариантов ${верных}, а нужен ровно один — поставьте галочку «Верный» одному варианту.`);
			}
		});

		const всего = вопросы.length;
		const кто = Array.from({ length: всего + 1 }, () => []);
		результаты.forEach((р, i) => {
			const имя = `результат ${i + 1}${текст(р?.title) ? ` «${текст(р.title)}»` : ''}`;
			const от = целое(р?.from);
			const до = целое(р?.to);
			if (от === null || до === null) {
				скажи('диапазон', `${имя}: не заполнено «${от === null ? 'От' : 'До'}» — у викторины у каждого результата есть диапазон верных ответов.`);
				return;
			}
			if (Number.isNaN(от) || Number.isNaN(до)) {
				скажи('диапазон', `${имя}: в «От» или «До» не целое число.`);
				return;
			}
			if (от > до) {
				скажи('диапазон', `${имя}: «От» (${от}) больше «До» (${до}).`);
				return;
			}
			if (от < 0 || до > всего) {
				скажи('диапазон', `${имя}: диапазон ${от}–${до} выходит за пределы 0–${всего} (вопросов ${всего}).`);
			}
			for (let n = Math.max(0, от); n <= Math.min(всего, до); n++) кто[n].push(текст(р?.title) || `результат ${i + 1}`);
		});

		// Дыры и пересечения считаем, только когда сами диапазоны целы:
		// иначе одна опечатка дала бы три сообщения об одном и том же.
		if (!беды.some((б) => б.код === 'диапазон') && результаты.length && всего) {
			const дыры = кто.map((к, n) => (к.length === 0 ? n : null)).filter((n) => n !== null);
			if (дыры.length) {
				скажи('покрытие', `ни один результат не покрывает счёт ${дыры.join(', ')} — диапазоны должны покрыть всё от 0 до ${всего} верных.`);
			}
			кто.forEach((к, n) => {
				if (к.length > 1) скажи('покрытие', `счёт ${n} попадает сразу в несколько результатов: ${к.map((т) => `«${т}»`).join(', ')}.`);
			});
		}
	}

	// ── Личностный ──────────────────────────────────────────────────────────
	if (тип === 'personality') {
		const заголовки = new Set(результаты.map((р) => текст(р?.title)).filter(Boolean));
		const получили = new Set();
		вопросы.forEach((в, i) => {
			список(в?.options).forEach((о, j) => {
				for (const куда of баллы(о?.scores)) {
					if (заголовки.has(куда)) получили.add(куда);
					else {
						скажи(
							'баллы',
							`вопрос ${i + 1}, вариант ${j + 1}: в «Баллах» стоит «${куда}», а такого результата в этом тесте нет — ` +
								'его переименовали или удалили. Выберите заново из списка.',
						);
					}
				}
			});
		});
		for (const заголовок of заголовки) {
			if (!получили.has(заголовок)) {
				скажи('недостижим', `результат «${заголовок}» не получает баллов ни от одного варианта — выпасть он не может.`);
			}
		}
	}

	return беды;
}

// ── Прогон ────────────────────────────────────────────────────────────────
if (import.meta.url.startsWith('file:') && process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const все = тесты();

	const кПоказу = [];
	const кПадению = [];
	for (const { файл, data } of все) {
		const кому = isPublished(data) ? кПадению : кПоказу;
		for (const б of бедыТеста(data)) кому.push(`«${текст(data.title)}» (${файл}): ${б.что}`);
	}

	// СЧЁТЧИК ОХВАТА: «бед нет» при нуле просмотренных тестов — не то же,
	// что «бед нет» при десяти. Число говорит, какое из двух.
	const опубликовано = все.filter(({ data }) => isPublished(data)).length;
	console.log(`[тесты] просмотрено тестов: ${все.length} (опубликовано ${опубликовано}, черновиков ${все.length - опубликовано}).`);

	for (const строка of кПоказу) console.log(`[тесты] ${строка} (черновик — сборку не роняю)`);

	let код = 0;
	if (кПадению.length) {
		console.error('');
		console.error(`[тесты] ОСТАНОВЛЕН: бед ${кПадению.length}. Выкладка не пойдёт, пока они есть.`);
		for (const строка of кПадению) console.error(`  ${строка}`);
		код = 1;
	} else {
		console.log('ок      Тесты: у опубликованных ошибок нет.');
	}

	if (process.argv.includes('--selftest')) код = Math.max(код, самопроверка());
	process.exitCode = код;
}

// ── Самопроверка ──────────────────────────────────────────────────────────
//
// Два здоровых теста обязаны пройти БЕЗ ЕДИНОЙ беды — иначе «поймал» ниже
// не значит ничего (урок CLAUDE.md: подлог, который пойман, ничего не значит,
// пока проверка не промолчала на здоровом). Дальше каждый подлог портит РОВНО
// ОДНО место здорового теста, как это и случится в жизни, и обязан быть пойман
// ИМЕННО своим правилом.
function самопроверка() {
	const викторина = () => ({
		category: 'test',
		test: {
			results: [
				{ title: 'Новичок', from: 0, to: 1 },
				{ title: 'Знаток', from: 2, to: 2 },
			],
			kind: {
				type: 'quiz',
				questions: [
					{ text: 'Кто?', images: [{ src: '/images/uploads/a.webp' }], options: [{ text: 'А', correct: true }, { text: 'Б', correct: false }] },
					{ text: 'Где?', options: [{ text: 'А' }, { text: 'Б', correct: true }] },
				],
			},
		},
	});
	const личностный = () => ({
		category: 'test',
		test: {
			results: [{ title: 'Маг' }, { title: 'Воин' }],
			kind: {
				type: 'personality',
				questions: [
					{ text: 'Что возьмёте?', options: [{ text: 'Книгу', scores: ['Маг'], reply: 'Мудро' }, { text: 'Меч', scores: ['Воин'] }] },
					{ text: 'Куда пойдёте?', options: [{ text: 'В башню', scores: 'Маг' }, { text: 'В бой', scores: ['Воин', 'Маг'] }] },
				],
			},
		},
	});

	/** [что портим, ожидаемый код, порча]. Каждая трогает одно место. */
	const подлоги = [
		['вид не выбран', 'вид', викторина, (d) => delete d.test.kind.type],
		['неизвестный вид', 'вид', викторина, (d) => (d.test.kind.type = 'survey')],
		['нет вопросов', 'нет-вопросов', викторина, (d) => (d.test.kind.questions = [])],
		['нет результатов', 'нет-результатов', личностный, (d) => (d.test.results = [])],
		['у результата нет заголовка', 'заголовок-результата', личностный, (d) => (d.test.results[1].title = '')],
		['заголовок из одних эмодзи', 'адрес-результата', личностный, (d) => (d.test.results[1].title = '🔥🔥')],
		['два заголовка — один адрес', 'адрес-результата', викторина, (d) => (d.test.results[1].title = 'новичок!')],
		['у вопроса нет текста', 'текст-вопроса', викторина, (d) => (d.test.kind.questions[1].text = '')],
		['пять картинок', 'картинки', викторина, (d) => (d.test.kind.questions[0].images = Array(5).fill({ src: '/x.webp' }))],
		['картинка не выбрана', 'картинки', викторина, (d) => (d.test.kind.questions[0].images[0].src = '')],
		['один вариант', 'число-вариантов', личностный, (d) => d.test.kind.questions[0].options.pop()],
		['семь вариантов', 'число-вариантов', личностный, (d) => (d.test.kind.questions[0].options = Array(7).fill({ text: 'А', scores: ['Маг'] }))],
		['у варианта нет текста', 'текст-варианта', викторина, (d) => (d.test.kind.questions[0].options[1].text = '')],
		['два верных', 'верный', викторина, (d) => (d.test.kind.questions[0].options[1].correct = true)],
		['ни одного верного', 'верный', викторина, (d) => (d.test.kind.questions[1].options[1].correct = false)],
		['«До» пусто', 'диапазон', викторина, (d) => (d.test.results[1].to = '')],
		['буквы в «От»', 'диапазон', викторина, (d) => (d.test.results[1].from = 'abc')],
		['«От» больше «До»', 'диапазон', викторина, (d) => (d.test.results[1].from = 3)],
		['диапазон за пределами', 'диапазон', викторина, (d) => (d.test.results[1].to = 5)],
		['дыра в диапазонах', 'покрытие', викторина, (d) => (d.test.results[0].to = 0)],
		['диапазоны пересекаются', 'покрытие', викторина, (d) => (d.test.results[0].to = 2)],
		['баллы на чужой результат', 'баллы', личностный, (d) => (d.test.kind.questions[0].options[1].scores = ['Лучник'])],
		['результат без баллов', 'недостижим', личностный, (d) => d.test.results.push({ title: 'Лучник' })],
	];

	let плохо = 0;
	for (const [имя, d] of [['викторина', викторина()], ['личностный', личностный()]]) {
		const беды = бедыТеста(d);
		if (беды.length) {
			плохо++;
			console.log(` ПЛОХО  здоровый тест «${имя}» краснеет: ${беды.map((б) => б.что).join(' | ')}`);
		} else console.log(`  ок    здоровый тест «${имя}» проходит без бед`);
	}
	for (const [имя, код, образец, порча] of подлоги) {
		const d = образец();
		порча(d);
		const беды = бедыТеста(d);
		const своё = беды.filter((б) => б.код === код);
		if (своё.length) console.log(`  ок    подлог «${имя}» пойман: ${своё[0].что}`);
		else {
			плохо++;
			console.log(` ПЛОХО  подлог «${имя}» НЕ пойман правилом «${код}»${беды.length ? ` (поймано чужим: ${беды.map((б) => б.код).join(', ')})` : ''}`);
		}
	}

	// Порог «черновик — не падать» живёт в прогоне, а не в правилах, поэтому
	// и проверяется отдельно: тот же сломанный тест с галочкой «Черновик»
	// обязан считаться неопубликованным.
	const черновик = { ...викторина(), draft: true };
	if (isPublished(normalizeFrontmatter(черновик))) {
		плохо++;
		console.log(' ПЛОХО  черновик считается опубликованным — его ошибки уронили бы сборку');
	} else console.log('  ок    черновик не считается опубликованным — его ошибки только покажутся');

	console.log(плохо ? ` ПЛОХО  самопроверка: провалов ${плохо}` : `ок      Самопроверка тестов: ${подлоги.length} подлогов пойманы своими правилами, здоровые молчат.`);
	return плохо ? 1 : 0;
}
