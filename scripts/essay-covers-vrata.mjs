// КАДРЫ С ЮТЮБА ДЕВЯТИ ОПУБЛИКОВАННЫМ ВИДЕОЭССЕ СЕРИИ «ВРАТА АНИМЕ».
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ, ЕСЛИ ЭТО УЖЕ УМЕЕТ ЗАДАЧА 19. Умеет, но только
// с ЧЕРНОВИКАМИ: у `archive-youtube-embed.mjs` вторым условием отбора стоит
// `if (!post.draft) continue`. Эти девять были опубликованы к тому моменту
// и потому не попали в план — не по ошибке, а по устройству того прогона.
// Ещё он требует выгрузку канала (`--videos yt.json`) и ищет ролик по
// названию; здесь ни то ни другое не нужно: адрес ролика лежит в самом
// материале блоком `::video{youtube="…"}`, у всех девяти ровно по одному.
//
// СВОИХ ПРАВИЛ ЗДЕСЬ НЕТ НИ ОДНОГО. Какой кадр брать (`fetchThumb`) и как
// вписать строку в шапку (`setCover`) — обе зовутся из задачи 19, а не
// переписаны рядом. Копия правила «первый кадр тяжелее 10 КБ» разошлась бы
// с оригиналом молча, и в репозиторий уехала бы серая заглушка ютюба,
// которая на сайте выглядит настоящей обложкой.
//
// СПИСОК ЗАКРЫТЫЙ И ПОИМЁННЫЙ, А НЕ ПРАВИЛО «ВСЕ ВИДЕОЭССЕ БЕЗ ОБЛОЖКИ».
// Правило однажды разбредётся по архиву и тронет материал, которого автор
// намеренно оставил без картинки; девять имён тронуть больше девяти не могут.
// Пропал кто-то из списка — скрипт ПАДАЕТ и называет его, а не делает восемь
// из девяти молча.
//
// ОБЛОЖКА В ТЕКСТ НЕ ПОЛЕЗЕТ: `remark-lead-cover` выходит сразу для
// `videoessay` (`CATEGORIES_WITH_OWN_HERO`) — в начале материала остаётся
// ролик. Проверено кодом ещё в задаче 19, здесь только повторено.
//
// Запуск:
//   node scripts/essay-covers-vrata.mjs           ← показать план, ничего не менять
//   node scripts/essay-covers-vrata.mjs --write   ← скачать кадры и вписать обложки

import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { POSTS_DIR } from './archive-clean-lib.mjs';
import { fetchThumb, setCover } from './archive-youtube-embed.mjs';

/**
 * СЕРИЯ «ВРАТА АНИМЕ», ВЫПУСКИ 1–9. Замер 31 августа 2026: это ВСЕ видеоэссе
 * архива без своего кадра — остальным 28 кадр поставила задача 19. Совпадение
 * не случайное: девять «Врат» опубликованы раньше, чем тот прогон случился.
 */
const IDS = ['ep-35', 'ep-36', 'ep-37', 'ep-39', 'ep-42', 'ep-49', 'ep-54', 'ep-63', 'ep-67'];

const UPLOADS = new URL('../public/images/uploads/', import.meta.url);

/**
 * Идентификатор ролика из любой из трёх форм адреса, которые встречаются
 * в архиве: `youtu.be/ID`, `youtube.com/watch?v=ID`, `/embed/ID`. Хвост
 * `?si=…` у ссылок «поделиться» отбрасывается сам — он идёт после id.
 */
function videoIdOf(url) {
	return /(?:youtu\.be\/|[?&]v=|\/embed\/)([\w-]{11})/.exec(String(url ?? ''))?.[1] ?? null;
}

/** Шапка и тело порознь: правим только шапку, тело возвращаем байт в байт. */
function splitPost(raw) {
	const m = /^(---\r?\n[\s\S]*?\r?\n---)([\s\S]*)$/.exec(raw);
	return m ? { head: m[1], body: m[2] } : null;
}

async function собратьПлан() {
	const план = [];
	const беды = [];

	for (const id of IDS) {
		const файл = new URL(`${id}.md`, POSTS_DIR);

		let raw;
		try {
			raw = await readFile(файл, 'utf8');
		} catch {
			беды.push(`${id}: файла больше нет — список протух, разбирать руками`);
			continue;
		}

		const части = splitPost(raw);
		if (!части) {
			беды.push(`${id}: не разобрал шапку материала`);
			continue;
		}

		const url = /::video\{[^\n]*youtube="([^"]*)"/.exec(части.body)?.[1];
		const vid = videoIdOf(url);
		if (!vid) {
			беды.push(`${id}: в тексте нет разобранного ролика ютюба (нашлось: ${url ?? '—'})`);
			continue;
		}

		// setCover сама откажется, если обложка уже стоит рукой, — спрашиваем
		// ЕЁ, а не смотрим на поле своими глазами: правило одно, и живёт оно там.
		const имя = `yt-${vid}.jpg`;
		const голова = setCover(части.head, `/images/uploads/${имя}`);
		if (!голова) {
			беды.push(`${id}: обложка уже задана рукой — не трогаю`);
			continue;
		}

		let ужеЕсть = false;
		try {
			await stat(new URL(имя, UPLOADS));
			ужеЕсть = true;
		} catch {
			// файла нет — обычное состояние, за ним и идём
		}

		план.push({ id, vid, имя, файл, головаБыла: части.head, голова, тело: части.body, ужеЕсть });
	}

	return { план, беды };
}

async function main() {
	const пишем = process.argv.includes('--write');
	const { план, беды } = await собратьПлан();

	for (const p of план) {
		console.log(`${p.id}  ролик ${p.vid}  →  public/images/uploads/${p.имя}${p.ужеЕсть ? ' (файл уже лежит, перезапишу)' : ''}`);
		const было = p.головаБыла.split('\n');
		console.log(`      в шапку: + ${p.голова.split('\n').find((l, i) => l !== было[i])}`);
	}

	if (беды.length) {
		console.log(`\nНЕ ВЫЙДЕТ у ${беды.length}:`);
		for (const б of беды) console.log(`  ${б}`);
	}

	// ЗАСЛОН СТОИТ ПЕРЕД ЗАПИСЬЮ, А НЕ ПОСЛЕ. Список закрытый и поимённый:
	// если хоть один из девяти не разобрался, это не «сделаем восемь», а повод
	// остановиться и посмотреть. Половина сделанной работы над опубликованными
	// материалами хуже несделанной — искать потом, кому поставили, а кому нет.
	if (беды.length) {
		console.error('\nОСТАНОВЛЕН: список поимённый, делаю его целиком или не делаю вовсе.');
		process.exit(1);
	}

	if (!пишем) {
		console.log(`\nПлан на ${план.length} материалов. Ничего не записано — для записи добавьте --write`);
		return;
	}

	await mkdir(UPLOADS, { recursive: true });

	// СНАЧАЛА КАЧАЕМ ВСЁ, ПОТОМ ПИШЕМ ВСЁ. Кадр может не отдаться серединой
	// прогона; запиши мы шапки по ходу — часть материалов ссылалась бы
	// на картинку, которой нет, и сборка показала бы битую обложку.
	const кадры = [];
	for (const p of план) {
		const кадр = await fetchThumb(p.vid);
		if (!кадр) {
			console.error(`ОСТАНОВЛЕН: у ${p.id} (ролик ${p.vid}) годного кадра нет ни в одном размере. Не записано НИЧЕГО.`);
			process.exit(1);
		}
		кадры.push({ p, кадр });
		console.log(`  скачан ${p.id}: ${кадр.name}, ${Math.round(кадр.buf.length / 1024)} КБ`);
	}

	for (const { p, кадр } of кадры) {
		await writeFile(new URL(p.имя, UPLOADS), кадр.buf);
		await writeFile(p.файл, p.голова + p.тело, 'utf8');
	}

	console.log(`\nЗАПИСАНО: кадров ${кадры.length}, обложек вписано ${кадры.length}`);
	console.log('Повторный прогон обязан сказать «обложка уже задана рукой» про все девять.');
}

await main();
