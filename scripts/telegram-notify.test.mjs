// ПИСЬМО РОБОТА ТЕЛЕГРАМА ГОВОРИТ ПРАВДУ: ВОСПРОИЗВЕДЕНИЕ 25 АВГУСТА.
//
//   node scripts/telegram-notify.test.mjs
//   node scripts/telegram-notify.test.mjs --подлог
//
// ЧТО СЛУЧИЛОСЬ 25 АВГУСТА 2026. В 14:02 UTC заказчику пришло зелёное письмо
// «🟢 Новые посты из канала — 📥 забрано новых постов: 0». Робот сходил в канал,
// ничего не нашёл, но всё равно записал закладку «докуда дошёл»
// (`src/data/telegramFeed.mjs`, там время захода — оно новое всегда), закладка
// попала в коммит, а письмо шло на ЛЮБОЙ коммит. Число же считало файлы постов
// и честно показывало ноль. Письмо о новостях, приходящее в тишину, через
// неделю перестают открывать вместе с настоящими.
//
// И ВТОРАЯ ПОЛОВИНА, ХУЖЕ ПЕРВОЙ. Замечания робота («бот молчит двенадцатый
// день», «бот пропустил посты, добрал со страницы канала») прицеплялись только
// к письму о новых постах. То есть письмо «кажется, бота выкинули из канала»
// не могло прийти НИКОГДА: постов в этот момент как раз и нет. В воркфлоу
// на GitHub этот шаг стоял с `if: always()` — при переезде на сервер условие
// потерялось.
//
// ЧТО ПРОВЕРЯЕТСЯ. Из hetzner/run-telegram.sh вынимаются ДВА НАСТОЯЩИХ блока —
// «закладка не новость» и «какое письмо» — и гоняются: первый в песочнице
// из живых git-репозиториев (голый «GitHub» и клон робота), второй с заглушкой
// вместо отправки в телеграм.
//
// ПОЧЕМУ ЭТО НЕ «ВЕЧНОЗЕЛЁНАЯ» ПРОВЕРКА. Ключ `--подлог` возвращает обоим
// блокам ПРЕЖНИЙ текст, и проверка обязана покраснеть дважды: зелёным письмом
// с нулём постов и пропавшим замечанием.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, readFileSync, writeFileSync, mkdirSync, existsSync, chmodSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const SCRIPT = join(ROOT, 'hetzner/run-telegram.sh');

/**
 * Текст блока — из самого робота, а не переписанный рядом: копия разошлась бы
 * с первой же правкой, и проверка сторожила бы себя, а не робота.
 */
export function читатьБлок(текст, имя) {
	const от = текст.indexOf(`# ─── начало блока «${имя}»`);
	const до = текст.indexOf(`# ─── конец блока «${имя}»`);
	if (от < 0 || до < 0) return null;
	return текст.slice(текст.indexOf('\n', от), до);
}

const git = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });

const положить = (repo, путь, текст) => {
	const файл = join(repo, путь);
	mkdirSync(dirname(файл), { recursive: true });
	writeFileSync(файл, текст, 'utf8');
};

const ЗАКЛАДКА = 'src/data/telegramFeed.mjs';

/**
 * Блок «закладка не новость» в песочнице из настоящих репозиториев.
 *
 * @param {'закладка'|'закладка и пост'|'ничего'} что — что робот привёз.
 * @param {string} блок — текст блока (прежний, если подлог).
 * @returns {{новость: string, имяКоммита: string, вывод: string}}
 */
function прогонКоммита(что, блок) {
	const box = mkdtempSync(join(tmpdir(), 'baka-tg-notify-'));
	try {
		const seed = join(box, 'seed');
		const bare = join(box, 'github.git');
		mkdirSync(seed, { recursive: true });
		git(seed, 'init', '--initial-branch=main');
		git(seed, 'config', 'user.name', 'заказчик');
		git(seed, 'config', 'user.email', 'owner@example.com');
		положить(seed, ЗАКЛАДКА, 'export const telegramFeed = {"lastRunAt": "вчера"};\n');
		// Папка постов заведена заранее: у робота `git add` стоит с `2>/dev/null`,
		// и на пустом месте он молчит, а песочница обязана быть похожей на жизнь.
		положить(seed, 'src/content/posts/старый-пост.md', '---\ntitle: Старый\n---\n');
		git(seed, 'add', '-A');
		git(seed, 'commit', '-m', 'Начало');
		git(box, 'clone', '--bare', seed, bare);

		const robot = join(box, 'robot');
		git(box, 'clone', bare, robot);
		git(robot, 'config', 'user.name', 'baka-telegram-bot');
		git(robot, 'config', 'user.email', 'actions@users.noreply.github.com');

		// Робот отработал: закладку он переписывает ВСЕГДА, пост — если нашёл.
		if (что !== 'ничего') положить(robot, ЗАКЛАДКА, 'export const telegramFeed = {"lastRunAt": "сегодня"};\n');
		if (что === 'закладка и пост') положить(robot, 'src/content/posts/новый-пост.md', '---\ntitle: Новый\ndraft: true\n---\n');
		git(robot, 'add', 'src/content/posts', ЗАКЛАДКА);

		const сценарий = [
			'set -u',
			'ERRORS=""',
			'fail() { ERRORS="${ERRORS}${1}"; echo "!!! $1"; }',
			блок,
			'echo "НОВОСТЬ=[$NEWS]"',
			`echo "ОШИБКИ=[$ERRORS]"`,
			"git log -1 --format='КОММИТ=[%s]'",
		].join('\n');
		const вывод = execFileSync('bash', ['-c', сценарий], { cwd: robot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
		const взять = (имя) => (вывод.match(new RegExp(`${имя}=\\[([^\\]]*)\\]`)) ?? [, ''])[1];
		return { новость: взять('НОВОСТЬ'), ошибки: взять('ОШИБКИ'), имяКоммита: взять('КОММИТ'), вывод };
	} finally {
		rmSync(box, { recursive: true, force: true });
	}
}

/**
 * Блок «какое письмо» с заглушкой вместо телеграма.
 *
 * @returns {{письмо: string, код: number}}
 */
function прогонПисьма({ ошибки = '', новость = '', замечания = '' }, блок) {
	const box = mkdtempSync(join(tmpdir(), 'baka-tg-letter-'));
	try {
		const стук = join(box, 'письмо.txt');
		const заглушка = join(box, 'notify.sh');
		writeFileSync(заглушка, `#!/bin/bash\nprintf '%s' "$1" > ${стук}\n`, 'utf8');
		chmodSync(заглушка, 0o755);

		const сценарий = [
			'set -u',
			`NOTIFY=${заглушка}`,
			`STAMP="2026-08-25 14:02 UTC"`,
			`LOG=/root/baka-logs/telegram.log`,
			`ERRORS=${JSON.stringify(ошибки)}`,
			`NEWS=${JSON.stringify(новость)}`,
			`DETAILS=${JSON.stringify(замечания)}`,
			блок,
		].join('\n');
		let код = 0;
		try {
			execFileSync('bash', ['-c', сценарий], { cwd: box, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
		} catch (err) {
			код = err.status ?? 1;
		}
		return { письмо: existsSync(стук) ? readFileSync(стук, 'utf8') : '', код };
	} finally {
		rmSync(box, { recursive: true, force: true });
	}
}

// ─── Прогон ────────────────────────────────────────────────────────────────

const подлог = process.argv.includes('--подлог') || process.argv.includes('--selftest');
const беды = [];
const ок = (строка) => console.log(`  ✓ ${строка}`);
const плохо = (строка) => {
	беды.push(строка);
	console.log(`  ✗ ${строка}`);
};

const текст = readFileSync(SCRIPT, 'utf8');

// Прежние тексты обоих блоков — дословно, как они стояли до 25 августа.
const ПРЕЖНИЙ_КОММИТ = `
NEWS=""
if git diff --cached --quiet; then
	echo "новых постов в канале нет"
else
	COUNT=$(git diff --cached --name-only -- src/content/posts | wc -l | tr -d ' ')
	git commit -m "Забрать новые посты из телеграма" || fail "коммит не прошёл"
	git pull --rebase --quiet origin main || fail "pull --rebase перед пушем не прошёл"
	if git push --quiet; then
		echo "запушено, новых файлов постов: $COUNT"
		NEWS="📥 забрано новых постов: \${COUNT}"
	else
		fail "ПУШ НЕ ПРОШЁЛ — посты забраны, но на GitHub не уехали"
	fi
fi
`;
const ПРЕЖНЕЕ_ПИСЬМО = `
if [ -n "$ERRORS" ]; then
	"$NOTIFY" "$(printf '🔴 Забор постов не доделан\\n%s\\n\\n%b' "$STAMP" "$ERRORS")"
	exit 1
elif [ -n "$NEWS" ]; then
	"$NOTIFY" "$(printf '🟢 Новые посты из канала\\n%s\\n\\n%s\\n%s' "$STAMP" "$NEWS" "$DETAILS")"
else
	echo "=== ИТОГ: новостей нет ==="
fi
`;

if (подлог) {
	console.log('=== ПОДЛОГ: роботу возвращены ПРЕЖНИЕ правила ===\n');

	const r = прогонКоммита('закладка', ПРЕЖНИЙ_КОММИТ);
	if (r.новость.includes('0')) ок(`робот объявил новостью пустой заход: «${r.новость}» — ровно как 25 августа в 14:02`);
	else плохо(`робот НЕ соврал даже по прежнему правилу (новость «${r.новость}») — песочница не воспроизводит поломку`);

	const п = прогонПисьма({ замечания: '**Бот молчит 12 дней.**' }, ПРЕЖНЕЕ_ПИСЬМО);
	if (!п.письмо) ок('замечание без новых постов не ушло никуда — «бота выкинули из канала» заказчик бы не узнал');
	else плохо('замечание ушло письмом и по прежнему правилу — песочница не воспроизводит поломку');
} else {
	console.log('=== ПИСЬМО РОБОТА ТЕЛЕГРАМА ГОВОРИТ ПРАВДУ ===\n');

	const блокКоммита = читатьБлок(текст, 'закладка не новость');
	const блокПисьма = читатьБлок(текст, 'какое письмо');

	if (!блокКоммита || !блокПисьма) {
		плохо('в hetzner/run-telegram.sh нет размеченных блоков — проверять нечего');
	} else {
		const пусто = прогонКоммита('закладка', блокКоммита);
		if (!пусто.новость) ок('заход без новых постов новостью не объявлен — зелёного письма не будет');
		else плохо(`заход без постов объявлен новостью: «${пусто.новость}» — вернулось письмо 25 августа`);
		if (пусто.имяКоммита.includes('Отметка')) ок(`закладка уехала своим именем: «${пусто.имяКоммита}»`);
		else плохо(`закладка коммитится как забор постов: «${пусто.имяКоммита}» — история врёт про новые посты`);
		if (!пусто.ошибки) ок('закладка всё-таки запушена и без ошибок — телеграм не отдаст те же обновления заново');
		else плохо(`закладка не уехала: ${пусто.ошибки}`);

		const есть = прогонКоммита('закладка и пост', блокКоммита);
		if (есть.новость.includes('1')) ок(`настоящий пост объявлен новостью: «${есть.новость}»`);
		else плохо(`настоящий пост НЕ объявлен новостью («${есть.новость}») — заказчик не узнает о черновике`);
		if (есть.имяКоммита.includes('Забрать новые посты')) ок(`коммит с постом назван по-прежнему: «${есть.имяКоммита}»`);
		else плохо(`коммит с постом назван «${есть.имяКоммита}»`);

		const тишина = прогонКоммита('ничего', блокКоммита);
		if (!тишина.новость) ок('заход, где не поменялось вообще ничего, молчит');
		else плохо('пустой заход что-то объявил новостью');

		const красное = прогонПисьма({ ошибки: 'ПУШ НЕ ПРОШЁЛ' }, блокПисьма);
		if (красное.письмо.includes('🔴')) ок('сбой — красное письмо');
		else плохо('сбой остался без письма');
		if (красное.код === 1) ок('при сбое робот выходит кодом 1 — systemd запишет заход неудачным');
		else плохо(`при сбое робот вышел кодом ${красное.код}`);

		const зелёное = прогонПисьма({ новость: '📥 забрано новых постов: 2' }, блокПисьма);
		if (зелёное.письмо.includes('🟢') && зелёное.письмо.includes('2')) ок('новые посты — зелёное письмо с их числом');
		else плохо('о новых постах не сказано');

		const жёлтое = прогонПисьма({ замечания: '**Бот молчит 12 дней.** Проверьте, стоит ли бот в администраторах канала.' }, блокПисьма);
		if (жёлтое.письмо.includes('Бот молчит')) ок('замечание БЕЗ новых постов доехало письмом — «бота выкинули из канала» больше не пропадает');
		else плохо('замечание без новых постов не ушло никуда — вернулась потеря при переезде с GitHub');
		if (жёлтое.код === 0) ок('замечание уходит кодом 0 — это не сбой робота, и красного письма не будет');
		else плохо(`замечание вышло кодом ${жёлтое.код} — заход объявлен сбойным там, где сбоя нет`);

		const прицеп = прогонПисьма({ новость: '📥 забрано новых постов: 1', замечания: '**Бот пропустил 1 пост.**' }, блокПисьма);
		if (прицеп.письмо.includes('Бот пропустил')) ок('замечание ВМЕСТЕ с постами приезжает прицепом, а не отдельным письмом');
		else плохо('замечание потерялось, хотя посты приехали');

		const молчание = прогонПисьма({}, блокПисьма);
		if (!молчание.письмо) ок('сказать нечего — письма нет вовсе');
		else плохо(`письмо ушло в пустоту: «${молчание.письмо.slice(0, 60)}»`);
	}
}

console.log('');
if (беды.length) {
	console.log(`ПРОВЕРКА НЕ ПРОШЛА: ${беды.length}.`);
	process.exit(1);
}
