// ЖИРНЫЙ В ЗАГОЛОВКЕ — ОДИН ОТВЕТ У ВСЕХ ТРОИХ.
//
//   node scripts/heading-bold.test.mjs             — спросить
//   node scripts/heading-bold.test.mjs --selftest  — плюс подлог: прежнее правило
//
// ЗАЧЕМ. Правило заказчика одно («жирного внутри заголовка не бывает»,
// 12 августа 2026), а отвечали на него по-разному: `archive-headings.mjs`
// смотрел только верхний уровень дерева и заголовок внутри цитаты не трогал,
// `archive-subheads.mjs` обходил дерево целиком и трогал. Какой ответ
// сработает, решал запуск (доревизия задачи 15, находка 36).
//
// ЗАОДНО ОНИ РАСХОДИЛИСЬ И ВТОРЫМ ОБРАЗОМ, КОТОРОГО РЕЕСТР НЕ НАЗЫВАЛ:
// первый снимал жирный ЛЮБОЙ («### Часть **жирная**, часть нет»), второй —
// только у заголовка, жирного целиком.
//
// ЧТО СПРАШИВАЕТСЯ. Не «правильно ли снят жирный» (это решает сам заказчик,
// и подлоги на это стоят в каждом скрипте), а «ОДИН ЛИ ОТВЕТ у троих»:
// у разовой правки заголовков, у разовой правки подзаголовков и у проверки,
// которая теперь идёт в `npm run build`.
import { fixBody } from './archive-headings.mjs';
import { planSubheads } from './archive-subheads.mjs';
import { жирныеЗаголовки } from './check-heading-bold.mjs';
import { планСнятияЖирного } from './heading-bold.mjs';
import { readPostsRaw, parseBody } from './archive-clean-lib.mjs';

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

// Образцы: сперва то, ради чего правило заведено, потом краевые случаи,
// потом то, чего трогать нельзя.
const ОБРАЗЦЫ = [
	['### **Весь заголовок жирный**', 'заголовок целиком жирный'],
	['### Часть **жирная**, часть нет', 'жирный кусок внутри заголовка'],
	['### **Два** слова **жирных**', 'два жирных куска в одном заголовке'],
	['### __Подчёркиванием__', 'жирный записан подчёркиваниями'],
	['## **Второй уровень**', 'уровень заголовка сохраняется'],
	['#### **Как отличить эти работы?** ', 'хвостовой пробел за заголовком'],
	['### [**жирная ссылка**](https://x.ru)', 'жирный внутри ссылки в заголовке'],
	['> ### **в цитате**', 'ЗАГОЛОВОК ВНУТРИ ЦИТАТЫ — на нём и расходились'],
	['- ### **в пункте списка**', 'заголовок внутри пункта списка'],
	[':::spoiler{noun="кусок"}\n### **в спойлере**\n:::', 'заголовок внутри спойлера'],
	['### **Первый жирный**\n\nТекст.\n\n### **Второй жирный**', 'два жирных заголовка в одном теле'],
	['### Обычный заголовок', 'чистый заголовок — трогать нечего'],
	['текст **жирный** в абзаце', 'жирный в абзаце — не наше дело'],
	['### Заголовок с *курсивом*', 'курсив в заголовке'],
	['`### **код**`', 'решётка и звёздочки внутри кода'],
	['    ### **отступом**', 'блок с отступом — это код'],
];

console.log('ЖИРНЫЙ В ЗАГОЛОВКЕ: правка заголовков, правка подзаголовков и проверка сборки — один ответ.');
console.log();

for (const [образец, зачем] of ОБРАЗЦЫ) {
	const тело = `\n${образец}\n`;

	// 1. Разовая правка заголовков.
	const заголовки = fixBody(тело)?.body ?? тело;
	// 2. Разовая правка подзаголовков — в режиме опубликованного поста,
	//    где она правит ТОЛЬКО заголовки и абзацев не трогает.
	const подзаголовки = planSubheads(тело, {}, { onlyHeadings: true }).body;
	// 3. Проверка сборки: она не правит, а считает, — сверяем через «нашла ли».
	const нашлаСборка = жирныеЗаголовки([{ id: 'подлог', draft: false, front: {}, body: тело }]).length > 0;

	const сошлись = заголовки === подзаголовки;
	const тронуто = заголовки !== тело;
	const согласнаСборка = нашлаСборка === тронуто;

	скажи(сошлись && согласнаСборка, `${зачем}${тронуто ? '' : ' (не трогаем)'}`);
	if (!сошлись) {
		console.log(`          заголовки:    ${JSON.stringify(заголовки)}`);
		console.log(`          подзаголовки: ${JSON.stringify(подзаголовки)}`);
	}
	if (!согласнаСборка) console.log(`          проверка сборки говорит «${нашлаСборка ? 'нашла' : 'чисто'}», а правка ${тронуто ? 'тронула' : 'не тронула'}`);
}

// ── ЖИВЫЕ ДАННЫЕ ──────────────────────────────────────────────────────────
// Числа СЧИТАЮТСЯ, а не пишутся: вписанное руками устаревает от первой же
// правки заказчика в админке.
console.log();
console.log('── живой архив ──');
const posts = await readPostsRaw();
const поПравке = posts.filter((p) => !p.draft && fixBody(p.body)).length;
const поПроверке = new Set(жирныеЗаголовки(posts).map((х) => х.id)).size;
скажи(поПравке === поПроверке, `опубликованных постов с жирным в заголовке: правка ${поПравке}, проверка сборки ${поПроверке}`);

// ── ПОДЛОГ ────────────────────────────────────────────────────────────────
// Подлог возвращает ПРЕЖНЕЕ правило — то, что жило в archive-headings.mjs:
// только верхний уровень дерева. Оно обязано разойтись с нынешним ровно там,
// где расходились скрипты, и совпасть там, где они и раньше сходились.
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── ПОДЛОГ: прежнее правило (только верхний уровень дерева) ──');

	const прежнееПравило = (тело) => {
		const дерево = parseBody(тело);
		const верхние = { children: (дерево.children ?? []).filter((b) => b.type === 'heading') };
		return планСнятияЖирного(верхние, тело).заголовки.length;
	};

	const вЦитате = '\n> ### **в цитате**\n';
	скажи(
		прежнееПравило(вЦитате) === 0 && планСнятияЖирного(parseBody(вЦитате), вЦитате).заголовки.length === 1,
		`заголовок в цитате: прежнее правило видело ${прежнееПравило(вЦитате)}, нынешнее видит ${планСнятияЖирного(parseBody(вЦитате), вЦитате).заголовки.length}`,
	);

	// И ВТОРАЯ ПОЛОВИНА: на обычном заголовке прежнее и нынешнее правило
	// обязаны совпасть, иначе «поймал» неотличимо от «ругается на всё подряд».
	const обычный = '\n### **Весь заголовок жирный**\n';
	скажи(
		прежнееПравило(обычный) === планСнятияЖирного(parseBody(обычный), обычный).заголовки.length,
		'на заголовке верхнего уровня прежнее и нынешнее правило согласны',
	);
}

console.log();
if (плохо) {
	console.log(`ПРОВАЛОВ: ${плохо}`);
	process.exit(1);
}
console.log(`Образцов ${ОБРАЗЦЫ.length}. Ответ один у всех троих.`);
