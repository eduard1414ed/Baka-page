// РОБОТЫ: ЧИТАЮТСЯ, УМЕЮТ СКАЗАТЬ О ПАДЕНИИ И НЕ ВИСЯТ БЕЗ КОНЦА.
//
//   node scripts/workflows.test.mjs             — спросить
//   node scripts/workflows.test.mjs --selftest  — плюс подлоги
//
// ЗАЧЕМ ТРИ ВОПРОСА СРАЗУ, И ПОЧЕМУ ОНИ РАЗНЫЕ.
//
//   1. ЧИТАЕТСЯ ЛИ YAML. Кривой файл робота GitHub просто не запускает —
//      молча, без письма и без строчки в интерфейсе.
//   2. СКАЖЕТ ЛИ РОБОТ, ЧТО УПАЛ. Письмо приходит, только когда робот САМ
//      решил, что есть о чём рассказать. Упал — файла-то он написать
//      не успел, и узнать об этом можно только зайдя и посмотрев
//      (ревизия задачи 15, находка 4).
//   3. ЕСТЬ ЛИ ПРЕДЕЛ ПО ВРЕМЕНИ. **Зависший робот НЕ ПАДАЕТ — он висит**,
//      и второго вопроса ему мало: письма не будет, потому что и падения нет.
//      За ним при этом стоит очередь (`cancel-in-progress: false`), то есть
//      один молчащий чужой сервер останавливает робота на сутки. Предел
//      GitHub по умолчанию — ШЕСТЬ ЧАСОВ (находка 5).
//
// ЧИСЛА ПРЕДЕЛОВ ЗДЕСЬ НЕ ПРОВЕРЯЮТСЯ, И ЭТО НАРОЧНО. Правильное число знает
// только замер, а он у каждого робота свой и записан в самом файле рядом
// с настройкой. Проверка сторожит другое: что предел ЕСТЬ и что он меньше
// шестичасового умолчания GitHub, — то есть что настройка вообще работает.
import { readdir, readFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..');
const ПАПКА = join(КОРЕНЬ, '.github', 'workflows');

/** Предел GitHub по умолчанию — шесть часов. Больше него настройка бессмысленна. */
const УМОЛЧАНИЕ_GITHUB = 6 * 60;

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

/**
 * Что не так с одним роботом.
 *
 * ВЫНЕСЕНО ФУНКЦИЕЙ РОВНО ЗАТЕМ, ЧТОБЫ ЕЁ МОЖНО БЫЛО УРОНИТЬ ПОДЛОГОМ:
 * проверка, которая на живых файлах не может провалиться, ничем не отличается
 * от сломавшейся — обе отвечают «всё хорошо».
 *
 * @param {string} имя как назвать робота в строчке беды
 * @param {string} текст содержимое файла
 * @returns {string[]} список бед; пусто — всё на месте
 */
export function бедыРобота(имя, текст) {
	let разобрано;
	try {
		разобрано = yaml.load(текст);
	} catch (ошибка) {
		return [`${имя}: файл не читается как YAML — ${String(ошибка.message).split('\n')[0]}`];
	}
	if (!разобрано?.jobs || typeof разобрано.jobs !== 'object') return [`${имя}: в файле нет ни одной задачи`];

	const беды = [];
	for (const [задача, тело] of Object.entries(разобрано.jobs)) {
		const предел = тело?.['timeout-minutes'];
		if (typeof предел !== 'number') {
			беды.push(`${имя}, задача «${задача}»: нет предела по времени — зависнув, робот будет висеть до шести часов`);
		} else if (предел <= 0 || предел >= УМОЛЧАНИЕ_GITHUB) {
			беды.push(`${имя}, задача «${задача}»: предел ${предел} мин бессмыслен — у GitHub и так ${УМОЛЧАНИЕ_GITHUB}`);
		}
	}

	// О ПАДЕНИИ РОБОТ ГОВОРИТ ТРЕМЯ СПОСОБАМИ, И ВСЕ ТРИ ЗАКОННЫ: шагом
	// `if: failure()`, шагом `if: always()` с заголовком по исходу и письмом,
	// которое спрашивает `steps.…outcome`. Первая версия проверки знала два
	// из трёх и объявила бедой применение решений по кандидатам — а у того
	// заголовок письма как раз и различает «применены», «не применились»
	// и «робот не дошёл до работы». **Признак, знающий не все законные формы,
	// врёт в сторону «сломано», и чинить по нему пошли бы здорового.**
	//
	// СПРАШИВАЕТСЯ ПО СУЩЕСТВУ, А НЕ ПО ФОРМЕ: есть ли шаг, который выполнится
	// ДАЖЕ ПРИ ПАДЕНИИ, и заводит ли этот робот задачу на GitHub (это и есть
	// письмо заказчику). Одного условия мало: `always()` без письма — это шаг
	// уборки, а не рассказ.
	const выполнитсяПриПадении = /if:\s*(failure|always)\(\)/.test(текст);
	const заводитПисьмо = /gh issue create/.test(текст);
	if (!выполнитсяПриПадении || !заводитПисьмо) {
		беды.push(
			`${имя}: упав, ничего не скажет — ` +
				`${выполнитсяПриПадении ? 'шаг при падении есть' : 'нет шага с if: failure()/always()'}, ` +
				`${заводитПисьмо ? 'письмо заводится' : 'письма (gh issue create) нет'}`,
		);
	}

	return беды;
}

console.log('РОБОТЫ: читаются, говорят о падении, не висят без конца.');
console.log();

const файлы = (await readdir(ПАПКА)).filter((имя) => имя.endsWith('.yml') || имя.endsWith('.yaml'));
console.log(`Роботов на проверке: ${файлы.length}`);
console.log();

for (const имя of файлы) {
	const текст = await readFile(join(ПАПКА, имя), 'utf8');
	const беды = бедыРобота(имя, текст);
	const разобрано = yaml.load(текст);
	const пределы = Object.values(разобрано.jobs ?? {})
		.map((з) => з?.['timeout-minutes'])
		.join(', ');
	скажи(беды.length === 0, `${имя.padEnd(30)} предел ${String(пределы).padStart(3)} мин`);
	for (const беда of беды) console.log(`          ${беда}`);
}

// ── ПОДЛОГИ ───────────────────────────────────────────────────────────────
// Подлог СОЗДАЁТ беду, а не меняет её во всех файлах разом: общая подмена
// расхождения не создаёт и не ловится (CLAUDE.md).
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── ПОДЛОГИ ──');

	const здоровый = [
		'name: Робот',
		'on:',
		'  workflow_dispatch:',
		'jobs:',
		'  x:',
		'    runs-on: ubuntu-latest',
		'    timeout-minutes: 20',
		'    steps:',
		'      - run: echo привет',
		'      - name: Сказать, если робот упал',
		'        if: failure()',
		'        run: gh issue create --title упал',
		'',
	].join('\n');

	скажи(бедыРобота('здоровый', здоровый).length === 0, 'на здоровом роботе проверка молчит');

	const безПредела = здоровый.replace('    timeout-minutes: 20\n', '');
	const бедыБезПредела = бедыРобота('без предела', безПредела);
	скажи(бедыБезПредела.some((б) => б.includes('нет предела')), `робот без предела пойман: ${бедыБезПредела[0] ?? '(не пойман)'}`);

	const безШага = здоровый.replace('        if: failure()\n', '        if: success()\n');
	const бедыБезШага = бедыРобота('без шага при падении', безШага);
	скажи(бедыБезШага.some((б) => б.includes('ничего не скажет')), 'робот без шага, выполняющегося при падении, пойман');

	// ОДНОГО УСЛОВИЯ МАЛО: `always()` без письма — это шаг уборки, а не рассказ.
	const безПисьма = здоровый.replace('        run: gh issue create --title упал\n', '        run: rm -f report.txt\n');
	const бедыБезПисьма = бедыРобота('без письма', безПисьма);
	скажи(бедыБезПисьма.some((б) => б.includes('письма')), 'шаг при падении БЕЗ письма пойман');

	const бессмысленный = здоровый.replace('timeout-minutes: 20', 'timeout-minutes: 600');
	скажи(
		бедыРобота('бессмысленный', бессмысленный).some((б) => б.includes('бессмыслен')),
		'предел больше шестичасового умолчания GitHub пойман',
	);

	const кривой = здоровый.replace('jobs:', 'jobs: : :');
	скажи(бедыРобота('кривой', кривой).length > 0, 'нечитаемый YAML пойман');

	// ВТОРОЙ ЗАКОННЫЙ СПОСОБ — `always()` с письмом, чей заголовок различает
	// исход. Так устроено применение решений по кандидатам, и первая версия
	// этой проверки объявила его бедой: признак знал не все формы.
	const черезAlways = здоровый.replace('        if: failure()\n', '        if: always()\n');
	скажи(бедыРобота('через always', черезAlways).length === 0, 'шаг `if: always()` с письмом — тоже ответ, проверка молчит');
}

console.log();
if (плохо) {
	console.log(`ПРОВАЛОВ: ${плохо}`);
	process.exit(1);
}
console.log('Все роботы читаются, у каждого есть предел и способ сказать о падении.');
