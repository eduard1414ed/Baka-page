//   node scripts/check-post-refs.mjs             — спросить
//   node scripts/check-post-refs.mjs --selftest  — плюс подлоги
//
// ПОЧЕМУ ОТДЕЛЬНЫМ СКРИПТОМ, А НЕ БРОСКОМ ОШИБКИ ИЗ ПЛАГИНА РАЗМЕТКИ.
// Потому что бросок сборку НЕ ОСТАНАВЛИВАЕТ — это замерено 31 августа 2026,
// а не предположено. Плагин бросил ошибку на материале с несуществующим
// адресом, и вот что вышло:
//
//   код возврата `astro build` — 0;
//   в логе — красная строка `[glob-loader] Error rendering …`;
//   страница построена, И ТЕКСТ МАТЕРИАЛА ПРОПАЛ С НЕЁ ЦЕЛИКОМ —
//   не только врезка, а оба абзаца вокруг неё.
//
// То есть загрузчик коллекции ловит ошибку разметки сам, отдаёт пустое тело
// и идёт дальше. Худший из возможных исходов: выкладка проходит, статья
// на сайте пустая, и узнать об этом можно только глазами.
//
// ОТСЮДА ДВА СЛЕДСТВИЯ, И ОБА ВАЖНЫ:
//   1) настоящий заслон — здесь, ПЕРЕД сборкой, с кодом возврата 1;
//   2) плагин разметки больше НЕ БРОСАЕТ. Он громко жалуется и убирает
//      один блок, оставляя текст статьи целым: если заслон почему-то обошли,
//      пропавший блок лучше пропавшей статьи.
//
// ЧЕРНОВИКИ НЕ РОНЯЮТ СБОРКУ, А ПОКАЗЫВАЮТСЯ ОТДЕЛЬНО. У черновика страницы
// нет, читателю его врезки не видны, и падать из-за неготового материала
// значило бы остановить весь сайт из-за чужой недоделки. Но и молчать нельзя:
// беда всплывёт ровно в минуту публикации.

import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import { normalizeFrontmatter } from '../src/lib/frontmatter.mjs';
import { isPublished } from '../src/lib/publishing.mjs';
import { canPlayInline, whyCannotPlay } from '../src/lib/postRef.mjs';
import { getYoutubeVideoId } from '../src/lib/youtube.mjs';
import { fetchFeedItems } from '../src/lib/podcastFeed.mjs';

const POSTS_DIR = new URL('../src/content/posts/', import.meta.url);

/** Врезка в теле: `::material{…}` отдельной строкой. */
const ВРЕЗКА = /^::material\{([^\n]*)\}\s*$/gm;

function атрибуты(строка) {
	const итог = {};
	const выражение = /([\w-]+)="((?:[^"])*)"/g;
	let m;
	while ((m = выражение.exec(строка))) итог[m[1]] = m[2].replaceAll('&quot;', '"');
	return итог;
}

function всеПосты() {
	const посты = new Map();
	for (const файл of readdirSync(fileURLToPath(POSTS_DIR))) {
		if (!файл.endsWith('.md')) continue;
		const сырое = readFileSync(fileURLToPath(new URL(файл, POSTS_DIR)), 'utf8');
		const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(сырое);
		if (!m) continue;
		const id = файл.replace(/\.md$/, '');
		посты.set(id, { id, файл: `src/content/posts/${файл}`, data: normalizeFrontmatter(yaml.load(m[1]) ?? {}), body: m[2] });
	}
	return посты;
}

/**
 * Все беды всех врезок архива.
 *
 * @param {Map<string, any>} посты
 * @param {Set<string>|null} вФиде guid выпусков, которые правда есть в RSS.
 *   `null` — фид не ответил, и про звук мы в этот раз ничего не спрашиваем:
 *   иначе моргнувшая сеть роняла бы выкладку по чужой причине. Пустой фид
 *   сборку и так остановит — этим занят scripts/check-players.mjs.
 */
export function бедыВрезок(посты, вФиде) {
	const беды = [];

	for (const пост of посты.values()) {
		const черновик = !isPublished(пост.data);

		for (const совпало of пост.body.matchAll(ВРЕЗКА)) {
			const атр = атрибуты(совпало[1]);
			const id = String(атр.id ?? '').trim();
			const режим = атр.mode === 'play' ? 'play' : 'link';
			const скажи = (что) => беды.push({ где: пост.файл, черновик, что });

			if (!id) {
				скажи('во врезке не выбран материал. Откройте её в админке и выберите, или уберите блок.');
				continue;
			}

			const цель = посты.get(id);
			if (!цель) {
				скажи(
					`материала «${id}» на сайте нет — файла src/content/posts/${id}.md не существует. ` +
						'Материал удалили, переименовали или в адресе опечатка. Выберите материал заново.',
				);
				continue;
			}

			if (режим === 'play' && !canPlayInline(цель)) {
				скажи(
					`у врезки на «${цель.data.title}» (${id}) выбрано «Играет здесь», а играть нечего: ` +
						`${whyCannotPlay(цель)}. Поставьте «Ведёт на материал».`,
				);
				continue;
			}

			if (режим === 'play' && цель.data.category === 'podcast' && вФиде && !вФиде.has(цель.data.audioGuid)) {
				скажи(
					`у врезки на «${цель.data.title}» (${id}) выбрано «Играет здесь», а звука нет: ` +
						'выпуск не нашёлся в RSS подкаста. Проверьте у материала поле «Выпуск в RSS».',
				);
				continue;
			}

			if (режим === 'play' && цель.data.category === 'videoessay') {
				const ролик = getYoutubeVideoId(/::video\{[^\n]*youtube="([^"]*)"/.exec(цель.body)?.[1] ?? '');
				if (!ролик) {
					скажи(
						`у врезки на «${цель.data.title}» (${id}) выбрано «Играет здесь», а ролика нет: ` +
							'в тексте видеоэссе не нашлось блока «Видео» со ссылкой на YouTube.',
					);
					continue;
				}
			}

			// НЕОПУБЛИКОВАННАЯ ЦЕЛЬ — НЕ ПОВОД РОНЯТЬ СБОРКУ. Снять материал
			// с публикации — обычная работа заказчика в админке, и падающая
			// от одной галочки выкладка была бы заслоном, который снимут вместе
			// с пользой. Но ссылка при этом ведёт в никуда, и сказать надо.
			if (!isPublished(цель.data) && !черновик) {
				беды.push({
					где: пост.файл,
					черновик: true,
					что: `врезка ведёт на «${цель.data.title}» (${id}), а он не опубликован — страницы на сайте нет, ссылка ведёт в никуда.`,
				});
			}
		}
	}

	return беды;
}

// ── Прогон ────────────────────────────────────────────────────────────────
if (import.meta.url.startsWith('file:') && process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const посты = всеПосты();
	const выпуски = await fetchFeedItems();
	const вФиде = выпуски.length ? new Set(выпуски.map((i) => i.guid)) : null;

	if (!вФиде) {
		console.log('[врезки] RSS не ответил — про звук в этот раз не спрашиваю. Пустой фид остановит сборку позже, на check-players.');
	}

	const все = бедыВрезок(посты, вФиде);
	const врезок = [...посты.values()].reduce((сумма, п) => сумма + [...п.body.matchAll(ВРЕЗКА)].length, 0);

	// СЧЁТЧИК ОХВАТА. «Пусто — бед нет» выглядит одинаково и когда бед правда
	// нет, и когда проверка не увидела НИ ОДНОЙ врезки. Второе уже случалось
	// в этом проекте шесть раз, и всегда в эту сторону.
	console.log(`[врезки] просмотрено материалов: ${посты.size}, врезок в них: ${врезок}.`);

	const кПоказу = все.filter((б) => б.черновик);
	const кПадению = все.filter((б) => !б.черновик);

	for (const б of кПоказу) console.log(`[врезки] ${б.где}: ${б.что} (материал не опубликован — сборку не роняю)`);

	if (кПадению.length) {
		console.error('');
		console.error(`[врезки] ОСТАНОВЛЕН: бед ${кПадению.length}. Выкладка не пойдёт, пока они есть.`);
		for (const б of кПадению) console.error(`  ${б.где}: ${б.что}`);
		process.exit(1);
	}

	console.log('ок      Врезки на материалы: все ведут на существующие материалы, «играет здесь» стоит только там, где есть что играть.');

	if (process.argv.includes('--selftest')) {
		// ПОДЛОГ РАЗВОДИТ ОДНУ ВРЕЗКУ, а не отменяет проверку целиком: так это
		// и случится в жизни — кто-то переименует один материал.
		const подложные = new Map(посты);
		подложные.set('проба-с-битой-врезкой', {
			id: 'проба-с-битой-врезкой',
			файл: 'src/content/posts/проба-с-битой-врезкой.md',
			data: { title: 'Проба', category: 'note', date: new Date() },
			body: '::material{id="ep-takogo-net"}\n',
		});
		const поймано = бедыВрезок(подложные, вФиде).filter((б) => !б.черновик);
		console.log(поймано.length ? '  ок    подлог «врезка на несуществующий материал» пойман' : ' ПЛОХО  подлог НЕ пойман — заслон слеп');
		if (!поймано.length) process.exit(1);

		// И ОБРАТНАЯ СТОРОНА: на здоровом архиве заслон обязан молчать. Иначе
		// «поймал» не значит ничего — он ловил бы всё подряд.
		console.log(все.filter((б) => !б.черновик).length === 0 ? '  ок    на живом архиве молчит' : ' ПЛОХО  краснеет на живом архиве');
	}
}
