// ЧТО ЗДЕСЬ ДЕРЖИТСЯ, И ПОЧЕМУ ЭТО НЕ ГИГИЕНА, А ОПЛАЧЕННОЕ ПРАВИЛО.
//
// 1. НИ ОДИН ШАГ ВЫКЛАДКИ НЕ ОБРЕЗАЕТСЯ ЧЕРЕЗ `| tail`. Оплачено 26 августа
//    2026: заливка зеркала сообщила «317 операций записи (230 заливок,
//    87 удалений)», а в журнале от неё осталось ВОСЕМЬ строк — четыре про
//    удаление и три итоговых. Ни строки «Решение: залить столько-то», ни хода
//    работы. Разбор «почему вдруг 230 файлов» встал намертво и стоил получаса:
//    числа выглядели поломкой счётчика, а сломан был журнал.
//    Причина — `node scripts/mirror-sync.mjs | tail -8` в run-deploy.sh.
//    Тот же урок уже записан в проекте про добор тайтлов: «`| tail -N`
//    у прогона, который что-то СООБЩАЕТ, съедает начало сообщений».
//    Экономить было не на чем: журнал сборки и так 1700 строк.
//
// 2. `set -o pipefail` СТОИТ НА МЕСТЕ. Это несущая строка, а не гигиена.
//    Замер того же дня: с конвейером и без pipefail падение заливки зеркала
//    превращается в «всё хорошо» — робот отрапортует об успехе и сдвинет
//    отметку «докуда выложено». Именно поэтому проверка смотрит на неё
//    отдельно, а не считает само собой разумеющимся.
//
// ЧИТАЕМ НАСТОЯЩИЙ hetzner/run-deploy.sh, а не копию правил рядом: копия
// разошлась бы с оригиналом на первой правке и продолжала бы зеленеть.

import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..');
const ФАЙЛ = join(КОРЕНЬ, 'hetzner', 'run-deploy.sh');
const ПОДЛОГ = process.argv.includes('--подлог');

let исходник = readFileSync(ФАЙЛ, 'utf8');

if (ПОДЛОГ) {
	// ВОЗВРАЩАЕМ РОВНО ТУ СТРОКУ, КОТОРАЯ ЭТО И НАТВОРИЛА, — дословно,
	// включая число. Подлог, который «ломает похоже», ничего не доказывает.
	const было = 'if node scripts/mirror-sync.mjs; then';
	if (!исходник.includes(было)) {
		console.error('ПОДЛОГ НЕ НАШЁЛ, ЧТО ПОДМЕНЯТЬ: строка запуска заливки зеркала изменилась.');
		console.error('Это не «всё хорошо», это сломанный подлог — почините его вместе со скриптом.');
		process.exit(1);
	}
	исходник = исходник.replace(было, 'if node scripts/mirror-sync.mjs | tail -8; then');
}

let провалов = 0;
const сверка = (описание, вышло, пояснение = '') => {
	console.log(`${вышло ? '  ✓' : '  ✗'} ${описание}${вышло || !пояснение ? '' : ` — ${пояснение}`}`);
	if (!вышло) провалов++;
};

console.log(ПОДЛОГ ? 'ПОДЛОГ: в запуск заливки зеркала возвращён «| tail -8»\n' : 'Журнал выкладки не теряет сообщений\n');

// ── 1. НИКАКИХ `| tail` У ШАГОВ ВЫКЛАДКИ ───────────────────────────────────
//
// Ищем по СМЫСЛУ, а не по одному написанию: `| tail`, `|tail`, с любым числом
// и с любыми ключами. Спрашивать надо тем языком, на котором пишут в жизни.
const строки = исходник.split('\n');
const виновные = строки
	.map((с, i) => ({ с, n: i + 1 }))
	.filter(({ с }) => !с.trimStart().startsWith('#'))
	.filter(({ с }) => /\|\s*tail\b/.test(с));

сверка(
	`ни один шаг выкладки не обрезан через «| tail» (найдено ${виновные.length})`,
	виновные.length === 0,
	виновные.map(({ n, с }) => `строка ${n}: ${с.trim()}`).join(' / '),
);

// ── 2. PIPEFAIL НА МЕСТЕ ────────────────────────────────────────────────────
сверка('`set -o pipefail` стоит', /^\s*set -o pipefail\b/m.test(исходник), 'без него провал конвейера читается успехом');

// ── 3. ОБА ШАГА ВЫКЛАДКИ ВСЁ ЕЩЁ ПРОВЕРЯЮТСЯ НА ИСХОД ──────────────────────
//
// Убрать `| tail` можно и вместе с проверкой исхода — тогда журнал станет
// полным, а провал перестанет замечаться вовсе. Это было бы хуже, чем было.
сверка('исход выкладки основного сайта проверяется', /if\s+npx wrangler deploy\b/.test(исходник));
сверка('исход заливки зеркала проверяется', /if\s+node scripts\/mirror-sync\.mjs\b/.test(исходник));

console.log('');
if (ПОДЛОГ) {
	if (провалов > 0) {
		console.log(`ПОДЛОГ ПОЙМАН: провалов ${провалов}. Проверка умеет краснеть.`);
		process.exit(0);
	}
	console.log('ПОДЛОГ НЕ ПОЙМАН — проверка ничего не стоит.');
	process.exit(1);
}
if (провалов > 0) {
	console.log(`ПРОВАЛОВ: ${провалов}`);
	process.exit(1);
}
console.log('Всё сошлось.');
