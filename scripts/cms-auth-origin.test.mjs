/**
 * ВОРКЕР ВХОДА НЕ ОТДАЁТ КЛЮЧ ОТ GITHUB ПОСТОРОННЕМУ САЙТУ.
 *
 * Воркер `cms-auth` заканчивает вход тем, что отдаёт странице ключ (токен)
 * с правами `repo,user` — то есть право писать во ВСЕ репозитории аккаунта.
 * Отдаёт он его сообщением в окно, которое его открыло.
 *
 * ЧЕМ ЭТО БЫЛО ОПАСНО. Старая версия слала ключ ЛЮБОМУ, кто пришлёт слово
 * «authorizing:github», и слала по обратному адресу самого спрашивающего.
 * Значит посторонняя страница могла сама открыть окошко воркера (параметр
 * `site_id` задаёт вызывающий, и вписать туда `bakapodcast.com` мог кто
 * угодно), дождаться, пока GitHub — уже разрешивший приложение однажды —
 * пустит без единого вопроса, спросить ключ и получить его себе.
 *
 * Заслон — сверка origin у сообщения. Его, в отличие от `site_id`, ставит
 * браузер, и отправитель подделать его не может.
 *
 * КАК ПРОВЕРЯЕТСЯ. Берётся НАСТОЯЩИЙ воркер (`cms-auth/src/index.js`), ему
 * подсовывается поддельный GitHub, отдающий заранее известный ключ, и у него
 * запрашивается настоящий ответ на `/callback`. Из ответа вынимается скрипт
 * страницы КАК ЕСТЬ и исполняется в поддельном окне. Дальше окну шлют два
 * сообщения: одно с чужого адреса, одно со своего.
 *
 *   с чужого  → ключа быть не должно
 *   со своего → ключ обязан прийти, иначе сломан вход в админку
 *
 * Ключ `--подлог` снимает заслон ровно так, как он выглядел до починки,
 * и ждёт, что проверка покраснеет. Не покраснела — она смотрит не туда.
 */
import { readFile } from 'node:fs/promises';
import { writeFile, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname, join } from 'node:path';
import { createContext, runInContext } from 'node:vm';

const КОРЕНЬ = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ВОРКЕР = join(КОРЕНЬ, 'cms-auth/src/index.js');

/** Ключ, который «выдаёт» поддельный GitHub. Ищем в ответах именно его. */
const КЛЮЧ = 'ghu_ЭТО-КЛЮЧ-ОТ-ВСЕХ-РЕПОЗИТОРИЕВ';
const СВОЙ = 'https://bakapodcast.com';
const ЧУЖОЙ = 'https://zloy.example.com';
const ДОМЕНЫ = 'bakapodcast.com,www.bakapodcast.com';

/**
 * Спросить у настоящего воркера настоящий ответ с ключом внутри.
 *
 * Подделан только сам GitHub: его ответ на обмен кода на ключ. Всё
 * остальное — разбор печенья, сверка от подделки запроса, сборка страницы —
 * идёт по живому коду воркера.
 */
async function страницаСКлючом(путь) {
	const модуль = await import(`${путь}?${Math.random()}`);
	const прежнийFetch = globalThis.fetch;
	globalThis.fetch = async () => ({ json: async () => ({ access_token: КЛЮЧ }) });
	try {
		const csrf = 'a1b2c3d4e5f60718293a4b5c6d7e8f90';
		const ответ = await модуль.default.fetch(
			new Request(`https://cms-auth.test/callback?code=xyz&state=${csrf}`, {
				headers: { Cookie: `csrf-token=github_${csrf}` },
			}),
			{
				ALLOWED_DOMAINS: ДОМЕНЫ,
				GITHUB_CLIENT_ID: 'id',
				GITHUB_CLIENT_SECRET: 'secret',
			},
		);
		return await ответ.text();
	} finally {
		globalThis.fetch = прежнийFetch;
	}
}

/**
 * Исполнить скрипт страницы в поддельном окне и спросить его с двух адресов.
 *
 * Скрипт берётся из ответа КАК ЕСТЬ, а не переписывается рядом: переписанная
 * копия разошлась бы с настоящей при первой же правке воркера.
 */
function спроситьКлюч(html, откуда) {
	const кусок = /<script>([\s\S]*?)<\/script>/.exec(html);
	if (!кусок) return { беда: 'в ответе воркера нет скрипта — проверять нечего' };

	const сказанное = [];
	const обработчики = [];
	const окно = {
		addEventListener: (имя, ф) => имя === 'message' && обработчики.push(ф),
		opener: { postMessage: (текст, адрес) => сказанное.push({ текст, адрес }) },
	};
	runInContext(кусок[1], createContext({ window: окно, URL, console }));

	if (!обработчики.length) return { беда: 'скрипт не завёл ни одного обработчика сообщений' };

	сказанное.length = 0; // приветствие при запуске ключа не несёт, оно нам не интересно
	for (const ф of обработчики) ф({ data: 'authorizing:github', origin: откуда });
	return { сказанное };
}

/** Снять заслон ровно так, как было до починки: слать всем и всегда. */
async function безЗаслона() {
	const исходный = await readFile(ВОРКЕР, 'utf8');
	const ЗАСЛОН = /\s*if \(hasToken && trustedPatterns\.length && !isTrusted\(origin\)\) \{[\s\S]*?\n\s*\}\n/;
	if (!ЗАСЛОН.test(исходный)) {
		console.log('✗ ПОДЛОГ НИ ЧЕГО НЕ ЗАМЕНИЛ: заслона в коде не нашлось, подменять нечего.');
		console.log('  Это беда подлога, а не проверки. Ищите, как теперь выглядит заслон.');
		return (код = 1);
	}
	const путь = join(КОРЕНЬ, 'cms-auth/src/.подлог.mjs');
	await writeFile(путь, исходный.replace(ЗАСЛОН, '\n'), 'utf8');
	return путь;
}

async function main() {
	const подлог = process.argv.includes('--подлог');
	const путь = подлог ? await безЗаслона() : ВОРКЕР;

	// Код возврата копится в переменной, а выход стоит ПОСЛЕ уборки: process.exit
	// прекращает работу немедленно и блок finally не выполняет вовсе. Пока выход
	// стоял внутри, временный файл подлога оставался лежать в исходниках.
	let код = 0;
	try {
		const html = await страницаСКлючом(путь);
		if (!html.includes(КЛЮЧ)) {
			console.log('✗ Воркер не отдал ключ вовсе — значит подделка GitHub не сработала,');
			console.log('  и проверять «кому он его отдаёт» не на чем.');
			return (код = 1);
		}

		const чужому = спроситьКлюч(html, ЧУЖОЙ);
		const своему = спроситьКлюч(html, СВОЙ);
		for (const итог of [чужому, своему]) {
			if (итог.беда) {
				console.log(`✗ ${итог.беда}`);
				return (код = 1);
			}
		}

		const утёк = чужому.сказанное.some((с) => String(с.текст).includes(КЛЮЧ));
		const дошёл = своему.сказанное.some((с) => String(с.текст).includes(КЛЮЧ));

		console.log(`чужому  ${ЧУЖОЙ}  →  ${утёк ? 'КЛЮЧ ОТДАН' : 'ничего'}`);
		console.log(`своему  ${СВОЙ}  →  ${дошёл ? 'ключ отдан' : 'НИЧЕГО'}`);
		console.log();

		if (подлог) {
			if (утёк) {
				console.log('✓ ПОДЛОГ ПОЙМАН: сняли заслон — и ключ ушёл на посторонний адрес.');
				console.log('  Значит проверка меряет именно то, ради чего написана.');
				return (код = 0);
			}
			console.log('✗ ПОДЛОГ НЕ ПОЙМАН: заслон снят, а проверка осталась зелёной —');
			console.log('  значит её «всё хорошо» ничего не значит.');
			return (код = 1);
		}

		if (утёк) {
			console.log('✗✗ ВОРКЕР ОТДАЁТ КЛЮЧ ОТ GITHUB ПОСТОРОННЕМУ САЙТУ.');
			console.log('   Посторонняя страница может открыть окно входа сама, дождаться');
			console.log('   ключа и забрать его себе — это право писать во ВСЕ репозитории.');
			return (код = 1);
		}
		if (!дошёл) {
			console.log('✗✗ КЛЮЧ НЕ ДОХОДИТ И ДО СВОЕЙ АДМИНКИ — вход сломан.');
			console.log(`   Проверьте, что в ALLOWED_DOMAINS воркера есть ${new URL(СВОЙ).hostname}.`);
			return (код = 1);
		}
		console.log('ок      Ключ уходит только на свой домен: посторонний сайт его не получит,');
		console.log('        а вход в админку работает.');
		return (код = 0);
	} finally {
		if (подлог) await unlink(путь).catch(() => {});
	}
	return код;
}

const позвалиНапрямую = resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1] ?? '');
if (позвалиНапрямую) process.exit(await main());
