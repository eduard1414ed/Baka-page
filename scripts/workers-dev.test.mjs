// СЛУЖЕБНЫЙ АДРЕС ВОРКЕРА ОБЯЗАН БЫТЬ ВКЛЮЧЁН ЯВНО.
//
//   node scripts/workers-dev.test.mjs             — спросить
//   node scripts/workers-dev.test.mjs --selftest  — плюс подлог
//
// ЗАЧЕМ. У двух воркеров проекта служебный адрес `…workers.dev` — не отладочная
// мелочь, а рабочий вход:
//   • `baki-cms-auth` — по нему идёт ЛОГИН В АДМИНКУ (`base_url`
//     в `public/admin/config.yml`);
//   • `baki-publish-cron` — по нему работает ручной запуск будильника.
// Wrangler отключает такой адрес при деплое, если он не включён явно строкой
// `"workers_dev": true`. Ровно так он поступил с адресом сайта 8 августа 2026,
// когда к тому привязывали домен.
//
// ПОЧЕМУ ЭТО ПРОВЕРКА, А НЕ ПОМЕТКА В ДОКУМЕНТАХ. Пометка тут уже была —
// и в `CLAUDE.md`, и в болячках стояло «им нужна явная строка `workers_dev`».
// У `publish-cron` строка была, у `cms-auth` её не было ВООБЩЕ (ревизия
// задачи 15, находка 8). То есть запись защищала не тем, чем казалась,
// и это записанный урок проекта: пометка не удерживает ничего.
//
// СПРАШИВАЕТСЯ И ВТОРАЯ ПОЛОВИНА: правда ли админка ходит на тот самый адрес.
// Без неё проверка стерегла бы строку, смысл которой мог давно уехать.
import { readFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * JSONC → объект.
 *
 * Строки с `//` внутри значения не режем: комментарий считается только тот,
 * что стоит в начале строки (так написаны оба наших файла), — иначе адрес
 * `https://…` в значении обрубался бы на двух косых, и проверка падала бы
 * на здоровом файле.
 */
export function читатьJsonc(текст) {
	const без = текст
		.split('\n')
		.filter((строка) => !/^\s*\/\//.test(строка))
		.join('\n');
	return JSON.parse(без);
}

const ВОРКЕРЫ = [
	{ файл: 'cms-auth/wrangler.jsonc', зачем: 'вход в админку' },
	{ файл: 'publish-cron/wrangler.jsonc', зачем: 'ручной запуск будильника' },
];

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

console.log('СЛУЖЕБНЫЕ АДРЕСА ВОРКЕРОВ: включены явно, и админка ходит на свой.');
console.log();

const настройки = new Map();
for (const воркер of ВОРКЕРЫ) {
	const текст = await readFile(join(КОРЕНЬ, воркер.файл), 'utf8');
	const данные = читатьJsonc(текст);
	настройки.set(воркер.файл, данные);
	скажи(данные.workers_dev === true, `${воркер.файл} (${воркер.зачем}): workers_dev = ${JSON.stringify(данные.workers_dev)}`);
}

// ── Админка ходит именно на этот адрес ────────────────────────────────────
const config = await readFile(join(КОРЕНЬ, 'public', 'admin', 'config.yml'), 'utf8');
const base = config.match(/^\s*base_url:\s*(\S+)/m)?.[1] ?? '';
const имяВхода = настройки.get('cms-auth/wrangler.jsonc')?.name;
скажи(
	base.includes('.workers.dev') && base.includes(String(имяВхода)),
	`админка ходит на ${base || '(не нашёл base_url)'} — это служебный адрес «${имяВхода}»`,
);

// ── ПОДЛОГ ────────────────────────────────────────────────────────────────
// «Пусто» ничего не значит, пока не показано, что проверка умеет находить.
// Подлог СОЗДАЁТ расхождение в ОДНОМ файле — так, как оно и случилось в жизни:
// у соседа строка была, у входа в админку её не было.
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── ПОДЛОГ: настройка без строки — та, что лежала до 15 августа ──');

	const прежний = '{\n\t"name": "baki-cms-auth",\n\t"main": "src/index.js",\n\t"compatibility_date": "2026-08-05"\n}\n';
	const разобран = читатьJsonc(прежний);
	скажи(разобран.workers_dev !== true, `прежняя настройка поймана: workers_dev = ${JSON.stringify(разобран.workers_dev)}`);

	// И ВТОРАЯ ПОЛОВИНА: на здоровом подлог обязан молчать, иначе «поймал»
	// неотличимо от «ругается на всё подряд».
	const здоровый = '{\n\t"name": "x",\n\t// пояснение\n\t"workers_dev": true\n}\n';
	скажи(читатьJsonc(здоровый).workers_dev === true, 'здоровую настройку с комментарием разбирает и не ругается');

	// Комментарий разбирается по началу строки, а не по любым двум косым:
	// иначе адрес внутри значения обрубался бы, и проверка врала бы.
	const сАдресом = '{\n\t"base": "https://x.workers.dev",\n\t"workers_dev": true\n}\n';
	скажи(читатьJsonc(сАдресом).base === 'https://x.workers.dev', 'адрес внутри значения разбор не съедает');
}

console.log();
if (плохо) {
	console.log(`ПРОВАЛОВ: ${плохо}`);
	process.exit(1);
}
console.log('Оба служебных адреса включены явно.');
