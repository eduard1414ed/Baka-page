// ШАПКА ОБЯЗАНА ЧИТАТЬСЯ ОБРАТНО — ОДНО ПРАВИЛО НА ПРОЕКТ.
//
// ЭТО ЗАСЛОН, А НЕ УКРАШЕНИЕ. Кривая шапка роняет сборку ВСЕГО САЙТА, а не
// один пост: Astro читает коллекцию целиком и падает на первом же нечитаемом
// файле. Своё правило кавычек в этом проекте уже соврало — оно не видело
// двоеточия в конце заголовка, и 70 постов архива положили бы сайт. Правило
// починено, но верить ему на слово больше нельзя: пусть отвечает сам js-yaml,
// тот же самый, каким шапку читает сборка.
//
// СВЕРЯЕТСЯ НЕ «РАЗОБРАЛОСЬ БЕЗ ОШИБКИ», А ЧТО РАЗОБРАЛОСЬ. YAML умеет
// прочитать строку числом или датой, не поругавшись ни на что: `title: 007`
// вернётся числом 7, `title: да` — булевым. Ошибки нет, а заголовок пропал.
//
// ПОЧЕМУ ОДНО МЕСТО. Правило жило в двух копиях — у импорта из телеграма
// и у робота выпусков, — и к нему надо было дописать ещё две: разовым
// скриптам заголовков сезонов и постов-ссылок (доревизия задачи 15,
// находка 31). Четыре копии одного заслона расходятся молча, а расходятся
// они в ту сторону, где заслона нет.
import yaml from 'js-yaml';

/**
 * Что не так с шапкой готового файла.
 *
 * @param {string} имя как назвать файл в строчке беды («№142 (ep-150)» или slug)
 * @param {string} текст готовый текст файла целиком, вместе с телом
 * @param {Record<string, unknown>} ждали что мы туда клали; вложенное — точкой
 *        («bonusLinks.boosty»). Дату кладите строкой «2026-08-15»: YAML читает
 *        её датой, и здесь она приводится обратно к дню.
 * @returns {string[]} список бед; пусто — читается
 */
export function бедыШапки(имя, текст, ждали) {
	const head = String(текст).split(/^---$/m)[1];

	let прочитано;
	try {
		прочитано = yaml.load(head);
	} catch (ошибка) {
		return [`${имя}: шапка не читается — ${String(ошибка.message).split('\n')[0]}`];
	}
	if (!прочитано || typeof прочитано !== 'object') {
		return [`${имя}: шапка прочиталась не полями, а ${JSON.stringify(прочитано)}`];
	}

	const беды = [];
	for (const [поле, надо] of Object.entries(ждали)) {
		let вышло = поле.split('.').reduce((узел, ключ) => (узел == null ? узел : узел[ключ]), прочитано);
		// Дату YAML читает датой — это и нужно; сверяем сам день.
		if (вышло instanceof Date) вышло = вышло.toISOString().slice(0, 10);
		if (вышло !== надо) {
			беды.push(`${имя}: поле «${поле}» прочиталось как ${JSON.stringify(вышло)}, а клали ${JSON.stringify(надо)}`);
		}
	}

	return беды;
}
