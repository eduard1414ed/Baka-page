#!/usr/bin/env node
// Проверки галочки «только в кавычках» (тз/11, часть B).
//
// ФАЙЛОМ, А НЕ ОДНОСТРОЧНИКОМ `node -e`: обратный слэш внутри однострочника
// проходит через две системы экранирования подряд, и выражение перестаёт
// совпадать вообще ни с чем — при этом проверка не падает, а бодро отвечает
// «ничего не найдено» (CLAUDE.md, «Уроки проекта»).
//
// ПОЧЕМУ ПРИМЕРЫ НАПИСАНЫ ФРАЗАМИ, А НЕ НАБОРАМИ ЗНАКОВ. Подлог, повторяющий
// формулировку проверки, проверяет не проверку, а аккуратность того, кто её
// писал. Поэтому ниже стоят строки в том виде, в каком они встречаются
// в архиве: с ёлочками, лапками, прямыми кавычками телефонного автонабора,
// с номером сезона внутри кавычек и с обычной речью без кавычек вовсе.
//
//   node scripts/anime-quotes.test.mjs

import { buildAnimeMatcher, findMentions } from '../src/lib/animeMentions.mjs';

let failed = 0;

function check(name, ok, detail = '') {
	if (!ok) failed += 1;
	console.log(`  ${ok ? 'ок      ' : 'ПРОВАЛ  '} ${name}${detail ? ` — ${detail}` : ''}`);
}

// Справочник для проверок: «Монстр» — обычное слово, галочка стоит; «Магическая
// битва» — тоже под галочкой, но из двух слов и с номером сезона в текстах;
// «Дандадан» галочки не носит и обязан находиться везде, как раньше.
const catalog = (strict) => [
	{
		id: 'monster',
		data: { titleRu: 'Монстр', titleOriginal: 'Monster', aliasesAuto: ['Монстра', 'Монстре', 'Монстром'], strictQuotes: strict },
	},
	{
		id: 'jujutsu',
		data: { titleRu: 'Магическая битва', titleOriginal: 'Jujutsu Kaisen', aliasesAuto: ['Магическую битву', 'Магической битвы'], strictQuotes: strict },
	},
	{ id: 'dandadan', data: { titleRu: 'Дандадан', titleOriginal: 'Dandadan' } },
];

const ids = (text, strict) => findMentions(text, buildAnimeMatcher(catalog(strict))).map((m) => m.id);

console.log('\n=== ГАЛОЧКА ВКЛЮЧЕНА: ЧТО НАХОДИТСЯ ===');

const shouldFind = [
	['«Монстр» — лучшее, что нарисовал Урасава', 'ёлочки'],
	['Пересмотрел "Монстра" целиком', 'прямые кавычки, и сразу в падеже'],
	['А в „Монстре“ этого нет вовсе', 'лапки'],
	["Взял с полки 'Монстра'", 'апострофы'],
	['«Магическую битву 0» сделали за 4 месяца', 'номер внутри кавычек — цифра кавычек не отменяет'],
	['Дизайн у «Магическая битва 2» вышел спорным', 'то же, но название в именительном'],
	['Читаю «Монстр», думаю про «Магическая битва»', 'два тайтла в одной фразе'],
];

for (const [text, why] of shouldFind) {
	const found = ids(text, true);
	check(`${why}: ${text}`, found.length > 0, found.length ? `нашлось: ${found.join(', ')}` : 'НЕ НАШЛОСЬ НИЧЕГО');
}

console.log('\n=== ГАЛОЧКА ВКЛЮЧЕНА: ЧТО НЕ ДОЛЖНО НАХОДИТЬСЯ ===');

const shouldNotFind = [
	['В этом фильме про кайдзю монстр появляется на сороковой минуте', 'обычное слово без кавычек'],
	['Тут у нас магическая битва в чистом виде, без всякого сюжета', 'обычная фраза из двух слов'],
	['Он сказал: «да», а монстр всё равно вылез', 'кавычки соседней фразы не считаются'],
	['«Монстр в конце этой книги» — детская сказка', 'кавычки есть, но название внутри чужой фразы'],
];

for (const [text, why] of shouldNotFind) {
	const found = ids(text, true);
	check(`${why}: ${text}`, found.length === 0, found.length ? `а нашлось: ${found.join(', ')}` : 'молчит');
}

console.log('\n=== ГАЛОЧКА ВЫКЛЮЧЕНА: ВСЁ КАК БЫЛО ===');

for (const [text] of shouldNotFind.slice(0, 2)) {
	const found = ids(text, false);
	check(`без галочки находится: ${text}`, found.length > 0, found.join(', ') || 'НЕ НАШЛОСЬ');
}

console.log('\n=== ГАЛОЧКА — НЕ НА ВЕСЬ СПРАВОЧНИК ===');
{
	const text = 'Смотрю дандадан и думаю про монстр';
	const found = ids(text, true);
	check(
		'у тайтла без галочки название ловится без кавычек, у тайтла с галочкой — нет',
		found.length === 1 && found[0] === 'dandadan',
		found.join(', ') || 'не нашлось ничего',
	);
}

console.log('\n=== КАВЫЧКИ НИЧЕГО НЕ ДОКАЗЫВАЮТ САМИ (тз/11, B.3) ===');
{
	const text = 'Смотрел на «Кинопоиске», читал «Афишу», листал «Мир фантастики»';
	const found = ids(text, true);
	check('фраза в кавычках, которой нет в справочнике, упоминанием не становится', found.length === 0, found.join(', ') || 'молчит');
}

console.log(
	failed === 0
		? '\nВсе проверки прошли: и находит, и молчит там, где должна молчать.'
		: `\nПРОВАЛОВ: ${failed} — верить этим проверкам нельзя.`,
);
process.exit(failed === 0 ? 0 : 1);
