// СОРТ ПАРЫ ДУБЛИКАТОВ — ОДИН ОТВЕТ У ОТЧЁТА И У УДАЛЕНИЯ.
//
//   node scripts/dedupe-kind.test.mjs             — спросить правило
//   node scripts/dedupe-kind.test.mjs --selftest  — плюс подлог: вернуть прежнее правило
//
// ЗАЧЕМ. От сорта зависит, КАКОЙ пост из пары удалить: у дословных копий
// уходит новый, у почти-копий — старый, «один длиннее» не трогается вовсе.
// Заказчик принимает решение по строчке отчёта, а удаляет её другой скрипт.
// Пока сорт считался дважды, разъехаться они могли молча — и уже расходились
// в одном месте: отчёт сравнивал с порогом ОКРУГЛЁННЫЙ процент, а удаление
// саму долю, так что пара с 89,6 % общих слов читалась в отчёте копией,
// а удалению доставалась «разными материалами».
//
// ЧТО СПРАШИВАЕТСЯ. Не «правильный ли сорт» (это решает замер по архиву,
// он записан в задаче 19), а «ОДИН ЛИ ОН у двух читателей». Поэтому строчка
// отчёта разбирается обратно в сорт и сверяется с тем, что вернула `сортПары`.
import { сортПары, diffNote, ПОРОГ_ОБЩИХ_СЛОВ } from './archive-duplicates.mjs';

/** Строчка отчёта → сорт, каким её прочитает человек. */
function сортИзОтчёта(строка) {
	if (строка.includes('СОВПАДАЮТ ДОСЛОВНО')) return 'дословная копия';
	if (строка.includes('ДЛИННЕЕ') || строка.includes('целиком внутри')) return 'один длиннее';
	if (строка.includes('ПОЧТИ КОПИЯ')) return 'почти копия';
	if (строка.includes('РАЗНЫЕ МАТЕРИАЛЫ')) return 'разные материалы';
	return `(не разобрал: ${строка})`;
}

const слова = (n, приставка = 'сл') => Array.from({ length: n }, (_, i) => `${приставка}${i}`).join(' ');

/**
 * Пара, у которой доля общих слов задана числом.
 * Нужна затем, что интересные случаи лежат вплотную к порогу, а в архиве
 * таких нет: там разрыв между 47 % и 91 %.
 */
function параСДолей(общих, всего) {
	const a = слова(всего, 'о');
	const b = [слова(общих, 'о'), слова(всего - общих, 'б')].join(' ');
	return [{ id: 'а', text: a }, { id: 'б', text: b }];
}

const СЛУЧАИ = [
	{
		имя: 'дословная копия',
		пара: [{ id: 'а', text: 'один и тот же текст' }, { id: 'б', text: 'один и тот же текст' }],
		ждём: 'дословная копия',
	},
	{
		имя: 'один длиннее, начало совпадает',
		пара: [{ id: 'а', text: 'начало текста' }, { id: 'б', text: 'начало текста и продолжение' }],
		ждём: 'один длиннее',
	},
	{
		имя: 'короткий целиком ВНУТРИ длинного, но не с начала',
		пара: [{ id: 'а', text: 'середина текста' }, { id: 'б', text: 'до этого середина текста и после' }],
		ждём: 'один длиннее',
	},
	{
		имя: `ровно порог ${ПОРОГ_ОБЩИХ_СЛОВ * 100} % — это ещё копия`,
		пара: параСДолей(90, 100),
		ждём: 'почти копия',
	},
	{
		имя: 'чуть ниже порога — разные материалы',
		пара: параСДолей(89, 100),
		ждём: 'разные материалы',
	},
	{
		// РОВНО ТА ЩЕЛЬ, В КОТОРОЙ ДВЕ КОПИИ ПРАВИЛА ОТВЕЧАЛИ ПО-РАЗНОМУ:
		// 224/250 = 0,896 → округляется в 90 %, но порога не достигает.
		имя: 'щель округления (89,6 %) — и отчёт, и удаление говорят «разные»',
		пара: параСДолей(224, 250),
		ждём: 'разные материалы',
	},
	{
		имя: 'совсем разные материалы под одним названием',
		пара: [{ id: 'а', text: слова(50, 'x') }, { id: 'б', text: слова(50, 'y') }],
		ждём: 'разные материалы',
	},
];

let плохо = 0;

console.log('СОРТ ПАРЫ: отчёт и удаление обязаны отвечать одинаково.');
console.log();

for (const случай of СЛУЧАИ) {
	const [a, b] = случай.пара;
	const свой = сортПары(a, b).вид;
	const вОтчёте = сортИзОтчёта(diffNote(a, b));
	const ок = свой === случай.ждём && вОтчёте === случай.ждём;
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${случай.имя}`);
	if (!ок) console.log(`          ждали «${случай.ждём}», правило «${свой}», отчёт «${вОтчёте}»`);

	// СОРТ НЕ ЗАВИСИТ ОТ ПОРЯДКА ПАРЫ. Пары приходят из `allPairs` в том
	// порядке, в каком лежат файлы, и решение «кого удалить» строится поверх:
	// перевернись ответ — перевернулась бы и жертва.
	const наоборот = сортПары(b, a).вид;
	if (наоборот !== свой) {
		плохо++;
		console.log(` ПЛОХО  ${случай.имя}: от перестановки пары сорт сменился на «${наоборот}»`);
	}
}

// ── ПОДЛОГ ────────────────────────────────────────────────────────────────
// «Пусто» ничего не значит, пока не показано, что проверка умеет находить.
// Подлог возвращает ПРЕЖНЕЕ правило — то, что жило в отчёте: сравнение
// с порогом по округлённому проценту. Оно обязано разойтись с нынешним
// ровно на паре из щели округления.
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── ПОДЛОГ: прежнее правило отчёта (порог по округлённому проценту) ──');

	const прежнееПравило = (a, b) => {
		const набор = (s) => new Set(s.split(' '));
		const wa = набор(a.text);
		const wb = набор(b.text);
		const общих = [...wa].filter((w) => wb.has(w)).length;
		const процент = Math.round((общих / Math.max(wa.size, wb.size)) * 100);
		return процент >= 90 ? 'почти копия' : 'разные материалы';
	};

	const [a, b] = параСДолей(224, 250);
	const прежний = прежнееПравило(a, b);
	const нынешний = сортПары(a, b).вид;
	const разошлись = прежний !== нынешний;
	if (!разошлись) плохо++;
	console.log(`${разошлись ? '  ок  ' : ' ПЛОХО'}  на 89,6 % прежнее правило говорит «${прежний}», нынешнее «${нынешний}»`);

	// И ВТОРАЯ ПОЛОВИНА: на здоровом подлог обязан МОЛЧАТЬ, иначе «поймал»
	// неотличимо от «ругается на всё подряд».
	const [c, d] = параСДолей(95, 100);
	const сходятся = прежнееПравило(c, d) === сортПары(c, d).вид;
	if (!сходятся) плохо++;
	console.log(`${сходятся ? '  ок  ' : ' ПЛОХО'}  на явной копии (95 %) прежнее и нынешнее правило совпадают`);
}

console.log();
if (плохо) {
	console.log(`ПРОВАЛОВ: ${плохо}`);
	process.exit(1);
}
console.log(`Случаев ${СЛУЧАИ.length}. Отчёт и удаление отвечают одинаково.`);
