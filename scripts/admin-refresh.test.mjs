#!/usr/bin/env node
// ПРОВЕРКА: ЯРЛЫК АДМИНКИ ЗАБИРАЕТ ЧУЖОЕ ПРИ ЗАПУСКЕ (задача 29).
//
// Запуск:            node scripts/admin-refresh.test.mjs
// Подлоги:           node scripts/admin-refresh.test.mjs --подлог
//                    node scripts/admin-refresh.test.mjs --подлог-силой
//
// ПОЧЕМУ НЕ ЗАПУСКАЕМ САМ ЯРЛЫК. scripts/local-admin.mjs поднимает сервер
// админки и живёт, пока открыто окно, — в песочнице его не прогнать. Поэтому
// проверяемый кусок ВЫНИМАЕТСЯ ИЗ САМОГО ФАЙЛА (от метки «1½» до метки «2»)
// и исполняется в настоящих git-репозиториях. Переписать его рядом было бы
// проще и бесполезнее: копия разошлась бы с оригиналом при первой правке
// и проверяла бы вчерашний код.
//
// ЧЕТЫРЕ СЛУЧАЯ:
//   1. робот привёз выпуск            — забрать и назвать по заголовку;
//   2. приехала только служебная       — забрать молча, новостью не звать;
//      закладка робота телеграма
//   3. на диске несохранённая правка   — НЕ забирать и НИЧЕГО не тронуть;
//      в том же файле
//   4. хранилище недоступно            — сказать словами и не упасть.
//
// ДВА ПОДЛОГА, И ОНИ СТЕРЕГУТ РАЗНОЕ:
//   --подлог        возвращает состояние до задачи 29: чужое не забирается
//                   вовсе. Случай 1 обязан покраснеть.
//   --подлог-силой  забирает, убрав с дороги правки заказчика («мешают —
//                   уберём»). Случай 3 обязан покраснеть. Без этого второго
//                   подлога ключ --ff-only можно было бы заменить на что
//                   угодно, и проверка бы этого не заметила.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ЯРЛЫК = join(ROOT, 'scripts', 'local-admin.mjs');
const ПОДЛОГ = process.argv.includes('--подлог');
const ПОДЛОГ_СИЛОЙ = process.argv.includes('--подлог-силой');

let бед = 0;
const скажи = (текст = '') => console.log(текст);
const проверь = (условие, что) => {
	скажи(`   ${условие ? '✓' : '✗'} ${что}`);
	if (!условие) бед += 1;
};

const гит = (где, доводы) => execFileSync('git', доводы, { cwd: где, encoding: 'utf8' }).trim();

const ПОСТ = 'src/content/posts/ep-153.md';
const ЗАКЛАДКА = 'src/data/telegramFeed.mjs';
const ЗАГОЛОВОК = 'Как жить во время конца света? — «Мертвые мертвые демоны» | Эссе';
const постТекст = (тело) => `---\ntitle: '${ЗАГОЛОВОК}'\ndate: 2026-08-27\ncategory: podcast\ndraft: true\n---\n\n${тело}\n`;

// ── вынимаем проверяемый кусок из самого ярлыка ────────────────────────────
function кусокЯрлыка() {
	const текст = readFileSync(ЯРЛЫК, 'utf8');
	const начало = текст.indexOf('// ═══ 1½. ЗАБИРАЮ ЧУЖОЕ');
	const конец = текст.indexOf('// ═══ 2. ПОДНИМАЕМ АДМИНКУ');
	if (начало < 0 || конец < 0 || конец <= начало) {
		скажи('✗ НЕ НАШЁЛ В ЯРЛЫКЕ КУСОК «ЗАБИРАЮ ЧУЖОЕ» — проверять нечего.');
		process.exit(1);
	}
	let кусок = текст.slice(начало, конец);

	if (ПОДЛОГ_СИЛОЙ) {
		// Ошибка, которую легко совершить: «мешают несохранённые правки?
		// уберём их и заберём». Ровно ОДНА строка разводится, как и случилось
		// бы в жизни.
		const строка = "	const перемотал = гит.можно(['merge', '--ff-only', 'origin/main']);";
		if (!кусок.includes(строка)) {
			скажи('✗ ПОДЛОГ НЕ УДАЛСЯ: не нашёл строку перемотки.');
			process.exit(1);
		}
		кусок = кусок.replace(строка,
			"	гит.можно(['checkout', '--', '.']);\n" + строка);
	}

	return кусок;
}

// СПИСОК ИМПОРТОВ ВЫНИМАЕТСЯ ИЗ ЯРЛЫКА, А НЕ ПЕРЕПИСЫВАЕТСЯ ЗДЕСЬ.
// Он тут уже был переписан — и на первой же правке ярлыка разошёлся: проверка
// упала с «версияИзКоммита is not defined» на коде, где всё правильно. То есть
// соврала в сторону «сломано», и чинить пошли бы здоровое. Списка больше нет:
// берём тот, что стоит в самом ярлыке.
function импортыЯрлыка() {
	const текст = readFileSync(ЯРЛЫК, 'utf8');
	const найдено = текст.match(/^import \{[^}]*\} from '\.\/repo-news-lib\.mjs';$/m);
	if (!найдено) {
		скажи('✗ НЕ НАШЁЛ В ЯРЛЫКЕ ИМПОРТ ОБЩЕГО ДОМА — обёртку не собрать.');
		process.exit(1);
	}
	return найдено[0];
}

const ОБЁРТКА = (кусок) => `import { existsSync } from 'node:fs';
import { resolve, join } from 'node:path';
${импортыЯрлыка()}

const ROOT = resolve(process.cwd());
const скажи = (текст = '') => console.log(текст);

${ПОДЛОГ ? '// ПОДЛОГ: прежнее правило — чужое при запуске не забиралось вовсе.\nfunction забратьЧужое() {}\n' : кусок}

забратьЧужое();
`;

// ── песочница ──────────────────────────────────────────────────────────────
function построить() {
	const корень = mkdtempSync(join(tmpdir(), 'baka-refresh-'));
	const хранилище = join(корень, 'github.git');
	const заказчик = join(корень, 'заказчик');
	const робот = join(корень, 'робот');

	execFileSync('git', ['init', '--bare', '-b', 'main', хранилище], { stdio: 'ignore' });
	execFileSync('git', ['clone', '--quiet', хранилище, заказчик], { stdio: 'ignore' });

	const представься = (где, имя) => {
		гит(где, ['config', 'user.name', имя]);
		гит(где, ['config', 'user.email', `${имя}@example.com`]);
	};
	представься(заказчик, 'eduard1414ed');

	mkdirSync(join(заказчик, 'src', 'content', 'posts'), { recursive: true });
	mkdirSync(join(заказчик, 'src', 'data'), { recursive: true });
	mkdirSync(join(заказчик, 'scripts'), { recursive: true });
	writeFileSync(join(заказчик, 'src', 'content', 'posts', 'ep-100.md'), постТекст('Старый пост.'));
	writeFileSync(join(заказчик, ЗАКЛАДКА), 'export const lastSeen = 1;\n');
	гит(заказчик, ['add', '-A']);
	гит(заказчик, ['commit', '-m', 'Начало']);
	гит(заказчик, ['push', '--quiet', 'origin', 'main']);

	writeFileSync(join(заказчик, 'scripts', 'подъём.mjs'), ОБЁРТКА(кусокЯрлыка()));
	execFileSync('cp', [join(ROOT, 'scripts', 'repo-news-lib.mjs'), join(заказчик, 'scripts', 'repo-news-lib.mjs')]);

	execFileSync('git', ['clone', '--quiet', хранилище, робот], { stdio: 'ignore' });
	представься(робот, 'baka-episodes-bot');

	return { корень, заказчик, робот };
}

function прогнать(где) {
	try {
		return { код: 0, вывод: execFileSync(process.execPath, ['scripts/подъём.mjs'], { cwd: где, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }) };
	} catch (сбой) {
		return { код: сбой.status, вывод: `${сбой.stdout || ''}${сбой.stderr || ''}` };
	}
}

const роботПривёз = (робот, файл, текст, сообщение) => {
	гит(робот, ['pull', '--quiet', '--rebase', 'origin', 'main']);
	writeFileSync(join(робот, файл), текст);
	гит(робот, ['add', '-A']);
	гит(робот, ['commit', '-m', сообщение]);
	гит(робот, ['push', '--quiet', 'origin', 'main']);
};

const метка = ПОДЛОГ ? '   [ПОДЛОГ]' : ПОДЛОГ_СИЛОЙ ? '   [ПОДЛОГ СИЛОЙ]' : '';

// ═══ 1. РОБОТ ПРИВЁЗ ВЫПУСК ════════════════════════════════════════════════
скажи(`\n=== 1. Пока заказчика не было, робот привёз выпуск ===${метка}\n`);
{
	const { корень, заказчик, робот } = построить();
	// ПРИВОЗИТ НЕ ФАЙЛ, А ПОРЦИЮ. Замер на настоящем приходе 27.08.2026: один
	// выпуск это одиннадцать файлов — обложки, вырезка персонажа, расшифровка,
	// служебные списки. Проверять на одном файле значит не проверить главного:
	// не утонет ли единственная важная строчка в свите.
	гит(робот, ['pull', '--quiet', '--rebase', 'origin', 'main']);
	mkdirSync(join(робот, 'public', 'episodes'), { recursive: true });
	mkdirSync(join(робот, 'src', 'content', 'transcripts'), { recursive: true });
	writeFileSync(join(робот, ПОСТ), постТекст('Совсем новый выпуск.'));
	writeFileSync(join(робот, 'public/episodes/oblozhka-640w.webp'), 'картинка');
	writeFileSync(join(робот, 'public/episodes/oblozhka-1280w.webp'), 'картинка');
	writeFileSync(join(робот, 'src/content/transcripts/rasshifrovka.json'), '[]');
	гит(робот, ['add', '-A']);
	гит(робот, ['commit', '-m', 'Добавить черновики новых выпусков из RSS']);
	гит(робот, ['push', '--quiet', 'origin', 'main']);

	проверь(!existsSync(join(заказчик, ПОСТ)), 'до запуска выпуска у заказчика нет');

	const итог = прогнать(заказчик);

	if (ПОДЛОГ) {
		проверь(!existsSync(join(заказчик, ПОСТ)),
			'ПОДЛОГ: прежнее правило выпуска не забрало — админка открылась на вчерашнем');
		проверь(!итог.вывод.includes(ЗАГОЛОВОК), 'ПОДЛОГ: и не сказало о нём ни слова');
	} else {
		проверь(итог.код === 0, 'отработал без падения');
		проверь(existsSync(join(заказчик, ПОСТ)), 'ВЫПУСК ЗАБРАН: файл появился на диске');
		проверь(итог.вывод.includes(ЗАГОЛОВОК), 'назвал выпуск по заголовку, а не по имени файла');
		проверь(/робот выпусков/.test(итог.вывод), 'сказал, кто привёз, человеческим именем');
		проверь(/ПОКА ВАС НЕ БЫЛО/.test(итог.вывод), 'вынес это отдельной рамкой, а не строчкой в потоке');
		проверь(/служебные данные: 3 файлов/.test(итог.вывод),
			'СВИТУ СВЕРНУЛ ЧИСЛОМ: обложки и расшифровка не топят единственную важную строчку');
		проверь(!/oblozhka-640w/.test(итог.вывод), 'и не вывалил их в столбик');
	}

	rmSync(корень, { recursive: true, force: true });
}

// ═══ 2. ТОЛЬКО СЛУЖЕБНАЯ ЗАКЛАДКА ══════════════════════════════════════════
скажи('\n=== 2. Приехала только служебная отметка робота телеграма ===\n');
{
	const { корень, заказчик, робот } = построить();
	гит(робот, ['config', 'user.name', 'baka-telegram-bot']);
	роботПривёз(робот, ЗАКЛАДКА, 'export const lastSeen = 2;\n', 'Отметка робота телеграма: новых постов не было');

	const итог = прогнать(заказчик);

	if (!ПОДЛОГ) {
		проверь(readFileSync(join(заказчик, ЗАКЛАДКА), 'utf8').includes('lastSeen = 2'),
			'забрал молча: отметка на диске обновилась');
		проверь(/нового для вас нет/.test(итог.вывод),
			'НОВОСТЬЮ НЕ НАЗВАЛ: четырежды в сутки кричать «приехало новое» о пустоте нельзя');
		проверь(!/ПОКА ВАС НЕ БЫЛО/.test(итог.вывод), 'рамку со списком не рисовал');
	} else {
		проверь(true, 'ПОДЛОГ: этот случай стережёт не он');
	}

	rmSync(корень, { recursive: true, force: true });
}

// ═══ 3. НА ДИСКЕ НЕСОХРАНЁННАЯ ПРАВКА В ТОМ ЖЕ ФАЙЛЕ ═══════════════════════
скажи(`\n=== 3. Заказчик правил тот же пост и не выложил ===${метка}\n`);
{
	const { корень, заказчик, робот } = построить();
	const МОЙ = 'src/content/posts/ep-100.md';
	роботПривёз(робот, МОЙ, постТекст('Версия робота.'), 'Картинка к посту');
	writeFileSync(join(заказчик, МОЙ), постТекст('Моя несохранённая правка.'));

	const итог = прогнать(заказчик);
	const наДиске = readFileSync(join(заказчик, МОЙ), 'utf8');

	if (ПОДЛОГ_СИЛОЙ) {
		проверь(!/Моя несохранённая правка/.test(наДиске),
			'ПОДЛОГ СИЛОЙ: правка заказчика затёрта — ровно то, чего допускать нельзя');
	} else if (ПОДЛОГ) {
		проверь(/Моя несохранённая правка/.test(наДиске), 'ПОДЛОГ: не забирал вовсе, значит и не затёр');
	} else {
		проверь(итог.код === 0, 'не упал');
		проверь(/Моя несохранённая правка/.test(наДиске),
			'НИЧЕГО НЕ ЗАТЁРТО: правка заказчика на диске цела');
		проверь(/НИЧЕГО не тронуто/.test(итог.вывод), 'сказал вслух, что не тронул ничего');
		проверь(/ВЫЛОЖИТЬ НА САЙТ/.test(итог.вывод), 'сказал, что делать: выложить кнопкой');
		проверь(/ЖДЁТ В ХРАНИЛИЩЕ/.test(итог.вывод), 'всё равно показал, что там лежит');
	}

	rmSync(корень, { recursive: true, force: true });
}

// ═══ 4. ХРАНИЛИЩЕ НЕДОСТУПНО ═══════════════════════════════════════════════
скажи('\n=== 4. Хранилища нет на месте (интернет пропал) ===\n');
{
	const { корень, заказчик } = построить();
	гит(заказчик, ['remote', 'set-url', 'origin', join(корень, 'нет-такого.git')]);

	const итог = прогнать(заказчик);

	if (!ПОДЛОГ) {
		проверь(итог.код === 0, 'НЕ УПАЛ: админку надо поднять в любом случае');
		проверь(/не достучался до хранилища/.test(итог.вывод), 'сказал словами, что не спросил хранилище');
	} else {
		проверь(итог.код === 0, 'ПОДЛОГ: этот случай стережёт не он');
	}

	rmSync(корень, { recursive: true, force: true });
}

// ═══ 5. У ЗАКАЗЧИКА ЕСТЬ СВОЙ НЕВЫЛОЖЕННЫЙ КОММИТ ══════════════════════════
//
// Тут ловится ошибка, найденная репетицией на живых данных 27.08.2026: ярлык
// сказал «привезли 15 файлов» там, где робот привёз 9. Шесть лишних были
// СОБСТВЕННЫЕ файлы заказчика: сравнение двух вершин напрямую (две точки)
// не различает, в какой стороне лежит разница. Считать надо от точки
// расхождения — тремя точками.
//
// И вторая половина того же случая: пост, который ещё не забран, лежит только
// в хранилище. Заголовок берётся ИЗ ТЕКСТА файла — значит текст надо взять
// оттуда же, иначе в списке встанет «пост (src/content/posts/ep-153.md)».
скажи('\n=== 5. У заказчика свой невыложенный коммит, робот привёз выпуск ===\n');
{
	const { корень, заказчик, робот } = построить();
	роботПривёз(робот, ПОСТ, постТекст('Совсем новый выпуск.'), 'Добавить черновики новых выпусков из RSS');

	// Заказчик записал у себя шесть своих файлов и не выложил их.
	mkdirSync(join(заказчик, 'своё'), { recursive: true });
	for (let н = 1; н <= 6; н += 1) writeFileSync(join(заказчик, 'своё', `файл-${н}.mjs`), 'моя работа\n');
	гит(заказчик, ['add', '-A']);
	гит(заказчик, ['commit', '-m', 'Моя работа']);

	const итог = прогнать(заказчик);
	// SHOW=1 печатает весь вывод прогона — на случай разбора, почему покраснело.
	if (process.env.SHOW) console.log('--- ВЫВОД ---\n' + итог.вывод + '\n--- код ' + итог.код);

	if (!ПОДЛОГ) {
		проверь(итог.код === 0, 'не упал');
		проверь(/ЖДЁТ В ХРАНИЛИЩЕ/.test(итог.вывод), 'показал, что лежит в хранилище, хотя забрать не мог');
		проверь(итог.вывод.includes(ЗАГОЛОВОК),
			'НАЗВАЛ ПОСТ ПО ЗАГОЛОВКУ, хотя файла на диске ещё нет — взял текст из хранилища');
		проверь(!/файл-1\.mjs/.test(итог.вывод) && !/служебные данные: [1-9]/.test(итог.вывод),
			'СВОИ ФАЙЛЫ В ЧУЖУЮ НОВОСТЬ НЕ ПОПАЛИ: считается от точки расхождения, а не двух вершин');
		проверь(/Моя работа/.test(гит(заказчик, ['log', '-1', '--format=%s'])),
			'свой коммит на месте, ничего не переписано');
	} else {
		проверь(true, 'ПОДЛОГ: этот случай стережёт не он');
	}

	rmSync(корень, { recursive: true, force: true });
}

скажи('');
if (ПОДЛОГ || ПОДЛОГ_СИЛОЙ) {
	if (бед > 0) {
		скажи(`✗ ПОДЛОГ НЕ СРАБОТАЛ КАК ЖДАЛИ: несошедшихся утверждений ${бед}.`);
		process.exit(1);
	}
	скажи(ПОДЛОГ
		? '✓ ПОДЛОГ ПОЙМАН: без забора админка открывается на вчерашнем.'
		: '✓ ПОДЛОГ ПОЙМАН: забор силой затирает правки заказчика.');
	process.exit(0);
}
if (бед > 0) {
	скажи(`✗ НЕ СОШЛОСЬ: ${бед}`);
	process.exit(1);
}
скажи('✓ ВСЁ СОШЛОСЬ: чужое забирается, служебное молчит, своё не затирается,');
скажи('  без интернета админка всё равно поднимется.');
process.exit(0);
