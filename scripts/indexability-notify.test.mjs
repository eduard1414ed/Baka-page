// ПРОВЕРКА ПИСЬМА ОБ ИНДЕКСИРУЕМОСТИ (hetzner/run-deploy.sh).
//
//   node scripts/indexability-notify.test.mjs           — проверить
//   node scripts/indexability-notify.test.mjs --подлог  — убедиться, что краснеет
//
// Три блока робота выкладки вынимаются ИЗ САМОГО ФАЙЛА по меткам-комментариям
// и запускаются в песочнице с заглушкой вместо notify.sh. Переписать их рядом
// нельзя: копия разошлась бы с первой же правкой робота.
//
// Проверяется то, из-за чего в проекте уже платили:
//   • вчерашнее замечание не приезжает как сегодняшнее (чистка перед прогоном);
//   • знаки & < > экранированы — иначе телеграм откажет и письма НЕ БУДЕТ ВОВСЕ;
//   • заголовок говорит исход: 🟡 когда состав выдачи изменился, 🚀 когда нет;
//   • нет новостей — нет и лишних слов в письме.

import { readFileSync, writeFileSync, mkdtempSync, rmSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const РОБОТ = new URL('../hetzner/run-deploy.sh', import.meta.url);

/** Вынуть блок робота по меткам. Текст берётся из самого файла. */
export function читатьБлок(текст, имя) {
	const от = текст.indexOf(`# ─── начало блока «${имя}»`);
	const до = текст.indexOf(`# ─── конец блока «${имя}»`);
	if (от < 0 || до < 0) return null;
	return текст.slice(текст.indexOf('\n', от), до);
}

let бед = 0;
const ок = (с) => console.log(`  ✓ ${с}`);
const плохо = (с) => { console.error(`  ✗ ${с}`); бед += 1; };

/**
 * Разыграть заход робота.
 *
 * @param {{вчера?: string, сегодня?: string, ошибки?: string}} что
 * @returns {{письмо: string, естьФайл: boolean}}
 */
function прогон({ вчера, сегодня, ошибки = '' }, блоки) {
	const дом = mkdtempSync(join(tmpdir(), 'baka-index-notify-'));
	try {
		const заглушка = join(дом, 'notify.sh');
		writeFileSync(заглушка, '#!/bin/bash\nprintf \'%s\' "$1" > "$(dirname "$0")/письмо.txt"\n');
		execFileSync('chmod', ['+x', заглушка]);

		// Вчерашнее замечание лежит на диске — файл закрыт .gitignore
		// и переживает заход.
		if (вчера) writeFileSync(join(дом, 'notify-index.md'), вчера);

		const сценарий = [
			'set -u',
			`cd "${дом}"`,
			`NOTIFY="${заглушка}"`,
			'STAMP="2026-08-30 12:00 UTC"',
			'BUILD_SEC="271"',
			'LOG="/root/baka-logs/deploy.log"',
			'MAIN_OK=1', 'MIRROR_OK=1', 'WARN=""',
			`ERRORS=${JSON.stringify(ошибки)}`,
			блоки.чистка,
			// «сегодняшняя работа»: сборка написала замечание или не написала
			сегодня ? `cat > notify-index.md <<'КОНЕЦ'\n${сегодня}КОНЕЦ` : ':',
			блоки.чтение,
			ошибки ? блоки.ошибка : блоки.письмо,
		].join('\n');

		execFileSync('bash', ['-c', сценарий], { stdio: 'pipe' });
		const п = join(дом, 'письмо.txt');
		return { письмо: existsSync(п) ? readFileSync(п, 'utf8') : '', естьФайл: existsSync(join(дом, 'notify-index.md')) };
	} finally {
		rmSync(дом, { recursive: true, force: true });
	}
}

function проверить(исходник) {
	const блоки = {
		чистка: читатьБлок(исходник, 'чистка замечаний индексируемости'),
		чтение: читатьБлок(исходник, 'замечания индексируемости'),
		письмо: читатьБлок(исходник, 'какое письмо о выкладке'),
	};
	for (const [имя, б] of Object.entries(блоки)) {
		if (!б) { плохо(`блок «${имя}» не нашёлся в run-deploy.sh — метки переписали`); return; }
	}
	// Ветка неудачи живёт вне размеченного блока: берём её строку как есть.
	const строкаОшибки = исходник.split('\n').find((с) => с.includes('Выкладка прошла не полностью'));
	блоки.ошибка = строкаОшибки ?? '';

	// 1. Вчерашнее не протекает
	const а = прогон({ вчера: 'Индексируемость тайтлов: −12 из выдачи. ПОЗАВЧЕРАШНЕЕ\n' }, блоки);
	if (а.письмо.includes('ПОЗАВЧЕРАШНЕЕ')) плохо('вчерашнее замечание приехало как сегодняшнее — чистка перед прогоном не работает');
	else ок('вчерашнее замечание стёрто и в письмо не попало');

	// 2. Нет новостей — обычный заголовок
	if (а.письмо.includes('🚀')) ок('новостей нет — письмо обычное, 🚀');
	else плохо(`новостей нет, а заголовок не 🚀: «${а.письмо.slice(0, 80)}»`);

	// 3. Сегодняшнее доезжает и меняет заголовок
	const б = прогон({ сегодня: 'Индексируемость тайтлов: +1 в выдачу, −3 из выдачи.\nВошли: tenki-no-ko\n' }, блоки);
	if (б.письмо.includes('tenki-no-ko')) ок('сегодняшнее замечание доехало до письма');
	else плохо(`сегодняшнее замечание в письмо не попало: «${б.письмо.slice(0, 120)}»`);
	if (б.письмо.includes('🟡')) ок('состав выдачи изменился — заголовок 🟡, отдельный исход');
	else плохо(`состав выдачи изменился, а заголовок не 🟡: «${б.письмо.slice(0, 80)}»`);

	// 4. Знаки & < > экранированы
	const в = прогон({ сегодня: 'Ушли БЕЗ объяснения: kaze&mizu, <Rewrite>\n' }, блоки);
	if (в.письмо.includes('&amp;') && в.письмо.includes('&lt;Rewrite&gt;')) {
		ок('знаки & < > экранированы — телеграм не откажет в приёме письма');
	} else {
		плохо(`знаки & < > уехали как есть — телеграм ответит отказом и письма не будет вовсе: «${в.письмо.slice(-80)}»`);
	}

	// 5. При ошибке выкладки замечание тоже доезжает
	const г = прогон({ сегодня: 'Ушли БЕЗ объяснения: naruto\n', ошибки: 'заливка зеркала не прошла\\n' }, блоки);
	if (г.письмо.includes('naruto') && г.письмо.includes('🔴')) ок('при неудачной выкладке замечание доезжает в красном письме');
	else плохо(`при неудачной выкладке замечание потерялось: «${г.письмо.slice(0, 140)}»`);
}

const исходник = readFileSync(РОБОТ, 'utf8');
const подлог = process.argv.includes('--подлог') || process.argv.includes('--selftest');

if (!подлог) {
	console.log('Письмо об индексируемости:');
	проверить(исходник);
	if (бед > 0) { console.error(`✗ Бед: ${бед}`); process.exitCode = 1; }
	else console.log('ок      Письмо об индексируемости: вчерашнее не течёт, знаки экранированы, заголовок говорит исход.');
} else {
	// ДВА ПОДЛОГА, И КАЖДЫЙ СНИМАЕТ РОВНО ОДНУ СТРОКУ — так, как это и случится
	// в жизни, когда её сочтут лишней. Снятие блока целиком тут не годится:
	// без блока не осталось бы и второй его половины.
	const подлоги = [
		['чистка', 'rm -f notify-index.md'],
		['экранирование', `escape_html() { sed -e 's/&/\\&amp;/g' -e 's/</\\&lt;/g' -e 's/>/\\&gt;/g'; }`],
	];
	let код = 0;
	for (const [имя, строка] of подлоги) {
		const было = исходник;
		const стало =
			имя === 'экранирование'
				? исходник.replace(строка, 'escape_html() { cat; }')
				: исходник.split('\n').filter((с) => с.trim() !== строка).join('\n');
		if (стало === было) {
			console.error(`✗ ПОДЛОГ «${имя}» НИЧЕГО НЕ ЗАМЕНИЛ: строки нет дословно, и его «поймал» ничего не значит.`);
			console.error(`   Искал: ${строка}`);
			код = 1;
			continue;
		}
		бед = 0;
		console.log(`Подлог «${имя}»:`);
		проверить(стало);
		if (бед === 0) { console.error(`✗ ПОДЛОГ «${имя}» НЕ ПОЙМАН: сняли строку, а проверка промолчала.`); код = 1; }
		else console.log(`  ✓ подлог «${имя}» пойман, бед ${бед}`);
	}
	бед = 0;
	console.log('Здоровый робот:');
	проверить(исходник);
	if (бед > 0) { console.error('✗ На здоровом роботе проверка красная — значит ловит себя.'); код = 1; }
	else console.log('  ✓ на здоровом роботе проверка молчит');
	process.exitCode = код;
}
