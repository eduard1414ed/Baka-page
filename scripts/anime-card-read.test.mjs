// КАРТОЧКА ТАЙТЛА ЧИТАЕТСЯ СКРИПТАМИ ТАК ЖЕ, КАК ЕЁ ЧИТАЕТ САЙТ.
//
//   node scripts/anime-card-read.test.mjs             — спросить
//   node scripts/anime-card-read.test.mjs --selftest  — плюс подлог: прежнее чтение
//
// ЗАЧЕМ. Sveltia на очищенное списковое поле пишет ПУСТУЮ СТРОКУ, а не
// пропускает его. Схема сайта это переживает с восьмого этапа
// (`emptyToUndefined` в `src/content.config.ts`), и правило записано уроком.
// **До скриптов оно не дошло:** они читают те же файлы сырыми, мимо схемы.
//
// ЧЕМ ЭТО УЖЕ СТОИЛО. 15 августа 2026 `scripts/anime-cases.mjs` — тот, что
// гоняет робот падежных форм, — ПАДАЛ на первой же такой карточке
// с `TypeError: было.every is not a function`. Сайт при этом собирался
// и все проверки были зелёными: схему-то починили. То есть беда жила ровно
// там, куда правило не прошли, и молчала.
//
// ЧИНИМ ЧТЕНИЕ, А НЕ ДАННЫЕ. Переписать карточки значило бы поспорить с тем,
// что пишет сама админка: первое же сохранение вернуло бы пустую строку назад.
//
// ЗАПИСЬ ПРИ ЭТОМ ОСТАЁТСЯ БАЙТ В БАЙТ. Приведение типов не имеет права
// доехать до диска: пересчёт форм переписал бы `aliases: ""` в `aliases: []`
// у чужих карточек, и разница пришла бы на восемь файлов, к которым он
// отношения не имеет.
import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readdir } from 'node:fs/promises';
import { нормализоватьКарточку, списком, readAnimeCollection, writeAliasesAuto } from './anime-cases-lib.mjs';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..');

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

console.log('КАРТОЧКА ТАЙТЛА: скрипты читают её так же, как сайт, а пишут байт в байт.');
console.log();

// ── 1. Приведение типов ───────────────────────────────────────────────────
console.log('── приведение ──');

скажи(Array.isArray(списком('')), 'пустая строка → список');
скажи(списком('').length === 0, 'и список этот пуст');
скажи(Array.isArray(списком(undefined)), 'поля нет → список');
скажи(Array.isArray(списком(null)), '`null` → список');
скажи(списком(['а', 'б']).length === 2, 'настоящий список остаётся собой');

// ПУСТАЯ СТРОКА И НЕПУСТАЯ — РАЗНЫЕ СЛУЧАИ, и второй тут опаснее: строку
// «Кэйон» можно было бы «привести» посимвольно и завести одиннадцать
// вариантов написания из одиннадцати букв. Не приводим: не список — значит
// списка нет.
скажи(списком('Кэйон').length === 0, 'непустая строка НЕ рассыпается на буквы');

const кривая = { id: 'x', titleRu: 'Тайтл', aliases: '', aliasesAuto: '' };
const ровная = нормализоватьКарточку(кривая);
скажи(Array.isArray(ровная.aliases) && Array.isArray(ровная.aliasesAuto), 'карточка с двумя пустыми строками приводится целиком');
скажи(ровная.titleRu === 'Тайтл' && ровная.id === 'x', 'остальные поля карточки не тронуты');

// ── 2. То самое место, где падало ─────────────────────────────────────────
// Спрашиваем НЕ пересказ, а сравнение из `anime-cases.mjs`: было/стало.
console.log();
console.log('── сравнение «было/стало», на котором падал робот падежей ──');

const сравнить = (было, стало) => было.length === стало.length && было.every((f, i) => f === стало[i]);
let упало = false;
try {
	сравнить(нормализоватьКарточку(кривая).aliasesAuto, []);
} catch {
	упало = true;
}
скажи(!упало, 'на приведённой карточке сравнение проходит');

// ── 3. Живые данные ───────────────────────────────────────────────────────
// Пример берётся ИЗ ДАННЫХ, а не вписывается именем. Но если его там нет —
// говорим об этом ВСЛУХ и идём дальше, а не падаем: правило может быть
// применено, и тогда примеру взяться неоткуда (записанный урок проекта).
console.log();
console.log('── живой справочник ──');

const ANIME = new URL('../src/content/anime/', import.meta.url);
const имена = (await readdir(ANIME)).filter((n) => n.endsWith('.json'));
const кривые = [];
for (const имя of имена) {
	const сырое = JSON.parse(await readFile(new URL(имя, ANIME), 'utf8'));
	for (const поле of ['aliases', 'aliasesAuto']) {
		if (поле in сырое && !Array.isArray(сырое[поле])) кривые.push(`${имя}: ${поле} = ${JSON.stringify(сырое[поле])}`);
	}
}
console.log(`  карточек в справочнике: ${имена.length}; полей-списков, записанных не списком: ${кривые.length}`);
for (const строка of кривые.slice(0, 10)) console.log(`      ${строка}`);
if (кривые.length === 0) {
	console.log('  ПРИМЕЧАНИЕ: сегодня таких карточек нет — значит живого примера у проверки');
	console.log('              нет, и держится она на подложенных. Это не повод её убирать:');
	console.log('              пустую строку пишет сама админка, и вернуться она может завтра.');
}

const справочник = await readAnimeCollection();
const всеСписками = справочник.every((e) => Array.isArray(e.data.aliases) && Array.isArray(e.data.aliasesAuto));
скажи(всеСписками, `после чтения списками стали все ${справочник.length} карточек`);
скажи(справочник.every((e) => e.сырое !== undefined), 'у каждой карточки сохранено сырое содержимое — из него идёт запись');

// ── 4. Запись байт в байт ─────────────────────────────────────────────────
console.log();
console.log('── запись не переписывает чужих полей ──');

const папка = await mkdtemp(join(tmpdir(), 'baka-anime-'));
try {
	const путь = join(папка, 'x.json');
	const исходный = { id: 'x', titleRu: 'Тайтл', aliases: '', manual: ['synopsis'] };
	await writeFile(путь, JSON.stringify(исходный, null, '\t') + '\n', 'utf8');

	const сырое = JSON.parse(await readFile(путь, 'utf8'));
	const запись = { file: 'x.json', url: pathToFileURL(путь), сырое, data: нормализоватьКарточку(сырое) };
	await writeAliasesAuto(запись, ['формa1', 'формa2']);

	const после = JSON.parse(await readFile(путь, 'utf8'));
	скажи(после.aliases === '', `чужое поле осталось как было: aliases = ${JSON.stringify(после.aliases)}`);
	скажи(Array.isArray(после.aliasesAuto) && после.aliasesAuto.length === 2, 'своё поле записано списком');
	скажи(JSON.stringify(после.manual) === JSON.stringify(['synopsis']), 'ручная пометка не тронута');

	// И вторая половина: пустой список УДАЛЯЕТ поле, а не пишет пустоту.
	await writeAliasesAuto({ ...запись, сырое: JSON.parse(await readFile(путь, 'utf8')) }, []);
	const после2 = JSON.parse(await readFile(путь, 'utf8'));
	скажи(!('aliasesAuto' in после2), 'пустой пересчёт убирает поле, а не кладёт пустоту');
	скажи(после2.aliases === '', 'и чужое поле по-прежнему нетронуто');
} finally {
	await rm(папка, { recursive: true, force: true });
}

// ── ПОДЛОГ ────────────────────────────────────────────────────────────────
// «Пусто» ничего не значит, пока не показано, что проверка умеет находить.
// Подлог возвращает ПРЕЖНЕЕ чтение — сырое, мимо приведения, — и обязан
// уронить ровно то сравнение, на котором падал робот.
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── ПОДЛОГ: прежнее чтение, сырое и мимо приведения ──');

	const прежнееЧтение = (данные) => данные; // ровно так было до 15 августа
	let поймано = false;
	let сообщение = '';
	try {
		const было = прежнееЧтение(кривая).aliasesAuto ?? [];
		сравнить(было, []);
	} catch (ошибка) {
		поймано = true;
		сообщение = String(ошибка.message).split('\n')[0];
	}
	скажи(поймано, `прежнее чтение роняет сравнение: ${сообщение || '(не упало)'}`);

	// И ВТОРАЯ ПОЛОВИНА: на здоровой карточке прежнее чтение работало, значит
	// проверка не должна называть бедой всё подряд.
	const здоровая = { id: 'y', aliases: ['а'], aliasesAuto: ['б'] };
	let ровно = false;
	try {
		сравнить(прежнееЧтение(здоровая).aliasesAuto, ['б']);
		ровно = true;
	} catch {
		ровно = false;
	}
	скажи(ровно, 'на карточке со списками прежнее чтение не падало — проверка ругается не на всё');
}

console.log();
if (плохо) {
	console.log(`ПРОВАЛОВ: ${плохо}`);
	process.exit(1);
}
console.log('Скрипты читают карточку как сайт, а пишут её как лежала.');
