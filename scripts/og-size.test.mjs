// ПРОВЕРКА ПРАВИЛА РАЗМЕРА ПРЕВЬЮ (src/lib/ogImage.mjs, `ogSize`).
//
// Спрашивает три вещи, и все три — то, из-за чего правку и делали
// (20 августа 2026, жалоба заказчика на превью в телеграме):
//
//   1. ФОРМА СОХРАНЯЕТСЯ. Пропорция превью совпадает с пропорцией обложки.
//      Именно этого не было раньше: всё сводилось к полосе 1200×630, и вокруг
//      квадратной обложки бонуса появлялись бумажные поля.
//   2. ПРЕДЕЛ СВЕРХУ. Длинная сторона не больше OG_MAX_SIDE — иначе в каждую
//      ссылку уезжают лишние килобайты.
//   3. ПРЕДЕЛ СНИЗУ. Короткая сторона не меньше OG_MIN_SIDE, НАСКОЛЬКО ЭТО
//      ВОЗМОЖНО в пределах пункта 2: маленькое превью соцсети показывают
//      уголком вместо большой карточки, а постеры тайтлов приходят мелкими.
//
// Размеры берутся ИЗ ЖИВЫХ ДАННЫХ — из настоящих обложек архива, а не из
// придуманного списка: правило про них и написано. Нечего измерить (папок
// с картинками нет) — скрипт говорит об этом вслух и берёт записанный образец,
// а не молчит и не падает.
//
//   node scripts/og-size.test.mjs             — проверить
//   node scripts/og-size.test.mjs --selftest  — вернуть ПРЕЖНЕЕ правило
//                                               (полоса 1200×630) и убедиться,
//                                               что проверка краснеет
//
// ЗАЧЕМ ПОДЛОГ. Проверка, которая не может провалиться, — это ложь в сторону
// «всё хорошо». Подлог здесь возвращает ровно то правило, что стояло в проекте
// до правки: если однажды кто-то вернёт полосу, проверка обязана покраснеть.

import { readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import sharp from 'sharp';
import { ogSize, OG_MAX_SIDE, OG_MIN_SIDE, OG_DEFAULT_WIDTH, OG_DEFAULT_HEIGHT } from '../src/lib/ogImage.mjs';

const selftest = process.argv.includes('--selftest');

/** Прежнее правило: всё сводилось к одной полосе. Только для подлога. */
const прежнееПравило = () => ({ width: 1200, height: 630 });

const правило = selftest ? прежнееПравило : ogSize;

/** Записанный образец — на случай, если живых картинок под рукой нет. */
const ОБРАЗЕЦ = [
	{ width: 2000, height: 2000, откуда: 'обложка выпуска' },
	{ width: 1200, height: 1200, откуда: 'обложка бонуса' },
	{ width: 1920, height: 1080, откуда: 'кадр 16:9' },
	{ width: 486, height: 1000, откуда: 'вытянутый вверх' },
	{ width: 1000, height: 343, откуда: 'вытянутый вширь' },
	{ width: 225, height: 320, откуда: 'постер тайтла' },
];

/** Живые размеры: сколько-то настоящих обложек и постеров архива. */
async function живыеРазмеры() {
	const корень = new URL('../', import.meta.url);
	const папки = [
		{ путь: new URL('public/images/uploads/', корень), сколько: 60, откуда: 'обложка из админки' },
		{ путь: new URL('public/anime/', корень), сколько: 40, откуда: 'постер тайтла' },
		{ путь: new URL('public/cutout/', корень), сколько: 20, откуда: 'вырезанный персонаж' },
	];

	const найдено = [];
	for (const { путь, сколько, откуда } of папки) {
		const dir = fileURLToPath(путь);
		if (!existsSync(dir)) continue;
		const файлы = (await readdir(dir))
			.filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
			.sort()
			.slice(0, сколько);
		for (const f of файлы) {
			try {
				const m = await sharp(fileURLToPath(new URL(f, путь))).metadata();
				if (m.width && m.height) найдено.push({ width: m.width, height: m.height, откуда: `${откуда} ${f}` });
			} catch {
				// Битый или неизвестный файл — не повод ронять проверку правила.
			}
		}
	}
	return найдено;
}

const беды = [];

function проверить({ width, height, откуда }) {
	const r = правило(width, height);
	const было = width / height;
	const стало = r.width / r.height;

	// Округление до целых пикселей сдвигает пропорцию на доли процента.
	// Порог 1 % — это заведомо больше округления и заведомо меньше любой
	// настоящей подгонки: полоса из квадрата даёт расхождение в 90 %.
	if (Math.abs(стало - было) / было > 0.01) {
		беды.push(`форма не сохранилась: ${width}×${height} (${было.toFixed(2)}) → ${r.width}×${r.height} (${стало.toFixed(2)})   ${откуда}`);
	}

	const длинная = Math.max(r.width, r.height);
	if (длинная > OG_MAX_SIDE) {
		беды.push(`длинная сторона ${длинная} больше предела ${OG_MAX_SIDE}: ${width}×${height} → ${r.width}×${r.height}   ${откуда}`);
	}

	// Снизу спрашиваем только там, где предел сверху этого не запрещает:
	// у вытянутой картинки короткая сторона обязана остаться маленькой.
	const короткая = Math.min(r.width, r.height);
	const вытянутость = Math.max(width, height) / Math.min(width, height);
	const влезаетЛи = OG_MIN_SIDE * вытянутость <= OG_MAX_SIDE;
	if (влезаетЛи && короткая < OG_MIN_SIDE) {
		беды.push(`короткая сторона ${короткая} меньше предела ${OG_MIN_SIDE}, хотя влезала: ${width}×${height} → ${r.width}×${r.height}   ${откуда}`);
	}
}

const живые = await живыеРазмеры();
const образцы = живые.length > 0 ? живые : ОБРАЗЕЦ;
if (живые.length === 0) {
	console.log('⚑ Живых картинок не нашлось (нет папок public/images/uploads, public/anime, public/cutout) — беру записанный образец.');
} else {
	console.log(`Живых обложек и постеров взято: ${живые.length}.`);
}

// Записанный образец гоняем ВСЕГДА, даже когда есть живые: в нём лежат крайние
// случаи архива, а первые по алфавиту живые файлы могут их и не содержать.
for (const с of [...образцы, ...ОБРАЗЕЦ]) проверить(с);

// Размеров нет вовсе — превью рисовать не из чего, и правило обязано отдать
// размер общей картинки сайта, а не ноль и не бесконечность.
const пусто = ogSize(0, 0);
if (!selftest && (пусто.width !== OG_DEFAULT_WIDTH || пусто.height !== OG_DEFAULT_HEIGHT)) {
	беды.push(`на нечитаемых размерах правило отдало ${пусто.width}×${пусто.height}, а должно размер общей картинки`);
}

if (selftest) {
	if (беды.length === 0) {
		console.error('✗ ПОДЛОГ НЕ ПОЙМАН: вернули прежнее правило (полоса 1200×630), а проверка промолчала. Чинить надо проверку.');
		process.exit(1);
	}
	console.log(`✓ Подлог пойман: прежнее правило дало ${беды.length} нарушений. Вот первые три:`);
	for (const б of беды.slice(0, 3)) console.log('   ' + б);
	console.log('  Проверка умеет краснеть.');
	process.exit(0);
}

if (беды.length > 0) {
	console.error(`✗ Правило размера превью нарушено в ${беды.length} случаях:`);
	for (const б of беды) console.error('   ' + б);
	process.exit(1);
}

console.log(`ок      Правило размера превью: проверено образцов ${образцы.length + ОБРАЗЕЦ.length}, форма сохраняется у всех, пределы ${OG_MIN_SIDE}…${OG_MAX_SIDE} соблюдены.`);
