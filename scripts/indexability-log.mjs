// ЛОГ ПЕРЕХОДОВ ИНДЕКСИРУЕМОСТИ + ДВА ЗАСЛОНА. Шаг сборки, после `astro build`.
//
// Читает рабочий файл `dist/indexability.json` (его кладёт эндпоинт
// src/pages/indexability.json.ts), сравнивает с прошлой сборкой НА ЭТОЙ
// МАШИНЕ, пишет `build-logs/indexability-ГГГГ-ММ-ДД.json` и удаляет рабочий
// файл — на сайте ему делать нечего.
//
// ДВА ЗАСЛОНА, И ОНИ РАЗНЫЕ.
//
//   1. КАТАСТРОФА — роняет сборку. Ловит не сдвиг, а поехавшие данные:
//      в индекс не попала НИ ОДНА страница либо ни у одной страницы нет
//      ни одного своего упоминания. Порог тут ноль, а не доля, как
//      у scripts/check-players.mjs. Заслону не нужна история, поэтому он
//      работает и на чистой машине, где прошлого лога нет вовсе.
//
//   2. СДВИГ — только говорит вслух, сборку НЕ роняет. Решение заказчика
//      от 30 августа 2026; задание требовало падения. Довод принят, но
//      у решения есть слепое пятно, и оно записано здесь, чтобы не потерялось:
//      большинство сборок делает Hetzner по расписанию, и консоль там никто
//      не читает. Поэтому предупреждение ложится ЕЩЁ И В ЛОГ, а со временем
//      ему стоит завести строчку в письме робота.
//
// ПОЧЕМУ СЧИТАЕТСЯ ТОЛЬКО `left`, А НЕ ВСЕ ПЕРЕМЕНЫ. `entered` — это работа
// сайта, а не тревога: упоминания копятся, страницы входят в индекс сами.
// И число их тем больше, чем реже собирается машина: на Hetzner сборки каждые
// четверть часа, а на машине заказчика прошлый лог может быть двухнедельным.
// Считай мы обе стороны — порог срабатывал бы на здоровых данных именно там,
// где человек меньше всего готов разбираться.

import { readFile, writeFile, unlink, readdir, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { ПРЕДЕЛ_ПЕРЕМЕН, ХРАНИТЬ_ЛОГОВ } from '../src/lib/animeIndexability.mjs';

const РАБОЧИЙ = new URL('../dist/indexability.json', import.meta.url);
const ЛОГИ = new URL('../build-logs/', import.meta.url);

/**
 * Что изменилось с прошлой сборки.
 *
 * `left` делится надвое, и это главное различие всего файла:
 *
 *   объяснённые   — страница лишилась упоминаний, которых В ЭТОЙ СБОРКЕ нет
 *                   среди постов вообще. То есть пост удалили или сняли
 *                   с публикации. Обычная работа заказчика: строчка в логе.
 *   необъяснённые — пост на месте, а упоминание пропало. Вот это и есть
 *                   «поехал матчинг», и вот об этом надо кричать.
 *
 * Задание считает любую непустую `left` признаком поломки. На живых данных
 * это неверно: посты удаляются регулярно (восемь удалений за две недели
 * августа 2026), и заслон, краснеющий на обычной работе, снимут вместе
 * с пользой.
 *
 * Третья причина, о которой честно говорит текст предупреждения: заказчик
 * переписал текст поста, и название тайтла из него ушло. Формально данные
 * действительно поехали, но беды тут нет.
 *
 * @returns {{ entered: string[], left: string[], объяснённые: string[], необъяснённые: string[] }}
 */
export function переходы(прежний, нынешний) {
	if (!прежний) return { entered: [], left: [], объяснённые: [], необъяснённые: [] };

	const былиВИндексе = new Set(прежний.pages.filter((p) => p.index).map((p) => p.id));
	const сталиВИндексе = new Set(нынешний.pages.filter((p) => p.index).map((p) => p.id));

	const entered = [...сталиВИндексе].filter((id) => !былиВИндексе.has(id)).sort();
	const left = [...былиВИндексе].filter((id) => !сталиВИндексе.has(id)).sort();

	const постыСейчас = new Set(нынешний.posts ?? []);
	const прежниеСтраницы = new Map(прежний.pages.map((p) => [p.id, p]));
	const нынешниеСтраницы = new Map(нынешний.pages.map((p) => [p.id, p]));

	const объяснённые = [];
	const необъяснённые = [];
	for (const id of left) {
		const было = new Set(прежниеСтраницы.get(id)?.своиПосты ?? []);
		const стало = new Set(нынешниеСтраницы.get(id)?.своиПосты ?? []);
		const потеряно = [...было].filter((p) => !стало.has(p));
		// Ни одного потерянного упоминания — значит страницу закрыло что-то
		// другое (например, поглощение соседом): это не пропажа данных.
		const всеПотерянныеИсчезли = потеряно.length > 0 && потеряно.every((p) => !постыСейчас.has(p));
		(всеПотерянныеИсчезли ? объяснённые : необъяснённые).push(id);
	}
	return { entered, left, объяснённые, необъяснённые };
}

/**
 * ЗАСЛОН БЕЗ ИСТОРИИ. Возвращает строку беды или null.
 *
 * Спрашивает то, чего не может быть при исправных данных, и потому не стареет
 * и не требует прошлого лога. Ноль как порог выбран не для строгости: любая
 * доля («упало больше половины») на растущем архиве однажды сработает
 * законно, а ноль — никогда.
 */
export function катастрофа({ всего, вИндексе, соСвоими }) {
	if (всего === 0) return 'страниц тайтлов в сборке нет вовсе — читать нечего';
	if (вИндексе === 0) return `в индекс не попало НИ ОДНОЙ страницы из ${всего}`;
	if (соСвоими === 0) return `ни у одной страницы из ${всего} нет ни одного своего упоминания`;
	return null;
}

/**
 * ТЕКСТ ДЛЯ БОТА В ТЕЛЕГРАМЕ. Возвращает строки или null, если сказать нечего.
 *
 * Пишется ПРОСТЫМ ТЕКСТОМ, без разметки: письмо уходит с `parse_mode=HTML`,
 * и `run-deploy.sh` экранирует это содержимое целиком (`& < >`). Поставь мы
 * сюда `<b>`, оно уехало бы в письмо буквами. Заголовок с разметкой добавляет
 * шелл — так же, как у робота телеграма и робота выпусков.
 *
 * ПИШЕТСЯ ТОЛЬКО КОГДА ЕСТЬ О ЧЁМ СКАЗАТЬ. Робот выкладки собирает сайт
 * каждые десять минут; строчка «изменений нет» в каждом письме через неделю
 * похоронит под собой то, ради чего письмо читают. Нет новостей — нет файла.
 *
 * ПОРОГ `ПРЕДЕЛ_ПЕРЕМЕН` ЗДЕСЬ НЕ ДЕЙСТВУЕТ, И ЭТО НАРОЧНО. Он написан про
 * машину заказчика, где между сборками бывает две недели; на сервере сборка
 * каждые десять минут, и сорока перемен там не наберётся никогда — то есть
 * письмо не пришло бы ни разу. Заказчик просил сообщать, «когда что-то
 * меняется», поэтому здесь новостью считается любая перемена.
 *
 * @returns {string | null}
 */
export function письмоОбИндексируемости({ entered, объяснённые, необъяснённые, indexed, total, когда }) {
	if (entered.length === 0 && объяснённые.length === 0 && необъяснённые.length === 0) return null;

	const список = (ids) => ids.slice(0, 10).join(', ') + (ids.length > 10 ? ` и ещё ${ids.length - 10}` : '');
	const ушло = объяснённые.length + необъяснённые.length;
	const строки = [];

	const части = [];
	if (entered.length) части.push(`+${entered.length} в выдачу`);
	if (ушло) части.push(`−${ушло} из выдачи`);
	строки.push(`Индексируемость тайтлов: ${части.join(', ')}. Сейчас в выдаче ${indexed} из ${total}.`);

	if (когда) строки.push(`Считаю от прошлой сборки (${когда}).`);
	if (entered.length) строки.push(`Вошли: ${список(entered)}`);
	if (объяснённые.length) строки.push(`Ушли, потому что посты удалены или сняты с публикации: ${список(объяснённые)}`);
	if (необъяснённые.length) {
		строки.push(`Ушли БЕЗ объяснения: ${список(необъяснённые)}`);
		строки.push(
			'Посты на месте, а упоминания пропали. Причин три: вы переписали тексты и названия ' +
				'из них ушли; правило меняли нарочно; поехал разбор упоминаний — вот это беда.',
		);
	}
	return строки.join('\n');
}

const ддммгг = (d) => d.toISOString().slice(0, 10);

async function главная() {
	if (!existsSync(fileURLToPath(РАБОЧИЙ))) {
		console.error('✗ Нет dist/indexability.json — сборка не дошла до эндпоинта индексируемости.');
		console.error('  Что делать: собрать заново (npm run build). Если повторяется — смотреть');
		console.error('  src/pages/indexability.json.ts, он мог упасть на чтении коллекций.');
		return 1;
	}
	const нынешний = JSON.parse(await readFile(РАБОЧИЙ, 'utf8'));

	await mkdir(fileURLToPath(ЛОГИ), { recursive: true });
	const имена = (await readdir(ЛОГИ)).filter((f) => /^indexability-\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort();
	// Читаем прошлый лог ДО записи нынешнего: сегодняшний файл уже может быть
	// на месте, если сборку сегодня запускали не в первый раз.
	const прежнееИмя = имена.at(-1) ?? null;
	const прежний = прежнееИмя ? JSON.parse(await readFile(new URL(прежнееИмя, ЛОГИ), 'utf8')) : null;

	const всего = нынешний.pages.length;
	const вИндексе = нынешний.pages.filter((p) => p.index).length;
	const соСвоими = нынешний.pages.filter((p) => p.свои > 0).length;
	const { entered, left, объяснённые, необъяснённые } = переходы(прежний, нынешний);

	const распределение = {};
	for (const p of нынешний.pages) распределение[p.счёт] = (распределение[p.счёт] ?? 0) + 1;
	const forced = {
		in: нынешний.pages.filter((p) => p.force === true).length,
		out: нынешний.pages.filter((p) => p.force === false).length,
	};
	const поглощено = нынешний.pages.filter((p) => p.причина === 'поглощена').length;

	console.log(
		`        Индексируемость тайтлов: в индексе ${вИндексе} из ${всего}, закрыто ${всего - вИндексе} ` +
			`(поглощено сезонами ${поглощено}, вручную +${forced.in}/−${forced.out}).`,
	);

	const беда = катастрофа({ всего, вИндексе, соСвоими });
	if (беда) {
		console.error(`ПРОВАЛ  Индексируемость: ${беда}.`);
		console.error('        Это не «сдвиг», а поехавшие данные: так выглядит отвалившийся разбор');
		console.error('        упоминаний. Выкладывать такую сборку нельзя — весь каталог тайтлов');
		console.error('        исчез бы из поиска молча.');
		console.error('        Что делать: позвать Claude Code и показать эту строку.');
		return 1;
	}

	const замечания = [];
	if (прежний) {
		const когда = прежний.builtAt ? прежний.builtAt.slice(0, 10) : прежнееИмя;
		if (объяснённые.length > 0) {
			console.log(`        Выпали из индекса из-за удалённых постов: ${объяснённые.length}. Это обычная работа.`);
		}
		if (необъяснённые.length >= ПРЕДЕЛ_ПЕРЕМЕН) {
			const строка =
				`С прошлой сборки на этой машине (${когда}) из индекса выпало ${необъяснённые.length} страниц, ` +
				'и удалением постов это не объясняется.';
			замечания.push(строка);
			console.warn(`ВНИМАНИЕ ${строка}`);
			console.warn('        Первые десять: ' + необъяснённые.slice(0, 10).join(', '));
			console.warn('        Три причины, в порядке вероятности: (1) вы переписали тексты, и названия');
			console.warn('        из них ушли; (2) правило индексируемости меняли нарочно; (3) поехал разбор');
			console.warn('        упоминаний — вот это беда, и тогда позовите Claude Code.');
			console.warn('        Сайт при этом выложится: остановки тут нет по вашему решению.');
		} else if (необъяснённые.length > 0) {
			console.log(`        Выпали из индекса без объяснения: ${необъяснённые.length} (${необъяснённые.slice(0, 5).join(', ')}).`);
		}
	}

	const лог = {
		builtAt: нынешний.builtAt,
		предыдущийЛог: прежнееИмя,
		total: всего,
		indexed: вИндексе,
		excluded: всего - вИндексе,
		absorbed: поглощено,
		forced,
		entered,
		left,
		leftОбъяснённые: объяснённые,
		leftНеобъяснённые: необъяснённые,
		замечания,
		scoreDistribution: распределение,
		posts: нынешний.posts,
		pages: нынешний.pages,
	};
	await writeFile(new URL(`indexability-${ддммгг(new Date())}.json`, ЛОГИ), JSON.stringify(лог, null, '\t') + '\n', 'utf8');

	// Черновик письма для бота. Файл пишется ТОЛЬКО когда есть новость;
	// стирает его перед прогоном сам робот выкладки (hetzner/run-deploy.sh),
	// иначе вчерашняя новость приехала бы как сегодняшняя — этой граблей
	// проект уже платил письмом про выпуск, расшифрованный накануне.
	const ключ = process.argv.find((a) => a.startsWith('--notify='));
	if (ключ) {
		const текст = письмоОбИндексируемости({
			entered,
			объяснённые,
			необъяснённые,
			indexed: вИндексе,
			total: всего,
			когда: прежний?.builtAt?.slice(0, 10) ?? null,
		});
		if (текст) await writeFile(new URL(ключ.slice('--notify='.length), new URL('../', import.meta.url)), текст + '\n', 'utf8');
	}

	// Старые логи убираем: они нужны только для диффа с последним.
	const порог = Date.now() - ХРАНИТЬ_ЛОГОВ * 86400000;
	for (const имя of имена) {
		const д = Date.parse(имя.slice('indexability-'.length, -'.json'.length));
		if (Number.isFinite(д) && д < порог) await unlink(new URL(имя, ЛОГИ)).catch(() => {});
	}

	await unlink(РАБОЧИЙ).catch(() => {});
	return 0;
}

// Русские буквы в пути: import.meta.url их кодирует, process.argv[1] — нет.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
	process.exitCode = await главная();
}
