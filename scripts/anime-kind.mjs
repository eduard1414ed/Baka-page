// ДОБОР ПОЛЯ `kind` В КАРТОЧКИ ТАЙТЛОВ — ЧТО ЭТО ЗА ПРОИЗВЕДЕНИЕ.
//
//   node scripts/anime-kind.mjs --сколько=10   — пробный прогон
//   node scripts/anime-kind.mjs                — все, у кого поля нет
//   node scripts/anime-kind.mjs --обновить     — перечитать и тех, у кого есть
//
// ЗАЧЕМ. Страница тайтла говорит поисковику, что она про произведение,
// но не говорит, про какое: сериал это, фильм или короткометражка. В разметке
// это разница между `CreativeWork` («что-то сделанное человеком») и `Movie`
// с `TVSeries` — типами, которые поисковик знает и умеет связывать с тем, что
// уже знает о фильме. Разбор типа живёт в `animeSchemaType`
// (src/lib/schema.mjs), сюда он ходит за словом.
//
// Поле приходит в том же ответе `GET /api/animes/<id>`, что и франшиза:
// новых обращений к чужому серверу не добавляется, читается ещё одно поле.
// Значения Shikimori: tv, movie, ova, ona, special, tv_special, music, pv, cm.
//
// ПУСТО — ЭТО ОТВЕТ, А НЕ ПРОПУСК. `null` значит «спросили, тип не назван»
// и отличается от «не спрашивали» (поля нет вовсе) — то же правило, что
// у франшизы.

import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { доборПоля } from './anime-field-lib.mjs';

// Русские буквы в пути: import.meta.url их кодирует, process.argv[1] — нет.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
	process.exitCode = await доборПоля({
		имяПоля: 'kind',
		прочитать: (данные) => данные.kind || null,
		// После франшизы: оба поля пришли из одного ответа и описывают
		// само произведение, а не наше к нему отношение.
		послеКлюча: 'franchise',
		назвать: (kind) => kind ?? '(тип не назван)',
		арг: process.argv.slice(2),
	});
}
