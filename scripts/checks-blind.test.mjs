// ТРИ ПРОВЕРКИ СОБРАННОГО САЙТА УМЕЮТ ЗАМЕТИТЬ, ЧТО ОСЛЕПЛИ.
//
//   node scripts/checks-blind.test.mjs   (после `npm run build`)
//
// ЗАЧЕМ. `check-css`, `check-hidden` и `check-edges` собирают стили страницы
// по ссылкам в разметке. Файл, который не прочитался, пропускался МОЛЧА,
// и «пусто — нарушений нет» выглядело одинаково и когда нарушений правда нет,
// и когда проверка не увидела ни одного правила (ревизия задачи 15, находка 6).
// За проект такое случалось ШЕСТЬ раз, и всегда в эту сторону.
//
// ЧТО СПРАШИВАЕТСЯ. Не «есть ли счётчик» (строку легко написать и легко
// забыть обновить), а ПОВЕДЕНИЕ: если увести у страниц файл стилей,
// проверка обязана ПОКРАСНЕТЬ и назвать пропажу, а не отчитаться «чисто».
//
// ПОДЛОГ УВОДИТ ФАЙЛ, А НЕ ПОРТИТ ЕГО. Испорченный файл проверка прочитает
// и разберёт как сможет — это другой случай. Нас интересует ровно тот,
// на котором наступали: имя файла стилей поменялось или файл переехал,
// ссылка в разметке ведёт в никуда, и правил не видно вовсе.
//
// РАБОТАЕМ НА КОПИИ СБОРКИ, А НЕ НА `dist/`. Двигать файлы в живой сборке
// нельзя: оборвись прогон посередине — и на диске останется покалеченная
// сборка, которую кто-нибудь выложит. Копия делается только из того,
// что нужно проверкам.
import { cp, rm, mkdtemp, readdir, rename, readFile, appendFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { spawn } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const КОРЕНЬ = join(ЗДЕСЬ, '..');
const DIST = join(КОРЕНЬ, 'dist');

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

if (!existsSync(DIST)) {
	console.log('Сборки нет — сначала `npm run build`. Ничего не проверял.');
	process.exit(1);
}

/** Прогнать проверку в песочнице и вернуть исход с выводом. */
function прогнать(скрипт, ключи, где) {
	return new Promise((готово) => {
		const дитя = spawn(process.execPath, [join(ЗДЕСЬ, скрипт), ...ключи], { cwd: где, stdio: ['ignore', 'pipe', 'pipe'] });
		let вывод = '';
		дитя.stdout.on('data', (к) => (вывод += к));
		дитя.stderr.on('data', (к) => (вывод += к));
		дитя.on('close', (код) => готово({ код, вывод }));
	});
}

// ── Песочница ─────────────────────────────────────────────────────────────
// Берём НЕ всю сборку (полгигабайта), а по одной странице каждого вида плюс
// файлы стилей: проверкам этого довольно, а копирование укладывается в секунды.
const песочница = await mkdtemp(join(tmpdir(), 'baka-checks-'));
const песДист = join(песочница, 'dist');

const СТРАНИЦЫ = ['index.html', '404.html', join('about', 'index.html'), join('posts', 'ep-10', 'index.html')].filter((п) =>
	existsSync(join(DIST, п)),
);

try {
	await cp(join(DIST, '_astro'), join(песДист, '_astro'), { recursive: true });
	for (const страница of СТРАНИЦЫ) {
		await cp(join(DIST, страница), join(песДист, страница), { recursive: true });
	}
	// `check-css` читает палитру из исходников, а не из сборки.
	await cp(join(КОРЕНЬ, 'src', 'styles'), join(песочница, 'src', 'styles'), { recursive: true });

	console.log('ПРОВЕРКИ СОБРАННОГО САЙТА: умеют ли они заметить, что ослепли.');
	console.log(`Песочница: ${СТРАНИЦЫ.length} страниц + файлы стилей.`);
	console.log();

	// ── ЗДОРОВЫЙ СЛУЧАЙ ───────────────────────────────────────────────────
	// Без него «поймала» неотличимо от «ругается на всё подряд».
	console.log('── на здоровой сборке обязаны молчать ──');
	for (const [скрипт, ключи] of [
		['check-css.mjs', []],
		['check-hidden.mjs', []],
		['check-edges.mjs', ['--образцы', '1440']],
	]) {
		const { код, вывод } = await прогнать(скрипт, ключи, песочница);
		const считало = /Разобрано: /.test(вывод);
		const числа = вывод.match(/Разобрано: [^\n]+/)?.[0] ?? '(строки охвата нет)';
		скажи(код === 0 && считало, `${скрипт.padEnd(18)} код ${код}; ${числа}`);
	}

	// ── ПОДЛОГ: файлы стилей уехали ───────────────────────────────────────
	console.log();
	console.log('── ПОДЛОГ: файлы стилей уведены, ссылки в разметке ведут в никуда ──');

	const было = join(песДист, '_astro');
	const стало = join(песочница, '_astro-уведён');
	await rename(было, стало);
	const сколькоУвели = (await readdir(стало)).filter((н) => н.endsWith('.css')).length;
	console.log(`  уведено файлов стилей: ${сколькоУвели}`);

	for (const [скрипт, ключи, чтоЖдём] of [
		['check-css.mjs', [], 'ОСЛЕПЛА'],
		['check-hidden.mjs', [], 'НЕ ПРОЧИТАЛОСЬ'],
		['check-edges.mjs', ['--образцы', '1440'], 'НЕ ПРОЧИТАЛОСЬ'],
	]) {
		const { код, вывод } = await прогнать(скрипт, ключи, песочница);
		const покраснела = код !== 0;
		const назвала = вывод.includes(чтоЖдём);
		скажи(покраснела && назвала, `${скрипт.padEnd(18)} код ${код}, сказала «${чтоЖдём}»: ${назвала ? 'да' : 'НЕТ'}`);
		if (!покраснела || !назвала) console.log(`          вывод: ${JSON.stringify(вывод.slice(0, 400))}`);
	}

	// ── И ОБРАТНО ─────────────────────────────────────────────────────────
	// Проверка, которая покраснела и осталась красной, ничего не доказывает:
	// надо показать, что она возвращается в зелёное, когда беду убрали.
	console.log();
	console.log('── файлы возвращены — обязаны снова молчать ──');
	await rename(стало, было);
	for (const [скрипт, ключи] of [
		['check-css.mjs', []],
		['check-hidden.mjs', []],
		['check-edges.mjs', ['--образцы', '1440']],
	]) {
		const { код } = await прогнать(скрипт, ключи, песочница);
		скажи(код === 0, `${скрипт.padEnd(18)} код ${код}`);
	}
	// ── ВТОРОЙ ПОДЛОГ: НАСТОЯЩЕЕ НАРУШЕНИЕ ────────────────────────────────
	// Слепота и слепое пятно — разные беды. Проверка может честно разобрать
	// все правила и всё равно не найти нарушения, если её собственное правило
	// сломалось от опечатки. Спрашиваем тем же приёмом, что у `check-assets`:
	// дописать в собранный CSS правило, нарушающее каждый пункт, убедиться,
	// что поймано, и вернуть файл.
	//
	// ПРАВИЛО ПИШЕТСЯ ТАК, КАК ПИШУТ В ЖИЗНИ, а не переписывает формулировку
	// проверки: подлог, списанный с проверки, проверяет не её, а собственную
	// аккуратность (записанный урок проекта).
	console.log();
	console.log('── ПОДЛОГ: живое нарушение дописано в собранный CSS ──');

	const стилиПес = join(песДист, '_astro');
	const первыйCss = (await readdir(стилиПес)).filter((н) => н.endsWith('.css')).sort()[0];
	const путьCss = join(стилиПес, первыйCss);
	const целыйCss = await readFile(путьCss, 'utf8');

	const НАРУШЕНИЕ = [
		'.podlog-note{font-size:9px}',
		'.podlog-force{color:#ff0000!important}',
		'.podlog-both{display:none;grid-template-columns:1fr 1fr}',
		// `auto-fit` — именно та схлопывающая сетка, которую ищет пункт 4.
		// Первый подлог был написан с `repeat(3,1fr)` и НЕ ловился — но виновата
		// была не проверка, а подлог: пункт про `auto-fit`, а не про сетку вообще.
		'.podlog-grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(200px,1fr))}',
		'.podlog-color{background:#123456}',
	].join('\n');

	await appendFile(путьCss, '\n' + НАРУШЕНИЕ + '\n', 'utf8');
	try {
		const { код, вывод } = await прогнать('check-css.mjs', [], песочница);
		const пункты = [
			['Размеры шрифта меньше 11 px', 'podlog-note'],
			['Пометки принудительного приоритета', 'podlog-force'],
			['Видимость и раскладка в одном правиле', 'podlog-both'],
			['Сетка схлопывающая вместо заполняющей', 'podlog-grid'],
			['Цвета мимо палитры', 'podlog-color'],
		];
		скажи(код !== 0, `check-css покраснела на живом нарушении: код ${код}`);
		for (const [пункт, класс] of пункты) {
			скажи(вывод.includes(класс), `поймано «${пункт}» (${класс})`);
		}
	} finally {
		await writeFile(путьCss, целыйCss, 'utf8');
	}

	// И проверка обязана снова молчать после возврата файла — иначе мы не знаем,
	// вернули ли мы всё.
	{
		const { код } = await прогнать('check-css.mjs', [], песочница);
		скажи(код === 0, `после возврата файла check-css снова молчит: код ${код}`);
	}

	// ── ТО ЖЕ ДЛЯ `check-hidden` ──────────────────────────────────────────
	// Класс берём ИЗ ДАННЫХ: у элемента, который в песочнице правда помечен
	// `hidden`. Вписанный именем протух бы от первой правки вёрстки.
	const разметка = await readFile(join(песДист, СТРАНИЦЫ[0]), 'utf8');
	const сHidden = [...разметка.matchAll(/<\w+((?:\s+[^\s=>]+(?:=(?:"[^"]*"|'[^']*'|[^\s>]+))?)*)\s*\/?>/g)]
		.filter((т) => /(?:^|\s)hidden(?:=|\s|$)/.test(т[1]))
		.map((т) => т[1].match(/\sclass="([^"]*)"/)?.[1] ?? '')
		.filter(Boolean);
	const классСHidden = сHidden[0]?.split(/\s+/)[0];

	console.log();
	if (!классСHidden) {
		// МОЛЧА ПРОПУСТИТЬ НЕЛЬЗЯ: «не проверяли» и «проверили, чисто» — разное.
		console.log('── ПОДЛОГ для check-hidden ПРОПУЩЕН: на страницах песочницы нет элемента');
		console.log('   с `hidden` и классом. Подделать его значило бы проверять свою выдумку.');
	} else {
		console.log(`── ПОДЛОГ: правило перебивает hidden у живого класса .${классСHidden} ──`);
		const целыйCss2 = await readFile(путьCss, 'utf8');
		await appendFile(путьCss, `\n.${классСHidden}{display:grid}\n`, 'utf8');
		try {
			const { код, вывод } = await прогнать('check-hidden.mjs', [], песочница);
			скажи(код !== 0 && вывод.includes(классСHidden), `check-hidden поймала перебитый hidden: код ${код}`);
			if (код === 0) console.log(`          вывод: ${JSON.stringify(вывод.slice(0, 300))}`);
		} finally {
			await writeFile(путьCss, целыйCss2, 'utf8');
		}
		const { код } = await прогнать('check-hidden.mjs', [], песочница);
		скажи(код === 0, `после возврата файла check-hidden снова молчит: код ${код}`);
	}
} finally {
	await rm(песочница, { recursive: true, force: true });
}

console.log();
if (плохо) {
	console.log(`ПРОВАЛОВ: ${плохо}`);
	process.exit(1);
}
console.log('Все три проверки краснеют, когда слепнут, и молчат, когда видят.');
