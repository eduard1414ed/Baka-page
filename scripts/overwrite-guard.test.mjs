#!/usr/bin/env node
// ПРОВЕРКА ЗАСЛОНА: НЕ СТИРАЕТ ЛИ СОХРАНЕНИЕ ИЗ АДМИНКИ РАБОТУ РОБОТА (задача 29).
//
// Запуск:          node scripts/overwrite-guard.test.mjs
// Подлог:          node scripts/overwrite-guard.test.mjs --подлог
//
// ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. Открытая вкладка админки держит свою копию поста
// и при сохранении пишет её на диск целиком. Приехала за это время правка
// робота — сохранение возвращает файл к дороботовскому виду. Для git это
// не столкновение, а обычная правка: он её запишет, отправит и выложит,
// и не скажет никто. Так откатился пост ep-102.
//
// ПЕСОЧНИЦА ИЗ НАСТОЯЩИХ РЕПОЗИТОРИЕВ, а не чтение кода: беда живёт не в одной
// строчке, а в порядке событий — робот запушил, заказчик забрал, вкладка
// сохранила старое. Воспроизвести это можно только по-настоящему.
//
// ЗАПУСКАТОР БЕРЁТСЯ ИЗ САМОГО ФАЙЛА, копией прямо перед прогоном: копия,
// переписанная рядом, разошлась бы с оригиналом при первой же правке.
//
// ВЫКЛАДКА ПОДМЕНЕНА ЗАГЛУШКОЙ — настоящая выложила бы ЖИВОЙ САЙТ из песочницы.
// Заглушка оставляет отметку: по ней и видно, дошло дело до выкладки или нет.
//
// ТРИ СЛУЧАЯ, И ВСЕ ТРИ ОБЯЗАТЕЛЬНЫ:
//   1. затирание       — заслон обязан остановить и назвать пост;
//   2. законная правка — тот же свежий пост от робота, но правится по-людски:
//                        заслон обязан ПРОМОЛЧАТЬ и пропустить;
//   3. чужая работа старая — робот трогал файл давно, отметка о выкладке
//                        новее: правка законна, заслон молчит.
//
// БЕЗ ВТОРОГО И ТРЕТЬЕГО СЛУЧАЯ «поймал» не значит ничего. Основная работа
// заказчика — править свежий черновик, привезённый роботом: дописать текст,
// снять галочку «черновик». Заслон, который на этом краснеет, будет снят
// через неделю вместе с пользой. Второй случай стережёт строгость признака
// «пропали ВСЕ строки робота»: ослабь его до «хоть одна» — и случай 2
// покраснеет немедленно.
//
// ПОДЛОГ возвращает ПРЕЖНЕЕ правило — то есть состояние до задачи 29, когда
// заслона не было вовсе, — и вырезает РОВНО его, из настоящего файла. Проверка
// обязана увидеть, что затирание молча уехало на сайт.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync, cpSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ЗАПУСКАТОР = join(ROOT, 'scripts', 'launch-deploy.mjs');
const ПОДЛОГ = process.argv.includes('--подлог');

let бед = 0;
const скажи = (текст = '') => console.log(текст);
const проверь = (условие, что) => {
	скажи(`   ${условие ? '✓' : '✗'} ${что}`);
	if (!условие) бед += 1;
};

const гит = (где, доводы) => execFileSync('git', доводы, { cwd: где, encoding: 'utf8' }).trim();

const ПОСТ = 'src/content/posts/ep-153.md';
const ОБЛОЖКА = '/images/uploads/oblozhka.jpg';

// Два поста, привезённых роботом телеграма, — те самые, что заказчик убрал
// нарочно 03.09.2026. Имена и заголовки взяты из жизни: по ним в выводе видно,
// что запускатор зовёт материалы по-человечески, а не путями файлов.
const ПОСТ2 = 'src/content/posts/oboi-i-kalendari.md';
const ЗАГОЛОВОК2 = 'Обои и календари';
const ПОСТ3 = 'src/content/posts/luchshiy-multfilm.md';
const ЗАГОЛОВОК3 = 'Лучший российский мультфильм всех времен';

const существуетВХранилище = (где, путь) => {
	try {
		execFileSync('git', ['cat-file', '-e', `HEAD:${путь}`], { cwd: где, stdio: 'ignore' });
		return true;
	} catch {
		return false;
	}
};

// Пост пишется так, как его пишет Sveltia: длинные значения одной строкой,
// без переносов. Подлог для самопроверки пишем так, как пишут в жизни.
const постТекст = ({ cover = '', тело }) =>
	`---\ntitle: 'Как жить во время конца света? — «Мертвые мертвые демоны» | Эссе'\ndate: 2026-08-27\ncategory: podcast\ndraft: true\n${cover ? `cover: ${cover}\n` : ''}---\n\n${тело}\n`;

const ЗАГЛУШКА_ТАЙТЛОВ = `console.log('Все размеченные тайтлы уже есть в справочнике.');\n`;
const ЗАГЛУШКА_ВЫКЛАДКИ = `import { writeFileSync } from 'node:fs';
console.log('── собираю сайт');
console.log('   готово за 0 с');
console.log('── выкладываю на bakapodcast.com');
writeFileSync(new URL('../ВЫЛОЖЕНО', import.meta.url), 'да');
process.exit(0);
`;

// ── подлог: вырезаем РОВНО заслон, из настоящего файла ─────────────────────
function запускаторДляПесочницы() {
	const текст = readFileSync(ЗАПУСКАТОР, 'utf8');
	if (!ПОДЛОГ) return текст;

	const начало = текст.indexOf('// ── ЗАСЛОН: НЕ СТИРАЕТ ЛИ СОХРАНЕНИЕ');
	const конец = текст.indexOf('// ── 3. записываю правки заказчика');
	if (начало < 0 || конец < 0 || конец <= начало) {
		скажи('✗ ПОДЛОГ НЕ УДАЛСЯ: не нашёл заслон в запускаторе — проверять нечего.');
		process.exit(1);
	}
	return текст.slice(0, начало) + текст.slice(конец);
}

// ── песочница ──────────────────────────────────────────────────────────────
function построить() {
	const корень = mkdtempSync(join(tmpdir(), 'baka-overwrite-'));
	const хранилище = join(корень, 'github.git');
	const заказчик = join(корень, 'заказчик');
	const робот = join(корень, 'робот');

	execFileSync('git', ['init', '--bare', '-b', 'main', хранилище], { stdio: 'ignore' });
	execFileSync('git', ['clone', '--quiet', хранилище, заказчик], { stdio: 'ignore' });

	const представься = (где, имя) => {
		гит(где, ['config', 'user.name', имя]);
		гит(где, ['config', 'user.email', `${имя}@example.com`]);
	};
	представься(заказчик, 'eduard1414ed');

	mkdirSync(join(заказчик, 'src', 'content', 'posts'), { recursive: true });
	mkdirSync(join(заказчик, 'scripts'), { recursive: true });
	writeFileSync(join(заказчик, ПОСТ), постТекст({ тело: 'Первый абзац.\n\nВторой абзац.' }));
	writeFileSync(join(заказчик, 'README.md'), 'проверочный репозиторий\n');

	writeFileSync(join(заказчик, 'scripts', 'launch-deploy.mjs'), запускаторДляПесочницы());
	cpSync(join(ROOT, 'scripts', 'repo-news-lib.mjs'), join(заказчик, 'scripts', 'repo-news-lib.mjs'));
	writeFileSync(join(заказчик, 'scripts', 'quick-deploy.mjs'), ЗАГЛУШКА_ВЫКЛАДКИ);
	writeFileSync(join(заказчик, 'scripts', 'sync-anime.mjs'), ЗАГЛУШКА_ТАЙТЛОВ);

	гит(заказчик, ['add', '-A']);
	гит(заказчик, ['commit', '-m', 'Начало']);
	гит(заказчик, ['push', '--quiet', 'origin', 'main']);

	execFileSync('git', ['clone', '--quiet', хранилище, робот], { stdio: 'ignore' });
	представься(робот, 'baka-tg-photos-bot');

	return { корень, заказчик, робот };
}

function прогнать(где) {
	try {
		const вывод = execFileSync(process.execPath, ['scripts/launch-deploy.mjs'], {
			cwd: где, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'],
		});
		return { код: 0, вывод };
	} catch (сбой) {
		return { код: сбой.status, вывод: `${сбой.stdout || ''}${сбой.stderr || ''}` };
	}
}

// Первый заход: выложить и записать отметку «докуда выложено». Без неё
// заслон не знал бы, что считать свежим, — а в жизни она есть всегда.
function первыйЗаход(заказчик) {
	const итог = прогнать(заказчик);
	if (итог.код !== 0) {
		скажи('✗ ПЕСОЧНИЦА НЕ СОБРАЛАСЬ: первый заход не прошёл, а он обязан.');
		скажи(итог.вывод.split('\n').slice(-15).join('\n'));
		process.exit(1);
	}
	rmSync(join(заказчик, 'ВЫЛОЖЕНО'), { force: true });
}

// Робот кладёт в хранилище правку этого поста, заказчик её забирает —
// то есть у него на диске она УЖЕ есть.
function роботПривёзИЗаказчикЗабрал(заказчик, робот) {
	гит(робот, ['pull', '--quiet', '--rebase', 'origin', 'main']);
	writeFileSync(join(робот, ПОСТ), постТекст({ cover: ОБЛОЖКА, тело: 'Первый абзац.\n\nВторой абзац.' }));
	гит(робот, ['add', '-A']);
	гит(робот, ['commit', '-m', 'Картинка к посту из телеграма']);
	гит(робот, ['push', '--quiet', 'origin', 'main']);
	гит(заказчик, ['pull', '--quiet', '--rebase', 'origin', 'main']);
}

// Робот кладёт в хранилище НОВЫЙ пост, заказчик его забирает: теперь этот
// материал лежит у него на диске, и он может его удалить — как в админке.
function роботПривёзНовыйПост(заказчик, робот, путь, заголовок) {
	гит(робот, ['pull', '--quiet', '--rebase', 'origin', 'main']);
	writeFileSync(join(робот, путь),
		`---\ntitle: '${заголовок}'\ndate: 2026-09-02\ncategory: podcast\n---\n\nПривезено из телеграма.\n`);
	гит(робот, ['add', '-A']);
	гит(робот, ['commit', '-m', 'Пост из телеграма']);
	гит(робот, ['push', '--quiet', 'origin', 'main']);
	гит(заказчик, ['pull', '--quiet', '--rebase', 'origin', 'main']);
}

const ЗАЯВКА = '.git/baka-снос-спрошено.json';

// ═══ 1. ЗАТИРАНИЕ ══════════════════════════════════════════════════════════
скажи(`\n=== 1. Вкладка админки записала старую копию поверх правки робота ===${ПОДЛОГ ? '   [ПОДЛОГ]' : ''}\n`);
{
	const { корень, заказчик, робот } = построить();
	первыйЗаход(заказчик);
	роботПривёзИЗаказчикЗабрал(заказчик, робот);

	проверь(readFileSync(join(заказчик, ПОСТ), 'utf8').includes(ОБЛОЖКА),
		'до сохранения правка робота у заказчика на диске ЕСТЬ');

	// Вкладка админки была открыта ДО прихода робота: она держит копию без
	// обложки и пишет её целиком, добавив то, что человек напечатал.
	writeFileSync(join(заказчик, ПОСТ), постТекст({ тело: 'Первый абзац.\n\nВторой абзац.\n\nТретий абзац, дописан в админке.' }));

	const итог = прогнать(заказчик);

	if (ПОДЛОГ) {
		// С прежним правилом заслона нет — и затирание обязано молча уехать.
		проверь(итог.код === 0, 'ПОДЛОГ: прежнее правило пропустило затирание без единого слова');
		проверь(existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'ПОДЛОГ: дело дошло до выкладки');
		проверь(!гит(заказчик, ['show', 'HEAD:' + ПОСТ]).includes(ОБЛОЖКА),
			'ПОДЛОГ: работа робота стёрта и записана в хранилище — та самая беда');
	} else {
		проверь(итог.код === 1, 'заслон остановил выкладку (код возврата 1, а не 0)');
		проверь(/СТИРАЕТ СВЕЖУЮ РАБОТУ РОБОТА/.test(итог.вывод), 'сказал прямым текстом, что стирает чужое');
		проверь(/Мертвые мертвые демоны/.test(итог.вывод), 'назвал пост по заголовку, а не по имени файла');
		проверь(/робот картинок/.test(итог.вывод), 'назвал, ЧЕЙ это был труд, человеческим именем');
		проверь(итог.вывод.includes(ОБЛОЖКА), 'показал, что именно пропало');
		проверь(/ВАШИ ПРАВКИ ЦЕЛЫ/.test(итог.вывод) && /САЙТ НЕ ТРОНУТ/.test(итог.вывод),
			'успокоил: правки целы, сайт прежний');
		проверь(/Закройте вкладку админки/.test(итог.вывод), 'сказал, что делать дальше');

		проверь(!existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'до выкладки дело НЕ дошло');
		проверь(гит(заказчик, ['status', '--porcelain']) !== '',
			'НИЧЕГО НЕ ЗАПИСАНО: правка заказчика так и лежит незакоммиченной');
		проверь(гит(заказчик, ['show', 'HEAD:' + ПОСТ]).includes(ОБЛОЖКА),
			'в хранилище работа робота цела');
		проверь(/Третий абзац, дописан в админке/.test(readFileSync(join(заказчик, ПОСТ), 'utf8')),
			'работа заказчика тоже цела — ничего не откачено');
	}

	rmSync(корень, { recursive: true, force: true });
}

// ═══ 2. ЗАКОННАЯ ПРАВКА СВЕЖЕГО ЧЕРНОВИКА ══════════════════════════════════
скажи('\n=== 2. Тот же свежий пост, но правится по-людски ===\n');
{
	const { корень, заказчик, робот } = построить();
	первыйЗаход(заказчик);
	роботПривёзИЗаказчикЗабрал(заказчик, робот);

	// Обычная работа: заказчик дописал текст, обложку робота оставил.
	writeFileSync(join(заказчик, ПОСТ), постТекст({
		cover: ОБЛОЖКА,
		тело: 'Первый абзац переписан.\n\nВторой абзац.\n\nИ третий добавлен.',
	}));

	const итог = прогнать(заказчик);

	проверь(итог.код === 0, 'запускатор дошёл до конца (код возврата 0)');
	проверь(!/СТИРАЕТ СВЕЖУЮ РАБОТУ/.test(итог.вывод), 'заслон промолчал — и правильно сделал');
	проверь(existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'дело дошло до выкладки');
	проверь(гит(заказчик, ['show', 'HEAD:' + ПОСТ]).includes(ОБЛОЖКА), 'работа робота на месте');
	проверь(/И третий добавлен/.test(гит(заказчик, ['show', 'HEAD:' + ПОСТ])), 'работа заказчика на месте');

	rmSync(корень, { recursive: true, force: true });
}

// ═══ 3. ЧУЖАЯ РАБОТА СТАРАЯ ════════════════════════════════════════════════
скажи('\n=== 3. Робот трогал пост давно, с тех пор всё было выложено ===\n');
{
	const { корень, заказчик, робот } = построить();
	роботПривёзИЗаказчикЗабрал(заказчик, робот);
	// Выложили УЖЕ ПОСЛЕ прихода робота — значит вкладка админки его правку
	// видела наверняка, и снос обложки теперь решение человека, а не беда.
	первыйЗаход(заказчик);

	writeFileSync(join(заказчик, ПОСТ), постТекст({ тело: 'Первый абзац.\n\nВторой абзац.\n\nОбложку убрал нарочно.' }));

	const итог = прогнать(заказчик);

	проверь(итог.код === 0, 'запускатор дошёл до конца (код возврата 0)');
	проверь(!/СТИРАЕТ СВЕЖУЮ РАБОТУ/.test(итог.вывод), 'заслон промолчал: правка робота была ещё до выкладки');
	проверь(existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'дело дошло до выкладки');

	rmSync(корень, { recursive: true, force: true });
}

// ═══ 4. СНОС НАРОЧНО: СПРОСИЛ И ПРОПУСТИЛ ПО ВТОРОМУ НАЖАТИЮ ═══════════════
//
// Ради этого случая задача и делалась. 03.09.2026 заказчик убрал в админке два
// поста, привезённых роботом телеграма, — и не смог выложить сайт ничем: заслон
// объявлял снос бедой, а выхода из окна не было ни одного. Снос вкладка сделать
// не может, значит это работа человека; спросить о ней надо, но спросить —
// не значит запретить.
скажи(`\n=== 4. Заказчик нарочно убрал пост, привезённый роботом ===${ПОДЛОГ ? '   [ПОДЛОГ]' : ''}\n`);
{
	const { корень, заказчик, робот } = построить();
	первыйЗаход(заказчик);
	роботПривёзНовыйПост(заказчик, робот, ПОСТ2, ЗАГОЛОВОК2);

	rmSync(join(заказчик, ПОСТ2));

	const первый = прогнать(заказчик);

	if (ПОДЛОГ) {
		проверь(первый.код === 0, 'ПОДЛОГ: прежнее правило пропустило снос, не спросив');
		проверь(existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'ПОДЛОГ: дело дошло до выкладки');
	} else {
		проверь(первый.код === 1, 'первое нажатие остановлено (код возврата 1)');
		проверь(/УБИРАЕТЕ С САЙТА/.test(первый.вывод), 'сказал про снос, а не про стирание');
		проверь(!/СТИРАЕТ СВЕЖУЮ РАБОТУ/.test(первый.вывод), 'не назвал это затиранием: беда другая');
		проверь(первый.вывод.includes(ЗАГОЛОВОК2), 'назвал пост по заголовку, а не по имени файла');
		проверь(/робот картинок/.test(первый.вывод), 'назвал, ЧЕЙ это был труд, человеческим именем');
		проверь(/нажмите «Выложить» ещё раз/.test(первый.вывод), 'сказал, чем ответить «да»');
		проверь(/Убрали СЛУЧАЙНО/.test(первый.вывод), 'сказал и что делать, если это ошибка');
		проверь(!existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'до выкладки дело НЕ дошло');
		проверь(existsSync(join(заказчик, ЗАЯВКА)), 'заявка на снос записана');

		const второй = прогнать(заказчик);

		проверь(второй.код === 0, 'второе нажатие прошло до конца (код возврата 0)');
		проверь(/подтвердили снос вторым нажатием/.test(второй.вывод), 'сказал вслух, почему пропустил');
		проверь(existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'дело дошло до выкладки');
		проверь(!существуетВХранилище(заказчик, ПОСТ2), 'пост убран и из хранилища — то, чего человек хотел');
		проверь(!existsSync(join(заказчик, ЗАЯВКА)), 'заявка потрачена: разрешение одноразовое');
	}

	rmSync(корень, { recursive: true, force: true });
}

// ═══ 5. РАЗРЕШЕНИЕ НЕ ПЕРЕНОСИТСЯ НА ДРУГОЙ СНОС ═══════════════════════════
//
// Без этого одно сказанное «да» тихо разрешало бы всё, что удалится следом, —
// в том числе случайное. Разрешение именное: набор другой — вопрос заново.
if (!ПОДЛОГ) {
	скажи('\n=== 5. Сказал «да» про один пост, а удалилось два ===\n');
	const { корень, заказчик, робот } = построить();
	первыйЗаход(заказчик);
	роботПривёзНовыйПост(заказчик, робот, ПОСТ2, ЗАГОЛОВОК2);
	роботПривёзНовыйПост(заказчик, робот, ПОСТ3, ЗАГОЛОВОК3);

	rmSync(join(заказчик, ПОСТ2));
	проверь(прогнать(заказчик).код === 1, 'спросил про первый снос');

	// Пока окно было открыто, удалился и второй пост.
	rmSync(join(заказчик, ПОСТ3));
	const второй = прогнать(заказчик);

	проверь(второй.код === 1, 'спросил ЗАНОВО: набор снесённого стал другим');
	проверь(второй.вывод.includes(ЗАГОЛОВОК3), 'и назвал в вопросе второй пост тоже');
	проверь(!existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'до выкладки дело НЕ дошло');

	rmSync(корень, { recursive: true, force: true });
}

// ═══ 6. РАЗРЕШЕНИЕ ПРОТУХАЕТ ═══════════════════════════════════════════════
//
// Заявка, пролежавшая ночь, — это не ответ человека, а забытая бумажка.
if (!ПОДЛОГ) {
	скажи('\n=== 6. Между вопросом и вторым нажатием прошли сутки ===\n');
	const { корень, заказчик, робот } = построить();
	первыйЗаход(заказчик);
	роботПривёзНовыйПост(заказчик, робот, ПОСТ2, ЗАГОЛОВОК2);

	rmSync(join(заказчик, ПОСТ2));
	проверь(прогнать(заказчик).код === 1, 'спросил про снос');

	// Состариваем заявку: ровно то, что сделали бы сутки.
	const заявка = JSON.parse(readFileSync(join(заказчик, ЗАЯВКА), 'utf8'));
	заявка.время = Date.now() - 24 * 60 * 60 * 1000;
	writeFileSync(join(заказчик, ЗАЯВКА), JSON.stringify(заявка));

	const второй = прогнать(заказчик);
	проверь(второй.код === 1, 'протухшая заявка ничего не разрешила — спросил заново');
	проверь(!existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'до выкладки дело НЕ дошло');

	rmSync(корень, { recursive: true, force: true });
}

// ═══ 7. СТЕНА ВТОРЫМ НАЖАТИЕМ НЕ ОТКРЫВАЕТСЯ ═══════════════════════════════
//
// Затирание человек не делал и о нём не знает: на вопрос «правда хотели?» он
// ответит «да» про свою правку, ничего не зная про молчаливый откат чужой.
// Поэтому у затирания второго нажатия нет и быть не должно.
if (!ПОДЛОГ) {
	скажи('\n=== 7. Затирание: жми хоть десять раз ===\n');
	const { корень, заказчик, робот } = построить();
	первыйЗаход(заказчик);
	роботПривёзИЗаказчикЗабрал(заказчик, робот);
	writeFileSync(join(заказчик, ПОСТ), постТекст({ тело: 'Первый абзац.\n\nВторой абзац.\n\nТретий абзац, дописан в админке.' }));

	const первый = прогнать(заказчик);
	const второй = прогнать(заказчик);

	проверь(первый.код === 1 && второй.код === 1, 'остановил оба раза');
	проверь(/СТИРАЕТ СВЕЖУЮ РАБОТУ/.test(второй.вывод), 'и во второй раз это стена, а не вопрос');
	проверь(!existsSync(join(заказчик, ЗАЯВКА)), 'заявки на снос не заводил: сносить нечего');
	проверь(!existsSync(join(заказчик, 'ВЫЛОЖЕНО')), 'до выкладки дело НЕ дошло');

	rmSync(корень, { recursive: true, force: true });
}

скажи('');
if (ПОДЛОГ) {
	if (бед > 0) {
		скажи(`✗ ПОДЛОГ НЕ СРАБОТАЛ КАК ЖДАЛИ: несошедшихся утверждений ${бед}.`);
		process.exit(1);
	}
	скажи('✓ ПОДЛОГ ПОЙМАН: без заслона затирание молча уезжает на сайт.');
	скажи('  Значит зелёный ответ обычного прогона чего-то стоит.');
	process.exit(0);
}
if (бед > 0) {
	скажи(`✗ НЕ СОШЛОСЬ: ${бед}`);
	process.exit(1);
}
скажи('✓ ВСЁ СОШЛОСЬ: затирание останавливает намертво, законную правку пропускает,');
скажи('  на старую работу робота не ругается, а про снос спрашивает —');
скажи('  и пропускает его по второму нажатию, поимённо и один раз.');
process.exit(0);
