//   node scripts/deploy-race.test.mjs
//   node scripts/deploy-race.test.mjs --подлог
//
// ЧТО СЛУЧИЛОСЬ 25 АВГУСТА 2026. Робот сборки проснулся в 12:49 UTC, забрал
// коммит 7a766cf1 и пошёл собирать — почти шесть минут. В 12:51 с машины ушёл
// коммит 3f4b8cc1, и быстрая выкладка положила его на сайт в 12:55:01. Робот
// закончил и выложил СВОЮ сборку в 12:55:16 — на пятнадцать секунд позже
// и БЕЗ этого коммита. На сайте оказалась версия постарше; спасло только то,
// что робот пишет отметку «докуда выложено» номером коммита, с которого
// НАЧИНАЛ: через десять минут он увидел 3f4b8cc1 «новым» и пересобрал всё
// заново. Шесть минут работы впустую и одиннадцать минут неправильного сайта.
// В тот раз в коммите была одна документация, и не заметил никто.
//
// ЧТО ПРОВЕРЯЕТСЯ. Из hetzner/run-deploy.sh вынимается НАСТОЯЩИЙ текст блока
// «нас обогнали» — не его пересказ — и гоняется в песочнице из двух git-
// репозиториев: голый «GitHub», куда во время сборки приехал чужой коммит,
// и клон робота, застрявший на старом. Блок обязан промолчать на здоровом
// заходе и увести робота от выкладки на обогнанном.
//
// ПОЧЕМУ ЭТО НЕ «ВЕЧНОЗЕЛЁНАЯ» ПРОВЕРКА. Ключ `--подлог` возвращает ПРЕЖНЕЕ
// правило — то есть отсутствие блока, как было до 25 августа, — и проверка
// обязана покраснеть: робот выложит устаревшую сборку поверх свежей. Не
// покраснела — значит песочница не воспроизводит поломку и её «ок» ничего
// не значит.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const SCRIPT = join(ROOT, 'hetzner/run-deploy.sh');
const НАЧАЛО = '# ─── начало блока «нас обогнали»';
const КОНЕЦ = '# ─── конец блока «нас обогнали»';

/**
 * Текст блока — из самого робота, а не переписанный рядом: копия разошлась бы
 * с первой же правкой, и проверка сторожила бы себя, а не робота.
 */
export function читатьБлок(текст) {
	const от = текст.indexOf(НАЧАЛО);
	const до = текст.indexOf(КОНЕЦ);
	if (от < 0 || до < 0) return null;
	return текст.slice(от + НАЧАЛО.length, до);
}

const git = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });

/**
 * Песочница: голый «GitHub» и клон робота, который забрал состояние ДО того,
 * как в хранилище приехал чужой коммит.
 *
 * @param {'обогнали'|'спокойно'} что — приезжал ли чужой коммит во время сборки.
 * @param {string} блок — текст блока (пустой = прежнее правило, подлога ради).
 * @returns {{ выложил: boolean, вывод: string, код: number }}
 */
function прогон(что, блок) {
	const box = mkdtempSync(join(tmpdir(), 'baka-deploy-race-'));
	try {
		const seed = join(box, 'seed');
		const bare = join(box, 'github.git');
		mkdirSync(seed, { recursive: true });
		git(seed, 'init', '--initial-branch=main');
		git(seed, 'config', 'user.name', 'заказчик');
		git(seed, 'config', 'user.email', 'owner@example.com');
		writeFileSync(join(seed, 'пост.md'), 'первый\n', 'utf8');
		git(seed, 'add', '-A');
		git(seed, 'commit', '-m', 'Первый пост');
		git(box, 'clone', '--bare', seed, bare);

		// Робот проснулся, забрал состояние и ушёл собирать на шесть минут.
		const robot = join(box, 'robot');
		git(box, 'clone', bare, robot);
		const NEW = git(robot, 'rev-parse', 'origin/main').trim();

		// Пока он собирал, с машины ушёл коммит — и его уже выложили.
		if (что === 'обогнали') {
			writeFileSync(join(seed, 'документация.md'), 'правки с машины\n', 'utf8');
			git(seed, 'add', '-A');
			git(seed, 'commit', '-m', 'Правки с машины: 5 файлов');
			git(seed, 'push', bare, 'main');
		}

		// Сборка закончена, робот подошёл к выкладке. Дальше — его собственный
		// текст; «ВЫЛОЖИЛ» стоит ровно там, где у него `npx wrangler deploy`.
		const сценарий = `set -u\nNEW=${NEW}\n${блок}\necho ВЫЛОЖИЛ\n`;
		let вывод = '';
		let код = 0;
		try {
			вывод = execFileSync('bash', ['-c', сценарий], { cwd: robot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
		} catch (err) {
			код = err.status ?? 1;
			вывод = `${err.stdout ?? ''}${err.stderr ?? ''}`;
		}
		return { выложил: вывод.includes('ВЫЛОЖИЛ'), вывод: вывод.trim(), код };
	} finally {
		rmSync(box, { recursive: true, force: true });
	}
}

// ─── Прогон ────────────────────────────────────────────────────────────────

const подлог = process.argv.includes('--подлог') || process.argv.includes('--selftest');
const беды = [];
const ок = (строка) => console.log(`  ✓ ${строка}`);
const плохо = (строка) => {
	беды.push(строка);
	console.log(`  ✗ ${строка}`);
};

const текст = readFileSync(SCRIPT, 'utf8');

if (подлог) {
	console.log('=== ПОДЛОГ: роботу возвращено ПРЕЖНЕЕ правило — блока нет вовсе ===\n');
	const r = прогон('обогнали', '');
	if (r.выложил) ок('робот выложил устаревшую сборку поверх свежей — ровно как 25 августа в 12:55:16');
	else плохо('робот НЕ выложил даже без блока — песочница не воспроизводит поломку, её «ок» ничего не значит');
} else {
	console.log('=== ВЫКЛАДКА НЕ КЛАДЁТ СТАРОЕ ПОВЕРХ СВЕЖЕГО ===\n');

	const блок = читатьБлок(текст);
	if (блок === null) {
		плохо('в hetzner/run-deploy.sh нет блока «нас обогнали» — проверять нечего');
	} else {
		// Блок, стоящий ПОСЛЕ выкладки, бесполезен: спрашивать надо до неё.
		const где = текст.indexOf(НАЧАЛО);
		const выкладка = текст.indexOf('npx wrangler deploy');
		if (выкладка > где) ок('блок спрашивает хранилище ДО выкладки на bakapodcast.com');
		else плохо('блок стоит ПОСЛЕ выкладки — спрашивать после того, как положил, поздно');

		const обычный = прогон('спокойно', блок);
		if (обычный.выложил) ок('обычный заход выкладывает как выкладывал — блок здоровому не мешает');
		else плохо(`блок не пустил ОБЫЧНЫЙ заход: ${обычный.вывод.split('\n').slice(-2).join(' / ')}`);

		const гонка = прогон('обогнали', блок);
		if (!гонка.выложил) ок('обогнанный заход не выложил ничего — старое поверх свежего не легло');
		else плохо('обогнанный заход ВЫЛОЖИЛ устаревшую сборку — вернулась поломка 25 августа');
		if (гонка.код === 0) ок('уходит спокойно, кодом 0 — красного письма о живом роботе не будет');
		else плохо(`уходит кодом ${гонка.код} — заказчик получит письмо о сбое там, где сбоя нет`);
	}
}

console.log('');
if (беды.length) {
	console.log(`ПРОВЕРКА НЕ ПРОШЛА: ${беды.length}.`);
	process.exit(1);
}
console.log('Всё сошлось.');
