// ДОБОР ПОЛЯ `franchise` В КАРТОЧКИ ТАЙТЛОВ.
//
//   node scripts/anime-franchise.mjs --сколько=10   — пробный прогон
//   node scripts/anime-franchise.mjs                — все, у кого поля нет
//   node scripts/anime-franchise.mjs --обновить     — перечитать и тех, у кого есть
//
// ЗАЧЕМ. Правило индексируемости (src/lib/animeIndexability.mjs) закрывает
// страницу сезона, у которой нет ничего своего: всё, что о ней сказано, уже
// стоит на странице основного тайтла. Чтобы понять, кто кому сезон, нужно
// родство — и брать его надо у источника, а не угадывать по началу адреса.
// Замер 30 августа 2026 показал, чем кончается догадка: по началу слага
// «Принцесса Мононоке» (1997, Миядзаки) попадает в семью «Мононокэ» (2007,
// сериал-хоррор) — общего у них только кусок адреса. У Shikimori же
// у «Принцессы» франшизы нет вовсе, и в чужую семью она не попадёт никогда.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ СКРИПТ, А НЕ `sync-anime.mjs --refresh`. Тот перезаписывает
// ВСЕ поля ВСЕХ 658 карточек через `writeAnimeEntry`: перекачивает обложки,
// заново берёт описания и русские названия, пересчитывает падежные формы,
// переписывает альтернативные названия. Ручные правки защищены только у тех
// полей, что отмечены в `manual`, — а отмечены они не везде. Здесь же
// дописывается РОВНО ОДИН ключ, и стереть нечему.
//
// Поле `franchise` приходит в том же ответе `GET /api/animes/<id>`, который
// проект уже умеет запрашивать: новых обращений к чужому серверу задача
// не добавляет, просто читается ещё одно поле ответа.
//
// ВСЯ МАШИНЕРИЯ — В scripts/anime-field-lib.mjs, общая с добором типа
// произведения (`anime-kind.mjs`). Здесь только то, чем эти два похода
// различаются.

import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { доборПоля } from './anime-field-lib.mjs';

// Русские буквы в пути: import.meta.url их кодирует, process.argv[1] — нет.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
	process.exitCode = await доборПоля({
		имяПоля: 'franchise',
		// Пустую строку и отсутствие поля читаем одинаково — «одиночка».
		прочитать: (данные) => данные.franchise || null,
		послеКлюча: 'url',
		назвать: (франшиза) => франшиза ?? '(одиночка)',
		считать: (франшиза) => (франшиза ? 'с франшизой' : 'одиночек'),
		арг: process.argv.slice(2),
	});
}
