// Проверки заливки на зеркало (задача 13).
//
// Спрашивают ЧИСТЫЕ функции `mirror-sync.mjs` — те, что решают, чему ехать,
// каким будет адрес и что делать с расхождением. Сети тут нет, поэтому прогон
// занимает миллисекунды и его можно гонять вместе с проверками раздела 8.4.
//
// ЧЕГО ЭТИ ПРОВЕРКИ НЕ ЗНАЮТ И ЗНАТЬ НЕ МОГУТ: правильна ли подпись запроса.
// Проверить её можно только настоящим походом в хранилище, и он сделан пробным
// прогоном робота — там же, где меряли, дотягивается ли GitHub до Москвы.
// Своего «эталона подписи» тут нет нарочно: выдуманный по памяти эталон
// проверял бы не подпись, а мою память.
//
// Запуск: node scripts/mirror-sync.test.mjs
// Подлог: node scripts/mirror-sync.test.mjs --подлог — ломает каждое правило
//         по очереди и убеждается, что проверки краснеют. Без этого шага
//         «всё хорошо» не значит ничего.

import {
	едетНаЗеркало,
	путьВАдресе,
	решить,
	удалениеПодозрительно,
	типФайла,
} from './mirror-sync.mjs';

const карта = (пары) => new Map(Object.entries(пары));

/**
 * Список утверждений. Берёт набор функций, чтобы тот же самый список можно было
 * задать подложенным, СЛОМАННЫМ функциям и убедиться, что он краснеет.
 */
function утверждения({ едетНаЗеркало, путьВАдресе, решить, удалениеПодозрительно, типФайла }) {
	const базовые = решить(
		карта({ 'index.html': 'aaa', 'posts/x/index.html': 'bbb', 'style.css': 'ccc' }),
		карта({ 'index.html': 'aaa', 'posts/x/index.html': 'ИНОЕ', 'старое.html': 'ddd' }),
	);
	const залито = базовые.залить.map((x) => x.key).sort();

	return [
		// ── что едет, а что нет ────────────────────────────────────────────────
		['админка на зеркало не едет', !едетНаЗеркало('admin/index.html')],
		['страница роботов на зеркало не едет', !едетНаЗеркало('admin/tools/index.html')],
		['данные админки не едут', !едетНаЗеркало('admin-data/ep-102.json')],
		['список постов для админки не едет', !едетНаЗеркало('admin-posts.json')],
		['очередь отложенной публикации не едет', !едетНаЗеркало('publish-queue.json')],
		['обычная страница едет', едетНаЗеркало('posts/znakomtes/index.html')],
		['главная едет', едетНаЗеркало('index.html')],
		[
			'ПОИСКОВЫЙ ИНДЕКС ЕДЕТ — без него на зеркале не работал бы поиск',
			едетНаЗеркало('pagefind/index/en_abc.pf_index') && едетНаЗеркало('pagefind/pagefind.js'),
		],
		[
			'файл, чьё имя лишь НАЧИНАЕТСЯ на admin, едет — запрет только на папку',
			едетНаЗеркало('administrativnyy-post/index.html'),
		],

		// ── адрес ──────────────────────────────────────────────────────────────
		[
			'русские буквы в имени файла кодируются процентами',
			путьВАдресе('cutout/Пони-png-640w.webp').includes('%D0%9F%D0%BE%D0%BD%D0%B8'),
		],
		[
			'КОСЫЕ ОСТАЮТСЯ КОСЫМИ, а не превращаются в %2F',
			путьВАдресе('a/b/c.html').endsWith('/a/b/c.html') && !путьВАдресе('a/b/c.html').includes('%2F'),
		],
		['имя бакета стоит первым в пути', путьВАдресе('x.html').startsWith('/ru.bakapodcast.com/')],
		['у пустого ключа (это сам бакет) косой на конце нет', путьВАдресе('') === '/ru.bakapodcast.com'],

		// ── что делать с расхождением ──────────────────────────────────────────
		['совпавший отпечаток не перезаливается', базовые.совпало === 1],
		['изменившийся и новый — заливаются', залито.join('|') === 'posts/x/index.html|style.css'],
		['новое помечено новым', базовые.залить.find((x) => x.key === 'style.css')?.новый === true],
		['изменившееся новым НЕ помечено', базовые.залить.find((x) => x.key === 'posts/x/index.html')?.новый === false],
		['лишнее в бакете стирается', базовые.стереть.join('|') === 'старое.html'],

		// ── заслон против пустой сборки ────────────────────────────────────────
		[
			'ПЕРВАЯ выкладка проходит: стираем одну заглушку из двух объектов',
			!удалениеПодозрительно(1, 2),
		],
		['обычная уборка проходит: 5 из 1100', !удалениеПодозрительно(5, 1100)],
		['СЛОМАННАЯ СБОРКА НЕ СТИРАЕТ ЗЕРКАЛО: 1000 из 1100 — стоп', удалениеПодозрительно(1000, 1100)],
		['умеренная уборка проходит: 25 из 1100', !удалениеПодозрительно(25, 1100)],

		// ── тип файла ──────────────────────────────────────────────────────────
		['у страницы указана кодировка', типФайла('index.html') === 'text/html; charset=utf-8'],
		['кусок поискового индекса — просто байты', типФайла('pagefind/x.pf_fragment') === 'application/octet-stream'],
		['картинка узнаётся по расширению', типФайла('anime/naruto-320w.webp') === 'image/webp'],
		[
			'точка в ПАПКЕ не считается расширением файла',
			типФайла('ru.bakapodcast.com/index.html') === 'text/html; charset=utf-8',
		],
	];
}

const настоящие = { едетНаЗеркало, путьВАдресе, решить, удалениеПодозрительно, типФайла };

// Подлоги: каждое правило ломается так, как его СЛОМАЛИ БЫ В ЖИЗНИ, а не так,
// как удобно проверке. «Забыли про папку админки», «закодировали ключ целиком»,
// «сравнили по имени, а не по отпечатку», «заслон только по доле».
const подлоги = {
	'админка забыта в списке запретов': { едетНаЗеркало: (key) => !key.startsWith('admin-data/') },
	'ключ закодирован целиком, вместе с косыми': {
		путьВАдресе: (key) => `/${encodeURIComponent(BUCKET_ЗАГЛУШКА)}/${encodeURIComponent(key)}`,
	},
	'сравнение по наличию, а не по отпечатку': {
		решить: (местные, вБакете) => ({
			залить: [...местные.keys()].filter((k) => !вБакете.has(k)).map((key) => ({ key, новый: true })),
			стереть: [...вБакете.keys()].filter((k) => !местные.has(k)),
			совпало: [...местные.keys()].filter((k) => вБакете.has(k)).length,
		}),
	},
	'заслон только по доле, без нижней границы': {
		удалениеПодозрительно: (стираем, всего) => стираем > всего * 0.25,
	},
	'тип берётся у последней точки во всём пути': {
		типФайла: (key) => (key.includes('.') ? `тип/${key.slice(key.lastIndexOf('.') + 1)}` : 'нет'),
	},
};
const BUCKET_ЗАГЛУШКА = 'ru.bakapodcast.com';

function прогнать(импл) {
	return утверждения({ ...настоящие, ...импл }).map(([имя, ok]) => ({ имя, ok }));
}

const подлог = process.argv.includes('--подлог');

if (!подлог) {
	const итоги = прогнать({});
	for (const { имя, ok } of итоги) console.log(`  ${ok ? 'ок     ' : 'ПРОВАЛ '} ${имя}`);
	const плохо = итоги.filter((x) => !x.ok);
	console.log('');
	if (плохо.length) {
		console.error(`Провалено ${плохо.length} из ${итоги.length}.`);
		process.exit(1);
	}
	console.log(`Все ${итоги.length} проверок прошли.`);
} else {
	console.log('ПОДЛОГИ: ломаем каждое правило и смотрим, покраснеет ли проверка.\n');
	let плохо = 0;
	for (const [имя, сломанное] of Object.entries(подлоги)) {
		let упало;
		try {
			упало = прогнать(сломанное).filter((x) => !x.ok);
		} catch (error) {
			// Свалившийся подлог — тоже пойманный подлог: проверка не смолчала.
			упало = [{ имя: `упало с ошибкой: ${error.message}` }];
		}
		if (упало.length) {
			console.log(`  поймано  «${имя}» → ${упало.length} проверок покраснело`);
			console.log(`             первая: ${упало[0].имя}`);
		} else {
			console.error(`  ПРОПУЩЕНО «${имя}» → проверки не заметили поломки`);
			плохо++;
		}
	}
	console.log('');
	if (плохо) {
		console.error(`${плохо} подлог(ов) прошли незамеченными — проверки слепы.`);
		process.exit(1);
	}
	console.log('Все подлоги пойманы: проверки умеют проваливаться.');
}
