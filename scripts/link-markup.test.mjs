// РАЗМЕТКА ССЫЛКИ, КОТОРАЯ НЕ СОБРАЛАСЬ — проверка правила и подлоги.
//
//   node scripts/link-markup.test.mjs             — правило на выдуманных постах
//   node scripts/link-markup.test.mjs --selftest  — подлоги: правило обязано ослепнуть
//
// ОТКУДА ВЗЯЛОСЬ ПРАВИЛО. Разовый скрипт задачи 19 обещал в отчёте раздел
// «битая разметка ссылки», а список, который он печатает, не заполнялся ни разу:
// раздел не мог напечататься НИКОГДА и читался как «битых ссылок нет»
// (доревизия задачи 15, находка 30). Пока он молчал, на трёх опубликованных
// страницах жили настоящие беды — их и взяли образцами ниже, дословно.
//
// ПОЧЕМУ ПРАВИЛО ПЕРЕЕХАЛО В СБОРКУ. Разовый скрипт своё отработал и смотрит
// только черновики; беда же приходит с каждой правкой в админке. Дом правила —
// там же, где живёт соседний вопрос про ссылки в никуда: сборка говорит вслух
// и ничего не чинит (`src/plugins/post-links-integration.mjs`).

import { сломаннаяРазметкаСсылок } from '../src/plugins/post-links-integration.mjs';

const FAILURES = [];

function check(name, condition, detail = '') {
	console.log((condition ? '  ок    ' : '  ПЛОХО ') + name + (detail && !condition ? `  [${detail}]` : ''));
	if (!condition) FAILURES.push(name);
}

/** Один пост-однодневка для правила. */
const пост = (body, { draft = false } = {}) =>
	new Map([['проба', { draft, external: false, title: 'Проба', body }]]);

// ─── ТРИ НАСТОЯЩИХ СЛУЧАЯ, ДОСЛОВНО ИЗ АРХИВА ──────────────────────────────
// Вписаны именно строками, а не «похожими»: правило родилось из них, и подлог,
// переписанный своими словами, проверял бы мою аккуратность, а не правило.
const ЖИВЫЕ = [
	[
		'ep-106: круглая скобка уехала на строку ниже',
		'Либо вступить в закрытый канал прямо в телеграме: [https://t.me/tribute/app?startapp=s26z](https://t.me/tribute/app?startapp=s26z\n\n)',
	],
	[
		'ep-97: в адрес врезки затёк кусок markdown',
		'::link{label="German Names in Frieren be like" url="https://youtu.be/XznWGAAXsd0](https://youtu.be/XznWGAAXsd0"}',
	],
	[
		'ep-67: у врезки подпись и адрес поменяны местами',
		'::link{label="https://www.animenewsnetwork.com/answerman/2017-05-31/.116809" url="How Are Anime Opening And Ending Themes Chosen?"}',
	],
];

// ─── ЗДОРОВОЕ: правило обязано МОЛЧАТЬ ─────────────────────────────────────
// Без этой половины «поймало все три» ничего не значит: правило, ругающееся
// на всё подряд, выглядит работающим.
const ЗДОРОВОЕ = [
	['обычная ссылка в тексте', 'Читайте [статью](https://t-j.ru/list/x/) целиком.'],
	['две ссылки в одной строке', 'Тут [раз](https://a.ru/) и [два](https://b.ru/).'],
	['врезка с подписью и адресом', '::link{label="Как выбирают опенинги" url="https://www.animenewsnetwork.com/answerman/2016-01-22/.97839"}'],
	['адрес с якорем и хвостом запроса', '::link{label="Опенинги" url="https://a.ru/x?y=1&z=2#:~:text=Опенинг"}'],
	['картинка с подписью — не ссылка', '::image{src="/images/uploads/a.jpg" alt="" caption="Кадр" width="column"}'],
	['ссылка на страницу сайта', 'Об этом [был выпуск](/posts/ep-4/).'],
	['квадратные скобки без ссылки', 'Он сказал [неразборчиво] и ушёл.'],
	['круглые скобки в тексте', 'Купить (даже не предзаказ уже) можно тут.'],
	['подпись врезки без адреса вовсе', '::label{text="Источники"}'],
];

function main() {
	const selftest = process.argv.includes('--selftest');

	console.log('── настоящие беды архива: правило обязано их назвать ──');
	for (const [name, body] of ЖИВЫЕ) {
		const found = сломаннаяРазметкаСсылок(пост(body));
		check(name, found.length > 0, `ничего не нашлось`);
	}

	console.log('\n── здоровое: правило обязано молчать ──');
	for (const [name, body] of ЗДОРОВОЕ) {
		const found = сломаннаяРазметкаСсылок(пост(body));
		check(name, found.length === 0, found.map((x) => x.why).join('; '));
	}

	console.log('\n── черновики не спрашиваются ──');
	{
		const found = сломаннаяРазметкаСсылок(пост(ЖИВЫЕ[1][1], { draft: true }));
		check('у черновика правило молчит — страницы у него нет', found.length === 0, String(found.length));
	}

	console.log('\n── причина названа, а не сведена в одну кучу ──');
	{
		const скобка = сломаннаяРазметкаСсылок(пост(ЖИВЫЕ[0][1]))[0];
		const адрес = сломаннаяРазметкаСсылок(пост(ЖИВЫЕ[1][1]))[0];
		check('у незакрытой скобки своя причина', /скобка не закрылась/.test(скобка?.why ?? ''), скобка?.why);
		check('у затёкшей разметки своя причина', /затекла разметка/.test(адрес?.why ?? ''), адрес?.why);
		check('названы пост и строка', скобка?.slug === 'проба' && Number.isInteger(скобка?.line), JSON.stringify(скобка));
	}

	if (selftest) {
		console.log('\n── ПОДЛОГИ: правило, ослеплённое нарочно, обязано пропустить беду ──');

		// Отменяем первое правило: считаем строку здоровой, если в ней есть хоть
		// какая-то круглая скобка. Ровно так рассуждала бы небрежная проверка.
		const слепое1 = (posts) =>
			сломаннаяРазметкаСсылок(posts).filter((x) => !/скобка не закрылась/.test(x.why));
		check(
			'ПОДЛОГ: без правила о скобке беда ep-106 проходит незамеченной',
			слепое1(пост(ЖИВЫЕ[0][1])).length === 0,
			'подлог не ослепил — значит правило ловит это чем-то ещё, проверить',
		);

		// Отменяем второе правило.
		const слепое2 = (posts) =>
			сломаннаяРазметкаСсылок(posts).filter((x) => !/затекла разметка/.test(x.why));
		check(
			'ПОДЛОГ: без правила об адресе беды ep-97 и ep-67 проходят незамеченными',
			слепое2(пост(ЖИВЫЕ[1][1])).length === 0 && слепое2(пост(ЖИВЫЕ[2][1])).length === 0,
			'подлог не ослепил',
		);
	}

	console.log();
	if (FAILURES.length) {
		console.log(`ЕСТЬ ОШИБКИ (${FAILURES.length}): ` + FAILURES.join('; '));
		process.exit(1);
	}
	console.log('Все проверки прошли.');
}

main();
