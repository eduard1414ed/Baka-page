// ФАСАД ВИДЕОЭССЕ: ЮТЮБА НА СТРАНИЦЕ НЕТ, ПОКА НЕ НАЖАЛИ.
//
//   node scripts/post-face-youtube.test.mjs             — спросить
//   node scripts/post-face-youtube.test.mjs --selftest  — плюс подлоги
//
// ЧТО СПРАШИВАЕМ И ПОЧЕМУ НЕ ГЛАЗАМИ.
//
// Обещание фасада — «до нажатия ни одного обращения к ютюбу» — проверяется
// сетевой панелью браузера, и это остаётся заказчику. А вот ДВЕ вещи под ним
// глазами не проверить вовсе, и обе тихие:
//
//   1) окошко появляется ТОЛЬКО по нажатию и ложится в ту же коробку;
//   2) двух источников звука не бывает — открыли ролик, значит звук встал;
//      пошёл звук, значит ролик закрылся. Второй источник тут не второй
//      `<audio>` (он на странице один), а именно РОЛИК, и разводить их
//      приходится руками.
//
// Берём НАСТОЯЩИЕ собранные скрипты из `dist/_astro/` — страницы материала
// и панели плеера — и исполняем их в Node поверх подделки окна, общей
// с проверками порядка и подключения (scripts/player-window-stub.mjs).
//
// ОТДЕЛЬНО СЧИТАЕМ, К КОМУ ХОДИТ СТРАНИЦА. Адрес ютюба в тексте скрипта —
// это НЕ обращение к ютюбу: строка лежит в коде и оживает только по нажатию.
// Правило проекта: считать надо то, что браузер запрашивает сам, — `src`
// у медиа и скриптов, `href` у `<link>`. Иначе замер завышает на три порядка.

import { readdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { makeWindow, makeFacade, makeElement } from './player-window-stub.mjs';

const DIST = new URL('../dist/', import.meta.url);

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

/**
 * Собранный скрипт — тот самый файл, который грузит браузер.
 *
 * ИЩЕМ ПО СОДЕРЖИМОМУ, А НЕ ПО ИМЕНИ. Файлов `_slug_.astro_…` в сборке ДВА —
 * у страницы материала и у страницы тайтла, — и «первый подходящий по имени»
 * половину прогонов был бы чужим. Имя тут не различает, различает примета.
 */
async function собранныйСкрипт(примета) {
	const папка = new URL('_astro/', DIST);
	const имена = (await readdir(fileURLToPath(папка))).filter((f) => f.endsWith('.js'));
	const подошли = [];
	for (const имя of имена) {
		const код = await readFile(new URL(имя, папка), 'utf8');
		if (код.includes(примета)) подошли.push({ имя, код });
	}
	if (подошли.length !== 1) {
		console.log(`ПРОВЕРКА ОСЛЕПЛА: файлов с приметой «${примета}» в dist/_astro/ ${подошли.length}, а нужен ровно один.`);
		console.log('Это не «всё хорошо»: либо сайт не собран (npm run build), либо примета устарела и её надо чинить.');
		process.exit(1);
	}
	return подошли[0].код;
}

// ПРИМЕТЫ — куски кода, которые в этих скриптах есть и больше нигде.
const СТРАНИЦА = '.post-face[data-youtube]';
const ПАНЕЛЬ = '__bakaPlayerReady';

/**
 * Исполнить скрипты поверх подделки и отдать управление проверкам.
 * Подделка стоит, ПОКА идут проверки: обработчики без окна под ними падают.
 */
async function сОкном({ фасады = [], скрипты, подмена = (код) => код }, проверки) {
	const окно = makeWindow({ фасады });
	const имена = ['window', 'document', 'matchMedia', 'IntersectionObserver', 'HTMLMediaElement', 'requestAnimationFrame', 'getSelection', 'location', 'history', 'localStorage'];
	const прежние = Object.fromEntries(имена.map((имя) => [имя, globalThis[имя]]));

	globalThis.window = окно.win;
	globalThis.document = окно.documentStub;
	for (const имя of имена.slice(2)) globalThis[имя] = окно.win[имя];

	try {
		for (const начало of скрипты) {
			// eslint-disable-next-line no-new-func
			new Function(подмена(await собранныйСкрипт(начало)))();
		}
		for (const { name, fn } of окно.handlers) if (name === 'astro:page-load') await fn();
		await проверки(окно);
	} finally {
		for (const имя of имена) {
			if (прежние[имя] === undefined) delete globalThis[имя];
			else globalThis[имя] = прежние[имя];
		}
	}
	return окно;
}

const нажать = (фасад) => фасад.кнопка.dispatch('click');

console.log('ФАСАД ВИДЕОЭССЕ: ютюба на странице нет, пока не нажали.');
console.log();

// ── 1. До нажатия и после ─────────────────────────────────────────────────
console.log('── окошко появляется только по нажатию ──');

{
	const фасад = makeFacade({ ролик: 'sR8gPdLqE_M' });
	await сОкном({ фасады: [фасад], скрипты: [СТРАНИЦА] }, () => {
		скажи(фасад.окошко() === null, 'до нажатия окошка нет — на странице ни одного обращения к ютюбу');
		скажи(фасад.кнопкаНаМесте(), 'кнопка на кадре стоит');

		нажать(фасад);

		const окошко = фасад.окошко();
		скажи(Boolean(окошко), 'после нажатия окошко появилось');
		скажи(окошко?.src === 'https://www.youtube.com/embed/sR8gPdLqE_M?autoplay=1', `и оно про тот самый ролик: ${окошко?.src}`);
		скажи(/[?&]autoplay=1/.test(окошко?.src ?? ''), 'с автозапуском — второго нажатия внутри чужого окошка не будет');
		скажи(окошко?.className === 'post-face-embed', 'окошко ложится в ту же коробку своим классом');
		скажи(!фасад.кнопкаНаМесте(), 'кнопка ушла из разметки, а не спряталась атрибутом');
	});
}

// ── 2. Двух источников звука не бывает ────────────────────────────────────
console.log();
console.log('── двух источников звука не бывает ──');

{
	// Плеер подделываем сами: здесь спрашивается не он, а то, зовут ли его.
	const первый = makeFacade({ ролик: 'AAAAAAAAAAA' });
	const второй = makeFacade({ ролик: 'BBBBBBBBBBB' });

	await сОкном({ фасады: [первый, второй], скрипты: [СТРАНИЦА] }, (окно) => {
		let пауз = 0;
		окно.win.__bakaPlayer = { audio: makeElement({ pause: () => (пауз += 1) }) };

		нажать(первый);
		скажи(пауз === 1, 'открыли ролик — звук поставлен на паузу');

		нажать(второй);
		скажи(второй.окошко() !== null, 'второй фасад открылся');
		скажи(первый.окошко() === null, 'первый закрылся сам — двух роликов разом не бывает');
		скажи(первый.кнопкаНаМесте(), 'и кнопка вернулась к нему на кадр');
	});
}

// ── 3. Запуск звука закрывает ролик ───────────────────────────────────────
console.log();
console.log('── пошёл звук — ролик закрылся ──');

{
	const фасад = makeFacade({ ролик: 'CCCCCCCCCCC' });
	// Скрипты в том же порядке, в каком их перечисляет собранная страница.
	await сОкном({ фасады: [фасад], скрипты: [СТРАНИЦА, ПАНЕЛЬ] }, (окно) => {
		скажи(typeof окно.win.__bakaCloseFacades === 'function', 'страница выставила дверь «закрой ролики»');

		нажать(фасад);
		скажи(фасад.окошко() !== null, 'ролик открыт');

		// Звук пошёл ЛЮБЫМ из пяти путей — событие одно на все.
		const звук = окно.win.__bakaPlayer.audio;
		звук.dispatch('play');

		скажи(фасад.окошко() === null, 'ролик закрылся, как только пошёл звук');
		скажи(фасад.кнопкаНаМесте(), 'кнопка вернулась на кадр');
	});
}

// ── 4. Дверь не остаётся от прошлой страницы ──────────────────────────────
console.log();
console.log('── на странице без фасадов двери нет ──');

{
	await сОкном({ фасады: [], скрипты: [СТРАНИЦА] }, (окно) => {
		скажи(окно.win.__bakaCloseFacades === undefined, 'фасадов нет — дверь убрана, а не оставлена от прошлой страницы');
	});
}

// ── 5. Подлоги ────────────────────────────────────────────────────────────
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── подлоги: проверка обязана покраснеть ──');

	// ПОДЛОГ 1 — ОКОШКО ЛЕЖИТ В РАЗМЕТКЕ СРАЗУ, а по нажатию только
	// показывается. Ровно так фасад и сделали бы «попроще», и ровно это
	// он обязан не делать: ютюб оказался бы на странице до нажатия.
	const фасад = makeFacade({ ролик: 'DDDDDDDDDDD' });
	фасад.сцена.append(makeElement({ tagName: 'iframe', src: 'https://www.youtube.com/embed/DDDDDDDDDDD' }));
	await сОкном({ фасады: [фасад], скрипты: [СТРАНИЦА] }, () => {
		скажи(фасад.окошко() !== null, 'подлог «окошко лежит сразу» виден проверке — она смотрит на разметку, а не на код');
	});

	// ПОДЛОГ 2 — АВТОЗАПУСК УБРАН. Человек нажал «смотреть» и должен был бы
	// нажимать второй раз, уже внутри чужого окошка.
	const фасад2 = makeFacade({ ролик: 'EEEEEEEEEEE' });
	await сОкном(
		{
			фасады: [фасад2],
			скрипты: [СТРАНИЦА],
			подмена: (код) => {
				if (!код.includes('?autoplay=1')) {
					console.log(' ПЛОХО  ПОДЛОГ НЕ СРАБОТАЛ: автозапуска в собранном скрипте не нашёл. Чинить подлог, а не код.');
					плохо++;
					return код;
				}
				return код.replace('?autoplay=1', '');
			},
		},
		() => {
			нажать(фасад2);
			скажи(!/autoplay=1/.test(фасад2.окошко()?.src ?? ''), 'подлог «автозапуск убран» пойман');
		},
	);

	// ПОДЛОГ 3 — ЗВУК НЕ ОСТАНАВЛИВАЕТСЯ ПРИ ОТКРЫТИИ РОЛИКА.
	const фасад3 = makeFacade({ ролик: 'FFFFFFFFFFF' });
	await сОкном(
		{
			фасады: [фасад3],
			скрипты: [СТРАНИЦА],
			подмена: (код) => {
				// Забираем ВЫРАЖЕНИЕ ЦЕЛИКОМ, вместе с `window.` перед ним.
				// Первая редакция подлога брала только хвост — и оставляла
				// `window.void 0`, то есть ломала синтаксис вместо правила.
				// Проверка падала целиком и выглядела красной по чужой причине.
				const пауза = /(?:window\.)?__bakaPlayer\?\.audio\?\.pause\(\)/;
				if (!пауза.test(код)) {
					console.log(' ПЛОХО  ПОДЛОГ НЕ СРАБОТАЛ: остановки звука в собранном скрипте не нашёл. Чинить подлог, а не код.');
					плохо++;
					return код;
				}
				return код.replace(пауза, 'void 0');
			},
		},
		(окно) => {
			let пауз = 0;
			окно.win.__bakaPlayer = { audio: makeElement({ pause: () => (пауз += 1) }) };
			нажать(фасад3);
			скажи(пауз === 0, 'подлог «звук не останавливается» пойман');
		},
	);
}

console.log();
if (плохо) {
	console.log(`ПЛОХО: ${плохо}. Фасад поведёт себя не так, как обещано.`);
	process.exit(1);
}
console.log('Всё сошлось.');
