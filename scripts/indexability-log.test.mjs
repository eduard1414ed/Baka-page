// ПРОВЕРКА ДИФФА И ЗАСЛОНА ИНДЕКСИРУЕМОСТИ (scripts/indexability-log.mjs).
//
//   node scripts/indexability-log.test.mjs           — проверить
//   node scripts/indexability-log.test.mjs --подлог  — убедиться, что краснеет
//
// Здесь проверяется НЕ правило (оно в scripts/indexability.test.mjs), а две
// вещи вокруг него: умеет ли дифф отличать удалённый пост от поехавшего
// разбора, и ловит ли заслон случай «данные поехали целиком».
//
// Первое важнее, чем кажется: заслон, краснеющий на обычной работе заказчика,
// снимут вместе с пользой. Посты удаляются регулярно — восемь удалений
// за две недели августа 2026, — и каждое из них законно убирает страницу
// из индекса.

import { readFile, writeFile, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const ИСХОДНИК = new URL('./indexability-log.mjs', import.meta.url);
const ПОДМЕНА = new URL('./indexability-log.подлог.mjs', import.meta.url);

const ПОДЛОГИ = {
	// Дифф перестал отличать удалённый пост от пропавшего упоминания —
	// то есть вернулось правило из задания «любая непустая left это поломка».
	удаления: [
		'const всеПотерянныеИсчезли = потеряно.length > 0 && потеряно.every((p) => !постыСейчас.has(p));',
		'const всеПотерянныеИсчезли = false;',
	],
	// Заслон перестал ловить «в индексе ноль страниц».
	заслон: ['if (вИндексе === 0) return `в индекс не попало НИ ОДНОЙ страницы из ${всего}`;', 'if (вИндексе < 0) return null;'],
};

const стр = (id, index, своиПосты = []) => ({ id, index, своиПосты });

const СЛУЧАИ = [
	[
		'прошлого лога нет — обе стороны пусты, это первая сборка',
		(m) => {
			const р = m.переходы(null, { pages: [стр('a', true)], posts: ['p1'] });
			return р.entered.length === 0 && р.left.length === 0 ? null : 'на пустом прошлом дифф что-то насчитал';
		},
	],
	[
		'страница выпала из-за УДАЛЁННОГО поста — объяснено',
		(m) => {
			const прежний = { pages: [стр('a', true, ['p1'])], posts: ['p1'] };
			const нынешний = { pages: [стр('a', false, [])], posts: [] }; // поста p1 больше нет
			const р = m.переходы(прежний, нынешний);
			if (!р.left.includes('a')) return 'страница не попала в left вовсе';
			if (!р.объяснённые.includes('a')) return 'удаление поста не признано объяснением';
			return null;
		},
	],
	[
		'страница выпала, а пост НА МЕСТЕ — не объяснено, это тревога',
		(m) => {
			const прежний = { pages: [стр('a', true, ['p1'])], posts: ['p1'] };
			const нынешний = { pages: [стр('a', false, [])], posts: ['p1'] }; // пост жив
			const р = m.переходы(прежний, нынешний);
			if (!р.необъяснённые.includes('a')) return 'пропажа упоминания при живом посте сошла за обычную работу';
			return null;
		},
	],
	[
		'страница вошла в индекс — это entered и никакой тревоги',
		(m) => {
			const прежний = { pages: [стр('a', false, [])], posts: [] };
			const нынешний = { pages: [стр('a', true, ['p1'])], posts: ['p1'] };
			const р = m.переходы(прежний, нынешний);
			return р.entered.includes('a') && р.left.length === 0 ? null : 'вход в индекс посчитан неверно';
		},
	],
	[
		'заслон: в индексе ноль страниц — беда',
		(m) => (m.катастрофа({ всего: 658, вИндексе: 0, соСвоими: 640 }) ? null : 'заслон промолчал на пустом индексе'),
	],
	[
		'заслон: ни у одной страницы нет своих упоминаний — беда',
		(m) => (m.катастрофа({ всего: 658, вИндексе: 5, соСвоими: 0 }) ? null : 'заслон промолчал на отвалившемся разборе'),
	],
	[
		'заслон: ЗДОРОВЫЕ числа — молчит',
		(m) => (m.катастрофа({ всего: 658, вИндексе: 306, соСвоими: 571 }) ? 'заслон покраснел на здоровых числах' : null),
	],
];

function проверить(m) {
	const беды = [];
	for (const [имя, случай] of СЛУЧАИ) {
		let ответ;
		try {
			ответ = случай(m);
		} catch (e) {
			ответ = `упало — ${e.message}`;
		}
		if (ответ) беды.push(`«${имя}»: ${ответ}`);
	}
	return беды;
}

const загрузить = (href) => import(`${href}?${Date.now()}${Math.random()}`);

async function главная() {
	const подлог = process.argv.includes('--подлог') || process.argv.includes('--selftest');

	if (!подлог) {
		const беды = проверить(await загрузить(ИСХОДНИК.href));
		if (беды.length > 0) {
			console.error(`✗ Дифф или заслон индексируемости неисправны, случаев ${беды.length}:`);
			for (const б of беды) console.error('   ' + б);
			return 1;
		}
		console.log(`ок      Дифф и заслон индексируемости: ${СЛУЧАИ.length} случаев.`);
		return 0;
	}

	const исходник = await readFile(ИСХОДНИК, 'utf8');
	let код = 0;
	for (const [имя, [было, стало]] of Object.entries(ПОДЛОГИ)) {
		if (!исходник.includes(было)) {
			console.error(`✗ ПОДЛОГ «${имя}» НЕ СОБРАН: строки нет дословно. Значит код переписали.`);
			код = 1;
			continue;
		}
		await writeFile(ПОДМЕНА, исходник.replace(было, стало), 'utf8');
		let беды;
		try {
			беды = проверить(await загрузить(ПОДМЕНА.href));
		} finally {
			await unlink(ПОДМЕНА).catch(() => {});
		}
		if (беды.length === 0) {
			console.error(`✗ ПОДЛОГ «${имя}» НЕ ПОЙМАН: развели строку, а проверка промолчала.`);
			код = 1;
		} else {
			console.log(`✓ Подлог «${имя}» пойман: ${беды[0]}`);
		}
	}
	if (код === 0) {
		const беды = проверить(await загрузить(ИСХОДНИК.href));
		if (беды.length > 0) {
			console.error('✗ А на здоровом коде проверка красная — значит ловит себя:');
			for (const б of беды) console.error('   ' + б);
			код = 1;
		} else {
			console.log('✓ На здоровом коде проверка молчит.');
		}
	}
	return код;
}

// Русские буквы в пути: import.meta.url их кодирует, process.argv[1] — нет.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
	process.exitCode = await главная();
}
