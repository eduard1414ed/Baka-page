/**
 * Прогнать тело статьи через ту же разметку, что и сборка.
 * `путь` уезжает в текст ошибки — им проверяется, что файл статьи назван.
 */
async function вРазметку(тело, путь = 'src/content/posts/проба.md') {
	let процессор = unified().use(remarkParse);
	for (const плагин of цепочка) процессор = процессор.use(плагин);
	процессор = процессор.use(remarkRehype, { allowDangerousHtml: true }).use(rehypeStringify, { allowDangerousHtml: true });

	const файл = { value: тело, path: путь, data: { astro: { frontmatter: { title: 'Проба', category: 'note', draft: true } } } };
	const итог = await процессор.process(файл);
	return String(итог);
}

// ── Живые примеры из коллекции ────────────────────────────────────────────
function всеПосты() {
	const посты = [];
	for (const файл of readdirSync(fileURLToPath(POSTS_DIR))) {
		if (!файл.endsWith('.md')) continue;
		const сырое = readFileSync(fileURLToPath(new URL(файл, POSTS_DIR)), 'utf8');
		const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(сырое);
		if (!m) continue;
		посты.push({ id: файл.replace(/\.md$/, ''), data: normalizeFrontmatter(yaml.load(m[1]) ?? {}), body: m[2] });
	}
	return посты;
}

