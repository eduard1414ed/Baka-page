/** Что плагин сказал в лог и что при этом вышло разметкой. */
async function приБеде(тело) {
	const сказано = [];
	const прежний = console.error;
	console.error = (...части) => сказано.push(части.join(' '));
	try {
		return { разметка: await вРазметку(тело, путь), сказано: сказано.join('\n') };
	} finally {
		console.error = прежний;
	}
}

