/** Одна статья с одной врезкой — и что скажет о ней заслон. */
function заслонОВрезке(строка) {
	const архив = new Map(посты.map((p) => [p.id, { ...p, файл: `src/content/posts/${p.id}.md` }]));
	архив.set('проба', { id: 'проба', файл: путь, data: { title: 'Проба', category: 'note', date: new Date() }, body: `${строка}\n` });
	return бедыВрезок(архив, вФиде).filter((б) => !б.черновик && б.где === путь);
}

