#!/usr/bin/env node
// ПРОВЕРКА ЗАСЛОНА ПЕРЕД ЗАПИСЬЮ У РОБОТА ВЫПУСКОВ (находка 3 ревизии).
//
// Заголовок и описание выпуска приходят из чужого сервиса. Что придёт завтра,
// мы не знаем, а кривая шапка роняет сборку ВСЕГО САЙТА. Поэтому черновик
// сначала собирается в памяти и читается настоящим `js-yaml` — тем же, каким
// его будет читать сборка.
//
// ЗДЕСЬ СПРАШИВАЮТСЯ ОБЕ СТОРОНЫ. Мало показать, что заслон ловит беду:
// «пусто» у проверки ничего не значит, пока не показано, что она умеет
// находить, — и наоборот, проверка, ругающаяся на здоровое, будет снята
// первой же сессией.
//
//   node scripts/sync-episodes.test.mjs

// Черновик собирается ТЕМ ЖЕ кодом, которым его собирает робот. Переписанный
// рядом своими словами проверял бы сам себя, а не робота (урок проекта).
import { buildDraft as draft, frontmatterProblems } from './sync-episodes.mjs';

let провалов = 0;
const проба = (имя, вышло, ждали) => {
	const ок = вышло === ждали;
	if (!ок) провалов += 1;
	console.log(`  ${ок ? 'ок      ' : 'ПРОВАЛ  '} ${имя}${ок ? '' : ` — вышло ${вышло}, ждали ${ждали}`}`);
};

const день = new Date('2026-08-15T10:00:00Z');
const беда = (episode) => {
	const text = draft(episode);
	const ждали = { title: episode.title, guid: episode.guid, date: день.toISOString().slice(0, 10) };
	return frontmatterProblems('ep-999', text, ждали).length;
};

console.log('Здоровое — заслон обязан молчать:');
проба('обычный заголовок', беда({ title: 'Выпуск 150. Про аниме', guid: 'guid-1', pubDate: день, descriptionHtml: '<p>Текст</p>', imageUrl: null }), 0);
проба('апостроф в заголовке', беда({ title: "Про 'Наруто' и других", guid: 'guid-2', pubDate: день, descriptionHtml: '', imageUrl: null }), 0);
проба('двоеточие в заголовке', беда({ title: 'Re:Zero — разбор', guid: 'guid-3', pubDate: день, descriptionHtml: '', imageUrl: null }), 0);
проба('решётка и кавычки', беда({ title: '#150 «Баки!» — итоги', guid: 'guid-4', pubDate: день, descriptionHtml: '', imageUrl: null }), 0);

console.log('\nБольное — заслон обязан назвать беду:');
// Перенос строки внутри заголовка: YAML прочитает такую шапку иначе, чем мы
// клали, либо не прочитает вовсе. Ровно то, ради чего заслон и написан.
проба('перенос строки в заголовке', беда({ title: 'Выпуск 150\nвторая строка', guid: 'guid-5', pubDate: день, descriptionHtml: '', imageUrl: null }) > 0, true);
// Заголовок, закрывающий шапку: «---» посреди значения.
проба('строка «---» в заголовке', беда({ title: 'Итоги\n---\nfake: да', guid: 'guid-6', pubDate: день, descriptionHtml: '', imageUrl: null }) > 0, true);
// guid с переносом — то же самое, но во втором поле.
проба('перенос строки в guid', беда({ title: 'Обычный', guid: 'guid\nsecond: подмена', pubDate: день, descriptionHtml: '', imageUrl: null }) > 0, true);

console.log(провалов === 0 ? '\nВсё сошлось.' : `\nПРОВАЛОВ: ${провалов}`);
process.exitCode = провалов === 0 ? 0 : 1;
