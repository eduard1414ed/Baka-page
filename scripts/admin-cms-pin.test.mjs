/**
 * ПРОГРАММА АДМИНКИ ПРИБИТА К ВЕРСИИ И СВЕРЯЕТСЯ ПО ОТПЕЧАТКУ.
 *
 * Страница /admin/ грузит программу CMS с чужого сайта (unpkg), и на этой же
 * странице живёт ключ от GitHub с правами repo,user. Пока в адресе не стояла
 * версия, браузер брал «самую свежую какая есть»: что unpkg завтра положит,
 * то и запустится. Теперь версия названа поимённо, а атрибут integrity —
 * отпечаток содержимого, по которому браузер САМ отказывается запускать
 * подменённый файл.
 *
 * Проверка спрашивает то же, что спросит браузер: скачивает файл по тому
 * самому адресу и считает его отпечаток. Разошлось — админка не запустится
 * вовсе, и узнать об этом лучше здесь, чем от заказчика.
 *
 * Ключ --подлог меняет в скачанном файле один знак — ровно так выглядела бы
 * подмена пакета — и ждёт, что отпечаток разойдётся.
 */
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve, dirname, join } from 'node:path';

const КОРЕНЬ = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const СТРАНИЦА = join(КОРЕНЬ, 'public/admin/index.html');

async function main() {
	const подлог = process.argv.includes('--подлог');
	const html = await readFile(СТРАНИЦА, 'utf8');

	const тег = /<script\b[^>]*\bsrc="(https:\/\/unpkg\.com\/[^"]+)"[^>]*>/s.exec(html);
	if (!тег) {
		console.log('✗ Тега со скриптом CMS на странице админки не нашлось — проверять нечего.');
		return 1;
	}
	const адрес = тег[1];
	const отпечаток = /\bintegrity="sha384-([A-Za-z0-9+/=]+)"/.exec(тег[0])?.[1];
	const кросс = /\bcrossorigin="anonymous"/.test(тег[0]);

	console.log(`адрес       ${адрес}`);

	if (!/@sveltia\/cms@\d+\.\d+\.\d+\//.test(адрес)) {
		console.log('✗✗ ВЕРСИЯ В АДРЕСЕ НЕ НАЗВАНА.');
		console.log('   Браузер возьмёт самую свежую какая есть — то есть запустит на странице');
		console.log('   с ключом от GitHub то, что чужой сайт положит туда завтра.');
		return 1;
	}
	if (!отпечаток) {
		console.log('✗✗ ОТПЕЧАТКА (integrity) НЕТ.');
		console.log('   Версия названа, но подменить содержимое по тому же адресу никто не мешает.');
		return 1;
	}
	if (!кросс) {
		console.log('✗✗ НЕТ crossorigin="anonymous".');
		console.log('   Без него браузер отпечаток у чужого домена не проверяет ВОВСЕ,');
		console.log('   и строчка integrity становится украшением.');
		return 1;
	}

	let байты;
	try {
		const ответ = await fetch(адрес);
		if (!ответ.ok) {
			console.log(`✗ unpkg ответил кодом ${ответ.status} — сверять не с чем.`);
			console.log('  Это беда связи или снятой версии, а не обязательно поломка.');
			return 1;
		}
		байты = Buffer.from(await ответ.arrayBuffer());
	} catch (е) {
		console.log(`✗ До unpkg не достучались: ${е.message}`);
		console.log('  Проверка без сети невозможна — она спрашивает ровно то, что спросит браузер.');
		return 1;
	}

	if (подлог) {
		// Меняем один знак — так выглядела бы подменённая сборка пакета.
		байты = Buffer.from(байты);
		байты[байты.length - 1] = байты[байты.length - 1] ^ 1;
	}

	const посчитано = createHash('sha384').update(байты).digest('base64');
	const сошлось = посчитано === отпечаток;

	console.log(`в странице  sha384-${отпечаток}`);
	console.log(`у файла     sha384-${посчитано}`);
	console.log();

	if (подлог) {
		if (!сошлось) {
			console.log('✓ ПОДЛОГ ПОЙМАН: изменили в файле один знак — отпечаток разошёлся.');
			console.log('  Значит браузер подменённую программу запускать откажется.');
			return 0;
		}
		console.log('✗ ПОДЛОГ НЕ ПОЙМАН: файл изменён, а отпечаток тот же — так не бывает,');
		console.log('  значит проверка считает не то, что думает.');
		return 1;
	}

	if (!сошлось) {
		console.log('✗✗ ОТПЕЧАТОК НЕ СОШЁЛСЯ С ФАЙЛОМ.');
		console.log('   Браузер откажется запускать программу, и админка не откроется вовсе.');
		console.log('   Либо в отпечатке опечатка, либо по этому адресу теперь другой файл.');
		return 1;
	}
	console.log('ок      Версия названа, отпечаток сходится с тем, что отдаёт unpkg,');
	console.log('        подмена содержимого браузером не запустится.');
	return 0;
}

const позвалиНапрямую = resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1] ?? '');
if (позвалиНапрямую) process.exit(await main());
