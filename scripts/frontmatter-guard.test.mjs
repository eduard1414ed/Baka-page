// ЗАСЛОН «ШАПКА ЧИТАЕТСЯ ОБРАТНО» — ОДИН НА ЧЕТЫРЁХ, И ОН УМЕЕТ ПРОВАЛИТЬСЯ.
//
//   node scripts/frontmatter-guard.test.mjs             — спросить
//   node scripts/frontmatter-guard.test.mjs --selftest  — плюс подлог: прежнее правило
//
// ЗАЧЕМ. Кривая шапка роняет сборку ВСЕГО САЙТА, а не свой файл. Правило
// «перед записью прочитать шапку тем же js-yaml, каким её читает сборка»
// стояло у троих из пятерых, кто пишет в `src/content/posts/` (доревизия
// задачи 15, находка 31). Теперь оно одно на всех, и спрашивается здесь
// у КАЖДОГО из четырёх — не пересказом, а вызовом их собственных функций.
//
// ПОЧЕМУ ПОДЛОГ ВОЗВРАЩАЕТ ПРЕЖНЕЕ ПРАВИЛО, А НЕ ЛОМАЕТ ШАПКУ НАУГАД.
// Заслон обязан ловить ровно то, ради чего заведён: своё правило кавычек
// в этом проекте уже проглядело двоеточие В КОНЦЕ заголовка и положило бы
// сайт на 70 постах. Значит подлог — это то самое своё правило.
import { бедыШапки } from './frontmatter-guard.mjs';
import { frontmatterProblems as шапкаВыпуска } from './sync-episodes.mjs';
import { frontmatterProblems as шапкаТелеграма } from './telegram-import.mjs';
import { replaceTitle } from './archive-season-titles.mjs';
import { editHead } from './archive-external-posts.mjs';

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

const файл = (шапка) => `---\n${шапка}\n---\n\nТело поста.\n`;

console.log('ЗАСЛОН «ШАПКА ЧИТАЕТСЯ ОБРАТНО»: и ловит, и молчит на здоровом.');
console.log();

// ── 1. Сам заслон ─────────────────────────────────────────────────────────
console.log('── общее правило ──');

скажи(
	бедыШапки('пост', файл("title: 'Обзор аниме «Всё зря:»'\ndraft: true"), { title: 'Обзор аниме «Всё зря:»', draft: true }).length === 0,
	'здоровая шапка с двоеточием в кавычках — молчит',
);

// ДВОЕТОЧИЕ В КОНЦЕ — ТОТ САМЫЙ ЗНАК, КОТОРОГО НЕ ВИДЕЛО СВОЁ ПРАВИЛО КАВЫЧЕК.
// Двоеточие ВНУТРИ строки («Всё зря:»») YAML отличным образом переживает —
// значит и заслон обязан на нём молчать, иначе он ругался бы на здоровое.
скажи(
	бедыШапки('пост', файл('title: Обзор всех аниме весны:'), { title: 'Обзор всех аниме весны:' }).length > 0,
	'двоеточие В КОНЦЕ и без кавычек — назвал беду',
);
скажи(
	бедыШапки('пост', файл('title: Обзор аниме «Всё зря:»'), { title: 'Обзор аниме «Всё зря:»' }).length === 0,
	'двоеточие ВНУТРИ строки — здоровое, заслон молчит',
);

скажи(
	бедыШапки('пост', файл('title: Строка\nс переносом'), { title: 'Строка\nс переносом' }).length > 0,
	'перенос строки в заголовке — назвал беду',
);

// YAML читает `007` числом, а `true` — булевым: ошибки нет, а заголовок пропал.
// Это половина находки: «разобралось» и «разобралось тем, что клали» — разное.
// (Русское «да» булевым НЕ читается: js-yaml разбирает по YAML 1.2, где
// булевых слов ровно два. Проверено — на нём заслон законно молчит.)
скажи(
	бедыШапки('пост', файл('title: 007'), { title: '007' }).length > 0,
	'заголовок «007» прочитался числом — назвал беду, хотя YAML не ругался',
);
скажи(
	бедыШапки('пост', файл('title: true'), { title: 'true' }).length > 0,
	'заголовок «true» прочитался булевым — назвал беду',
);

скажи(
	бедыШапки('пост', файл('date: 2026-08-15'), { date: '2026-08-15' }).length === 0,
	'дата читается датой, и это не беда — сверяется сам день',
);

скажи(
	бедыШапки('пост', файл('bonusLinks:\n  boosty: https://boosty.to/x'), { 'bonusLinks.boosty': 'https://boosty.to/x' }).length === 0,
	'вложенное поле читается точкой',
);

скажи(бедыШапки('пост', '---\n: : :\n---\n', { title: 'X' }).length > 0, 'шапка вовсе не разбирается — назвал беду');
скажи(бедыШапки('пост', файл('просто строка'), { title: 'X' }).length > 0, 'шапка прочиталась не полями — назвал беду');

// ── 2. Каждый из четырёх ──────────────────────────────────────────────────
// Спрашиваем ИХ СОБСТВЕННЫЕ функции: переписанная рядом копия проверяла бы
// саму себя, а не то, что стоит у робота.
console.log();
console.log('── четверо, кто пишет в src/content/posts/ ──');

const выпускЗдоровый = файл("title: 'Выпуск 150: про что-то'\naudioGuid: abc-123\ncategory: podcast\ndraft: true\ndate: 2026-08-15");
скажи(
	шапкаВыпуска('ep-150', выпускЗдоровый, { title: 'Выпуск 150: про что-то', guid: 'abc-123', date: '2026-08-15' }).length === 0,
	'робот выпусков: здоровая шапка — молчит',
);
скажи(
	шапкаВыпуска('ep-150', файл('title: Выпуск 150: про что-то\naudioGuid: abc-123\ncategory: podcast\ndraft: true\ndate: 2026-08-15'), {
		title: 'Выпуск 150: про что-то',
		guid: 'abc-123',
		date: '2026-08-15',
	}).length > 0,
	'робот выпусков: двоеточие в заголовке без кавычек — назвал беду',
);

const тгЖдали = { id: 42, slug: 'post-42', title: 'Заголовок', category: 'note', date: '2026-08-15', bonusLinks: {} };
const тгЗдоровый = файл('title: Заголовок\ncategory: note\ntgId: 42\ntgUrl: https://t.me/podcastbaka/42\ndraft: true\ndate: 2026-08-15');
скажи(шапкаТелеграма(тгЖдали, тгЗдоровый).length === 0, 'импорт из телеграма: здоровая шапка — молчит');
скажи(
	шапкаТелеграма(тгЖдали, файл('title: Заголовок\ncategory: note\ntgId: 42\ntgUrl: https://t.me/podcastbaka/42\ndraft: true\ndate: не дата')).length > 0,
	'импорт из телеграма: испорченная дата — назвал беду',
);

// Заголовки сезонов: значение готовит `replaceTitle` через сам js-yaml,
// поэтому здоровым обязано выйти даже название с двоеточием и кавычками.
const сезонШапка = "---\ntitle: 'Обзор всех аниме весны:'\ndate: 2022-05-15\ndraft: true\n---\n\nТело.\n";
const сезонНовый = 'Обзор аниме «Рыцарь: Скелет»';
скажи(
	бедыШапки('сезон', replaceTitle(сезонШапка.split('\n\n')[0], сезонНовый) + '\n\nТело.\n', { title: сезонНовый }).length === 0,
	'заголовки сезонов: название с двоеточием и кавычками записалось и прочиталось',
);

// Посты-ссылки: адрес подставляется в строку как есть, и это чужие данные.
const внешняяШапка = "---\ncategory: note\nexternalUrl: ''\ncover: ''\nnoCover: true\ndraft: true\n---";
скажи(
	бедыШапки('внешний', editHead(внешняяШапка, { url: 'https://t-j.ru/a/', cover: '/i/c.jpg' }) + '\n\nТело.\n', {
		externalUrl: 'https://t-j.ru/a/',
		cover: '/i/c.jpg',
		noCover: false,
	}).length === 0,
	'посты-ссылки: адрес и обложка прочитались обратно',
);

// ── ПОДЛОГ ────────────────────────────────────────────────────────────────
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── ПОДЛОГ: прежнее «своё правило кавычек» ──');

	// Ровно то правило, что жило в проекте до заслона: кавычки ставим, если
	// в строке встретился один из опасных знаков. Двоеточия В КОНЦЕ оно
	// не видело — заголовок «Обзор всех аниме весны:» уезжал без кавычек.
	const прежнееПравило = (текст) => (/[:#\-{}[\]&*!|>%@`"']\s/.test(текст) ? `'${текст.replaceAll("'", "''")}'` : текст);

	const опасный = 'Обзор всех аниме весны:';
	const такПисалиРаньше = файл(`title: ${прежнееПравило(опасный)}`);
	const поймано = бедыШапки('пост', такПисалиРаньше, { title: опасный }).length > 0;
	скажи(поймано, `прежнее правило записало «${прежнееПравило(опасный)}» — заслон это поймал`);

	// И ВТОРАЯ ПОЛОВИНА: на том, что прежнее правило писало ПРАВИЛЬНО, заслон
	// обязан молчать. Без этого «поймал» неотличимо от «ругается на всё».
	const безопасный = 'Обзор всех аниме весны';
	скажи(
		бедыШапки('пост', файл(`title: ${прежнееПравило(безопасный)}`), { title: безопасный }).length === 0,
		'на безобидном заголовке прежнее правило и заслон согласны — заслон молчит',
	);
}

console.log();
if (плохо) {
	console.log(`ПРОВАЛОВ: ${плохо}`);
	process.exit(1);
}
console.log('Заслон один, стоит у всех четверых, и умеет провалиться.');
