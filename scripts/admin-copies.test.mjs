// КОПИИ, КОТОРЫЕ СВЕСТИ НЕЛЬЗЯ, — И ПОТОМУ ОНИ СВЕРЯЮТСЯ.
//
//   node scripts/admin-copies.test.mjs             — спросить
//   node scripts/admin-copies.test.mjs --selftest  — плюс подлоги
//
// ЗАЧЕМ. Страницы админки (`public/admin/…`) живут ВНЕ сборки Astro: это
// обычные статические файлы, и импортировать из `src/` или из `scripts/`
// они не умеют. Значит часть правил у них своя, и свести копии в один дом
// невозможно физически. Остаётся одно — сверять.
//
// ПОЧЕМУ НЕ ПОМЕТКА «МЕНЯЕТЕ ТУТ — ПОПРАВЬТЕ И ТАМ». В этом проекте такая
// пометка не удержала ни одной копии, и обе копии ниже — доказательство:
//   • у списка полей пометки не было вовсе, а третью копию (схему сборки)
//     не называл никто (ревизия задачи 15, находка 12);
//   • у палитры пометка СТОЯЛА с обеих сторон — и не помогла: `--muted` был
//     скопирован неправильно с самого выноса стилей 11 августа 2026, то есть
//     копия была неточной С РОЖДЕНИЯ, и не сверял её никто ни разу
//     (находка 12а).
//
// ЧТО СПРАШИВАЕТСЯ:
//   1. СПИСОК ПОЛЕЙ «ПРАВЛЕНО РУКАМИ» — три копии, и все три обязаны
//      совпадать: `scripts/anime-lib.mjs` (кто НЕ перезаписывает поле),
//      `public/admin/index.html` (кто СТАВИТ признак) и `src/content.config.ts`
//      (кто это значение примет). Разъедутся — добавленное поле либо уронит
//      сборку (громко), либо не защитится в админке, и робот ТИХО затрёт
//      правку заказчика.
//   2. ПАЛИТРА СЛУЖЕБНЫХ СТРАНИЦ — каждое значение из
//      `public/admin/tools/tools.css` сверяется с `src/styles/tokens.css`
//      ПО ЗНАЧЕНИЮ.
//
// ПОДЛОГ ОБЯЗАН РАЗВОДИТЬ ОДНУ КОПИЮ. Подмена, меняющая значение во всех
// местах сразу, расхождения не создаёт и не ловится (CLAUDE.md). Поэтому
// разборы ниже принимают ТЕКСТ, а не путь: настоящий текст даёт настоящий
// ответ, а испорченная копия одного файла — красный.
import { readFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MANUAL_FIELDS } from './anime-lib.mjs';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const КОРЕНЬ = join(ЗДЕСЬ, '..');

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

const читать = (...путь) => readFile(join(КОРЕНЬ, ...путь), 'utf8');

console.log('КОПИИ ВНЕ СБОРКИ: список полей и палитра служебных страниц.');
console.log();

// ── 1. Список полей «правлено руками» ─────────────────────────────────────
console.log('── список полей «правлено руками» ──');

/**
 * Список из админки — её же строкой, а не пересказом.
 *
 * Пересказ разошёлся бы с админкой ровно так же, как разошлись бы копии:
 * проверка отвечала бы про список, который написали ЗДЕСЬ.
 */
function списокАдминки(текст) {
	const строка = текст.match(/^\s*const MANUAL_ANIME_FIELDS = .*$/m);
	if (!строка) return null;
	return new Function(`${строка[0]} return MANUAL_ANIME_FIELDS;`)();
}

/**
 * Список из схемы сборки. Достаётся разбором, потому что `content.config.ts` —
 * TypeScript: узел его импортировать не умеет, а переписать значение рядом
 * значило бы завести ЧЕТВЁРТУЮ копию — ту самую, которая всегда права.
 */
function списокСхемы(текст) {
	const кусок = текст.match(/manual:\s*z\.preprocess\([^)]*?,\s*z\.array\(z\.enum\(\[([^\]]*)\]\)\)/s);
	if (!кусок) return null;
	return [...кусок[1].matchAll(/'([^']+)'|"([^"]+)"/g)].map((м) => м[1] ?? м[2]);
}

const текстАдминки = await читать('public', 'admin', 'index.html');
const текстСхемы = await читать('src', 'content.config.ts');

const изАдминки = списокАдминки(текстАдминки);
const изСхемы = списокСхемы(текстСхемы);

скажи(Array.isArray(изАдминки), 'список в админке нашёлся');
скажи(Array.isArray(изСхемы), 'список в схеме сборки нашёлся');

/**
 * Сравнение СПИСКАМИ, а не длиной и не множеством.
 *
 * Порядок тут ничего не решает (все трое только проверяют вхождение), но
 * сравнивать по одному числу нельзя: «сверка списком слепа к перестановке»
 * — записанный урок, и тут он оборачивается тем, что подменённое поле
 * при равной длине прошло бы молча. Поэтому сортируем и сверяем поимённо.
 */
const ключ = (список) => [...(список ?? [])].sort().join(', ');

const домашний = ключ(MANUAL_FIELDS);
скажи(ключ(изАдминки) === домашний, `админка: [${ключ(изАдминки)}] против anime-lib [${домашний}]`);
скажи(ключ(изСхемы) === домашний, `схема сборки: [${ключ(изСхемы)}] против anime-lib [${домашний}]`);

// ЭТО НЕ УКРАШЕНИЕ: пустой список сошёлся бы сам с собой три раза подряд
// и проверка сказала бы «всё хорошо» про защиту, которой нет.
скажи(MANUAL_FIELDS.length >= 3, `полей в списке ${MANUAL_FIELDS.length} — список не пустой`);

// ── 2. Палитра служебных страниц ──────────────────────────────────────────
console.log();
console.log('── палитра служебных страниц ──');

/**
 * Объявления `--имя: значение` из ПЕРВОГО блока `:root { … }`.
 *
 * Первый блок берётся нарочно: в `tokens.css` дальше идут медиазапросы,
 * которые переопределяют часть имён по ширине экрана, — сравнивать служебную
 * страницу с ними не с чем, у неё брейкпоинтов палитры нет вовсе. Цвета
 * в медиазапросах не меняются ни разу, там только кегли и поля.
 */
function токеныКорня(текст) {
	const блок = текст.match(/:root\s*\{([\s\S]*?)\n\}/);
	if (!блок) return null;
	const найдено = new Map();
	// Комментарии выбрасываем ДО разбора: внутри них лежат и `--имя`, и `#hex`
	// (в `tokens.css` их там десятки), и без уборки они уехали бы в токены.
	const тело = блок[1].replace(/\/\*[\s\S]*?\*\//g, '');
	// Имя берём как `--` и всё до двоеточия, а НЕ как `[a-z0-9-]+`: узкий набор
	// знаков — это признак, не знающий всех законных форм, и молчит он в сторону
	// «расхождений нет». Поймано собственным подлогом: имя `--выдуманное` мимо
	// такого набора проезжало молча.
	for (const м of тело.matchAll(/(--[^\s:{}]+)\s*:\s*([^;]+);/g)) {
		найдено.set(м[1], м[2].trim().replace(/\s+/g, ' ').toLowerCase());
	}
	return найдено;
}

/** Расхождения: каждое имя служебной страницы — против сайта. */
function расхожденияПалитры(текстСайта, текстСлужебной) {
	const сайт = токеныКорня(текстСайта);
	const служебная = токеныКорня(текстСлужебной);
	if (!сайт || !служебная) return null;
	const беды = [];
	for (const [имя, значение] of служебная) {
		// ИМЕНИ НЕТ НА САЙТЕ ВОВСЕ — это тоже расхождение, а не «ну и ладно»:
		// служебная страница красилась бы значением, которого в палитре нет,
		// и найти это можно было бы только глазами.
		if (!сайт.has(имя)) беды.push({ имя, тут: значение, там: '(такого имени на сайте нет)' });
		else if (сайт.get(имя) !== значение) беды.push({ имя, тут: значение, там: сайт.get(имя) });
	}
	return { беды, сколько: служебная.size };
}

const текстТокенов = await читать('src', 'styles', 'tokens.css');
const текстСлужебной = await читать('public', 'admin', 'tools', 'tools.css');

const палитра = расхожденияПалитры(текстТокенов, текстСлужебной);
скажи(Boolean(палитра), 'оба блока `:root` разобрались');

if (палитра) {
	// Число печатается замером, а не словами: копия растёт вместе со страницами
	// роботов, и вписанное сюда «девять» разъехалось бы с первой же правкой.
	скажи(палитра.сколько > 0, `значений в копии: ${палитра.сколько}`);
	скажи(палитра.беды.length === 0, `расхождений: ${палитра.беды.length}`);
	for (const б of палитра.беды) console.log(`          ${б.имя}: служебная ${б.тут}, сайт ${б.там}`);
}

// ── ПОДЛОГИ ───────────────────────────────────────────────────────────────
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── ПОДЛОГИ ──');

	// Каждый подлог сперва доказывает, что он ЧТО-ТО заменил: подлог, ничего
	// не заменивший, обвиняет в своей ошибке проверку (CLAUDE.md).
	const подменить = (текст, было, стало, зачем) => {
		const новый = текст.replace(было, стало);
		скажи(новый !== текст, `подлог «${зачем}» и правда что-то заменил`);
		return новый;
	};

	// 1. Заказчик добавил четвёртое поле в АДМИНКЕ и забыл про остальных двоих.
	const админкаЧетвёртая = подменить(
		текстАдминки,
		/const MANUAL_ANIME_FIELDS = \[[^\]]*\]/,
		"const MANUAL_ANIME_FIELDS = ['titleRu', 'synopsis', 'poster', 'titleOriginal']",
		'четвёртое поле только в админке',
	);
	скажи(ключ(списокАдминки(админкаЧетвёртая)) !== домашний, 'разъехавшаяся админка поймана');

	// 2. Обратный случай: поле убрали из СХЕМЫ. Сборка при этом не упадёт,
	//    пока такого значения нет в живых карточках, — то есть промолчит.
	const схемаБезПоля = подменить(
		текстСхемы,
		/z\.enum\(\['titleRu', 'synopsis', 'poster'\]\)/,
		"z.enum(['titleRu', 'synopsis'])",
		'поле выпало из схемы',
	);
	скажи(ключ(списокСхемы(схемаБезПоля)) !== домашний, 'разъехавшаяся схема поймана');

	// 3. Палитра: ОДНО значение служебной страницы уехало. Ровно так это
	//    и случилось в жизни — поправили на сайте, не поправили здесь.
	const служебнаяИначе = подменить(
		текстСлужебной,
		/--muted: #[0-9a-f]{6};/i,
		'--muted: #6b6660;',
		'прежнее неверное значение --muted',
	);
	const сПодлогом = расхожденияПалитры(текстТокенов, служебнаяИначе);
	скажи(
		сПодлогом.беды.some((б) => б.имя === '--muted'),
		`подложенный --muted найден (расхождений ${сПодлогом.беды.length})`,
	);

	// 4. Имя, которого на сайте нет вовсе, — тоже расхождение, а не «ну и ладно».
	const служебнаяЛишняя = подменить(
		текстСлужебной,
		'--paper: #f8f6f0;',
		'--paper: #f8f6f0;\n\t--выдуманное: #ff0000;',
		'имя, которого нет на сайте',
	);
	скажи(
		расхожденияПалитры(текстТокенов, служебнаяЛишняя).беды.some((б) => б.имя === '--выдуманное'),
		'имя, которого нет в tokens.css, названо расхождением',
	);

	// 5. И половина, без которой «поймал» ничего не значит: на ЗДОРОВЫХ файлах
	//    проверка обязана молчать. Иначе она красная всегда и её выключат.
	скажи(расхожденияПалитры(текстТокенов, текстСлужебной).беды.length === 0, 'на здоровых файлах проверка молчит');
}

console.log();
if (плохо) {
	console.log(`ПРОВАЛОВ: ${плохо}`);
	process.exit(1);
}
console.log('Три списка полей совпадают, палитра служебных страниц совпадает с сайтом.');
