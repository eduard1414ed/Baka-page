#!/usr/bin/env node
// Проверки правила «нужна ли эта картинка собранным страницам»
// (src/lib/imageVariants.mjs, isWantedByPages).
//
// НА ЭТОМ ПРАВИЛЕ ДЕРЖИТСЯ ВСЯ ЭКОНОМИЯ СБОРКИ: оно решает, каким из 1233
// загрузок делать копии, а каким только удалить оригинал. Ошибётся в одну
// сторону — вернутся 92 секунды на каждую сборку и две тысячи лишних файлов;
// ошибётся в другую — на живой странице дыра вместо картинки.
//
// ФАЙЛОМ, А НЕ ОДНОСТРОЧНИКОМ `node -e`: в проекте однострочник уже дважды
// врал «ничего не найдено» из-за двойного экранирования обратного слэша.
//
// МОЛЧАНИЕ ПРОВЕРЯЕТСЯ НАРАВНЕ С ОТВЕТОМ. Правило, отвечающее «нужна» на всё
// подряд, не экономит ничего и выглядит при этом безупречно, потому что сайт
// цел. Поэтому половина случаев ниже — те, где ответом обязано быть «нет».
//
//   node scripts/image-variants.test.mjs
//
// Подлоги написаны ТАК, КАК ПИШЕТ САМА СБОРКА: пути берутся из настоящих имён
// проекта, а ожидаемые ссылки считает тот же getImageVariantSrcs, которым их
// пишет страница. Подлог, повторяющий формулировку правила, проверяет
// не правило, а собственную аккуратность.

import { isWantedByPages, collectUploadRefs, getImageVariantSrcs, getOgVariantSrc, variantBase, isOptimizableImage } from '../src/lib/imageVariants.mjs';

const UP = '/images/uploads';

/** Разметка страницы так, как её пишет сборка: srcset из двух размеров. */
const pageWith = (src) => `<img srcset="${getImageVariantSrcs(src).map((v) => `${v.src} ${v.width}w`).join(', ')}" alt="">`;

/**
 * Правило спрашивают ЧЕРЕЗ сборщик набора, а не в обход него: в сборке между
 * разметкой и решением стоит именно он, и подсунь проверка правилу готовый
 * набор — она проверяла бы половину пути. Ошибка в границах пути (например,
 * если бы ширина `640w` из srcset прилипала к адресу) прошла бы незамеченной.
 */
const asks = (html) => collectUploadRefs(html, `${UP}/`);

const cases = [
	// ——— Обязано ответить «нужна» ———
	{
		name: 'обычная картинка поста, на которую ссылается страница',
		src: `${UP}/tg-1531.jpg`,
		html: pageWith(`${UP}/tg-1531.jpg`),
		want: true,
	},
	{
		name: 'имя с пробелами и точками — страница пишет его %-кодировкой',
		src: `${UP}/photo_2026-08-05 17.48.25.jpeg`,
		html: pageWith(`${UP}/photo_2026-08-05 17.48.25.jpeg`),
		want: true,
	},
	{
		name: 'обложка, видная ТОЛЬКО в превью ссылки: webp-копий никто не просит',
		src: `${UP}/1.jpeg`,
		html: `<meta property="og:image" content="${getOgVariantSrc(`${UP}/1.jpeg`)}">`,
		want: true,
	},
	{
		name: 'русское имя файла',
		src: `${UP}/Пони.png`,
		html: pageWith(`${UP}/Пони.png`),
		want: true,
	},

	// ——— Обязано ответить «не нужна» ———
	{
		name: 'картинка черновика: страниц у него нет, ссылок на неё тоже',
		src: `${UP}/tg-999999.jpg`,
		html: pageWith(`${UP}/tg-1531.jpg`),
		want: false,
	},
	{
		name: 'пустая сборка — не ссылается никто',
		src: `${UP}/tg-1531.jpg`,
		html: '',
		want: false,
	},
	{
		// Ровно те грабли, на которых обжигались копии для превью: «5-og.jpg»
		// находился ВНУТРИ «photo_2026-08-05 17.48.25-og.jpg». Если правило
		// начнёт искать куском имени, этот случай станет «нужна» — и вернёт
		// в сборку тысячу картинок, не сломав ничего видимого.
		name: 'ЛОВУШКА: короткое имя вложено в длинное, а ссылки на него нет',
		src: `${UP}/5.png`,
		html: pageWith(`${UP}/photo_2026-08-05 17.48.25.jpeg`) + pageWith(`${UP}/тест-5.png`),
		want: false,
	},
	{
		// Расширение входит в имя копий с 10 августа: `4.png` и `4.jpeg` —
		// разные картинки. Спутает их правило — на странице встанет чужая.
		name: 'ЛОВУШКА: тот же ствол имени, другое расширение',
		src: `${UP}/4.jpeg`,
		html: pageWith(`${UP}/4.png`),
		want: false,
	},
	{
		// Оригинал в разметке встречается у постов, привезённых из телеграма:
		// в теле стоит ::image{src="/images/uploads/tg-1.jpg"}, и в html
		// эта строка попасть НЕ должна — страница пишет только копии. Но если
		// когда-нибудь попадёт, правило не должно принимать её за ссылку
		// на копии: оригинал на сайт не уезжает вовсе.
		name: 'ссылка на ОРИГИНАЛ, а не на копии, — это не заказ копий',
		src: `${UP}/tg-2.jpg`,
		html: `<img src="${UP}/tg-2.jpg">`,
		want: false,
	},
	{
		// Граница пути. В srcset за адресом идёт пробел и ширина; захвати
		// сборщик набора лишнее — адрес не совпал бы ни с чем, и сборка тихо
		// перестала бы делать копии ВООБЩЕ ВСЕМ. Сайт при этом собрался бы.
		name: 'ГРАНИЦА: ширина из srcset не должна прилипать к адресу',
		src: `${UP}/tg-777.jpg`,
		html: `<img srcset="${UP}/tg-777-jpg-640w.webp 640w, ${UP}/tg-777-jpg-1280w.webp 1280w">`,
		want: true,
	},
	{
		// То же самое с другой стороны: адрес внутри url(…) в стилях.
		name: 'ГРАНИЦА: закрывающая скобка url(…) не должна прилипать',
		src: `${UP}/fon.png`,
		html: `<style>.x{background-image:url(${UP}/fon-png-1280w.webp)}</style>`,
		want: true,
	},
];

let bad = 0;
for (const c of cases) {
	const got = isWantedByPages(c.src, asks(c.html));
	const ok = got === c.want;
	if (!ok) bad += 1;
	console.log(`${ok ? '  ✓' : '  ✗'} ${c.name}${ok ? '' : ` — ждали ${c.want}, получили ${got}`}`);
}

// ——— Подлог самому правилу: умеет ли эта проверка вообще падать ———
//
// Проверка, которую нечем уронить, добавляет строчку «ок» и ноль знания.
// Подменяем правило заведомо сломанными и требуем, чтобы список выше покраснел.
const traps = [
	{ name: 'правило отвечает «нужна» всем подряд', rule: () => true },
	{ name: 'правило отвечает «не нужна» всем подряд', rule: () => false },
	{ name: 'правило ищет куском имени, а не полным путём', rule: (src, html) => html.includes(variantBase(decodeURIComponent(src)).split('/').pop()) },
	{
		// Сборщик набора режет путь по пробелу и скобке. Заставим его резать
		// только по кавычке — и адрес из srcset приедет вместе с шириной.
		name: 'сборщик набора прихватывает лишнее за адресом',
		rule: (src, html) => isWantedByPages(src, new Set([...html.matchAll(/\/images\/uploads\/[^"']+/g)].map((m) => m[0]))),
	},
	{
		// Забыли про превью: обложка, видная только в разворачивалке ссылки,
		// стала бы «никому не нужной» и пропала из телеграма.
		name: 'правило забыло про jpeg-копию для превью',
		rule: (src, html) => getImageVariantSrcs(src).some((v) => asks(html).has(v.src)),
	},
];

let blind = 0;
for (const trap of traps) {
	const caught = cases.some((c) => trap.rule(c.src, c.html) !== c.want);
	if (!caught) blind += 1;
	console.log(`${caught ? '  ✓' : '  ✗'} подлог пойман: ${trap.name}`);
}

console.log(
	bad === 0 && blind === 0
		? `\nВсе ${cases.length} случаев сошлись, все ${traps.length} подлогов пойманы.`
		: `\nПРОВАЛ: неверных ответов ${bad}, непойманных подлогов ${blind}.`,
);

// Связь с остальными именами явная: их зовёт та же сборка.
void isOptimizableImage;

process.exit(bad === 0 && blind === 0 ? 0 : 1);
