//
//   node scripts/episodes-notify.test.mjs
//   node scripts/episodes-notify.test.mjs --подлог
//
// ЧТО СЛУЧИЛОСЬ 28 АВГУСТА 2026. В 06:01 UTC пришло зелёное письмо «🖼 вырезаны
// персонажи с новых обложек», а под ним — подробный рассказ «Расшифрован
// ep-153, стоимость $0.113». Выглядело это так, будто робот второй раз оплатил
// расшифровку выпуска, сделанного НАКАНУНЕ.
//
// Расшифровки в тот день не прибавилось ни одной: последний коммит
// «Расшифровать новые выпуски» — от 27 августа 06:00. Платный шаг отработал
// правильно и ep-153 пропустил. Соврал ХВОСТ ПИСЬМА: `notify.md` пишется,
// только когда есть о чём сказать, лежит в папке репозитория и закрыт
// .gitignore — то есть переживает заход, и вчерашний файл уехал в сегодняшнее
// письмо. Ровно тот урок, что уже был применён к роботу телеграма
// (`rm -f notify-tg.md`) и не доехал до робота выпусков.
//
// ЧТО ПРОВЕРЯЕТСЯ. Из hetzner/run-episodes.sh вынимаются ДВА НАСТОЯЩИХ блока —
// «чистка замечаний» и «что рассказать» — и гоняются в песочнице подряд, между
// ними разыгрывается заход робота: пишет он сегодня замечания или нет.
// Отправка телеграма подменена заглушкой.
//
// ПОЧЕМУ ЭТО НЕ «ВЕЧНОЗЕЛЁНАЯ» ПРОВЕРКА. Ключ `--подлог` убирает из блока
// РОВНО ОДНУ строку — ту самую `rm -f`, — как это и случится в жизни, когда её
// сочтут лишней. Проверка обязана покраснеть вчерашним рассказом в сегодняшнем
// письме. Снятие блока целиком тут не годится: без блока не осталось бы
// и второй его половины, экранирования.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, readFileSync, writeFileSync, existsSync, chmodSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const SCRIPT = join(ROOT, 'hetzner/run-episodes.sh');

/** Текст блока — из самого робота, а не переписанный рядом. */
function читатьБлок(текст, имя) {
	const от = текст.indexOf(`# ─── начало блока «${имя}»`);
	const до = текст.indexOf(`# ─── конец блока «${имя}»`);
	if (от < 0 || до < 0) return null;
	return текст.slice(текст.indexOf('\n', от), до);
}

/**
 * Заход робота целиком: вчерашние замечания на диске, потом чистка,
 * потом работа сегодняшнего дня, потом письмо.
 *
 * @param {object} что
 * @param {string} что.вчера        — что лежало в notify.md со вчера.
 * @param {string} что.вчераОбложки — что лежало в notify-covers.md со вчера.
 * @param {string} что.сегодня      — что напишет расшифровка сегодня ('' — ничего).
 * @param {string} что.новость      — NEWS, с которым робот дошёл до письма.
 * @returns {{письмо: string}}
 */
function прогон({ вчера = '', вчераОбложки = '', сегодня = '', новость = '🖼 вырезаны персонажи с новых обложек\n' }, блокЧистки, блокПисьма) {
	const box = mkdtempSync(join(tmpdir(), 'baka-ep-notify-'));
	try {
		const стук = join(box, 'письмо.txt');
		const заглушка = join(box, 'notify.sh');
		writeFileSync(заглушка, `#!/bin/bash\nprintf '%s' "$1" > ${стук}\n`, 'utf8');
		chmodSync(заглушка, 0o755);

		// Вчерашний заход оставил файлы лежать — их никто не убирал.
		if (вчера) writeFileSync(join(box, 'notify.md'), вчера, 'utf8');
		if (вчераОбложки) writeFileSync(join(box, 'notify-covers.md'), вчераОбложки, 'utf8');

		const сценарий = [
			'set -u',
			`NOTIFY=${заглушка}`,
			`REPO=${box}`,
			'STAMP="2026-08-28 06:01 UTC"',
			'LOG=/root/baka-logs/episodes.log',
			'ERRORS=""',
			`NEWS=${JSON.stringify(новость)}`,
			'cd "$REPO" || exit 1',
			блокЧистки,
			// Сегодняшний заход: расшифровка пишет замечания, только если есть о чём.
			сегодня ? `printf '%s' ${JSON.stringify(сегодня)} > notify.md` : ': расшифровок не прибавилось',
			блокПисьма,
			// Письмо в жизни собирается ниже по скрипту; здесь — тот же printf.
			`"$NOTIFY" "$(printf '🟢 <b>Робот выпусков: есть новое</b>\\n%s\\n\\n%b\\n%s' "$STAMP" "$NEWS" "$DETAILS")"`,
		].join('\n');

		execFileSync('bash', ['-c', сценарий], { cwd: box, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
		return { письмо: existsSync(стук) ? readFileSync(стук, 'utf8') : '' };
	} finally {
		rmSync(box, { recursive: true, force: true });
	}
}

// ─── Прогон ────────────────────────────────────────────────────────────────

const подлог = process.argv.includes('--подлог') || process.argv.includes('--selftest');
const беды = [];
const ок = (с) => console.log(`  ✓ ${с}`);
const плохо = (с) => { беды.push(с); console.log(`  ✗ ${с}`); };

const текст = readFileSync(SCRIPT, 'utf8');
let блокЧистки = читатьБлок(текст, 'чистка замечаний');
const блокПисьма = читатьБлок(текст, 'что рассказать');

const ВЧЕРА = '### ✅ ep-153 — расшифрован, ждёт проверки\nстоимость: $0.113, 514 кредитов\n';
const СЕГОДНЯ = '### ✅ ep-154 — расшифрован, ждёт проверки\n';

if (!блокЧистки || !блокПисьма) {
	плохо('в hetzner/run-episodes.sh нет размеченных блоков — проверять нечего');
} else if (подлог) {
	console.log('=== ПОДЛОГ: из блока убрана ОДНА строка — та, что чистит замечания ===\n');
	const было = блокЧистки;
	блокЧистки = блокЧистки.split('\n').filter((с) => с.trim() !== 'rm -f notify.md notify-covers.md').join('\n');
	if (блокЧистки === было) {
		плохо('строку `rm -f notify.md notify-covers.md` в блоке не нашли — подлог ничего не заменил, и его «поймал» ничего не значит');
	} else {
		const п = прогон({ вчера: ВЧЕРА, сегодня: '' }, блокЧистки, блокПисьма);
		if (п.письмо.includes('ep-153')) ок('вчерашний рассказ уехал в сегодняшнее письмо — ровно письмо 28 августа 06:01');
		else плохо('вчерашние замечания НЕ протекли даже без чистки — песочница не воспроизводит поломку');
	}
} else {
	console.log('=== ПИСЬМО РОБОТА ВЫПУСКОВ ГОВОРИТ ПРО СЕГОДНЯ ===\n');

	// 1. Главное: день без расшифровок молчит о расшифровках.
	const тишина = прогон({ вчера: ВЧЕРА, сегодня: '' }, блокЧистки, блокПисьма);
	if (!тишина.письмо.includes('ep-153')) ок('расшифровок сегодня нет — вчерашний ep-153 в письмо не попал');
	else плохо('в письмо уехал вчерашний ep-153 — вернулось письмо 28 августа');
	if (тишина.письмо.includes('вырезаны персонажи')) ок('сегодняшняя новость про обложки при этом на месте');
	else плохо('письмо потеряло сегодняшнюю новость');

	// 2. Настоящая расшифровка доезжает — чистка не съела полезное.
	const работа = прогон({ вчера: ВЧЕРА, сегодня: СЕГОДНЯ }, блокЧистки, блокПисьма);
	if (работа.письмо.includes('ep-154')) ок('сегодняшняя расшифровка рассказана');
	else плохо('сегодняшняя расшифровка пропала — чистка съела нужное');
	if (!работа.письмо.includes('ep-153')) ок('и вчерашняя рядом с ней не приписалась');
	else плохо('вчерашний рассказ приклеился к сегодняшнему');

	// 3. То же для замечаний вырезания персонажей.
	const обложки = прогон({ вчераОбложки: 'вчера вырезано 3 персонажа\n', сегодня: '' }, блокЧистки, блокПисьма);
	if (!обложки.письмо.includes('вчера вырезано')) ок('вчерашние замечания об обложках тоже не переживают заход');
	else плохо('notify-covers.md пережил заход — вчерашние обложки в сегодняшнем письме');

	// 4. Знаки разметки в чужом заголовке не роняют письмо.
	const знаки = прогон({ сегодня: 'ep-155 — «Кровь&слёзы <Rewrite>» расшифрован\n' }, блокЧистки, блокПисьма);
	if (знаки.письмо.includes('&amp;') && знаки.письмо.includes('&lt;Rewrite&gt;')) ок('знаки & < > из заголовка выпуска экранированы — телеграм не откажет в приёме письма');
	else плохо(`знаки & < > уехали в письмо как есть — телеграм ответит отказом и письма не будет вовсе: «${знаки.письмо.slice(-90)}»`);
}

console.log('');
if (беды.length) {
	console.log(`ПРОВЕРКА НЕ ПРОШЛА: ${беды.length}.`);
	process.exit(1);
}
console.log('Всё сошлось.');
