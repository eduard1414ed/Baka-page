// ПОДПИСЬ АВТОРА В ПОЛЕ МАРКИРОВКИ — ПРОГОН НАСТОЯЩЕГО ПРАВИЛА ПО ЖИВОМУ АРХИВУ.
//
//   node scripts/author-label.test.mjs
//   node scripts/author-label.test.mjs --selftest
//
// ЗАЧЕМ. Поле `adLabel` носит две разные вещи: маркировку рекламы и подпись
// автора. Спутать их дорого в обе стороны — либо реклама превратится
// в человека по имени «Реклама. ООО «Яндекс Музыка»…», либо текст подписчика
// окажется подписан ведущим.
//
// А ГЛАВНОЕ — ЗАПЯТАЯ. У «Авторы текста: А, Б, В» она разделяет имена,
// у «Автор текста: Кристина, «крисгринпис на связи»» принадлежит имени.
// Разница видна только на живом архиве: в выдуманных примерах такой подписи
// никто бы не написал.
//
// ПОДЛОГ убирает различие между единственным и множественным — ровно та
// правка, которую однажды сделают «для простоты».
//
// ЧТО РОНЯЕТ СБОРКУ, А ЧТО ТОЛЬКО ГОВОРИТ ВСЛУХ. Роняют её только те беды,
// которые может завести КОД: «сказано „Автор“, а разобралось двое», «реклама
// принята за подпись». Беды, которые может завести ЧЕЛОВЕК в админке —
// написал «Автор перевода:», поставил лишнюю запятую, — печатаются
// предупреждением и сборку не трогают. Заслон, который краснеет на обычной
// работе, однажды снимут вместе с пользой; а выкладка, вставшая из-за
// опечатки в подписи, — это цена, которой правка не стоит.

import { readdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';
import yaml from 'js-yaml';
import { авторыИзМаркировки } from '../src/lib/author.mjs';

const selftest = process.argv.includes('--selftest');
const ПОСТЫ = fileURLToPath(new URL('../src/content/posts/', import.meta.url));

/** Подлог: делить запятой всегда, не глядя на слово «Автор» или «Авторы». */
const подложенное = (adLabel) => {
	const m = String(adLabel ?? '')
		.trim()
		.match(/^Автор(ы)?\s+текста\s*:\s*(.+)$/i);
	if (!m) return [];
	return m[2]
		.replace(/[\s.;]+$/, '')
		.split(',')
		.map((и) => и.trim())
		.filter(Boolean);
};

const разобрать = selftest ? подложенное : авторыИзМаркировки;

const метки = [];
for (const файл of (await readdir(ПОСТЫ)).filter((f) => f.endsWith('.md'))) {
	const шапка = (await readFile(join(ПОСТЫ, файл), 'utf8')).match(/^---\n([\s\S]*?)\n---/);
	if (!шапка) continue;
	let data;
	try {
		data = yaml.load(шапка[1]) ?? {};
	} catch {
		continue;
	}
	const метка = String(data.adLabel ?? '').trim();
	if (метка) метки.push({ файл: файл.replace(/\.md$/, ''), метка });
}

if (метки.length === 0) {
	console.error('✗ В архиве не осталось ни одной непустой маркировки — проверять нечего.');
	process.exit(1);
}

const беды = [];
const замечания = [];
let подписей = 0;
let реклам = 0;

for (const { файл, метка } of метки) {
	const имена = разобрать(метка);

	if (/^Автор/i.test(метка)) {
		подписей++;
		if (имена.length === 0) замечания.push(`${файл}: «${метка}» начинается со слова «Автор», но подписью не считается`);
		// Имя из одного знака или из пустоты — признак того, что строку
		// порезали не по тому месту. Это тоже бывает от руки, поэтому
		// не приговор, а замечание.
		for (const имя of имена) {
			if (имя.length < 2) замечания.push(`${файл}: из подписи вышло имя «${имя}»`);
		}
		// ЕДИНСТВЕННОЕ ЧИСЛО — ОДИН АВТОР. Это и есть то, что ломает подлог.
		if (/^Автор\s+текста/i.test(метка) && имена.length !== 1) {
			беды.push(`${файл}: «${метка}» — сказано «Автор», а разобралось ${имена.length}`);
		}
	} else {
		реклам++;
		if (имена.length > 0) беды.push(`${файл}: рекламная маркировка «${метка.slice(0, 40)}…» принята за подпись автора`);
	}
}

if (selftest) {
	if (беды.length === 0) {
		console.error('✗ ПОДЛОГ НЕ ПОЙМАН: правило перестало отличать «Автор» от «Авторы», а проверка промолчала.');
		process.exit(1);
	}
	console.log(`✓ Подлог пойман: ${беды[0]}`);
	console.log('  Проверка умеет краснеть.');
	process.exit(0);
}

if (беды.length > 0) {
	console.error(`✗ Разбор подписей автора сломан в ${беды.length} случаях:`);
	for (const б of беды) console.error('   ' + б);
	process.exit(1);
}

for (const з of замечания) console.log(`⚠ Подпись автора: ${з}`);

console.log(
	`ок      Подписи автора: разобрано ${подписей}, рекламных маркировок не тронуто ${реклам}` +
		(замечания.length > 0 ? `, непонятых подписей ${замечания.length}` : '') + '.',
);
