// У КАЖДОГО ПОХОДА В ЧУЖОЙ СЕРВИС ЕСТЬ СРОК.
//
//   node scripts/fetch-timeout.test.mjs             — спросить
//   node scripts/fetch-timeout.test.mjs --selftest  — плюс подлоги
//
// ЗАЧЕМ. Без срока Node ждёт молчащее соединение минутами, а робот в это время
// держит очередь: у всех воркфлоу `cancel-in-progress: false`, поэтому
// следующий заход по расписанию встаёт и ждёт. Один зависший чужой сервер
// останавливал робота на сутки, и выглядело это как «робот перестал ходить»
// (ревизия задачи 15, находка 5). Срок стоял ровно у двух разовых скриптов
// из четырнадцати мест, и числа у них были РАЗНЫЕ — 25 и 20 секунд.
//
// СПРАШИВАЕТСЯ ТРИ РАЗНЫХ ВОПРОСА:
//   1. НЕТ ЛИ ПОХОДА БЕЗ СРОКА — поиском по исходникам;
//   2. НЕТ ЛИ ВТОРОГО ЧИСЛА — своего `AbortSignal.timeout(…)` мимо общего;
//   3. ПРАВДА ЛИ СРОК СРАБАТЫВАЕТ и правда ли повтор считает его сетевым —
//      прогоном на подделке сервера, который молчит.
// Ответ «да» на первый ничего не говорит про третий: строка может стоять,
// а работать не так.
import { readdir, readFile, writeFile, unlink } from 'node:fs/promises';
import { join, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ТАЙМАУТ, сроком, похоженаСбойСети, сПовторами } from './retry.mjs';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const КОРЕНЬ = join(ЗДЕСЬ, '..');

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

/** Все исходники проекта, кроме чужого кода и самих проверок. */
async function исходники(папка, собрано = []) {
	for (const запись of await readdir(папка, { withFileTypes: true })) {
		if (запись.name === 'node_modules' || запись.name.startsWith('.')) continue;
		const путь = join(папка, запись.name);
		if (запись.isDirectory()) await исходники(путь, собрано);
		else if (['.mjs', '.js', '.ts'].includes(extname(запись.name))) собрано.push(путь);
	}
	return собрано;
}

/**
 * Походы, у которых нет срока.
 *
 * Ищем `fetch(…)` с настройками и без `сроком`. Голый `fetch(адрес)` без
 * второго довода — тоже без срока, и он опаснее: там даже места для него нет.
 */
async function походыБезСрока() {
	const найдено = [];
	for (const папка of ['scripts', 'src']) {
		for (const путь of await исходники(join(КОРЕНЬ, папка))) {
			const имя = путь.slice(КОРЕНЬ.length + 1).replaceAll('\\', '/');
			// Проверки не спрашиваем: они нарочно подделывают `fetch`, и срок
			// в подделке ничего не значит.
			if (имя.endsWith('.test.mjs')) continue;
			const текст = await readFile(путь, 'utf8');
			текст.split('\n').forEach((строка, номер) => {
				// `await fetch(` — именно поход. Определения метода с именем
				// `fetch(list) {` сюда не попадают: перед ними нет `await`.
				if (!/\bawait fetch\(/.test(строка)) return;
				if (/сроком\(/.test(строка)) return;
				найдено.push({ файл: имя, строка: номер + 1, текст: строка.trim().slice(0, 90) });
			});
		}
	}
	return найдено;
}

/** Свои числа сроков — мимо общего. */
async function свойСрок() {
	const найдено = [];
	for (const папка of ['scripts', 'src']) {
		for (const путь of await исходники(join(КОРЕНЬ, папка))) {
			const имя = путь.slice(КОРЕНЬ.length + 1).replaceAll('\\', '/');
			if (имя === 'scripts/retry.mjs' || имя.endsWith('.test.mjs')) continue;
			const текст = await readFile(путь, 'utf8');
			if (/AbortSignal\.timeout\(/.test(текст)) найдено.push(имя);
		}
	}
	return найдено;
}

console.log('СРОК ПОХОДА: одно число на проект, и оно правда обрывает.');
console.log(`Общий срок: ${ТАЙМАУТ / 1000} с.`);
console.log();

// ── 1. Все походы со сроком ───────────────────────────────────────────────
const без = await походыБезСрока();
скажи(без.length === 0, `походов без срока: ${без.length}`);
for (const м of без) console.log(`          ${м.файл}:${м.строка} — ${м.текст}`);

// ── 2. Второго числа нет ──────────────────────────────────────────────────
const свои = await свойСрок();
скажи(свои.length === 0, `мест со своим числом срока: ${свои.length}`);
for (const ф of свои) console.log(`          ${ф}`);

// ── 3. Срок правда обрывает, и повтор его переживает ──────────────────────
console.log();
console.log('── срок в работе ──');
/**
 * Поход к серверу, который не ответит никогда.
 *
 * Сигнал заводится ВНУТРИ, а не снаружи: заведённый заранее успевает
 * сработать до того, как на него подпишутся, и тогда обработчик не позовут
 * вовсе — проверка виснет вместо того, чтобы ответить. Поймано ею же:
 * первый заход кончился «unsettled top-level await».
 */
const молчащийСервер = (мс) =>
	new Promise((_, отказ) => {
		const сигнал = AbortSignal.timeout(мс);
		// ТАЙМЕР ВНУТРИ `AbortSignal.timeout` НЕ ДЕРЖИТ ЦИКЛ СОБЫТИЙ. В настоящем
		// походе цикл держит само сетевое соединение, а тут держать нечему:
		// Node видит, что ждать больше некого, и выходит с «unsettled top-level
		// await» ДО того, как срок сработает. Проверка при этом падает кодом 13 —
		// то есть врёт в безопасную сторону, но всё же врёт. Держим цикл сами.
		const держим = setTimeout(() => отказ(new Error('срок не сработал вовсе')), мс + 500);
		const кончить = (ошибка) => {
			clearTimeout(держим);
			отказ(ошибка);
		};
		if (сигнал.aborted) return кончить(сигнал.reason);
		сигнал.addEventListener('abort', () => кончить(сигнал.reason), { once: true });
	});

let оборвалось = null;
try {
	// Число маленькое нарочно: проверяется ПОРЯДОК событий, а не длина
	// ожидания. Настоящие тридцать секунд ждать незачем.
	await молчащийСервер(50);
} catch (ошибка) {
	оборвалось = ошибка;
}
скажи(оборвалось !== null, `молчащий сервер оборван по сроку: ${оборвалось?.name ?? '(не оборвался)'}`);
скажи(
	похоженаСбойСети(оборвалось),
	`оборванный по сроку поход считается СЕТЕВЫМ — значит повтор сходит заново (${оборвалось?.name})`,
);

// СВОЙ `signal` ВЫЗЫВАЮЩЕГО НЕ ПЕРЕБИВАЕМ: у него может быть своя причина
// оборвать поход, и молча её отменить было бы хуже, чем не поставить срок.
const мойСигнал = AbortSignal.timeout(1234);
скажи(сроком({ signal: мойСигнал }).signal === мойСигнал, 'свой signal вызывающего остаётся его');
скажи(сроком().signal instanceof AbortSignal, 'без своего signal подставляется общий срок');
скажи(сроком({ method: 'POST' }).method === 'POST', 'остальные настройки не теряются');

// И ПОВТОР ПРАВДА ХОДИТ ЗАНОВО после обрыва по сроку — это половина правила,
// без которой срок превратил бы моргнувшую сеть в падение робота.
let заходов = 0;
const итог = await сПовторами(
	async () => {
		заходов++;
		if (заходов < 2) throw Object.assign(new Error('The operation was aborted due to timeout'), { name: 'TimeoutError' });
		return 'дошло';
	},
	{ паузы: [1], назвать: 'подложенный поход', сказать: () => {} },
);
скажи(итог === 'дошло' && заходов === 2, `после обрыва по сроку повтор сходил заново: заходов ${заходов}`);

// ── ПОДЛОГИ ───────────────────────────────────────────────────────────────
// Подлог СОЗДАЁТ то, что ищут, а не меняет значение во всех копиях сразу.
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── ПОДЛОГИ ──');

	const безСрока = join(ЗДЕСЬ, 'ПОДЛОГ-без-срока.mjs');
	await writeFile(безСрока, "export async function х(u) {\n\tconst r = await fetch(u);\n\treturn r.text();\n}\n", 'utf8');
	try {
		const сПодлогом = await походыБезСрока();
		скажи(сПодлогом.some((м) => м.файл.endsWith('ПОДЛОГ-без-срока.mjs')), `поход без срока найден (всего ${сПодлогом.length})`);
	} finally {
		await unlink(безСрока);
	}

	const своёЧисло = join(ЗДЕСЬ, 'ПОДЛОГ-своё-число.mjs');
	await writeFile(своёЧисло, "export const о = { signal: AbortSignal.timeout(25000) };\n", 'utf8');
	try {
		const сПодлогом = await свойСрок();
		скажи(сПодлогом.some((ф) => ф.endsWith('ПОДЛОГ-своё-число.mjs')), `своё число срока найдено (всего ${сПодлогом.length})`);
	} finally {
		await unlink(своёЧисло);
	}

	// И ВТОРАЯ ПОЛОВИНА: на здоровом дереве обе проверки обязаны молчать.
	скажи((await походыБезСрока()).length === 0 && (await свойСрок()).length === 0, 'после уборки подлогов обе проверки снова молчат');
}

console.log();
if (плохо) {
	console.log(`ПРОВАЛОВ: ${плохо}`);
	process.exit(1);
}
console.log('У каждого похода есть срок, и число у него одно.');
