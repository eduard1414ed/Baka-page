// МИНИ-ПЛЕЕР ВРЕЗКИ ПОДКЛЮЧАЕТСЯ К ТОМУ ЖЕ ЗВУКУ, ЧТО И ПЛЕЕР ВЫПУСКА.
//
//   node scripts/post-play-wiring.test.mjs             — спросить
//   node scripts/post-play-wiring.test.mjs --selftest  — плюс подлоги
//
// ЧТО СПРАШИВАЕМ И ПОЧЕМУ ИМЕННО ЭТО.
//
// Своего кода воспроизведения у врезки нет вовсе: звук на странице один,
// `<audio>` один, и двух источников не бывает ПО УСТРОЙСТВУ, а не по
// договорённости. Держится это на двух вещах, и обе невидимы глазом:
//
//   1) блок объявляет о себе признаком `data-episode-card`, а панель
//      подключает ВСЕ такие блоки — раньше она искала один класс и один
//      элемент, `querySelector('.episode-player')`;
//   2) у мини-плеера нет ни перемотки ±15, ни выбора скорости, и прежний
//      заслон подключения («есть все семь контролов, иначе ухожу») отказался
//      бы подключать его МОЛЧА: блок нарисовался бы, кнопка бы не работала.
//
// Ни то ни другое нельзя увидеть, читая разметку: это делает скрипт. Поэтому
// берём НАСТОЯЩИЙ собранный скрипт панели из `dist/_astro/` и исполняем его
// в Node поверх подделки окна (scripts/player-window-stub.mjs, общей с
// проверкой порядка). Проверяется тот самый файл, который грузит браузер.
//
// ЧЕГО ЭТА ПРОВЕРКА НЕ ДЕЛАЕТ И НЕ МОЖЕТ. Она не смотрит, как это выглядит,
// не тащит ползунок пальцем и не слушает звук. Это остаётся заказчику
// и стоит в чек-листе приёмки.

import { readdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { makeWindow, makeCard } from './player-window-stub.mjs';

const DIST = new URL('../dist/', import.meta.url);

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

/** Собранный скрипт панели плеера — тот самый файл, который грузит браузер. */
async function скриптПанели() {
	const папка = new URL('_astro/', DIST);
	const имена = await readdir(fileURLToPath(папка));
	const имя = имена.find((f) => f.startsWith('PlayerBar.astro_astro_type_script') && f.endsWith('.js'));
	if (!имя) {
		console.log('ПРОВЕРКА ОСЛЕПЛА: собранного скрипта панели в dist/_astro/ нет. Соберите сайт: npm run build.');
		process.exit(1);
	}
	return { имя, код: await readFile(new URL(имя, папка), 'utf8') };
}

/**
 * Исполнить скрипт панели поверх подделки и отдать управление проверкам.
 *
 * ПОДДЕЛКА СТОИТ, ПОКА ИДУТ ПРОВЕРКИ, а не только пока грузится скрипт.
 * Первая редакция снимала её сразу после загрузки — и первое же нажатие
 * на кнопку падало с «document is not defined»: обработчик-то живой, а окна
 * под ним уже нет. Поэтому проверки идут внутри, а уборка — в `finally`.
 *
 * `подмена` правит ТЕКСТ собранного скрипта — так работают подлоги.
 * Файл на диске при этом не трогается ни разу.
 */
async function сОкном({ карточки, подмена = (код) => код }, проверки) {
	const { код } = await скриптПанели();
	const окно = makeWindow({ карточки });

	const имена = ['window', 'document', 'matchMedia', 'IntersectionObserver', 'HTMLMediaElement', 'requestAnimationFrame', 'getSelection', 'location', 'history', 'localStorage'];
	const прежние = Object.fromEntries(имена.map((имя) => [имя, globalThis[имя]]));

	globalThis.window = окно.win;
	globalThis.document = окно.documentStub;
	for (const имя of имена.slice(2)) globalThis[имя] = окно.win[имя];

	try {
		// eslint-disable-next-line no-new-func
		new Function(подмена(код))();
		// Панель подключает блоки в обработчике загрузки страницы — зовём его,
		// как это делает браузер.
		for (const { name, fn } of окно.handlers) if (name === 'astro:page-load') await fn();
		await проверки(окно);
	} finally {
		for (const имя of имена) {
			if (прежние[имя] === undefined) delete globalThis[имя];
			else globalThis[имя] = прежние[имя];
		}
	}
	return окно;
}

/** Нажать кнопку блока — так, как это делает браузер. */
function нажать(блок, хват) {
	const кнопка = блок.части.get(хват);
	for (const [событие, fn] of кнопка.нажатия) if (событие === 'click') fn();
}

console.log('МИНИ-ПЛЕЕР ВРЕЗКИ: подключается к тому же звуку, что и плеер выпуска.');
console.log();

// Хваты, которые несёт каждый из двух блоков. Списки РАЗНЫЕ, и в этом весь
// вопрос: у врезки нет ни ±15, ни скорости.
const ПЛЕЕР_ВЫПУСКА = ['ep-toggle', 'ep-back15', 'ep-fwd15', 'ep-range', 'ep-rate', 'ep-time-current', 'ep-time-duration'];
const ВРЕЗКА = ['ep-toggle', 'ep-range', 'ep-time-current', 'ep-time-duration'];

// ── 1. Врезку подключают, хотя контролов у неё меньше ─────────────────────
console.log('── врезку подключают, хотя ±15 и скорости у неё нет ──');

{
	const врезка = makeCard({ guid: 'guid-врезки', контролы: ВРЕЗКА, duration: '2583' });
	await сОкном({ карточки: [врезка] }, (окно) => {
	скажи(Boolean(окно.win.__bakaPlayer), 'панель объявила себя — плеер на странице есть');
	скажи(врезка.части.get('ep-toggle').нажатия.length > 0, 'на кнопку врезки навешен обработчик');
	скажи(врезка.части.get('ep-range').нажатия.length > 0, 'на дорожку врезки навешены обработчики');

	// ГЛАВНОЕ: нажатие правда запускает выпуск, а не молчит.
	const звук = окно.win.__bakaPlayer.audio;
	нажать(врезка, 'ep-toggle');
	скажи(звук.src.includes('guid-врезки'), `нажатие запустило выпуск: ${звук.src || '(ничего)'}`);
	скажи(!звук.paused, 'звук пошёл');
	});
}

// ── 2. Плеер выпуска и врезка на одной странице ───────────────────────────
console.log();
console.log('── на одной странице живут оба блока ──');

{
	const плеер = makeCard({ guid: 'выпуск-страницы', контролы: ПЛЕЕР_ВЫПУСКА, duration: '3723' });
	const врезка = makeCard({ guid: 'другой-выпуск', контролы: ВРЕЗКА, duration: '2583' });
	await сОкном({ карточки: [плеер, врезка] }, (окно) => {
	скажи(плеер.части.get('ep-toggle').нажатия.length > 0, 'плеер страницы подключён');
	скажи(врезка.части.get('ep-toggle').нажатия.length > 0, 'врезка подключена тоже');

	// ЗВУК ОДИН НА СТРАНИЦУ, И ЭТО НЕ ДОГОВОРЁННОСТЬ, А УСТРОЙСТВО. Запустили
	// врезку поверх играющего выпуска — предыдущий остановился сам, потому что
	// источник у обоих один и тот же `<audio>`.
	const звук = окно.win.__bakaPlayer.audio;
	нажать(плеер, 'ep-toggle');
	скажи(звук.src.includes('выпуск-страницы'), 'играет выпуск страницы');

	нажать(врезка, 'ep-toggle');
	скажи(звук.src.includes('другой-выпуск'), 'нажали врезку — играет она');
	скажи(!звук.src.includes('выпуск-страницы'), 'предыдущий выпуск не играет: источник звука один, второго не бывает');
	});
}

// ── 3. Панель прячется, пока виден хоть один блок ─────────────────────────
console.log();
console.log('── панель: одна, и появляется, когда блоки ушли за край ──');

{
	const врезка = makeCard({ guid: 'выпуск', контролы: ВРЕЗКА, duration: '2583' });
	const второй = makeCard({ guid: 'выпуск', контролы: ВРЕЗКА, duration: '2583' });
	await сОкном({ карточки: [врезка, второй] }, (окно) => {
	нажать(врезка, 'ep-toggle');
	// Панель пересчитывает себя при загрузке страницы; после запуска зовём
	// то же, что зовёт переход между страницами.
	окно.win.__bakaPlayer.watchMainPlayer();

	скажи(окно.наблюдаемые.length === 2, `следит за ОБОИМИ блоками того же выпуска (следит за ${окно.наблюдаемые.length})`);

	const панель = окно.элемент('player-bar');

	окно.видимость(врезка, true);
	окно.видимость(второй, true);
	скажи(панель.hidden === true, 'блоки на экране — панель спрятана: два одинаковых набора кнопок это выбор без разницы');
	скажи(окно.уТелаКласс('has-player') === false, 'и место под панель не занято — кнопка «наверх» стоит на своём месте');

	// ОДИН УШЁЛ, ВТОРОЙ ОСТАЛСЯ — панель по-прежнему не нужна. Прежний код
	// спрашивал `entries[0]`, то есть ответ ПОСЛЕДНЕГО сработавшего блока,
	// и здесь показал бы панель поверх видимого блока.
	окно.видимость(врезка, false);
	скажи(панель.hidden === true, 'один ушёл, второй виден — панели по-прежнему нет');

	// Ушли за край оба — панель обязана появиться, иначе звуком нечем управлять.
	окно.видимость(второй, false);
	скажи(панель.hidden === false, 'оба ушли за край — панель появилась и берёт управление на себя');
	скажи(окно.уТелаКласс('has-player') === true, 'место под панель занято — кнопка «наверх» поднимается над ней');
	});
}

// ── 4. Подлоги ────────────────────────────────────────────────────────────
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── подлоги: проверка обязана покраснеть ──');

	// ПОДЛОГ 1 — ПРЕЖНИЙ ЗАСЛОН ПОДКЛЮЧЕНИЯ. Возвращаем требование «есть все
	// семь контролов»: врезка перестанет подключаться, причём МОЛЧА — блок
	// нарисуется, кнопка не сработает. Ровно так это и выглядело бы в жизни,
	// если бы заслон не тронули.
	const врезка = makeCard({ guid: 'guid-врезки', контролы: ВРЕЗКА, duration: '2583' });
	await сОкном({
		карточки: [врезка],
		подмена: (код) => {
			// Собранный скрипт сжат, имена в нём другие; ищем сам заслон
			// по его форме, а не по именам из исходника.
			const заслон = /if\(!(\w+)\|\|!(\w+)\|\|!(\w+)\)return;/;
			if (!заслон.test(код)) {
				console.log(' ПЛОХО  ПОДЛОГ НЕ СРАБОТАЛ: заслона подключения в собранном скрипте не узнал. Чинить подлог, а не код.');
				плохо++;
				return код;
			}
			return код.replace(заслон, 'if(!$1||!$2||!$3||1)return;');
		},
	}, (окно) => {
		скажи(врезка.части.get('ep-toggle').нажатия.length === 0, 'подлог «прежний заслон» пойман: врезку перестали подключать');
		скажи(Boolean(окно.win.__bakaPlayer), 'и при этом панель всё равно объявилась — значит подлог сломал ровно подключение');
	});

	// ПОДЛОГ 2 — ПРЕЖНИЙ СЕЛЕКТОР. Возвращаем поиск по имени класса вместо
	// признака: блоков на странице не найдётся вовсе, потому что подделка
	// отвечает только на признак — как и настоящая врезка, у которой класса
	// `.episode-player` нет.
	const врезка2 = makeCard({ guid: 'guid-врезки', контролы: ВРЕЗКА, duration: '2583' });
	await сОкном({
		карточки: [врезка2],
		подмена: (код) => {
			if (!код.includes('[data-episode-card]')) {
				console.log(' ПЛОХО  ПОДЛОГ НЕ СРАБОТАЛ: признака в собранном скрипте нет. Чинить подлог.');
				плохо++;
				return код;
			}
			return код.replaceAll('[data-episode-card]', '.episode-player');
		},
	}, () => {});
	скажи(врезка2.части.get('ep-toggle').нажатия.length === 0, 'подлог «искать по имени класса» пойман: врезку не нашли');
}

console.log();
if (плохо) {
	console.log(`ПЛОХО: ${плохо}. Кнопка во врезке не заиграет.`);
	process.exit(1);
}
console.log('Всё сошлось.');
