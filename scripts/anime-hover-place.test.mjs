#!/usr/bin/env node
// ГДЕ ВСТАЁТ МАРКА ПРИ НАВЕДЕНИИ — ПРОВЕРЯЕТСЯ СЧЁТОМ, А НЕ ГЛАЗАМИ.
//
// Не всё, что живёт в браузере, требует браузера: положение марки — это два
// числа из коробки ссылки и размеров окна. Глазами его проверяют на той ширине,
// которая сейчас открыта, и на той строке, куда попал курсор; здесь — на всех
// ширинах чек-листа разом и в углах, до которых курсором добираются случайно.
//
// ГОНЯЕТСЯ НАСТОЯЩАЯ ФУНКЦИЯ, та же, что зовёт компонент. Второй реализации
// рядом нет — сверять было бы не с чем.
//
//   node scripts/anime-hover-place.test.mjs
//   node scripts/anime-hover-place.test.mjs --selftest
//
// `--selftest` подкладывает наивное правило («ставим строго под ссылкой, ни
// на что не оглядываясь») и убеждается, что проверка его ловит. Без этого шага
// зелёный ответ не значит ничего.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import {
	местоДляМарки,
	ШИРИНА,
	ВЫСОТА,
	ЗАЗОР,
	ПОЛЕ,
	ОТБИВКА_ВПРАВО,
	ОТБИВКА_ВНИЗ,
} from '../src/lib/hoverPlacement.mjs';

const КОМПОНЕНТ = new URL('../src/components/AnimeHoverCard.astro', import.meta.url);

const селфтест = process.argv.includes('--selftest');
let беды = 0;
const скажи = (строка) => console.log(строка);
const плохо = (строка) => { беды++; скажи('  НЕТ  ' + строка); };
const ладно = (строка) => скажи('  ок   ' + строка);

// Наивное правило: ровно то, что напишут, если забыть про края окна.
function наивно({ короб, прокруткаX, прокруткаY }) {
	return { лево: короб.left + прокруткаX, верх: короб.bottom + ЗАЗОР + прокруткаY, перевёрнута: false };
}

const место = селфтест ? наивно : местоДляМарки;

/** Строка текста шириной 90 и высотой 22 — обычная ссылка на тайтл. */
function ссылка(left, top) {
	return { left, top, bottom: top + 22 };
}

// ── 1. Габарит в стилях и габарит в расчёте — одно число ──────────────────
//
// Числа живут в двух местах поневоле: CSS не умеет спросить модуль. Значит
// их надо СТЕРЕЧЬ, а не надеяться. Вынимаем из самого файла компонента.
function габаритИзСтилей() {
	const текст = readFileSync(fileURLToPath(КОМПОНЕНТ), 'utf8');

	// ПРАВИЛ `.stamp` В ФАЙЛЕ НЕСКОЛЬКО, И ГАБАРИТ ТОЛЬКО В ОДНОМ. Первая
	// редакция брала первое попавшееся — и упала, как только у марки появился
	// подъём при появлении (`.hover-card .stamp { transform }`). Ошибка была
	// в измерителе: спрашивать надо не «первый блок с таким именем», а «блок,
	// где габарит задан». Ищем среди ВСЕХ и требуем ровно одного.
	const сГабаритом = [...текст.matchAll(/\.stamp\s*\{([^}]*)\}/g)]
		.map((m) => ({ ш: /width:\s*(\d+)px/.exec(m[1]), в: /height:\s*(\d+)px/.exec(m[1]) }))
		.filter((б) => б.ш && б.в);

	if (сГабаритом.length === 0) throw new Error('в AnimeHoverCard.astro нет правила .stamp с width и height в пикселях');
	if (сГабаритом.length > 1) throw new Error(`габарит .stamp задан в ${сГабаритом.length} правилах — копии разъедутся`);

	return { ширина: Number(сГабаритом[0].ш[1]), высота: Number(сГабаритом[0].в[1]) };
}

function проверитьГабарит() {
	скажи('\n── габарит в стилях и в расчёте ──');
	const стили = габаритИзСтилей();
	if (стили.ширина === ШИРИНА) ладно(`ширина ${ШИРИНА} совпала со стилями`);
	else плохо(`ширина: в стилях ${стили.ширина}, в расчёте ${ШИРИНА}`);
	if (стили.высота === ВЫСОТА) ладно(`высота ${ВЫСОТА} совпала со стилями`);
	else плохо(`высота: в стилях ${стили.высота}, в расчёте ${ВЫСОТА}`);
}

// ── 2. Ни при каком положении марка не вылезает за окно ───────────────────
//
// Ширины — из чек-листа §25 дизайн-системы, И ПО ПИКСЕЛЮ ЗА КАЖДЫМ ПЕРЕЛОМОМ:
// раскладка разваливается в первых же пикселях после переключения, а круглые
// числа этой полосы не касаются.
// 401 и 402 — сам перелом: 8 поля слева + 384 марки + 2 отбивки + 8 поля
// справа = 402, и это ПЕРВАЯ ширина, где марка помещается.
const ШИРИНЫ = [320, 390, 401, 402, 403, 620, 621, 820, 821, 1100, 1101, 1440];
const ВЫСОТЫ = [500, 700, 900];

function проверитьКрая() {
	скажи('\n── марка не вылезает за окно ни при каком положении ──');
	let проверено = 0;
	let показов = 0;

	for (const ширинаОкна of ШИРИНЫ) {
		for (const высотаОкна of ВЫСОТЫ) {
			// Ссылка ездит по всей ширине и по всей высоте окна, включая углы.
			for (let x = 0; x <= ширинаОкна; x += 17) {
				for (let y = 0; y <= высотаОкна - 22; y += 23) {
					проверено++;
					const ответ = место({
						короб: ссылка(x, y),
						ширинаОкна,
						высотаОкна,
						прокруткаX: 0,
						прокруткаY: 0,
					});
					if (!ответ) continue;
					показов++;

					const правыйКрай = ответ.лево + ШИРИНА + ОТБИВКА_ВПРАВО;
					const нижнийКрай = ответ.верх + ВЫСОТА + ОТБИВКА_ВНИЗ;

					if (ответ.лево < ПОЛЕ) {
						плохо(`окно ${ширинаОкна}×${высотаОкна}, ссылка (${x},${y}): левый край ${ответ.лево} < ${ПОЛЕ}`);
						return;
					}
					if (правыйКрай > ширинаОкна) {
						плохо(`окно ${ширинаОкна}×${высотаОкна}, ссылка (${x},${y}): правый край ${правыйКрай} > ${ширинаОкна}`);
						return;
					}
					if (ответ.верх < 0) {
						плохо(`окно ${ширинаОкна}×${высотаОкна}, ссылка (${x},${y}): верх ${ответ.верх} выше окна`);
						return;
					}
					if (нижнийКрай > высотаОкна) {
						плохо(`окно ${ширинаОкна}×${высотаОкна}, ссылка (${x},${y}): низ ${нижнийКрай} > ${высотаОкна}`);
						return;
					}
				}
			}
		}
	}
	ладно(`положений проверено ${проверено}, из них марка показывается в ${показов} — за окно не вышла ни разу`);
}

// ── 3. Переворот вверх у нижнего края ────────────────────────────────────
function проверитьПереворот() {
	скажи('\n── переворот вверх, когда снизу не помещается ──');
	const ширинаОкна = 1440;
	const высотаОкна = 800;

	const сверху = место({ короб: ссылка(100, 100), ширинаОкна, высотаОкна, прокруткаX: 0, прокруткаY: 0 });
	if (сверху && сверху.перевёрнута === false && сверху.верх === 100 + 22 + ЗАЗОР) {
		ладно(`ссылка вверху страницы — марка снизу, верх ${сверху.верх}`);
	} else {
		плохо(`ссылка вверху страницы: ждали марку снизу на ${100 + 22 + ЗАЗОР}, вышло ${JSON.stringify(сверху)}`);
	}

	// Ссылка у самого низа: снизу остаётся 800−742 = 58 при нужных 175.
	const внизу = место({ короб: ссылка(100, 720), ширинаОкна, высотаОкна, прокруткаX: 0, прокруткаY: 0 });
	if (внизу && внизу.перевёрнута === true && внизу.верх === 720 - ЗАЗОР - ВЫСОТА) {
		ладно(`ссылка у нижнего края — марка перевернулась, верх ${внизу.верх}`);
	} else {
		плохо(`ссылка у нижнего края: ждали переворот на ${720 - ЗАЗОР - ВЫСОТА}, вышло ${JSON.stringify(внизу)}`);
	}
}

// ── 4. Прижатие к правому краю ───────────────────────────────────────────
function проверитьПрижатие() {
	скажи('\n── прижатие к правому краю с полем ──');
	const ширинаОкна = 1000;
	const ответ = место({ короб: ссылка(900, 100), ширинаОкна, высотаОкна: 800, прокруткаX: 0, прокруткаY: 0 });
	const ждали = ширинаОкна - ШИРИНА - ОТБИВКА_ВПРАВО - ПОЛЕ;
	if (ответ && ответ.лево === ждали) ладно(`ссылка у правого края — марка прижата на ${ждали}`);
	else плохо(`прижатие: ждали лево ${ждали}, вышло ${JSON.stringify(ответ)}`);
}

// ── 5. Прокрутка переводится в координаты страницы ────────────────────────
function проверитьПрокрутку() {
	скажи('\n── координаты считаются для страницы, а не для окна ──');
	const без = место({ короб: ссылка(100, 100), ширинаОкна: 1440, высотаОкна: 800, прокруткаX: 0, прокруткаY: 0 });
	const с = место({ короб: ссылка(100, 100), ширинаОкна: 1440, высотаОкна: 800, прокруткаX: 30, прокруткаY: 2000 });
	if (без && с && с.лево === без.лево + 30 && с.верх === без.верх + 2000) {
		ладно('прокрутка прибавляется к обеим координатам');
	} else {
		плохо(`прокрутка: ${JSON.stringify(без)} против ${JSON.stringify(с)}`);
	}
}

// ── 6. Узкое окно: марки нет вовсе ───────────────────────────────────────
function проверитьУзкое() {
	скажи('\n── в узкое окно марка не ставится ──');
	// ПЕРЕЛОМ СЧИТАЕТСЯ, А НЕ БЕРЁТСЯ НА ГЛАЗ: поле 8 + марка 384 + отбивка 2
	// + поле 8 = 402. Первый прогон ждал 401 и покраснел — ошибка была
	// в ожидании, а не в правиле.
	const перелом = ПОЛЕ + ШИРИНА + ОТБИВКА_ВПРАВО + ПОЛЕ;

	for (const ширинаОкна of [320, 390, перелом - 1]) {
		const ответ = место({ короб: ссылка(10, 100), ширинаОкна, высотаОкна: 800, прокруткаX: 0, прокруткаY: 0 });
		if (ответ === null) ладно(`окно ${ширинаОкна} — марки нет`);
		else плохо(`окно ${ширинаОкна}: ждали «места нет», вышло ${JSON.stringify(ответ)}`);
	}

	for (const ширинаОкна of [перелом, перелом + 1]) {
		const ответ = место({ короб: ссылка(10, 100), ширинаОкна, высотаОкна: 800, прокруткаX: 0, прокруткаY: 0 });
		if (ответ) ладно(`окно ${ширинаОкна} — марка есть`);
		else плохо(`окно ${ширинаОкна}: марка обязана помещаться`);
	}
}

проверитьГабарит();
проверитьКрая();
проверитьПереворот();
проверитьПрижатие();
проверитьПрокрутку();
проверитьУзкое();

if (селфтест) {
	скажи(
		беды > 0
			? `\nПОДЛОГ ПОЙМАН (${беды} расхождений) — проверка умеет краснеть.`
			: '\nПОДЛОГ НЕ ПОЙМАН: проверка бесполезна, чинить надо её.',
	);
	process.exitCode = беды > 0 ? 0 : 1;
} else {
	скажи(беды === 0 ? '\nок      Марка встаёт на место при любой ширине окна' : `\nПРОВАЛ  Расхождений: ${беды}`);
	if (беды > 0) process.exitCode = 1;
}
