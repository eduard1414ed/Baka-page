// ДАННЫЕ: путь к картинке и подпись, адрес видео, текст спойлера. Эта —
// единственная, которая кладёт ССЫЛКУ. Отсюда соблазн, названный в ТЗ прямо:
// «раз уж мы всё равно знаем заголовок, сохраним и его». Сохранённый заголовок
// соврёт при первом же переименовании выпуска — И СБОРКА ПРИ ЭТОМ НЕ УПАДЁТ:
// страница соберётся чисто, а во всех старых статьях останется старое
// название. Такое находят случайно и через полгода. Ловить это может только
