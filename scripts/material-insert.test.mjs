// СПРАШИВАЕТСЯ НАСТОЯЩИЙ КОД АДМИНКИ, А НЕ ЕГО ПЕРЕСКАЗ. Скрипт вынимается
// из `public/admin/index.html` КАК ЕСТЬ и исполняется в Node поверх подделки
// из трёх глобальных имён, которые ему даёт Sveltia (CMS, h, createClass).
// Перепиши мы `toBlock` рядом — проверка сверяла бы копию с копией.
//
// ПОДЛОГ ВОЗВРАЩАЕТ РОВНО ТУ БЕДУ, О КОТОРОЙ ПРЕДУПРЕЖДАЕТ ТЗ: дописывает
// в `toBlock` сохранение заголовка. Проверка обязана покраснеть на нём
// и промолчать на здоровом коде — иначе её «ок» не значит ничего.

import { readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { canPlayInline, whyCannotPlay } from '../src/lib/postRef.mjs';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const КОРЕНЬ = join(ЗДЕСЬ, '..');
const АДМИНКА = join(КОРЕНЬ, 'public/admin/index.html');
const НАСТРОЙКИ = join(КОРЕНЬ, 'public/admin/config.yml');

let плохо = 0;
const скажи = (ок, что) => {
	if (!ок) плохо++;
	console.log(`${ок ? '  ок  ' : ' ПЛОХО'}  ${что}`);
};

/**
 * Вынуть модульный скрипт админки и исполнить его, подсунув то, что в браузере
 * даёт сама Sveltia. Возвращает зарегистрированные кнопки редактора по их id.
 *
 * `подмена` — необязательная правка ТЕКСТА скрипта: так работают подлоги.
 * Настоящий файл при этом не трогается ни разу.
 */
async function кнопкиРедактора(подмена = (текст) => текст) {
	const html = await readFile(АДМИНКА, 'utf8');
	const куски = [...html.matchAll(/<script[^>]*type="module"[^>]*>([\s\S]*?)<\/script>/g)]
		.map((m) => m[1])
		.filter((кусок) => кусок.trim());

	if (куски.length !== 1) {
		throw new Error(`Ожидал один модульный скрипт в админке, нашёл ${куски.length}. Проверка ослепла — чинить её, а не код.`);
	}

	const кнопки = new Map();
	const поля = new Map();

	const CMS = {
		registerEditorComponent: (описание) => кнопки.set(описание.id, описание),
		registerFieldType: (имя, control, preview) => поля.set(имя, { control, preview }),
		registerEventListener: () => {},
		registerPreviewTemplate: () => {},
	};

	// `h` и `createClass` в браузере даёт Sveltia. Здесь они нужны только затем,
	// чтобы модуль доисполнился до регистрации кнопок: сами поля мы не рисуем —
	// вид проверяет заказчик руками, это правило проекта.
	const h = (тег, свойства, ...дети) => ({ тег, свойства, дети });
	const createClass = (описание) => описание;

	const тело = подмена(куски[0]);
	const исполнить = new Function('CMS', 'h', 'createClass', 'window', 'fetch', 'alert', 'document', тело);
	исполнить(CMS, h, createClass, { addEventListener() {} }, async () => ({ ok: false }), () => {}, { addEventListener() {} });

	return { кнопки, поля };
}

/** Разобрать директиву обратно тем же выражением, каким это делает админка. */
function обратно(кнопка, строка) {
	const совпало = кнопка.pattern.exec(строка.trim());
	return совпало ? кнопка.fromBlock(совпало) : null;
}

console.log('ВРЕЗКА НА СВОЙ МАТЕРИАЛ: в файл уезжает только адрес.');
console.log();

const { кнопки, поля } = await кнопкиРедактора();
const врезка = кнопки.get('material');

// ── 1. Кнопка вообще есть, и она видна в меню ─────────────────────────────
console.log('── кнопка заведена и вписана в меню ──');

скажи(Boolean(врезка), 'кнопка «material» зарегистрирована в админке');
скажи(врезка?.label === 'Наш материал', `подпись пункта меню — «Наш материал» (сейчас «${врезка?.label}»)`);
скажи(поля.has('material-search'), 'поле выбора материала зарегистрировано (material-search)');

// РЕГИСТРАЦИИ МАЛО. Sveltia показывает в меню ТОЛЬКО перечисленное
// в `editor_components` у поля. Забудешь вписать — кнопки просто не будет,
// и никакой ошибки при этом не появится.
const настройки = await readFile(НАСТРОЙКИ, 'utf8');
const списки = [...настройки.matchAll(/editor_components:\s*\[([^\]]*)\]/g)].map((m) => m[1]);
скажи(
	списки.some((список) => список.split(',').some((имя) => имя.trim() === 'material')),
	'пункт вписан в editor_components — без этого кнопки в меню не будет, и молча',
);

// ── 2. Главное: в файл уезжает ТОЛЬКО адрес ───────────────────────────────
console.log();
console.log('── в файл уезжает только адрес материала ──');

// Данные формы намеренно «богатые»: поле выбора держит у себя и заголовок,
// и признак «может ли играть». Всё это нужно ЭКРАНУ и не должно доехать
// до файла.
const богатые = {
	match: {
		id: 'ep-152',
		title: 'У Синкая появился наследник | И наступит рассвет',
		canPlay: true,
		whyNot: null,
		thumb: '/images/uploads/cover-640w.webp',
		date: '2026-08-12',
		number: '№152',
	},
	label: '',
	mode: 'link',
};

const простой = врезка.toBlock(богатые).trim();
скажи(простой === '::material{id="ep-152"}', `умолчания в файл не пишутся: ${простой}`);

const атрибуты = [...простой.matchAll(/([\w-]+)="/g)].map((m) => m[1]);
скажи(
	атрибуты.length === 1 && атрибуты[0] === 'id',
	`атрибут ровно один и это адрес (нашлось: ${атрибуты.join(', ') || 'ни одного'})`,
);

// Отдельно и поимённо — то, чего быть не должно ни при каких данных.
for (const запрещено of ['У Синкая', '№152', '2026-08-12', 'cover-640w', 'canPlay']) {
	скажи(!простой.includes(запрещено), `в файл не уехало «${запрещено}»`);
}

const сОбоими = врезка.toBlock({ ...богатые, label: 'мы уже разбирали это', mode: 'play' }).trim();
скажи(
	сОбоими === '::material{id="ep-152" label="мы уже разбирали это" mode="play"}',
	`заданные автором подпись и режим пишутся: ${сОбоими}`,
);

скажи(врезка.toBlock({ match: {}, label: 'что-то', mode: 'play' }) === '', 'без выбранного материала блок не ставится вовсе');

// ── 3. Туда-обратно ───────────────────────────────────────────────────────
console.log();
console.log('── блок открывается на правку тем же, чем записан ──');

const назад = обратно(врезка, сОбоими);
скажи(назад?.match?.id === 'ep-152', 'адрес вернулся');
скажи(назад?.label === 'мы уже разбирали это', 'подпись вернулась');
скажи(назад?.mode === 'play', 'режим вернулся');
скажи(
	назад && !('title' in назад.match),
	'заголовка в форме нет — поле достанет его из списка по адресу, а не из файла',
);

const назадПростой = обратно(врезка, простой);
скажи(назадПростой?.mode === 'link', 'у блока без режима подставляется «ведёт на материал»');
скажи(назадПростой?.label === '', 'у блока без подписи поле остаётся пустым — подпись подставит сборка');

// КАВЫЧКА В ПОДПИСИ. Разбор директив кончает значение атрибута на первой же
// прямой кавычке — то же правило, что у подписи картинки (directiveAttr.mjs).
const сКавычкой = врезка.toBlock({ ...богатые, label: 'разбирали «Monster», а не "Monster"' }).trim();
скажи(!/label="[^"]*"[^"]*"/.test(сКавычкой), `кавычка в подписи экранирована: ${сКавычкой}`);
скажи(
	обратно(врезка, сКавычкой)?.label === 'разбирали «Monster», а не "Monster"',
	'кавычка вернулась в поле такой, какой её набрали',
);

// ── 4. Предпросмотр не ломает вставку текста ──────────────────────────────
console.log();
console.log('── предпросмотр пустой кнопки не начинается с тега ──');

// Sveltia зовёт `toPreview` С ПУСТЫМИ ДАННЫМИ при регистрации, смотрит первый
// HTML-тег в ответе и после этого ЗАБИРАЕТ СЕБЕ ВСЕ ТАКИЕ ТЕГИ из вставляемого
// текста (importDOM). Начнись ответ с тега — текст, скопированный из соцсетей,
// рассыпался бы на наши блоки. В документации Decap об этом нет ни слова.
for (const пусто of [{}, { match: {} }, { match: {}, label: '', mode: 'link' }]) {
	const вид = String(врезка.toPreview(пусто)).trim();
	скажи(!вид.startsWith('<'), `на пустых данных ответ без тега: «${вид.slice(0, 40)}»`);
}

// ── 5. «Может ли играть» — одно правило на админку и на сборку ────────────
console.log();
console.log('── правило «может ли играть» отвечает одинаково всем ──');

const случаи = [
	[{ data: { category: 'podcast' } }, true, 'выпуск подкаста'],
	[{ data: { category: 'videoessay' } }, true, 'видеоэссе'],
	[{ data: { category: 'bonus' } }, false, 'бонус — своего аудио нет, он на Patreon и Boosty'],
	[{ data: { category: 'note' } }, false, 'заметка'],
	[{ data: { category: 'article' } }, false, 'статья'],
	[{ data: { category: 'podcast', externalUrl: 'https://kinopoisk.ru/x' } }, false, 'подкаст на чужом сайте'],
];
for (const [пост, ждём, что] of случаи) {
	скажи(canPlayInline(пост) === ждём, `${что}: ${canPlayInline(пост) ? 'играть можно' : 'играть нельзя'}`);
}

// Причина обязана быть ровно там, где нельзя, и молчать там, где можно:
// иначе «нельзя без причины» уедет в текст ошибки сборки пустотой.
for (const [пост, ждём, что] of случаи) {
	const причина = whyCannotPlay(пост);
	скажи(ждём ? причина === null : Boolean(причина), `${что}: причина ${ждём ? 'не нужна' : `названа — «${причина}»`}`);
}

// АДМИНКА НЕ РЕШАЕТ ЭТО САМА. Спроси она своим списком категорий — списки
// разъехались бы молча: админка разрешала бы то, на чём падает сборка.
const html = await readFile(АДМИНКА, 'utf8');
const кусокВрезки = html.slice(html.indexOf('Кнопка «Наш материал»'), html.indexOf("id: 'material',"));
скажи(
	!/'(podcast|videoessay|bonus|note|article)'/.test(кусокВрезки),
	'в коде кнопки нет своего списка категорий — ответ приходит готовым из списка материалов',
);

// ── 6. Подлоги ────────────────────────────────────────────────────────────
if (process.argv.includes('--selftest')) {
	console.log();
	console.log('── подлоги: проверка обязана покраснеть ──');

	// ПОДЛОГ 1 — ровно та беда, о которой предупреждает ТЗ: заголовок уезжает
	// в файл «за компанию». Разводится ОДНА строка, как это и случилось бы
	// в жизни, когда кто-то решит, что так удобнее.
	const сЗаголовком = await кнопкиРедактора((текст) => {
		const было = 'const parts = [`id="${escapeAttr(id)}"`];';
		if (!текст.includes(было)) throw new Error('ПОДЛОГ НЕ СРАБОТАЛ: строка, которую он подменяет, изменилась. Чинить подлог.');
		return текст.replace(было, 'const parts = [`id="${escapeAttr(id)}"`, `title="${escapeAttr((data.match || {}).title)}"`];');
	});
	const испорчено = сЗаголовком.кнопки.get('material').toBlock(богатые).trim();
	const поймано = [...испорчено.matchAll(/([\w-]+)="/g)].map((m) => m[1]).length !== 1;
	скажи(поймано, `подлог «сохраним и заголовок» пойман: ${испорчено}`);

	// ПОДЛОГ 2 — предпросмотр начинается с тега. Именно так однажды сломалась
	// вставка текста из соцсетей: каждый абзац становился нашим блоком.
	const сТегом = await кнопкиРедактора((текст) => {
		const было = "if (!m.id) return 'Наш материал (не выбран)';";
		if (!текст.includes(было)) throw new Error('ПОДЛОГ НЕ СРАБОТАЛ: строка предпросмотра изменилась. Чинить подлог.');
		return текст.replace(было, "if (!m.id) return '<div>Наш материал (не выбран)</div>';");
	});
	скажи(
		String(сТегом.кнопки.get('material').toPreview({})).trim().startsWith('<'),
		'подлог «предпросмотр с тегом» пойман',
	);

	// ПОДЛОГ 3 — пункт вычистили из меню. Кнопка при этом остаётся
	// зарегистрированной, и заметить пропажу можно только этой проверкой.
	const безПункта = настройки.replace(/(editor_components:\s*\[[^\]]*?)material,\s*/, '$1');
	скажи(
		безПункта !== настройки && !/editor_components:[^\]]*\bmaterial\b/.test(безПункта),
		'подлог «пункт вычищен из меню» пойман',
	);
}

console.log();
if (плохо) {
	console.log(`ПЛОХО: ${плохо}. Врезка на материал в этом виде поедет неправильно.`);
	process.exit(1);
}
console.log('Всё сошлось.');
