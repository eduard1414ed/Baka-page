#!/usr/bin/env node
// ПЕРФОРАЦИЯ ВСПЛЫВАЮЩЕЙ МАРКИ ОБЯЗАНА СОВПАДАТЬ С ПЕРФОРАЦИЕЙ ОБЫЧНОЙ.
//
// Зачем это отдельной проверкой. Марка при наведении всплывает прямо над блоком
// «упоминается в материале», где стоят её же родные сёстры (AnimeBadge.astro).
// Зубцы у них обязаны быть одинаковыми — иначе читатель видит не «тот же
// компонент», а две похожие вещи, и это читается неряшливостью. При этом
// нарисованы они РАЗНЫМ способом: у обычной марки кружки цвета бумаги поверх,
// у всплывающей настоящая маска (иначе отбивка `drop-shadow` вышла бы
// прямоугольной). Два разных способа с одинаковым результатом — это ровно тот
// случай, который расходится молча.
//
// ГЕОМЕТРИЯ ВЫНИМАЕТСЯ ИЗ САМИХ ФАЙЛОВ, А НЕ ПЕРЕПИСЫВАЕТСЯ СЮДА. Переписанный
// рядом список — это копия, и врёт она в сторону «сломано»: правку внесут
// в компонент, проверка упадёт на здоровом коде. Отсюда и маска, и числа
// обычной марки читаются из `src/`.
//
//   node scripts/anime-hover-mask.test.mjs
//   node scripts/anime-hover-mask.test.mjs --selftest
//
// `--selftest` подкладывает маске другой радиус — ровно так она и разъедется,
// если однажды кто-то поправит зубцы у одной марки и не поправит у другой.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import sharp from 'sharp';

const КОМПОНЕНТ = new URL('../src/components/AnimeHoverCard.astro', import.meta.url);
const МАРКА = new URL('../src/components/AnimeBadge.astro', import.meta.url);

const селфтест = process.argv.includes('--selftest');
let беды = 0;
const скажи = (строка) => console.log(строка);

/** Адрес маски — из стилей всплывающей марки, как он там написан. */
function маскаИзКомпонента() {
	const текст = readFileSync(fileURLToPath(КОМПОНЕНТ), 'utf8');
	const найдено = /mask-image:\s*url\("(data:image\/svg\+xml,[^"]*)"\)/.exec(текст);
	if (!найдено) throw new Error('в AnimeHoverCard.astro не нашлось mask-image с адресом data:image/svg+xml');
	return найдено[1]
		.replace(/^data:image\/svg\+xml,/, '')
		.replace(/%3C/g, '<')
		.replace(/%3E/g, '>')
		.replace(/%23/g, '#');
}

/** Шаг и радиус кружка — из стилей ОБЫЧНОЙ марки, чтобы сверять было с чем. */
function зубцыОбычнойМарки() {
	const текст = readFileSync(fileURLToPath(МАРКА), 'utf8');
	// radial-gradient(circle at 5px 0, var(--paper) 4px, transparent 4.5px) 0 0 / 16px 10px repeat-x
	const найдено = /radial-gradient\(circle at [^,]+,\s*var\(--paper\)\s*(\d+)px[^)]*\)[^;]*?\/\s*(\d+)px (\d+)px repeat-x/.exec(текст);
	if (!найдено) throw new Error('в AnimeBadge.astro не нашлась перфорация по горизонтали');
	const радиус = Number(найдено[1]);
	const шаг = Number(найдено[2]);
	// Центр кружка стоит на 1 px СНАРУЖИ края (`top: -1px`), значит внутрь
	// марки он входит на радиус минус этот отступ.
	const наружу = /\.stamp::before\s*\{[^}]*top:\s*-(\d+)px/.exec(текст);
	if (!наружу) throw new Error('в AnimeBadge.astro не нашлось смещение верхней полосы перфорации');
	return { радиус, шаг, глубина: радиус - Number(наружу[1]) };
}

async function main() {
	let svg = маскаИзКомпонента();
	const образец = зубцыОбычнойМарки();

	if (селфтест) {
		// ПОДЛОГ РАЗВОДИТ РОВНО ОДНУ КОПИЮ, как это и случится в жизни: зубцы
		// поправят у всплывающей марки и не поправят у обычной.
		svg = svg.replace(/r='4'/g, "r='6'");
		скажи('ПОДЛОГ: радиус кружка в маске поднят с 4 до 6.');
	}

	const { data, info } = await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
	const прозрачность = (x, y) => data[(y * info.width + x) * info.channels + 3];
	const дырка = (x, y) => прозрачность(x, y) < 128;

	скажи(`\nобычная марка: шаг ${образец.шаг}, радиус ${образец.радиус}, зубец глубиной ${образец.глубина}`);
	скажи(`маска: растр ${info.width}×${info.height}`);

	// Глубина зубца: сколько прозрачных пикселей вниз от края в середине зубца.
	let глубина = 0;
	while (глубина < info.height && дырка(5, глубина)) глубина++;

	// Сколько зубцов по верхнему краю и через сколько идут.
	const начала = [];
	for (let x = 0; x < info.width; x++) {
		if (дырка(x, 0) && (x === 0 || !дырка(x - 1, 0))) начала.push(x);
	}
	const шаги = new Set(начала.slice(1).map((x, i) => x - начала[i]));

	const случаи = [
		['глубина зубца совпала с обычной маркой', глубина, образец.глубина],
		['шаг зубцов совпал с обычной маркой', шаги.size === 1 ? [...шаги][0] : `разнобой ${[...шаги]}`, образец.шаг],
		['зубцов по верхнему краю', начала.length, info.width / образец.шаг],
		['середина марки не прозрачна', дырка(info.width >> 1, info.height >> 1), false],
		['левый край прогрызен', дырка(0, 5), true],
		['правый край прогрызен', дырка(info.width - 1, 5), true],
		['нижний край прогрызен', дырка(5, info.height - 1), true],
	];

	скажи('');
	for (const [имя, вышло, ждали] of случаи) {
		const сошлось = вышло === ждали;
		if (!сошлось) беды++;
		скажи(`  ${сошлось ? 'ок  ' : 'НЕТ '} ${имя.padEnd(42)} вышло ${вышло}, ждали ${ждали}`);
	}

	if (селфтест) {
		скажи(
			беды > 0
				? '\nПОДЛОГ ПОЙМАН — проверка умеет краснеть.'
				: '\nПОДЛОГ НЕ ПОЙМАН: проверка бесполезна, чинить надо её.',
		);
		process.exitCode = беды > 0 ? 0 : 1;
		return;
	}

	скажи(беды === 0 ? '\nок      Зубцы всплывающей марки те же, что у обычной' : `\nПРОВАЛ  Расхождений: ${беды}`);
	if (беды > 0) process.exitCode = 1;
}

// Русские буквы в пути к проекту: import.meta.url их кодирует, а process.argv[1]
// нет, и строчное сравнение не совпало бы НИКОГДА (CLAUDE.md, «Уроки проекта»).
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
	await main();
}
