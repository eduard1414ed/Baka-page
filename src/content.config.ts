				// Подсказка к полю `anime`, а не оно само: размечает тайтлы человек,
				// автоматика только предлагает (тз/07 — «не размечать автоматически»).
				//
				// ПРОСТО СТРОКИ, А НЕ reference('anime'), намеренно. Ссылка
