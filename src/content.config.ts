		url: optionalUrl,
		// Франшиза по версии Shikimori: один и тот же идентификатор у всех
		// сезонов, фильмов и арок одного произведения («shingeki_no_kyojin»
		// у «Атаки титанов» и всех её сезонов). Приходит в том же ответе
		// `GET /api/animes/<id>`, который проект и так запрашивает, — новых
