		// заказчик так все 658 карточек, весь каталог тайтлов молча выпал бы
		// из поиска. Поэтому в админке это выбор из трёх, где пустое значение
		// нейтрально, а пустота здесь читается как «правило работает» —
		// безопасная сторона, как у `strictQuotes` и `noSpeech`.
