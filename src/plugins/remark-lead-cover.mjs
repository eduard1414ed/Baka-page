import { visit, EXIT } from 'unist-util-visit';
import { isOptimizableImage } from '../lib/imageVariants.mjs';

/**
 * Обложка поста в начало текста — если картинок в тексте нет ни одной.
 *
 * ЭТО ОТМЕНА ПРАВИЛА, А НЕ ПОЧИНКА НЕДОДЕЛКИ. С этапа 6 обложка нарочно
 * не выводилась на самой странице поста: она нужна ленте и превью в соцсетях,
 * а на странице картинка и так есть. Довод был верным ровно до тех пор, пока
 * картинка на странице ПРАВДА есть. У обзоров, написанных руками, её нет
 * вовсе — страница открывается голым заголовком, хотя обложка у поста задана
 * и в ленте показывается. Отменено решением заказчика 12 августа 2026;
 * старое правило и ссылка на отмену стоят в CLAUDE.md, src/content.config.ts
 * и public/admin/config.yml.
 *
 * ПОЧЕМУ ПЛАГИН, А НЕ РАЗМЕТКА СТРАНИЦЫ. Обложка обязана выглядеть ТОЧНО ТАК
 * ЖЕ, как иллюстрация в тексте: та же ширина колонки, та же пропорция без
 * обрезки, то же увеличение по нажатию. Всё это уже умеет remarkImageFigure —
 * значит вставлять надо не вёрстку, а обычный узел `::image`, и пусть его
 * разберёт тот же код. Вёрстка фигуры остаётся в одном месте на весь сайт.
 * Собрать её второй раз на странице материала было бы копией, которая
 * разъедется с первой же правкой вида иллюстраций.
 *
 * ИДЁТ ПОСЛЕ remarkEpisodeCover И ДО remarkAdLabel/remarkImageFigure:
 * первый уже убрал из тела обложку выпуска (иначе мы посчитали бы её
 * картинкой в тексте, хотя на странице её нет), второй ставит маркировку
 * рекламы у первой строки ТЕКСТА и наш кадр правильно пропустит, третий
 * превращает `::image` в готовую фигуру.
 *
 * НОМЕРА У ОБЛОЖКИ НЕТ, и заводить его не пришлось: номер получают только
 * подписанные иллюстрации (см. numberFigures), а подписи у обложки нет —
 * поля под неё не существует. Добавит автор картинку в такой пост — условие
 * «в теле картинок нет» перестанет выполняться, обложка из текста исчезнет
 * сама, и нумерация посчитается так, будто её тут и не было.
 */

// Разделы, где своя картинка сверху есть всегда и обложка в тексте была бы
// вторым таким же кадром: у выпуска и бонуса — квадратная обложка в шапке
// (её убирает из тела remarkEpisodeCover), у видеоэссе — плеер на 1000.
// Список свой, а не общий с remarkEpisodeCover: там он про «эту картинку
// уже показали выше», здесь — про «место наверху занято».
const CATEGORIES_WITH_OWN_HERO = ['podcast', 'bonus', 'videoessay'];

/**
 * Медиа ли это. Ролик считается картинкой наравне с кадром: правило заведено
 * не ради обложки, а ради того, чтобы страница не открывалась голым
 * заголовком, — а у ролика кадр есть, и обложка над ним читалась бы дублем.
 */
function isMedia(node) {
	if (node.type === 'image') return true;
	return node.type === 'leafDirective' && (node.name === 'image' || node.name === 'video');
}

/**
 * Есть ли в теле хоть одно медиа — НЕ СЧИТАЯ спрятанного в спойлере.
 *
 * Содержимое спойлера лежит в `<template>`, и до нажатия его на странице нет
 * вообще: читатель, спойлер не раскрывший, видит ровно тот голый заголовок,
 * ради которого правило и заведено. Раскроет — увидит обложку сверху
 * и картинку ниже, то есть обычный пост с картинками.
 *
 * Спойлер к этому моменту ещё не собран (remarkSpoiler идёт последним),
 * поэтому его границы — это два маркера-директивы среди соседей верхнего
 * уровня, ровно как их читает сам remarkSpoiler.
 */
function hasMediaOutsideSpoiler(tree) {
	let insideSpoiler = false;

	for (const child of tree.children) {
		if (child.type === 'leafDirective' && child.name === 'spoiler-start') {
			insideSpoiler = true;
			continue;
		}
		if (child.type === 'leafDirective' && child.name === 'spoiler-end') {
			insideSpoiler = false;
			continue;
		}
		if (insideSpoiler) continue;

		let found = false;
		visit(child, (node) => {
			if (!isMedia(node)) return;
			found = true;
			return EXIT;
		});
		if (found) return true;
	}

	return false;
}

export default function remarkLeadCover() {
	return (tree, file) => {
		const frontmatter = file?.data?.astro?.frontmatter ?? {};
		const { category, cover, noCover } = frontmatter;

		if (CATEGORIES_WITH_OWN_HERO.includes(category)) return;

		// «Обложки нет намеренно» перебивает всё — тем же порядком, что
		// и в getCardMedia: это осознанный выбор автора, а не пустое поле.
		if (noCover === true) return;
		if (!cover) return;

		// РОЛИК СЧИТАЕТСЯ КАРТИНКОЙ, и спрашивается он у ТЕЛА — ниже,
		// в `hasMediaOutsideSpoiler` (`isMedia` пускает и `::video`).
		// Прежде тут стояла отдельная строка про поля «Ссылка на ролик»
		// и «Своё видео»: они ставили окошко ВЫШЕ текста, то есть занимали
		// место наверху. Поля сняты решением заказчика 15 августа 2026,
		// и случай остался один — блок в тексте.
		if (hasMediaOutsideSpoiler(tree)) return;

		// Сжатые копии умеет делать только jpg/jpeg/png; для остального
		// remarkImageFigure собрал бы ссылки на несуществующие файлы.
		// В архиве такой обложки нет ни одной — но молча пропустить нельзя:
		// автор увидит страницу без картинки и не узнает почему.
		if (!isOptimizableImage(decodeURIComponent(cover))) {
			console.warn(
				`[обложка в текст] ${file?.path ?? 'пост'}: обложка «${cover}» не jpg/jpeg/png, ` +
					'сжатых копий у неё не будет — в начало текста не поставлена.',
			);
			return;
		}

		// Альт пустой намеренно: обложка ничего не добавляет к заголовку,
		// который диктор только что прочитал, а придумывать за автора описание
		// картинки нельзя. Поля подписи и альта у обложки не существует.
		tree.children.unshift({
			type: 'leafDirective',
			name: 'image',
			attributes: { src: cover, alt: '' },
			children: [],
		});
	};
}
