import { unescapeAttr } from '../lib/directiveAttr.mjs';
/**
 * Подпись блока внутри текста материала: `::label{text="видеоверсия"}`.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ БЛОК, А НЕ ЗАГОЛОВОК. Автор писал такие подписи обычным
 * заголовком третьего уровня — и «Видеоверсия» выглядела разделом статьи,
 * а не подписью блока, то есть иначе, чем стоящая рядом `[ аудиоверсия ]`.
 * Заголовки в тексте при этом трогать нельзя: в статьях они настоящие.
 *
 * ВИД БЕРЁТСЯ У ОБЩЕЙ ПОДПИСИ БЛОКА — класс `.body-label` в global.css, тот же,
 * что у `[ аудиоверсия ]`, `[ о выпуске ]` и `[ таймкоды ]`. Своего описания
 * тут нет и быть не должно: пять подписей обязаны выглядеть одинаково.
 *
 * СКОБКИ РИСУЕТ CSS, автор их не пишет. Напиши он их сам — вышли бы двойные,
 * а в поисковый индекс полезло бы «[ видеоверсия ]».
 *
 * Заголовком второго уровня, как `[ аудиоверсия ]`: это подпись к тому, что
 * идёт следом, и в оглавлении страницы для экранного диктора она на месте.
 */
export default function remarkBlockLabel() {
	return (tree, file) => {
		const walk = (node) => {
			if (!Array.isArray(node.children)) return;

			for (const child of node.children) {
				walk(child);

				if (child.type !== 'leafDirective' || child.name !== 'label') continue;

				const text = unescapeAttr(child.attributes?.text ?? '').trim();

				// Пустая подпись — это пустая строка на странице и ничего больше.
				// Молча рисовать её нельзя, тихо выбрасывать тоже: скажем в сборку.
				if (!text) {
					console.warn(
						`[подпись блока] ${file?.path ?? 'пост'}: подпись пустая, блок не показан. ` +
							'Впишите слово в админке или уберите маркер.',
					);
					child.data = { hName: 'span', hProperties: {}, hChildren: [] };
					continue;
				}

				child.data = {
					hName: 'h2',
					hProperties: { class: 'body-label tech' },
					hChildren: [{ type: 'text', value: text }],
				};
			}
		};

		walk(tree);
	};
}
