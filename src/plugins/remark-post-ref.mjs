/**
 * `::material{id="ep-152" label="ещё по теме" mode="play"}` — врезка на другой
 * материал сайта. Ставит её кнопка «Наш материал» в админке
 * (public/admin/index.html), а вид описан в src/styles/global.css.
 *
 * В ФАЙЛЕ СТАТЬИ ЛЕЖИТ ТОЛЬКО АДРЕС МАТЕРИАЛА. Заголовок, обложка,
 * длительность, номер выпуска и время чтения берутся здесь, при сборке,
 * из самой коллекции. Поэтому переименованный выпуск меняет название
 * во всех врезках архива сам, а не оставляет их врать полгода.
 *
 * ТРИ БЛОКА, И РАЗЛИЧАЮТСЯ ОНИ ДЕЙСТВИЕМ:
 *   врезка      — указывает на материал, уводит по клику;
 *   мини-плеер  — играет здесь (выпуск подкаста);
 *   фасад       — играет здесь (видеоэссе), до нажатия ютюба на странице нет.
 *
 * ПОЧЕМУ КОЛЛЕКЦИЯ ЧИТАЕТСЯ С ДИСКА, А НЕ ЧЕРЕЗ `getCollection`. Плагины
 * разметки живут вне мира Astro: `astro:content` для них не существует.
 * Тем же способом читает справочник тайтлов remark-anime.mjs — это не обход
 * правил, а единственная дверь.
 *
 * ПЛАГИН АСИНХРОННЫЙ, И ЭТО ОБЯЗАТЕЛЬНО: длительность выпуска живёт в RSS
 * подкаста, а не в файле. По сети это ничего не стоит — фид качается один раз
 * за сборку и лежит в памяти процесса (см. podcastFeed.mjs). Асинхронный
 * плагин разметки в проекте уже есть: remark-image-figure.mjs.
 */

const POSTS_DIR = new URL('../content/posts/', import.meta.url);

// Коллекция читается ОДИН раз на сборку. Постов 755, врезок будет много,
// и перечитывать папку на каждую значило бы сотни лишних обходов диска.
// Внутри одной сборки коллекция не меняется.
let кэшПостов = null;

/**
 * Все материалы с диска: `{ id, data, body }` — ровно та форма, которую ждут
 * общие модули (`getCardMedia`, `getPostTiming`, `postHref`).
 *
 * ДАТЫ ПРИВОДЯТСЯ К `Date` РУКАМИ. Схема коллекции сюда не дотягивается,
 * а `isPublished` спрашивает у `publishAt` метод `getTime`: приди туда строка,
 * отложенная публикация упала бы с невнятной ошибкой посреди разметки.
 */
function всеПосты() {
	if (кэшПостов) return кэшПостов;

	кэшПостов = new Map();
	for (const файл of readdirSync(fileURLToPath(POSTS_DIR))) {
		if (!файл.endsWith('.md')) continue;
		const id = файл.replace(/\.md$/, '');
		try {
			const сырое = readFileSync(fileURLToPath(new URL(файл, POSTS_DIR)), 'utf8');
			const разобрано = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(сырое);
			if (!разобрано) continue;

			// ПУСТЫЕ ПОЛЯ ЛЕЧИМ ТЕМ ЖЕ ПРАВИЛОМ, ЧТО И СХЕМА. Админка пишет
			// в незаполненное поле пустую строку, а `postHref` собирает адрес
			// через `??` — и пустая строка для него НЕ пустая: врезка выходила
			// со ссылкой `href=""`. Правило живёт одним местом, здесь только
			// вызов (см. src/lib/frontmatter.mjs).
			const data = normalizeFrontmatter(yaml.load(разобрано[1]) ?? {});

			кэшПостов.set(id, { id, data, body: разобрано[2] });
		} catch {
			// Кривой файл материала — не повод уронить разметку всех статей:
			// на нём всё равно упадёт схема коллекции, и скажет об этом внятно.
		}
	}
	return кэшПостов;
}

const текст = (значение) => ({ type: 'text', value: значение });
const эл = (tagName, properties, children = []) => ({ type: 'element', tagName, properties, children });

/** Стрелка внутрь сайта — или наружу, если материал лежит на чужом сайте. */
function стрелка(наружу) {
	return эл('span', { class: 'post-ref-arrow', 'aria-hidden': 'true' }, [текст(наружу ? '↗' : '→')]);
}

/** Треугольник кнопки «играть» — тот же, что у плеера выпуска и у панели. */
function значокИграть() {
	return эл('svg', { class: 'icon-play', viewBox: '0 0 24 24', 'aria-hidden': 'true' }, [
		эл('path', { d: 'M8 5v14l11-7z' }),
	]);
}

function значокПауза() {
	return эл('svg', { class: 'icon-pause', viewBox: '0 0 24 24', 'aria-hidden': 'true', hidden: true }, [
		эл('rect', { x: '7', y: '5', width: '4', height: '14', rx: '1' }),
		эл('rect', { x: '13', y: '5', width: '4', height: '14', rx: '1' }),
	]);
}

/** Подпись блока: `[ … ]` рисует CSS, здесь только слово. */
function подписьБлока(слово) {
	return эл('div', { class: 'body-label tech' }, [текст(слово)]);
}

/**
 * МЕТАСТРОКА — ТОТ ЖЕ ФОРМАТ, ЧТО У КАРТОЧКИ В ЛЕНТЕ (§10 дизайн-системы):
 * `подкаст · №152 · 43:07`, `подкаст · бонус · 01:30:18`, `статья · 4 мин
 * чтения`. Своего формата у врезки нет и быть не должно — иначе один
 * и тот же материал подписывался бы на сайте двумя способами.
 *
 * Капслок делает CSS, здесь текст строчными.
 *
 * @param {{id:string,data:any}} пост
 * @param {{meta:string}|null} время Ответ getPostTiming: длительность, время
 *   чтения или название чужой площадки — что именно, решает он, а не мы.
 * @param {boolean} сДлительностью В мини-плеере длительность уже стоит в строке
 *   контролов, и повторять её в нижней строке нельзя: один факт — одно место.
 */
function метастрока(пост, время, сДлительностью = true) {
	const раздел = sectionOf(пост.data.category);
	const подпись = categories.find((c) => c.id === раздел)?.labelOne ?? раздел;
	const части = [подпись.toLowerCase()];

	if (пост.data.category === 'bonus') части.push('бонус');
	// Номер есть только у обычного выпуска: у бонуса своей нумерации нет.
	else if (раздел === 'podcast') {
		const номер = episodeNumber(пост.id);
		if (номер) части.push(номер);
	}

	if (сДлительностью && время?.meta) части.push(время.meta);
	return части.join(' · ');
}

/** Картинка материала: два размера, форму задаёт сам материал. */
function миниатюра(медиа, форма, класс, sizes) {
	return эл('img', {
		class: класс,
		'data-shape': форма,
		src: медиа.src,
		srcset: медиа.srcset ?? undefined,
		sizes: медиа.srcset ? sizes : undefined,
		// АЛЬТ ПУСТОЙ НАМЕРЕННО: заголовок материала стоит рядом текстом,
		// и озвучивать его дважды незачем (§7 ТЗ).
		alt: '',
		loading: 'lazy',
		decoding: 'async',
	});
}

/** Блок А — врезка. Весь блок одна ссылка. */
function блокВрезка({ пост, медиа, время, подпись }) {
	const наружу = isExternalPost(пост.data);
	const заголовок = эл('div', { class: 'post-ref-title' }, [текст(пост.data.title)]);
	const мета = эл('div', { class: 'post-ref-meta tech' }, [текст(`${метастрока(пост, время)} `), стрелка(наружу)]);

	const свойства = {
		class: медиа ? 'post-ref' : 'post-ref no-cover',
		href: postHref(пост),
	};
	// Внешний материал открывается в новой вкладке — так же, как карточка
	// в ленте: два одинаковых на вид перехода не могут вести себя по-разному.
	if (наружу) {
		свойства.target = '_blank';
		свойства.rel = 'noopener noreferrer';
	}

	const дети = [подписьБлока(подпись)];

	if (медиа) {
		дети.push(
			эл('div', { class: 'post-ref-row' }, [
				миниатюра(медиа, mediaShape(пост.data.category), 'post-ref-thumb', '120px'),
				эл('div', { class: 'post-ref-text' }, [заголовок, мета]),
			]),
		);
	} else {
		// Без обложки — одной колонкой по оси чтения, без сдвига вбок и без
		// заглушки: §9.1 дизайн-системы запрещает её для материала прямо.
		дети.push(заголовок, мета);
	}

	return { hName: 'a', hProperties: свойства, hChildren: дети };
}

/** Блок Б — мини-плеер подкаста. */
function блокПлеер({ пост, медиа, время, подпись, выпуск }) {
	const адрес = postHref(пост);

	return {
		hName: 'div',
		hProperties: {
			class: 'post-play',
			// `data-episode-card` — ПРИЗНАК «ЗДЕСЬ ЕСТЬ ВЫПУСК И ЕГО КНОПКИ».
			// По нему панель плеера подключает блок и решает, показываться ли
			// самой (PlayerBar.astro). Своего кода воспроизведения у врезки нет
			// вовсе — и не должно быть: звук на странице один, `<audio>` один,
			// и двух источников не бывает по устройству, а не по договорённости.
			'data-episode-card': '',
			// ДАННЫЕ ВЫПУСКА ЛЕЖАТ АТРИБУТАМИ, а поведение навешивает скрипт —
			// ровно как у плеера на странице выпуска (EpisodePlayer.astro).
			// Убрать любой из этих атрибутов значит убрать всё поведение: блок
			// останется на месте и будет выглядеть исправным.
			'data-guid': пост.data.audioGuid,
			'data-audio': выпуск.audioUrl,
			'data-title': пост.data.title,
			'data-cover': медиа?.src ?? '',
			'data-link': адрес,
			'data-duration': String(выпуск.durationSec ?? ''),
		},
		hChildren: [
			подписьБлока(подпись),
			эл('a', { class: 'post-play-title', href: адрес }, [
				эл('span', { class: 'post-ref-title' }, [текст(пост.data.title)]),
			]),
			эл('div', { class: 'post-play-ctl' }, [
				// ХВАТЫ ДЛЯ СКРИПТА — ТЕ ЖЕ ИМЕНА, ЧТО У ПЛЕЕРА ВЫПУСКА (`ep-…`).
				// Не потому, что это врезка выпуска, а потому что подключает их
				// один и тот же код: заведи мы свои имена, у панели появился бы
				// второй набор селекторов, то есть вторая реализация подключения.
				// Вид при этом даёт второй класс рядом — `play`, `seek`, `tech`.
				эл('button', { type: 'button', class: 'ep-toggle play play--inset', 'aria-label': 'Слушать выпуск' }, [
					значокИграть(),
					значокПауза(),
				]),
				эл('span', { class: 'ep-time-current post-play-time tech' }, [текст('00:00')]),
				эл('input', {
					class: 'ep-range seek',
					type: 'range',
					min: '0',
					max: String(выпуск.durationSec ?? 0),
					step: '1',
					value: '0',
					'aria-label': 'Перемотка',
				}),
				эл('span', { class: 'ep-time-duration post-play-time tech' }, [текст(formatClock(выпуск.durationSec ?? 0))]),
			]),
			эл('div', { class: 'post-play-foot' }, [
				// Длительность здесь не повторяется — она уже стоит в строке
				// контролов выше. Один факт — одно место.
				эл('span', { class: 'post-ref-meta tech' }, [текст(метастрока(пост, время, false))]),
				эл('a', { class: 'post-play-go', href: адрес }, [
					эл('span', { class: 'post-play-meta tech' }, [текст('страница выпуска '), стрелка(false)]),
				]),
			]),
		],
	};
}

/** Блок В — фасад видеоэссе. */
function блокФасад({ пост, медиа, время, подпись, ролик }) {
	const адрес = postHref(пост);

	return {
		hName: 'div',
		hProperties: {
			class: 'post-face',
			// ДО НАЖАТИЯ ЮТЮБА НА СТРАНИЦЕ НЕТ ВООБЩЕ: ни iframe, ни скрипта,
			// ни картинки с их домена. Здесь лежит только идентификатор ролика,
			// а окно подставит скрипт по нажатию.
			'data-youtube': ролик,
		},
		hChildren: [
			подписьБлока(подпись),
			эл('div', { class: 'post-face-stage' }, [
				миниатюра(медиа, 'wide', 'post-face-frame', '(max-width: 760px) 100vw, 700px'),
				эл('button', { type: 'button', class: 'play play--inset post-face-play', 'aria-label': 'Смотреть видеоэссе' }, [
					значокИграть(),
				]),
			]),
			эл('div', { class: 'post-face-cap' }, [
				эл('span', { class: 'post-ref-title' }, [текст(пост.data.title)]),
				эл('a', { class: 'post-face-go', href: адрес }, [
					эл('span', { class: 'post-face-meta tech' }, [текст(`${время?.meta ?? метастрока(пост, время)} `), стрелка(false)]),
				]),
			]),
		],
	};
}

/**
 * ПОДПИСЬ ПО УМОЛЧАНИЮ ЗАВИСИТ ОТ ДЕЙСТВИЯ, и это решение отсюда, а не из ТЗ.
 * ТЗ называет базовым «ещё по теме» — оно верно для блока, который уводит.
 * Над блоком, который играет здесь, эта подпись читалась бы неправдой, и макет
 * `бака-перекрёстные-ссылки-финал.html` показывает над ними другие слова.
 * Взяты слова макета. Автор всё равно вписывает своё, когда захочет.
 */
const ПОДПИСЬ_ПО_УМОЛЧАНИЮ = {
	link: 'ещё по теме',
	podcast: 'послушать прямо здесь',
	videoessay: 'посмотреть прямо здесь',
};

/**
 * ЖАЛОБА НА БИТУЮ ВРЕЗКУ. Громкая, но НЕ бросок — и это замер, а не вкус.
 *
 * ЗДЕСЬ СТОЯЛ `throw`, И ОН НЕ ДЕЛАЛ ОБЕЩАННОГО. Замер 31 августа 2026:
 * загрузчик коллекции ловит ошибку разметки сам, `astro build` возвращает 0,
 * выкладка проходит — А ТЕКСТ МАТЕРИАЛА ПРОПАДАЕТ СО СТРАНИЦЫ ЦЕЛИКОМ,
 * вместе с абзацами вокруг врезки. То есть бросок не останавливал сборку,
 * зато уничтожал статью, и увидеть это можно было только глазами.
 *
 * НАСТОЯЩИЙ ЗАСЛОН ЖИВЁТ В scripts/check-post-refs.mjs и стоит ПЕРВЫМ шагом
 * `npm run build`, до сборки: он и роняет выкладку кодом 1. Здесь — вторая
 * линия на случай, если сборку запустили в обход: жалоба в лог и один
 * пропавший блок вместо одной пропавшей статьи.
 *
 * ФАЙЛ СТАТЬИ НАЗЫВАЕТСЯ ОБЯЗАТЕЛЬНО. Врезка — одна строчка посреди длинного
 * текста; без имени файла её пришлось бы искать по всему архиву.
 */
function падать(узел, файл, беда) {
	console.error(`[врезка на материал] ${файл?.path ?? 'файл статьи не назван'}: ${беда}`);
	// Блок убираем, ТЕКСТ СТАТЬИ ОСТАВЛЯЕМ ЦЕЛЫМ. Пустой узел, а не бросок.
	узел.data = { hName: 'span', hProperties: {}, hChildren: [] };
}

export default function remarkPostRef() {
	return async (дерево, файл) => {
		const врезки = [];
		visit(дерево, 'leafDirective', (узел) => {
			if (узел.name === 'material') врезки.push(узел);
		});
		if (врезки.length === 0) return;

		const посты = всеПосты();

		for (const узел of врезки) {
			const атрибуты = узел.attributes ?? {};
			const id = String(атрибуты.id ?? '').trim();

			if (!id) {
				падать(узел, файл, 'у врезки не выбран материал — откройте её в админке и выберите, или уберите блок');
				continue;
			}

			const пост = посты.get(id);
			if (!пост) {
				падать(
					узел,
					файл,
					`материала «${id}» на сайте нет. Файла src/content/posts/${id}.md не существует — материал удалили, ` +
						'переименовали или в адресе опечатка. Откройте врезку в админке и выберите материал заново.',
				);
				continue;
			}

			const режим = атрибуты.mode === 'play' ? 'play' : 'link';

			if (режим === 'play' && !canPlayInline(пост)) {
				падать(
					узел,
					файл,
					`у врезки на «${пост.data.title}» (${id}) выбрано «Играет здесь», а играть нечего: ` +
						`${whyCannotPlay(пост)}. Поставьте «Ведёт на материал».`,
				);
				continue;
			}

			// МАТЕРИАЛ ЕСТЬ, НО СТРАНИЦЫ У НЕГО ПОКА НЕТ. Сборку не роняем:
			// снять материал с публикации — обычная работа заказчика в админке,
			// и падающая от неё сборка остановила бы весь сайт из-за одной
			// галочки. Но и молчать нельзя — ссылка ведёт в никуда.
			// Так же устроен показ битых внутренних ссылок в post-links-integration.
			if (!isPublished(пост.data)) {
				console.warn(
					`[врезка на материал] ${файл?.path ?? 'пост'}: врезка ведёт на «${пост.data.title}» (${id}), ` +
						'а он не опубликован — страницы на сайте нет, ссылка ведёт в никуда. ' +
						'Опубликуйте материал или уберите врезку.',
				);
			}

			const время = await getPostTiming(пост);
			const медиа = await getCardMedia(пост);
			const подпись =
				unescapeAttr(атрибуты.label ?? '').trim() ||
				ПОДПИСЬ_ПО_УМОЛЧАНИЮ[режим === 'play' ? пост.data.category : 'link'] ||
				ПОДПИСЬ_ПО_УМОЛЧАНИЮ.link;

			if (режим === 'play' && пост.data.category === 'podcast') {
				const выпуск = await findEpisodeByGuid(пост.data.audioGuid);
				if (!выпуск?.audioUrl) {
					падать(
						узел,
						файл,
						`у врезки на «${пост.data.title}» (${id}) выбрано «Играет здесь», а звука нет: ` +
							'выпуск не нашёлся в RSS подкаста. Проверьте поле «Выпуск в RSS» у материала.',
					);
					continue;
				}
				узел.data = блокПлеер({ пост, медиа, время, подпись, выпуск });
				continue;
			}

			if (режим === 'play' && пост.data.category === 'videoessay') {
				const ролик = getYoutubeVideoId(/::video\{[^\n]*youtube="([^"]*)"/.exec(пост.body)?.[1] ?? '');
				if (!ролик) {
					падать(
						узел,
						файл,
						`у врезки на «${пост.data.title}» (${id}) выбрано «Играет здесь», а ролика нет: ` +
							'в тексте видеоэссе не нашлось блока «Видео» со ссылкой на YouTube.',
					);
					continue;
				}
				// КАДРА НЕТ — ФАСАДА НЕТ. Это единственная разрешённая подмена
				// (§5.3 ТЗ): вместо фасада ставится обычная врезка. Тихой её
				// не назовёшь — она сказана в ТЗ и говорится в лог.
				if (!медиа) {
					console.warn(
						`[врезка на материал] ${файл?.path ?? 'пост'}: у видеоэссе «${пост.data.title}» (${id}) нет кадра — ` +
							'вместо фасада поставлена обычная врезка. Добавьте материалу обложку, и фасад появится сам.',
					);
					узел.data = блокВрезка({ пост, медиа, время, подпись: ПОДПИСЬ_ПО_УМОЛЧАНИЮ.link });
					continue;
				}
				узел.data = блокФасад({ пост, медиа, время, подпись, ролик });
				continue;
			}

			узел.data = блокВрезка({ пост, медиа, время, подпись });
		}
	};
}
