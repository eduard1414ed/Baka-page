/**
 * Маркировка рекламы (тз/10.7): «Реклама. ООО «…», ИНН …, erid: …».
 *
 * ПОЛЕ ПОСТА, А НЕ ТЕКСТ. Строка лежит во фронтматтере (`adLabel`), а не в теле:
 * так её не сломать правкой текста, не потерять при импорте и не отправить
 * случайно в поиск. Поле пустое — блока нет вовсе, и на нерекламных постах
 * не меняется ничего.
 *
 * ПОЧЕМУ ВСТАВЛЯЕТ ПЛАГИН, А НЕ СТРАНИЦА. Блок обязан встать СБОКУ ОТ ПЕРВОЙ
 * СТРОКИ ТЕКСТА, а не в начале материала: у поста первым блоком бывает широкая
 * картинка, видео или галерея — они шире читальной колонки и вылезают ровно
 * в ту полосу справа, где висит маркировка. Страница вставить блок «перед
 * текстом» не может: она видит тело материала одним куском `<Content />`
 * и не знает, где внутри него кончилось медиа. Поэтому место выбирается здесь,
 * по дереву разметки. Решение заказчика 10 августа 2026.
 *
 * ИДЁТ ПОСЛЕ remarkEpisodeCover И ДО remarkImageFigure, и это важно с обеих
 * сторон: первый убирает из тела обложку выпуска (иначе маркировка встала бы
 * ПОД неё, а на странице этой картинки нет вовсе), второй превращает `::image`
 * в готовую вёрстку (после него узла-директивы уже не осталось бы, и медиа
 * стало бы неотличимо от текста).
 *
 * ВИД — технический слой без капслока, `--muted`; описание живёт в стилях
 * страницы материала (`.ad-mark` в src/pages/posts/[slug].astro). Разметку
 * плагина стили компонента не видят, поэтому правила там писаны `:global`.
 *
 * В ПОИСК НЕ ИДЁТ: `data-pagefind-ignore`. Иначе «ЭКСМО», «ИНН» и erid полезли
 * бы в цитаты выдачи, а запрос «эксмо» начал бы находить пост как материал про
 * издательство — тот же случай, что с блоком соцсетей и врезкой ссылок.
 * В описание для поисковика и в превью ссылки маркировка не попадает по другой
 * причине и без всякой пометки: описание строится из ТЕЛА поста
 * (src/lib/excerpt.mjs), а строка лежит в поле.
 */

/** Абзац, в котором нет ничего, кроме картинки, — это медиа, а не текст. */
function isImageOnly(node) {
	if (node.type !== 'paragraph') return false;
	const meaningful = node.children.filter((child) => child.type !== 'text' || child.value.trim() !== '');
	return meaningful.length === 1 && meaningful[0].type === 'image';
}

/**
 * Первый узел, который читается ТЕКСТОМ. Директивы (`::image`, `::video`,
 * `::link`, `::label`) и одиночные картинки пропускаем: маркировка должна
 * встать сбоку от строки, а не сбоку от кадра.
 */
const TEXT_BLOCKS = new Set(['paragraph', 'heading', 'list', 'blockquote', 'table']);

function firstTextIndex(children) {
	for (let i = 0; i < children.length; i++) {
		const node = children[i];
		if (!TEXT_BLOCKS.has(node.type)) continue;
		if (isImageOnly(node)) continue;
		return i;
	}
	return -1;
}

export default function remarkAdLabel() {
	return (tree, file) => {
		const text = (file?.data?.astro?.frontmatter?.adLabel ?? '').trim();
		if (!text) return;

		let at = firstTextIndex(tree.children);

		// Текста в материале нет вовсе — одни картинки или одно видео.
		// Прятать маркировку нельзя (закон требует видимой пометки), поэтому
		// ставим её первой и говорим об этом в сборку: ломаться громко лучше,
		// чем тихо врать.
		if (at < 0) {
			at = 0;
			console.warn(
				`[маркировка рекламы] ${file?.path ?? 'пост'}: в материале нет ни одного абзаца текста, ` +
					'пометка поставлена перед первым блоком. Проверьте, что она видна и ни на что не наехала.',
			);
		}

		tree.children.splice(at, 0, {
			type: 'paragraph',
			data: {
				hName: 'aside',
				hProperties: { class: 'ad-mark tech', 'data-pagefind-ignore': true },
			},
			children: [{ type: 'text', value: text }],
		});
	};
}
