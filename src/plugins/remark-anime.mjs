const ANIME_CONTENT_DIR = new URL('../content/anime/', import.meta.url);

// Справочник читается ОДИН раз на сборку и матчер строится тоже один: постов
// 1594, тайтлов 53, и перечитывать одно другим значило бы сотни лишних
// обращений к диску. Внутри одной сборки справочник не меняется.
let matcherCache = null;
let entriesCache = null;

// Справочник, разобранный один раз на сборку. Просят его двое — матчер (по чему
// искать) и нумерация (какой номер поставить сноской), и читать диск дважды
// ради этого незачем.
function catalogEntries() {
	if (entriesCache) return entriesCache;

	const entries = [];
	for (const file of readdirSync(fileURLToPath(ANIME_CONTENT_DIR))) {
		if (!file.endsWith('.json')) continue;
		try {
			const data = JSON.parse(readFileSync(fileURLToPath(new URL(file, ANIME_CONTENT_DIR)), 'utf8'));
			if (data?.id) entries.push({ id: data.id, data });
		} catch {
			// Кривой файл справочника — не повод уронить разметку всех постов;
			// на нём всё равно упадёт схема коллекции, и скажет об этом внятно.
		}
	}

	entriesCache = entries;
	return entries;
}

function animeMatcher() {
	if (matcherCache) return matcherCache;

	// `apply`: это ТЕКСТЫ ПОСТОВ, тут галочка «только в кавычках» действует.
	matcherCache = buildAnimeMatcher(catalogEntries(), { quotes: 'apply', speech: false });
	return matcherCache;
}

// СПИСОК ID СПРАВОЧНИКА. Отдельно от матчера потому, что матчер знает только
// тайтлы с названием, а метка `:anime[…]{id="x"}` может стоять на любом файле.
//
// ОТДАЁМ ВСЕГДА НОВОЕ МНОЖЕСТВО, И ЭТО НЕ ПРИДИРКА К СТИЛЮ. Разметка ниже
// вычёркивает из полученного списка размеченное (`pending.delete`), а первая
// редакция этой функции возвращала сам кэш — то есть каждый пост выгрызал
// из него свои тайтлы, и к сотому посту в справочнике «оставалось» 29 названий
// вместо 53, к тысячному ноль. Ссылки в постах пропали ВСЕ, сборка при этом
// прошла с кодом 0, а лог наполнился строчками «такого тайтла в справочнике
// нет» про тайтлы, которые в нём есть. Кэшируем массив, а Set строим заново:
// 53 строки на пост — ничто, а спорить с мутацией снаружи нечем.
let idsCache = null;

function catalogIds() {
	if (!idsCache) {
		idsCache = readdirSync(fileURLToPath(ANIME_CONTENT_DIR))
			.filter((file) => file.endsWith('.json'))
			.map((file) => file.replace(/\.json$/, ''));
	}
	return new Set(idsCache);
}

// Про один и тот же пропавший тайтл говорим один раз на сборку, а не на каждый
// пост: страница выпуска и страница тайтла разбирают одно и то же тело дважды.
const warnedMissing = new Set();

function warnUnknownAnime(id, postId) {
	const key = id + ' ' + postId;
	if (warnedMissing.has(key)) return;
	warnedMissing.add(key);
	console.warn(
		`[тайтлы] «${postId}»: в тексте метка на тайтл «${id}», а в справочнике его нет — ` +
			`название осталось обычным текстом, ссылки не будет. Если тайтл удалили из каталога, ` +
			`так и задумано; если он ещё не добран роботом, ссылка появится после его прохода.`,
	);
}

// НОМЕР СНОСКИ — ТОТ ЖЕ, ЧТО КИКЕРОМ В МАРКЕ (решение заказчика 31 августа
// 2026, тз/тз-ссылка-на-аниме.md §2.2). Считает его общий animeCatalog.mjs —
// тот самый, что нумерует каталог и обе формы марки. Своего счёта тут нет
// намеренно: копии разъехались бы молча, и один тайтл получил бы в строке одну
// цифру, а в марке под текстом другую. Заметить это можно было бы только сверив
// две части одной страницы глазами.
//
// В СТРОКЕ НОМЕР БЕЗ ВЕДУЩИХ НУЛЕЙ («⁴⁷»), в марке остаётся «CAT. 047»:
// там это подпись поля каталога, здесь — сноска в тексте.
let codesCache = null;

function catalogNumber(id) {
	if (!codesCache) codesCache = catalogCodes(catalogEntries());
	// У тайтла, чей файл не разобрался, номера нет — тогда сноски просто
	// не будет. Ссылка при этом остаётся: `known` считает файлы, а не разбор.
	return codesCache.get(id)?.order ?? null;
}

// СТРОЕНИЕ ССЫЛКИ. Название и номер — РАЗНЫЕ элементы, и это не украшение:
// подчёркивание висит на названии, а не на самой ссылке, потому что
// `text-decoration` от предка у потомка снять нельзя — линия протянулась бы
// и под цифрами (тз §2.2).
//
// У номера две пометки, и обе по делу:
//   `aria-hidden` — диктору цифра не говорит ничего сверх самой ссылки,
//     а «Фрирен четырнадцать» посреди фразы это мусор в речи;
//   `data-pagefind-ignore` — иначе номер уехал бы в поисковый индекс вплотную
//     к названию, как уже уезжали счётчик галереи и подпись кнопки спойлера.
const LINK_CLASS = 'anime-mention anime-mention--text';
const NAME_CLASS = 'anime-mention-name';
const NUM_CLASS = 'anime-mention-num';

// КАВЫЧКИ ЗАБИРАЮТСЯ ВНУТРЬ ССЫЛКИ (решение заказчика 31 августа 2026).
//
// Надстрочный номер стоит СРАЗУ ЗА названием, поэтому у названия в кавычках он
// оказывался ВНУТРИ них: «Моб Психо 100³⁶⁵». Читается это опечаткой — цифра
// влезла в чужое название. Лечится не снятием кавычек (их убирать заказчик
// как раз не хочет), а тем, что ссылка забирает их себе: подчёркивание идёт
// под «…», номер встаёт за закрывающей — «Моб Психо 100»³⁶⁵.
//
// ГДЕ СТОЯТ КАВЫЧКИ, СПРАШИВАЕМ У ОБЩЕГО ПРАВИЛА (`indexOfQuoteNear`), того же,
// по которому работает галочка «только в кавычках». Своя проверка разошлась бы
// с ним молча: у неё был бы свой список кавычек и свой хвост.
//
// ХВОСТ В 8 ЗНАКОВ БЕЗ БУКВ — часть того же правила, и он тут кстати:
// «Магическая битва 2» отдаёт ссылке всю фразу вместе с номером сезона.
//
// А ЕСЛИ КАВЫЧКА ОТКРЫЛАСЬ, НО НЕ ЗАКРЫЛАСЬ — НОМЕРА НЕ БУДЕТ ВОВСЕ, и это
// не мелочь, а признание. «Истребителя демонов: Бесконечная крепость» —
// отдельный фильм, а ссылкой стало короткое название сериала: сработало
// правило «искать название до двоеточия». Номер — это АДРЕС КАРТОЧКИ
// справочника, и ставить его внутрь чужого названия значит утверждать, что
// в кавычках стоит эта карточка. Она там не стоит.
//
// Подчёркивание, переход и марка при наведении остаются: сериал в этой фразе
// действительно назван, увести читателя на его страницу честно. Врёт только
// цифра, её и убираем. Таких мест в архиве 10 против 999 обычных, и все десять
// исчезнут сами, как только полные названия заведут в справочнике: ссылкой
// станет вся фраза (длинное название забирает кусок раньше короткого,
// см. сортировку в animeMentions.mjs).
/**
 * @returns {{ начало: number, конец: number, частьФразы: boolean }}
 *   границы ссылки с кавычками и признак «кавычки чужие».
 */
function сКавычками(текст, начало, конец) {
	const открывающая = indexOfQuoteNear(текст, начало - 1, -1);
	if (открывающая === -1) return { начало, конец, частьФразы: false };

	// СТОРОНА КАВЫЧКИ ТУТ РЕШАЕТ ВСЁ. Слева от упоминания сплошь и рядом стоит
	// ЗАКРЫВАЮЩАЯ кавычка соседнего тайтла — «Боруто», «Фури-кури», Приоритет… —
	// и принять её за начало фразы значит отнять номер у невиновного. Так
	// и случилось на первом же прогоне: три ссылки из 1317.
	const закрывающая = indexOfQuoteNear(текст, конец, 1);
	if (закрывающая === -1) return { начало, конец, частьФразы: isOpeningQuote(текст[открывающая]) };

	return { начало: открывающая, конец: закрывающая + 1, частьФразы: false };
}

function numberProps() {
	return { class: NUM_CLASS, 'aria-hidden': 'true', 'data-pagefind-ignore': 'true' };
}

function autoLinkNode(id, text, безНомера = false) {
	const number = безНомера ? null : catalogNumber(id);
	const children = [
		{ type: 'element', tagName: 'span', properties: { class: NAME_CLASS }, children: [{ type: 'text', value: text }] },
	];

	if (number !== null) {
		children.push({
			type: 'element',
			tagName: 'sup',
			properties: numberProps(),
			children: [{ type: 'text', value: String(number) }],
		});
	}

	return {
		type: 'animeAutoLink',
		data: {
			hName: 'a',
			hProperties: { href: `/anime/${id}`, class: LINK_CLASS },
			hChildren: children,
		},
	};
}

/**
 * То же строение для метки `:anime[…]`, но обёртка тут mdast-овая, а не готовая
 * разметка. Внутри метки лежит ДЕРЕВО markdown — название бывает набрано
 * курсивом, — и подмени мы его готовым текстом, разметка внутри пропала бы.
 */
function mentionChildren(id, children, слева = '', справа = '', безНомера = false) {
	const number = безНомера ? null : catalogNumber(id);
	const внутри = [
		...(слева ? [{ type: 'text', value: слева }] : []),
		...children,
		...(справа ? [{ type: 'text', value: справа }] : []),
	];
	const wrapped = [
		{ type: 'animeMentionName', children: внутри, data: { hName: 'span', hProperties: { class: NAME_CLASS } } },
	];

	if (number !== null) {
		wrapped.push({
			type: 'animeMentionNum',
			children: [],
			data: { hName: 'sup', hProperties: numberProps(), hChildren: [{ type: 'text', value: String(number) }] },
		});
	}

	return wrapped;
}

/**
 * `:anime[Текст]{id="frieren" source="shikimori" source-id="9253"}` — метка тайтла
 * в тексте, ставит кнопка «Аниме» в админке (public/admin/index.html). `id` — slug
 * тайтла в справочнике (src/content/anime/), `source`/`source-id` нужны только
 * роботу, который добирает данные тайтла после публикации (scripts/sync-anime.mjs),
 * сам сайт их не читает.
 *
 * Первое упоминание каждого id в посте становится ссылкой на /anime/id,
 * повторные — обычный текст (см. тз/03-тайтлы.md, п. 4).
 *
 * ЧТО ИМЕННО КЛАДЁТСЯ В СТРАНИЦУ (тз/тз-ссылка-на-аниме.md, §2.2):
 *
 *   <a href="/anime/frieren" class="anime-mention anime-mention--text"
 *     ><span class="anime-mention-name">Фрирен</span
 *     ><sup class="anime-mention-num" aria-hidden="true"
 *            data-pagefind-ignore="true">14</sup></a>
 *
 * КЛАССА ДВА, И ВТОРОЙ НУЖЕН НЕ ДЛЯ КРАСОТЫ. `anime-mention` значит «ссылка
 * на страницу тайтла» — его же ставит расшифровка выпуска (Transcript.astro),
 * и по нему считает нажатия аналитика. `anime-mention--text` значит «и она
 * стоит в тексте материала»: вид (чернила, волосяная линия, сноска) достаётся
 * только ей. В расшифровке ссылка выглядит как прежде — решение заказчика
 * 31 августа 2026; там же 1066 таких ссылок, и сноска посреди живой речи
 * читалась бы сором.
 *
 * ИЩЕТСЯ ВЕСЬ СПРАВОЧНИК, А НЕ ТОЛЬКО ТАЙТЛЫ ЭТОГО ПОСТА (хвост 44, решение
 * заказчика 11 августа 2026). Любое название из справочника, встреченное
 * в тексте, становится ссылкой — ровно так же, как это давно работает
 * в расшифровках выпусков. Раньше искались только тайтлы, стоящие в поле
 * «Тайтлы поста», то есть разметка требовала, чтобы тайтл сначала отметили
 * руками, — а весь смысл в обратном.
 *
 * Замер перед включением: 410 новых ссылок в 318 постах, ложных 15 (3,7 %),
 * и все 15 у двух тайтлов — «Апокалипсис: Отель» (ловилось слово «апокалипсис»)
 * и «Акира» (имена людей: Акира Хирата, Акира Ямаока). Оба получили галочку
 * «только в кавычках», и это единственный способ отменить ложную ссылку в посте:
 * поштучной отмены, как в расшифровках, у поста нет — там якорь стоит на номере
 * реплики, а реплик у поста не бывает.
 *
 * ПО ЧЕМУ ИЩЕМ — НЕ НАШЕ ДЕЛО, И ЭТО ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА.
 * Список названий и правило совпадения берутся у `src/lib/animeMentions.mjs`,
 * того же кода, которым размечаются расшифровки выпусков. Значит сюда сами
 * собой приходят: оба списка вариантов написания (ручной `aliases` и падежный
 * `aliasesAuto`), кусок названия до двоеточия, нечувствительность к регистру
 * и к «е»/«ё», границы слова и галочка «только в кавычках».
 *
 * ДО ЭТАПА 11, ЧАСТИ B, ЗДЕСЬ ЛЕЖАЛА СВОЯ КОПИЯ ЭТОГО ПРАВИЛА — и она была
 * разъехавшейся: искала только `titleRu` и `titleOriginal`, точным совпадением
 * буква в букву, о вариантах написания не знала вовсе. «в Ходячем замке»
 * в посте ссылкой не становилось, хотя ровно эта форма записана у тайтла
 * в карточке. Заметить копию было нельзя: варианты заполнены у двух тайтлов
 * из 53, и расхождению негде было случиться (СТАТУС.md, хвост 45).
 *
 * ЧТО ОСТАЛОСЬ СВОИМ. Одно правило, и оно про пост, а не про названия:
 * ссылкой становится ПЕРВОЕ упоминание каждого тайтла, дальше обычный текст.
 *
 * СПИСОК ТАЙТЛОВ ПОСТА СЧИТАЕТСЯ ЕЩЁ В ОДНОМ МЕСТЕ, и это неизбежно:
 * `animeMentionedInPostText` в src/lib/animeMentionIndex.mjs. Ему нужен только
 * СПИСОК — для марок под текстом и для страницы тайтла, — и работает он
 * с плоским текстом, а не с деревом markdown. Список названий и правило
 * совпадения у обоих одни (общий матчер), а разойтись они могут только
 * на названии, разорванном разметкой посередине («**Атака** титанов»): его
 * увидит тот и не увидит этот. Замер 11 августа 2026 по всем 1595 постам:
 * таких мест ноль. МЕНЯЕТЕ ЗДЕСЬ — ПОСМОТРИТЕ И ТАМ.
 *
 * `::anime-ref{id="" source="" source-id=""}` — служебная метка без видимого
 * текста, ничего не выводит на странице. Ставит поле «Тайтлы поста» в CMS
 * (public/admin/index.html, preSave), когда через него добавляют тайтл,
 * которого ещё нет в справочнике: сам по себе тайтл в тексте не упомянут
 * (иначе не нужно было бы это поле), но роботу на GitHub Actions
 * (scripts/sync-anime.mjs) нужно откуда-то узнать source/source-id, чтобы
 * его найти — эта метка и есть то место.
 *
 * МЕТКА НА ТАЙТЛ, КОТОРОГО В СПРАВОЧНИКЕ НЕТ, ССЫЛКОЙ НЕ СТАНОВИТСЯ.
 * Раньше становилась — безусловно, не спрашивая справочник, — и вела на 404.
 * Случаев два, и оба обычные: тайтл отметили кнопкой «Аниме» раньше, чем робот
 * донабрал его в справочник (это штатное состояние, так и задумано выше),
 * и **тайтл удалили из каталога в админке**. Второе стало возможным 11 августа
 * 2026, когда удаление там включили.
 *
 * Сборка при этом НЕ падает — проверено удалением настоящего тайтла, на который
 * ссылается опубликованный пост: страниц становится на одну меньше, и всё.
 * То есть без этой проверки читатель молча получал бы ссылку в никуда, а никто
 * бы об этом не узнал. Поэтому: текст остаётся текстом, а сборка говорит вслух —
 * и только про НЕ-черновики, иначе 1568 привезённых черновиков утопили бы лог.
 */
export default function remarkAnime() {
	return (tree, file) => {
		const seen = new Set();
		const known = catalogIds();
		const frontmatter = file.data?.astro?.frontmatter ?? {};
		const isDraft = frontmatter.draft === true;
		const postId = frontmatter.title ?? file.path ?? 'пост без заголовка';

		// ОТМЕНА ЛОЖНОЙ ССЫЛКИ В ЭТОМ ПОСТЕ (хвост 50, решение заказчика
		// 11 августа 2026). Запись «убрать тайтл целиком» из поля «Упоминания
		// тайтлов» (`animeId:*`) действует не только в расшифровке, но и в тексте:
		// название остаётся обычным текстом.
		//
		// ЯКОРЬ — «ТАЙТЛ × ПОСТ», И ПОЗИЦИЯ В ТЕКСТЕ ТУТ НЕ ГОДИТСЯ. В расшифровке
		// якорь стоит на номере реплики и позиции в ней, и работает это потому,
		// что текст расшифровки руками не правят. Тело поста правят в админке
		// постоянно — позиция сдвинулась бы молча. А «тайтл × пост» достаточен:
		// ссылкой становится ПЕРВОЕ упоминание тайтла, то есть на пост приходится
		// ровно одна ссылка на тайтл.
		//
		// ПОШТУЧНЫЕ ЯКОРЯ (`k-on:12,45.83`) сюда не относятся вовсе: они про
		// номера реплик, а реплик у поста нет.
		//
		// ТО ЖЕ САМОЕ ОБЯЗАН СПРОСИТЬ `animeMentionedInPostText`, иначе ссылка
		// из текста пропала бы, а пост на странице тайтла остался.
		const hiddenHere = new Set(parseMentionExceptions(frontmatter.mentionsHidden).hiddenAnime);

		visit(tree, 'textDirective', (node, index, parent) => {
			if (node.name !== 'anime' || !parent || typeof index !== 'number') return;

			const id = node.attributes?.id;
			if (!id) return;

			// Тайтл убран из этого поста руками — даже размеченный кнопкой
			// «Аниме» остаётся текстом. Иначе отмена работала бы только
			// на автоматической разметке, и это выглядело бы поломкой.
			if (hiddenHere.has(id)) {
				parent.children.splice(index, 1, ...node.children);
				return index;
			}

			// Такого тайтла в справочнике нет — оставляем текст текстом.
			if (!known.has(id)) {
				if (!isDraft) warnUnknownAnime(id, postId);
				parent.children.splice(index, 1, ...node.children);
				return index;
			}

			if (seen.has(id)) {
				// Не первое упоминание — заменяем узел его же содержимым, без ссылки.
				parent.children.splice(index, 1, ...node.children);
				return index;
			}

			seen.add(id);

			// У метки `:anime[…]` кавычки лежат не внутри узла, а в СОСЕДНИХ
			// текстовых узлах — их приходится переносить внутрь руками.
			// Правило то же самое, просто спрошено у двух строк порознь:
			// слева смотрим назад от последнего знака, справа вперёд от первого.
			const пред = parent.children[index - 1];
			const след = parent.children[index + 1];
			const открывающая =
				пред?.type === 'text' ? indexOfQuoteNear(пред.value, пред.value.length - 1, -1) : -1;
			const закрывающая = след?.type === 'text' ? indexOfQuoteNear(след.value, 0, 1) : -1;

			let слева = '';
			let справа = '';
			if (открывающая !== -1 && закрывающая !== -1) {
				слева = пред.value.slice(открывающая);
				справа = след.value.slice(0, закрывающая + 1);
				пред.value = пред.value.slice(0, открывающая);
				след.value = след.value.slice(закрывающая + 1);
			}

			// Кавычка ОТКРЫЛАСЬ, а закрылась не рядом — метка стоит на ЧАСТИ фразы
			// в кавычках, и номер был бы неправдой. Слово «открылась» тут ключевое:
			// закрывающая кавычка соседнего тайтла началом фразы не является.
			// Довод целиком у `сКавычками`.
			const частьФразы =
				открывающая !== -1 && закрывающая === -1 && isOpeningQuote(пред.value[открывающая]);

			node.data = { hName: 'a', hProperties: { href: `/anime/${id}`, class: LINK_CLASS } };
			node.children = mentionChildren(id, node.children, слева, справа, частьФразы);
		});

		// Служебная метка (см. описание выше) — ничего не показываем, просто убираем узел.
		visit(tree, 'leafDirective', (node, index, parent) => {
			if (node.name !== 'anime-ref' || !parent || typeof index !== 'number') return;
			parent.children.splice(index, 1);
			return index;
		});

		// Кого ещё можно разметить: весь справочник минус то, что уже отмечено
		// меткой в тексте руками. Тайтл из поля «Тайтлы поста» отдельного
		// упоминания тут не требует — он и так входит в справочник.
		const matcher = animeMatcher();
		if (matcher.length === 0) return;

		const pending = catalogIds();
		for (const id of seen) pending.delete(id);
		for (const id of hiddenHere) pending.delete(id);
		if (pending.size === 0) return;

		// ССЫЛКУ ВНУТРЬ ССЫЛКИ СТАВИТЬ НЕЛЬЗЯ. Название тайтла запросто окажется
		// подписью авторской ссылки («читайте про Атаку титанов»), и обёрнутое
		// нашим `<a>` оно дало бы вложенные ссылки: разметка недопустимая, а на
		// странице у слова пропадает нажатие целиком. До части B случай был
		// почти невозможен (искалось точное совпадение с названием), теперь
		// ищутся ещё и падежные формы, и он стал обычным.
		const insideLink = new Set();
		visit(tree, ['link', 'linkReference'], (node) => {
			visit(node, 'text', (child) => insideLink.add(child));
		});

		visit(tree, 'text', (node, index, parent) => {
			if (!parent || typeof index !== 'number' || pending.size === 0) return;
			if (insideLink.has(node)) return;

			const hit = findMentions(node.value, matcher).find((mention) => pending.has(mention.id));
			if (!hit) return;

			const границы = сКавычками(node.value, hit.start, hit.end);
			const before = node.value.slice(0, границы.начало);
			const after = node.value.slice(границы.конец);

			const replacement = [];
			if (before) replacement.push({ type: 'text', value: before });
			replacement.push(autoLinkNode(hit.id, node.value.slice(границы.начало, границы.конец), границы.частьФразы));
			if (after) replacement.push({ type: 'text', value: after });

			parent.children.splice(index, 1, ...replacement);
			pending.delete(hit.id);

			return index;
		});
	};
}
