// Своего раздела ему не надо, а рядом с выпусками он на месте.
//
// `description` — что написано в выдаче поисковика под ссылкой на раздел
// и в превью, когда ссылку на раздел кидают в чат (тз/06, шаг 8). Своё у каждой
// категории: одинаковое описание на всех страницах поисковик считает признаком
// пустого сайта. Лежит здесь, рядом с подписью, чтобы не разъехалось.
//
// ПОДПИСЕЙ ДВЕ, И ЭТО НЕ ДУБЛИРОВАНИЕ — это два разных высказывания.
//
//   label    — название РАЗДЕЛА: «Статьи», «Заметки». Стоит во вкладках ленты,
//              заголовком раздела, в ссылке «← назад» со страницы материала
//              и значением фильтра в поиске. Множественное число.
//   labelOne — название ОДНОГО материала: «Статья», «Заметка». Стоит только
//              в метастроке карточки, где речь идёт про конкретную вещь:
//              `[ ЗАМЕТКА ] · 4 МИН ЧТЕНИЯ`.
//
// У «Подкаста», «Видеоэссе» и «Бонуса» они совпадают. Написаны всё равно обе,
// а не выведены запасным правилом «нет своей — бери общую»: молчаливое правило
// однажды подставит множественное число новой категории, и заметить это
// можно будет только глазами на карточке.
//
// ЕЩЁ ДВЕ ПОДПИСИ ПОЯВИЛИСЬ ВМЕСТЕ С АРХИВОМ (часть 4 дизайна), и обе — про
// русское согласование, которого из `label` не вывести никаким правилом:
//
//   countForms — три формы для числа: «143 выпуска», «1 статья», «38 заметок».
//                Стоит в строке счёта под заголовком архива и раздела.
//                Русскому числительному нужно ровно три формы, двумя
//                не обойтись, а `label` не даёт ни одной из них.
//   labelMany  — множественное число в именительном, строчными: «подкасты».
//                Стоит ровно в одном месте — в ссылке «Все подкасты в архиве»
//                внизу подборки на главной. Не то же, что `label` («Подкаст»),
//                и не то же, что `countForms` («выпусков»).
//
// Выглядит как четыре подписи на одну категорию, и это осознанно: у каждой
// ровно одно место применения, и все четыре живут здесь, рядом. Разложи их
// по компонентам — и таблица форм разъедется со списком категорий ровно тогда,
// когда кто-нибудь заведёт шестую.
//
// `intro` — ПОДВОДКА В ШАПКЕ РАЗДЕЛА, и это НЕ `description`. Разные тексты
// для разных читателей: `description` уходит в метатег и в выдачу поисковика
// (до 160 знаков, с названием подкаста), `intro` человек видит глазами
// на странице. Сначала на странице стояло описание для поисковика, и вышел
// дефект: у разделов оно разной длины, поэтому шапка была то на две строки,
// то на три, и при переходе по вкладкам весь список под ней прыгал.
//
// ДЛИНА ПОДВОДКИ — ЧАСТЬ ВЁРСТКИ, а не вкусовое: держать в 55–95 знаках.
// В этом диапазоне подводка занимает две строки на широком экране и три
// на узком у ЛЮБОГО раздела, и шапка перестаёт менять высоту при переключении.
// Выйдете за 95 — вернётся прыжок, и заметить это можно будет только глазами.
//
// ЗНАЧЕНИЕ ФИЛЬТРА В ПОИСКЕ БЕРЁТСЯ ИЗ `label` В ДВУХ МЕСТАХ СРАЗУ —
