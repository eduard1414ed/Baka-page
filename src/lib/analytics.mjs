export const ANALYTICS_HOSTS = ['bakapodcast.com'];

/**
 * Работают ли счётчики на этом адресе. Чистая функция — её можно спросить
 * подлогом, не открывая браузер.
 */
export function считаемЭтотАдрес(hostname) {
	return ANALYTICS_HOSTS.some((host) => hostname === host || hostname.endsWith(`.${host}`));
}
