// КОРОТКАЯ ПОДПИСЬ ПОД МАРКОЙ (задача 22, `/mybest/`, тз-22 «Длинные названия»).
//
// ОДНО ПРАВИЛО НА СТРАНИЦУ И НА КАРТИНКУ. Подпись под маркой на странице
// и подпись в скачанной картинке обязаны совпадать: человек правит её руками,
// глядя на страницу, и вправе ждать в картинке то же самое. Режь их две копии —
// разъехались бы на первом же знаке, о котором одна знает, а другая нет.
//
// Правило из ТЗ: настоящее имя стоит в начале, дальше приписка. Режем
// по ПЕРВОМУ двоеточию, точке, вопросительному или восклицательному знаку.
// Двоеточие и точка уходят вместе с припиской; «?» и «!» остаются — они часть
// имени («Кэйон!»), и без них оно выглядит оборванным.
//
// «ЕСЛИ ЗНАК НЕ В НАЧАЛЕ» — ЭТО ПОРОГ `MIN_PREFIX_LENGTH`, А НЕ «НЕ ПЕРВАЯ
// БУКВА». Порог уже есть в проекте, и ровно для этого вопроса — «где кончается
// настоящее имя перед двоеточием»: по нему режут название для поиска
// упоминаний, для подсказок вариантов и для склонения. Без него «Re:Zero»
// стало бы «Re», а «Dr. Stone» — «Dr»: знак там стоит внутри имени.
//
// Это ПЕРВАЯ из трёх мер. Вторая — предел строк — живёт в стилях страницы
// (три строки) и в картинке (две); третья — правка подписи руками.
import { MIN_PREFIX_LENGTH } from './animeMentions.mjs';

//
// ДВЕ ОГОВОРКИ, И ОБЕ НАЙДЕНЫ ПРОГОНОМ ПО ВСЕМУ КАТАЛОГУ (3 октября 2026):
//   * точка МЕЖДУ ЦИФРАМИ — не конец имени: «Евангелион 3.0+1.01» иначе
//     становился «Евангелионом 3», «Версия 1.1а» — «Версией 1»;
//   * «?» и «!» берутся ВСЕЙ ПАЧКОЙ: «Волейбол!!» иначе терял второй знак.
const CUT_AFTER = /^[?!]+/;
const STOPS = /[:.?!]/g;

// РЕЖЕТСЯ ТОЛЬКО ДЛИННОЕ (решение заказчика 3 октября 2026). Правило, приложенное
// ко всем названиям, стирало отличие продолжений: из 685 тайтлов 32 группы
// получали одинаковые подписи — «Стальной алхимик: Братство» становился
// «Стальным алхимиком», четыре «Атаки титанов» — одной. Короткое название
// влезает и так; резать есть смысл только то, что не влезает.
//
// ПОРОГ — ЗАМЕР, А НЕ НА ГЛАЗ. Все 685 названий набраны настоящей Literata
// в колонку подписи картинки (238 px, 15/1.2): в две строки влезает всё
// до 51 знака включительно, первое невлезающее — 52 знака. Взято 50, с запасом
// на буквы шире средних. С 3 октября 2026 подпись в картинке 9:16 набрана
// крупнее — 18 (решение заказчика, mybestImage.mjs), и в две строки там
// влезает меньше: многоточие у 38 подписей из 685 против 17 при 15. Порог
// оставлен: на странице он верен, а длинное в картинке ловит многоточие. На странице и особенно на телефоне (марка 111 px,
// 11 px, три строки — влезает около 36 знаков) этого порога мало, и там
// длинное ловит вторая мера — многоточие после третьей строки.
export const SHORT_TITLE_LIMIT = 50;

/** @returns {string} подпись под маркой; пустую строку возвращает пустой. */
export function shortTitle(title) {
	const text = String(title ?? '').replace(/\s+/g, ' ').trim();
	if (text.length <= SHORT_TITLE_LIMIT) return text;
	STOPS.lastIndex = 0;
	let match;
	while ((match = STOPS.exec(text))) {
		const at = match.index;
		if (at < MIN_PREFIX_LENGTH) continue;
		if (match[0] === '.' && /\d/.test(text[at - 1] ?? '') && /\d/.test(text[at + 1] ?? '')) continue;
		const tail = text.slice(at).match(CUT_AFTER);
		return text.slice(0, tail ? at + tail[0].length : at).trim();
	}
	return text;
}
