// Адрес страницы из заголовка: «Нарисуй это, потом умри» → narisuy-eto-potom-umri.
//
// ПОЧЕМУ ЭТО НЕ translit.mjs, хотя тот стоит рядом и называется похоже.
// Тот переводит ЛАТИНИЦУ В КИРИЛЛИЦУ и только для поиска: «ghibli» → «гибли»,
// читателю не показывается никогда. Здесь ровно обратное направление и другая
// задача — имя файла и кусок адреса. Общего кода у них нет ни строчки, и свести
// их в один модуль нельзя: таблицы замен разные (там «ch» → «ч», тут «ч» → «ch»,
// а «щ» → «sch» обратно в «щ» уже не превращается).
//
// ПОЧЕМУ ЭТОТ ФАЙЛ ВООБЩЕ ПОЯВИЛСЯ. До импорта из телеграма адреса делала
// только админка (Sveltia, настройка `slug` в public/admin/config.yml), и своего
// кода у правила не было вовсе. Импорт заводит посты мимо админки — значит
// правилу нужен дом, иначе копия появится внутри скрипта импорта.
//
// ТАБЛИЦА СВЕРЕНА С НАСТОЯЩИМИ ФАЙЛАМИ, а не взята из головы. Три поста
// заведены заказчиком через админку, и адреса, которые она им дала, эта функция
// обязана повторить буква в букву (проверка — scripts/telegram-import.test.mjs):
//
//   «Нарисуй это, потом умри»                     → narisuy-eto-potom-umri
//   «Знакомьтесь: Ёдзи Такэсигэ»                  → znakomtes-yodzi-takesige
//   «Девушки-пони: Серая Золушка | В чем секрет популярности?»
//                                                 → devushki-poni-seraya-zolushka-v-chem-sekret-populyarnosti
//
// Расхождение с админкой опасно ровно одним: заказчик заведёт пост с тем же
// заголовком руками, получит другое имя файла, и на сайте окажется два поста
// вместо одного. Поэтому таблица проверяется, а не подразумевается.

const CYRILLIC = {
	а: 'a',
	б: 'b',
	в: 'v',
	г: 'g',
	д: 'd',
	е: 'e',
	ё: 'yo',
	ж: 'zh',
	з: 'z',
	и: 'i',
	й: 'y',
	к: 'k',
	л: 'l',
	м: 'm',
	н: 'n',
	о: 'o',
	п: 'p',
	р: 'r',
	с: 's',
	т: 't',
	у: 'u',
	ф: 'f',
	х: 'h',
	ц: 'ts',
	ч: 'ch',
	ш: 'sh',
	щ: 'sch',
	ъ: '',
	ы: 'y',
	ь: '',
	э: 'e',
	ю: 'yu',
	я: 'ya',
	// Украинские и белорусские буквы попадаются в цитатах и именах.
	і: 'i',
	ї: 'yi',
	є: 'ye',
	ґ: 'g',
	ў: 'u',
};

/**
 * Заголовок → кусок адреса. Пустой заголовок даёт пустую строку: решать,
 * чем её заменить, — дело того, кто зовёт (у импорта это дата и номер поста).
 *
 * @param {string} title
 * @returns {string}
 */
export function slugify(title) {
	const lower = String(title ?? '')
		.toLowerCase()
		// Разложенные диакритики (macOS хранит «й» именно так) — иначе «й»
		// не найдётся в таблице и уедет в мусор.
		.normalize('NFC');

	let out = '';
	for (const char of lower) {
		if (char in CYRILLIC) out += CYRILLIC[char];
		else if (/[a-z0-9]/.test(char)) out += char;
		else out += '-';
	}

	return out.replace(/-+/g, '-').replace(/^-|-$/g, '');
}
