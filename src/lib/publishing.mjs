// Пост виден на сайте, если это не черновик и время публикации (если задано)
// уже наступило. `date` и `publishAt` — разные оси (см. тз/09-отложенный-постинг.md):
// `date` только для отображения и сортировки, `publishAt` только для видимости.
// Используется везде, где раньше была проверка `!data.draft` — сборка сайта,
// лента, категории, страница поста.
export function isPublished({ draft, publishAt }, now = new Date()) {
	if (draft) return false;
	if (publishAt && publishAt.getTime() > now.getTime()) return false;
	return true;
}

/**
 * Черновик теста, который можно показать В РЕЖИМЕ РАЗРАБОТКИ (сессия «Тесты-3»).
 *
 * У черновика страницы нет (урок «у черновика нет страницы»), а тест надо
 * пройти глазами и руками до публикации. Решение заказчика 9 октября 2026:
 * черновик ТЕСТА виден в `astro dev` — его поднимает ярлык «Открыть-админку»,
 * то есть правка в админке тут же видна на соседней вкладке.
 *
 * ПОЧЕМУ ОН НЕ ПОПАДЁТ НА САЙТ. Флаг `dev` вызывающий берёт из
 * `import.meta.env.DEV`, а настоящая сборка (`astro build`, ей пользуется
 * выкладка) подставляет туда `false` ещё до запуска. Вторая линия —
 * scripts/check-drafts-in-dist.mjs в `npm run build`: нашлась в готовом
 * сайте страница черновика — сборка падает, выкладки нет.
 *
 * Флаг передаётся ПАРАМЕТРОМ, а не читается здесь: этот файл зовут и обычные
 * скрипты Node, у которых `import.meta.env` нет вовсе.
 *
 * Только тесты: остальные черновики (их сотни) в режиме разработки
 * по-прежнему не видны — ленты там остались бы прежними.
 *
 * @param {{ draft?: boolean, category?: string }} data
 * @param {boolean} dev
 */
export function isDevTestPreview(data, dev) {
	return dev === true && data.category === 'test' && Boolean(data.draft);
}
