// Здесь чистая арифметика: на входе коробка ссылки и размеры окна, на выходе
// два числа. Спрятанная в обработчик наведения, она проверялась бы только
// глазами и только на той ширине, которая сейчас открыта. Вынесенную можно
// спросить на любой ширине за миллисекунду — см. scripts/anime-hover-place.test.mjs.
//
// Ни окна, ни документа этот файл не знает и знать не должен.

/** Габарит марки. ЧИСЛА ДУБЛИРУЮТ СТИЛИ `AnimeHoverCard.astro`, и это стерегут:
    проверка вынимает их из того файла и сверяет с этими. Разъедутся — покраснеет. */
export const ШИРИНА = 384;
export const ВЫСОТА = 168;

/** Отступ марки от строки, сверху или снизу. */
export const ЗАЗОР = 4;

/** Поле у края окна, ближе которого марка не подходит. */
export const ПОЛЕ = 8;

/** Насколько отбивка вылезает за марку: `drop-shadow(2px 3px …)`. Считается,
    потому что горизонтальной прокрутки не должно давать и она тоже. */
export const ОТБИВКА_ВПРАВО = 2;
export const ОТБИВКА_ВНИЗ = 3;

/**
 * @param {{
 *   короб: { left: number, top: number, bottom: number },
 *   ширинаОкна: number, высотаОкна: number,
 *   прокруткаX: number, прокруткаY: number,
 * }} что
 * @returns {{ лево: number, верх: number, перевёрнута: boolean } | null}
 *   Координаты в системе СТРАНИЦЫ, а не окна: марка лежит в конце документа
 *   и прокручивается вместе с ним. `null` — места нет, показывать нечего.
 */
export function местоДляМарки({ короб, ширинаОкна, высотаОкна, прокруткаX, прокруткаY }) {
	// В ОКНО УЖЕ 400 px МАРКА НЕ СТАВИТСЯ ВОВСЕ, И ЭТО НЕ ЛЕНЬ. Сжать её нельзя:
	// это тот же компонент, что в блоке «упоминается в материале», а размеры
	// повторяемого компонента задаёт дизайн-система, не место показа (§26 п. 4).
	// Значит выбор один: либо марка вылезает за край и рождает горизонтальную
	// прокрутку — которой на сайте нет нигде, кроме ленты галереи, — либо её
	// в таком окне не бывает. Второе честнее: марка это добавка для десктопа,
	// а не решение задачи маркера, и на телефоне её нет и так.
	if (ширинаОкна < ШИРИНА + ПОЛЕ * 2 + ОТБИВКА_ВПРАВО) return null;

	// ПО ГОРИЗОНТАЛИ: левый край марки по левому краю ссылки, но не ближе поля
	// к любому краю окна. Отбивка справа входит в предел — она такая же часть
	// картинки, как сама марка.
	const предел = ширинаОкна - ШИРИНА - ОТБИВКА_ВПРАВО - ПОЛЕ;
	const лево = Math.max(ПОЛЕ, Math.min(короб.left, предел));

	// ПО ВЕРТИКАЛИ: снизу, если помещается; иначе сверху, если помещается там.
	const снизу = короб.bottom + ЗАЗОР;
	const сверху = короб.top - ЗАЗОР - ВЫСОТА;

	const влезаетСнизу = снизу + ВЫСОТА + ОТБИВКА_ВНИЗ <= высотаОкна;
	const влезаетСверху = сверху >= 0;

	// НЕ ВЛЕЗАЕТ НИКУДА — НЕ ПОКАЗЫВАЕМ. Прижать её к краю и накрыть саму ссылку
	// было бы хуже, чем не показать: читатель теряет то, на что смотрел.
	if (!влезаетСнизу && !влезаетСверху) return null;

	const перевёрнута = !влезаетСнизу;
	const верхВОкне = перевёрнута ? сверху : снизу;

	return {
		лево: лево + прокруткаX,
		верх: верхВОкне + прокруткаY,
		перевёрнута,
	};
}
