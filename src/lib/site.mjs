// Общие сведения о сайте: адрес, имя, описание по умолчанию.
//
// Лежат отдельным модулем, потому что их спрашивают в трёх разных местах:
// astro.config.mjs (обычный node во время сборки), страницы Astro и скрипты.
// Обычный .js читается одинаково везде — тот же приём, что у src/data/platforms.js.
//
// ГЛАВНЫЙ АДРЕС — МОСКОВСКОЕ ЗЕРКАЛО, а не bakapodcast.com. Решение заказчика
// 11 августа 2026 (задача 14, часть 2), и вот причина, чтобы её не «починили»
// обратно: большинство читателей в России и приходят из поиска на русском.
// Гуглом там тоже пользуются, а человек, нашедший сайт через Google и живущий
// в Москве, попал бы на адрес, который у него не открывается. Разделить
// поисковики нельзя — канонический адрес у страницы один и один на всех.
//
// Обе копии сайта раздают ОДНИ И ТЕ ЖЕ файлы, поэтому обе говорят поисковику
// одно и то же. bakapodcast.com и www.bakapodcast.com остаются живыми адресами
// и закрыты этим же тегом <link rel="canonical"> (см. src/layouts/Layout.astro).
//
// ЭТО ЕДИНСТВЕННОЕ МЕСТО, ГДЕ АДРЕС САЙТА ЗАПИСАН. За ним идут canonical,
// og:url, карта сайта, RSS, хлебные крошки, разметка Schema.org и строка
// Sitemap в /robots.txt. Второй копии заводить нельзя.

export const SITE_URL = 'https://ru.bakapodcast.com';
export const SITE_NAME = 'Бака!';
// Родительный падеж имени сайта — «разбор в 12 материалах «Баки!»».
// Живёт РЯДОМ с именительным нарочно: склонять название кодом нечем,
// а вписанное в другой файл оно пережило бы переименование сайта молча.
export const SITE_NAME_GENITIVE = 'Баки!';
export const SITE_TITLE = 'Бака! — подкаст об аниме';
export const SITE_DESCRIPTION = 'Подкаст об аниме и о том, что скрывается между кадрами';

/** Язык сайта в двух написаниях: для <html lang> и для og:locale. */
export const SITE_LANG = 'ru';
export const SITE_LOCALE = 'ru_RU';

/**
 * Путь на сайте → полный адрес со схемой и доменом.
 *
 * Нужен там, где относительной ссылки мало и требуется абсолютная: canonical,
 * og:image, карта сайта, RSS. Аргумент может быть уже абсолютным адресом
 * (например, обложка выпуска на хостинге подкаста) — такой возвращается как есть.
 */
export function absoluteUrl(path) {
	if (!path) return null;
	if (/^https?:\/\//.test(path)) return path;
	return new URL(path, SITE_URL).href;
}

/**
 * Заголовок страницы для <title>: «Название — Бака!».
 *
 * У главной приписка не нужна — там название сайта и так стоит первым словом,
 * «Бака! — подкаст об аниме — Бака!» выглядело бы глупо.
 */
export function pageTitle(title) {
	return title ? `${title} — ${SITE_NAME}` : SITE_TITLE;
}
