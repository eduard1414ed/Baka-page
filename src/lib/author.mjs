// (TASK-markup, пункт 3.1).
//
// Раньше в разметке и `author`, и `publisher` были одним и тем же —
// `Organization: Бака!`. Для поисковика это значит «текст написал сайт»:
// связать его с человеком, у которого есть книга, публикации на «Кинопоиске»
// и подкаст на Arzamas, было не по чему. Издателем организация остаётся —
// это правда, — а автором становится человек.
//
// ОТКУДА БЕРУТСЯ ДАННЫЕ, И ПОЧЕМУ НЕ ВСЕ ОТСЮДА:
//
//   описание и телеграм — ЖИВЫЕ, из src/content/pages/about.md. Заказчик
//     правит их в админке, и правка обязана доезжать до разметки сама.
//     Впиши мы их сюда копией — разошлись бы молча, и узнать об этом было бы
//     неоткуда: разметку не видно глазами;
//   имя и ссылка на книгу — здесь. На странице «О проекте» ведущий назван
//     «Эд», а книга там не упомянута вовсе; полное имя стоит в разделе 2.1
//     пользовательского соглашения того же сайта и в выходных данных книги
//     («Составитель и редактор книги — Эдуард Царионов»). Поля для книги
//     в админке нет, заводить его ради одной ссылки не стали.
//
// ИМЯ ПОЛНОЕ, А «ЭД» УШЛО В `alternateName`. Оба написания — свои, оба
// опубликованы самим проектом. Полное сильнее ровно тем, ради чего пункт
// и затевался: по нему человек связывается с книгой и с текстами
// в чужих изданиях, а «Эд» не связывается ни с чем.

/**
 * Под каким именем ведущий записан на странице «О проекте».
 *
 * ИЩЕМ ПО ИМЕНИ, А НЕ ПО МЕСТУ В СПИСКЕ. Ведущих там трое, порядок задаётся
 * в админке перетаскиванием, и «первый в списке» однажды станет другим
 * человеком — молча, вместе с чужой биографией в разметке каждого поста.
 */
export const ИМЯ_НА_СТРАНИЦЕ = 'Эд';

/** Полное имя — как он подписан в книге и в пользовательском соглашении. */
export const ПОЛНОЕ_ИМЯ = 'Эдуард Царионов';

/** Книга: «Манга, моэ, исекай. Большой гид по аниме», Альпина. */
export const КНИГА = 'https://alpinabook.ru/catalog/book-manga-moe-isekay/';

/**
 * КТО НАПИСАЛ ЭТОТ ТЕКСТ — ИНОГДА СКАЗАНО В ПОЛЕ МАРКИРОВКИ РЕКЛАМЫ.
 *
 * Поле `adLabel` заведено под строку «Реклама. ООО «…», ИНН …, erid: …»,
 * но заказчик пользуется им и как подписью автора: «Автор текста: Ксюша».
 * Замер по архиву 31 августа 2026: поле непустое у 27 материалов, из них
 * 23 — подпись автора и только 4 настоящая реклама.
 *
 * ЕДИНСТВЕННОЕ И МНОЖЕСТВЕННОЕ РАЗБИРАЮТСЯ ПО-РАЗНОМУ, И ЭТО НЕ ПРИДИРКА.
 * «Авторы» — значит их несколько, и запятая разделяет имена. «Автор» — значит
 * один, и запятая принадлежит самому имени: в архиве есть подпись
 * «Автор текста: Кристина, «крисгринпис на связи»», и разделив её, мы завели
 * бы автора по имени «крисгринпис на связи». Слово, которое человек выбрал
 * сам, и говорит, как читать строку.
 *
 * СЛОВО «ТЕКСТА» НЕОБЯЗАТЕЛЬНО. В архиве все 23 подписи написаны полностью,
 * но требовать этого от человека, который печатает в админке, нельзя: «Автор:
 * Ксюша» — та же подпись, и не узнать её значило бы потерять автора молча.
 *
 * ВСЁ ОСТАЛЬНОЕ — НЕ ПОДПИСЬ. Строка про ЭКСМО и Яндекс.Музыку сюда не попадёт
 * ни при какой погоде: у неё нет этого зачина. «Автор перевода: …» тоже
 * не попадёт — и это правильно: переводчик не автор текста.
 *
 * @returns {string[]} Имена в том порядке, в каком их написали. Пусто —
 *   значит подписи нет, и автором остаётся ведущий.
 */
export function авторыИзМаркировки(adLabel) {
	const строка = String(adLabel ?? '').trim();
	const m = строка.match(/^Автор(ы)?(?:\s+текста)?\s*:\s*(.+)$/i);
	if (!m) return [];

	const множественное = Boolean(m[1]);
	const хвост = m[2].replace(/[\s.;]+$/, '');

	return (множественное ? хвост.split(',') : [хвост]).map((имя) => имя.trim()).filter(Boolean);
}

/**
 * Person по имени — со всем, что о человеке известно проекту.
 *
 * ЧТО ОТКУДА. Описание и ссылка на профиль берутся со страницы «О проекте»,
 * если человек там есть: их правит заказчик в админке, и правка обязана
 * доезжать до разметки сама. Автора-подписчика, которого на странице нет,
 * отдаём одним именем — большего про него не известно, а сочинять запрещено.
 *
 * ВЕДУЩИЙ УЗНАЁТСЯ ПО ОБОИМ НАПИСАНИЯМ. В подписи «Авторы текста: Алексей
 * Филиппов, Даулет Жанайдаров, Эдуард Царионов» он назван полным именем,
 * а на странице «О проекте» — «Эд». Не признай мы их одним человеком —
 * в разметке завелись бы двое, и ни один не связался бы с книгой.
 *
 * @param {string} имя Как человек подписан.
 * @param {{hosts?: {name?: string, bio?: string, url?: string}[]}} about
 *   Данные страницы «О проекте» (src/content/pages/about.md).
 */
export function персона(имя, about) {
	const этоВедущийПроекта = имя === ИМЯ_НА_СТРАНИЦЕ || имя === ПОЛНОЕ_ИМЯ;
	const наСтранице = (about?.hosts ?? []).find((h) => h?.name === (этоВедущийПроекта ? ИМЯ_НА_СТРАНИЦЕ : имя));

	// Ссылки на «то же самое в другом месте». Профиль — со страницы
	// «О проекте», книга — только у того, чья она. Пустых сюда не пускаем:
	// битая ссылка в `sameAs` хуже её отсутствия.
	const sameAs = [наСтранице?.url, этоВедущийПроекта ? КНИГА : null].filter(Boolean);

	return {
		'@type': 'Person',
		name: этоВедущийПроекта ? ПОЛНОЕ_ИМЯ : имя,
		...(этоВедущийПроекта ? { alternateName: ИМЯ_НА_СТРАНИЦЕ } : {}),
		...(наСтранице?.bio ? { description: наСтранице.bio } : {}),
		...(sameAs.length > 0 ? { sameAs } : {}),
	};
}

/**
 * Кто подписан под материалом: один Person, список из нескольких — или null.
 *
 * ПОРЯДОК ИСТОЧНИКОВ. Сначала подпись в поле маркировки: её поставил человек
 * про КОНКРЕТНЫЙ текст, и она сильнее любого умолчания. Нет подписи — автором
 * идёт ведущий проекта.
 *
 * NULL, А НЕ ЗАГЛУШКА. Подписи нет, и ведущего на странице «О проекте» тоже
 * нет — значит его там переименовали, и сочинять описание неоткуда. Тогда
 * автором останется организация: это беднее, но не ложь. Молчать при этом
 * нельзя, поэтому зовущий обязан сказать о пропаже в лог сборки.
 *
 * @param {{adLabel?: string}} postData Шапка материала.
 * @param {object} about Данные страницы «О проекте».
 */
export function authorFor(postData, about) {
	const подписанные = авторыИзМаркировки(postData?.adLabel);

	if (подписанные.length > 0) {
		const люди = подписанные.map((имя) => персона(имя, about));
		// Один автор — объектом, несколько — списком. Список из одного
		// у Schema.org законен, но читается «их могло быть больше».
		return люди.length === 1 ? люди[0] : люди;
	}

	// Ведущего на странице нет — значит и описания взять неоткуда.
	if (!(about?.hosts ?? []).some((h) => h?.name === ИМЯ_НА_СТРАНИЦЕ)) return null;
	return персона(ИМЯ_НА_СТРАНИЦЕ, about);
}
