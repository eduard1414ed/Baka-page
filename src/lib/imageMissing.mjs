//
// Родиться она может тремя путями, и все три обязаны выглядеть одинаково:
//   — страница знает при сборке, что постера нет   → src/components/ImageMissing.astro;
//   — выдача поиска рисует марку тайтла без постера → src/pages/search.astro;
//   — картинка была, но не загрузилась              → src/layouts/Layout.astro.
// Три копии двух тегов разъехались бы молча — сначала классом, потом альтом.
//
// Сам текст «Изображения нет» тут не написан: его рисует CSS
// (`.img-missing::after` в src/styles/global.css). Так он не попадает
// в поисковый индекс — иначе лез бы в цитаты выдачи по всему каталогу.

/** Путь к рисунку. Ссылкой, а не внутрь страницы: файл лежит в public/. */
export const IMAGE_MISSING_SRC = '/character-empty.png';

/**
 * Разметка заглушки.
 *
 * @param {{ compact?: boolean }} [options]
 *   `compact` — узкое место (марка, карточка каталога, выдача поиска):
 *   там подпись не помещается и прячется, а рисунок становится крупнее.
 * @returns {string} Готовый кусок разметки.
 */
export function imageMissingHtml({ compact = false } = {}) {
	const cls = compact ? 'img-missing img-missing--compact' : 'img-missing';
	// Альт пустой намеренно: рисунок ничего не сообщает сверх подписи рядом,
	// а диктор, читающий «рисунок персонажа», только мешал бы.
	return `<span class="${cls}"><img src="${IMAGE_MISSING_SRC}" alt="" loading="lazy" width="240" height="240"></span>`;
}
