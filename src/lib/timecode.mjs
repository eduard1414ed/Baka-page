// ЧТО ТАКОЕ ТАЙМКОД — ОПРЕДЕЛЕНО ЗДЕСЬ И БОЛЬШЕ НИГДЕ.
//
// Времени на сайте касаются три разных места: текст выпуска (метки в шоунотах
// ищет src/plugins/remark-timecode.mjs), блок таймкодов у выпуска и видеоэссе
// (src/components/TimecodeList.astro) и расшифровка. Разойдись у них понятие
// формата — одно и то же «1:02:11» в одном месте стало бы часом с минутами,
// а в другом минутой с секундами, и промах был бы ровно на час.
//
// Формат H:MM:SS держим отдельно от M:SS: минуты бывают трёхзначными
// (выпуски длиннее часа), и без разделения секунды путались бы с минутами.
export const TIMECODE_SOURCE = '(?:(\\d{1,2}):([0-5]\\d):([0-5]\\d)|(\\d{1,3}):([0-5]\\d))';

/**
 * Разбор совпадения регулярного выражения в секунды.
 *
 * @param {RegExpMatchArray} match Совпадение по TIMECODE_SOURCE.
 * @returns {number} Секунды от начала.
 */
export function matchToSeconds(match) {
	const [, h, m, s, m2, s2] = match;
	if (h !== undefined) return Number(h) * 3600 + Number(m) * 60 + Number(s);
	return Number(m2) * 60 + Number(s2);
}

// ЗДЕСЬ БЫЛ `parseTimecode` — «строка целиком таймкод?». Он никого не нашёл:
// поле «Таймкоды» заполняется списком, и разбирает его `parseTimecodeList`
// ниже, а по одной строке за раз не спрашивал никто. Снят 15 августа 2026
// (ревизия задачи 15, находка 13) вместе со своим `WHOLE_RE`. Понадобится
// снова — это три строки поверх `matchToSeconds`, а не потеря.

/**
 * Секунды в вид 4:07 или 1:23:45 — обратная сторона того же формата,
 * и живёт она рядом с разбором нарочно: разъедься они, время на странице
 * перестало бы совпадать с тем, куда перематывает нажатие.
 *
 * @param {number} seconds
 * @returns {string}
 */
export function formatTimecode(seconds) {
	const total = Math.max(0, Math.floor(Number(seconds) || 0));
	const pad = (n) => String(n).padStart(2, '0');
	const s = total % 60;
	const m = Math.floor(total / 60) % 60;
	const h = Math.floor(total / 3600);
	return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${m}:${pad(s)}`;
}

/**
 * @typedef {{ seconds: number, time: string, title: string }} TimecodeRow
 */

/**
 * Разбор списка таймкодов, вставленного одним куском.
 *
 * Автор вставляет в поле готовый список из шоунотов — по строке на тему:
 *
 *     00:00 — Интро
 *     01:10 — Демоны
 *     10:42 Смена эпохи
 *
 * Разделитель между временем и темой необязателен и может быть любым
 * из привычных: длинное тире, короткое, дефис, точка с запятой. Заставлять
 * автора приводить чужой список к одному виду руками — ровно та работа,
 * ради избавления от которой поле и заведено.
 *
 * ЖИВЁТ ТУТ, А НЕ В КОМПОНЕНТЕ, потому что этот же разбор понадобится разовому
 * скрипту, который вытащит таймкоды из тел 143 выпусков архива. Две копии
 * правил разошлись бы молча, и скрипт разобрал бы архив не так, как страница.
 *
 * НИЧЕГО НЕ УГАДЫВАЕТ И НЕ ЧИНИТ. Строка, которая не разобралась, не попадает
 * в список вовсе и уходит предупреждением: тихо подставленное «наверное, автор
 * имел в виду» увело бы плеер не туда, и заметить это было бы нечем.
 *
 * @param {string} source Содержимое поля «Таймкоды».
 * @param {(message: string) => void} [onWarn] Куда сказать о непонятной строке.
 * @returns {{ seconds: number, time: string, title: string }[]} Готовые строки.
 */
export function parseTimecodeList(source, onWarn = () => {}) {
	// Время, необязательный разделитель, тема. Тему берём «всё остальное»:
	// в ней бывает что угодно, включая двоеточия и тире.
	const LINE_RE = new RegExp(`^${TIMECODE_SOURCE}\\s*[—–\\-·:.]?\\s*(.*)$`);

	// Строку «Таймкоды:» пропускаем молча: это подпись самого списка, её
	// копируют вместе с ним из шоунотов, и ругаться на неё нечего.
	const HEADING_RE = /^таймкоды\s*:?$/i;

	const rows = [];

	for (const raw of String(source ?? '').split('\n')) {
		const line = raw.trim();
		if (!line || HEADING_RE.test(line)) continue;

		const match = line.match(LINE_RE);

		if (!match) {
			onWarn(`«${line}» — не похоже на таймкод, строка пропущена. Пишется как «12:04 — Тема».`);
			continue;
		}

		const title = match[6].trim();

		if (!title) {
			onWarn(`у отметки ${line} не написано, о чём она — строка пропущена.`);
			continue;
		}

		// Время печатаем своё, а не авторское: «07:05» и «7:05» в одном
		// столбце читались бы двумя разными форматами.
		const seconds = matchToSeconds(match);
		rows.push({ seconds, time: formatTimecode(seconds), title });
	}

	return rows;
}
