// Дата материала в двух написаниях. Оба нужны одновременно: длинное — в
// текстовой карточке и в списках, короткое — в указателе коротких заметок
// на главной, где на дату отведена вторая колонка шириной в несколько знаков.
//
// Почему не `Intl.DateTimeFormat` прямо в компонентах: для русского языка
// он дописывает « г.» в конце — «8 августа 2026 г.». В утверждённом дизайне
// его нет нигде, и убрать его настройками формата нельзя, только срезать
// после форматирования. Одно место, где это делается, — здесь.

const LONG = new Intl.DateTimeFormat('ru-RU', { day: 'numeric', month: 'long', year: 'numeric' });
const SHORT = new Intl.DateTimeFormat('ru-RU', { day: '2-digit', month: '2-digit' });

/**
 * «8 августа 2026». Без « г.» на конце.
 * @param {Date} date
 */
export function formatPostDate(date) {
	return LONG.format(date).replace(/\s*г\.\s*$/u, '');
}

/**
 * «18.07» — день и месяц, без года.
 *
 * Год опущен намеренно: короткие заметки на главной свежие по определению,
 * а четыре лишних знака в узкой колонке отняли бы место у названия.
 * @param {Date} date
 */
export function formatShortDate(date) {
	return SHORT.format(date);
}
