//
// ЧТО ЛОМАЕТСЯ. Наши блоки в тексте поста пишутся директивой:
// `::image{src="…" caption="…"}`. Разбор директив кончает значение атрибута
// на первой же прямой кавычке — значит подпись `The Brilliance of Naoki
// Urasawa's "Monster"` разорвала бы блок, и читатель увидел бы на странице
// строку `::image{src=… caption=…}` словами. В архиве такая подпись есть,
// и не одна: ep-21 и ep-83.
//
// ПОЧЕМУ ЭТО ФАЙЛ, А НЕ СТРОЧКА НА МЕСТЕ. Правило двустороннее: кто пишет —
// подменяет кавычку на `&quot;`, кто читает — подменяет обратно. Копий было
// ШЕСТЬ (админка, разовый скрипт врезок и четыре плагина сборки), и ещё
// восемь мест подпись не экранировали вовсе — семь сборщиков переносов с DTF
// и осенний (доревизия задачи 15, находка 32). Разъедься стороны — блок
// на странице показался бы словами, и заметить это можно было бы только
// глазами и только на том посте, где кавычка есть.
//
// АДМИНКА СВОЮ КОПИЮ ОСТАВЛЯЕТ ПОНЕВОЛЕ: `public/admin/index.html` живёт вне
// сборки и импортировать отсюда не может. Поэтому копия там сверяется
// проверкой `scripts/directive-attr.test.mjs`, а не пометкой «поправьте и там»:
// пометка в этом проекте уже не удержала ни одной копии.

/** Значение → внутрь `attr="…"`. */
export const escapeAttr = (value) => String(value ?? '').replaceAll('"', '&quot;');

/** Значение из `attr="…"` → как его написал человек. */
export const unescapeAttr = (value = '') => String(value).replaceAll('&quot;', '"');
