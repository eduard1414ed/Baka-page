// Русское числительное: «1 выпуск», «2 выпуска», «5 выпусков».
//
// Один код на весь сайт. Такая же функция была написана внутри карточки тайтла
// («упоминание / упоминания / упоминаний»), и второй копии заводить нельзя:
// правило одно, а разъезжаются копии молча — на числах вроде 111 и 114,
// которые в тестовых данных не встречаются никогда.

/**
 * @param {number} n Число, к которому подбирается форма.
 * @param {[string, string, string]} forms Формы для 1, 2 и 5: «выпуск»,
 *   «выпуска», «выпусков». У несклоняемых слов все три совпадают.
 * @returns {string}
 */
export function plural(n, forms) {
	const mod10 = Math.abs(n) % 10;
	const mod100 = Math.abs(n) % 100;
	// 11–14 — исключение из всех правил: «11 выпусков», а не «11 выпуск».
	if (mod100 >= 11 && mod100 <= 14) return forms[2];
	if (mod10 === 1) return forms[0];
	if (mod10 >= 2 && mod10 <= 4) return forms[1];
	return forms[2];
}

/** «143 выпуска» — число и подобранная к нему форма. */
export function withCount(n, forms) {
	return `${n} ${plural(n, forms)}`;
}
