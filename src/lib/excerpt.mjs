// Описание страницы поста (<meta name="description"> и превью в соцсетях)
// из текста самого поста. Своего поля под описание у поста нет и заводить его
// не стали: 143 выпуска архива пришлось бы заполнять руками.
//
// Задача не «взять первый абзац», а «взять первый ОСМЫСЛЕННЫЙ абзац». В текстах
// выпусков сверху почти всегда лежит служебное: обложка выпуска картинкой,
// реклама («Любимые книги подкаста — на полке в Яндекс Книгах: ссылка»),
// столбик ссылок на Patreon и Boosty. Показывать это в выдаче поисковика
// и в превью телеграма — худшее, что можно сделать.
//
// Пороги ниже выведены прогоном по всем 146 постам архива (scripts/ там нет,
// проверка разовая), а не назначены на глаз: см. статус/этап-6-seo.md.

/** Абзац короче этого — подпись, приписка или обрывок, но не описание. */
const MIN_PARAGRAPH = 60;

/**
 * Мягкий порог для второго прохода. У совсем коротких постов (ep-1 «Опенинг» —
 * одна фраза на 51 символ) первый проход не находит ничего, а своя короткая
 * фраза лучше общего описания сайта. Ниже 25 символов уже мусор: «Пампам»,
 * строка таймкода «12:04 — Новый блок».
 */
const MIN_PARAGRAPH_RELAXED = 25;

/** Если ссылки занимают больше этой доли абзаца, это блок ссылок, а не текст. */
const MAX_LINK_SHARE = 0.3;

/** Сколько символов оставляем. 160 — сколько показывает Google в выдаче. */
const MAX_LENGTH = 160;

/**
 * Снять markdown-разметку, оставив читаемый текст.
 * Порядок важен: сначала блочное (картинки, директивы), потом строчное.
 */
function stripMarkdown(text) {
	return (
		text
			// Картинка ![подпись](адрес) — убираем целиком вместе с подписью:
			// «Обложка выпуска» описанием быть не может.
			.replace(/!\[[^\]]*\]\([^)]*\)/g, '')
			// Ссылка [текст](адрес) → текст.
			.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
			// Свои блоки редактора: ::image{...}, ::video{...}, ::spoiler-start.
			.replace(/^::+[a-z-]+(\{[^}]*\})?\s*$/gim, '')
			// Заголовки, цитаты, маркеры списка в начале строки.
			.replace(/^\s{0,3}(#{1,6}|>|[-*+]|\d+\.)\s+/gm, '')
			// Жирный, курсив, код, зачёркнутое — только сами знаки.
			.replace(/[*_`~]/g, '')
			// Голый адрес, оставшийся в тексте без разметки.
			.replace(/https?:\/\/\S+/g, '')
			.replace(/[ \t]+/g, ' ')
			.trim()
	);
}

/** Доля символов, занятых ссылками, — до того как разметку сняли. */
function linkShare(paragraph) {
	const links = paragraph.match(/\[[^\]]*\]\([^)]*\)|https?:\/\/\S+/g) ?? [];
	if (links.length === 0) return 0;
	const linkChars = links.reduce((sum, link) => sum + link.length, 0);
	return linkChars / paragraph.length;
}

/** Обрезать по границе слова и поставить многоточие, если резали. */
function truncate(text, max = MAX_LENGTH) {
	if (text.length <= max) return text;
	const cut = text.slice(0, max);
	const lastSpace = cut.lastIndexOf(' ');
	// lastSpace === -1 бывает у одного длинного слова — тогда режем как есть.
	return `${(lastSpace > max / 2 ? cut.slice(0, lastSpace) : cut).replace(/[\s,.;:—-]+$/, '')}…`;
}

/**
 * Описание поста из его текста.
 *
 * @param {string} body Текст поста в markdown (post.body).
 * @param {string} fallback Что вернуть, если осмысленного абзаца не нашлось —
 *   обычно общее описание сайта. Пустое описание хуже общего: поисковик тогда
 *   придумывает его сам из случайного куска страницы.
 * @returns {string}
 */
export function excerptFromBody(body, fallback) {
	if (!body) return fallback;

	// Абзац — кусок между пустыми строками. Внутри абзаца перевод строки
	// превращаем в пробел: в текстах выпусков предложения часто разбиты
	// по строкам, а это один абзац.
	const paragraphs = body.split(/\n\s*\n/);

	const candidates = [];
	for (const raw of paragraphs) {
		const paragraph = raw.trim();
		if (!paragraph) continue;
		// Сплошные ссылки (столбик Patreon/Boosty, строчка с рекламой) — мимо.
		if (linkShare(paragraph) > MAX_LINK_SHARE) continue;

		const text = stripMarkdown(paragraph).replace(/\n+/g, ' ');
		// Первый же абзац нормальной длины — он и есть описание. Возвращаем
		// сразу, а не выбираем «лучший»: автор начинает с главного.
		if (text.length >= MIN_PARAGRAPH) return truncate(text);
		if (text.length >= MIN_PARAGRAPH_RELAXED) candidates.push(text);
	}

	// Второй проход: длинных абзацев нет вовсе — берём самый длинный короткий.
	if (candidates.length > 0) {
		return truncate(candidates.reduce((best, text) => (text.length > best.length ? text : best)));
	}

	return fallback;
}
