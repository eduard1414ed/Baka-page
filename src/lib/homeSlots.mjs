// Что показывает главная. Раздел 3.2 ТЗ (тз/08-дизайн.md).
//
// Главная — витрина, она не растёт: фиксированный набор слотов, и всё.
// Логика вынесена из страницы отдельным модулем не для красоты, а чтобы её
// можно было прогнать обычным node на настоящем архиве и посмотреть глазами,
// что попало в каждый слот, — не поднимая сайт.
//
// ГЛАВНОЕ ПРАВИЛО, ОБЩЕЕ ДЛЯ ВСЕХ СЛОТОВ: материал показывается на главной
// ОДИН РАЗ. Каждый следующий слот выбирает из того, что ещё не занято. Без
// этого последнее видеоэссе встало бы и в первый слот, и в сайдбар — они оба
// берут «самое свежее», просто с разными условиями.

/**
 * @typedef {{ id: string, data: { category: string, date: Date } }} Post
 */

/**
 * @typedef {object} HomeSlots
 * @property {Post | null} hero       Слот 1. Главный материал, большой, слева
 * @property {Post[]}      sidebar    Слот 2. Три карточки справа
 * @property {Post | null} podcast    Слот 3. Второй ряд, левый
 * @property {Post | null} second     Слот 4. Второй ряд, правый
 * @property {Post | null} third      Слот 5. Третий ряд, левый
 * @property {Post[]}      notes      Слот 6. Короткие заметки, до четырёх
 * @property {string[]}    shownIds   Всё, что заняло слоты, — по одному разу
 */

/**
 * Разложить материалы по слотам главной.
 *
 * @param {Post[]} posts Опубликованные материалы, отсортированные от свежих
 *   к старым. Отбор по `draft` и `publishAt` делает вызывающий: он же строит
 *   этот список для лент и для карты сайта, и второго правила «что считается
 *   опубликованным» в проекте быть не должно.
 * @param {object} options
 * @param {string[]} options.podcastCategories Какие категории считаются
 *   выпуском подкаста. Приезжает из content.config (`categoriesShownIn`),
 *   а не пишется здесь списком: бонус — такой же выпуск, и знать об этом
 *   должен один файл, а не два.
 * @param {(post: Post) => boolean} [options.hasMedia] Будет ли у карточки
 *   картинка. Спрашивается у вызывающего, а не решается здесь: правило «из чего
 *   берётся обложка» живёт в `postCardMedia.mjs` и второй копии иметь не должно.
 *   Не передали — считаем, что картинка есть у всех, и слот 4 ведёт себя
 *   по-старому.
 * @returns {HomeSlots}
 */
export function pickHomeSlots(posts, { podcastCategories, hasMedia = () => true }) {
	const taken = new Set();

	/** Самый свежий из ещё не занятых, подходящий под условие. */
	const take = (matches = () => true) => {
		const found = posts.find((post) => !taken.has(post.id) && matches(post));
		if (found) taken.add(found.id);
		return found ?? null;
	};

	const isCategory = (...ids) => (post) => ids.includes(post.data.category);
	const isPodcast = (post) => podcastCategories.includes(post.data.category);

	// Слот 1. Последнее видеоэссе. Видеоэссе может не быть ни одного —
	// тогда главный материал это просто самое свежее, что есть.
	const hero = take(isCategory('videoessay')) ?? take();

	// Слот 2. Три самых свежих любой категории из оставшихся.
	const sidebar = [take(), take(), take()].filter(Boolean);

	// Слот 3. Последний выпуск подкаста, бонус считается выпуском наравне
	// с обычным. Следствие: сюда может попасть платный материал — поэтому
	// плашка «Бонус» в метастроке обязана быть заметной, это единственное,
	// что предупредит читателя до перехода.
	// Выпусков может не быть вовсе — тогда следующий по хронологии.
	const podcast = take(isPodcast) ?? take();

	// Слот 4. Правый во втором ряду — ЗДЕСЬ КАРТИНКА ОБЯЗАТЕЛЬНА.
	//
	// ПОЧЕМУ ИМЕННО ЗДЕСЬ, А НЕ ВЕЗДЕ. У этой колонки внутри своя сетка из двух
	// дорожек — текст и картинка, — и сама колонка растянута на высоту ряда
	// (`align-self: stretch` у `.article-feature`): растянута ради вертикальной
	// линии слева, иначе линия обрывалась бы по низкой колонке. Материал без
	// обложки оставляет вторую дорожку пустой, а текст, выровненный по центру,
	// повисает посреди пустого поля в пол-экрана. Заказчик увидел это на
	// «4К-ремастере» рядом с выпуском №135 и решил такие сюда не пускать
	// (10 августа 2026).
	//
	// Не нашлось ни одного с картинкой — слот остаётся пустым, и ряд становится
	// одноколоночным сам (`.feature-row.single`). Это лучше пустого места:
	// пустая половина ряда читается поломкой вёрстки, а широкий материал —
	// решением.
	const second = take(hasMedia);

	// Слот 5. Левый в третьем ряду — ТО ЖЕ ПРАВИЛО, и вот почему оно нужно
	// и здесь.
	//
	// Дыра тут другой природы, поэтому её и не видно из разметки. Колонка
	// не растянута по высоте (`align-items: start` у ряда), вертикального
	// провала нет — но внутри у неё ТОЖЕ две дорожки, `1.15fr 0.85fr`. Материал
	// без обложки занимает первую, а вторая, в 43% ширины колонки, остаётся
	// пустой: текст жмётся влево, а справа от него ничего.
	//
	// Сначала правило поставили только слоту 4, и заказчик увидел ту же беду
	// строкой ниже — потому что запрет ПЕРЕДВИНУЛ материал без обложки сюда,
	// а не убрал его с главной. Правило, снятое в одном месте из двух, снято
	// наполовину.
	const third = take(hasMedia);

	// Слот 6. До четырёх заметок из оставшихся. Меньше четырёх — покажем
	// сколько есть; ни одной — блока не будет вовсе, и материал третьего ряда
	// займёт всю ширину (это решает уже страница, по длине списка).
	const notes = [take(isCategory('note')), take(isCategory('note')), take(isCategory('note')), take(isCategory('note'))].filter(
		Boolean,
	);

	return { hero, sidebar, podcast, second, third, notes, shownIds: [...taken] };
}
