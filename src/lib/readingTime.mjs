// Арифметика времени чтения: сколько минут занимает текст поста. Считается ОДИН
// РАЗ ПРИ СБОРКЕ и попадает в готовую страницу обычным текстом — в браузере
// на эту цифру не уходит ни строчки скрипта.
//
// Здесь СПЕЦИАЛЬНО нет ни знания о категориях поста, ни обращений к сети: файл
// занят одним делом — превратить markdown в число минут. Кому какое число
// показывать (время чтения или длительность выпуска) решает src/lib/postTiming.mjs.
// Разделение не ради красоты: без сети и без категорий эту арифметику можно
// прогнать на любом куске текста и проверить глазами, чем я и пользовался.

// 180 слов в минуту, а не привычные по англоязычным статьям 250. Русские слова
// длиннее: там, где в английском «read», у нас «прочитать». По английской норме
// время выходило бы заниженным примерно на треть — читатель открывал бы пост
// «на 4 минуты» и сидел над ним 6.
const WORDS_PER_MINUTE = 180;

// Картинки добавляют время по убывающей: первая +12 секунд, вторая +11, третья
// +10 и так далее, но не меньше 3 секунд за штуку. Так честнее, чем ровная
// прибавка: первую картинку в посте рассматривают, а девятую в галерее
// пролистывают. Без нижней границы длинная галерея вообще перестала бы
// добавлять время, а листать её всё-таки надо.
const FIRST_IMAGE_SECONDS = 12;
const MIN_IMAGE_SECONDS = 3;

// Меньше трёх минут — метку не показываем вовсе. «1 мин» рядом с заголовком
// выглядит суетливо и ничего не сообщает: и так видно, что текст короткий.
const MIN_MINUTES = 3;

// Картинки в тексте бывают двух видов, и это разная разметка:
// `::image{src="..." caption="..."}` — блок «Изображение с подписью» из админки
// (см. src/plugins/remark-image-figure.mjs), `![alt](адрес)` — обычная
// markdown-картинка (так робот сверки вставляет обложку выпуска).
const IMAGE_DIRECTIVE_RE = /^::image\b[^\n]*/gm;
const MARKDOWN_IMAGE_RE = /!\[[^\]]*\]\([^)]*\)/g;

function countMatches(text, regex) {
	return text.match(regex)?.length ?? 0;
}

// Считаем ТОЛЬКО то, что читатель читает глазами как текст. Всё остальное —
// служебная разметка, подписи к картинкам и надписи на кнопках — выбрасываем:
// эти слова не читают подряд, и время они завышают.
//
// Текст внутри спойлера, наоборот, ОСТАЁТСЯ: спойлеры обычно раскрывают, и если
// не считать их, у поста, где половина текста под кнопкой, время будет вдвое
// меньше настоящего.
function toPlainText(body) {
	return (
		body
			// Блоки кода целиком — их не читают, их проглядывают.
			.replace(/```[\s\S]*?```/g, ' ')
			// Обычная markdown-картинка вместе с её alt — alt это подпись.
			.replace(MARKDOWN_IMAGE_RE, ' ')
			// Блочная разметка из админки, каждая на своей строке: `::image{...}`
			// с подписью внутри, `::video{...}`, `::spoiler-start{label="..."}`
			// с надписью на кнопке, `::spoiler-end{}`. Убираем строку целиком —
			// вместе с подписями и надписями, но текст МЕЖДУ метками спойлера
			// при этом не трогаем, он остаётся в подсчёте.
			.replace(/^:{2,3}[a-z][\w-]*(?:\{[^}]*\})?[^\n]*$/gim, ' ')
			// Метки внутри строки: `:anime[Наруто]{id="naruto"}` и
			// `:spoiler-inline[спрятанное]{}`. Оставляем то, что в квадратных
			// скобках, — это и есть видимый текст, — а атрибуты выбрасываем.
			.replace(/:[a-z][\w-]*\[([^\]]*)\](?:\{[^}]*\})?/gi, '$1')
			// Ссылка: остаётся подпись, адрес уходит. Адрес глазами не читают.
			.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
			// Если разметку писали руками через HTML — теги не текст.
			.replace(/<[^>]*>/g, ' ')
			// Решётки заголовков, кавычки цитат, маркеры списков — в начале строки.
			.replace(/^\s{0,3}(?:#{1,6}\s+|>\s?|[-*+]\s+|\d+[.)]\s+)/gm, '')
			// Горизонтальная линия.
			.replace(/^\s{0,3}(?:[-*_]\s*){3,}$/gm, ' ')
			// Звёздочки, подчёркивания, тильды и обратные кавычки — оформление
			// текста, а не текст. Само слово внутри них остаётся.
			.replace(/[*_~`]/g, '')
			.replace(/\s+/g, ' ')
			.trim()
	);
}

// Слово — цепочка букв или цифр, возможно с дефисом или апострофом внутри.
// Дефис внутри важен: без него «какой-то» и «из-за» считались бы за два слова,
// и время у живого разговорного текста уезжало бы вверх.
const WORD_RE = /[\p{L}\p{N}]+(?:[-'’][\p{L}\p{N}]+)*/gu;

function countWords(text) {
	return countMatches(text, WORD_RE);
}

function imageSeconds(count) {
	let total = 0;
	for (let index = 0; index < count; index += 1) {
		total += Math.max(FIRST_IMAGE_SECONDS - index, MIN_IMAGE_SECONDS);
	}
	return total;
}

/**
 * Разбор тела поста в цифры: сколько слов, сколько картинок, сколько секунд.
 * Отдельно от getReadingMinutes — так проверочный скрипт может показать, из чего
 * сложилось время, а не только итог.
 *
 * @param {string | undefined} body — тело поста в markdown (без frontmatter)
 */
export function measureBody(body) {
	if (!body) return { words: 0, images: 0, seconds: 0 };

	const images = countMatches(body, IMAGE_DIRECTIVE_RE) + countMatches(body, MARKDOWN_IMAGE_RE);
	const words = countWords(toPlainText(body));
	const seconds = (words / WORDS_PER_MINUTE) * 60 + imageSeconds(images);

	return { words, images, seconds };
}

/**
 * Сколько минут читается текст, или null — если он короче трёх минут и метку
 * показывать не надо.
 *
 * @param {string | undefined} body — тело поста в markdown
 * @returns {number | null}
 */
export function getReadingMinutes(body) {
	const { seconds } = measureBody(body);
	// Сравниваем именно секунды, а не округлённые минуты: пост на 2 минуты
	// 55 секунд округлился бы до 3 и метку получил, хотя трёх минут в нём нет.
	if (seconds < MIN_MINUTES * 60) return null;

	return Math.round(seconds / 60);
}
