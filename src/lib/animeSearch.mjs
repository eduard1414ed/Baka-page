//
// Правило появилось на странице тайтла (часть 10) и жило там же, в разметке:
// пока место было одно, копии просто негде было завестись. С 11 августа 2026
// мест стало три — страница тайтла, страница материала и запись внешней статьи
// в индексе, — и правило переехало сюда целиком.
//
// Слов четыре вида, и каждый нужен по своей причине:
//   1. Русское название — то, что человек набирает чаще всего.
//   2. Оригинальное — «Sousou no Frieren» набирают латиницей как есть.
//   3. ВАРИАНТЫ НАПИСАНИЯ из админки: «Кейон» через «е», «Клуб лёгкой музыки»,
//      падежи. Заказчик вписывает их руками ровно затем, чтобы тайтл находился,
//      и вправе ждать, что вписанное подействует ВЕЗДЕ, а не в одном разделе.
//   4. ЛАТИНИЦА КИРИЛЛИЦЕЙ (src/lib/translit.mjs): без неё «гибли» не находил
//      ни одного из трёх тайтлов Ghibli. Переводятся ДАННЫЕ, а не запрос —
//      «гибли» → «gibli» с «ghibli» не совпадёт, по-русски «h» не пишется.
//
// НИ ОДНА ИЗ ЭТИХ СТРОК НЕ ПОКАЗЫВАЕТСЯ ЧИТАТЕЛЮ. Латиница кириллицей читается
// как «соусоу но фрирен», и вслух её произносить незачем — там, где строка
// уходит в разметку, ей полагается `.visually-hidden` и `aria-hidden`.

import { latinSearchForms } from './translit.mjs';

/**
 * Слова, которых НЕТ в тексте страницы тайтла, — варианты написания и латиница
 * кириллицей. Названия и студия там уже стоят своими буквами, и повторять их
 * в невидимом поле значило бы дать Pagefind второй вес тому же слову.
 *
 * @param {{ titleOriginal?: string, studio?: string, aliases?: string[] }} data
 * @returns {string} слова через пробел; пустая строка, если добавить нечего
 */
export function animeSearchExtras(data) {
	const latinSource = [data.titleOriginal, data.studio].filter(Boolean).join(' ');
	return [...(data.aliases ?? []), ...(latinSource ? latinSearchForms(latinSource) : [])].filter(Boolean).join(' ');
}

/**
 * ВСЕ слова тайтла, включая сами названия. Для страниц, где тайтл только
 * УПОМЯНУТ и его названия в тексте может не быть вовсе: материал, где тайтл
 * проставлен рукой в поле «Тайтлы поста», и внешняя статья, у которой текста
 * у нас нет в принципе — есть только заголовок и список размеченных тайтлов.
 *
 * @param {{ titleRu?: string, titleOriginal?: string, studio?: string, aliases?: string[] }} data
 * @returns {string} слова через пробел
 */
export function animeSearchWords(data) {
	return [data.titleRu, data.titleOriginal, animeSearchExtras(data)].filter(Boolean).join(' ');
}
