// Markdown поста → голый читаемый текст. ОДИН КОД НА ВЕСЬ САЙТ.
//
// Зачем отдельный файл. Снимать разметку нужно двоим: счётчику времени чтения
// (src/lib/readingTime.mjs) и подводке материала (src/lib/excerpt.mjs) — а она
// же идёт в описание страницы для поисковика, в превью ссылки в мессенджере
// и в ленту RSS.
//
// Копий было две, и они разъехались ровно так, как обещает CLAUDE.md: счётчик
// времени умел снимать метку тайтла `:anime[Фрирен]{id="…"}`, а подводка — нет,
// и код разметки поехал на карточку, в выдачу поисковика и в телеграм.
// Заметил это заказчик глазами на главной. Поэтому теперь код один.
//
// ЧТО СЮДА НЕ ВХОДИТ. Обрезка на первом спойлере — дело подводки, а не этой
// функции: время чтения, наоборот, обязано считать спрятанный текст, спойлеры
// обычно раскрывают. Разные задачи — разные файлы.

/** Обычная markdown-картинка: `![подпись](адрес)`. */
export const MARKDOWN_IMAGE_RE = /!\[[^\]]*\]\([^)]*\)/g;

/**
 * Снять разметку, оставив то, что человек читает глазами.
 *
 * Порядок замен важен: сначала блочное, потом строчное. Иначе, например,
 * скобки от `[текст](адрес)` съедят содержимое `:anime[Наруто]{…}` раньше,
 * чем до него дойдёт своя замена.
 *
 * @param {string} body Текст в markdown.
 * @returns {string} Текст в одну строку, пробелы схлопнуты.
 */
export function toPlainText(body) {
	if (!body) return '';

	return (
		body
			// Блоки кода целиком — их не читают, их проглядывают.
			.replace(/```[\s\S]*?```/g, ' ')
			// Обычная markdown-картинка вместе с её alt — alt это подпись.
			.replace(MARKDOWN_IMAGE_RE, ' ')
			// Блочная разметка из админки, каждая на своей строке: `::image{...}`
			// с подписью внутри, `::video{...}`, `::spoiler-start{label="..."}`
			// с надписью на кнопке, `::spoiler-end{}`. Убираем строку целиком —
			// вместе с подписями и надписями, но текст МЕЖДУ метками спойлера
			// при этом не трогаем.
			.replace(/^:{2,3}[a-z][\w-]*(?:\{[^}]*\})?[^\n]*$/gim, ' ')
			// Метки внутри строки: `:anime[Фрирен]{id="sousou-no-frieren" …}`,
			// `:spoiler-inline[спрятанное]{}`, `:number[…]`. Оставляем то, что
			// в квадратных скобках, — это и есть видимый текст, — а атрибуты
			// выбрасываем. Вот этой замены и не было в подводке.
			.replace(/:[a-z][\w-]*\[([^\]]*)\](?:\{[^}]*\})?/gi, '$1')
			// Ссылка: остаётся подпись, адрес уходит. Адрес глазами не читают.
			.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
			// Голый адрес, оставшийся в тексте без разметки.
			.replace(/https?:\/\/\S+/g, ' ')
			// Если разметку писали руками через HTML — теги не текст.
			.replace(/<[^>]*>/g, ' ')
			// Решётки заголовков, кавычки цитат, маркеры списков — в начале строки.
			.replace(/^\s{0,3}(?:#{1,6}\s+|>\s?|[-*+]\s+|\d+[.)]\s+)/gm, '')
			// Горизонтальная линия.
			.replace(/^\s{0,3}(?:[-*_]\s*){3,}$/gm, ' ')
			// Звёздочки, подчёркивания, тильды и обратные кавычки — оформление
			// текста, а не текст. Само слово внутри них остаётся.
			.replace(/[*_~`]/g, '')
			.replace(/\s+/g, ' ')
			.trim()
	);
}
