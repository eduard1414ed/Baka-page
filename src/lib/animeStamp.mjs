// Цвет марки аниме. Один код на обе формы марки — вертикальную каталожную
// (AnimeCard.astro) и горизонтальную (AnimeBadge.astro).
//
// ЦВЕТ ВЫБИРАЕТСЯ ПО ИМЕНИ ТАЙТЛА, А НЕ ПО МЕСТУ В РЯДУ. Ряд марок должен быть
// разноцветным, но один и тот же тайтл обязан выглядеть одинаково везде, где
// попадается: иначе «Фрирен» в каталоге и «Фрирен» на главной читались бы
// как две разные вещи. Считай это каждая форма марки сама — копии разъехались
// бы молча, и заметить это можно было бы только сравнив две страницы глазами.
//
// Сами значения — четыре пастельных `--stamp-*` в tokens.css. §3.3 разрешает
// их прямым текстом, но только у марок и только через `--stamp`.

const STAMP_COLORS = 4;

/** @returns {string} `var(--stamp-2)` — подставляется в `--stamp` на марке. */
export function stampVar(animeId) {
	const sum = [...String(animeId)].reduce((total, char) => total + char.charCodeAt(0), 0);
	return `var(--stamp-${(sum % STAMP_COLORS) + 1})`;
}
