// Имена голосов, вписанные руками в админке (тз/05, шаг 6).
//
// Где лежат: одной строкой в поле `speakers` самого поста, например
//   speakers: 'speaker_0=Эд; speaker_1=Ксюша; speaker_2=Даулет Жинайдаров'
//
// ПОЧЕМУ СТРОКОЙ В ПОСТЕ, А НЕ В ФАЙЛЕ РАСШИФРОВКИ. Поле стоит в редакторе
// поста, а расшифровка — другой файл. CMS умеет сохранять только свою же
// запись: писать за одно сохранение в два файла — это два коммита, из которых
// второй может не пройти, и пост разъедется с именами. Пускать же CMS в сам
// файл расшифровки нельзя вовсе — она переписывает файл целиком, а там триста
// оплаченных реплик. Для CMS строка это обычное текстовое поле, терять в нём
// нечего: списки внутри своих компонентов она на втором этапе теряла и портила.
//
// Автоматические имена при этом никуда не деваются — они остаются в файле
// расшифровки, а вписанное руками просто побеждает при показе. Значит, ошибку
// всегда можно отменить, стерев строку.

// Точка с запятой между голосами и знак равенства внутри пары — поэтому в самом
// имени их быть не может. Виджет в админке их вырезает при вводе; тут на всякий
// случай тоже: битую пару лучше пропустить, чем показать читателю мусор.
const PAIR_SEPARATOR = ';';

/** Строка из поста → { speaker_0: 'Эд', … }. Мусор молча пропускается. */
export function parseSpeakerNames(value) {
	const names = {};

	for (const chunk of String(value ?? '').split(PAIR_SEPARATOR)) {
		const at = chunk.indexOf('=');
		if (at === -1) continue;

		const id = chunk.slice(0, at).trim();
		const name = chunk.slice(at + 1).trim();
		if (id && name) names[id] = name;
	}

	return names;
}

/** { speaker_0: 'Эд', … } → строка для поля поста. Пустые имена не пишем. */
export function serializeSpeakerNames(names) {
	return Object.entries(names ?? {})
		.filter(([id, name]) => id && String(name ?? '').trim())
		.map(([id, name]) => `${id}=${String(name).trim()}`)
		.join('; ');
}

/**
 * Расшифровка + строка из поста → расшифровка с подставленными именами.
 *
 * Голос, которого человек не трогал, остаётся с автоматическим именем.
 * Знак `?` в автоматическом имени означает «автоматика сомневалась», и на
 * странице такой голос показывается как «Спикер не определён» (см.
 * speakerLabel в src/lib/transcript.mjs) — вписанное руками имя убирает
 * и сомнение, и эту подпись заодно.
 */
export function applySpeakerNames(transcriptData, value) {
	const names = parseSpeakerNames(value);
	if (Object.keys(names).length === 0) return transcriptData;

	return { ...transcriptData, speakers: { ...transcriptData?.speakers, ...names } };
}
