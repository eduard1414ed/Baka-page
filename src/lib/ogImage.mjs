// Картинки превью для соцсетей: где они лежат и какого размера (тз/08, часть 2.4).
//
// ПРЕВЬЮ ПОВТОРЯЕТ ФОРМУ ОБЛОЖКИ, А НЕ НАОБОРОТ (решение заказчика 20 августа
// 2026). Раньше здесь была полоса ровно 1200×630 на всё: что шире 3:2 —
// обрезалось по центру, остальное вписывалось целиком на бумажный фон.
// Замер по архиву показал цену: из 535 материалов со своей картинкой 279
// получали бумажные поля по краям, а 256 обрезались. Квадратная обложка
// бонуса приезжала в телеграм светлой полосой с квадратиком посередине.
// Теперь квадратная обложка даёт квадратное превью, кадр 16:9 — превью 16:9,
// постер тайтла — вертикальное. Ни полей, ни обрезки: телеграм показывает
// картинку как есть, не подгоняя её под полосу (проверено на живых ссылках,
// см. комментарий про twitter:card в src/layouts/Layout.astro).
//
// Сами файлы делает сборка, src/plugins/og-images-integration.mjs.

/**
 * Общая картинка сайта — единственная, у кого размер задан числом: на ней
 * лежит логотип, а не чья-то обложка, и повторять ей нечего.
 */
export const OG_DEFAULT_WIDTH = 1200;
export const OG_DEFAULT_HEIGHT = 630;

/**
 * Предел длинной стороны. Больше незачем: телеграм показывает превью
 * примерно в 500 px шириной, остальное — лишние килобайты в каждой ссылке.
 */
export const OG_MAX_SIDE = 1200;

/**
 * Предел КОРОТКОЙ стороны, ниже которого картинку растягиваем.
 *
 * Нужен из-за постеров тайтлов: они приходят от Shikimori маленькими —
 * замер по 400 карточкам дал ширину от 208 px, и мельче 600 px там 374 штуки
 * из 400. Мелкую картинку соцсети показывают уголком вместо большой карточки,
 * поэтому такие растягиваем. Растяжение не портит вид: показывают их всё
 * равно мельче, чем 600 px, — оно только добавляет веса файлу.
 *
 * Предел длинной стороны при столкновении СИЛЬНЕЕ: у вытянутой картинки
 * (в архиве самая узкая 486×1000) короткая сторона так и останется меньше 600.
 */
export const OG_MIN_SIDE = 600;

/**
 * Бумажный фон, на который ложится прозрачное.
 *
 * ПРОЗРАЧНОСТЬ В ПРЕВЬЮ НЕ УХОДИТ, И ЭТО РЕШЕНИЕ ЗАКАЗЧИКА, А НЕ ЛЕНЬ:
 * телеграм пересобирает картинку превью у себя, и прозрачный PNG у него
 * может лечь на чёрное — то самое, ради чего правка и затевалась (у бонуса
 * про «Железобетон» вместо фигуры был чёрный квадрат). Бумага предсказуема
 * в любом клиенте и в любой теме. Та же причина записана в coverCutout.mjs
 * про вырезанных персонажей.
 *
 * Единственное место в проекте, где цвет палитры записан числом мимо
 * `--paper` в tokens.css: картинку рисует sharp во время сборки, а он про
 * CSS-переменные ничего не знает. Меняете `--paper` — поправьте и здесь.
 */
export const OG_BACKGROUND = '#F8F6F0';

/** Общая картинка сайта: логотип на бумаге. Достаётся всем, у кого своей нет. */
export const OG_DEFAULT = '/og/default.jpg';

/**
 * Размер превью по размеру исходной картинки — ОДНО ПРАВИЛО НА ПРОЕКТ.
 *
 * Форма сохраняется в точности: ни обрезки, ни полей. Меняется только масштаб,
 * и только в двух случаях — картинка больше предела или меньше него.
 *
 * Считается здесь, а не в сборочном шаге, чтобы правило можно было спросить
 * отдельно от рисования файлов: scripts/og-size.test.mjs гоняет его на живых
 * пропорциях архива и умеет краснеть.
 *
 * @param {number} width Ширина исходной картинки в пикселях.
 * @param {number} height Высота исходной картинки.
 * @returns {{width: number, height: number}} Размер файла превью.
 */
export function ogSize(width, height) {
	// Размеры не прочитались — отдаём размер общей картинки сайта, а решать,
	// что делать дальше, будет вызывающий: рисовать превью не из чего.
	if (!width || !height || width < 1 || height < 1) {
		return { width: OG_DEFAULT_WIDTH, height: OG_DEFAULT_HEIGHT };
	}

	const long = Math.max(width, height);
	const short = Math.min(width, height);

	let scale = 1;
	if (long > OG_MAX_SIDE) scale = OG_MAX_SIDE / long;
	else if (short < OG_MIN_SIDE) scale = Math.min(OG_MIN_SIDE / short, OG_MAX_SIDE / long);

	// Округление сдвигает пропорцию меньше чем на пиксель — этого не видно
	// ни на одном экране, а целые числа обязательны: дробных пикселей нет.
	return { width: Math.max(1, Math.round(width * scale)), height: Math.max(1, Math.round(height * scale)) };
}

/**
 * Адрес превью материала. Плоское имя без папок — так записано в ТЗ.
 */
export function ogUrlForPost(slug) {
	return `/og/${slug}.jpg`;
}

/**
 * Адрес превью страницы тайтла.
 *
 * ПРОСТРАНСТВО ИМЁН У НИХ ОТДЕЛЬНОЕ, и это не украшение: идентификаторы
 * тайтлов и материалов живут в разных справочниках и совпасть могут запросто —
 * тайтл с идентификатором вроде `ep-5` молча перебил бы одноимённый выпуск,
 * и в телеграме у выпуска развернулась бы обложка аниме.
 *
 * Оба адреса собираются здесь, в одном файле: разъехаться им негде.
 */
export function ogUrlForAnime(animeId) {
	return `/og/anime-${animeId}.jpg`;
}
