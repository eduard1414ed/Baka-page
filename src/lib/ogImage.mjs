// Картинки превью для соцсетей: где они лежат и какого размера (тз/08, часть 2.4).
//
// Соцсети показывают превью полосой 1200×630. Материалы на сайте хранятся
// в других пропорциях, поэтому кадрирование нужно всегда, и правило одно:
// ОБРЕЗАЕМ ТОЛЬКО ТО, ЧТО И ТАК ШИРЕ. Кадр 16:9 режется по центру, потери
// минимальны. Квадратная обложка выпуска и постер аниме не режутся вовсе —
// вписываются целиком на бумажный фон: обрезка квадрата до широкой полосы
// срезала бы ровно то, ради чего обложку рисовали.
//
// Сами файлы делает сборка, src/plugins/og-images-integration.mjs.

export const OG_WIDTH = 1200;
export const OG_HEIGHT = 630;

/**
 * Бумажный фон, на который вписывается всё, что не шире полосы.
 *
 * Единственное место в проекте, где цвет палитры записан числом мимо
 * `--paper` в tokens.css: картинку рисует sharp во время сборки, а он про
 * CSS-переменные ничего не знает. Меняете `--paper` — поправьте и здесь.
 */
export const OG_BACKGROUND = '#F8F6F0';

/** Общая картинка сайта: логотип на бумаге. Достаётся всем, у кого своей нет. */
export const OG_DEFAULT = '/og/default.jpg';

/**
 * Адрес превью материала.
 *
 * Плоское имя без папок — так записано в ТЗ. Когда своё превью появится
 * у страниц тайтлов, им понадобится отдельное пространство имён
 * (`/og/anime-<id>.jpg`), иначе тайтл с идентификатором вроде `ep-5`
 * перебил бы выпуск.
 */
export function ogUrlForPost(slug) {
	return `/og/${slug}.jpg`;
}
