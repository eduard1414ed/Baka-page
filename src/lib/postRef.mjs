// Врезка на свой материал: что про материал должны одинаково знать админка
// и сборка (ТЗ «Врезки со ссылками на свои материалы»).
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Одно и то же правило спрашивают двое, и по разным
// поводам: список для админки (src/pages/admin-materials.json.ts) — чтобы
// не дать выбрать «играет здесь» там, где играть нечему; плагин сборки —
// чтобы уронить сборку, если такое всё-таки записано в файле статьи (§6.4 ТЗ).
// Напиши мы правило дважды, разъехались бы они молча: админка разрешала бы
// то, на чём падает сборка, или наоборот — запрещала бы законное, и человек
// пошёл бы искать поломку в исправном.
//
// ЗАСЛОН И ПОДСКАЗКА — РАЗНЫЕ ВЕЩИ, И ОБЕ НУЖНЫ. Подсказка в админке ловит
// ошибку там, где её делают; заслон в сборке ловит то, что пришло мимо
// админки — правку файла руками, импорт, старую вкладку. Убрать заслон
// «раз админка не даст» нельзя: админка не единственный путь в файл.
//
// Файл обычный `.mjs` без импортов из `astro:content`: его читает и сборка
// Astro, и обычный node в проверках. Всё, что нужно, приходит параметрами.

import { isExternalPost } from './externalPost.mjs';

/**
 * КАТЕГОРИИ, У КОТОРЫХ ЗВУК ИЛИ ВИДЕО ЕСТЬ СВОИ.
 *
 * Подкаст — аудио в RSS. Видеоэссе — ролик в теле материала.
 *
 * БОНУСА ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ ЗАКАЗЧИКА ОТ 31 АВГУСТА 2026. Раздел
 * у бонуса «Подкаст» (`sectionOf`), то есть по разделу он от выпуска
 * неотличим, — но своего аудио у него нет вовсе: бонус это указатель
 * на материал, лежащий на Patreon и Boosty. Спрашивать надо КАТЕГОРИЮ,
 * а не раздел, иначе «играет здесь» разрешилось бы у 115 материалов,
 * у которых играть нечего.
 */
const КАТЕГОРИИ_СО_СВОИМ_ЗВУКОМ = ['podcast', 'videoessay'];

/**
 * Может ли врезка на этот материал играть на месте.
 *
 * ВНЕШНИЙ МАТЕРИАЛ НЕ МОЖЕТ НИКОГДА, даже с категорией «Подкаст», — а таких
 * двадцать штук. Своей страницы у него нет, и звука у нас нет тоже: и то
 * и другое живёт на чужом сайте. Признак «внешний» работает поверх любой
 * категории, поэтому спрашивается первым.
 *
 * @param {{ data: Record<string, any> }} post
 * @returns {boolean}
 */
export function canPlayInline(post) {
	const data = post?.data ?? {};
	if (isExternalPost(data)) return false;
	return КАТЕГОРИИ_СО_СВОИМ_ЗВУКОМ.includes(data.category);
}

/**
 * Почему играть нельзя — человеческим языком, для подсказки в админке
 * и для текста ошибки сборки. `null`, если можно.
 *
 * ОДНА ПРИЧИНА НА ДВА МЕСТА, а не две похожие строки в разных файлах:
 * читатель админки и читатель лога сборки — один и тот же человек, и объяснять
 * ему одно и то же двумя способами незачем.
 *
 * @param {{ data: Record<string, any> }} post
 * @returns {string | null}
 */
export function whyCannotPlay(post) {
	const data = post?.data ?? {};
	if (isExternalPost(data)) {
		return 'материал лежит на чужом сайте — ни своей страницы, ни своего звука у него нет';
	}
	if (data.category === 'bonus') {
		return 'у бонуса нет своего аудио: он лежит на Patreon и Boosty';
	}
	if (!КАТЕГОРИИ_СО_СВОИМ_ЗВУКОМ.includes(data.category)) {
		return 'играть можно только выпуск подкаста и видеоэссе';
	}
	return null;
}
