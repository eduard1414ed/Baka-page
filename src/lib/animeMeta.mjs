// ЗАГОЛОВОК И ОПИСАНИЕ СТРАНИЦЫ ТАЙТЛА В ПОИСКОВОЙ ВЫДАЧЕ
// (TASK-markup, пункты 2.2 и 2.3).
//
// ЧТО БЫЛО НЕ ТАК. Заголовок «Унесённые призраками — Бака!» занимал 28 знаков
// из доступных шестидесяти, а описание было куском синопсиса с Shikimori —
// то есть чужим текстом, одинаковым с десятками сайтов. В выдаче страница
// ничем не отличалась от карточки того же аниме где угодно ещё.
//
// ЧТО СТАЛО. И заголовок, и описание собираются из СВОИХ данных: сколько
// у нас материалов про этот тайтл и сколько раз он прозвучал в разговорах.
// Этого нет ни у кого, кроме нас.
//
// ВИДИМЫЙ ТЕКСТ СТРАНИЦЫ НЕ МЕНЯЕТСЯ НИ НА ЗНАК. Синопсис как стоял, так
// и стоит; правила ниже касаются только <title> и <meta name="description">.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ДЕСЯТЬ СТРОК В САМОЙ СТРАНИЦЕ. Правила
// с пределами длины проверяются замером по всему архиву, а не взглядом
// на одну страницу: «влезает ли в 60 знаков» на «Унесённых призраками»
// и на «Легенде о героях Галактики» — разные вопросы. Замер зовёт эти же
// функции (scripts/anime-meta-report.mjs), а не переписывает их рядом.

import { plural } from './plural.mjs';
import { SITE_NAME_GENITIVE } from './site.mjs';
import { isExternalPost } from './externalPost.mjs';
import { КАТЕГОРИЯ_ВЫПУСКА } from './animeIndexability.mjs';

/**
 * Предел заголовка. Шире Google всё равно обрежет многоточием, и обрежет
 * не там, где мы бы хотели.
 */
export const ПРЕДЕЛ_ЗАГОЛОВКА = 60;

/** Предел описания. Ниже 150 держаться не обязаны, выше 160 — нельзя. */
export const ПРЕДЕЛ_ОПИСАНИЯ = 160;

/** Сколько названий материалов перечисляем, если они влезают. */
export const НАЗВАНИЙ_В_ОПИСАНИИ = 3;

/**
 * Из скольких верхних материалов их выбираем.
 *
 * БОЛЬШЕ, ЧЕМ НАЗВАНИЙ, И ЭТО НЕ ЗАПАС «НА ВСЯКИЙ СЛУЧАЙ». Заголовки выпусков
 * длинные («Наруто. Экзамен на Чуунина. Часть 1 | Темари — лучшая героиня
 * аниме и что не так с Гаарой?» — сто знаков), и первый же такой съедает
 * всё описание. Останавливайся мы на первом невлезшем — у «Наруто» со ста
 * шестью материалами в описании стояло бы одно название, а место под второе
 * пропадало бы зря. Поэтому перебираем восьмёрку верхних и берём те, что
 * помещаются, сохраняя их порядок.
 */
const ОТКУДА_ВЫБИРАЕМ = 8;

/**
 * Свои материалы — те же, что считает правило индексируемости.
 *
 * Внешние статьи (лежащие на чужих сайтах) в счёт не идут: страницы у них
 * нет, и «разбор в 5 материалах» с двумя ссылками наружу было бы неправдой.
 * Спрашиваем ту же функцию `isExternalPost`, что и всё остальное в проекте, —
 * своего определения «свой» тут нет.
 */
export function свои(mentions) {
	return (mentions ?? []).filter(({ post }) => !isExternalPost(post.data));
}

/** Выпуск ли это. По КАТЕГОРИИ, а не по разделу ленты: бонус — не выпуск. */
const этоВыпуск = (post) => post?.data?.category === КАТЕГОРИЯ_ВЫПУСКА;

/**
 * Заголовок страницы тайтла целиком, вместе с «Баки!».
 *
 * Возвращает null там, где сказать нечего, — и тогда страница остаётся
 * на прежнем шаблоне «{название} — Бака!». Случаев два: своих материалов нет
 * вовсе (врать нельзя) и заголовок не влезает в предел даже без года
 * (обрезать название запрещено заданием, а обрезать нечего больше).
 *
 * ЛЕСЕНКА СОКРАЩЕНИЯ — С ХВОСТА, А НЕ С НАЗВАНИЯ:
 *   1. «Унесённые призраками (2001) — разбор в 12 материалах «Баки!»»
 *   2. без года: «Унесённые призраками — разбор в 12 материалах «Баки!»»
 *   3. короче: «Унесённые призраками — 12 материалов «Баки!»»
 *   4. прежний шаблон.
 *
 * ТРЕТЬЯ СТУПЕНЬ ЗАВЕДЕНА ЗАМЕРОМ, А НЕ ДЛЯ КРАСОТЫ. Без неё в предел
 * не влезал 101 тайтл из 571 — все длинноимённые, от «Легенды о героях
 * Галактики» до исекаев с названием-предложением, — и все они оставались
 * на прежнем шаблоне, то есть теряли новый сигнал целиком. Короткий хвост
 * возвращает 43 из этих 101. Оставшиеся 58 не спасти ничем: у них одно
 * только название длиннее шестидесяти знаков («Переродившись
 * аристократом-неудачником…» — 103), а резать название задание запрещает.
 *
 * ПРО ОДИН МАТЕРИАЛ. В задании написано «разбор в выпуске «Баки!»», и это
 * верно, когда материал и правда выпуск. Когда единственный материал —
 * заметка или бонус, слово «выпуск» было бы неправдой в том же самом
 * заголовке, где задание запрещает врать про число. Поэтому слово
 * выбирается по категории материала.
 */
export function animeTitle({ name, year, mentions }) {
	const материалы = свои(mentions);
	const N = материалы.length;
	if (N === 0 || !name) return null;

	const хвост =
		N === 1
			? `разбор в ${этоВыпуск(материалы[0].post) ? 'выпуске' : 'материале'} «${SITE_NAME_GENITIVE}»`
			: `разбор в ${N} ${plural(N, ['материале', 'материалах', 'материалах'])} «${SITE_NAME_GENITIVE}»`;

	const сГодом = year ? `${name} (${year}) — ${хвост}` : `${name} — ${хвост}`;
	if (сГодом.length <= ПРЕДЕЛ_ЗАГОЛОВКА) return сГодом;

	const безГода = `${name} — ${хвост}`;
	if (безГода.length <= ПРЕДЕЛ_ЗАГОЛОВКА) return безГода;

	const короткий = `${name} — ${N} ${plural(N, ['материал', 'материала', 'материалов'])} «${SITE_NAME_GENITIVE}»`;
	if (короткий.length <= ПРЕДЕЛ_ЗАГОЛОВКА) return короткий;

	return null;
}

/**
 * Описание страницы тайтла для выдачи.
 *
 * Возвращает null, если своих материалов нет: тогда остаётся синопсис —
 * чужой текст лучше пустоты, так сказано в задании.
 *
 * СТРОИТСЯ С ХВОСТА. Сначала собирается то, ради чего описание и затевалось
 * («12 материалов, 47 упоминаний в разговорах»), и только потом к нему
 * добавляются названия — столько, сколько влезает в предел. Собери мы
 * наоборот, названия вытеснили бы числа, а числа тут главное.
 *
 * ПРО «В ВЫПУСКАХ». Слово выбирается по тому, что на самом деле перечислено:
 * все выпуски — «в выпусках», иначе «в материалах». Одно название — «в
 * выпуске»/«в материале».
 */
export function animeDescription({ mentions }) {
	const материалы = свои(mentions);
	const N = материалы.length;
	if (N === 0) return null;

	const M = материалы.reduce((всего, { times }) => всего + (times?.length ?? 0), 0);

	const проМатериалы = `${N} ${plural(N, ['материал', 'материала', 'материалов'])}`;
	const хвост =
		M > 0
			? `${проМатериалы}, ${M} ${plural(M, ['упоминание', 'упоминания', 'упоминаний'])} в разговорах.`
			: `${проМатериалы}.`;

	// Названия берём в том же порядке, в каком их видит читатель на странице:
	// сверху те, где тайтл обсуждали больше всего.
	const выбранные = [];
	for (const материал of материалы.slice(0, ОТКУДА_ВЫБИРАЕМ)) {
		if (выбранные.length >= НАЗВАНИЙ_В_ОПИСАНИИ) break;
		const проба = [...выбранные, материал];
		if (сложить(проба, хвост).length > ПРЕДЕЛ_ОПИСАНИЯ) continue;
		выбранные.push(материал);
	}

	// Не влезло ни одно название — остаётся один хвост. Он короче ста знаков,
	// зато состоит целиком из наших фактов и ни на кого не похож.
	if (выбранные.length === 0) return хвост;

	return сложить(выбранные, хвост);
}

function сложить(выбранные, хвост) {
	const всеВыпуски = выбранные.every(({ post }) => этоВыпуск(post));
	const где =
		выбранные.length === 1 ? (всеВыпуски ? 'выпуске' : 'материале') : всеВыпуски ? 'выпусках' : 'материалах';
	const названия = выбранные.map(({ post }) => post.data.title);

	return `Обсуждали в ${где} ${перечислить(названия)}. ${хвост}`;
}

/**
 * ««А», «Б» и «В»» — русское перечисление с союзом перед последним.
 *
 * КАВЫЧКИ ВНУТРИ НАЗВАНИЙ ОСТАЮТСЯ КАК ЕСТЬ. Заголовки выпусков сплошь
 * с ёлочками («Как «Монолог фармацевта» обманывает зрителя?»), и вложенная
 * пара — известная беда русской типографики. Городить лапки внутри ёлочек
 * ради мета-тега не стоит: в выдаче Google кавычки часто выбрасывает вовсе,
 * а лишнее правило про типографику завело бы копию того, что уже живёт
 * в src/lib/typography.mjs.
 */
function перечислить(названия) {
	const вКавычках = названия.map((н) => `«${н}»`);
	if (вКавычках.length === 1) return вКавычках[0];
	return `${вКавычках.slice(0, -1).join(', ')} и ${вКавычках.at(-1)}`;
}
