// Фотографии из экспорта телеграма: как они называются и куда встают.
//
// ОДНО ОПИСАНИЕ НА ДВА МЕСТА. Правило раскладки одинаково у разбора
// (scripts/telegram-import.mjs, задача 7.1) и у робота подгрузки
// (scripts/telegram-photos.mjs, задача 7.2): первая фотография идёт И в обложку,
// И первой строкой текста, остальные встают одним блоком ПОСЛЕ текста. Две копии
// этого правила разъехались бы молча — у поста, привезённого сразу с картинками,
// они стояли бы так, а у догруженного иначе, и виноватого потом не найти.
//
// ИМЯ ФАЙЛА В ЗАГРУЗКАХ СЧИТАЕТСЯ ТОЖЕ ЗДЕСЬ, и это та же болезнь, что лечит
// `variantBase` у сжатых копий: имя производного файла обязана считать ОДНА
// функция на обе стороны — и та, что файл создаёт, и та, что потом спрашивает
// «он уже есть?». Робот узнаёт «эта картинка уже привезена» именно по наличию
// файла с таким именем; разойдись два имени — он тащил бы архив заново при
// каждом нажатии, а в посте копились бы дубли.

/** Имя файла фотографии в `public/images/uploads`. */
export const photoFileName = (photoId) => `tg-${photoId}.jpg`;

/** Путь к ней в тексте поста и в поле «Обложка». */
export const photoSrc = (photoId) => `/images/uploads/${photoFileName(photoId)}`;

/**
 * Блок картинки в разметке поста — ровно такой же ставит кнопка в админке.
 *
 * `width="column"` ЗДЕСЬ НЕ УКРАШЕНИЕ. Sveltia дописывает его при сохранении
 * всегда (`toBlock` в public/admin/index.html: `width="${data.width ||
 * 'column'}"`), поэтому без него первое же сохранение поста в админке давало бы
 * правку на пустом месте — по строке на каждую картинку. Сайту эти две записи
 * безразличны: «во всю ширину» узнаётся по `width === 'full'`, а всё остальное
 * одинаково. Наступили 10 августа 2026, увидев коммит заказчика.
 *
 * Меняете здесь — поправьте и `toBlock` в админке: импортировать она не умеет,
 * и это одно из тех мест, где копия неизбежна.
 */
export const imageBlock = (src) => `::image{src="${src}" alt="" width="column"}`;

/**
 * Разложить фотографии вокруг текста поста.
 *
 * Первая картинка в теле не пропадёт: правило «показанное в шапке из текста
 * убирается» (remark-episode-cover.mjs) действует только у выпусков и бонусов,
 * а привезённые посты — заметки. Обложка им нужна для ленты и для превью ссылки,
 * на самой странице она не показывается, поэтому дублирования на экране нет.
 *
 * `intoCover: false` — «обложку не трогать»: у поста она уже стоит либо первая
 * картинка уже привезена раньше. Тогда ВСЁ новое встаёт после текста, а поле
 * обложки остаётся тем, что заказчик выбрал руками. Правка руками сильнее
 * догадки робота.
 *
 * @param {string} body   текст поста без картинок
 * @param {string[]} srcs пути картинок по порядку
 * @returns {{ cover: string, text: string }} cover пустой — поле не менять
 */
export function withPhotos(body, srcs, { intoCover = true } = {}) {
	const [first, ...rest] = srcs;
	const cover = intoCover ? (first ?? '') : '';
	const head = cover ? imageBlock(cover) : '';
	const tail = (cover ? rest : srcs).map(imageBlock).join('\n');

	return { cover, text: [head, body, tail].filter(Boolean).join('\n\n') };
}

/**
 * Уменьшить фотографию и положить в загрузки.
 *
 * 1000 px по длинной стороне — столько же, сколько заказчик уменьшает снимки
 * перед загрузкой в админку руками. УМЕНЬШАТЬ НАДО ДО КОММИТА: попавшее в git
 * остаётся в его истории навсегда, и «потом пережмём» не работает.
 */
export async function savePhoto(from, to) {
	const sharp = (await import('sharp')).default;
	await sharp(from)
		.resize({ width: 1000, height: 1000, fit: 'inside', withoutEnlargement: true })
		.jpeg({ quality: 82 })
		.toFile(to);
}
