// ЧТО ЗНАЧИТ ПУСТОЕ ПОЛЕ В ШАПКЕ МАТЕРИАЛА. Одно правило на схему и на тех,
// кто читает файлы мимо неё.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Админка, сохраняя запись, пишет в незаполненное поле
// ПУСТУЮ СТРОКУ, а не пропускает его. Схема коллекции (src/content.config.ts)
// лечит это на входе, и потому весь сайт живёт с чистыми данными. А плагины
// разметки и скрипты читают те же файлы СЫРЫМИ — `astro:content` для них
// не существует, — и для них лечения не было вовсе.
//
// ЭТО НЕ ДОГАДКА, А ПОЙМАННАЯ ОШИБКА. Плагин врезок собрал адрес ссылки
// через `postHref`, а тот написан так: `data.externalUrl ?? '/posts/…'`.
// Пустая строка НЕ пустая для `??` — она непустая по правилам языка, — и врезка
// вышла с `href=""`, то есть ссылкой в никуда. Разметка при этом выглядела
// безупречно, и увидеть это можно было только нажатием.
//
// В ПРОЕКТЕ ЭТО УЖЕ ЗАПИСАНО УРОКОМ: «правило, пройденное по сайту,
// не пройдено по скриптам, и граница эта невидима». Вот та самая граница,
// и вот дверь через неё.

/**
 * Пустое значение необязательного поля — это «поля нет».
 *
 * @param {unknown} значение
 */
export const emptyToUndefined = (значение) => (значение === '' || значение === null ? undefined : значение);

/**
 * ГАЛОЧКА «ЧЕРНОВИК» ЛЕЧИТСЯ ОСОБО, И ЭТО ОТДЕЛЬНОЕ ПРАВИЛО, А НЕ ИСКЛЮЧЕНИЕ.
 *
 * Остальным полям «ничего» безопасно читать как «поля нет»: обложки нет,
 * описания нет, ссылок нет. У черновика отсутствие поля значит ОПУБЛИКОВАН —
 * так стоит у старых постов, заведённых до появления галочки. Пропусти мы
 * «ничего» через обычную поправку, стёртое значение тихо опубликовало бы
 * неготовый материал, и заметить это было бы некому.
 *
 * Поэтому «ничего» читается как «черновик» — в БЕЗОПАСНУЮ сторону. Отсутствие
 * поля по-прежнему значит «опубликован», это разные случаи.
 *
 * @param {unknown} значение
 */
export const draftValue = (значение) => (значение === '' || значение === null ? true : значение);

/**
 * Шапка, прочитанная сырой, — в том виде, в каком её видит сайт.
 *
 * Зовут отсюда все, кто читает файлы материалов в обход схемы: плагин врезок,
 * разовые скрипты, проверки. Своей поправки на месте писать нельзя — она
 * разъедется со схемой молча, и разойдётся именно там, где поле пустое,
 * то есть в самом редком и самом незаметном случае.
 *
 * @param {Record<string, any>} шапка Разобранный YAML шапки, как есть.
 * @returns {Record<string, any>} Она же, но с вылеченными пустотами.
 */
export function normalizeFrontmatter(шапка) {
	const итог = {};
	for (const [поле, значение] of Object.entries(шапка ?? {})) {
		итог[поле] = поле === 'draft' ? draftValue(значение) : emptyToUndefined(значение);
	}
	// Даты в сырой шапке бывают и строкой, и датой — js-yaml разбирает
	// незакавыченную дату сам, а закавыченную оставляет строкой. Дальше
	// у них спрашивают `getTime`, и строка уронила бы это невнятно.
	for (const поле of ['date', 'publishAt']) {
		if (итог[поле] !== undefined && !(итог[поле] instanceof Date)) итог[поле] = new Date(итог[поле]);
	}
	return итог;
}
