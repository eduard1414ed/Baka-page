// ИНДЕКСИРУЕМОСТЬ СТРАНИЦЫ ТАЙТЛА — ВЫЧИСЛЯЕМЫЙ ПРИЗНАК, А НЕ ГАЛОЧКА.
//
// Страниц тайтлов 658, и почти половина держится на одном упоминании без
// таймкодов: своего содержания там нет, только описание с Shikimori (то есть
// чужой текст, лежащий ещё на сотне сайтов) и одна карточка. Такие страницы
// разбавляют домен и мешают ранжироваться сильным.
//
// Признак пересчитывается ПРИ КАЖДОЙ СБОРКЕ. Это не разовая расстановка
// флагов: архив живой, упоминания копятся, и страница обязана входить
// в индекс сама, когда наберёт вес, — без чьего-либо участия.
//
// НИЧЕГО НЕ ПРЯЧЕТСЯ ОТ ЧИТАТЕЛЯ. Все 658 страниц остаются на сайте, работают
// в навигации и во внутреннем поиске Pagefind. Меняется ровно одно: отдаются
// ли они поисковым системам (`noindex, follow` в разметке и отсутствие строки
// в карте сайта). Поиск по сайту и поисковик снаружи — разные вещи.
//
// ─────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ФАЙЛ ЗДЕСЬ, А НЕ В `src/config/indexability.js`
//
// Задание (тз/TASK-indexability.md) называет тот путь. Требование под ним —
// «пороги лежат одним местом, а не размазаны по коду», и оно выполняется
// здесь. А папки `src/config/` в проекте нет вовсе: пороги живут рядом
// с правилом, которое их читает, — `OG_MAX_SIDE` в `ogImage.mjs`, размер
// страницы архива в `archive.mjs`, вес упоминания в `animeMentionIndex.mjs`.
// Завести второй дом для чисел значит заставить следующего искать порог
// в двух местах.
//
// Довод сильнее: число обязано лежать рядом с правилом, которое его читает,
// чтобы САМОПРОВЕРКА МОГЛА СПРОСИТЬ ОБА РАЗОМ. `scripts/og-size.test.mjs`
// импортирует и правило `ogSize`, и пределы из одного файла — и потому
// проверяет правило целиком. Разнеси их — и подлог сможет подменить правило,
// оставив числа зелёными.
// ─────────────────────────────────────────────────────────────────────────

import { isExternalPost } from './externalPost.mjs';
// Нужны только фасаду в самом низу файла. Само правило (`решить`) ничего
// отсюда не берёт и проверяется без Astro и без указателя упоминаний.
import { sharedMentionIndex, postsForAnime } from './animeMentionIndex.mjs';

/**
 * Веса счёта.
 *
 * ЗАМЕР по архиву на 30 августа 2026 (658 страниц тайтлов, 2765 карточек
 * в блоках «упоминания»), от него и подобраны:
 *
 *   свои     — 2409 карточек ведут на наши страницы, 356 на чужие сайты;
 *   таймкоды — есть у 261 страницы из 658, всего 3199 меток;
 *   подкаст  — 791 карточка выпуска.
 *
 * ПОЧЕМУ У ПОДКАСТА ВЕС 2, А НЕ 1 (как было в задании). Решение заказчика:
 * страница, о тайтле которой говорили в выпуске, обязана быть в индексе
 * всегда. У выпуска вес 2, а сам он считается ещё и своим материалом (+1),
 * поэтому одного выпуска хватает ровно на порог. Без этого страница
 * с упоминанием в выпуске, но без размеченных таймкодов, набирала 2
 * и закрывалась — при том что страница с одним таймкодом проходила.
 *
 * ПОЧЕМУ ТАЙМКОДЫ — ДА/НЕТ, А НЕ ЧИСЛО. Счёт решает один вопрос: пускать
 * или нет. 531 таймкод «Наруто» и один таймкод «Седьмого духа» отвечают на
 * него одинаково, а разница между ними порогу не нужна.
 */
export const ВЕСА = Object.freeze({ свои: 1, таймкоды: 2, подкаст: 2 });

/**
 * Порог: со счётом ниже страница из индекса закрыта.
 *
 * Словами правило читается так: **в индексе страница, у которой есть хотя бы
 * один свой выпуск подкаста, ИЛИ хотя бы один таймкод, ИЛИ три своих
 * материала любого рода.**
 *
 * ЗАМЕР порогов на том же архиве (счёт без поглощения):
 *   порог 2 → 349 в индексе, порог 3 → 305, порог 4 → 269, порог 5 → 231.
 * На тройке закрывается ровно то, ради чего задача затевалась: 87 страниц
 * без единого своего материала и 238 с одним.
 */
export const ПОРОГ = 3;

/**
 * Сколько перемен статуса за сборку считается поводом сказать вслух.
 *
 * Заказчик решил 30 августа 2026: сборку НЕ РОНЯТЬ, только предупреждать
 * (задание требовало падения). Довод заказчика принят, но у решения есть
 * слепое пятно, и оно записано здесь, чтобы не потерялось: большинство
 * сборок делает Hetzner по расписанию, консоль там не читает никто, —
 * значит предупреждение обязано попадать ещё и в лог, а со временем
 * в письмо робота.
 */
export const ПРЕДЕЛ_ПЕРЕМЕН = 40;

/** Сколько дней держать логи переходов, прежде чем убрать. */
export const ХРАНИТЬ_ЛОГОВ = 30;

/**
 * КАКАЯ КАТЕГОРИЯ СЧИТАЕТСЯ ВЫПУСКОМ. Строго `podcast`, и «Бонус» сюда
 * НЕ ВХОДИТ — решение заказчика от 30 августа 2026.
 *
 * Это не придирка к слову, а разница по существу, и она чуть не проехала
 * молча. В разметке карточки стоит не категория, а РАЗДЕЛ ЛЕНТЫ:
 * `sectionOf('bonus')` возвращает `'podcast'` (у категории стоит
 * `feedWith: 'podcast'`, см. src/content.config.ts), поэтому бонус
 * в собранной странице выглядит выпуском. Первый замер это и посчитал —
 * и завысил число страниц в индексе на 19.
 *
 * По существу же бонус — тизер: заголовок, описание и плашка подписки,
 * а сам материал лежит на Patreon и Boosty. Страница тайтла с одной такой
 * карточкой — ровно та тонкая страница, ради которой задача затевалась.
 *
 * ЗАМЕР: бонусов в блоках упоминаний 142; страниц, которые держались бы
 * в индексе ТОЛЬКО на бонусе, — 19 (3-gatsu-no-lion, haikyuu-second-season,
 * оба «ДжоДжо» и другие: у каждой в блоке ровно одна карточка).
 */
export const КАТЕГОРИЯ_ВЫПУСКА = 'podcast';

/**
 * Что даёт странице список её упоминаний.
 *
 * СЧЁТ СЧИТАЕТСЯ ПО ТОМУ ЖЕ СПИСКУ, КОТОРЫЙ ВИДИТ ЧИТАТЕЛЬ. На вход идёт
 * ровно то, что вернул `postsForAnime` и что рисуется в блоке «упоминания».
 * Посчитай мы своим кодом — счёт и страница разъехались бы, и отличить это
 * от правды было бы нечем.
 *
 * @param {{ post: { id: string, data: object }, times: number[] }[]} упоминания
 * @returns {{ свои: string[], подкаст: number, таймкоды: boolean }}
 */
export function разобратьУпоминания(упоминания) {
	// Внешние в счёт не идут, но и не штрафуют: страница с одними ссылками
	// на чужие сайты просто ждёт, пока наберёт своих.
	const свои = упоминания.filter(({ post }) => !isExternalPost(post.data));

	return {
		свои: свои.map(({ post }) => post.id).sort(),
		подкаст: свои.filter(({ post }) => post.data.category === КАТЕГОРИЯ_ВЫПУСКА).length,
		таймкоды: свои.some(({ times }) => (times?.length ?? 0) > 0),
	};
}

/**
 * Счёт страницы. Чистая арифметика, без порога и без поглощения.
 *
 * @param {{ свои: string[], подкаст: number, таймкоды: boolean }} что
 * @returns {number}
 */
export function счёт({ свои, подкаст, таймкоды }) {
	return свои.length * ВЕСА.свои + (таймкоды ? ВЕСА.таймкоды : 0) + подкаст * ВЕСА.подкаст;
}

/**
 * Ручное переопределение: `true` — всегда в индекс, `false` — всегда закрыто,
 * ничего — работает правило.
 *
 * Читается ОТДЕЛЬНОЙ функцией, а не сравнением на месте, ровно по одной
 * причине: `undefined` и `false` тут значат разное, и спутать их — значит
 * закрыть от поисковика весь каталог. Sveltia на снятую галочку пишет то
 * `false`, то пустую строку, то `null`; поле поэтому не галочка, а выбор
 * из трёх, и пустота читается как «правило работает».
 *
 * @returns {true | false | null}
 */
export function переопределение(data) {
	const v = data?.forceIndex;
	if (v === true || v === 'true') return true;
	if (v === false || v === 'false') return false;
	return null;
}

/**
 * Снимки страниц: всё, что правилу нужно знать, и ничего сверх.
 *
 * Без ввода-вывода — читает уже загруженные коллекции. Отделено от `решить`
 * затем, чтобы правило можно было спросить на подложенных данных, не поднимая
 * ни Astro, ни указателя упоминаний.
 *
 * @returns {{ id: string, франшиза: string|null, force: true|false|null,
 *             свои: string[], подкаст: number, таймкоды: boolean }[]}
 */
export function снимки({ animeList, posts, index }, postsForAnime) {
	return animeList.map((entry) => {
		const разбор = разобратьУпоминания(postsForAnime(entry.id, posts, index));
		return {
			id: entry.id,
			// Пустая франшиза — это «одиночка», а НЕ группа пустых. Про цену
			// путаницы см. `решить`.
			франшиза: entry.data.franchise || null,
			force: переопределение(entry.data),
			...разбор,
		};
	});
}

/**
 * ГЛАВНОЕ ПРАВИЛО. Порядок страниц на входе на ответ не влияет — по
 * построению, а не потому, что мы их отсортировали.
 *
 * Две ступени.
 *
 * 1. СЧЁТ. Ниже порога — закрыта.
 *
 * 2. ПОГЛОЩЕНИЕ ВНУТРИ ФРАНШИЗЫ. Страница закрыта, если есть страница ТОЙ ЖЕ
 *    непустой франшизы, у которой все её упоминания есть и их СТРОГО больше.
 *    Смысл: у сезона нет ничего своего — всё, что о нём сказано, уже стоит
 *    на странице основного тайтла, и в выдаче они конкурируют за один запрос.
 *    ЗАМЕР: закрывает 16 страниц — пять сезонов «Атаки титанов», два арка
 *    «Клинка», «Моб Психо 2» и «3», «Волейбол!! 2», «Ребёнок идола 2» и т.д.
 *
 * ПОЧЕМУ ПОГЛОЩЕНИЕ ОГРАНИЧЕНО ФРАНШИЗОЙ. Без ограничения то же правило
 * ловит 85 страниц, и почти всё это мусор: «Драконий жемчуг» (6 своих
 * материалов) оказывается поглощён «Наруто», «Седьмой дух» — «Юри на льду»,
 * «Бесконечный поезд» — «Магической битвой». Совпадение постов там принято
 * за родство. НЕ СНИМАЙТЕ ЭТО ОГРАНИЧЕНИЕ, оно не усложнение, а всё правило.
 *
 * ПОЧЕМУ ЭТОГО ХВАТАЕТ ПРОТИВ ЛОЖНОГО РОДСТВА. Shikimori кладёт в одну
 * франшизу и разные экранизации: «Стальной алхимик» (2003) и «Братство»
 * (2009) — одна франшиза `fullmetal_alchemist`. Поглощение их не трогает,
 * потому что у «Братства» три своих материала, которых нет у соседа.
 * То есть точная группировка и проверка на собственный материал работают
 * вместе, и поодиночке ни та, ни другая не справилась бы.
 *
 * НИЧЬЯ НЕ ЗАКРЫВАЕТ НИКОГО — из-за строгого «больше». ЗАМЕР: таких пар 3
 * («ДжоДжо: Египет» и «Рыцари звёздной пыли» и др.). Разбить ничью можно
 * было бы по алфавиту или по порядку файлов — и это ровно та мина, про
 * которую в проекте записан урок «равенство, разрешаемое порядком файлов».
 * Цена ошибки к тому же несимметрична: лишняя страница в индексе чинится
 * галочкой, а обе закрытые страницы одной арки — потерянный материал,
 * пропажи которого никто не заметит.
 *
 * ЦЕПОЧКИ решаются сами: поглощение считается против ВСЕХ членов семьи,
 * а включение множеств транзитивно. Итераций до неподвижной точки не нужно,
 * а значит нет и вопроса «в каком порядке итерировали».
 *
 * @param {ReturnType<typeof снимки>} страницы
 * @returns {Map<string, object>}
 */
/** Ключ корзины, в которую складываются тайтлы без франшизы. Семьёй она
 *  не является: см. `семьяДля` ниже. */
const ОДИНОЧКИ = Symbol('без франшизы');

export function решить(страницы) {
	const счета = new Map(страницы.map((с) => [с.id, счёт(с)]));
	const прошла = (с) => счета.get(с.id) >= ПОРОГ;

	// Семьи. Одиночки (франшиза пустая) в семьи не собираются ВОВСЕ.
	// Свалить их в общую группу значило бы объявить сотни не связанных
	// друг с другом тайтлов сезонами друг друга — это тот самый случай
	// «без ограничения франшизой», который ловит 85 страниц мусора.
	const семьи = new Map();
	for (const с of страницы) {
		const ключ = с.франшиза ?? ОДИНОЧКИ;
		if (!семьи.has(ключ)) семьи.set(ключ, []);
		семьи.get(ключ).push(с);
	}

	// ВСЯ ЗАЩИТА ОТ ЛОЖНОГО РОДСТВА — В ЭТОЙ ОДНОЙ СТРОКЕ, и написана она
	// так нарочно: подлог самопроверки разводит её одну и обязан покраснеть.
	// Одиночка (пустая франшиза) семьи не имеет ВОВСЕ — не «семью из себя»,
	// а именно никакой. Отдай мы ей общую корзину `ОДИНОЧКИ` — сотни
	// не связанных тайтлов стали бы сезонами друг друга.
	const семьяДля = (с) => (с.франшиза ? семьи.get(с.франшиза) : []);

	const свои = new Map(страницы.map((с) => [с.id, new Set(с.свои)]));

	/** Кто поглотил страницу, или null. */
	function поглотитель(с) {
		if (с.force === true) return null;
		const A = свои.get(с.id);
		for (const b of семьяДля(с)) {
			if (b.id === с.id) continue;
			// Закрытая руками страница поглощать не может: иначе она утащила бы
			// за собой сезоны, и вся семья исчезла бы из индекса разом — при
			// том что человек закрывал ровно одну страницу.
			if (b.force === false) continue;
			if (b.свои.length <= A.size) continue;
			const B = свои.get(b.id);
			let внутри = true;
			for (const p of A) if (!B.has(p)) { внутри = false; break; }
			if (внутри) return b.id;
		}
		return null;
	}

	const решения = new Map();
	for (const с of страницы) {
		const кто = поглотитель(с);
		// Порядок причин важен для отчётности: «мало» стоит ВЫШЕ «поглощена»,
		// поэтому счётчик поглощённых считает только те страницы, которые
		// иначе были бы в индексе, и его можно сверить с замером «16».
		let index;
		let причина;
		if (с.force === true) { index = true; причина = 'вручную-в'; }
		else if (с.force === false) { index = false; причина = 'вручную-из'; }
		else if (!прошла(с)) { index = false; причина = 'мало'; }
		else if (кто) { index = false; причина = 'поглощена'; }
		else { index = true; причина = 'сила'; }

		решения.set(с.id, {
			id: с.id,
			index,
			причина,
			счёт: счета.get(с.id),
			свои: с.свои.length,
			подкаст: с.подкаст,
			таймкоды: с.таймкоды,
			франшиза: с.франшиза,
			поглотитель: причина === 'поглощена' ? кто : null,
			force: с.force,
			своиПосты: с.свои,
		});
	}
	return решения;
}

/**
 * ФАСАД ДЛЯ СБОРКИ: одна точка, из которой решение берут ВСЕ.
 *
 * Потребителей трое, и это ровно то место, где задача может испортить дело:
 *
 *   1. `src/pages/anime/[slug].astro` — ставит `noindex` в разметку;
 *   2. `src/pages/sitemap.xml.ts`     — решает, класть ли строку в карту;
 *   3. `src/pages/indexability.json.ts` — отдаёт данные логу переходов.
 *
 * РАЗМЕТКА И КАРТА ОБЯЗАНЫ ОТВЕЧАТЬ ОДИНАКОВО. Скажи страница «не индексируй»,
 * а карта позови робота на неё же — это противоречивый сигнал, и задание
 * называет его худшим из возможных исходов. Поэтому правило считается ЗДЕСЬ
 * и один раз, а не по месту: страница тайтла не пересчитывает свой флаг
 * из собственного списка упоминаний, хотя список у неё на руках, — иначе это
 * была бы вторая реализация правила, и разъехались бы они молча.
 *
 * Кэш на процесс, ключ — длины коллекций, как у `buildCatalog`
 * и `sharedMentionIndex`. Сам указатель упоминаний берётся общий, так что
 * лишних 12 секунд задача не добавляет.
 *
 * @returns {Map<string, object>} id тайтла → решение
 */
let кэшРешений = null;

export function индексируемостьСборки({ posts, transcripts, animeList }) {
	const ключ = `${posts.length}:${transcripts.length}:${animeList.length}`;
	if (кэшРешений?.ключ === ключ) return кэшРешений.решения;

	const index = sharedMentionIndex({ posts, transcripts, animeList });
	const решения = решить(снимки({ animeList, posts, index }, postsForAnime));
	кэшРешений = { ключ, решения };
	return решения;
}
