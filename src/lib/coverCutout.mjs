// Персонаж вместо обложки: вырезанная фигура на прозрачном фоне (тз/12).
//
// Обложки выпусков сделаны по одному шаблону — светлый фон, чёрная рамка,
// надпись «БАКА!», кана слева, вертикальная подпись справа, персонаж внутри.
// В подкаст-приложениях этот шаблон нужен, а на сайте он повторяется на каждой
// карточке, и лента превращается в сетку из одинаковых «БАКА!». Поэтому на
// сайте показывается только персонаж, прямо на бумаге.
//
// Картинки делает разовый скрипт scripts/cover-cutout.mjs, он же пишет список.
// Оригиналы обложек в репозиторий не кладём: они живут у хостинга подкаста.
//
// ПОЧЕМУ ФАЙЛЫ ЛЕЖАТ РЯДОМ С ОБЛОЖКАМИ, А НЕ ВМЕСТО НИХ. Вырезанный персонаж
// не заменяет обложку, а дополняет её: прежняя копия остаётся на диске
// и подставляется сама, если персонажа для этой обложки нет. Значит плохо
// вырезанный персонаж чинится удалением ОДНОГО файла — этот выпуск вернётся
// к обычной обложке, и ни строчки кода править не надо.
//
// Обложка в RSS подкаста не меняется вовсе: она приходит из Mave и нужна
// подкаст-приложениям такой, какая есть.

// Список готовых картинок. Пишется скриптом из настоящего содержимого папки
// public/cutout/. Почему списком, а не проверкой файла на диске, и почему js,
// а не json, — ровно те же две причины, что у обложек выпусков: см. подробное
// объяснение в src/lib/episodeCover.mjs.
import CUTOUT_IDS from '../data/coverCutouts.mjs';

/** Два размера, не больше — правило проекта. Холст квадратный, 1200. */
export const CUTOUT_WIDTHS = [640, 1200];

const KNOWN = new Set(CUTOUT_IDS);

/**
 * Ключ картинки, загруженной в админку: "/images/uploads/Пони.png" → "Пони".
 *
 * У выпусков ключ другой — id картинки с хостинга подкаста, его считает
 * `coverIdFromUrl` в episodeCover.mjs. Два источника, два ключа, одна папка:
 * пространства имён у них не пересекаются, потому что id хостинга это uuid.
 *
 * @returns {string | null} null, если это не загруженная в админку картинка.
 */
export function cutoutIdForUpload(cover) {
	if (typeof cover !== 'string' || !cover.startsWith('/images/uploads/')) return null;
	const name = decodeURIComponent(cover.slice('/images/uploads/'.length));
	const dot = name.lastIndexOf('.');
	return dot === -1 ? name : name.slice(0, dot);
}

/** Есть ли для этого ключа вырезанный персонаж. */
export function hasCutout(id) {
	return Boolean(id) && KNOWN.has(id);
}

/**
 * Готовый набор для вывода, или null — если персонажа для этой обложки нет.
 *
 * @returns {{src: string, srcset: string} | null}
 */
export function cutoutSrcs(id) {
	if (!hasCutout(id)) return null;

	const variants = CUTOUT_WIDTHS.map((width) => ({
		width,
		src: encodeURI(`/cutout/${id}-${width}w.webp`),
	}));

	return {
		// В src самый маленький: его берут браузеры, не понимающие srcset,
		// и им лучше получить лёгкий файл, чем тяжёлый. Тот же порядок,
		// что у обложек выпусков и у картинок из админки.
		src: variants[0].src,
		srcset: variants.map((v) => `${v.src} ${v.width}w`).join(', '),
	};
}

/**
 * Картинка персонажа для превью в соцсетях — САМЫЙ КРУПНЫЙ размер.
 *
 * Отдаётся не как есть, а исходником для картинки 1200×630, которую рисует
 * сборка (src/plugins/og-images-integration.mjs). Та кладёт её НА БУМАГУ
 * и сохраняет в jpeg: прозрачный PNG в телеграме может лечь на чёрное,
 * и персонаж пропадёт совсем.
 *
 * @returns {string | null}
 */
export function cutoutSocialSource(id) {
	if (!hasCutout(id)) return null;
	return encodeURI(`/cutout/${id}-${CUTOUT_WIDTHS[CUTOUT_WIDTHS.length - 1]}w.webp`);
}
