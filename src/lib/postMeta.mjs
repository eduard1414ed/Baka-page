// Номер выпуска для метастроки карточки: `[ ПОДКАСТ ] · №135 · 01:06:33`.
//
// Отдельного поля с номером у поста нет и заводить его не стали: 143 выпуска
// архива пришлось бы заполнять руками. Номер берётся из имени файла — `ep-135`.
// Оно не выдумано и не случайно: робот сверки составляет его из адреса выпуска
// на хостинге подкаста (`…/ep-135`), см. scripts/sync-episodes.mjs.
//
// У выпуска без нормального адреса тот же робот кладёт запасное имя из куска
// guid — `ep-a1b2c3d4`. Число из такого имени не вытащить, и придумывать его
// нельзя: номер, взятый с потолка, хуже отсутствующего. Тогда метастрока просто
// обходится без номера, как у статьи или заметки.

/** Имя файла выпуска, из которого получается номер. */
const EPISODE_ID_RE = /^ep-(\d+)$/;

/**
 * Номер выпуска строкой — «№135», или null.
 *
 * @param {string} id Имя файла поста без расширения (post.id).
 * @returns {string | null}
 */
export function episodeNumber(id) {
	const number = episodeNumberValue(id);
	return number === null ? null : `№${number}`;
}

/**
 * Тот же номер, но числом — для разметки Schema.org (`episodeNumber`).
 *
 * Отдельная функция, а не разбор знака «№» на месте: правило «откуда берётся
 * номер» обязано жить в одном месте, иначе вторая копия однажды перестанет
 * знать про запасное имя `ep-a1b2c3d4` и выдаст NaN.
 *
 * @param {string} id Имя файла выпуска без расширения (post.id).
 * @returns {number | null}
 */
export function episodeNumberValue(id) {
	const match = EPISODE_ID_RE.exec(id ?? '');
	// Number() убирает возможный ведущий ноль: «ep-007» → 7.
	return match ? Number(match[1]) : null;
}
