// Короткий слепок значения поля тайтла (тз/05, шаг 6; CLAUDE.md, «Тайтл»).
//
// Зачем. Правленое руками поле нельзя перезаписывать данными из Shikimori
// или AniList, и признак стоит по каждому полю отдельно. Чтобы заказчику
// не приходилось помнить про галочку, админка ставит её сама — но для этого
// ей надо сравнить сохраняемое значение с тем, что лежало в файле раньше.
// Возить в браузер сами описания (у иного тайтла это полторы тысячи знаков
// на каждый из сотен тайтлов) незачем — хватает слепка на несколько букв.
//
// Хеш тут не про подлинность, а только про «изменилось / не изменилось»,
// поэтому берём самый простой и быстрый (FNV-1a).
//
// ВАЖНО: точно такая же функция продублирована в public/admin/index.html —
// админка это отдельная статическая страница, импортировать из src она не
// может. Меняете тут — поправьте и там, иначе сравнение перестанет сходиться.

export function fieldHash(value) {
	// Пробелы по краям не считаем правкой: CMS их местами добавляет и убирает
	// сама, и без этого поле помечалось бы правленым от одного открытия формы.
	const text = String(value ?? '').trim();
	let hash = 0x811c9dc5;

	for (let i = 0; i < text.length; i++) {
		hash ^= text.charCodeAt(i);
		hash = Math.imul(hash, 0x01000193) >>> 0;
	}

	return hash.toString(16);
}
