// ПО ЧЕМУ И ГДЕ ИЩУТСЯ УПОМИНАНИЯ ТАЙТЛОВ — ОДНО МЕСТО НА ВЕСЬ ПРОЕКТ
// (тз/05, шаг 5, вторая половина; тз/11, части A и B).
//
// Тут живут ровно три правила, и второй копии у них быть не должно:
//   1. ПО ЧЕМУ ищем — `buildAnimeMatcher`: русское и оригинальное название,
//      оба списка вариантов написания, кусок названия до двоеточия;
//   2. ГДЕ считается совпадением — `findMentions`: регистр, «е»/«ё», границы
//      слова, галочка «только в кавычках» (`strictQuotes`);
//   3. что с найденным делать — `splitByMentions` и `collectMentions`.
//
// РАЗМЕТКА ПОСТОВ ЗОВЁТ ЭТОТ ЖЕ КОД. Работает она с деревом markdown
// (src/plugins/remark-anime.mjs) — тексты постов это markdown, расшифровки JSON,
// одним куском их не разобрать, — но список названий и правило совпадения
// берёт отсюда. До этапа 11, части B, у неё была своя копия правила «по чему
// ищем»: она знала только `titleRu` и `titleOriginal` и не знала о вариантах
// написания вовсе. Разъехавшуюся копию не было видно ровно потому, что
// ручные варианты заполнены у двух тайтлов из 53, — расхождению нечем было
// проявиться (СТАТУС.md, хвост 45).
//
// Что у постов остаётся своим: КАКИЕ тайтлы искать (только стоящие в поле
// «Тайтлы поста») и сколько упоминаний размечать (первое, дальше обычный
// текст). Это правила про пост, а не про названия, и они живут у плагина.
//
// Чистые функции: ни сети, ни файлов.

const MIN_NAME_LENGTH = 2;

// КАВЫЧКИ СЧИТАЕМ ВСЕХ ВИДОВ (тз/11, B.3). Архив привезён из мессенджера
// и писан людьми: там встречаются и ёлочки, и лапки, и прямые, и апострофы,
// и то, что подставил автозамену телефон. Открывающую от закрывающей мы
// не отличаем нарочно — «Монстр“ с лапкой не с той стороны это опечатка
// человека, а не повод не найти упоминание.
const QUOTES = new Set([
	'«', '»', // ёлочки
	'„', '“', '”', '‟', // лапки во всех сочетаниях
	'"', '＂', // прямая и её широкий двойник
	"'", '‘', '’', '‚', '‛', // апострофы и одиночные
	'‹', '›', // одиночные ёлочки
	'「', '」', '『', '』', // японские
]);

function isQuote(char) {
	return char !== undefined && QUOTES.has(char);
}

// КАВЫЧКА НЕ ОБЯЗАНА СТОЯТЬ ВПЛОТНУЮ, И ЭТО НЕ ПОСЛАБЛЕНИЕ, А ЗАМЕР.
// Первая редакция требовала кавычку ровно рядом с названием — и на живом
// архиве отвергла бы «Магическую битву 0» и «Магическая битва 2»: номер сезона
// автор пишет ВНУТРИ кавычек, и между названием и закрывающей кавычкой стоит
// пробел с цифрой. То же с годом: «Призрак в доспехах (1995)».
//
// Поэтому кавычка ищется через короткий хвост, в котором НЕТ НИ ОДНОЙ БУКВЫ:
// цифры, пробелы, точки и скобки кавычек не отменяют, а первая же буква
// отменяет. Так «монстр в тексте про кайдзю» до кавычек соседней фразы
// не дотягивается, а «„Монстр“ Наоки Урасавы» находится.
//
// Восемь знаков — чтобы хвост не перерос в поиск кавычки по всей строке:
// «Магическая битва 2» это два знака, «Призрак в доспехах (1995)» — семь.
const QUOTE_TAIL = 8;

function quoteNear(text, from, step) {
	for (let i = 0, at = from; i <= QUOTE_TAIL; i++, at += step) {
		const char = text[at];
		if (char === undefined) return false;
		if (isQuote(char)) return true;
		if (/\p{L}/u.test(char)) return false;
	}
	return false;
}

/**
 * ВСЕ ФРАЗЫ В КАВЫЧКАХ ИЗ ОДНОГО КУСКА ТЕКСТА (тз/11, C.1, первый шаг).
 *
 * Живёт тут, а не в скрипте разведки, ровно по той же причине, по которой тут
 * живёт `isQuotedAt`: НАБОР КАВЫЧЕК ОДИН НА ПРОЕКТ. Заведи сбор кандидатов свой
 * список — и он молча разошёлся бы с тем, по которому считает сайт: одна
 * сторона видела бы японские скобки, другая нет, и фраза, из-за которой тайтл
 * не завели, на сайте потом ссылкой бы не стала (или наоборот).
 *
 * Пары ищутся подряд и не вкладываются: открывающую от закрывающей мы
 * не отличаем нарочно (см. QUOTES выше), поэтому «первая кавычка — открыла,
 * следующая — закрыла». Для мессенджерного архива это единственное, что
 * работает: там сплошь и рядом «Монстр“ с лапкой не с той стороны.
 *
 * Ничего не отсеивается: ни длина, ни отсутствие букв. Всё, что тут вернулось,
 * отсеивают ПОТОМ и вслух — иначе выброшенное молча никто не пересчитает
 * (scripts/anime-candidates-lib.mjs, все отказы попадают в отчёт числом).
 *
 * @returns {{ text: string, start: number, end: number }[]}
 */
export function collectQuotedPhrases(text) {
	const source = String(text ?? '');
	const out = [];

	let open = -1;
	for (let i = 0; i < source.length; i++) {
		if (!isQuote(source[i])) continue;
		if (open === -1) {
			open = i;
			continue;
		}
		const inner = source.slice(open + 1, i);
		if (inner.trim()) out.push({ text: inner, start: open + 1, end: i });
		open = -1;
	}

	return out;
}

/**
 * Стоит ли найденный кусок в кавычках — ровно тот вопрос, который задаёт себе
 * `findMentions` у тайтла с галочкой «только в кавычках».
 *
 * Наружу вынесено ради разведки (`scripts/anime-quotes.mjs`): отчёт обязан
 * считать кавычки ТЕМ ЖЕ кодом, которым их потом посчитает сборка, иначе
 * заказчику будут названы числа, не совпадающие с тем, что случится на сайте.
 */
export function isQuotedAt(text, start, end) {
	return quoteNear(text, start - 1, -1) && quoteNear(text, end, 1);
}

// Название до двоеточия ищем отдельно: в справочнике «Королевские космические
// силы: Крылья Хоннеамиз», а вслух говорят «Королевские космические силы» —
// в ep-135, выпуске про этот самый тайтл, полное название не звучит ни разу,
// и без этого правила у него нашёлся бы НОЛЬ упоминаний. Подзаголовок после
// двоеточия есть у доброй половины аниме, и вслух его не произносит никто.
//
// Порог в 6 символов — от ложных срабатываний: короткий кусок до двоеточия
// («Он и она: …») слишком похож на обычную речь. Полностью риск он не снимает:
// назовите тайтл «Твоё имя: …» — и слова «твоё имя» в разговоре станут
// упоминанием. Лечится правкой titleRu в src/content/anime/<slug>.json.
//
// Вывезено наружу, потому что по этому же порогу режут название ещё двое:
// подсказки к вариантам написания (src/lib/aliasHints.mjs) и склонение
// (scripts/anime-cases.mjs — склонять подзаголовок незачем, вслух его никто
// не произносит). Три копии числа разъехались бы молча.
export const MIN_PREFIX_LENGTH = 6;

// Без учёта регистра и без разницы между «е» и «ё» — то же правило, что
// у поиска внутри транскрипта. Причина та же: распознавание сплошь пишет
// «Унесенные» там, где в справочнике «Унесённые». Замена один символ на один,
// поэтому позиции найденного в исходной строке не сбиваются.
export function fold(text) {
	return String(text).toLowerCase().replace(/ё/g, 'е');
}

// Буква или цифра. Название не должно быть куском другого слова: «Наруто»
// внутри «нарутовский» — не упоминание тайтла. Проверяем символ слева и справа
// от совпадения. \p{L} покрывает и кириллицу, и латиницу, поэтому отдельных
// правил для «K-On!» и «Кэйон!» не нужно.
function isWordChar(char) {
	return char !== undefined && /[\p{L}\p{N}]/u.test(char);
}

// Одно название из справочника → что по нему искать (см. MIN_PREFIX_LENGTH).
//
// `cut` помечает кусок, полученный обрезкой по двоеточию. Он слабее целого
// названия, и это важно при столкновении — см. сортировку в buildAnimeMatcher.
function searchNames(title) {
	const names = [{ raw: title, cut: false }];
	const colon = title.indexOf(':');
	if (colon >= MIN_PREFIX_LENGTH) names.push({ raw: title.slice(0, colon).trim(), cut: true });
	return names;
}

/**
 * Справочник тайтлов → список названий для поиска.
 *
 * Берём русское и оригинальное название, как remark-anime.mjs, плюс ОБА списка
 * вариантов написания. Варианты закрывают то, чего названия не ловят:
 * разговорное произношение («K-On!» вместо «Кэйон!») и искажения распознавания
 * («Фринен»). Правила для них те же самые — регистр, «е»/«ё» и границы слова
 * разбираются ниже одинаково для всех названий.
 *
 * СПИСКОВ ДВА, И ОНИ РАЗНЫЕ ПО ПРОИСХОЖДЕНИЮ, А НЕ ПО СМЫСЛУ.
 *   `aliases`     — вписал человек, не перезаписывается никогда;
 *   `aliasesAuto` — посчитала морфология (scripts/anime-cases.mjs), падежи,
 *                   пересчитывается свободно.
 * Искать по ним надо одинаково — разница только в том, кто их завёл, — поэтому
 * тут они просто складываются. А не смешаны они в файле тайтла затем, чтобы
 * пересчёт не стёр ручную правку (тз/11, A.1).
 *
 * Сортировка по длине от длинного к короткому нужна, чтобы длинное название
 * побеждало короткое, когда одно вложено в другое — в том числе чтобы полное
 * название побеждало свой же кусок до двоеточия.
 *
 * ГАЛОЧКА «ТОЛЬКО В КАВЫЧКАХ» ЕДЕТ ВМЕСТЕ С НАЗВАНИЯМИ, а не спрашивается
 * отдельно у справочника: она свойство тайтла, и всякий, кто получил список
 * названий, обязан получить и её. Иначе один вызывающий её учтёт, другой нет,
 * и на сайте ссылка появится там, где заказчик её запретил.
 *
 * ГДЕ ОНА ДЕЙСТВУЕТ — ОБЯЗАН СКАЗАТЬ ВЫЗЫВАЮЩИЙ, и молчание тут запрещено.
 *   `quotes: 'apply'`  — действует. Тексты постов: их пишут, а не говорят,
 *                        и кавычки в них правда стоят.
 *   `quotes: 'ignore'` — не действует. Живая речь расшифровок (кавычек в ней
 *                        не бывает) и отчёты разведки, которые как раз меряют,
 *                        сколько галочка отняла бы.
 *
 * Замер 11 августа 2026, из-за которого это стало двумя разными ответами:
 * в текстах постов 74 % упоминаний стоят в кавычках, а в расшифровках только
 * 30 %. Включи галочку и там — и у «Акиры» ушли бы 9 ложных упоминаний
 * в постах ВМЕСТЕ с 30 верными в разговоре. Плюс в расшифровках поштучная
 * отмена упоминания уже есть, а в постах нет ничего (СТАТУС.md, хвост 44).
 * Решение заказчика 11 августа 2026.
 *
 * Значения по умолчанию тут нет намеренно: забудь вызывающий этот ответ —
 * и галочка молча перестала бы действовать (или начала действовать) в целом
 * разделе сайта, а выглядело бы это как «всё хорошо».
 *
 * @param {{ id: string, data: { titleRu?: string, titleOriginal: string, aliases?: string[], aliasesAuto?: string[], strictQuotes?: boolean } }[]} entries
 * @param {{ quotes: 'apply' | 'ignore' }} options
 */
export function buildAnimeMatcher(entries, options) {
	if (options?.quotes !== 'apply' && options?.quotes !== 'ignore') {
		throw new Error(
			"buildAnimeMatcher: скажите, действует ли тут галочка «только в кавычках» — { quotes: 'apply' } для текстов постов, { quotes: 'ignore' } для живой речи и отчётов.",
		);
	}
	const applyQuotes = options.quotes === 'apply';

	const names = [];
	const seen = new Set();

	for (const entry of entries) {
		const strictTitle = applyQuotes && entry.data?.strictQuotes === true;
		// Собственное имя тайтла — по нему решается старшинство при столкновении.
		const canon = String(entry.data?.titleRu || entry.data?.titleOriginal || '');

		for (const title of [
			entry.data?.titleRu,
			entry.data?.titleOriginal,
			...(entry.data?.aliases ?? []),
			...(entry.data?.aliasesAuto ?? []),
		]) {
			if (!title) continue;

			for (const { raw, cut } of searchNames(title)) {
				if (raw.length < MIN_NAME_LENGTH) continue;
				const folded = fold(raw);
				const key = entry.id + ' ' + folded;
				if (seen.has(key)) continue;
				seen.add(key);
				// ГАЛОЧКА ДЕЙСТВУЕТ ТОЛЬКО НА РУССКИЕ НАЗВАНИЯ. Опасность, от которой
				// она защищает, — совпадение с обычным РУССКИМ словом; «K-On!»,
				// «Shirobako», «Jujutsu Kaisen» и «Bleach» обычным русским словом
				// не бывают, а в кавычки автор их почти не ставит. Замер: у «Кэйон!»
				// на латиницу приходится 31 упоминание из 35 без кавычек, у «Белого
				// ящика» — 15 из 16. Без этой оговорки галочка отнимала бы заведомо
				// безопасное. Решение заказчика 11 августа 2026.
				const strict = strictTitle && /\p{Script=Cyrillic}/u.test(raw);
				names.push({ id: entry.id, name: raw, folded, strict, cut, canon: canon.length });
			}
		}
	}

	// СТАРШИНСТВО НАЗВАНИЙ — ЧЕТЫРЕ КЛЮЧА, И ТОЛЬКО ПЕРВЫЙ БЫЛ ТУТ ИЗНАЧАЛЬНО.
	//
	// 1. ДЛИННОЕ ПОБЕЖДАЕТ КОРОТКОЕ. Когда одно название вложено в другое,
	//    выигрывать должно длинное — иначе «Атака титанов» терялась бы внутри
	//    «Атака титанов: Финал».
	//
	// Остальные три появились 12 августа 2026, когда справочник вырос с 53
	// тайтлов до 424 и в нём стало много ПРОДОЛЖЕНИЙ. Кусок до двоеточия
	// у «Стального алхимика: Братство» — это ровно «Стальной алхимик», то есть
	// полное название ДРУГОГО тайтла, и длины у них совпадают. Победителя при
	// равной длине выбирал порядок файлов в папке, а `-` сортируется раньше `.`,
	// поэтому продолжение побеждало ВСЕГДА: 17 названий из 17. На живом сайте
	// это было 19 ссылок «Наруто» на «Ураганные хроники», 13 «Стальных
	// алхимиков» на «Братство» и 8 «Атак титанов» на «Финал. Часть 2».
	//
	// 2. ЦЕЛОЕ НАЗВАНИЕ ПОБЕЖДАЕТ ОБРЕЗАННОЕ ПО ДВОЕТОЧИЮ. Кусок — это догадка
	//    («вслух подзаголовок не произносят»), а целое название — факт.
	//    Догадка не имеет права перебивать факт.
	//
	// 3. ПРИ ПРОЧИХ РАВНЫХ ПОБЕЖДАЕТ ТОТ, ЧЬЁ СОБСТВЕННОЕ ИМЯ КОРОЧЕ. Ключ 2
	//    закрывает не всё: падежные формы продолжения морфология считает ТОЖЕ
	//    от куска до двоеточия и кладёт их в `aliasesAuto` готовыми, так что
	//    обрезкой они уже не помечены. «Человека-бензопила» лежит в двух
	//    карточках сразу и в обеих как полноправный вариант. Тогда название
	//    принадлежит тому, у кого оно и есть имя целиком, — а у того имя короче,
	//    потому что у соперника к нему приписан хвост после двоеточия.
	//
	// 4. И НАПОСЛЕДОК — ПО `id`, ЧТОБЫ ИСХОД НЕ ЗАВИСЕЛ ОТ ПОРЯДКА ФАЙЛОВ ВООБЩЕ.
	//    Это не украшение: именно порядок файлов и был причиной поломки. Пока
	//    хоть один случай решается им, поломка вернётся при первом переименовании
	//    файла, и заметить это будет некому.
	names.sort(
		(a, b) =>
			b.folded.length - a.folded.length ||
			Number(a.cut) - Number(b.cut) ||
			a.canon - b.canon ||
			(a.id < b.id ? -1 : a.id > b.id ? 1 : 0),
	);
	return names;
}

/**
 * Все упоминания названий в одном куске текста.
 * Возвращает список { id, start, end } по возрастанию позиции, без наложений.
 *
 * `start` — не только место для нарезки текста, но и половина якоря
 * для исключений упоминаний (вторая половина — номер реплики,
 * см. src/lib/mentionExceptions.mjs). Поэтому искать надо по реплике,
 * а не по склеенному тексту блока: в склейке позиции были бы чужие.
 *
 * ГАЛОЧКА «ТОЛЬКО В КАВЫЧКАХ» (тз/11, B.1). У тайтла с ней совпадение
 * считается упоминанием, только если кавычка стоит вплотную и слева, и справа:
 * «Монстр» — да, «слово монстр в тексте про кайдзю» — нет.
 *
 * КАВЫЧКИ НИЧЕГО НЕ ДОКАЗЫВАЮТ САМИ (тз/11, B.3). В русском в кавычки ставят
 * и журналы, и студии, и цитаты речи, поэтому совпадение со справочником
 * обязательно в любом случае — галочка только УЖЕСТОЧАЕТ проверку, а не
 * заменяет её. Отдельной ветки «нашлось в кавычках, значит тайтл» тут нет
 * и быть не должно.
 */
export function findMentions(text, matcher) {
	if (!text || matcher.length === 0) return [];

	const haystack = fold(text);
	const found = [];
	// Занятые куски строки: длинное название уже забрало этот отрезок, короткое
	// внутри него второй раз не считаем.
	const taken = new Uint8Array(haystack.length);

	for (const { id, folded, strict } of matcher) {
		let at = haystack.indexOf(folded);

		while (at !== -1) {
			const end = at + folded.length;
			const free = !taken.subarray(at, end).some((busy) => busy === 1);
			const boundaries = !isWordChar(haystack[at - 1]) && !isWordChar(haystack[end]);
			const quoted = !strict || isQuotedAt(haystack, at, end);

			if (free && boundaries && quoted) {
				found.push({ id, start: at, end });
				taken.fill(1, at, end);
			}

			at = haystack.indexOf(folded, at + 1);
		}
	}

	found.sort((a, b) => a.start - b.start);
	return found;
}

// Убранные руками упоминания (см. src/lib/mentionExceptions.mjs) на страницу
// не попадают вовсе и в индекс не идут. По умолчанию не убрано ничего.
const KEEP_ALL = { isHidden: () => false };

/**
 * Текст ОДНОЙ реплики → куски для вывода: обычный текст и упоминания.
 * Каждый кусок — { text } или { text, animeId, offset }.
 * Убранные руками упоминания возвращаются обычным текстом.
 *
 * @param {number} replicaIndex — место реплики в исходном массиве, якорь исключений
 */
export function splitByMentions(text, matcher, replicaIndex = -1, exceptions = KEEP_ALL) {
	const mentions = findMentions(text, matcher).filter(
		(mention) => !exceptions.isHidden(mention.id, replicaIndex, mention.start),
	);
	if (mentions.length === 0) return [{ text }];

	const parts = [];
	let cursor = 0;

	for (const mention of mentions) {
		if (mention.start > cursor) parts.push({ text: text.slice(cursor, mention.start) });
		parts.push({
			text: text.slice(mention.start, mention.end),
			animeId: mention.id,
			offset: mention.start,
		});
		cursor = mention.end;
	}

	if (cursor < text.length) parts.push({ text: text.slice(cursor) });
	return parts;
}

/**
 * Блоки транскрипта → какие тайтлы в каком месте упомянуты.
 * Возвращает Map: id тайтла → массив таймкодов (секунды, по возрастанию,
 * без повторов).
 *
 * Таймкод — начало БЛОКА, а не отдельной реплики. Так число под ссылкой на
 * странице тайтла совпадает с плашкой, которая стоит у этого куска в самом
 * транскрипте, и список не превращается в «11:57, 11:57, 12:10, 12:10» —
 * в ep-102 «Наруто» звучит четыре раза внутри двух блоков.
 *
 * Ищем при этом ПО РЕПЛИКАМ (block.parts), а не по склеенному тексту блока:
 * позиция внутри реплики — половина якоря для исключений, и в склейке она
 * оказалась бы чужой.
 *
 * @param {{ start: number, parts: { index: number, text: string }[] }[]} blocks — результат groupReplicas()
 */
export function collectMentions(blocks, matcher, exceptions = KEEP_ALL) {
	const byAnime = new Map();

	for (const block of blocks) {
		const seenHere = new Set();

		for (const part of block.parts) {
			for (const mention of findMentions(part.text, matcher)) {
				if (exceptions.isHidden(mention.id, part.index, mention.start)) continue;
				if (seenHere.has(mention.id)) continue;
				seenHere.add(mention.id);

				const times = byAnime.get(mention.id) ?? [];
				times.push(block.start);
				byAnime.set(mention.id, times);
			}
		}
	}

	return byAnime;
}
