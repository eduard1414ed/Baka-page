// Что писать в строке рядом с датой — «сколько это займёт». Строка одна, чисел
// в ней ровно одно, и решение, какое именно, принимается ЗДЕСЬ, в одном месте.
//
// Почему так, а не «время чтения отдельно, длительность отдельно»: и карточка
// в ленте (src/components/PostCard.astro), и страница поста
// (src/pages/posts/[slug].astro) зовут отсюда одну функцию. Значит показать
// оба числа сразу физически невозможно, а разойтись в ответе эти две страницы
// не могут — им неоткуда взять разные данные.

import { getReadingMinutes } from './readingTime.mjs';
import { findEpisodeByGuid } from './podcastFeed.mjs';
import { isExternalPost, externalSourceName } from './externalPost.mjs';

// Категории, у которых своя длительность и время чтения не имеет смысла:
// у выпуска подкаста — длительность аудио, у видеоэссе — длина ролика с его
// аудиоверсией. У обеих бывает расшифровка, и в подсчёт она не идёт никак:
// транскрипт — отдельная сущность (src/content/transcripts/), в тело поста
// он не входит и до арифметики чтения просто не доезжает.
//
// Появится ещё категория со своей длительностью — дописать сюда одну строку.
export const CATEGORIES_WITH_OWN_DURATION = ['podcast', 'videoessay'];

// Категории, где метки нет вообще никакой — ни длительности, ни чтения.
//
// «Бонус» — указатель на материал, который лежит на Patreon и Boosty: здесь
// только название и описание-тизер, а дальше плашка подписки (тз/10, задача 1).
// Длительности у нас нет (бонусов нет в публичном RSS), а время чтения
// посчиталось бы по тизеру, за которым текста всё равно не будет, — то есть
// врало бы читателю прямо в лицо.
export const CATEGORIES_WITHOUT_TIMING = ['bonus'];

/**
 * Секунды → «18 сек», «42 мин» или «1 ч 25 мин». В архиве встречается всё три:
 * выпуски идут от 18 секунд («Опенинг») до 1 ч 35 мин.
 */
export function formatDuration(seconds) {
	const totalMinutes = Math.round(seconds / 60);

	// Короче минуты — секундами. Без этой ветки «Опенинг» на 18 секунд
	// округлялся бы до «0 мин», и это не выдумка: такой выпуск в архиве есть.
	if (totalMinutes === 0) return `${Math.round(seconds)} сек`;

	const hours = Math.floor(totalMinutes / 60);
	const minutes = totalMinutes % 60;

	if (hours === 0) return `${totalMinutes} мин`;
	// Ровно час — «1 ч», а не «1 ч 0 мин».
	return minutes === 0 ? `${hours} ч` : `${hours} ч ${minutes} мин`;
}

/**
 * @typedef {{ kind: 'duration' | 'reading' | 'source', label: string }} PostTiming
 */

/**
 * Что показать рядом с датой, или null — если показывать нечего.
 *
 * Слово «слушать» / «читать» в подписи стоит не для красоты: в общей ленте
 * карточки разных категорий идут вперемешку, и без него «42 мин» у выпуска
 * и «4 мин» у заметки выглядели бы числами одного рода.
 *
 * null бывает в четырёх случаях, и все четыре — нормальное состояние,
 * а не поломка:
 *  — категория из CATEGORIES_WITHOUT_TIMING (сейчас это «Бонус»);
 *  — текст короче трёх минут («1 мин» рядом с заголовком выглядит суетливо);
 *  — у выпуска нет пары в RSS или фид недоступен в момент сборки (тогда
 *    на странице не будет и плеера — так устроено, см. podcastFeed.mjs);
 *  — видеоэссе живёт только на YouTube, аудиоверсии в RSS нет. Длительность
 *    ролика взять неоткуда: для этого нужен отдельный ключ к YouTube API,
 *    и ради этого его заводить не стали. Появится аудиоверсия — число
 *    подхватится само, править код не придётся.
 *
 * @param {{ body?: string, data: { category: string, audioGuid?: string } }} post
 * @returns {Promise<PostTiming | null>}
 */
export async function getPostTiming(post) {
	// Пост-ссылка на чужой сайт: вместо «сколько это займёт» — где это лежит,
	// «8 августа 2026 · Кинопоиск» (тз/10, задача 2). Время чтения тут посчитать
	// НЕ ИЗ ЧЕГО и нельзя даже пытаться: в теле поста лежит короткое описание,
	// а сам текст — на чужом сайте. Посчитанные по описанию «1 мин читать»
	// были бы прямой ложью.
	//
	// Проверка стоит первой и перебивает категорию: признак работает поверх
	// любой, в том числе поверх «Подкаста» с его длительностью из RSS.
	if (isExternalPost(post.data)) {
		const source = externalSourceName(post.data);
		return source ? { kind: 'source', label: source } : null;
	}

	if (CATEGORIES_WITHOUT_TIMING.includes(post.data.category)) return null;

	if (CATEGORIES_WITH_OWN_DURATION.includes(post.data.category)) {
		// Длительность берём из RSS, а не из своих файлов, по той же причине,
		// по которой не копируем к себе аудио (CLAUDE.md): она принадлежит
		// аудиофайлу, а он живёт на хостинге подкаста. Скопированное к себе
		// число замёрзло бы навсегда — робот сверки существующие посты
		// не трогает никогда, и перезалитый выпуск остался бы со старой цифрой.
		//
		// По сети это не стоит ничего: фид качается один раз за сборку
		// и лежит в памяти процесса (см. podcastFeed.mjs), сколько бы карточек
		// его ни спросило.
		const episode = post.data.audioGuid ? await findEpisodeByGuid(post.data.audioGuid) : null;
		if (!episode?.durationSec) return null;

		return { kind: 'duration', label: `${formatDuration(episode.durationSec)} слушать` };
	}

	const minutes = getReadingMinutes(post.body);
	if (minutes === null) return null;

	return { kind: 'reading', label: `${minutes} мин читать` };
}
