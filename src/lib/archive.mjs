// Общие правила страницы архива и страниц разделов (часть 4 тз/08-дизайн.md).
//
// Архив и раздел — ОДНА страница с разным набором материалов, поэтому и число
// на странице, и адрес страницы, и строка счёта считаются здесь, а не в каждой
// из двух страниц отдельно. Разойдись эти числа — карта сайта заявила бы
// поисковику страницы, которых нет, и заметить это было бы нечем.
//
// Модуль намеренно обычный: ничего не импортирует и прогоняется в node
// на живых данных.

import { withCount } from './plural.mjs';

/** Как архив называется в заголовке, в крошках и в надзаголовке раздела. */
export const ARCHIVE_TITLE = 'Архив';

/** Описание для поисковика и для превью ссылки на архив. */
export const ARCHIVE_DESCRIPTION =
	'Все выпуски подкаста, видеоэссе, статьи и заметки «Баки!» в одной ленте, от свежих к старым.';

/** Подводка в шапке архива — то же самое человеческими словами. */
export const ARCHIVE_INTRO = 'Выпуски подкаста, видеоэссе, статьи и заметки — в одной ленте, от свежих к старым.';

/** Адрес архива. Первая страница, она же вход со всех вкладок. */
export const ARCHIVE_BASE = '/archive/';

/**
 * Сколько материалов на странице. Раздел 4.2 ТЗ: 24, то есть 143 выпуска —
 * это шесть страниц.
 *
 * СТРАНИЦАМИ, А НЕ КНОПКОЙ «ПОКАЗАТЬ ЕЩЁ»: на страницу можно дать ссылку,
 * вернуться кнопкой «назад» и найти её поисковиком. После шести нажатий
 * кнопки адрес остался бы тем же, а при возврате из материала лента
 * свернулась бы обратно.
 */
export const PER_PAGE = 24;

/**
 * Сколько всего страниц выйдет из `total` материалов.
 *
 * Пустой список — всё равно одна страница: у раздела без единого материала
 * адрес обязан открываться и говорить, что материалов пока нет. Так же
 * считает и Astro, когда строит сами страницы, — числа обязаны совпадать,
 * иначе карта сайта разойдётся с сайтом.
 */
export function pageCount(total, perPage = PER_PAGE) {
	return Math.max(1, Math.ceil(total / perPage));
}

/**
 * Адрес страницы N. Первая страница живёт по короткому адресу без номера:
 * `/archive/`, а не `/archive/1/`. Второго адреса у одной и той же страницы
 * быть не должно — для поисковика это дубль.
 */
export function pageUrl(base, n) {
	return n <= 1 ? base : `${base}${n}/`;
}

/**
 * Строка счёта под заголовком: «143 выпуска · 24 видеоэссе · 61 статья».
 *
 * Разделы с нулём пропускаются: «0 видеоэссе» — это не сведения, а шум.
 * Список разделов приходит снаружи (archiveSections в content.config.ts):
 * в каждом перечислены все категории, которые в нём показываются, поэтому
 * бонусы попадают в счёт выпусков, а не теряются.
 *
 * @param {Array<{ data: { category: string } }>} posts
 * @param {Array<{ ids: string[], forms: [string, string, string] }>} sections
 */
export function archiveCountLine(posts, sections) {
	return sections
		.map((section) => posts.filter((post) => section.ids.includes(post.data.category)).length)
		.map((n, i) => (n > 0 ? withCount(n, sections[i].forms) : null))
		.filter(Boolean)
		.join(' · ');
}

/**
 * Какие номера страниц показывать в ряду пагинации.
 *
 * Всегда видны первая, последняя и окно из трёх подряд вокруг текущей;
 * пропуски заменяются на `null` — многоточие. Окно именно из трёх и именно
 * прижимается к краям (страница 1 из 11 → 1 2 3 … 11), потому что так
 * в макете и в справочнике состояний.
 *
 * @returns {Array<number | null>}
 */
export function pageNumbers(current, last) {
	if (last <= 1) return [1];

	// Окно из трёх подряд, прижатое к краю списка, если текущая у края.
	const start = Math.max(1, Math.min(current - 1, last - 2));
	const window = [start, start + 1, start + 2].filter((n) => n >= 1 && n <= last);

	const shown = new Set([1, ...window, last]);
	const sorted = [...shown].sort((a, b) => a - b);

	const out = [];
	let previous = 0;
	for (const n of sorted) {
		if (previous && n - previous > 1) out.push(null);
		out.push(n);
		previous = n;
	}
	return out;
}
