// Это ПРИЗНАК, а не категория: поле `externalUrl` может стоять у поста любой
// категории, обычно у «Статьи». Смысл — статья вышла на Кинопоиске или в Т—Ж,
// в нашей ленте она должна быть наравне с остальным, но открываться там,
// где опубликована.
//
// СВОЕЙ СТРАНИЦЫ У ТАКОГО ПОСТА НЕТ ВОВСЕ. Это главное правило этого файла,
// и держится оно в трёх местах сразу: страницы не создаёт
// src/pages/posts/[slug].astro, в карту сайта не пускает src/pages/sitemap.xml.ts,
// а карточка в ленте ведёт наружу (src/components/PostCard.astro). Иначе
// на сайте появились бы десятки пустых страниц с одной кнопкой «читать
// на Кинопоиске» — плохо и читателю, и поисковику.

import { hostOf } from './linkIcon.mjs';

/**
 * Домен → как площадка называется по-русски.
 *
 * Список нарочно короткий и пополняется по факту: сюда попадает то, где
 * заказчик правда печатается. Незнакомый домен не ломает ничего — подставится
 * сам домен («dtf.ru»), и его всегда можно перебить полем «Площадка».
 *
 * Ключ — домен без «www.». Поддомены проверяются точным совпадением, поэтому
 * у Т—Ж перечислены оба живых адреса: журнал переезжал.
 */
const SOURCE_BY_HOST = {
	'kinopoisk.ru': 'Кинопоиск',
	'journal.tinkoff.ru': 'Т—Ж',
	'journal.tbank.ru': 'Т—Ж',
	't-j.ru': 'Т—Ж',
	'dtf.ru': 'DTF',
	'vc.ru': 'vc.ru',
	'habr.com': 'Хабр',
	'mel.fm': 'Мел',
	'meduza.io': 'Медуза',
	'telegra.ph': 'Telegraph',
	'teletype.in': 'Teletype',
	'vk.com': 'VK',
	'vk.ru': 'VK',
	't.me': 'Telegram',
	'youtube.com': 'YouTube',
	'youtu.be': 'YouTube',
};

/**
 * Пост живёт на чужом сайте?
 *
 * Одна проверка на весь сайт: заполнен адрес — значит внешний. Отдельной
 * галочки «это внешний пост» нет намеренно, два состояния для одного факта
 * рано или поздно разъезжаются.
 *
 * @param {{ externalUrl?: string }} data Поля поста (post.data).
 */
export function isExternalPost(data) {
	return Boolean(data?.externalUrl);
}

/**
 * Название площадки: что вписали руками, иначе — по домену, иначе — сам домен.
 *
 * Вписанное руками побеждает всегда: домен не знает, что «Кинопоиск» иногда
 * надо подписать как «Кинопоиск Медиа», а список выше — не истина, а удобство.
 *
 * @param {{ externalUrl?: string, externalSource?: string }} data
 * @returns {string | null} null только у поста, который вообще не внешний.
 */
export function externalSourceName(data) {
	if (data?.externalSource) return data.externalSource;
	if (!data?.externalUrl) return null;

	const host = hostOf(data.externalUrl);
	if (!host) return null;

	return SOURCE_BY_HOST[host] ?? host;
}

/**
 * Куда ведёт ссылка на пост — на чужой сайт или на нашу страницу.
 *
 * Зовут отсюда все, кто рисует ссылку на пост: карточка в ленте, лента RSS.
 * Собирать адрес `/posts/…/` руками рядом с проверкой на внешний пост нельзя —
 * ровно так одно из мест однажды и забудут поправить.
 *
 * @param {{ id: string, data: { externalUrl?: string } }} post
 */
export function postHref(post) {
	return post.data.externalUrl ?? `/posts/${post.id}/`;
}
