// Когда файл материала правили в последний раз — для `dateModified`
// в разметке Schema.org (TASK-markup, пункт 1.3).
//
// ЗАЧЕМ. `datePublished` говорит поисковику «это вышло тогда-то», и только.
// `dateModified` говорит «а вот это мы с тех пор трогали» — по нему решают,
// не устарела ли страница и стоит ли зайти за ней ещё раз.
//
// ОТКУДА БЕРЁМ. Поля в шапке поста для этого нет и заводить его нельзя:
// 754 материала архива никто не станет заполнять руками, а забытое поле
// врало бы про свежесть. Настоящий ответ уже есть в git — там записано,
// какой коммит последним трогал файл. Админка коммитит каждое сохранение,
// значит правка заказчика попадает сюда сама.
//
// ОДИН ПОХОД, А НЕ 754. Спрашивать git про каждый файл отдельно — это
// восемьсот запусков процесса за сборку. Спрашиваем один раз обо всей папке
// с содержимым и раскладываем ответ в карту: 0,4 секунды на весь архив.
//
// ЧЕГО В GIT НЕТ — то либо ещё не закоммичено (новый пост из админки в тот
// самый миг, когда сборка его застала), либо лежит вне репозитория. Тогда
// спрашиваем файловую систему, а если и там нечего — отвечаем null,
// и поля в разметке просто не будет. ВЫДУМАННАЯ ДАТА ХУЖЕ ОТСУТСТВУЮЩЕЙ:
// её никто не проверит, а поисковику она скажет неправду.
//
// Время файловой системы стоит ВТОРЫМ, а не первым, и это не вкус: после
// свежего клона репозитория у всех файлов время клона, то есть «весь архив
// изменён сегодня». В git такой беды нет.
import { execFileSync } from 'node:child_process';
import { statSync } from 'node:fs';

/** Что спрашиваем у git. Обе папки с содержимым, за один заход. */
const ПАПКИ = ['src/content/posts', 'src/content/anime'];

/** Путь → ISO-дата последнего коммита, тронувшего файл. Считается один раз. */
let карта = null;

function построитьКарту() {
	const готово = new Map();

	try {
		// `%x00%cI` — нулевой байт как метка начала записи и дата коммита
		// в ISO. Ключ core.quotepath=false обязателен: без него git пишет
		// нелатинские пути восьмеричными кодами, и такой путь не совпадёт
		// ни с чем (в архиве такие имена не встречаются, но заводить мину
		// на будущее незачем).
		//
		// Дата КОММИТА (%cI), а не автора (%aI): вторую можно поставить любую,
		// а первая — когда правка на самом деле легла в историю.
		const вывод = execFileSync(
			'git',
			['-c', 'core.quotepath=false', 'log', '--format=%x00%cI', '--name-only', '--', ...ПАПКИ],
			{ encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
		);

		// Записи идут от свежих к старым, поэтому ПЕРВОЕ встреченное имя файла
		// и есть его последняя правка: дальше по списку только более старое.
		let дата = null;
		for (const строка of вывод.split('\n')) {
			if (строка.startsWith('\0')) {
				дата = строка.slice(1).trim() || null;
				continue;
			}
			const путь = строка.trim();
			if (!путь || !дата || готово.has(путь)) continue;
			готово.set(путь, дата);
		}
	} catch {
		// git не установлен, папка не репозиторий, история обрезана — всё это
		// не повод ронять сборку сайта. Останемся со временем файлов.
	}

	return готово;
}

/**
 * Дата последней правки файла в ISO — или null, если её неоткуда взять.
 *
 * @param {string} путь Путь от корня проекта, как его пишет git:
 *   `src/content/posts/ep-108.md`.
 * @returns {string | null}
 */
export function lastModifiedISO(путь) {
	карта ??= построитьКарту();

	const изGit = карта.get(путь);
	if (изGit) return изGit;

	try {
		return statSync(путь).mtime.toISOString();
	} catch {
		return null;
	}
}

/** Путь к файлу поста по его имени в коллекции. */
export function postFilePath(id) {
	return `src/content/posts/${id}.md`;
}

/** Путь к карточке тайтла по её имени в коллекции. */
export function animeFilePath(id) {
	return `src/content/anime/${id}.json`;
}
