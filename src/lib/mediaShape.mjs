// расползётся по слотам, и следующий выпуск снова обрежут.

import { sectionOf } from '../data/categories.js';

/**
 * Форма картинки материала.
 *
 * КВАДРАТ — У РАЗДЕЛА «ПОДКАСТ», А НЕ У КАТЕГОРИИ: бонус это тоже выпуск,
 * и обложка у него такая же квадратная. Спрашивать надо раздел.
 *
 * @param {string} category Категория материала (`post.data.category`).
 * @returns {'square' | 'wide'}
 */
export function mediaShape(category) {
	return sectionOf(category) === 'podcast' ? 'square' : 'wide';
}
