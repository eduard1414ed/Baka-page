// Мелкая типографика подводок: что нельзя оставлять висеть в конце строки.
//
// ОДИН ДОМ НА ВЕСЬ САЙТ. Правило зовётся из шапки раздела (SectionHead.astro),
// а шапка одна у архива, у всех разделов и у каталога тайтлов. Впиши его
// в текст руками — и оно продержится ровно до первой правки текста в другом
// месте: неразрывный пробел невидим, и потерю его не заметит никто.
//
// НЕРАЗРЫВНЫЙ ПРОБЕЛ ПИШЕТСЯ КОДОМ `\u00a0`, А НЕ ЗНАКОМ. Знак в исходнике
// неотличим от обычного пробела глазами, и однажды он в этом проекте уже
// потерялся при копировании файла — молча, без ошибки.

/** До скольких букв слово считается коротким и не отпускается на край строки. */
const КОРОТКОЕ_СЛОВО = 2;

/**
 * Приклеить короткие слова к следующему за ними: «в одной», «от свежих».
 *
 * Однобуквенный предлог в конце строки — это дыра в правом крае и пауза
 * там, где её нет в речи; на узком экране он вылезает почти всегда.
 * Приклеиваются слова из одной-двух букв, состоящие ТОЛЬКО из букв: у «то,»
 * перенос законен — запятая и есть пауза, а знак `—` ничего не держит и сам
 * уходит на предыдущую строку вместе со своим словом.
 *
 * Границу слова здесь считаем сами, разбором по пробелам: `\b`
 * в JavaScript — про латиницу, и на кириллице не совпадает ни с чем.
 *
 * @param {string} text
 * @returns {string}
 */
export function noHangingWords(text) {
	const части = String(text).split(' ');
	let итог = части[0] ?? '';
	for (let i = 1; i < части.length; i++) {
		const прежнее = части[i - 1];
		// Открывающие кавычки и скобки слева слово не портят: «(в одной».
		const голое = прежнее.replace(/^[^\p{L}\p{N}]+/u, '');
		const клеить = голое.length > 0 && голое.length <= КОРОТКОЕ_СЛОВО && /^\p{L}+$/u.test(голое);
		итог += (клеить ? '\u00a0' : ' ') + части[i];
	}
	return итог;
}
