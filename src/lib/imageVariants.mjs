// Два размера согласно CLAUDE.md: телефон и десктоп, не больше.
export const IMAGE_WIDTHS = [640, 1280];

// WEBP ЗДЕСЬ НЕ ЛИШНИЙ, ХОТЬ И «УЖЕ СЖАТ». С 13 августа 2026 админка сжимает
// картинку прямо в браузере, до отправки в GitHub, и отдаёт webp — другого
// формата её оптимизатор не умеет вовсе. Оставь мы webp в непережимаемых,
// такая загрузка уходила бы на сайт как есть, одним размером на все экраны:
// телефон получал бы 70 КБ вместо 25. То есть репозиторий похудел бы, а сайт
// потяжелел — ровно наоборот задуманному.
const OPTIMIZABLE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp']);

export function isOptimizableImage(pathname) {
	const dot = pathname.lastIndexOf('.');
	if (dot === -1) return false;
	return OPTIMIZABLE_EXT.has(pathname.slice(dot).toLowerCase());
}

/**
 * Основа имени сжатых копий. РАСШИРЕНИЕ ВХОДИТ В НЕЁ, И ЭТО ГЛАВНОЕ ЗДЕСЬ:
 * «1.png» → «1-png», «1.jpeg» → «1-jpeg».
 *
 * ПОЧЕМУ. Раньше расширение просто отбрасывалось, и два разных файла
 * с одинаковым именем давали ОДНИ И ТЕ ЖЕ копии: `1.png` и `1.jpeg` оба
 * превращались в `1-640w.webp`, `1-1280w.webp` и `1-og.jpg`. Один затирал
 * другой, и на сайт уезжала одна картинка вместо двух.
 *
 * Наступили 10 августа 2026, и не теоретически. Админка предлагает при
 * совпадении имени «сохранить оба» и честно переименовывает — но сравнивает
 * имя ЦЕЛИКОМ, вместе с расширением, поэтому `4.png` рядом с `4.jpeg` для неё
 * два разных файла, и она права. Ломалось уже у нас. В галерее опубликованной
 * заметки «Знакомьтесь: Ёдзи Такэсигэ» вместо четырёх кадров стояли обложки
 * четырёх выпусков подкаста; проверено сравнением пикселей, а не размеров —
 * размеры у всех восьми были 16:9 и совпадали.
 *
 * КОПИЙ ЭТОГО ПРАВИЛА БЫЛО ДВЕ: здесь и в самом скрипте сжатия
 * (src/plugins/optimize-uploads-integration.mjs), который считает имя файла
 * на диске. Разъедься они — страница просила бы один файл, а сборка делала
 * другой, и картинки пропали бы молча. Теперь обе стороны зовут эту функцию.
 *
 * @param {string} filename Имя или путь ДЕКОДИРОВАННЫЙ, без %-кодировки.
 */
export function variantBase(filename) {
	const dot = filename.lastIndexOf('.');
	if (dot === -1) return filename;
	return `${filename.slice(0, dot)}-${filename.slice(dot + 1).toLowerCase()}`;
}

/**
 * Отдельная jpeg-копия для превью в соцсетях: "…/photo.jpeg" → "…/photo-og.jpg".
 *
 * Нужна потому, что на сайт загруженные картинки уезжают только в webp,
 * а телеграм webp-превью разворачивает ненадёжно (см. CLAUDE.md).
 *
 * Это ТРЕТИЙ файл на картинку при правиле «максимум два размера» в CLAUDE.md,
 * и поэтому он делается НЕ для всех загрузок подряд, а только для тех, что
 * реально стоят в превью: сборка ищет ссылки на такие копии в готовых
 * страницах и создаёт только их (src/plugins/optimize-uploads-integration.mjs).
 * Правило про два размера про то, что показывается на странице; здесь другое
 * назначение и штучное количество — сейчас одна копия на весь сайт.
 */
export function getOgVariantSrc(originalSrc) {
	return encodeURI(`${variantBase(decodeURIComponent(originalSrc))}-og.jpg`);
}

// "/images/uploads/photo%20one.jpeg" -> ["/images/uploads/photo one-jpeg-640w.webp", ...]
// Имя считаем от РЕАЛЬНОГО (декодированного) пути — так же, как это делает
// скрипт сжатия на файловой системе, и той же функцией.
export function getImageVariantSrcs(originalSrc) {
	const base = variantBase(decodeURIComponent(originalSrc));

	return IMAGE_WIDTHS.map((width) => ({
		width,
		src: encodeURI(`${base}-${width}w.webp`),
	}));
}

/**
 * Все ссылки на загрузки, встреченные в собранных страницах, — ОДНИМ проходом.
 *
 * ПОЧЕМУ НЕ ПОИСК ПОДСТРОКОЙ НА КАЖДЫЙ ВОПРОС. Склеенная разметка сайта весит
 * 22 МБ, загрузок 1232, вопросов к каждой три — это около 3700 проходов
 * по двадцати двум мегабайтам, то есть 27 секунд на ровном месте. Замерено,
 * а не прикинуто: шаг сжатия занимал их, пережимая всего тридцать картинок.
 * Набор строится один раз, дальше вопрос стоит наносекунды.
 *
 * Кавычка, пробел, `>` и `)` — границы пути: `)` нужна для `url(...)` в стилях,
 * пробел обрывает элемент srcset перед его шириной.
 */
export function collectUploadRefs(builtHtml, dir = '/images/uploads/') {
	const refs = new Set();
	const re = new RegExp(`${dir.replace(/\//g, '\\/')}[^"'\\s>)]+`, 'g');
	for (const match of builtHtml.matchAll(re)) refs.add(match[0]);
	return refs;
}

/**
 * Просит ли хоть одна собранная страница копии этой картинки.
 *
 * ЗАЧЕМ ВОПРОС. Загрузок в репозитории больше тысячи, а ссылок на них
 * у собранных страниц — семь десятков: почти всё принадлежит черновикам,
 * а у черновика страницы нет вовсе. Сжимать их незачем — это 92 секунды
 * из 128 при каждой сборке и две тысячи файлов в лимит 20 000.
 *
 * ПОЧЕМУ ОТДЕЛЬНОЙ ФУНКЦИЕЙ, А НЕ СТРОЧКОЙ ВНУТРИ ХУКА СБОРКИ. Правило внутри
 * хука спрашивается только полной сборкой на подложенных данных, то есть
 * правкой живого файла и обязательной пересборкой после. Вынесенное
 * спрашивается выдуманными именами за миллисекунду, и МОЛЧАНИЕ ТАМ, ГДЕ ОНО
 * ДОЛЖНО МОЛЧАТЬ, так же важно, как ответ там, где должно ответить: правило,
 * отвечающее «нужна» на всё подряд, не экономит ничего, а отвечающее «не нужна»
 * на всё подряд оставляет дыры на живых страницах.
 *
 * СПРАШИВАЕМ ПОЛНЫМ ПУТЁМ, а не куском имени: имена вкладываются друг в друга,
 * и «5-640w.webp» нашлось бы внутри «photo 2026-08-05 17.48.25-640w.webp».
 * На этом здесь уже обжигались — см. getOgVariantSrc. Набор путей отвечает
 * на этот вопрос сам собой: в нём лежат целые пути, а не текст страницы.
 *
 * @param {string} originalSrc путь картинки, как его пишет страница
 * @param {Set<string>} refs   что просят страницы (collectUploadRefs)
 */
export function isWantedByPages(originalSrc, refs) {
	if (getImageVariantSrcs(originalSrc).some((v) => refs.has(v.src))) return true;
	// Обложка, видная только в превью ссылки, webp-копий не просит вовсе —
	// и без этой строки пропала бы как «никому не нужная».
	return refs.has(getOgVariantSrc(originalSrc));
}
