/**
 * Адрес видеофайла с просьбой показать кадр вместо чёрного прямоугольника.
 *
 * `preload="metadata"` заставляет браузер скачать заголовок файла и узнать
 * размеры кадра с длительностью — но КАДР ОН ПРИ ЭТОМ НЕ РИСУЕТ. Chrome
 * показывает чёрный прямоугольник, пока не нажмёшь play, и материал выглядит
 * сломанным. Метка `#t=0.1` — часть адреса, а не запрос к серверу: она просит
 * браузер встать на десятую долю секунды, а встав, он этот кадр рисует.
 * Побочное действие ровно одно: воспроизведение начнётся с 0,1 секунды.
 *
 * Свою метку автора не трогаем: вписал он `#t=30` — значит хотел начать
 * с тридцатой секунды, и спорить с ним нечего.
 *
 * @param {string} url Прямая ссылка на файл, как её дал Cyberduck.
 * @returns {string} Она же, но с меткой кадра.
 */
export function ownVideoSrc(url) {
	const text = String(url ?? '').trim();
	if (!text || text.includes('#')) return text;
	return `${text}#t=0.1`;
}
