// Одно и то же слово по-русски пишут двояко: «Kyoto» — и «Кёто», и «Киото»,
// «Yamada» — и «Ямада», и «Иамада». Поэтому строк получается две: с йотацией
// и без неё. Обе уходят в поле поиска, и какую бы человек ни набрал, тайтл
// найдётся. Выбирать одну «правильную» тут не из чего.
const PLAIN = PAIRS.filter(([latin]) => !['yu', 'ya', 'yo', 'ju', 'ja'].includes(latin));

function makeRule(pairs) {
	const re = new RegExp(pairs.map(([latin]) => latin).join('|'), 'g');
	const table = new Map(pairs);
	return (text) =>
		String(text ?? '')
			.toLowerCase()
			.replace(re, (chunk) => table.get(chunk) ?? chunk);
}

const jotted = makeRule(PAIRS);
const plain = makeRule(PLAIN);

/** @returns {string[]} Одна или две записи латинской строки кириллицей. */
export function latinSearchForms(text) {
	return [...new Set([jotted(text), plain(text)])];
}

/**
 * Приведение к сравнимому виду В КАТАЛОГЕ: общее правило поиска («ё» = «е»,
 * регистр не важен) плюс «й» = «и».
 *
 * Вторая замена нужна ровно здесь и НЕ ДОБАВЛЯЕТСЯ В ОБЩЕЕ ПРАВИЛО: там оно
 * ищет упоминания тайтлов в живой речи по всему архиву, и «мой» = «мои»
 * дало бы ложные упоминания сразу везде. В каталоге же ошибка стоит одной
 * лишней марки в выдаче, зато «гайнакс» находит Gainax.
 */
export function foldCatalog(text) {
	return fold(text).replace(/й/g, 'и');
}
