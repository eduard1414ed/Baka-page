// Латиница кириллицей — ТОЛЬКО ДЛЯ ПОИСКА ПО КАТАЛОГУ, никогда для показа.
//
// ЗАЧЕМ. Оригинальные названия и студии в справочнике записаны латиницей:
// Shikimori и AniList других не отдают. А самый вероятный запрос в каталог —
// «гибли», и он не является названием ни одного тайтла: человек ищет студию
// и набирает её по-русски. Без этой строчки «гибли» не находил ничего, хотя
// три тайтла Ghibli в каталоге есть. Проверено на живых данных.
//
// ЧТО ЭТО НЕ. Это не транслитерация по ГОСТу и не то, что можно показать
// читателю: «Sousou no Frieren» превращается в «соусоу но фрирен», а живой
// человек напишет «Фрирен». Строка уходит в невидимое поле поиска и только
// ДОБАВЛЯЕТ совпадения — убрать она ничего не может, потому что оригинал
// в том же поле остаётся как есть.
//
// ПОЧЕМУ ПЕРЕВОДИМ ДАННЫЕ, А НЕ ЗАПРОС. Данных тринадцать строк и они
// считаются один раз при сборке; запрос человек набирает по букве, и перевод
// «гибли» → «gibli» всё равно не совпал бы с «ghibli» — по-русски «h» не
// пишется вовсе. В эту сторону правило работает, в обратную нет.

