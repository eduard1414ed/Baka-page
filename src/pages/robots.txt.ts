/**
 * Тело группы: запреты, а `Allow: /` ПОСЛЕДНЕЙ строкой.
 *
 * ПОРЯДОК ЗДЕСЬ РЕШАЕТ, И РАЗБОРЩИКИ ЧИТАЮТ ЕГО ПО-РАЗНОМУ. Google берёт самое
 * ДЛИННОЕ подходящее правило, и ему всё равно, где стоит `Allow: /`. А часть
 * разборщиков (штатный `urllib.robotparser` в Python — из них) берёт ПЕРВОЕ
 * подходящее, и тогда `Allow: /`, стоящий сверху, подходит всему сразу
 * и отменяет все запреты ниже. Файл при этом выглядит совершенно правильным.
 * Так и было с этапа 6: спросили настоящий разборщик — он ответил, что
 * в админку пущены все, включая Googlebot.
 * Запреты сверху, `Allow: /` снизу — и обе породы разборщиков отвечают
 * одинаково.
 *
 * ПУСТЫХ СТРОК ВНУТРИ ГРУППЫ БЫТЬ НЕ ДОЛЖНО. Google их игнорирует, а часть
 * разборщиков считает пустую строку концом группы. Комментарий строкой
 * безопасен, пустая строка нет.
 *
 * ЧЕСТНАЯ ОГОВОРКА ПРО ЭТОТ ЗАПРЕТ: подлогом его уронить не вышло. Разорви
 * группу пустой строкой — названные боты просто провалятся обратно в группу
 * `*`, а правила у неё РОВНО ТЕ ЖЕ, потому что печатаются отсюда. То есть
 * сегодня это не мина, а гигиена. Миной оно станет в тот день, когда группы
 * начнут различаться, — и тогда подлог заработает.
 */
function правила(): string {
	const строки = ЗАКРЫТО.map(({ путь, почему }) =>
		почему ? `# ${почему.replace(/\n/g, '\n# ')}\nDisallow: ${путь}` : `Disallow: ${путь}`,
	);
	return [...строки, '# Всё остальное — можно.', 'Allow: /'].join('\n');
}

