#!/bin/bash
# ПИСЬМО О ТОМ, ЧТО РОБОТ НЕ ОТРАБОТАЛ. Зовётся из OnFailure= у юнитов
# systemd, имя робота приходит первым доводом.
#
# Молчит и возвращает 0, если телеграм недоступен: письмо о беде не имеет
# права породить вторую беду.

set -u
UNIT="${1:-неизвестный робот}"
NOTIFY=/root/baka-robot/notify.sh
STAMP=$(date -u '+%Y-%m-%d %H:%M UTC')

# Хвост журнала — то, ради чего письмо и читают. Знаки & < > телеграм читает
# разметкой и на кривой отвечает отказом: письмо не уходит ВОВСЕ.
TAIL=$(journalctl -u "$UNIT" -n 15 --no-pager 2>/dev/null | tail -c 700 | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g')

"$NOTIFY" "$(printf '🔴 <b>Робот не отработал: %s</b>\n%s\n\n<code>%s</code>\n\nПодробности: journalctl -u %s -n 50' "$UNIT" "$STAMP" "$TAIL" "$UNIT")"
exit 0
