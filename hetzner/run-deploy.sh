#!/bin/bash
# СБОРКА И ВЫКЛАДКА САЙТА НА ОБА АДРЕСА (задача 21).
#
# Заменяет сразу два умерших механизма:
#   • автосборку Cloudflare Workers Builds (собирала при каждом пуше),
#   • робота .github/workflows/mirror-sync.yml (зеркало ru.bakapodcast.com).
#
# ПОЧЕМУ ВМЕСТЕ, А НЕ ПОРОЗНЬ. Робот зеркала перед заливкой сам собирает сайт.
# Перенеси его отдельно — зеркало начнёт обновляться само, а основной сайт
# останется на ручной выкладке, и копии молча разъедутся. В уроках проекта это
# отдельная грабля: «выкладок две, и падают они порознь».
#
# ОБЕ КОПИИ ЕДУТ ИЗ ОДНОЙ СБОРКИ. Порядок строгий: pull → build → deploy →
# зеркало. Собрать раньше, чем забрал правки, — значит выложить сборку без них.
#
# Петли не будет: выкладка ничего не коммитит, новых коммитов не создаёт.

set -u
set -o pipefail   # без этого `node … | tee` съедает код возврата, и провал
                  # заливки считался бы удачей — на этом уже обжигались

REPO=/root/baka-site
STATE_DIR=/root/baka-state
STATE="$STATE_DIR/last-deployed-commit"
LOG_DIR=/root/baka-logs
NOTIFY=/root/baka-robot/notify.sh
mkdir -p "$STATE_DIR" "$LOG_DIR"

# ─── ЗАМОК НА РЕПОЗИТОРИЙ ──────────────────────────────────────────────────
# Все роботы работают в ОДНОЙ папке /root/baka-site и лезут в git. Столкнутся
# два — и git отвечает «Cannot fast-forward to multiple branches», работа
# считается сбойной, а заказчик получает красное письмо о живом роботе.
# Поймано 25.08.2026: опросчик постов (ходит каждые 5 минут) влез ровно
# в ту секунду, когда забирались посты из телеграма.
#
# Ждём до получаса: лучше постоять в очереди, чем разойтись с чужим коммитом.
# Не дождались — молча уходим, следующий заход сделает ту же работу.
exec 9>/root/baka-state/repo.lock
if ! flock -w 1800 9; then
	echo "репозиторий занят другим роботом дольше получаса — пропускаю заход"
	exit 0
fi


cd "$REPO" || exit 1
git fetch --quiet origin main 2>/dev/null || exit 0
NEW=$(git rev-parse origin/main)
LAST=$(cat "$STATE" 2>/dev/null || echo "")

if [ -z "$LAST" ]; then
	echo "$NEW" > "$STATE"
	echo "первый запуск: запомнил точку $NEW, не собираю"
	exit 0
fi
[ "$NEW" = "$LAST" ] && exit 0

LOG="$LOG_DIR/deploy-$(date -u '+%Y%m%d-%H%M%S').log"
exec > >(tee -a "$LOG") 2>&1
STAMP=$(date -u '+%Y-%m-%d %H:%M UTC')
echo "=== СБОРКА И ВЫКЛАДКА: $STAMP ==="
echo "новое: ${LAST:0:8} → ${NEW:0:8}"
git log --format='  %h %an: %s' "$LAST".."$NEW" | head -10

ERRORS=""
fail() { ERRORS="${ERRORS}${1}\n"; echo "!!! $1"; }

# --- 1. свежая копия ------------------------------------------------------
if ! git pull --ff-only 2>&1; then
	"$NOTIFY" "$(printf '🔴 <b>Выкладка не началась</b>\n%s\n\ngit pull не прошёл — сборка отменена, чтобы не выложить старое.' "$STAMP")"
	echo "=== pull не прошёл, выхожу ==="
	exit 1
fi

# --- 2. самопроверка правил заливки --------------------------------------
# Как в старом воркфлоу: сначала обычный прогон, потом подлог. Подлог обязан
# уронить проверку — иначе её «всё хорошо» ничего не значит.
echo "--- проверяю правила заливки"
if node scripts/mirror-sync.test.mjs && node scripts/mirror-sync.test.mjs --подлог; then
	echo "правила заливки в порядке"
else
	"$NOTIFY" "$(printf '🔴 <b>Выкладка остановлена заслоном</b>\n%s\n\nПроверка правил заливки зеркала не прошла. Сборка и выкладка ОТМЕНЕНЫ.\nЖурнал: %s' "$STAMP" "$LOG")"
	echo "=== заслон не пропустил, выхожу ==="
	exit 1
fi

# --- 3. сборка ------------------------------------------------------------
echo "--- собираю сайт"
BUILD_START=$(date +%s)
if npm run build; then
	BUILD_SEC=$(( $(date +%s) - BUILD_START ))
	echo "собрано за ${BUILD_SEC} с"
else
	"$NOTIFY" "$(printf '🔴 <b>Сборка упала</b>\n%s\n\nСайт НЕ выложен — на обоих адресах осталась прежняя версия, читатели ничего не заметили.\nЖурнал: %s' "$STAMP" "$LOG")"
	echo "=== сборка упала, ничего не выкладываю ==="
	exit 1
fi

# --- 4. основной сайт -----------------------------------------------------
echo "--- выкладываю на bakapodcast.com"
if npx wrangler deploy 2>&1 | tail -12; then
	echo "основной сайт выложен"
	MAIN_OK=1
else
	fail "выкладка основного сайта не прошла"
	MAIN_OK=0
fi

# --- 5. зеркало -----------------------------------------------------------
# Заливается даже если основной не вышел: лучше одна свежая копия, чем ни одной,
# а расхождение будет названо в письме прямо.
echo "--- заливаю зеркало ru.bakapodcast.com"
if node scripts/mirror-sync.mjs | tail -8; then
	echo "зеркало залито"
	MIRROR_OK=1
else
	fail "заливка зеркала не прошла"
	MIRROR_OK=0
fi

# --- итог -----------------------------------------------------------------
if [ -n "$ERRORS" ]; then
	WARN=""
	[ "$MAIN_OK" = "1" ] && [ "$MIRROR_OK" = "0" ] && WARN="\n⚠️ Основной сайт свежий, зеркало отстало — копии РАЗОШЛИСЬ."
	[ "$MAIN_OK" = "0" ] && [ "$MIRROR_OK" = "1" ] && WARN="\n⚠️ Зеркало свежее, основной сайт отстал — копии РАЗОШЛИСЬ."
	"$NOTIFY" "$(printf '🔴 <b>Выкладка прошла не полностью</b>\n%s\n\n%b%b\nЖурнал: %s' "$STAMP" "$ERRORS" "$WARN" "$LOG")"
	echo "=== ИТОГ: С ОШИБКАМИ, отметку не двигаю ==="
	exit 1
fi

echo "$NEW" > "$STATE"
"$NOTIFY" "$(printf '🚀 <b>Сайт пересобран и выложен</b>\n%s\n\nСборка: %s с\nОбе копии обновлены: bakapodcast.com и ru.bakapodcast.com' "$STAMP" "$BUILD_SEC")"
echo "=== ИТОГ: ВЫЛОЖЕНО ==="

find "$LOG_DIR" -name 'deploy-*.log' -mtime +30 -delete 2>/dev/null
exit 0
