#!/bin/bash
# СБОРКА И ВЫКЛАДКА САЙТА НА ОБА АДРЕСА (задача 21).
#
# Заменяет сразу два умерших механизма:
#   • автосборку Cloudflare Workers Builds (собирала при каждом пуше),
#   • робота .github/workflows/mirror-sync.yml (зеркало ru.bakapodcast.com).
#
# ПОЧЕМУ ВМЕСТЕ, А НЕ ПОРОЗНЬ. Робот зеркала перед заливкой сам собирает сайт.
# Перенеси его отдельно — зеркало начнёт обновляться само, а основной сайт
# останется на ручной выкладке, и копии молча разъедутся. В уроках проекта это
# отдельная грабля: «выкладок две, и падают они порознь».
#
# ОБЕ КОПИИ ЕДУТ ИЗ ОДНОЙ СБОРКИ. Порядок строгий: pull → build → deploy →
# зеркало. Собрать раньше, чем забрал правки, — значит выложить сборку без них.
#
# Петли не будет: выкладка ничего не коммитит, новых коммитов не создаёт.

set -u
set -o pipefail   # НЕСУЩАЯ СТРОКА, не гигиена: замер 26.08.2026 показал, что
                  # без неё падение заливки зеркала становится «всё хорошо».
                  # Без этого `node … | tee` съедает код возврата, и провал
                  # заливки считался бы удачей — на этом уже обжигались

REPO=/root/baka-site
STATE_DIR=/root/baka-state
STATE="$STATE_DIR/last-deployed-commit"
LOG_DIR=/root/baka-logs
NOTIFY=/root/baka-robot/notify.sh
mkdir -p "$STATE_DIR" "$LOG_DIR"

# ─── ЗАМОК НА РЕПОЗИТОРИЙ ──────────────────────────────────────────────────
# Все роботы работают в ОДНОЙ папке /root/baka-site и лезут в git. Столкнутся
# два — и git отвечает «Cannot fast-forward to multiple branches», работа
# считается сбойной, а заказчик получает красное письмо о живом роботе.
# Поймано 25.08.2026: опросчик постов (ходит каждые 5 минут) влез ровно
# в ту секунду, когда забирались посты из телеграма.
#
# Ждём до получаса: лучше постоять в очереди, чем разойтись с чужим коммитом.
# Не дождались — молча уходим, следующий заход сделает ту же работу.
exec 9>/root/baka-state/repo.lock
if ! flock -w 1800 9; then
	echo "репозиторий занят другим роботом дольше получаса — пропускаю заход"
	exit 0
fi


cd "$REPO" || exit 1
git fetch --quiet origin main 2>/dev/null || exit 0
NEW=$(git rev-parse origin/main)
LAST=$(cat "$STATE" 2>/dev/null || echo "")

if [ -z "$LAST" ]; then
	echo "$NEW" > "$STATE"
	echo "первый запуск: запомнил точку $NEW, не собираю"
	exit 0
fi
[ "$NEW" = "$LAST" ] && exit 0

# --- 0. А есть ли что выкладывать ------------------------------------------
# ПОЙМАНО 25.08.2026. Робот телеграма сходил в канал, не нашёл ни одного нового
# поста — и всё равно сделал коммит: он записывает себе закладку «докуда дошёл»
# (`src/data/telegramFeed.mjs`), а там стоит время захода, и оно новое всегда.
# Мы увидели новый коммит и честно собрали сайт 336 секунд, чтобы получить его
# байт в байт прежним. Так было бы четырежды в сутки, в тишине.
#
# ПОЭТОМУ СПРАШИВАЕМ НЕ «БЫЛ ЛИ КОММИТ», А «ЧТО В НЁМ ПОМЕНЯЛОСЬ». Сравниваем
# состояния целиком (`git diff LAST NEW`), а не по одному коммиту: накопилось
# пять — важен любой из них.
#
# СПИСОК НЕЭФИРНОГО КОРОТКИЙ И БУДЕТ ТАКИМ. Ошибка здесь стоит невыложенной
# правки, то есть ровно той беды, от которой этот робот и заведён, — поэтому
# сюда попадает только то, чего сборка не читает ВООБЩЕ:
#   • src/data/telegramFeed.mjs — закладку открывает один лишь сам робот;
#   • статус/, hetzner/ и документы в корне — вне src/ и public/, в сборку
#     не попадают ни строкой.
# Всё прочее считается влияющим, включая незнакомое: не знаем — собираем.
# ─── начало блока «нечего выкладывать» (проверка: scripts/deploy-idle.test.mjs)
SKIP=0
if CHANGED=$(git -c core.quotepath=false diff --name-only "$LAST" "$NEW" 2>/dev/null); then
	SKIP=1
	while IFS= read -r FILE; do
		[ -z "$FILE" ] && continue
		case "$FILE" in
			src/data/telegramFeed.mjs) ;;
			статус/*) ;;
			hetzner/*) ;;
			# ВЕБ-АНАЛИТИКА СБОРКОЙ НЕ ЧИТАЕТСЯ, И ЭТО ЗАМЕР, А НЕ ЗДРАВЫЙ СМЫСЛ.
			# 26.08.2026 посчитано, что читает `npm run build`: он запускает
			# не только `astro build`, но и четыре скрипта, среди которых
			# `scripts/og-size.test.mjs` — то есть «файлы проверок не влияют»
			# было бы ошибкой. Прогон по импортам от package.json
			# и astro.config.mjs даёт из папки scripts/ ровно шесть файлов,
			# и ни одного из scripts/analytics/. Связь тут ОДНОСТОРОННЯЯ:
			# аналитика читает src/data/platforms.js, обратно — никогда.
			# Заводя в scripts/analytics/ что-то, что читает сборка, эту
			# строку надо снять. Заслон — scripts/deploy-idle.test.mjs.
			scripts/analytics/*) ;;
			*/*) SKIP=0 ;;   # всё остальное в любой папке — влияет
			*.md) ;;         # документы в корне: CLAUDE.md, СТАТУС.md, README.md
			*) SKIP=0 ;;     # незнакомый файл в корне — собираем на всякий случай
		esac
	done <<< "$CHANGED"
fi
# Не сравнилось (истории разошлись, хранилище недоступно) — SKIP остаётся 0,
# и робот собирает, как собирал: молчание измерителя не повод не выкладывать.
if [ "$SKIP" = "1" ]; then
	echo "$(date -u '+%Y-%m-%d %H:%M UTC'): ${LAST:0:8} → ${NEW:0:8} — на страницы не попадает ничего, не собираю"
	git log --format='  %h %an: %s' "$LAST".."$NEW" 2>/dev/null | head -5
	# Отметку двигаем: сайт на этом коммите выглядел бы точно так же, как сейчас.
	# Не сдвинуть — и робот будет заходить с тем же вопросом каждые десять минут.
	echo "$NEW" > "$STATE"
	exit 0
fi
# ─── конец блока «нечего выкладывать»

LOG="$LOG_DIR/deploy-$(date -u '+%Y%m%d-%H%M%S').log"
exec > >(tee -a "$LOG") 2>&1
STAMP=$(date -u '+%Y-%m-%d %H:%M UTC')
echo "=== СБОРКА И ВЫКЛАДКА: $STAMP ==="
echo "новое: ${LAST:0:8} → ${NEW:0:8}"
git log --format='  %h %an: %s' "$LAST".."$NEW" | head -10

ERRORS=""
fail() { ERRORS="${ERRORS}${1}\n"; echo "!!! $1"; }

# ─── начало блока «чистка замечаний индексируемости» (проверка: scripts/indexability-notify.test.mjs)
# ЗАМЕЧАНИЕ ПИШЕТСЯ, ТОЛЬКО КОГДА ЕСТЬ НОВОСТЬ, А ЛЕЖИТ ВЕЧНО: файл закрыт
# .gitignore и переживает заход, и следующий, и десятый. Не сотри его — и
# позавчерашнее «−12 из выдачи» приедет как сегодняшнее. Этой граблей проект
# уже платил письмом про выпуск, расшифрованный накануне (28.08.2026).
rm -f notify-index.md
# ─── конец блока «чистка замечаний индексируемости»

# --- 1. свежая копия ------------------------------------------------------
if ! git pull --ff-only 2>&1; then
	"$NOTIFY" "$(printf '🔴 <b>Выкладка не началась</b>\n%s\n\ngit pull не прошёл — сборка отменена, чтобы не выложить старое.' "$STAMP")"
	echo "=== pull не прошёл, выхожу ==="
	exit 1
fi

# --- 2. самопроверка правил заливки --------------------------------------
# Как в старом воркфлоу: сначала обычный прогон, потом подлог. Подлог обязан
# уронить проверку — иначе её «всё хорошо» ничего не значит.
echo "--- проверяю правила заливки"
if node scripts/mirror-sync.test.mjs && node scripts/mirror-sync.test.mjs --подлог; then
	echo "правила заливки в порядке"
else
	"$NOTIFY" "$(printf '🔴 <b>Выкладка остановлена заслоном</b>\n%s\n\nПроверка правил заливки зеркала не прошла. Сборка и выкладка ОТМЕНЕНЫ.\nЖурнал: %s' "$STAMP" "$LOG")"
	echo "=== заслон не пропустил, выхожу ==="
	exit 1
fi

# --- 3. сборка ------------------------------------------------------------
echo "--- собираю сайт"
BUILD_START=$(date +%s)
if npm run build; then
	BUILD_SEC=$(( $(date +%s) - BUILD_START ))
	echo "собрано за ${BUILD_SEC} с"
else
	"$NOTIFY" "$(printf '🔴 <b>Сборка упала</b>\n%s\n\nСайт НЕ выложен — на обоих адресах осталась прежняя версия, читатели ничего не заметили.\nЖурнал: %s' "$STAMP" "$LOG")"
	echo "=== сборка упала, ничего не выкладываю ==="
	exit 1
fi

# --- 3.5. не обогнали ли нас, пока мы собирали ----------------------------
# ПОЙМАНО 25.08.2026. Сборка идёт почти шесть минут, и пока она шла, с машины
# ушёл коммит 3f4b8cc1, а быстрая выкладка положила его на сайт в 12:55:01.
# Мы через ПЯТНАДЦАТЬ СЕКУНД выложили поверх свою — собранную в 12:49, то есть
# БЕЗ этого коммита. Это старая грабля проекта «выкладок две, побеждает
# поздняя», и здесь поздней оказалась старая.
#
# Поэтому перед самой выкладкой спрашиваем хранилище ЗАНОВО. Ушло вперёд —
# наша сборка устарела, и класть её поверх свежей нельзя ни при каких условиях.
# Уходим спокойно и, главное, НЕ ТРОГАЯ отметку «докуда выложено»:
#   • выложила быстрая выкладка — она сама записала туда свой номер,
#     и следующий заход честно увидит «нечего делать»;
#   • коммит пришёл из админки — отметка осталась старой, и следующий заход
#     соберёт уже новое состояние.
# В обоих случаях лишней сборки не будет, а старое поверх свежего не ляжет.
#
# Сбой сети тут не беда: `git fetch` промолчит, `origin/main` останется прежним,
# и мы выложим, как выкладывали. Мы не знаем о чужой выкладке ровно столько же,
# сколько знали до 25 августа.
# ─── начало блока «нас обогнали» (проверка: scripts/deploy-race.test.mjs)
git fetch --quiet origin main 2>/dev/null || true
AHEAD=$(git rev-parse origin/main)
if [ "$AHEAD" != "$NEW" ]; then
	echo "пока мы собирали, в хранилище приехало ${AHEAD:0:8} — наша сборка ${NEW:0:8} устарела"
	echo "=== НЕ ВЫКЛАДЫВАЮ: старое поверх свежего не кладём. Отметку не двигаю ==="
	exit 0
fi
echo "хранилище на месте (${NEW:0:8}), нас никто не обогнал"
# ─── конец блока «нас обогнали»

# ─── начало блока «замечания индексируемости» (проверка: scripts/indexability-notify.test.mjs)
# Знаки & < > экранируются: письмо уходит с parse_mode=HTML, и на кривой
# разметке телеграм отвечает ОТКАЗОМ — письмо не приходит вовсе. Здесь это
# не перестраховка: в замечание попадают адреса тайтлов, а их имена приходят
# от Shikimori, то есть это чужой текст.
escape_html() { sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }
INDEX_NOTE=""
[ -s notify-index.md ] && INDEX_NOTE="$(head -c 700 notify-index.md | escape_html)"
# ─── конец блока «замечания индексируемости»

# --- 4. основной сайт -----------------------------------------------------
echo "--- выкладываю на bakapodcast.com"
# БЕЗ `| tail`: ОН СЪЕДАЕТ НАЧАЛО СООБЩЕНИЙ, А ОШИБКА ЖИВЁТ ИМЕННО ТАМ.
# Оплачено 26 августа 2026: разбор «почему зеркало залило 230 файлов» встал
# намертво, потому что в журнале от заливки уцелели последние восемь строк
# из девяноста — ни «Решения», ни хода работы. Код возврата при этом не терялся
# (спасал pipefail), то есть беда была не в исходе, а в невозможности потом
# понять, что произошло. Журнал сборки и так на 1700 строк; экономить
# на сообщениях выкладки в нём было нечего.
if npx wrangler deploy 2>&1; then
	echo "основной сайт выложен"
	MAIN_OK=1
else
	fail "выкладка основного сайта не прошла"
	MAIN_OK=0
fi

# --- 5. зеркало -----------------------------------------------------------
# Заливается даже если основной не вышел: лучше одна свежая копия, чем ни одной,
# а расхождение будет названо в письме прямо.
echo "--- заливаю зеркало ru.bakapodcast.com"
if node scripts/mirror-sync.mjs; then
	echo "зеркало залито"
	MIRROR_OK=1
else
	fail "заливка зеркала не прошла"
	MIRROR_OK=0
fi

# --- итог -----------------------------------------------------------------
if [ -n "$ERRORS" ]; then
	WARN=""
	[ "$MAIN_OK" = "1" ] && [ "$MIRROR_OK" = "0" ] && WARN="\n⚠️ Основной сайт свежий, зеркало отстало — копии РАЗОШЛИСЬ."
	[ "$MAIN_OK" = "0" ] && [ "$MIRROR_OK" = "1" ] && WARN="\n⚠️ Зеркало свежее, основной сайт отстал — копии РАЗОШЛИСЬ."
	"$NOTIFY" "$(printf '🔴 <b>Выкладка прошла не полностью</b>\n%s\n\n%b%b\n%s\nЖурнал: %s' "$STAMP" "$ERRORS" "$WARN" "$INDEX_NOTE" "$LOG")"
	echo "=== ИТОГ: С ОШИБКАМИ, отметку не двигаю ==="
	exit 1
fi

echo "$NEW" > "$STATE"
# ─── начало блока «какое письмо о выкладке» (проверка: scripts/indexability-notify.test.mjs)
# «Выложено, и состав выдачи изменился» — ОТДЕЛЬНЫЙ ИСХОД, а не удача
# с примечанием: заголовок обязан говорить исход, иначе перемену в выдаче
# не отличить от обычной сборки, не открыв письмо. Второго письма в ту же
# минуту не шлём — оно размыло бы оба.
if [ -n "$INDEX_NOTE" ]; then
	"$NOTIFY" "$(printf '🟡 <b>Сайт выложен, состав выдачи изменился</b>\n%s\n\nСборка: %s с\nОбе копии обновлены.\n\n%s' "$STAMP" "$BUILD_SEC" "$INDEX_NOTE")"
else
	"$NOTIFY" "$(printf '🚀 <b>Сайт пересобран и выложен</b>\n%s\n\nСборка: %s с\nОбе копии обновлены: bakapodcast.com и ru.bakapodcast.com' "$STAMP" "$BUILD_SEC")"
fi
# ─── конец блока «какое письмо о выкладке»
echo "=== ИТОГ: ВЫЛОЖЕНО ==="

find "$LOG_DIR" -name 'deploy-*.log' -mtime +30 -delete 2>/dev/null
exit 0
