#!/bin/bash
# ЕЖЕНЕДЕЛЬНАЯ СВОДКА ПО САЙТУ В ТЕЛЕГРАМ (задача 28).
#
# Зовётся baka-analytics.timer по понедельникам. Собирает короткую сводку
# за прошедшую неделю и шлёт её тем же ботом, что рапортует о работе сервера.
#
# ПОЧЕМУ ПОНЕДЕЛЬНИК: сводка считает семь дней, КОНЧАЯ ВЧЕРА. Запущенная
# в понедельник, она покрывает ровно прошлую календарную неделю —
# с понедельника по воскресенье. В любой другой день это была бы неделя,
# разрезанная посередине, и сравнивать её с прошлой было бы не с чем.
#
# ПУСТАЯ СВОДКА ЧИТАЕТСЯ КАК «ЧИТАТЕЛЕЙ НОЛЬ», и потому её не бывает:
# не забрались данные — digest.mjs печатает красное сообщение о беде
# и выходит с кодом 2, а мы это сообщение и отправляем. Совсем ничего
# не напечатал (упал, не хватило памяти, нет ключей) — пишем об этом сами.
#
# ИМЕНА ПЕРЕМЕННЫХ ТОЛЬКО ЛАТИНСКИЕ. Русское имя bash не считает именем:
# присваивание падает с «command not found», а проверка «$ИМЯ» разбирает
# литерал и никогда не пуста. Оплачено на первом же прогоне робота выпусков.

set -u
# ОБОЛОЧКА ПЕЧАТАЕТ «КОД 0», ДАЖЕ КОГДА УПАЛО: в конвейере исход берётся
# у ПОСЛЕДНЕЙ команды, а `node … | tee` не падает никогда. Эта строка
# возвращает конвейеру исход первой упавшей части.
set -o pipefail

REPO=/root/baka-site
LOG_DIR=/root/baka-logs
NOTIFY=/root/baka-robot/notify.sh
mkdir -p "$LOG_DIR"

LOG="$LOG_DIR/analytics-$(date -u '+%Y%m%d-%H%M%S').log"
STAMP=$(date -u '+%Y-%m-%d %H:%M UTC')
echo "=== СВОДКА ПО САЙТУ: $STAMP ===" | tee -a "$LOG"

cd "$REPO" || { "$NOTIFY" "$(printf '🔴 <b>Сводка по сайту</b>\nНет папки %s' "$REPO")"; exit 1; }

# Сколько дней — первым доводом, чтобы этот же скрипт годился и для разовой
# отправки руками: `run-analytics.sh 30`.
DAYS="${1:-7}"

OUT=$(/usr/bin/node scripts/analytics/digest.mjs --дней "$DAYS" 2>>"$LOG")
CODE=$?
echo "digest.mjs вышел с кодом $CODE, знаков в ответе: ${#OUT}" >> "$LOG"

if [ -z "$OUT" ]; then
	# Ни строчки на выходе — это не «нет данных», это «программа не отработала».
	# Различать обязательно: первое человек прочтёт в самой сводке, второе
	# не прочтёт нигде, если не сказать.
	TAIL=$(tail -c 600 "$LOG" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g')
	"$NOTIFY" "$(printf '🔴 <b>Сводка не собралась</b>\n%s\n\nПрограмма не напечатала ничего (код %s). Это НЕ «читателей ноль».\n\n<code>%s</code>\n\nЖурнал: %s' "$STAMP" "$CODE" "$TAIL" "$LOG")"
	echo "=== ИТОГ: СВОДКА НЕ СОБРАЛАСЬ ===" | tee -a "$LOG"
	find "$LOG_DIR" -name 'analytics-*.log' -mtime +30 -delete 2>/dev/null
	exit 1
fi

# Код 2 — «данные не забрались», и текст беды digest.mjs напечатал сам.
# Отправляем именно его: он объясняет, ЧТО не ответило.
"$NOTIFY" "$OUT"

if [ "$CODE" = "0" ]; then
	echo "=== ИТОГ: СВОДКА ОТПРАВЛЕНА ===" | tee -a "$LOG"
else
	echo "=== ИТОГ: ОТПРАВЛЕНО СООБЩЕНИЕ О БЕДЕ (код $CODE) ===" | tee -a "$LOG"
fi

find "$LOG_DIR" -name 'analytics-*.log' -mtime +30 -delete 2>/dev/null
exit 0
