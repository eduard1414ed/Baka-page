// ── ТЕЛЕГРАМ ───────────────────────────────────────────────────────────────

const Э = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

async function тг(метод, тело) {
	const r = await fetch(`${API}/${метод}`, {
		method: 'POST',
		headers: { 'Content-Type': 'application/json' },
		body: JSON.stringify(тело),
	});
	const j = await r.json().catch(() => ({}));
	if (!j.ok) console.error(`телеграм ${метод}: ${r.status} ${JSON.stringify(j).slice(0, 200)}`);
	return j;
}

// ПРЕДЕЛ ТЕЛЕГРАМА — 4096 ЗНАКОВ, и это знаки, а не байты. Длинный ответ
// режем ПО ГРАНИЦЕ СТРОКИ и говорим об этом вслух: молча обрезанный ответ
// выглядит целым. Сводка укладывается с запасом (замер: 1435 знаков за
// неделю), но заголовки постов пишет человек, и однажды они вырастут.
//
// ЗАПАСНОЙ ПУТЬ БЕЗ РАЗМЕТКИ — НЕ ПЕРЕСТРАХОВКА. Телеграм на кривую разметку
// отвечает отказом и не доставляет сообщение ВООБЩЕ: одна незакрытая пара
// <b> — и человек не получает ничего, причём молча. Порвать её может и обрезка
// посреди тега, и знак < в чужом тексте, который забыли заменить. Поэтому
// отказ по разметке — повод послать то же самое простым текстом, а не повод
// потерять ответ.
async function сказать(чат, текст) {
	const ПРЕДЕЛ = 4000;
	let т = текст;
	if (т.length > ПРЕДЕЛ) {
		const край = т.lastIndexOf('\n', ПРЕДЕЛ);
		т = т.slice(0, край > 0 ? край : ПРЕДЕЛ) + '\n\n<i>…дальше не поместилось (телеграм не пропускает длиннее 4096 знаков).</i>';
	}
	const j = await тг('sendMessage', { chat_id: чат, text: т, parse_mode: 'HTML', disable_web_page_preview: true });
	if (j.ok) return j;
	const голый = т.replace(/<[^>]*>/g, '');
	console.error('разметку телеграм не принял — шлю простым текстом');
	return тг('sendMessage', { chat_id: чат, text: голый, disable_web_page_preview: true });
}

/** Отправка файла. Отдельный метод телеграма: у документа предела в 4096 знаков нет. */
async function прислатьФайл(чат, путь, подпись) {
	const форма = new FormData();
	форма.append('chat_id', String(чат));
	форма.append('caption', подпись);
	форма.append('parse_mode', 'HTML');
	форма.append('document', new Blob([readFileSync(путь)], { type: 'text/markdown' }), путь.split('/').pop());
	const r = await fetch(`${API}/sendDocument`, { method: 'POST', body: форма });
	const j = await r.json().catch(() => ({}));
	if (!j.ok) console.error(`телеграм sendDocument: ${r.status} ${JSON.stringify(j).slice(0, 200)}`);
	return j;
}

// ── ЗАПУСК РАБОТЫ ──────────────────────────────────────────────────────────

/**
 * Запуск скрипта аналитики. Имя файла — из списка команд, из сообщения
 * не приходит НИЧЕГО, кроме числа дней (и оно уже превращено в число).
 *
 * Срок на работу обязателен: без него зависший поход в чужой сервис
 * подвесил бы бота навсегда, и снаружи это выглядело бы как «бот умер».
 */
function запустить(файл, ключи) {
	return new Promise((решить) => {
		execFile(
			'/usr/bin/node',
			[`scripts/analytics/${файл}.mjs`, ...ключи],
			{ cwd: РЕПО, timeout: 180000, maxBuffer: 10 * 1024 * 1024, env: process.env },
			(ошибка, вывод, ошибки) => решить({ ошибка, вывод: String(вывод), ошибки: String(ошибки) }),
		);
	});
}

// ОДНА РАБОТА ЗА РАЗ. Отчёт собирается до полутора минут, и десять нажатий
// подряд запустили бы десять сборок, съев и память сервера, и чужую квоту.
let занят = false;

async function ответить(чат, текст) {
	const слово = текст.trim().toLowerCase().replace(/^\//, '').replace(/@\w+$/, '');
	const дни = дниИзСообщения(слово);
	const голое = слово.replace(/\s*\d{1,3}\s*(?:дн|день|дня|дней|d)?\s*$/u, '').trim() || слово;

	const команда = КОМАНДЫ.find((к) => к.имя === голое || к.слова.includes(голое));
	if (!команда) {
		// НЕ ПОНЯЛ — ГОВОРИМ, ЧТО УМЕЕМ. Не молчим (выглядит поломкой)
		// и не догадываемся (подсунет ответ не на тот вопрос).
		await сказать(чат, `Не понял: <code>${Э(текст.trim().slice(0, 60))}</code>\n\n${ПОМОЩЬ}`);
		return;
	}

	if (команда.работа.чем === 'помощь') return сказать(чат, ПОМОЩЬ);

	if (занят) return сказать(чат, '⏳ Я ещё считаю прошлый вопрос. Спросите через минуту.');
	занят = true;
	try {
		if (команда.работа.чем === 'digest') {
			const ключи = [...команда.работа.ключи];
			if (дни !== null) {
				const i = ключи.indexOf('--дней');
				if (i > -1) ключи[i + 1] = String(дни);
			}
			const r = await запустить('digest', ключи);
			// Код 2 у сводки — «данные не забрались», и текст беды она печатает сама.
			// Любой другой сбой — наша поломка, и о ней тоже надо сказать вслух.
			if (r.вывод.trim()) await сказать(чат, r.вывод.trim());
			else await сказать(чат, `🔴 Не смог собрать сводку.\n\n<code>${Э((r.ошибки || String(r.ошибка)).slice(0, 600))}</code>`);
		} else if (команда.работа.чем === 'report') {
			await сказать(чат, '⏳ Собираю полный отчёт, это до полутора минут…');
			const ключи = дни !== null ? периодЗа(дни) : [];
			const r = await запустить('report', ключи);
			const строка = r.вывод.split('\n').find((s) => s.startsWith('Отчёт готов: '));
			const путь = строка ? строка.slice('Отчёт готов: '.length).trim() : null;
			if (путь && existsSync(путь)) {
				await прислатьФайл(чат, путь, '📄 Полный отчёт. Открывается любым текстовым редактором.');
			} else {
				await сказать(чат, `🔴 Отчёт собрать не вышло.\n\n<code>${Э((r.ошибки || r.вывод || String(r.ошибка)).slice(0, 600))}</code>`);
			}
		}
	} finally {
		занят = false;
	}
}

/** Ключи --с/--по для report.mjs: он про «--дней» не знает, у него свой язык. */
function периодЗа(дни) {
	const д = 86400000;
	const s = (x) => `${x.getFullYear()}-${String(x.getMonth() + 1).padStart(2, '0')}-${String(x.getDate()).padStart(2, '0')}`;
	const вчера = new Date(Date.now() - д);
	return ['--с', s(new Date(вчера.getTime() - (дни - 1) * д)), '--по', s(вчера)];
}

// ── ОЧЕРЕДЬ ────────────────────────────────────────────────────────────────

let сдвиг = 0;

async function круг() {
	// timeout=50 — это ДЛИННОЕ ожидание на стороне телеграма, а не пауза
	// у нас: соединение висит, пока не придёт сообщение или не выйдет срок.
	// Так один запрос в минуту вместо шестидесяти, и ответ приходит сразу.
	const j = await тг('getUpdates', { offset: сдвиг, timeout: 50, allowed_updates: ['message'] });
	if (!j.ok) return;
	for (const у of j.result ?? []) {
		сдвиг = у.update_id + 1;
		const м = у.message;
		if (!м?.text) continue;
		const чат = String(м.chat?.id ?? '');
		if (!СВОИ.has(чат)) {
			// ЧУЖОМУ — МОЛЧАНИЕ. В журнал пишем, чтобы стук был видно,
			// в телеграм — ни знака.
			console.log(`чужой ${чат} (${м.from?.username ?? 'без имени'}): ${JSON.stringify(м.text).slice(0, 80)} — молчу`);
			continue;
		}
		console.log(`свой ${чат}: ${JSON.stringify(м.text).slice(0, 80)}`);
		await ответить(чат, м.text).catch((e) => console.error(`ответить: ${e.message}`));
	}
}

// Список команд для синей кнопки «/». Ставится при каждом запуске: телеграм
// помнит его у себя, и правка списка в коде без этого до меню не доехала бы.
await тг('setMyCommands', { commands: КОМАНДЫ.map((к) => ({ command: к.имя, description: к.описание })) });
console.log(`слушаю; своих чатов: ${СВОИ.size}`);

for (;;) {
	try {
		await круг();
	} catch (e) {
		// Сеть отвалилась — ждём и пробуем снова. Падать нельзя: systemd,
		// конечно, поднимет, но частые перезапуски он в конце концов бросит.
		console.error(`круг: ${e.message}`);
		await new Promise((r) => setTimeout(r, 5000));
	}
}
