// ЧИСЛО В КОНЦЕ — ЭТО ДНИ, и это единственное, что берётся из сообщения.
// Берётся числом, а не строкой: «/week 14» превращается в 14, всё прочее
// отбрасывается. Предел в 400 дней — не украшение: за ним Метрика начинает
// отвечать долго, а вопрос «сколько было позапрошлым летом» никто не задаёт.
function дниИзСообщения(текст) {
	const m = текст.match(/(\d{1,3})\s*(?:дн|день|дня|дней|d)?\s*$/u);
	if (!m) return null;
	const n = Number(m[1]);
	return n >= 1 && n <= 400 ? n : null;
}

